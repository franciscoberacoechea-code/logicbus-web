                100mts de cable entre el m&oacute;dulo y el Hub de la red. El 7188EX tambi&eacute;n provee 14
                l&iacute;neas I/O definidas por el usuario. Con una tarjeta de expansi&oacute;n <a
                  href="https://www.logicbus.com.mx/categ_boards" target="_blank">interna</a> I/O con convertidores
                A/D, D/A, relay drivers y tambi&eacute;n dispone de entradas con protecci&oacute;n, por el contrario si
                la expansi&oacute;n se requiere externa pueden utilizarse los m&oacute;dulos <a
                  href="https://www.logicbus.com.mx/sub_data1" target="_blank">I-7000</a> por el bus RS-485.
                El 7188EX tambi&eacute;n soporta una bater&iacute;a de respaldo en tarjeta SRAM y tarjeta Flash-Rom,
                otorgando almacenamiento no vol&aacute;til desde 2Mb hasta 64Mb.</div>
