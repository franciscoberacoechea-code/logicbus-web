<center><strong>Tarjeta PCI Express, cuenta con 24 canales de entrada/salida, proveee un conector DB37, velocidad de respuesta 500 kHz, bus de datos de 8 bit.</strong></center><br>


<p>Las tarjetas PIO-D24U / D56U y PEX-D56 / D24 son el producto de nueva generación que ICP DAS proporciona para cumplir con los requisitos de conformidad con RoHS y está diseñado como completamente compatible con el PIO-D24 / D56. Los usuarios pueden reemplazar el PIO-D24 / D56 por el PIO-D24U / D56U y PEX-D24 / D56 directamente sin modificación de software / controlador.<br>

El PIO-D24U / D56U admite bus PCI de 3,3 V / 5 V, mientras que el PEX-D24 / D56 es compatible con el bus PCI Express. El PIO-D24U / D56U y el PEX-D24 / D56 constan de tres puertos bidireccionales de 8 bits. Los puertos de 8 bits se nombran como puerto A (PA), puerto B (PB) y puerto C (PC), respectivamente. Todos los puertos se configuran como entradas al encender o restablecer. Además, el PIO-D56 / D56U proporciona entradas digitales adicionales de 16 bits y salidas digitales de 16 bits.<br>

El PIO-D24U / D56U y el PEX-D24 / D56 tienen un interruptor de ID de tarjeta con el cual los usuarios pueden reconocer el tablero mediante el ID cuando usan dos o más tarjetas PIO-D24U / 56U y PEX-D24 / D56 en una computadora.<br>

Estas tarjetas admiten varias versiones del sistema operativo, como Linux, DOS, Windows 98 / NT / 2000 y Windows 7 / Vista / XP de 32/64 bits. El control DLL y Active X junto con varios programas de muestra de lenguaje basados ??en Turbo C ++, Borland C ++, Microsoft C ++, Visual C ++, Borland Delphi, Borland C ++ Builder, Visual Basic, C # .NET, Visual Basic.NET y LabVIEW se proporcionan con el fin de ayudar a los usuarios a desarrollar rápida y fácilmente sus propias aplicaciones.
</p><BR><br>

<strong>Caracteristicas</strong>

<ul>
<li>Admite el bus PCI de +5 V para PIO-D24 / D56</li>
<li>Admite el bus PCI + 3.3 / + 5 V para PIO-D24U / D56U</li>
<li>Admite PCI Express x 1 para PEX-D24 / D56</li>
<li>Hasta 56/24 (PIO-D56 / PIO-D24) canales de E / S digital</li>
<li>Puertos de E / S programables bidireccionales bajo control de software</li>
<li>Todas las líneas de E / S almacenadas en el tablero</li>
<li>Grupos de 8 bits seleccionables independientemente para E / S en el puerto de 24 bits</li>
<li>Doble cara SMD, tarjeta corta.</li>
<li>Se conecta directamente a DB-24PR, DB-24PD, DB-24RD, DB-24PRD, DB-16P8R, DB-24POR, DB-24SSR, DB-24C o cualquier tarjeta compatible con OPTO-22.</li>
<li>4 fuentes de interrupción: PC0, PC1, PC2, PC3</li>
<li>Un conector DB37, dos conectores de 20 pines (solo para PIO-D56 (U) y PEX-D56)</li>
<li>No hay una dirección base o IRQ cambia a establecer</li>
</ul><br>

<strong>Software</strong>
<ul>
<li>Programa de ejemplo DOS Lib y TC / BC / MSC (con códigos fuente)</li>
<li>DLL y OCX SDK para Windows 95/98 / NT / 2K.</li>
<li>DLL y OCX SDK para Windows XP / 2003 / Vista / 7 de 32 bits y 64 bits.</li>
<li>Se incluyen los programas de ejemplo VB / VC / Delphi / BCB / VB.NET / C # .NET con códigos fuente.</li>
<li>Kit de herramientas de LabVIEW para Windows.</li>
<li>Driver para Linux y DasyLab</li>
</ul>
