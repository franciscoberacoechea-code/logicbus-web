<p>El PISO-CM100U representa una solución muy poderosa y económica de una placa CAN activa con un canal CAN, que cubre una amplia gama de aplicaciones CAN. El microcontrolador integrado de 16 bits permite, entre otras muchas funciones, el filtrado, el preprocesamiento y el almacenamiento (con marca de tiempo) de los mensajes CAN, así como la transmisión en tiempo real de los mensajes CAN. Bajo el efecto del potente microcontrolador, esta tarjeta puede crearse para un controlador CAN sin perder datos, incluso en sistemas con una gran carga de bus. Además, los usuarios pueden desarrollar su propia aplicación CAN utilizando la biblioteca PISO-CM100U. Cuando el PISO-CM100U está activo, el intercambio de datos entre la aplicación de los usuarios y el firmware del bus CAN se realiza mediante el método de asignación de memoria del PISO-CM100U.</p><BR>


<strong>Caracteristicas:</strong>
<ul>
<li>Microprocessor inside with 80186, 80MHz</li>
<li>82C250 CAN transceiver</li>
<li>SJA1000T CAN controller</li>
<li>Support both CAN 2.0A and CAN 2.0B</li>
<li>Timestamp with at least ±1ms precision</li>
<li>DIP switch to select board number</li>
<li>Dual port RAM communication mechanism</li>
<li>RTC (real time clock) inside</li>
</ul>
