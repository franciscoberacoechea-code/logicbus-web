<center><strong>Convertidor RS-232 a 4 Canales de RS-485</strong></center><br>

<p>El I-7520U4 tiene 4 canales de salida independientes <a href="https://www.logicbus.com.mx/convertidores_info#RS-485">RS-485</a> y un canal de entrada <a href="https://www.logicbus.com.mx/convertidores_info#RS-232">RS-232</a>. Cada canal de salida est&aacute; equipada con un driver individual. Los datos desde un maestro al canal de entrada ser&aacute; reenviado simult&aacute;neamente a los cuatro canales de salida. <br>
Provee 2 modos de configuraci&oacute;n de la velocidad de transmisi&oacute;n, una es en modo &quot;Self-Turner&quot; y el otro es en modo fijo. El modo &quot;Self-Turner&quot; puede soportar m&uacute;ltiples velocidades y m&uacute;ltiples formatos de datos. El dise&ntilde;o &quot;Self-Turner&quot; es exactamente el mismo que la serie I-7520. El modo fijo ofrece una mejor calidad de transmisi&oacute;n de datos sobre largas l&iacute;neas o en un ambiente con mucho ruido el&eacute;ctrico.<br>
La protecci&oacute;n de corto circuito puede apagar el canal autom&aacute;ticamente, &eacute;ste tipo de dise&ntilde;o puede ser suficiente para proteger el sistema de comunicaci&oacute;n. Cuando un equipo RS-485 conectado se da&ntilde;a, el canal da&ntilde;ado ser&aacute; aislado para asegurar que los otros equipos funcionen correctamente.<br>
En algunos ambientes cr&iacute;ticos, se tendr&aacute; que agregar resistencias para prevenir la reflexi&oacute;n de se&ntilde;ales seriales. El I-7520U4 incluye una resistencia de 120 Ohms para cada canal seleccionable por jumpers.<br>
Tiene 6 LEDs para indicar el estado y el tr&aacute;fico de datos. El LED Tx/Rx se prender&aacute; cuando se est&eacute;n mandando o recibiendo datos.</p>
<strong>Caracter&iacute;sticas:</strong>
  <ul>
    <li>Hub RS-485 cableado en estrella.</li>
    <li>Driver RS-485 independiente para cada canal.</li>
    <li>Leds para indicar actividad TxD/RxD.</li>
    <li>Velocidad de Transmisi&oacute;n en modo &quot;Self-Turner&quot;, 300 a 115200 bps y modo fijo , 1200 a 115200 bps.</li>
    <li>Resistencia de 120 Ohms para cada canal.</li>
    <li>Alimentaci&oacute;n: +10 a +30 Vdc.</li>
    <li>Temperaturas de Operaci&oacute;n, -25&deg;C a +75&deg;C.</li>
    <li>Riel DIN.</li>
  </ul>

