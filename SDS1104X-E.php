<p>Osciloscopios de Fósforo SDS1000X-E El alcance de cuatro canales está disponible en modelos de 100 MHz e incorpora dos ADC de 1 GSa / s y dos módulos de memoria de 14 Mpts. Cuando todos los canales están habilitados, cada canal tiene una frecuencia de muestreo de 500 MSa / sy una longitud de registro estándar de 7 Mpts. Cuando solo está activo un solo canal por ADC, la frecuencia máxima de muestreo es de 1 GSa / sy la longitud máxima de registro es de 14 Mpts. Para facilitar el uso, se puede acceder a las funciones más comunes con su diseño de panel frontal fácil de usar.<br><br>
La serie SDS1000X-E emplea una nueva generación de tecnología SPO (osciloscopio súper-fósforo) que proporciona excelente fidelidad y rendimiento de la señal. El ruido del sistema también es más bajo que los productos similares en la industria. Viene con un rango de entrada vertical mínimo de 500 uV / div, un innovador sistema de disparo digital con alta sensibilidad y baja fluctuación de fase, y una tasa de captura de forma de onda de 400,000 cuadros / seg (modo de secuencia). El SDS1000X-E también emplea una función de visualización de graduación de intensidad de 256 niveles y un modo de visualización de temperatura de color que no se encuentra en otros modelos de esta clase. La decodificación de bus serie para IIC, SPI, UART, CAN, tipos de bus LIN está incluida. Los modelos X-E también incluyen grabación de forma de onda de historial y activación secuencial que permite el registro y la grabación de forma de onda extendida. Otra adición poderosa es la nueva función matemática FFT de 1 millón de puntos que otorga a la SDS1000X-E una resolución de frecuencia muy alta al observar los espectros de señal.
</p><BR>

