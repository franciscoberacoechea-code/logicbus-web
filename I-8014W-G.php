<center><strong>Módulo de entrada analógica de 250 KS / s, 16 bits y 8/16 canales.</strong></center><br>


<p>El I-8014W / I-8014CW es un módulo de entrada analógica de alto rendimiento. El I-8014W proporciona hasta 16 canales de entrada diferenciales de un solo terminal u 8, mientras que el I-8014CW proporciona hasta 8 canales de entrada diferenciales. Ambos módulos cuentan con una resolución de 16 bits, una frecuencia de muestreo de 250 kS / sy un búfer FIFO de 4 k de muestra, además de una protección de aislamiento de 2500 Vrms. El módulo I-8014W / I-8014CW contiene una impresionante función de escaneo llamada Magic Scan, que puede mejorar muchas de las funciones y satisfacer las demandas de los usuarios de alto nivel. La función de escaneo mágico puede escanear los canales de entrada individuales en diferentes rangos de entrada y al realizar un escaneo de canales múltiples, la velocidad de muestreo puede mantenerse a 250 kS / s. La función de Escaneo Mágico en el módulo I-8014W / I-8014CW se puede operar de dos maneras. El primero es un escaneo estándar y el otro es una función de Muestra y Espera Virtual. El costo de casi todas las tarjetas de AI es alto si incluye una función de Muestra y Espera. El módulo I-8014W / I-8014CW incluye una memoria tampón FIFO incorporada de 4 kb para la conversión A / D. La nueva tecnología FIFO utiliza una señal de interrupción activada, lo que significa que si el conteo muestreado es superior al nivel FIFO predefinido, la señal de interrupción notificará al host. Con la función Magic Scan y el buffer FIFO de 4 k, la I-8014W / I-8014CW puede implementar fácilmente aplicaciones de adquisición de datos de alta precisión, alta velocidad y tiempo crítico.
</p><BR><br>


