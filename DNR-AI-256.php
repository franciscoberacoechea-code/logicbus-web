      <td colspan="2"><div align="justify">The DNA-AI-256 and DNR-AI-256 are high performance, two channel Synchro/Resolver input and output boards for powerful RACKtangle I/O chassis,. The 256 series boards are functionally similar to the DNx-AI-255 but provide significantly more output drive for applications that require it. The DNR-AI-256 series is also an ideal solution for simulating LVDT/RVDTs. The board may be configured as two inputs, two outputs, or one input and one output.<br>
          <br>
          The board provides 2 input channels that will monitor either 3-wire synchros or 4-wire resolvers. The board&rsquo;s high precision circuitry combined with each channel&rsquo;s independent 16-bit A/D converter allow measurement accuracies up to &plusmn; 2.6 arc-minute. The inputs may be read at rates up to the excitation frequency (10 kHz max).&nbsp;<br>
          <br>
          Each channel provides its own programmable reference with outputs independently programmable from 5 to 28 Vrms at frequencies from 50 to 10 kHz and up to 2.4 VA. When using external references, the DNR-AI-256 automatically adjusts simulated outputs for variable amplitude and frequency references in one reference cycle.<br>
          <br>
          The DNR-AI-256 also provides two channels of synchro or resolver output that are ideal for driving such items as attitude indicators or as a test source for a wide variety of synchro or resolver input devices. The outputs each accept an independent reference signal and offer 16-bit output resolution. Each channel will drive up to 19.8 Vrms at 3.0 VA (total board output must be less than or equal to 5 VA) without external buffering. The current consumed by each output channel may be monitored and used to confirm the wiring is correct and the coils of the synchro/resolver or RVDT/LVDT are as expected.<br>
          <br>
          The board offers 350 Vrms of isolation between channels as well as between the I/O connections and the Cube or RACKtangle chassis. Like all PowerDNA/UEILogger I/O boards, the DNR-AI-256 offers operation in harsh environments and has been tested to 3g vibration, 50g shock, -40 to +70 &deg;C temperatures and altitudes up to 70,000 feet.<br>
          <br>
      Software for the DNR-AI-256 is provided as part of the UEI Framework. The framework provides a comprehensive yet easy to use API that supports all popular Windows programming languages and applications including LabVIEW, MATLAB/Simulink, DASYLab and any application supporting ActiveX or OPC servers. Factory software drivers are also provided for Linux and most real-time operating systems including VXworks, QNX, RTX, RT Linux and more.</div></td>
