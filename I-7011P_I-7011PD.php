<center><strong>Módulo DAQ con 1 entrada análoga (mV, V, mA y termopares más comunes y L y M), 1 entrada digital y 2 salidas digitales. Interfaz RS-485 con protocolo DCON. Incluye software gratuito <a href="https://tienda.logicbus.com.mx/AD-EZ-SW_p_5932.html"> EZ Data Logger</a>. Montaje en Riel DIN o pared. Alimentación 10~30 Vdc</strong></center>

<p align="justify"> La serie de módulos I-7011 cuenta con entrada de corriente y voltaje, así como entrada de termopar. El módulo proporciona una entrada analógica de 1 canal, una entrada digital de 1 canal que funciona como un contador de eventos de 50 Hz y una salida digital de 2 canales que se puede utilizar como alarma alta/baja. El módulo también cuenta con detección de cable abierto para la entrada de termopar y aislamiento intramódulo de 3000 VCC. El M-7011 admite los protocolos Modbus RTU y DCON, que se pueden configurar mediante software, y todas las especificaciones de hardware son las mismas que las del I-7011. El I-7011P admite dos tipos de termopar adicionales, L y M.</p>

Características:
<ul>
<li>Entrada analógica de 1 canal</li>
<li>Entrada de corriente, voltaje o termopar</li>
<li>Detección de termopar abierto</li>
<li>Alta resolución: 16 bits</li>
<li>Entrada digital de 1 canal como contador de eventos de 50 Hz</li>
<li>Salida digital de 1 canal como alarma alta/baja</li>
<li>Aislamiento intramódulo de 3000 VCC</li>
<li>Watchdog dual</li>
<li>Amplio rango de temperatura de funcionamiento: -25 a +75°C</li>
</ul>


