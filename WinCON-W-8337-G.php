<strong>Especificaciones e Informacion Adicional</strong>
<center><img src="imagenes/02/lincon_p2.jpg" alt="Especificaciones e Informacion Adicional" title="Especificaciones e Informacion Adicional" width="80%" class="image_productos"></center><br>

<p align="justify">El MCU (unidad de control principal) de Wincon-8337 es el motor de la W-8337. Cada MCU cuenta con un Módulo Procesador Central (CPM) y una fuente de alimentación de amplio rango. El CPM es un potente motor de procesamiento integrado que incluye una CPU, el interior 32M bytes de memoria flash y 64MB SDRAM bytes. El CPM ofrece un medio adicional de memoria Compact Flash tipo de formato II.El puerto Ethernet es también parte de la configuración básica. La CPM está equipado con el interfaz de PC: PS / 2 (teclado y ratón), puerto VGA y un puerto USB. Además de sistemas de interfaces o conexiones de bus de campo, tales como Modbus / TCP y CANopen DeviceNet / están disponibles en el MCU básicos de Wincon.</p>
