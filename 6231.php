  <p>Est&aacute; equipado con 12 canales de entrada anal&oacute;gicos con un rango de +/-60 V. Cada entrada anal&oacute;gica tiene un convertidor A/D de 24 bits con una velocidad de muestreo m&aacute;xima de 50 kHz por canal. Todos los canales son muestreados simult&aacute;neamente. También incluye aislamiento canal a canal de 250 Vrms para la integridad y protecci&oacute;n de las señales incrementadas.</p>
