            <li>Registrador Cryo-Temp a prueba de salpicaduras</li>
            <li>Rango de temperatura -86°C a +35°C</li>
            <li>1 año de vida de la batería a -80°C</li>
            <li>Alarmas de temperatura programadas por usuario</li>
            <li>Protección con contraseña de hardware y software</li>
