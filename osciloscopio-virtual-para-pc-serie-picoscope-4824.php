          <p>Las herramientas de activación permiten que se produzcan uno o más ciclos de una forma de onda cuando se cumplen varias condiciones, como la activación del alcance o el fallo de una prueba de límite de máscara.</p>

          <p>El generador de forma de onda arbitraria (AWG) de 80 MS / s de 14 bits se puede utilizar para emular las señales de los sensores durante el desarrollo del producto, o para realizar pruebas de resistencia de un diseño en un amplio rango de frecuencias. Las formas de onda AWG pueden crearse o editarse utilizando el editor AWG incorporado, importarse desde las trazas del osciloscopio o cargarse desde una hoja de cálculo.</p>

          <h2>Analizador de espectro FFT</h2>

