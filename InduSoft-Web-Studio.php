<h3>LA SOLUCIÓN</h3>

<p align="justify">La solución desarrollada por USSC y First Mile utiliza PLCs APC y WAGO, así como analizadores de potencia de Schneider Electric. Los sistemas instalados en la planta incluyen un sistema contra incendios, un sistema de regulación de potencia, aire acondicionado, refrigeración y otros. La aplicación InduSoft Web Studio desarrollada para monitorear el centro de datos se comunica con todos estos sistemas para brindar a los operadores y gerentes acceso a la información sobre el estado de los componentes clave del centro de datos.
<br><br>
Con el nuevo sistema implementado, los operadores del centro de datos ahora pueden recibir alertas cuando se producen fallas críticas o cuando los servidores se desconectan. El sistema también archiva parámetros críticos para su posterior evaluación, y facilita el seguimiento del estado de cualquier falla de la máquina antes y después de que se desconecten. 
<br><br>
Las piezas más importantes de las nuevas capacidades de monitoreo del centro de datos son los mensajes automatizados que reciben los operadores. Usando las funciones alarmantes de InduSoft Web Studio, la aplicación puede enviar alarmas a SMS y correo electrónico, asegurando que se reconozcan y respondan los problemas críticos. La notificación por SMS, en particular, permite obtener alarmas críticas de los teléfonos inteligentes, lo que permite a los operadores responder a los problemas desde cualquier lugar del centro de datos.</p>

