<div align="center">
  <strong>Tarjeta para caja INET-4xx con 16se/8di entradas de voltaje con convertidor A/D de 16 bit, 2 salidas análogas de voltaje de 14 bit y 2 salidas análogas de voltaje de 8 bit, 4 E/S digitales.</strong>
</div><br>

<p align="justify">Este módulo A/D ofrece 16SE/8DIFF canales de entrada de voltaje, cada cual se puede programar de manera independiente con el software para Windows que soporta la conexión directa a mucho tipos de sensores. 
<br><br>
Cada uno de los 6 canales diferenciales soporta conexión directa a algunos de los siguientes tipos de sensores: voltaje, termopar, termistor, RTD, celda de carga, galga extensiométrica, potenciómetro, corriente, resistencia. El rango de entrada de voltaje en cada canal es independientemente programable a uno de: +/-10mV, +/-20mV, +/-40mV, +/-80mV, +/-600mV, +/-1.2V, +/-2.5V, +/-5V, +/-10V, 0 a 1.2V, 0 a 2.5V, 0 a 5V. 
<br><br>
También cuenta con 2 canales que pueden entrega un voltaje entre -10.1 y +10.1V preciso a +/-4mV. Un convertidor interno A/D de 14 bit esta seguido por un amplificador que puede manejar hasta +/-4mA de corriente y 10K pF de capacitancia. Cada salida esta protegida contra cortocircuito de -180 a +18V, encendido o apagado, sin daño.</p>

<strong>Caracteristicas:</strong>
<ul>
<li>Se conecta a una ranura de la caja de tarjetas de instruNet.</li>
<li>16 SE/8 DIFF canales de entrada de voltaje con un convertidor A/D de 16 bit.</li>
<li>2 salidas de voltaje análogas de precisión (+/-10V, D/A de 14 bit).</li>
<li>2 salidas de voltaje análogas (0 … +10V, D/A de 8 bit).</li>
<li>4 E/S digitales universales (20mA sink, -10V~30V).</li>
<li>Se conecta directamente a sensores: voltaje, termopar, termistor, RTD, celda de carga, galga extensiométrica, potenciómetro, corriente, resistencia.</li>
</ul><br><br>

