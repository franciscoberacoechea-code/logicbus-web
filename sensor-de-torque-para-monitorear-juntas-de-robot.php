  <p align="justify"><b>Resumen de la aplicaci&oacute;n:</b>
    Los brazos robóticos incrementan la productividad automatizando tareas 24x7. Estos brazos se diseñan normalmente para entrenarse y operar como robot colaborativo.<br>
    Estos brazos se controlan desde sus articulaciones con servo motores. Adicional a la operación de estos brazos, los operadores buscan control exacto sobre ellos, por lo que se puede implementar un control completo a lazo cerrado de manera que se una operación autónoma.<br>
    Los sensores a reacción de Futek tienen el principio básico de galgas extensiométricas en puente, conectado a un acondicionador de señal y digitalizado para integrarse al sistema de control del robot.
    Los sensores de torque para juntas de robot vienen en varias geometrías, bajo perfil, forma de disco, diseños compactos e incluso pueden ser personalizados para las especificaciones del gobierno.
