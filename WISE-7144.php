				<p> 
					WISE (Web Inside, Smart Engine) es una serie de productos desarrollada por ICP DAS que funciona como unidades de control para su uso en control y monitoreo lógico remoto en diversas aplicaciones industriales. WISE ofrece una interfaz de sitio web intuitiva y fácil de usar que permite a los usuarios implementar la lógica de control IF-THEN-ELSE en los controladores a solo unos clics de distancia; no se requiere programación Con sus características potentes y fáciles de usar, minimizará la curva de aprendizaje, acortará el tiempo de comercialización y reducirá drásticamente el esfuerzo y el gasto en el desarrollo del sistema.<br><br>

					WISE-7144 sigue la especificación IEEE 802.3af (clasificación, Clase 1) de alimentación a través de Ethernet (PoE). Permite recibir energía de la red habilitada para PoE mediante pares Ethernet (cable Ethernet de categoría 5). Esta característica proporciona una mayor flexibilidad y una mayor eficiencia, por lo tanto, simplifica el diseño de los sistemas, ahorra espacio, reduce los cables y elimina la necesidad de enchufes eléctricos dedicados. Mientras tanto, en el caso de un entorno no PoE, WISE-7144 aún podrá recibir energía de fuentes de alimentación auxiliares como adaptadores de CA o batería, etc.<br><br>

					Este módulo WISE-7144 es compatible con el protocolo Modbus / TCP para una integración perfecta con el software SCADA disponible. Cuenta con salidas de colector abierto aislado de 8 canales y entradas digitales de contacto húmedo aisladas de 8 canales. Cada canal de salida admite una corriente de 300 mA que acciona +10 ~ 40 V CC y cada canal de entrada digital admite entrada de contador.
				</p><br>

