<center><strong>WinPAC-8000 basado en InduSoft con 8 ranuras de E / S, Windows CE.NET 5.0.</strong></center><br>


<p>WinPAC-8xx9 Series (WP-8139/8439/8839, WP-8149/8449/8849) es la segunda generación basada en Windows CE InduSoft PAC de equipa PXA270 CPU (520MHz) con Windows CE Sistema operativo .NET 5.0, conectividades variantes (VGA, USB, Ethernet, RS-232/485) y ranuras 1/4/8 para módulos de E / S paralelas de alto rendimiento (serie I-8K de alto perfil) y tipo serie I / Módulos O (módulos de E / S de alto perfil I-87K). Su sistema operativo, Windows CE 5.0, tiene muchas ventajas, incluida la capacidad dura en tiempo real, tamaño de núcleo pequeño, velocidad de arranque rápida, manejo de interrupciones a un nivel más profundo, control determinista alcanzable y bajo costo. El uso de Windows CE 5.0 en WinPAC-8000 le da la capacidad de ejecutar software de control basado en PC como Visual Basic .NET, Visual C #, Embedded Visual C ++, software SCADA, Soft PLC.
</p><BR><br>


<strong>Caracteristicas Generales:</strong>
<ul>
<LI>Puerto VGA incorporado</LI>
<LI>Capacidad de intercambio en caliente del módulo de E / S (estará disponible)</LI>
<LI>(Para los módulos de perfil alto I-87K solamente)</LI>
<LI>Capacidad de expansión de E / S enriquecida (RS-232/485, Ethernet, FRnet, CAN)</LI>
<LI>Disco flash incorporado (31 MB para WP-8x4x, 63 MB para WP-8x3x)</LI>
<LI>Temporizador de doble vigilancia</LI>
<LI>SRAM con respaldo de batería doble (512 KB)</LI>
<LI>Puertos Ethernet dobles</LI>
<LI>Entrada de energía redundante</LI>
<LI>El diseño de la carcasa con ventilación permite la operación entre -25 ? ~ + 75 ?</LI>
</ul>

