<p align="justify">Z-LINK1-LO es un dispositivo de radio de 869 MHz diseñado para la comunicación remota que funciona de manera transparente con el protocolo ModBUS RTU y que explota la capa física de la tecnología de transmisión LoRa (largo alcance). Basado en un radio módem UHF, Z-LINK1-LO permite la comunicación entre los módulos de E / S de línea SENECA Z-PC y los dispositivos ModBUS genéricos. Z-LINK1-LO significa facilitar el cableado de alimentación y la comunicación del bus serie montado en el riel DIN IEC 60715. El módulo se configura fácilmente a través de interruptores DIP o software de PC EASY SETUP. También incluye 2 puertos seriales (1 RS232, 1 RS485) y una etapa de aislamiento entre la comunicación y la alimentación de hasta 1.500 V. De acuerdo con los estándares ETSI y el cifrado de datos AES128, Z-LINK1-LO puede operar en E / S remotas o en puente. Modos con modo de comunicación punto a punto y punto a multipunto. La tecnología LoRa permite que el radio módem alcance una alta cobertura (hasta 1 km con una antena externa), una potencia de transmisión de 40 mW, la mayor inmunidad al ruido y la sensibilidad.</p>

<strong>Características:</strong>
<ul>
<li>Z-LINK1-LO es un dispositivo de radio de 869 MHz diseñado para operar en comunicación remota en una manera transparente con protocolo ModBUS RTU y explotando la capa física en tecnología de transmisión en LoRa (Largo Alcance). Basada sobre un radio módem UHF, Z-LINK1-LO habilita la comunicación entre los modulos SENECA Z-PC Line I/O y dispositivos genéricos ModBUS. El dispositivo Z-LINK1-LO fue pensado para facilitar el cableado de alimentación y de comunicación en bus al montarse en riel DIN IEC 60715.</li>
<li>El módulo es fácilmente configurado bajo DIP-switches o software para PC de fácil instalación.</li>
