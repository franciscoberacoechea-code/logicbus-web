<center><h2><b>Aplicaci&oacute;n de Celda de carga </b></h2></center>

<div class="part1">

<article>
  <p><b>Resumen de la aplicaci&oacute;n:</b>Para crear productos de alto rendimiento para la industria de aptitud física, los ingenieros y diseñadores deben entender cómo el cliente interactúa con ellos. Esto es crucial, ya que las fallas en el equipo pueden ocasionar lesiones, falencias comerciales y problemas legales.<br>

  La información que nos arrojan sensores de torque y fuerza le permite a los ingenieros recolectar, registrar y analizar las interacciones entre el equipo y las personas utilizándolo.
  </p>
<!-- coregir imagen de diagrama -->
<img src="imagenes/36/diagramas/desarrollo-de-productos-y-oem/medicion-de-fuerza-en-equipo-de-gimnasio.jpg" alt="Frenos por sistema cableado" width="50%">

<div>
  <p><b>C&oacute;mo funciona:</b><br></p>
  <ol>
    <li style="color: black;"><strong>Resistencia de banda elástica:</strong><br>
Una celda de carga miniatura se conecta a cada una de las bandas elásticas.A medida que el atleta tira de las bandas, la información es reunida por los sensores de fuerza.</li>

<li style="color: black;"><strong>Medición de carga en sentadilla:</strong><br>
Tradicionalmente, los entrenadores utilizan cinturones con peso para fortalecer al atleta. La medición de carga utilizando una celda que se conecta a un rodamiento, nos da libertad de movimiento e información necesaria.</li>
<li style="color: black;"><strong>Máquina de remo:</strong><br>
<strong>A-</strong> La eficiencia, fricción y torque de la rueda se miden para más confiabilidad. Así se mide también torque, RPM, ángulo y potencia.<br>
<strong>B-</strong> Una celda de carga miniatura modelo <strong><a href="https://tienda.logicbus.com.mx/LCM200_c_1633.html" target="_blank">LCM200</a></strong> se instala entre la manija de remo y la rueda de resistencia. Durante el ejercicio, la fuerza es capturada por el transductor y se monitorea cuánta fue requerida para operar el equipo.<br>
<strong>C-</strong> La celda de carga tipo pedal <strong><a href="https://tienda.logicbus.com.mx/LAU220_c_1820.html" target="_blank">LAU220</a></strong> calcula la presión que el pie del atleta está imprimiendo en la base durante el ejercicio.</li>
<li style="color: black;"><strong>Medición de fuerza en flexión de pierna.</strong><br>
Las celdas de carga se instalan en unos clips circulares para monitorear el movimiento del equipo. A medida que el atleta se ejercita la celda captura la fuerza con la que mueve los clips.
</li>
<li style="color: black;"><strong>Bicicleta fija:</strong><br>
<strong>A-</strong> Se utiliza una celda de carga tipo botón, panqueque, dona o multieje para monitorear el centro de gravedad cuando el atleta se ejercita.<br>
<strong>B-</strong> Se utiliza el sensor multieje <strong><a href="https://tienda.logicbus.com.mx/MBA400_c_1949.html" target="_blank">MBA400</a></strong>, <strong><a href="https://tienda.logicbus.com.mx/MBA500_c_1950.html" target="_blank">MBA500</a></strong> ó <strong><a href="https://tienda.logicbus.com.mx/MAU300_c_1948.html" target="_blank">MAU300</a></strong> se instalan en las manijas para monitorear la fuerza de agarre, empuje y tracción.<br>
<strong>C-</strong> La eficiencia y fricción de la rueda se mide con un sensor de torque rotatorio.<br>
<strong>D-</strong> Un sensor de tipo pedal mide la fuerza del pie.
</li>
<li style="color: black;"><strong>Máquina elíptica:</strong><br>
<strong>A-</strong> Un sensor multieje <strong><a href="https://tienda.logicbus.com.mx/MBA400_c_1949.html" target="_blank">MBA400</a></strong>, <strong><a href="https://tienda.logicbus.com.mx/MBA500_c_1950.html" target="_blank">MBA500</a></strong> ó <strong><a href="https://tienda.logicbus.com.mx/MAU300_c_1948.html" target="_blank">MAU300</a></strong> se instalan en las manijas para monitorear el agarre, empuje y tracción de la manija.<br>
<strong>B-</strong> La celda de carga tipo pedal <strong><a href="https://tienda.logicbus.com.mx/LAU220_c_1820.html" target="_blank">LAU220</a></strong> se utiliza para monitorear la presión que ejerce el pie del atleta.<br>
<strong>C-</strong> La eficiencia y fricción de la rueda se mide con un sensor de torque rotatorio.<br>
<strong>D-</strong> Prueba de confiabilidad en las juntas y pivotes en movimiento, con sus pruebas contra fatiga y movimientos repetitivos.</li>
  </ol>
