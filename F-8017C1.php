<center><strong>Módulo de entrada de corriente de 8 canales (cubierta gris) (RoHS).</strong></center><br>

<p>El F-8017C1 es un módulo de entrada diferencial analógico de 16 bits y 8 canales. Este módulo acepta un rango de entrada actual de 4 ~ 20mA y admite una medición del 25% por encima del rango (la precisión no está garantizada). Además, tiene una precisión de ± 0.05% para una aplicación altamente precisa. Además, este módulo proporciona una frecuencia de muestreo de 500Hz para algunas aplicaciones. El F-8017C1 proporciona un aislamiento óptico de 3000VDC entre los canales y el bus de fondo. Si algún alto voltaje o corriente daña estos canales, este módulo no afectará a otros componentes en el sistema iDCS-8000.</p>

Caracteristicas:
<ul>
<li>8 canales de entrada actuales.</li>
<li>Medición de overrange.</li>
<li>Conformidad con la RoHS.</li>
<li>Aislamiento de 3000 VDC desde la entrada al plano posterior.</li>
<li>Aislamiento de 3000 VDC desde la entrada al suelo del bastidor.</li>
<li>Redundancia.</li>
<li>Tiempo de conmutación redundante rápido (< 100us).</li>
</ul>
Aplicaciónes:
<ul>
<li>Automatización de edificios.</li>
<li>Automatización industrial.</li>
<li>Automatización de máquinas.</li>
<li>Mantenimiento remoto.</li>
<li>Diagnóstico remoto.</li>
<li>Equipo de pruebas.</li>
</ul>
