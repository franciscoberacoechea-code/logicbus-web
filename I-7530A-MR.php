<h1>I-7530A-MR</h1>

<div align="center">
<img src="https://tienda.logicbus.com.mx/assets/images/02/I-7530A-MR_la01.jpg" width="20%" alt="Convertidor Modbus RTU a CAN: I-7530A-MR" title="Convertidor Modbus RTU a CAN: I-7530A-MR" class="image_productos"><br><br>
