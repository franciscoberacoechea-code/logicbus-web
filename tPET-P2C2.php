<center><strong>Módulo Ethernet pequeño con PoE, 2 canales de entrada digital (contador de 32 bits) y 2 canales de salida digital (NPN, sumidero), voltaje de salida de +5 V CC ~ +30 V CC, comunicable mediante protocolo Modbus TCP</strong></center><br>
 <br>

<p> 
Proporcionando varias funciones de E / S digitales, la serie tET / tPET es un módulo de monitoreo y control de E / S Ethernet basado en IP. El módulo se puede controlar de forma remota a través de una red Ethernet de 10/100 M mediante el protocolo Modbus TCP. Modbus se ha convertido en un protocolo de comunicaciones estándar de facto en la industria, y ahora es el medio más comúnmente disponible para conectar dispositivos electrónicos industriales. Esto hace que la serie tET / tPET se integre perfectamente con HMI, SCADA, PLC y otros sistemas de software.<br><br>

La funcionalidad de la serie tET / tPET es casi la misma que la de la serie ET-7000 / PET-7000. Los pequeños módulos de E / S Ethernet de la serie tET / tPET admiten varios tipos de E / S, como entrada digital aislada con foto, contacto de relé, relé PhotoMOS y salida de colector abierto. El módulo se puede usar para crear una conexión de par DI a DO a través de Ethernet. Una vez que se completa la configuración, el módulo de la serie tET / tPET puede sondear el estado de los canales DI locales y luego usar el protocolo Modbus / TCP para escribir continuamente en un dispositivo DO remoto en el fondo.<br><br>

La serie tET / tPET proporciona un doble watchdog: CPU watchdog y host watchdog. El regulador de CPU se reinicia automáticamente cuando el firmware incorporado se ejecuta de forma anormal. El controlador de host supervisa el controlador del host (PC o PLC) y la salida del módulo puede pasar al estado predefinido (valor seguro) cuando falla el host.<br><br>

Para un ahorro de espacio máximo, la serie tET / tPET se ofrece en un asombroso factor de forma diminuto que significa que puede instalarse fácilmente en cualquier lugar, incluso directamente integrado en una máquina. Está equipado con dos conectores de bloque de terminales extraíbles para facilitar el cableado, y cuenta con una potente MCU ARM de 32 bits para manejar el tráfico de red eficiente. La serie tPET ofrece una verdadera alimentación IEEE 802.3af (clasificación, Clase 1) a través de Ethernet (PoE) utilizando un cable Ethernet estándar de categoría 5 para recibir energía de un conmutador PoE como el NS-205PSE. Cuando no hay un conmutador PoE en el sitio, la serie tPET acepta entrada de alimentación del adaptador de CC.</p><BR>


<strong>Caracteristicas:</strong>
<ul>
<li>Módulos de E / S Ethernet rentables (esclavo Modbus TCP / UDP)</li>
<li>Contiene una MCU de 32 bits que maneja de manera eficiente el tráfico de red</li>
<li>10/100 Base-TX Ethernet, RJ-45 x1 (Auto-negotiation, Auto MDI / MDIX, Indicador LED)</li>
<li>Admite protocolos TCP, UDP, HTTP, DHCP, BOOTP y TFTP</li>
<li>Admite respondedor UDP para descubrimiento de dispositivo</li>
<li>Admite configuración web y actualización de firmware a través de Ethernet</li>
<li>Entrada y salida digital aislada</li>
<li>Admite funciones de contador de alta velocidad DI y de 32 bits</li>
<li>Admite conexión de par de E / S a través de Ethernet</li>
<li>Vigilancia doble con encendido y valor seguro</li>
<li>Diminuto factor de forma con fácil montaje en riel DIN</li>
<li>RoHS obediente sin halógeno</li>
<li>Hecho de materiales ignífugos (nivel UL94-V0)</li>
<li>Bajo consumo de energía (aproximadamente 1.7 W solamente)</li>
</ul>
