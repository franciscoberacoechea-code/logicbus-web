<p align="justify">El Graphtec GL100-N-4TSR-GS103JT es un conjunto que viene con el registrador de datos compacto GL100-N, así como el adaptador de termistor de entrada de 4 canales GS-4TSR y el sensor de termistor GS-103JT. Su cuerpo permite a los usuarios cambiar sensores y terminales para medir varias señales. La dimensión del cuerpo principal es un ligero de 2,6 pulgadas de ancho x 3,93 pulgadas de alto x 1,06 pulgadas de espesor (66 mm x 100 mm x 27 mm).<br><br>
Funciona con dos baterías AA (no incluidas) o alimentación de bus USB (incluye cable USB MicroB-A incluido). Con una memoria integrada de 4,9 MB y una memoria externa a través de la ranura para tarjeta Micro SD, el cuerpo del GL100 también incluye un puerto USB (conexión Micro B).<br><br>
La pantalla del GL100N4TSRGS103JT es un monocromo retroiluminado con resolución de 128 × 64 puntos que muestra los valores medidos y la configuración. Los datos grabados no se muestran en la unidad principal; Los datos capturados solo se pueden mostrar en la PC usando el software de aplicación incluido.<br><br>
El GS-4TSR incluido es un adaptador de termistor de entrada de 4 canales que puede medir la temperatura en lógica (patrón de señal) o pulso (conteo instantáneo o acumulado), y puede medir un rango de temperatura de -40 a 120 ° C dependiendo del sensor del termistor conectado al adaptador. El sensor de termistor GS-103JT se incluye con el conjunto GL100-N-4TSR-GS103JT y tiene un rango de temperatura de -40 a 120 ° C.</p>

