        <p>El crecimiento de robots colaborativos que pueden trabajar codo con codo con las personas hace que la automatización sea accesible para una nueva generación de aplicaciones. Sin embargo, esta accesibilidad a menudo se ha producido a costa de precios más altos para sensores especiales, una repetibilidad reducida y un tiempo de ciclo dramáticamente reducido. La línea de robots articulados de seis ejes de colaboración industrial de Precise Automation ofrece las características, el precio y la repetibilidad que ofrecen los robots tradicionales con la facilidad de uso de los populares robots de colaboración. 
        <br>
        Los robots colaborativos permiten la creación de un entorno de fabricación mixto donde las personas pueden ingresar y trabajar eficientemente alrededor de los robots sin la pérdida de rendimiento. Sin embargo, cuando los usuarios están cerca, la mayoría de los robots "colaborativos" deben moverse lentamente o usar un modo colaborativo de velocidad reducida, perdiendo productividad. Los robots de seis ejes de Precise están diseñados para que puedan programarse fácilmente para moverse a mayores velocidades en el espacio libre y para limitar las velocidades cuando son posibles las colisiones contra una superficie rígida. Esto permite que el robot se mueva a velocidades similares a las personas, incluso cuando los usuarios están presentes en la celda de trabajo, al tiempo que limita las fuerzas al estándar de robot colaborativo ISO. Por lo tanto, los operadores pueden moverse libremente alrededor del robot sin preocuparse por su seguridad o reducir la productividad. El diseño robusto de estos robots proporciona repetibilidad y confiabilidad a nivel industrial y les permite cambiar y volver a desplegar fácilmente para operar en un modo tradicional no colaborativo para tiempos de ciclo aún más rápidos cuando no existe la posibilidad de que un operador esté presente. 
        <br><br>
        Para simplificar la configuración para nuevos usuarios, muchos robots colaborativos usan un entorno de programación con características limitadas. Los robots de colaboración de Precise Automation ofrecen la flexibilidad de una interfaz basada en web fácil de usar y un entorno de programación avanzada opcional tan capaz como cualquier robot industrial. La interfaz fácil de usar de Guidance Motion es accesible desde cualquier dispositivo habilitado para la web y permite a los técnicos u operadores configurar y enseñar al robot de forma rápida y fácil para realizar un trabajo real. Además, el potente control de movimiento permite las funciones de colaboración sin el uso de sensores costosos que proporcionan un rendimiento de nivel industrial a un costo menor que otros robots colaborativos de seis ejes.
        </p>


