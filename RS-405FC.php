<center><strong>Switch Ethernet Industrial con 5 puertos de anillo redundante en tiempo real, de los cuales 2 son puertos para fibra óptica (Conector SC, multimodo) que asegura la transmisión de datos inmune frente a interferencias EMI/RFI. La distancia para transmitir es hasta 2Km y es la solución perfecta para aplicaciones donde la transmisión se debe de proteger de la exposición eléctrica, subidas de tensión, la corrosión eléctrica o química. Caja de plástico, disponible para instalación en pared y motaje en riel DIN.</strong></center><br>


<p>El RS-405FC es un conmutador de anillo redundante en tiempo real de 5 puertos Ethernet industrial con fibra de 2 puertos (conector SC, modo múltiple) que asegura la transmisión de datos mediante la transmisión de fibra óptica para proporcionar inmunidad contra interferencia EMI / RFI. Se usa Ethernet para transmitir una señal de hasta 2 km (6,600 pies), y es la solución perfecta para aplicaciones donde la transmisión debe protegerse contra la exposición eléctrica, sobrevoltajes, rayos o corrosión química.<br><br>

El puerto de fibra de RS-405FC funciona en modo dúplex medio o completo. En modo dúplex completo, el rango es de 2 km con cables de fibra de 62.5 / 125µm; en modo semidúplex, el rango es de 412 m con cables de fibra de 62.5 / 125µm. El puerto Ethernet de RS-405FC admite la función de autonegociación 10 / 100M y la función automática MDI / MDIX.<br>

La técnica integrada Cyber-Ring ICP DAS permite que varios interruptores se coloquen en un anillo redundante. Detecta y se recupera de una falla de enlace de fibra o cobre dentro de aproximadamente 50 ms, para la mayoría de las aplicaciones un proceso sin interrupciones. Compatible con Modbus / TCP, Modbus / RTU y OPC, la aplicación SCADA puede monitorear el estado de Ethernet y el puerto de fibra con protocolo Modbus o OPC. <br><br>

RS-405FC proporciona dos entradas de alimentación que se pueden conectar simultáneamente a fuentes de alimentación de CC en vivo. Si una de las entradas de alimentación falla, la otra fuente en vivo actúa como una copia de seguridad para admitir automáticamente las necesidades de energía del RS-405FC. Y, la facilidad de salida de retransmisión puede entregar una señal de advertencia mientras falla la alimentación dual o el enlace de red.</p><BR><br>

