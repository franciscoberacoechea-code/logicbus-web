      <td colspan="2"><div align="justify">The DNA-QUAD-604 is a four channel quadrature encoder input board. The board provides standard A, B and Z (index) inputs for each channel. The 16.5 MHz maximum input frequency coupled with the boards 32 bit counters and 32-bit prescaler ensure the board easily handles the most challenging applications. A programmable deglitch/ debounce circuit allows the user to select debounce intervals between 92 nanoseconds and 1 second.<br>
          <br>
          The Index pin may be set to perform a variety of tasks. It may be set to; reset/load the counter immediately, reset/load the counter on the next A/B: low/low, low/high, high/low or high/high cycle, generate an interrupt, generate a cube-wide trigger pulse, etc. The index may be based on either rising or falling edge signals.<br>
          <br>
          The counters may be read on software command or the board may be set to transfer the counter data into buffers at fixed timing intervals. The 512 count FIFO ensures ample time to read the FIFOs without risking an overflow condition.<br>
          <br>
          The DNA-QUAD-604 also provides 4 digital inputs (in addition to the four A, B, Z channels) and 8 digital outputs. The digital I/O is compatible with both +5 and +3.3 volt logic, and the digital outputs are rated to supply &plusmn;12 mA of drive current. The board offers 350 V of isolation and 7 kV of ESD protection.<br>
          <br>
          Like all I/O boards (layers) in the PowerDNA family, the board is tested to operate from -40 to +85 &deg;C, through 50 g shocks, 5 g vibration and at altitudes up to 70,000 feet. All connections are through a common and convenient 37-pin D connector.<br>
          <br>
          The DNA-QUAD-604 is fully supported by wide variety of software drivers and programming tools.
