<center><strong>Módulo de salida de voltaje o de corriente de 8 canales aislado de 16 bits (cubierta gris) (RoHS).</strong></center><br>

<p>El I-87028UW es un módulo de salida analógica de tipo fuente que incluye 8 canales de salida analógica de terminación única, y permite un rango de salida programable en todos los canales de salida analógica (0 ~ 5 V, +/- 5 V, 0 ~ 10 V, + / -10 V, +4 ~ +20 mA o 0 ~ +20 mA). Cada canal de salida analógica se puede configurar para un rango individual y proporciona un nivel de inmunidad de RF que coincide con el definido por el estándar IEC 61000-4-3. Las salidas de voltaje y corriente son seleccionables por puente, y el módulo también presenta detección de cable abierto por canal para salidas de +4 ~ + 20 mA, junto con protección ESD de 4 KV así como aislamiento intramódulo de 2500 VDC. También se incluyen opciones para configurar el encendido y los valores seguros.</p>

Caracteristicas:
<ul>
<li>Aislamiento de canal a canal de 1 kV.</li>
<li>Detección de cable abierto para salida de corriente.</li>
<li>Inmunidad RF.</li>
<li>Protección de cortocircuito.</li>
<li>Valor de encendido.</li>
<li>Seguro.</li>
<li>Protección contra ESD de 4 kV.</li>
<li>Amplio rango de temperatura de funcionamiento: -25 ~ + 75 ° C.</li>
</ul>
Aplicaciones:
<ul>
<li>Automatización de edificios.</li>
<li>Automatización industrial.</li>
<li>Automatización de máquinas.</li>
<li>Mantenimiento remoto.</li>
<li>Diagnóstico remoto.</li>
<li>Equipo de pruebas.</li>
</ul>
