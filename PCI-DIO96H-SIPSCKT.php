	<strong>Descripci&oacute;n General </strong><br>	<br>
	La PCI-DIO96H/SIPSCKT es una tarjeta digital de E/S de alta densidad con sockets SIP para instalar resistencias pull-up/pull-down. La PCI-DIO96H/SIPSCKT ofrece 96 bits de E/S digitales. Proporciona 24 bits de E/S en grupos basados en el 82C55, modo 0. Cada grupo proporciona un puerto A y un puerto B de 8 bits as&iacute; como un puerto C de 8 bits que puede ser dividido en 2 puertos C de 4 bits: Puerto C-Hi, Puerto C-LO. <br>
