                  entre el tamaño del buffer y el rendimiento. La serie PicoScope 4000 siempre maximiza tanto el tamaño
                  del buffer como la frecuencia de actualización del display al mismo tiempo. Ahora puedes fácilmente
                  capturar el detalle de cada forma de onda sin comprometer el funcionamiento del equipo.<br><br>

