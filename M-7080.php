          <center><strong>Módulo de Adquisición de Datos de Entrada / Frecuencia, comunicable a través de Modbus RTU y RS-485. Con salida digital. Admite temperaturas de funcionamiento entre -25 a 75 ° C.</strong></center><br>
          <br>

          <p> 
            El I-7080 ofrece 2 contadores de alta velocidad o canales de entrada de frecuencia y 2 canales de salida digital. Se proporcionan dos tipos de entradas digitales, una para entrada aislada y la otra para entrada no aislada. La entrada aislada proporciona un voltaje de aislamiento de 3750 Vrms y la entrada no aislada proporciona un nivel de voltaje de umbral programable. El filtro digital incorporado es válido tanto para entrada aislada como no aislada y puede filtrar ruido donde el ancho de pulso alto / bajo es menor que el ancho mínimo alto / bajo del filtro digital. El recuento máximo es de hasta 32 bits y la frecuencia máxima es de hasta 100 kHz. El módulo también proporciona salida de alarma programable con colectores abiertos no aislados. El M-7080 es compatible con los protocolos Modbus RTU y DCON, que se pueden configurar a través del software, y todas las especificaciones de hardware son las mismas que las de la I-7080. Las funciones de la I-7080B son las mismas que las de la I-7080, excepto que la I-7080B proporciona una función de respaldo de batería virtual en modo contador. DCON, que se pueden configurar a través del software. ICPDAS recomienda seleccionar la versión "P" del módulo de entrada digital para uso industrial.
          </p><BR>

          <strong>Características:</strong>
          <ul>
            <li>Entrada de frecuencia / contador de 2 canales.</li>
            <li>Contador de 32 bits.</li>
            <li>Entrada aislada o no aislada</li>
            <li>Salida de alarma programable.</li>
            <li>Filtro digital programable.</li>
            <li>Nivel de voltaje de umbral programable.</li>
            <li>Frecuencia máxima de hasta 100 kHz.</li>
            <li>Respaldo de batería virtual incorporado para preservar los valores del contador.</li>
            <li>Dual Watchdog.</li>
            <li>Amplio rango de temperatura de funcionamiento: -25 ~ + 75 ° C.</li>
          </ul>
