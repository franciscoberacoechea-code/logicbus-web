<h2>DESCRIPCIÓN DEL SISTEMA</h2>

<p align="justify">Para  la alta calidad de monitorización del aire el sistema necesita, el sistema requiere de un  I-87017RCW-G  el cual  un es un módulo de entrada de corriente de 8 canales que está diseñado específicamente para medir solo la corriente. Para monitorear  la concentración de, proporcionando un monitor las 24 horas, y luego realiza el registro de los datos cada 30 segundos, en un archivo diario. Esto es, para que el sistema de monitoreo se instale generalmente en el exterior sin redes cableadas, también los usuarios el 8212W-3GWA-G es un módulo industrial Tri-banda 3G que funciona en frecuencias de WCDMA 2100/1900/850 MHz y GSM 850/900/1800/1900 MHz. Estos módulos utilizan la red 2G / 3G para la transferencia de datos conveniente y económica desde instrumentos remotos, medidores, computadoras o sistemas de control en datos en vivo o paquetes de datos, y así enviar informes diarios por correo electrónico o servidor FTP.<br>
Cuando se produce una excepción, el sistema realizara un muestreo del aire y enviara un pequeño mensaje (SMN) a los trabajadores para realizar los trámites requeridos necesarios. De manera inversa, los trabajadores pueden enviar un mensaje corto (SMS) a este sistema.</p>

<h2>FUNCIONALIDAD DEL SISTEMA </h2><br>

<p align="justify">El sistema está dividido en seis subsistemas funcionales de acuerdo con los requerimientos del usuario.
<ol>
<li>  Limpieza<br>
Se trata de la función de limpieza automática. Antes de usar una bolsa de muestreo, para extraer todo el aire para mantener un vacío y usar el nitrógeno para lavar la bolsa. Antes de limpiar los usuarios necesitan configurar el volumen de la bolsa de muestreo y velocidad del bombeo.</li>
<li>  Calibración<br>>
Antes del muestreo se requiere establecer una tasa de flujo adecuada y un límite de exposición permisible para el contaminante.</li>
<li>  Muestreo<br>
Proporciona una función de disparo de alto nivel, lo que significa que automáticamente generara aire a muestrear cuando el valor detectado este por encima del límite.</li>
<li>  Estado FTP<br>
La página HMI puede mostrar el estado de envío / recepción de mensajes cortos,
Red inalámbrica 3G o estado de conexión FTP y carga de archivos FTP progreso, también puede configurar el tiempo de carga de FTP para el informe diario.</li>
<li>  Envió de  correo electrónico <br>
La página de HMI puede habilitar la funcionalidad de correo electrónico, mostrar el tiempo de conexión o el estado, configurar el número de enviar correo electrónico y configurar la dirección de correo electrónico.</li>
<li>  Otras configuraciones <br>>
En la página del administrador, los usuarios deben ingresar la contraseña para iniciar sesión. La página HMI proporciona la válvula de tres vías y ajuste de interruptor de bomba que se utiliza para los procedimientos de limpieza y muestreo y puede establecer el servidor de correo electrónico o el servidor FTP.</li>
 </p>

