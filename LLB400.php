<h2><center>Diagramas de aplicaciones<br>Prueba a zapatos de nieve</center></h2>

<div align="center"><img src="imagenes/36/application_121_LLB400.jpg" alt="Aplicaciones" title="Prueba a zapatos de nieve" width="40%"  class="image_productos"></div><br>

<p align="justify">FUTEK ha llegado recientemente a través de un stand de prueba muy exclusivo y creativo para simular las cargas que se crean durante la marcha. En esta aplicación particular 2 botones de carga FUTEK se utilizan para medir la fuerza de los movimientos del dedo del pie y el talón un paso a la vez. La aplicación se simula mediante un módulo de tipo de metal para probar la resistencia y simular caminar en la nieve para ciclos de pruebas de zapato. La fuerza de la carga máxima probada en cada pie es aproximadamente 80-100 libras.
