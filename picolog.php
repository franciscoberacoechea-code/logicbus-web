<strong>M&uacute;ltiples Vistas</strong>
<p>PicoLog muestra los datos en muchas vistas, que pueden ser activadas como y cuando se requieran. &Eacute;stas vistas pueden ser activadas durante y despu&eacute;s de la recolecci&oacute;n de datos.</p>
<strong>Vista de Registro </strong>
<p>Te habilita para iniciar/parar el registro y especifica los archivos de registro. Muestra las lecturas actuales y las condiciones de alarma para cada canal. Todas las configuraciones como escala, canales y muestreo son controladas desde la vista de registro.</p>
<strong>Vista gr&aacute;fica XY</strong>
<p>Muestra un par&aacute;metro contra otro. &Uacute;til para graficar voltaje contra corriente, por ejemplo.</p>
<strong>Vista de Hoja C&aacute;lculo </strong>
<p>Muestra datos de texto en algun formato que pueda ser f&aacute;cilmente copiado y pegado en otras aplicaciones. Los datos pueden tambi&eacute;n guardarse en el disco en el formato de texto ASCII.</p>
<strong>Vista Gr&aacute;fica</strong>
<p>Las gr&aacute;ficas pueden ser mostradas durante y despu&eacute;s de la recolecci&oacute;n de datos. Cada canal puede ser mostrad en su propia gr&aacute;fica o canales m&uacute;ltiples pueden ser mostrados en la misma gr&aacute;fica. Los ejes pueden configurarse manualmente, autom&aacute;ticamente o en modo de registro de tablas. Los multiplicadores te permiten magnificar las &aacute;reas de inter&eacute;s. Las gr&aacute;ficas pueden ser copiados en el portapapeles y luego pegados en reportes.</p>
<strong>Vista de Notas </strong>
<p>La vista de notas te permite adjuntar notas a los datos.</p>
<strong>Vista de Reproductor</strong>
<p>Muestra los datos previamente grabados. Te habilita para desplazarte r&aacute;pidamente a trav&eacute;s de archivos guardados para comparar resultados en operaciones consecutivas. El reproductor puede ser utilizado para examinar los datos viejos mienstras que los datos nuevos se est&eacute;n registrando todav&iacute;a.</p>

<strong>Modos de Programaci&oacute;n </strong>

<p>PicoLog para Windows trabaja en dos modos: modo de reproductor para mostrar datos registrados previamente y registrar nuevos datos. Puedes tener mas de una copia de  PicoLog para Windows corriendo al mismo tiempo, as&iacute; que puedes usar el reproductor para analizar los datos viejos mientras se registran los nuevos datos.<br>
PicoLog puede recolectar datos desde mpultiples convertidores al mismo tiempo. &Eacute;sto no solo permite una mezcla de unidades de entrada de voltaje para ser usado en la misma PC, sino que tambi&eacute;n otros instrumentos basados en PC como el  TC-08 (<a href="tarjeta-daq-temperatura-tc-08">para medici&oacute;n de temperatura</a>) y el osciloscopio  ADC-200 para ser  usados al mismo tiempo.
<br><br>
