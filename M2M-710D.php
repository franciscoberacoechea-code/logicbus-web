<center><strong>Mantenimiento remoto con módulo de transmisión en serie M2M-710D</strong></center><br><br>
  
<p>M2M-710D es un módulo especialmente diseñado para el mantenimiento y actualización remota de soluciones seriales a aplicaciones de red.  Es adecuado para el campo industrial hostil.  M2M-710D ofrece 2 principales tecnologías en red.  La conexión en par provee túnel de datos TCP entre 2 dispositivos seriales.  Por lo tanto, significa que en una infraestructura cliente/servidor TCP/IP, M2M-710D puede ofrecer una transmisión de datos seriales de manera remota por Ethernet entre los lados local y servidor.  Esta solución puede transferir la condición del sitio de equipo de precisión.  El ingeniero de mantenimiento puede checar y diagnosticar directamente el dispositivo como si estuviera en el sitio, esto puede reducir los altos costos de mantenimiento para incrementar la competitividad de las empresas.<br><br>
M2M-710D también integra tecnologías Virtual COM.  Eso puede resolver la insuficiencia de un puerto COM real en la PC.  Aplicando esta tecnología, el ingeniero de mantenimiento puede tomar el mantenimiento o monitoreo remoto cuando sea y donde sea.</p>



