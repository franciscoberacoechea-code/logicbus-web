<strong><center>Sumador/subtractor de corriente/voltaje DC, permite realizar la suma o la resta de 2 señales analogicas y obtener la salida equivalente mediante una señal analogica (0-20mA y 4-20mA o 0-1/ 0-5/ 0-10 y 2 a 10Vdc). Alimentacion: 10 a 40Vdc o 19 a 28Vac</center></strong>

<div align="right">
<a href="https://tienda.logicbus.com.mx/Z190_p_4223.html" title="Ir a Tienda" target="_blank"><img src="images/shopping_cart.png" alt="Comprar"></a>
