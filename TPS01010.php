Aunque tradicionalmente las celdas de carga de los botones de carga no son conocidas por su alta precisión, los ingenieros de FUTEK han disipado este concepto al mejorar continuamente la precisión de este producto. El botón de carga en miniatura LLB300 ofrece alta precisión y alta rigidez. Tiene una no linealidad de ± 0.2% y una deflexión de 0.002 en nominal.
