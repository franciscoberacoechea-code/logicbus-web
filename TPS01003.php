<center><strong><b>La celda de carga en línea roscada en miniatura LCM200</b> ofrece una alta precisión. Tiene una no linealidad de ± 0.5% de la salida nominal y una desviación de 0.0002 en [0.00508 mm] a 0.0005 en [0.0127 mm] nominal.</strong></center><br>

