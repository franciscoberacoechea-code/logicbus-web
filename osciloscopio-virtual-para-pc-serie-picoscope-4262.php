          <h2>Características</h2>
          <ul>
            <li>Osciloscopio de doble canal / analizador de espectro</li>
            <li>Resolución de 16 bits</li>
            <li>Baja distorsión (96 dB SFDR)</li>
            <li>Bajo nivel de ruido (8.5 µV RMS)</li>
            <li>Ancho de banda de 5 MHz</li>
            <li>Memoria intermedia de 16 MS</li>
            <li>Generador de señal de baja distorsión</li>
