<p>Z190 permite realizar la suma o la resta de 2 señales analógicas (mA o V) y obtener la salida equivalente mediante una señal analógica (mA o V). Las dos entradas pueden tener también diferente importancia. Dispone de interruptores DIP para establecer los rangos de entrada / salida disponibles. La fuente de alimentación auxiliar permite también conexiones activas o pasivas en el lado de salida. Un aislamiento galvánico de 3 vías entre la fuente de alimentación // entrada // circuitos de salida garantiza la integridad de sus datos.
</p><br>

<strong>Caracteristicas:</strong>
<ul>
<li>Alimentación: 19 a 40 Vdc ó 19 a 28 Vac</li>
<li>2 canales de entrada: corriente 0 a 20, 4 a 20 mA ó voltaje 0 a 5, 1 a 5, 0 a 10, 2 a 10 Vdc</li>
<li>1 canal de salida: corriente 0 a 20 , 4 a 20 mA ó voltaje 0 a 5, 1 a 5, 0 a 10, 2 a 10 Vdc</li>
<li>Precisión: 0.2%</li>
<li>Aislamiento galvánico a 3 vías</li>
<li>Terminales removibles a tornillo</li>
<li>Montaje en riel DIN</li>
</ul>

