<article>
  <p><b>Resumen de la aplicaci&oacute;n:</b>
La prueba de tracción de cables o la prueba de unión de cables es una técnica que se utiliza para evaluar la calidad y resistencia de la unión en aplicaciones microelectrónicas. En este sistema automatizado para prueba de unión de cables, la celda LSM300 o LSB200 de FUTEK se pueden integrar en el mecanismo del cartucho para registrar la fuerza máxima o la fuerza de rotura de la unión de cables.</p>

<img src="imagenes/36/diagramas/manufactura/pruebas-de-union-de-cable.jpg" alt="Pruebas de unión de cable" width="50%">

<div>
  <p><b>C&oacute;mo funciona:</b><br></p>
  <ol>
    <li style="color: black;">Los sistemas para pruebas de unión de cable nos permiten realizar pruebas destructivas y no destructivas.</li>
    <li style="color: black;">Las pruebas destructivas son cuando se jala el cable verticalmente, y se mide la fuerza hasta que el cable se rompe o separa.</li>
    <li style="color: black;">Una prueba es no destructiva, cuando el cable se tensa a una fuerza predeterminada y solo con esto se valida la funcionalidad del mismo, sin romperlo.</li>
    <li style="color: black;">Los sistemas de prueba para uniones de cable pueden realizar también pruebas de cizallamiento de bola de soldadura, cizallamiento de troquel, tracción por tope de espárrago, tracción de cinta, pelado de pinzas, fatiga y empuje.</li>
    <li style="color: black;">Específicamente durante la prueba de tensión de cables la celda de carga <strong><a href="https://tienda.logicbus.com.mx/Montaje-lateral_c_1631.html" target="_blank">LSM300</a></strong> o la celda <strong><a href="https://tienda.logicbus.com.mx/LSB200_c_1670.html" target="_blank">LSB200</a></strong> pueden colocarse en la herramienta de gancho para medir la fuerza de tensión sobre el cable.</li>
    <li style="color: black;">Estas mediciones pueden transmitirse a la computadora para su análisis utilizando las soluciones USB de Futek.</li>
  </ol>
