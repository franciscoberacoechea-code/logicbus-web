 <div align="center">
 <img src="https://tienda.logicbus.com.mx/assets/images/02/m-7015p-g.jpg" class="image_productos" width="200" alt="Modulo de adquisicion de datos: M-7015P" title="Modulo de adquisicion de datos: M-7015P"><br>
