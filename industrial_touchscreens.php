<p><strong>Pantallas Industriales</strong>: Las pantallas ayudan a crear una interfaz amigable para el usuario que esté realizando alguna configuración mediante el manejo de herramientas en un entorno industrial.<br>
La pantalla HMI (interfaz hombre-máquina) es ideal para poner en marcha aplicaciones de entorno de trabajo limitadas debido a que hereda características de sus predecesoras haciéndola estable, confiable, fácil de usar y al mismo tiempo mantiene un diseño eléctrico fino en su estructura interna, así como un amplio rango de temperatura de operación y amplio rango de alimentación que le permiten adaptarse a las más duras condiciones de trabajo.</p>

