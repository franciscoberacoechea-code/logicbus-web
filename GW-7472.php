<p>GW-7472 (convertidor Ethernet/IP a Modbus RTU maestro) es útil para intercambio de datos entre una red Modbus RTU y una red Ethernet/IP.  Lee los registros desde esclavos Modbus RTU y publica estos datos a datos de registro de entrada del escáner Ethernet/IP.  Los datos de salida transmitidos por el escáner Ethernet/IP son actualizados a datos de registro de esclavos Modbus RTU vía el dispositivo GW-7472.  También para ahorrar espacio en instalación, el GW-7472 tiene una forma diminuta lo cual lo hace fácil de instalar donde sea, aun directamente añadido a un dispositivo serial o embedido dentro de una máquina.</p><BR>

