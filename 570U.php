<p align="justify">Controle y monitoree interfaces analógicas y digitales a través de cualquier conexión USB. El SeaI/O-570U-OEM, diseñado con el chip A/D LTC1867 de Linear Technology, proporciona ocho entradas analógicas de 16 bits de un solo extremo, ocho entradas aisladas ópticamente y ocho salidas de relé de forma C.
<br><br>
Las entradas A/D se pueden seleccionar de forma independiente por software para rangos de +/- 5 V o +/- 15 V y cuentan con una alta impedancia de entrada, lo que permite una fácil conexión a una variedad de sensores. Las entradas A/D admiten selecciones flotantes/no referenciadas o referenciadas a tierra. Esto hace que las entradas A/D sean ideales para medir fuentes de señales flotantes , como salidas de transformadores, termistores y dispositivos alimentados por baterías. Además, las entradas A/D pueden operar en modo bipolar o unipolar, y un interruptor DIP permite un voltaje de polarización de +5 a través de una resistencia de 10 K para el modo de entrada de termistor.
<br><br>
El módulo SeaI/O-570U-OEM cuenta con ocho entradas ópticamente aisladas clasificadas para 5-30V DC y proporciona aislamiento externo de 3500V DC, mientras que los relés de forma C se pueden configurar como normalmente abiertos o normalmente cerrados y pueden conmutar cargas de CC de hasta 24 W. Perfecto para una variedad de aplicaciones de adquisición/control y prueba y medición de datos, el SeaI/O-570U-OEM incluye bloques de terminales extraíbles, que simplifican las conexiones de cableado de campo.
<br><br>
El SeaI/O-570U-OEM se alimenta de su fuente de 9-30V DC, o seleccione entre una variedad de opciones de fuente de alimentación Sealevel. Los módulos funcionan en un amplio rango de temperatura de funcionamiento de -20 °C a 70 °C y el rango de temperatura ampliado es opcional.
<br><br>
Amplíe su red de E /S con los productos de la serie SeaI/O N. Los módulos SeaI/O están disponibles con relés Reed y Forma C , entradas ópticamente aisladas, interfaces TTL , funcionalidad A/D y D/A. Se pueden agregar hasta 246 módulos de expansión adicionales utilizando conectores de paso convenientes.
<br><br>
