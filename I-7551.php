<p>El convertidor-aislador I-7551 provee un canal el&eacute;ctrico Full-duplex aislado (Incluyendo el control de la se&ntilde;al) entre dos dispositivos RS-232. Este asilamiento es una consideraci&oacute;n importante si su sistema utiliza diferentes fuentes de poder, o tiene se&ntilde;ales muy ruidosas o necesita operar con diferentes potenciales.<br>
El I-7551 tiene la opción de reconfigurar el control de la señal que esta siendo usada. El CTS puede ser elegido en vez del DSR y el RTS en vez del DTR.<br>
El I-7551 incorpora dos convertidores DC a DC, el aislamiento del I-7551 es alojado en el circuito de interfaz de entrada y salida. En otras palabras, el I-7551 es un convertidor aislado RS-232 a RS-232 de 3 vías.</p>
