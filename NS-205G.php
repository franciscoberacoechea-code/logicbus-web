<p>NS-205G es un conmutador gigabit no gestionable de 5 puertos que admite 10/100/1000 Base-T, con una función de autonegociación 10/100/1000 M y función MDI / MDIX automática. Puede conectar 5 estaciones de trabajo y cambia automáticamente la velocidad de transmisión (10 Mbps o 100 Mbps o 1000 Mbps) entre megabytes y gigabytes para las conexiones correspondientes. 
<br><br>
Es una solución ideal para aplicaciones que requieren gran ancho de banda que pueden requerir soluciones de gigabyte (como transmisión de imágenes digitales de alta resolución, transmisión / descarga de archivos de video / audio y conectividad de servidores). 
<br><br>
El mecanismo de control de flujo también se negocia. Hay LED de velocidad de enlace / datos para cada puerto para ayudar a solucionar problemas. Los conectores de puerto están blindados RJ-45. 
<br><br>
Ahorro de energía por número de puertos conectados y estado del enlace: las computadoras no requieren un acceso a Internet de gigabyte todo el tiempo; tampoco los switches utilizan todos los puertos en todo momento. Cuando una computadora o equipo de red se apaga, los interruptores a menudo permanecen encendidos y continúan consumiendo una cantidad considerable de energía. Con la tecnología de ahorro de energía, NS-205G puede detectar automáticamente el estado del enlace y reducir el consumo de energía de los puertos que están inactivos. Sin embargo, las computadoras o cualquier grupo de personas conectadas al modo de espera (no apagadas) no proporcionarán ahorros significativos de energía. 
<br><br>
Ahorro de energía por longitud de cable: los interruptores de ahorro de energía tienen la capacidad de analizar la longitud de cualquier cable Ethernet conectado a ellos para ajustar el consumo de energía en consecuencia. Las longitudes más cortas requieren menos potencia.</p>

<strong>Caracter&iacute;sticas:</strong>
<ul>
<li>Crossover automático MDI / MDI-X para plug-and-play.</li>
<li>Cada puerto admite la negociación automática de velocidad 10/100 y 1000 Mbps.</li>
<li>Control de flujo de contrapresión Full Duplex IEEE 802.3xy semidúplex.</li>
<li>Admite temperaturas de funcionamiento de -40 ° C ~ +75 ° C.</li>
<li>Ancho de banda de memoria de alto rendimiento de 10 Gbps.</li>
<li>Tecnología de ahorro de energía.</li>
<li>Admite entrada de alimentación de +12 ~ +48 V CC (NS-205AG).</li>
<li>Arquitectura de almacenamiento y reenvío.</li>
<li>El embalaje delgado se adapta a su montaje en riel DIN.</li>
</ul>


