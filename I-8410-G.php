<center><strong>Rack Mount Embedded Controller: 256K Flash, 256K SRAM, CPU de 40 MHz en 4 ranuras de capacidad, sistema operativo Mini 7.</strong></center><br>


<p>La I-8410 y la I-8810 son unidades embebidas de E/S serie que utilizan el protocolo DCON Firmware. ICPDAS proporciona varios módulos de E/S, como entrada/salida analógica, entrada/salida digital y módulos de contador/frecuencia, que se pueden usar en aplicaciones remotas de adquisición y control de datos para el monitoreo del medio ambiente, la administración de energía y la automatización de fábricas, etc.<br> 

La CPU es un 80188 de 8 bits (40MHz). Además de las funciones originales (entrada, salida, valor de encendido, valor seguro, valor límite alto, valor límite bajo) del módulo de E/S, el firmware proporciona funciones adicionales para permitir que los módulos de E/S en diferentes ranuras se combinen juntos . Por ejemplo, si el valor del canal de un módulo AI está por encima de un valor límite alto predefinido, o por debajo de un valor límite inferior predefinido, la información se puede pasar inmediatamente a otro módulo DO para activar la alarma o la luz.<br> 

Se proporcionan varios kits de desarrollo de software (SDK) y demos, como DLL, ActiveX, controlador Labview, controlador de Indusoft, controlador de Linux, servidor OPC, etc. Los módulos de E/S se pueden agregar fácilmente a la I-8410/I-8810 y puede integrarse rápidamente en un sistema existente.
</p><BR><br>


<strong>Caracteristicas:</strong>
<ul>
<li>Admite la interfaz de comunicación RS-232 o RS-485.</li>
<li>Admite el protocolo de comunicación DCON.</li>
<li>Dual Bus diseñado para admitir módulos de E/S de la serie I-8K e I-87K, como DI/DO, AI/AO, módulos de contador/frecuencia.</li>
<li>La ranura de expansión de E/S compacta permite la instalación rápida de arios módulos de E/S de 8K y 87K.</li>
</ul>

