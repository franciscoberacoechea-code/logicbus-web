        <p style="text-align: justify;">La mayoría de los sistemas informáticos industriales proporcionan puertos serie RS-232 estándar. Aunque ampliamente aceptado, RS-232 tiene una velocidad de transmisión, alcance y capacidades de red limitadas. Los estándares RS-422 y RS-485 superan estas limitaciones mediante el uso de líneas de voltaje diferencial para datos y señales de control, que convierte transparentemente las señales RS-232 en señales aisladas RS-422 o RS-485 sin necesidad de cambiar ningún hardware o software. La I-7520 / I-7520A le permite construir fácilmente un sistema de comunicación de larga distancia de grado industrial utilizando hardware de PC estándar.</p>

        <p>El diseño del aislamiento entre la I-7520 y la I-7520R / AR es diferente. Si el usuario desea suministrar energía desde el PLC / PC, se debe utilizar el I-7520R / AR; de lo contrario, el aislamiento se interrumpirá. Consulte el manual del convertidor de bus I-7000 para obtener información detallada.</p>

