<p align="justify">S107P permite una conversión transparente y aislamiento de la línea serie RS485 / RS422 en RS232 y viceversa. Las interfaces RS485 y RS422 están disponibles en los terminales.
El RS232 a través de un cable con conector hembra DB9 (incluido). Fuente de alimentación de red de 230V incluida en la caja.</p>

<strong>Datos Técnicos:</strong>
<ul>
<li>CÓDIGO DE PEDIDO: S107P</li>
<li>DESCRIPCIÓN: RS232 - RS485 / 422 convertidor de serie, versión portátil</li>
<li>FUENTE DE ALIMENTACIÓN: 9..12 Vcc 100 mA</li>
<li>CONVERSIÓN: RS232 - RS485 / 422</li>
<li>COMUNICACIÓN: Half / full dúplex punto a punto o multipunto, cambio automático de dirección o RTS conducido</li>
<li>INTERFAZ RS232: conector frontal RJ45</li>
<li>INTERFAZ RS485 / 422: terminales extraíbles, conexiones tipo tornillo</li>
</ul><br><br>


