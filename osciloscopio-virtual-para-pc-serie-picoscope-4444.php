          <h2>Entradas diferenciales inteligentes</h2>

          <p>Con una sonda de osciloscopio tradicional, las mediciones de un solo extremo se realizan entre una entrada de alta impedancia y una tierra de baja impedancia.</p>

          <p>Con un osciloscopio diferencial, las mediciones se realizan entre dos entradas de alta impedancia, lo que permite realizar mediciones a través de componentes y puntos de prueba donde ninguno de los lados está conectado a tierra. Las entradas diferenciales también rechazan el ruido en modo común: el ruido captado por igual en ambas entradas de alta impedancia se rechaza.</p>

          <p>Cada uno de los cuatro canales de entrada en el PicoScope 4444 cuenta con una interfaz de sonda inteligente que detecta e identifica las sondas compatibles y las alimenta cuando es necesario. Cada canal puede tener su propia elección de voltaje o sonda de corriente.</p>

          <p>Las sondas no atenuantes permiten la medición de alta resolución y bajo ruido de señales que van desde milivoltios a ± 50 V. Las sondas atenuantes permiten medir señales de hasta 1000 V CAT III. Las sondas de corriente están disponibles para corrientes de hasta 2000 A, también clasificadas para mediciones de 1000 V CAT III.</p>


          <h2>PicoConnect 441: Medida de milivoltios a ± 50 V</h2>

          <p>Las sondas de voltaje diferencial PicoConnect 441 son adecuadas para voltajes de hasta ± 50 V (para voltajes más altos, consulte el PicoConnect 442). Las sondas están equipadas con conectores de 4 mm estándar de la industria y se suministran con puntas de sonda de gancho con resorte desmontables. Otros accesorios de 4 mm, como sondas multimétricas y pinzas de cocodrilo, están disponibles por separado.</p>

          <p>Además de medir señales de voltaje sin conexión a tierra, las entradas diferenciales son ideales para medir la corriente a través de resistencias de detección. Como ninguno de los lados necesita estar conectado a tierra, pueden realizar mediciones del lado alto. Los rangos de entrada sensibles, la alta resolución y el muestreo rápido son ideales para medir corrientes de cambio rápido en dispositivos con batería e IoT.</p>

          <p>Las entradas de alta impedancia y alta resolución también son adecuadas para la investigación biológica y científica, ya que permiten mediciones en señales de milivoltios de bajo nivel (2 mV / div a 12 bits) en presencia de ruido de modo común sin la necesidad de costosos Preamplificadores diferenciales o sondas diferenciales de osciloscopio. La sonda está construida con un cable twinax (conductores internos de par trenzado con un blindaje externo) para garantizar una alta proporción de rechazo en modo común (CMRR). La pantalla externa del cable se puede conectar opcionalmente a una tierra de señal para mejorar el rechazo de voltajes y corrientes en modo común.</p>

          <p>Las sondas PicoConnect 441 también son ideales para medir fuentes de señales diferenciales, como bus CAN y audio balanceado en un solo canal, y se pueden usar para medir directamente desde sensores tipo puente como celdas de carga y sensores de presión.</p>

          <h2>PicoConnect 442: sondas de 1000 V CAT III</h2>

          <p> El PicoConnect 442 es una sonda de voltaje diferencial atenuante que aumenta el rango de entrada a 1000 V para permitir la medición segura y rentable de señales monofásicas, trifásicas y de otro tipo, como las que se encuentran en los variadores de velocidad y los inversores.</p>

          <p>La sonda PicoConnect 442 no requiere alimentación ni baterías. Esto lo hace ideal para la medición de la calidad de la red y otras mediciones a largo plazo.</p>

          <p>Las entradas diferenciales del PicoScope 4444 permiten que cada canal mida señales con diferentes voltajes de modo común. Como ejemplo, considere la batería en un vehículo eléctrico. Puede medir en todo el paquete usando un conjunto de canales a un rango de entrada de ± 500 V, y al mismo tiempo configurar los otros canales a ± 5 V para medir a través de celdas individuales. Esta disposición le permite aprovechar la resolución completa del osciloscopio.</p>

          <h2>Tres sondas de corriente con interfaz de sonda inteligente</h2>

          <p>Tres sondas de corriente diferentes están disponibles con interfaces Pico D9. TA300 y TA301 utilizan el efecto Hall para medir corrientes de CA y CC sin conexión directa al cable, y el TA368 usa el principio de Rogowski para mediciones de CA solamente. La interfaz de sonda inteligente alimenta las sondas, por lo que no se requieren baterías. También significa que cuando conecta cualquiera de las dos sondas, el software PicoScope lo identifica y configura el osciloscopio para leer en amperios.</p>

          <p>La sonda de corriente TA300 es una sonda de 40 A adecuada para medir señales de CC a 100 kHz. Es una sonda de precisión para corrientes más pequeñas y puede resolverse hasta unos pocos miliamperios.</p>

          <p>La sonda de corriente TA301 es una sonda de 200/2000 A de rango conmutado adecuada para medir señales de ancho de banda de CC a 20 kHz.</p>

          <p>La sonda de corriente TA368 es una sonda de CA de 2000 A de rango único adecuada para medir señales por encima de CC a 20 kHz, y debido a que la sonda tiene una capacidad nominal de 1000 V CAT III, es ideal para realizar mediciones de corriente de la red.</p>

