<p align="justify">El Graphtec GL100-N-DPA-AC50A es un conjunto que se incluye con el registrador de datos compacto GL100-N, así como el Adaptador de Sensor de Corriente AC AC GS-DAP-AC, y el Sensor de Corriente AC GS-AC50A. Su cuerpo permite a los usuarios cambiar sensores y terminales para medir varias señales. La dimensión del cuerpo principal es un ligero de 2,6 pulgadas de ancho x 3,93 pulgadas de alto x 1,06 pulgadas de espesor (66 mm x 100 mm x 27 mm).<br><br>
Funciona con dos baterías AA (no incluidas) o alimentación de bus USB (incluye cable USB MicroB-A incluido). Con una memoria integrada de 4,9 MB y una memoria externa a través de la ranura para tarjeta Micro SD, el cuerpo del GL100 también incluye un puerto USB (conexión Micro B).<br><br>
La pantalla del GL100NDPAAC50A es un monocromo retroiluminado con resolución de 128 × 64 puntos que muestra los valores medidos y la configuración. Los datos grabados no se muestran en la unidad principal; Los datos capturados solo se pueden mostrar en la PC usando el software de aplicación incluido.<br><br>
El GS-DAP-AC es un adaptador de sensor de corriente CA que puede conectarse con hasta 2 sensores simultáneamente, y se puede conectar al GS-TH (no incluido con el GL100-N-CO2-DPA-LXUV), el GS- CO2, y el GS-LVUX.<br><br>
El sensor de corriente de CA GS-AC50A incluido es 1 de 3 sensores de corriente que se pueden conectar al adaptador de CA GS-DAP y tiene una potencia nominal de 50 A en las mediciones de corriente.</p><br><br>

