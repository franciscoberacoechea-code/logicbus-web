<p>La serie RS-408 es el último conmutador de anillo redundante en tiempo real de ICPDAS. Pueden satisfacer el requisito de link-lose-backup en la aplicación de campo industrial:<br><br>

<strong>Link-Loss-Backup:</strong> la ruta de respaldo se activará en 100 ms (configurable) y mantendrá toda la LAN funcionando. La serie RS-405 admite topologías versátiles :<br><br>

<strong>topologías versátiles:</strong> el protocolo STP patentado de RS-408 permite a los usuarios construir topologías más complicadas que la arquitectura de anillo básica. También es posible construir una LAN Ethernet de anillo redundante rentable combinando RS-408 con otro conmutador Ethernet no administrado de bajo costo, la serie NS-205/208.<br>

<strong>Rentable anillo Ethernet:</strong> Tener un RS-408 y otros interruptores de Ethernet no administrados de bajo costo (por ejemplo, serie NS-205/208) en un anillo, esta LAN Ethernet también tolera perder enlace. La serie RS-408 está equipada con 2 entradas de alimentación, que son redundantes entre sí. La función de salida del relé puede emitir una señal de advertencia durante un corte de energía o pérdida de enlace. <br>

<strong>Salida de relé:</strong> la salida de relé del RS-408 podría emitir una señal de advertencia cuando falla en una entrada de alimentación o cuando se pierde el enlace. Con el protocolo Modbus / TCP de apoyo, el administrador de LAN Ethernet puede obtener la información del estado del puerto individual de RS-408.<br>

<strong>Modbus / TCP:</strong> la serie RS-408 admite el protocolo Modbus / TCP. Usando este protocolo, el administrador de la LAN Ethernet puede leer el estado del puerto de RS-408 y SCADA puede conocer la condición de la LAN en la que se basa.

