<p align="justify"><strong><em>InduSoft Web Studio</em></strong>duSoft Web Studio, es un potente conjunto de herramientas de automatización totalmente modular para el desarrollo de aplicaciones, desde modernas interfaces Hombre-Maquina (HMI) hasta completos sistemas de Supervisión, Control y Adquisición de Datos  (<a href="scada"><strong>SCADA</strong></a>), bajo cualquier plataforma basada en Windows como NT, 2000, XP, Windows 7, CE o CE.net y para Internet o Intranet. Su entorno de desarrollo le permitir&aacute; trasladar los m&aacute;s complejos comportamientos de sus procesos industriales a aplicaciones con tan solo simples arrastres y clics de rat&oacute;n. Indusoft Web Studio es la soluci&oacute;n E-Automation ideal en el mundo industrial.<br>
Su entorno de desarrollo le permitirá trasladar los más complejos comportamientos de sus procesos industriales a aplicaciones con tan solo simples arrastres y clics de ratón. 
Estas aplicaciones consisten en pantallas animadas que sirven de interfaz con el operador, drivers para PLC y otros dispositivos de E/S controlables, una base de datos de etiquetas para aplicaciones, módulos opcionales tales como monitores para alarmas, gráficas de tendencia, recetas, planificadores de tareas e interactúan con otras aplicaciones de Windows durante la ejecución de la aplicación utilizando los siguientes protocolos:<br>
<ul>
<li>ODBC (Open Database Connectivity)</li>
<li>DDE (Dynamic Data Exchange)</li>
<li>NetDDE (Network Dynamic Data Exchange)</li>
<li>OPC (Open Connectivity)</li>
<li>TCP/IP (Transmission Control Protocol/Internet Protocol)</li>
</ul>

Despu&eacute;s de desarrollar la aplicaci&oacute;n, esta puede ser ejecutada en el mismo equipo en el que fue desarrollada o descargar la aplicaci&oacute;n a otro equipo (utilizado una conexi&oacute;n serial o TCP/IP) y ejecutarla usando InduSoft Web Studio o un software de ejecuci&oacute;n *<a href="CEView"><strong>CEView</strong></a>.El equipo procesa los datos de los dispositivos conectados y reacciona de acuerdo a estos, los muestra, guarda y permite descargarlos.</p>



