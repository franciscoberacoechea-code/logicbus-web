      <td colspan="2"><div align="justify">The DNA-AI-211 is a high performance, four-channel vibration measurement board for use with popular Cube chassis. The board is specifically designed to allow direct connection to industry standard 2-wire vibration sensors (e.g. ICP and IEPE). Each channel is based upon its own 24-bit A/D converter. This A/D per channel mode allows all four channels to be sampled simultaneously, allowing vibration data on different channels to be easily correlated in the time domain. The board will sample all four channels up to their maximum 125 kSPS (maximum board throughput of 500 kSPS). Using the Cube&rsquo;s powerful trigger/sync interface, channels on multiple boards and even in multiple Cubes are easily configured to sample simultaneously.<br>
          <br>
          The board&rsquo;s 24-bit converters provide exceptional accuracy with signal to noise ratios (SNR) of 109 dB at 5 kHz and 97 dB at the board&rsquo;s 105 kSPS max sample rate. The 24-bit converters also provide the dynamic range required to monitor everything from the smallest signals up to a full scale shock on a single input range. However in those few instances where even higher resolution is required for extremely low level signals, the AI-211 input amplifier offers 4 different input ranges from +25/-13 VDC to &plusmn;3.125VDC.<br>
          <br>
          Anti-aliasing filtering is provided by a combination of analog and digital FIR filters. The digital filter allows a combination of low passband ripple (&plusmn;0.005 dB), steep falloff and low stop band floor (-100 dB) unattainable with simple analog filtering. The digital nature of the filter also ensures that each filter induces an identical phase shift so no filter induced inter-channel phase jitter will impact or corrupt subsequent analysis.<br>
          <br>
          Each of the four input channels is fully electrically isolated from each other, as well as the cube in general. The isolation ensures that input noise is minimized as noise picked up by other channels has no impact on the measurement. The isolation also protects the cube and the reliability of measurements on other channels in the event that a sensor input is shorted externally or if a sensor fails in a way that could impact other measurements through a ground path.&nbsp;<br>
          <br>
          The bias drive current is user selectable from 0 mA to 8 mA in 255 steps (0.031 mA per step). The bias current is also monitored by on board A/D converters, allowing your application to easily determine if a particular sensor is shorted, opened or is otherwise behaving abnormally. Annunciator LEDs mounted adjacent to each channel&rsquo;s I/O connector also illuminate when the measured bias current is outside of the acceptable range. The current output may also be disabled allowing the input to perform standard voltage measurements.<br>
          <br>
      All connections are provided through standard 10-32 UNF coaxial connectors. Like all "Cube" I/O boards, the DNA-AI-211 offers operation in harsh environments and has been tested to 5 vibration, 50&nbsp;<em>g</em>&nbsp;shock, -40 to +85 &deg;C temperatures and altitudes up to 70,000 feet.</div></td>
