<p align="justify">El módulo Z109REG2 adquiere una señal de entrada universal, la convierte en formato analógico y la retransmite en una salida universal aislada.</p>

<strong>Caracteristicas:</strong>
<ul>
<li>entrada universal: tension, corriente termopares, termorresistencias, potenciómetro, reóstato.</li>
<li>medicion y retransmision en salida analógica aislada, con salida en tension y en corriente activa/pasiva.</li>
<li>seleccion mediante conmutadores DIP de: tipo de entrada, START-END, modo de salida</li>
<li>salida de contacto de alarma con relé, configurable mediante PC.</li>
<li>entrada de STROBE para activar la salida analógica por mando de un PLC</li>
<li>aislamiento en 3 puntos: 1500V</li>
</ul>

