<center><strong>Tarjeta de escalonamiento / control de servo de alta velocidad de 3 ejes.</strong></center><br>


<p>El PISO-PS300 es un panel de control de servomotor de pulso de 3 ejes. La CPU integrada de PISO-PS300 realiza el comando de movimiento transferido desde una PC host a través de un FIFO de 2K bytes. También envía la posición y el estado a la PC host a través de otro FIFO de 2K bytes. Este búfer proporciona un búfer de tiempo y es muy adecuado para sistemas operativos de Windows. Se proporcionan controladores DOS, Windows 95 y Windows NT.
</p><BR><br>

<strong>Caracteristicas</strong>
<ul>
<li>Tarjeta de control PCI de servo / paso de salida de impulsos de 3 ejes.</li>
<li>bus PCI</li>
<li>Velocidad de pulso de salida máxima: 1MHz.</li>
<li>Modo de simulación / modo real.</li>
<li>Encoder / pulso read read.</li>
<li>Modo de salida programable: CW / CCW, Pulso / Dirección</li>
<li>Interpolación lineal de 3 ejes, interpolación circular de 2 ejes.</li>
<li>Perfil de velocidad trapezoidal programable.</li>
<li>Período de DDA programable.</li>
<li>Configuración de dirección programable.</li>
<li>Regreso a casa de 2 velocidades programable, preajuste del hogar, dirección del hogar.</li>
<li>Interruptores de límite de inicio, avance y retroceso por eje.</li>
<li>parada de emergencia de hardware, parada de emergencia de software.</li>
<li>Limitar la autoprotección del interruptor.</li>
<li>Estado normal del interruptor de límite programable: N.O. (normal abierto) o N.C. (cierre normal).</li>
<li>8 entradas digitales, 7 salidas digitales.</li>
<li>Aislamiento óptico de 2500V.</li>
<li>CPU integrada, totalmente 45 comandos configurados.</li>
<li>DOS, Windows 95/98, controlador DLL de Windows NT.</li>
<li>BCB, VB, controlador Delphi.</li>
</ul>
