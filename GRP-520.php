<center><strong>Gateway 3G/ puerto Ethernet y serial. 1x RS-232/ 1x RS-485/ servidor web/ Router 3G. Temperatura de operacion -25°C~75°C (-13°F~167°F).</strong></center><br>

<p>El GRP-520 proporcionado por ICP DAS es una puerta de enlace 3G para Ethernet o puerto serie. Con el modelo de GPS opcional, el GRP-520 también puede ser un sistema de localización por GPS. Se puede usar en campos de aplicación M2M para transferir la E/S remota, datos Modbus o video de la cámara a través de 3G/2G. Dentro de la CPU de alto rendimiento, la serie GRP-520 puede manejar una gran cantidad de datos y son adecuados para el entorno industrial duro. La serie GRP-520 tiene un módulo 3G, una interfaz Ethernet y un módulo GPS opcional.</p>

Caracteristicas:
<ul>
Sistema embebido de Linux.
<li>Soporta Tri-banda WCDMA 2100/1900/850 MHz y banda cuádruple GSM 850/900/1800/1900 MHz.</li>
<li>10/100 Base-TX ethernet eontroller compatible.</li>
<li>Puerto COM: COM1 (3 cables RS232), COM2 (RS-485), COM3 (3 cables RS232).</li>
<li>GPS: 32 canales con seguimiento All-In-View (opción).</li>
<li>Soporte de tarjeta Micro SD.</li>
<li>Proporcionar la función de enrutador 3G.</li>
<li>Función de mapeo del puerto de soporte.</li>
<li>Proporcionar puerto serie a la puerta de enlace 3G.</li>
<li>Alta fiabilidad en entornos hostiles.</li>
<li>Montaje en riel DIN.</li>
</ul>
