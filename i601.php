<p text-align: justify>La tarjeta de adquisición de datos i601 conecta una computadora con Windows a sensores y controles a través de entradas analógicas, entradas digitales y salidas digitales.<br>

La i601 se alimenta del puerto USB, no requiere alimentación externa.<br>

Cuenta con 16 entradas referenciadas (SE) u 8 diferenciales para voltaje canales (Ch#1 al #16), cada uno configurable independientemente por software desde la PC con Windows que le permite conectar una gran variedad de diferentes tipos de sensores. Mide directamente: Voltaje, Termopares, Termistores, RTDs, Celdas de Carga, Galgas Extensiométricas, potenciómetros, Corriente, Resistencia.<br>

Resumen del producto:<br>


El rango de entrada de voltaje en cada canal es independientemente programable por software para medir: ± 20mV, ± 40mV, ± 80mV, ± 150mV, ± 300mV, ± 600mV, ± 1.2V, ± 2.5V, ± 5V, ± 10V.<br><br>

Se incluye un conector hembra Hd44 <br>
<div align="center"><img src="imagenes/217/diagrama-i601.png" alt="pasos industria 4.0" align="center" width="40%"></div>
<br>
que está compuesto por su conector de 44 pines y su cubierta de plástico. Ademas se cuenta con cajas para cableado para conexiones opcionales como: <br>
<a href="https://www.logicbus.com.mx/imagenes/217/i510.jpg"> i510</a>, <a href="https://www.logicbus.com.mx/imagenes/217/i511.jpg"> i511</a>, <a href="https://www.logicbus.com.mx/imagenes/217/i512.jpg">i512</a> Si se trabaja con termopares, se requiere una caja de cableado i510 debido a su sensor CJC (punta de compensación de unión fría).<br>


El i601 es un sistema autónomo de adquisición de datos USB. No se requieren componentes adicionales, como fuente de alimentación externa. <br>
Componentes incluido en su compra: Tarjeta i601, Cable USB, Software, Conector hembra Hd44 con conector, tapa y accesorios complementarios.<br>

Muestreo de hasta 160K muestras por segundo por canal, 12Ks / seg / ch para 2 canales, 6Ks / seg / ch para 4 canales y 3Ks / seg / ch para 8 canales.<br></p>


