<center><strong>Entrada digital ópticamente aislada de 32 canales y tarjeta de salida de colector abierto óptico digital de 32 canales (fuente actual). Incluye cable CA-4037B y dos conectores CA-4002 D-Sub.</strong></center><br>


<p>El PISO-P32A32/P32A32-5V?/P32A32U tiene 32 canales de entrada digital ópticamente aislada y 32 canales de salida digital ópticamente aislada, dispuestos en cuatro bancos aislados. Cada salida digital ofrece un transistor PNP y un diodo de supresión integral para la carga inductiva. Los canales de entrada aislados 0-15 están diseñados en el grupo A, mientras que los canales 16-31 son del grupo B. Los canales de salida aislados están diseñados en el grupo C y el grupo D. La entrada del fotoacoplador del PISO-P32A32-5V ??puede funcionar con cualquiera una fuente de corriente interna o una fuente de alimentación externa, mientras que la entrada del PISO-P32A32/P32A32U funciona solo con alimentación externa.<br><br>

Esta placa de interfaz se instala fácilmente en cualquier PC. La placa interactúa con las señales lógicas de campo, lo que elimina los problemas de bucle de tierra y aísla la computadora host de tensiones dañinas. El PISO-P32A32 tiene un conector D-Sub de 37 pines y un conector macho de 40 pines. El cable plano de 40 pines a DB-37 se usa para arreglarlo con la carcasa. El usuario puede conectar la señal digital a través del segundo conector D-Sub. Cada conector D-Sub contiene 16 canales de entrada y 16 canales de salida.<br>

El PISO-P32A32U también agrega un interruptor de ID de tarjeta. Los usuarios pueden establecer la ID de la tarjeta en una placa y reconocer la placa mediante la ID a través del software al usar dos o más tarjetas PISO-P32A32U en una computadora.<br>

El PISO-P32A32/P32A32-5V?/P32A32U es compatible con varios sistemas operativos, como Linux, DOS, Windows 98/NT/2000 y Windows XP/2003/Vista/7 de 32 bits/64 bits. También proporciona el control DLL y Active X, y varios programas de muestra de lenguaje en Turbo C ++, Borland C ++, Microsoft C ++, Visual C ++, Borland Delphi, Borland C ++ Builder, Visual Basic, C # .NET, Visual Basic.NET y LabVIEW para ayudar usuarios para desarrollar rápida y fácilmente sus aplicaciones.
</p><BR><br>

<strong>Caracteristicas</strong>

<ul>
<li>Soporta el bus PCI +5 V para PISO-P32A32 / P32A32-5V</li>
<li>Entrada digital ópticamente aislada de 32 canales.</li>
<li>Salida digital de 32 canales aislada ópticamente.</li>
<li>Convertidor DC / DC incorporado con aislamiento de 3000 VDC.</li>
<li>Cuatro bancos aislados.</li>
<li>Protección de aislamiento de fotografías de 3750 Vrms.</li>
</ul>
