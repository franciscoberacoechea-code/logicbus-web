<p align="justify">El botón de carga roscada en miniatura LLB215 (salida de cable inferior) está diseñado para aplicaciones de compresión en línea o de prensa. El LLB215 está hecho de un robusto acero inoxidable 17-4 PH, con un diámetro exterior subminiatura de 0.38 in [9.5 mm].
<br>
Aunque los botones de carga roscados en miniatura tradicionalmente no son conocidos por su alta precisión, los ingenieros han disipado este concepto al mejorar continuamente la precisión de este producto. Estas celdas de carga logran una gran precisión y rigidez con una no linealidad de ± 0.5% y una desviación de 0.0007 en nominal. También encontrará opciones disponibles para salidas externas coincidentes.
<br>
El botón de carga roscado en miniatura LLB215 estándar (salida de cable inferior) se puede modificar o personalizar para satisfacer sus requisitos y la mayoría de las capacidades están en nuestro inventario, lo que las hace disponibles para una entrega rápida. Similar a toda nuestra línea de productos de Celdas de Carga, este modelo se fabrica en los Estados Unidos y utiliza tecnología de galga extensiométrica de lámina metálica.</p><br>

<h2>Características</h2>
<ul>
<li>Compensación de temperatura totalmente interna (sin circuito de acondicionamiento externo)</li>
<li>Subminiatura / peso ligero</li>
<li>Baja deflexión / respuesta rápida</li>
<li>Construcción de acero inoxidable 17-4 PH.</li>
<li>Para uso en compresión</li>
<li>Utiliza tecnología de galga extensible de lámina metálica.</li>
<li>Salida de cable inferior </li>
</ul><br>

<p align="justify">Para todos aquellos que están buscando una solución completa podemos proveerle de displays de acondicionamiento de señales o nuestro sistema portátil VCal con el que podrás llevar directamente con el cliente un sistema de verificación fácil de usar haciéndolo ideal para verificación y calibración de tus productos en el sitio. La serie LLB también está disponible con opciones TEDS / IEEE1451.4</p>
