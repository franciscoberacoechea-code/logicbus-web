<h2>B. Estacionamientos Inteligentes</h2><br>

<p align="justify">Hoy en día varias empresas de automatización, actualmente están trabajando en optimizar los estacionamientos inteligentes, este tipo de proyectos se puede desarrollar de varias formas, en este artículo expondremos una de ellas.<br>
El estacionamiento inteligente, se conforma de un grupo de sensores, que estarán ubicados en los estacionamientos disponibles y estarán señalando si hay lugares libres o no, alimentados por una fuente de larga duración. La información se revela mediante un mapa, que envía la información mediante una aplicación móvil. De esta forma, la información de los sensores, se recopila mediante repetidores, los cuales a su vez están intercomunicados con un Gateway central, enviando la información al dispositivo móvil del lugar estacionamientos libres y su ubicación exacta en el mapa.</p>

<center><img src="https://www.logicbus.com.mx/imagenes/articulo/estacionamientos-int.JPG" class="image_productos" width ="40%" alt="Figura 3.  Estacionamientos Inteligentes" title="Figura 3.  Estacionamientos Inteligentes"></center><p><center><b>Figura 3.  Estacionamientos Inteligentes</b></p></center>

<p>El Gateway, también podría estar subiendo la información a la nube, esto abriendo la posibilidad de generar estadísticas, así medir los lugares con mayor concurrencia, tomando decisiones de mejora.<br>
Un aspecto importante es la forma de pago aceptando ya la posibilidad de monedas electrónicas y tarjeta de crédito, entre otros</p>

