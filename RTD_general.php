        </div>        <ul>
          <li>Ser qu&iacute;micamente inerte
          <li>Tiene un elevado punto de fusi&oacute;n (2041,4 K)
          <li>Como ya hemos dicho, tiene una alta linealidad
          <li>Puede ser obtenido con un alto grado de pureza. </li>
