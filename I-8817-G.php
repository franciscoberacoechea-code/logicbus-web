<center><strong>Controlador serie integrado de entrada / salida con 8 ranuras basadas en ISaGRAFm, pantalla de 7 segmentos de 5 segmentos, puerto RS 232, puerto RS 485, SRAM de 512Kb, flash de 512 KB, NVRAM, reloj en tiempo real, MiniOS7.</strong></center><br>


<p>La serie ISaGRAF i-8000 (I-8437-80 / 8837-80, I-8417/8817) es un ISaGRAF PAC e incluye ISaGRAF SoftLogic, ISaGRAF es una herramienta de programación de Windows y también proporciona un potente herramientas de depuración que incluyen Online Monitor and Control y también Offline Simulation. Hay más de 300 bloques de funciones integrados en el PAC para diversas aplicaciones industriales, incluyendo PID, movimiento, IO remoto, comunicación en serie, SMS, retención de variables, escalado, etc. En hardware, I-8xx7 tiene 3 o 4 puertos seriales, admite el protocolo esclavo Modbus RTU y se puede comunicar fácilmente con PC / HMI / Servidor OPC y panel táctil. El I-8xx7 también admite hasta 2 puertos COM del protocolo maestro Modbus RTU / ASCII para integrarse con otros dispositivos Modbus. El I-8x37-80 tiene un puerto Ethernet de 10M. El I-8xx7 es compatible con varios módulos de E / S de alto / bajo perfil. El usuario puede elegir módulos de E / S locales: módulos de E / S I-8K / I-87K y módulos de E / S remotas RS-485: I-7000 o unidades de expansión (I-87Kn o RU-87Pn) conectadas con I- 87K módulos de E / S en serie. Comparado con I-8437/8837 (se ha eliminado), I-8x37-80 es 2 ~ 4 veces más rápido.
</p><BR><br>


<strong>Caracteristicas:</strong>
<ul>
<li>80186, 40 MHz o 80186, CPU de 80 MHz</li>
<li>MiniOS7 en el interior</li>
<li>Software de desarrollo: ISaGRAF Ver.3</li>
<li>SRAM: 512 KB</li>
<li>Flash: 512 KB</li>
<li>4/8 ranuras para módulos de E / S de alto / bajo perfil I-87K</li>
<li>10 M puertos Ethernet (para I-8x37-80)</li>
<li>3/4 puertos en serie (RS-232/485)</li>
<li>temperatura de funcionamiento: -25 ~ +75 ° C</li>
</ul>

