<div align="justify">
<p>El HiTemp140-FP es un registrador de datos altas temperaturas de uso rudo con una sonda RTD larga y flexible con un diámetro estrecho, por lo que es ideal para su uso en los procesos de esterilización por vapor y liofilización.</p>

<p>De uso general para la cartografía, la validación y el seguimiento de las superficies de altas temperaturas y ambientes, este registrador de datos de acero inoxidable está disponible en dos modelos, el HiTemp140-FP-36 y el HiTemp140-FP-72, que cuentan con una sonda flexible de 36 y 72 pulgadas de longitud respectivamente. La sonda flexible está recubierta con aislamiento PFA y puede soportar temperaturas de hasta 260° C con una precisión de ± 0.1° C.</p>

<p>El diseño de la sonda HiTemp140-FP es estrecho y ligero por lo que es ideal para la colocación dentro de pequeños frascos, tubos, tubos de ensayo y otras aplicaciones de pequeño diámetro o delicados. Debido a que la sonda es flexible, los riesgos de ruptura (tanto de la sonda como el elemento sensor) generalmente asociados con los registradores de sonda rígida de acero inoxidable se ven disminuidos y es más fácil manipular la ubicación y colocación de la sonda. Los dispositivos almacenan hasta 32,700 lecturas con fecha y hora, está equipado con una memoria de estado sólido no volátil.</p>

<p>El HiTemp140-FP se puede configurar con un inicio retrasado y es capaz de leer los registros tan a menudo como cuatro lecturas por segundo, hasta una vez cada 24 horas.</p>

<p>Compatible con Data Logger Software, se puede iniciar, detener la descarga de datos obtenidos, así como también generar informes. El dispositivo se conecta a una PC con la interfaz IFC400 o la estación de acoplamiento IFC406 (se vende por separado). Los datos descargados se pueden graficar, resumir y exportarlos a Excel para su posterior análisis y cálculos.</p>
</div>
