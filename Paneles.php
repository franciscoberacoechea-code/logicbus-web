<p>Este medidor puede ser fácilmente integrado para trabajar con celdas de carga, sensores de torque y sensores de presión. Tiene un rango de entrada de hasta +/-500 mV / V. Acepta sensores de salida amplificada en el rango de ±12 VDC hasta 30 mA. También dispone de dos relevadores individuales y dos de voltaje y corriente analógicos. Este dispositivo provee una alimentación adicional de 24 VDC / 5VDC para sensores con amplificador integrado. El medidor también es compatible con TEDS lo que hace que sea más fácil cambiar entre varios sensores. E l dispositivo tiene integrado un convertido Analógico/Digital de alta velocidad, bajo ruido y de alta resolución (24 bits) siendo adecuado para mediciones de alta precisión. Este medidor de panel en particular también tiene la capacidad de mostrar los valores en una computadora a través de un enlace USB.</p>

