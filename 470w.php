<p align="justify">Diseñado con el chip A/D de aproximación sucesiva Maxim MAX197, el SeaI/O-470W proporciona una conexión de red inalámbrica a ocho entradas diferenciales o 16 de un solo extremo de 12 bits y dos canales de salida D/A de 12 bits. Las entradas A/D son seleccionables por software para rangos de 0-5V, 0-10V, +/-5V y +/-10V y cada canal se puede configurar mediante hardware para medir un bucle de corriente de 4-20 mA. Los dos canales D/A de 12 bits se pueden seleccionar mediante puentes para rangos de salida de 0-5V y 0-10V.
