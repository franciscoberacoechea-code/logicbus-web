  <p align="justify">Los sensores de presión con aprobación FDA O'Rings pueden ser usados en la producción de comida tales como la industria de la leche.</p><br><br>

  <center><strong>Procesos de automatización</strong></center><br>
<center><img src="imagenes/36/pmp300_app02.jpg" alt="PMP300" title="PMP300" width="35%" class="image_productos"></center><br><br>

<p align="justify">Los sensores de presión se pueden colocar debajo de un silo o tanque para monitorear que tan lleno o vacío se encuentra y de esta forma medir y monitorear la presión mientras conocemos el volumen y densidad del líquido. Utilizando controladores con pantallas digitales, PLCs, computadoras o sensores de adquisición de datos tu puedes medir y controlar el peso de la cantidad a dispensar y/o el flujo de liquido durante el proceso de automatización.</p><br>

<center><strong>Sistemas hidráulicos</strong></center><br>
<center><img src="imagenes/36/pmp300_app03.jpg" alt="PMP300" title="PMP300" width="35%" class="image_productos"></center><br><br>

<p align="justify">La mayoría de grúas, excavadoras y equipo similar son manejados usando sistemas hidráulicos. Para controlar el movimiento, el agarre y la fuerza aplicada, los sensores de presión son utilizados para supervisar y proporcionar la correcta presión a estos sistemas. La utilización de sensores de presión también permitirá al operador completo control de los dispositivos mecánicos y aplicará la suficiente fuerza o cargará sin esfuerzo. El sensor de presión también puede ser usado para supervisar el nivel del fluido hidráulico para el mantenimiento preventivo. Si y cuando el fluido presurizado comienza a alcanzar un nivel inseguro, el usuario será notificado.</p><br><br>

<center><strong>Supervisión de presión</strong></center><br>
<center><img src="imagenes/36/pmp300_app04.jpg" alt="PMP300" title="PMP300" width="35%" class="image_productos"></center><br><br>

<p align="justify">Los sensores de presión son usados para medir la presión de fluidos o gases. En este particular ejemplo el gas es comprimido en el compresor, cuando el gas es soltado tiene que ser enfriado ya que la compresión de gas por lo general aumenta su temperatura. El sensor de presión supervisa la presión real del aire antes de que sea transferido al secador.</p>
