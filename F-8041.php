<center><strong>Módulo de salida digital aislado de 32 canales (cubierta gris) (RoHS).</strong></center><br>

<p>El F-8041 es un módulo de salida digital con 32 canales NPN. El canal de salida de F-8041 es un canal de current sinking y puede conducir la carga hasta una corriente de 0.5A. Los canales de salida digital ofrecen LED para indicar el estado de salida digital. Además, el módulo ofrece aislamiento óptico de 3000 VDC entre canales y bus de fondo. Si cualquier alto voltaje o corriente daña los canales, el sistema (placas base, otros módulos y la unidad de control) no se verán afectados debido al beneficio del aislamiento.</p>

Caracteristicas:
<ul>
<li>32 canales de salida digital (sink). </li>
<li>Valor de seguridad (Preset / Hold).</li>
<li>Valor de encendido (inicial).</li>
<li>Indicación LED del canal de salida.</li>
<li>Conformidad con la RoHS.</li>
<li>Aislamiento de 3000 VDC desde la salida al plano posterior.</li>
<li>Aislamiento de 3000 VDC desde la salida al suelo del bastidor.</li>
<li>Redundancia.</li>
<li>Tiempo de conmutación redundante rápido (< 100us).</li>
</ul>
Aplicaciones:
<ul>
<li>Automatización de edificios.</li>
<li>Automatización industrial.</li>
<li>Automatización de máquinas.</li>
<li>Mantenimiento remoto.</li>
<li>Diagnóstico remoto.</li>
<li>Equipo de pruebas.</li>
</ul>
