	    <p><strong>Entrada Anal&oacute;gica:</strong> La serie 6069-410-010 proporciona a los dispositivos entradas an&aacute;logicas de 16-bits las cuales son seleccionables por software entre: 16 entradas anal&oacute;gicas de un solo extremo  u 8  diferenciales. Estos dispositivos soportan rangos de entrada seleccionables por software de: &plusmn;10V,&plusmn;5V, &plusmn;2V y de &plusmn;1V. </p>
	    <p><strong>Entrada de activaci&oacute;n:</strong> Incluye una entrada externa de disparo digital. El modo de disparo es seleccionable por software, modo borde sensible o modo sensible. Puede configurar el modo de borde sensible, ya sea de subida o de bajada. En modo sensible se puede configurar para el nivel alto o bajo. La configuraci&oacute;n por defecto al encender es en modo borde sensible al flanco de subida. </p>
	    <p><strong>Modo Retrigger:</strong> En el modo retrigger, puede configurar los eventos repetitivos de disparo de una entrada anal&oacute;gica. El disparador es autom&aacute;ticamente rearmado despu&eacute;s de que se active. Utilice el software para establecer el n&uacute;mero de disparo A/D(el n&uacute;mero de muestras que desee por disparo).   </p>
	    <p><strong>E/S Digitales:</strong> 8 E/S digitales bidireccionales. Cada canal digital se puede configurar individualmente para entrada o salida. Las terminales digitales de las E/S pueden detectar el estado de cualquier entrada de nivel TTL. Se puede configurar para pull-up (+5 V) o pull-down (0 V) a trav&eacute;s de un puente.</p>
	    <p><strong>Entrada del contador:</strong> Incluye dos contadores de eventos de 32 bits, para el conteo de pulsos TTL. Los contadores aceptan entradas de frecuencia de hasta 20MHz. </p>
	    <p><strong>Salida del temporizador:</strong> Los dispositivos de esta serie, contienen un temporizador de salida PWM que puede generar una salida de impulsos con una frecuencia programable en el rango de 0.0149 Hz a 32 MHz. Los par&aacute;metros de salida del temporizador son seleccionables por software.</p>
	    <p><strong>Reloj Externo de E/S:</strong> Los dispositivos de esta serie proporcionan una entrada de reloj externa y una salida de reloj externa para las entradas anal&oacute;gicas. </p>
