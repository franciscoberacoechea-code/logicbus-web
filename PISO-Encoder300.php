<center><strong>Tarjeta de entrada del codificador de 3 ejes PCI Bus. Incluye CA-SC68, conector macho SCSI-II de 68 pines (tipo de soldadura)</strong></center><br>


<p>PISO-ENCODER / 300/600 tiene un contador de codificador de 3 o 6 ejes. Cada eje tiene un contador verdadero de 32 bits con una tasa máxima de conteo de 1MHz. El restablecimiento del índice se reinicia al usar un canal C + / C-, que reiniciará cada revolución. El restablecimiento del hardware se restablece mediante un pin externo (HR1 ~ HR6). El HR1 ~ HR6 también puede ser una entrada digital. También se proporcionan salidas digitales de 8 canales. Los acopladores de foto de 2500 Vrms aíslan la E / S digital. Esta placa proporciona controladores DOS, Windows 95 y Windows NT.
</p><BR><br>

<strong>El modo de conteo tiene 3 tipos de selecciones:</strong>
<ol>
<li>Modo QUADRANT,</li>
<li>Modo CW_CCW</li>
<li>Modo PULSE_DIR.</li>
</ol>
<br>

<strong>Se proporcionan 3 tipos de modos de reinicio del contador:</strong>
<ol>
<li>Restablecer registro</li>
<li>Restablecer índice</li>
<li>Restablecimiento de hardware.</li>
</ol>
<br>

<strong>Caracteristicas:</strong>
<ul>
<li>Bus PCI</li>
<li>Contador de codificador de 3 ejes</li>
<li>True contador de 32 bits</li>
<li>Velocidad máxima de conteo: 1MHz.</li>
<li>Filtro digital interno de tercer orden.</li>
<li>Modo de conteo: Cuadrante, CW_CCW, PULSE_DIR</li>
<li>A +, A-, B +, B-, C +, C- entradas.</li>
<li>Función de contador de restablecimiento programable.</li>
<li>Función de contador de reinicio del índice (canal C).</li>
<li>Restablecimiento de hardware (HR1 ~ HR6), restablecer función de contador</li>
<li>Conector SCSI-II de 68 pines.</li>
</ul><br>

<strong>Software:</strong>
<ul>
<li>Toolkit para DOS</li>
<li>Toolkit para Windows 95/98</li>
<li>Toolkit para Windows NT</li>
<li>Toolkit para Windows 2000 / XP</li>
<li>Toolkit para LabVIEW 95/98</li>
<li>Toolkit para LabVIEW NT</li>
</ul>

