<p>El ET-7053, es un módulo que permite controlar entradas y salidas digitales mediante Ethernet, este módulo incluye un servidor web integrado, el cual permite configurar el dispositivo, monitorear y controlar las entradas y salidas desde un simple navegador web. El control y supervisión remotos son tan sencillos como navegar en Internet. <BR>

Con la función web HMI, no es necesario programar ni tener habilidades en HTML; la creación de páginas web dinámicas y atractivas para el control y monitoreo de entradas/salidas será divertido para los ingenieros. El ET-7053 ofrece a los usuarios un acceso fácil y seguro desde cualquier lugar y a cualquier hora. <BR>

Además, el ET-7053 soporta también el protocolo Modbus/TCP, lo cual hace una perfecta integración entre este dispositivo y software SCADA. <BR>

El ET-7053 esta diseñado para mediciones y monitoreo industrial, por lo que es lo bastante robusto para soportar ambientes rudos.<BR>

El ET-7053 provee 16 canales de entrada digital aislados de contacto seco (tipo source) cada entrada digital soporta entrada de contador (32 bits and 500Hz max.).  <BR>

