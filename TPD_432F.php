<p align="justify">TPD-432F TouchPAD es una HMI touchscreen la cual está diseñada para automatización de edificios y hogares. TPD-432F está equipado con una pantalla táctil de alta resolución TFT a color y encaja en enchufes eléctricos regulares de montaje en pared. Además, es perfectamente integrado con módulos de E/S y presenta una imagen flexible y definida por el usuario. En breve, es la mejor elección para actualizar el interruptor mecánico a botones de control inteligente.
<br><br>
Viene con un diseñador escalera para usuarios de PLC y un entorno de desarrollo en lenguaje C para programadores. Rápida y fácilmente puedes desarrollar tus programas con las herramientas incluidas.</p>

