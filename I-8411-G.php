<center><strong>Montaje en rack, controlador integrado: 256/512K flash, 256/512K SRAM, CPU de 40MHz, sistema operativo MiniOS7. Disponible en 4 y 8 ranuras de capacidad (4 x ranura: 512k/512k).</strong></center><br>


<p>El I-8411 / I-8811 es un controlador embebido en serie con 4/8 ranuras de E / S. Ambos están equipados con MiniOS7, un sistema operativo integrado similar al DOS desarrollado por ICPDAS Co., LTD.<br>

El MiniOS7 puede arrancar en muy poco tiempo (0.4 ~ 0.8 segundos). Tiene una función de diagnóstico de hardware incorporada, y admite todas las funciones para acceder a todos los módulos de E / S de las series 8K y 87K, como DI, DO, DIO , AI, AO, contador / frecuencia, módulos de movimiento, etc. <br>

El plano posterior I-8411 / I-8811 está equipado con cuatro puertos COM serie, incluyen puertos RS-232 y RS-485 y se pueden usar en aplicaciones remotas de adquisición y control de datos, incluida la supervisión del entorno, la administración de energía y la automatización de fábrica. Al utilizar SRAM de respaldo de batería S-256 (256 KBytes) o S-512 (512 KBytes), proporcionan la función de almacenamiento del registrador de datos.
</p><BR><br>


<strong>Caracteristicas:</strong>
<ul>
<li>Plano posterior paralelo de alta velocidad localizado.</li>
<li>Equipado con MiniOS7 (ROM-DOS como sistema operativo).</li>
<li>Admite IPv4.</li>
<li>Proporciona funciones completas de biblioteca C para: I-8000, I-87K I / O, pantalla LED de 7 segmentos, RTC (reloj de tiempo real), EEPROM y más.</li>
<li>El firmware se puede actualizar a través del puerto RS-232.</li>
<li>Admite capacidades "VxComm" para todos los puertos COM (RS-232 y RS-485).</li>
<li>Proporciona un número de serie de hardware o un ASICKey para proteger los sistemas designados.</li>
<li>Las ranuras de expansión de E / S compactas permiten la instalación rápida de módulos de E / S.</li>
<li>Circuito de vigilancia incorporado.</li>
<li>Dual Bus diseñado para admitir módulos de E / S de la serie I-8000 e I-87K.</li>
<li>Compatibilidad CAN avanzada con I-8421.</li>
</ul>

