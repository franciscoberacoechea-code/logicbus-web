<p>El crecimiento de robots colaborativos que pueden trabajar de forma segura codo a codo con las personas hace que la automatización sea accesible para una nueva generación de aplicaciones. Sin embargo, esta accesibilidad se ha producido a costa de un ciclo reducido tiempo, precios más altos y la pérdida de características. <br>
El PF3400 es el primer robot SCARA colaborativo de cuatro ejes del mundo. Su diseño intrínsecamente seguro permite que el PF3400 alcance velocidades y aceleraciones mucho más rápido que cualquier otro robot de colaboración, mientras que todavía limitando las fuerzas a los estándares de robots de colaboración ISO, haciendo del PF3400 el robot más rápido / más seguro del mundo. Este distintivo diseño SCARA puede realizar prueba de tiempo de ciclo de pick-and-place estándar de la industria en 1.4 segundos, solo un poco más lento que muchos robots industriales no colaborativos y comparable a los humanos operadores. Incluso a las velocidades más rápidas, el PF3400 limita las fuerzas de colisión en el espacio libre a menos de 100N y colisiones rígidas a menos de 150N.</p>

<center>
<img src="https://tienda.logicbus.com.mx/assets/images/254/PF3400_2.jpg" alt="ICPDAS:  WP-5441" title="ICPDAS: PROFI8155_frame" width="50%" class="image_productos contenedor"><br /></center>
<p>Los robots colaborativos potencialmente permiten la creación de una fabricación mixta ambiente donde las personas pueden ingresar y trabajar eficientemente alrededor de robots sin la pérdida de rendimiento. Sin embargo, la mayoría de los robots "colaborativos" deben moverse lentamente o use un modo de colaboración de velocidad reducida, perdiendo productividad cada vez que los usuarios están cerca. La combinación única de velocidad / seguridad del PF3400 lo permite para operar a toda velocidad y entregar rendimiento industrial en aplicaciones donde los operadores pueden moverse libremente alrededor del robot sin preocupaciones por su seguridad o impacto en la producción. Además de ofrecer un precio competitivo comparable a robots no colaborativos, el diseño mecánico único del PF3400 es optimizado para aplicaciones colaborativas de mesa. Este ligero robot puede ser transportado por una persona, montado en una mesa y, al enchufarlo a un cable de alimentación de CA y un cable de Ethernet, están listos para funcionar. El controlador, los suministros de energía y el uso del cable están integrados en la estructura del robot, eliminando los gabinetes externos del controlador y simplificando las instalaciones. Debido a su configuración novedosa, el PF3400 puede funcionar en celdas con impresiones de pie muy compactas mientras que proporciona el alcance vertical extraordinario de hasta 1.2M.</p>
<center>
<img src="https://tienda.logicbus.com.mx/assets/images/254/PF3400_4.jpg" alt="ICPDAS:  WP-5441" title="ICPDAS: PROFI8155_frame" width="50%" class="image_productos contenedor"><br /></center> <br>
<p>Para simplificar la configuración de nuevos usuarios, muchos robots colaborativos usan una programación ambiente con características limitadas. Los robots colaborativos de Precise Automation ofrecen flexibilidad tanto de una interfaz basada en web fácil de usar como de una avanzada opcional entorno de programación tan capaz como cualquier robot industrial. La guía fácil de usar La interfaz de movimiento es accesible desde cualquier dispositivo habilitado para la web y permite a los técnicos u operadores para configurar y enseñar rápida y fácilmente el PF3400 para realizar un trabajo real.</p>
