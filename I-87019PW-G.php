<center><strong>Módulo de entrada analógica universal de 8 canales (cubierta gris) (RoHS).</strong></center><br>

<p>El I-87019PW es un módulo de entrada analógica universal de 8 canales con una interfaz RS-485 especialmente diseñada para mediciones de termopar extremadamente precisas y cuenta con compensación automática de unión fría para cada canal para asegurar la consistencia de la salida de temperatura y la salida de temperatura estable en el campo. El diseño innovador del modelo mejorado asegura que la medición del termopar sea más precisa que con el diseño anterior. Además de las entradas de termopar, el I-87019PW también admite entradas de voltaje y corriente. El rango de entrada de tensión puede ser de +/- 15 mV a +/- 10 V, y el rango de entrada de corriente puede ser de 4 ~ 20 mA, 0 ~ 20 mA o +/- 20 mA. Se pueden conectar hasta 10 entradas analógicas de diferentes tipos a un solo módulo. Se proporciona protección contra sobretensiones de hasta 240 Vrms. El módulo también presenta detección de cable abierto por canal para termopar y entradas de 4 ~ 20 mA.</p>

Caracteristicas:
<ul>
<li>Entrada analógica de 8 canales.</li>
<li>Configuración individual del canal.</li>
<li>Detección abierta de termopar.</li>
<li>Consistencia de salida de temperatura.</li>
<li>Salida de temperatura estable en el campo.</li>
<li>Protección de sobretensión 240 Vrms.</li>
<li>Puente seleccionable de voltaje o entrada de corriente.</li>
<li>Protección contra ESD de 4 kV.</li>
<li>Dual Watchdog.</li>
<li>Aislamiento intramódulo de 3000 VDC, campo a campo.</li>
<li>Amplio rango de temperatura de funcionamiento: -25 ° C ~ +75 ° C.</li>
<li>RoHS.</li>
</ul>
Aplicaciones:
<ul>
