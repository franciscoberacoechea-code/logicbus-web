<center><strong>Módulo redundante de entrada digital aislado de 32 canales.</strong></center><br>

<p>El F-8040 dispone de 32 canales de entrada digital (sink/source). Se puede seleccionar la entrada de tipo sink o source a través de un cableado diferente. El F-8040 puede determinar la entrada binaria de una fuente de voltaje de CC. Los canales de entrada digital también ofrecen indicadores LED para mostrar localmente el estado de la entrada digital. Además, el módulo ofrece aislamiento óptico de 3000 VDC entre canales y bus de fondo. Si cualquier alto voltaje o corriente daña los canales, el sistema (placas base, otros módulos y la unidad de control) no se verán afectados debido al beneficio del aislamiento.</p>

Caracteristicas:
<ul>
<li>32 canales de entrada digital (sink/source).</li>
<li>Filtro digital (1 ~ 32767ms).</li>
<li>Indicación LED del canal de entrada.</li>
<li>Conformidad con la RoHS.</li>
<li>Aislamiento de 3000 VDC desde la entrada al backplane.</li>
<li>Aislamiento de 3000 VDC desde la entrada a la tierra del cuadro.</li>
<li>Redundancia.</li>
<li>Tiempo de conmutación redundante rápido (< 100us).</li>
</ul>
Aplicaciones:
<ul>
<li>Automatización de edificios.</li>
<li>Automatización industrial.</li>
<li>Automatización de máquinas.</li>
<li>Mantenimiento remoto.</li>
<li>Diagnóstico remoto.</li>
<li>Equipo de pruebas.</li>
</ul>
