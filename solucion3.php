<p>Combinado con GPS y 3G/4G, a través de la página web para ver la ubicación en tiempo real del vehículo y monitorear el estado de E/S y publicar mensajes anormales.</p>
<center><img src="imagenes/Soluciones/Solucion3/grafica1.jpg" width="40%"></center>
<p>La gestión de navegacion en tiempo real es una combinación de posicionamiento GPS y sistema de tecnología de mensajería instantánea GPRS. Al comenzar sesión en el inicio de sesión web con cuenta y contraseña, los administradores y despachadores de navegacion pueden conocer la ubicación en tiempo real de los vehículos, el estado de conducción en cualquier momento; también pueden consultar la ruta del historial de los vehículos y acceder para ver las declaraciones operativas de la navegacion, incluidas las estadísticas de kilometraje, informes anormales (por ejemplo, exceso de velocidad, inactividad, estado de activación de E/S), y así sucesivamente. El sistema de gestión de navegacion presenta la función SMS; puede enviar mensajes de texto a los gerentes y despachadores a la hora programada o cuando ocurre un evento inusual; para que puedan responder inmediatamente a las anomalías para evitar gastos innecesarios y mejorar la eficiencia operativa de la navegacion.</p>

<strong>Caracteristicas:</strong>
<ul>
<li>Diseño web adaptable que se puede usar a través de una computadora o navegador móvil.</li>
<li>Mantiene en monitoreo el estado en cualquier momento, el sistema registrará automáticamente el mensaje anormal y enviará un mensaje de texto.</li>
<li>Combina mapas para mostrar ubicaciones de vehículos en tiempo real y actualiza dinámicamente la información en tiempo real.</li>
<li>Función de informe completo, salida dinámica de los datos operativos de la flota.</li>
<li>La máquina del coche puede controlar la interfaz de E/S local y puede conectar dispositivos Modbus RTU externos.</li>
</ul>
