        <center><strong>Convertidor RS-232 a RS-422 / RS-485, alimentación +10 VDC ~ +30 VDC.</strong></center>

        <p style="text-align: justify;">La mayoría de los sistemas de computadoras industriales ofrecen puertos seriales estándar <a href="https://www.logicbus.com.mx/convertidores_info#RS-232">RS-232.</a> A pesar de que es ampliamente aceptado, RS-232 tiene un límite de velocidad de transmisión, rango y capacidad de red.  Los estándares de <a href="https://www.logicbus.com.mx/convertidores_info#RS-422">RS-422</a> y <a href="https://www.logicbus.com.mx/convertidores_info#RS-485">RS-485</a> sobrepasan estos límites por usar diferente líneas de voltaje para datos y control de señales, lo cual transparentemente convierten señales RS-232 en señales aisladas RS-422 y RS-485  sin la necesidad de cambiar hardware o software. I-7520 permite fácilmente añadir un grado industrial en los sistemas de comunicación a larga distancia usando el hardware estándar de la PC.</p>

        <p><strong>Características:</strong></p>
        <ul>
          <li>Auto switching de velocidad de transmisión, 300 ~ 115200 bps.</li>
          <li>Protección de aislamiento de 3000 VDC en el lado RS485.</li>
          <li>Velocidad de transmisión de hasta 115200 bps.</li>
          <li>Protección ESD para RS232/422/485.</li>
          <li>Entrada de poder de +10 ~ +30 VDC.</li>
          <li>Soporta temperaturas de operación desde -25°C ~ +75°C.</li>
          <li>Riel DIN.</li>
        </ul>



