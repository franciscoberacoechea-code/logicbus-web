<p align="justify">I-8093W es un módulo de codificador de alta velocidad de 3 ejes. Cada uno de sus ejes se puede configurar de forma independiente como uno de los modos de entrada Quadrant, Pulso / Dirección o CW / CCW. La velocidad máxima de entrada para el modo Cuadrante es de 1 MHz, y para los modos Pulso / Dirección y CW / CCW es de 4 MHz.
<br><br>
Las especificaciones de gama alta de I-8093W y el soporte completo de software lo hacen ideal para aplicaciones de amplio rango en la medición de posición de sistemas de movimiento para entornos industriales y de laboratorio.</p>

Caracterísiticas:
<ul>
<li>Entradas de codificador de 3 ejes.</li>
<li>Velocidad de entrada de 1 MHz para el modo de entrada de cuadrante.</li>
<li>Velocidad de entrada de 4 MHz para modos de entrada de pulso / dirección y cw / ccw.</li>
<li>Rango de conteo de 32 bits.</li>
<li>Aislamiento óptico de 2500 Vrms.</li>
</ul>
