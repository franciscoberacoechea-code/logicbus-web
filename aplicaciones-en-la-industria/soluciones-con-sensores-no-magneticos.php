                    <li class="mb-3"><b>Operación Segura</b> La protección magnética impide que el sensor sea atraído hacia el campo, protegiendo tanto el sensor como el equipo.</li>
                    <li class="mb-3"><b>Versatilidad de Instrumentación</b> Las opciones de salida permiten su integración con una variedad de equipos de monitoreo y control.</li>
