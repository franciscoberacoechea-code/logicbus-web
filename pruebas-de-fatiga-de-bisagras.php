  <p align="justify"><b>Resumen de la aplicaci&oacute;n:</b>
    Las bisagras de torque, de posición o de fricción, son todas sinónimo de un tipo de bisagra que permite a dos partes rotar una con respecto a la otra cuando se aplica carga. La bisagra después, regresa a su posición original cuando la carga se remueve debido a un cierta rigidez torsional. Por esta propiedad, se utilizan en todo, desde gabinetes hasta guanteras de automóviles y computadoras laptop. Este amplio rango de aplicaciones tiene como requerimiento que estas bisagras tengan un tiempo de vida más amplio que el del producto. Para asegurar esto, se deben realizar pruebas de fatiga y ciclos de prueba.
  </p>

