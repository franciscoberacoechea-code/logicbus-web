<p>Los PAC's de la serie I-7188XBD-CAN (Controlador de automatización programable) funcionan con un procesador 80188-40 con 512 KB de RAM estática y 512 KB de memoria Flash. Todos ellos proporcionan varias interfaces de comunicación para adaptarse a diversas aplicaciones, como el puerto CAN, el puerto RS-232 y el puerto RS-485. Los usos pueden programar su programa de aplicación de manera flexible con lenguaje C / C ++ debido al sistema de operación MiniOS7 incorporado. Además, los PAC's de la serie I-7188XBD-CAN tienen diferentes tipos de E / S para que los usuarios coincidan con sus requisitos.

</p>

<strong>Caracteristicas:</strong>
<ul>
<li>Diseño RoHS</li>
<li>Completamente compatible con USB 1.1 / 2.0 (velocidad máxima)</li>
<li>Totalmente compatible con el estándar ISO 11898-2</li>
<li>Admite tanto CAN 2.0A como CAN 2.0B</li>
<li>Desarrollado por bus USB</li>
<li>Velocidad de transmisión del bus CAN programable de 5Kbps a 1 Mbps o tasa de baudios definida por el usuario</li>
<li>Apoya la configuración del filtro de aceptación del bus CAN</li>
<li>Marca de tiempo del mensaje CAN con una precisión de ± 1 ms</li>
<li>Soporte de actualización de firmware a través de USB</li>
<li>Proporcionar biblioteca de API para el desarrollo de programas de usuario</li>
<li>Puente incorporado para seleccionar resistencia terminal de 120 ohmios</li>
<li>Indicador PWR / RUN / ERR para CAN y USB</li>
<li>Watchdog inside</li>
<li>Admite Windows 2000 / XP y WinCE (pronto)</li>
</ul>

