<center><strong>Tarjeta PCI universal multifunción de 32 canales de 12 bits de resolución, 110 kS/s de Ganancia baja.</strong></center><br>


<p>La tarjeta PCI universal PCI-1002LU / HU admite bus PCI de 3,3 V / 5 V y es el producto de nueva generación que ICP DAS proporciona para cumplir con RoHS. Las nuevas PCI-1002LU / HU (PCI universal) son totalmente compatibles con la PCI-1002L / H (PCI) y los usuarios pueden reemplazar la PCI-1002L / H directamente por la PCI-1002LU / HU sin modificación de software / controlador.<br><br>

La serie PCI-1002 es una familia de tarjetas A / D y presenta entradas analógicas de baja ganancia de 110 kS / s o de 44 kS / s de alta ganancia. Proporciona 32 entradas analógicas unipolares o 16 diferenciales de 12 bits, 16 entradas digitales y 16 canales de salida digital.<br><br>

La serie PCI-1002 admite varios sistemas operativos, como Linux, DOS, Windows 98 / NT / 2000 y Windows XP / 2003 / Vista / 7 de 32 bits. También proporciona el control DLL y Active X, y varios programas de muestra de lenguaje en Turbo C ++, Borland C ++, Microsoft C ++, Visual C ++, Borland Delphi, Borland C ++ Builder, Visual Basic, C # .NET, Visual Basic.NET y LabVIEW para ayudar usuarios para desarrollar rápida y fácilmente sus aplicaciones.
</p><BR><br>

<strong>Caracteristicas</strong>

<ul>
<li>Tarjeta PCI universal, admite bus PCI de 5 V y 3,3 V.</li>
<li>Conversor AD de alta velocidad de 12 bits, 100 kS / s.</li>
<li>32 entradas diferenciales single-ended / 16</li>
<li>El máximo. la velocidad de muestreo es de baja ganancia de 110 kS / s o de alta ganancia de 44 kS / s.</li>
<li>16 canales de entrada digital / 16 canales de salida digital</li>
<li>PCI-1002LU: baja ganancia programable: 1, 2, 4, 8,</li>
<li>PCI-1002HU: alta ganancia programable: 1, 10, 100, 1000.</li>
<li>Disparador interno / externo.</li>
<li>Tablero de tamaño medio</li>
<li>El puerto de entrada digital se puede establecer en pull-high o pull-low (PCI-1002 LU / HU solamente)./li></li>
</ul><br>

<strong>Aplicaciones</strong>
<ul>
<li>Automatización de laboratorio</li>
<li>Prueba de producción</li>
<li>Interfaz del sensor</li>
</ul><br>

<strong>Software</strong>
<ul>
<li>Programa de ejemplo DOS Lib y TC / BC / MSC (con códigos fuente)</li>
<li>DLL y OCX SDK para Windows 95/98 / NT / 2K.</li>
<li>DLL y OCX SDK para Windows XP / 2003 / Vista / 7 de 32 bits y 64 bits.</li>
<li>Se incluyen los programas de ejemplo VB / VC / Delphi / BCB / VB.NET / C # .NET con códigos fuente.</li>
<li>Kit de herramientas de LabVIEW para Windows.</li>
<li>Driver para Linux.</li>
</ul>
