<p>La próxima generación de robots colaborativos -ROBOTS de sies ejes.
El crecimiento de robots colaborativos que pueden trabajar de forma segura al lado de las personas hace que la automatización sea accesible para una nueva generación de aplicaciones. Sin embargo, esta accesibilidad a menudo tiene el costo de precios más altos para sensores especiales, una menor repetibilidad y un tiempo de ciclo drásticamente reducido. La línea de robots articulados de seis ejes industriales de Precise Automation proporciona las características, el precio y la repetibilidad que ofrecen los robots tradicionales con la facilidad de uso de los robots de colaboración populares.</p>

<center>
<img src="https://www.logicbus.com.mx/imagenes/254/PAVP6_2.JPG" alt="Robots Colaborativos Precise AutomationVS06-MP-PAVS6-8" title="Robots Colaborativos Precise Automation" width="30%"><br /></center>

<p>Los robots colaborativos permiten la creación de un entorno de fabricación mixto donde las personas pueden ingresar y trabajar de manera eficiente alrededor de los robots sin la pérdida de rendimiento. Sin embargo, cuando los usuarios están cerca, la mayoría de los robots "colaborativos" deben moverse lentamente o usar un modo colaborativo de velocidad reducida, perdiendo así la productividad. Los robots de seis ejes de Precise están diseñados para que puedan programarse fácilmente para moverse a velocidades más altas en el espacio libre y para limitar las velocidades cuando son posibles las colisiones contra una superficie rígida. Esto permite que el robot se mueva a velocidades similares a las personas, incluso cuando los usuarios están presentes en la celda de trabajo, al mismo tiempo que limitan las fuerzas al estándar de robot colaborativo ISO.</p>
<center>
<img src="https://www.logicbus.com.mx/imagenes/254/PAVP6_3.JPG" alt="Robots Colaborativos Precise AutomationVS06-MP-PAVS6-8" title="Robots Colaborativos Precise Automation" width="30%"><br /></center>

<p>Por lo tanto, los operadores pueden moverse libremente alrededor del robot sin preocuparse por su seguridad o reduciendo la productividad.
El diseño robusto de estos robots proporciona repetibilidad y confiabilidad a nivel industrial y les permite cambiarlos y redistribuirlos fácilmente para operar en un modo tradicional no colaborativo para tiempos de ciclo aún más rápidos cuando no hay potencial para que un operador esté presente.</p>
<br>
<center>
<img src="https://www.logicbus.com.mx/imagenes/254/PAVS6_3.JPG" alt="Robots Colaborativos Precise AutomationVS06-MP-PAVS6-8" title="Robots Colaborativos Precise Automation" width="30%"><br /></center>
	<br><br>
<p>Para simplificar la configuración para nuevos usuarios, muchos robots colaborativos utilizan un entorno de programación con funciones limitadas. Los robots de colaboración de Precise Automation ofrecen la flexibilidad tanto de una interfaz basada en web fácil de usar como de un entorno de programación avanzado opcional tan capaz como cualquier robot industrial. La interfaz de Guidance Motion, fácil de usar, es accesible desde cualquier dispositivo habilitado para la web y permite a los técnicos o
operadores para configurar y enseñar rápida y fácilmente al robot a realizar un trabajo real. Además, el potente control de movimiento permite las funciones de colaboración sin el uso de sensores costosos que proporcionan un rendimiento a nivel industrial a un costo menor que otros
Robots colaborativos de seis ejes.</p>


