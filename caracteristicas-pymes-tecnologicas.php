      <p>Características principales de una PyME</p>
      <ul>
        <li>El capital es proporcionado por una o dos personas que establecen una “sociedad”.</li>
        <li>Los propios dueños dirigen la marcha de la empresa; su administración es empírica.</li>
        <li>Su número de trabajadores empleados en el negocio crece y va de 16 hasta 250 personas.</li>
        <li>Utilizan más maquinaria y equipo, aunque se sigan basando más en el trabajo que en el capital.</li>
        <li>Dominan y abastecen un mercado más amplio, aunque no necesariamente tiene que ser local o regional, ya que muchas veces llegan a producir para el mercado nacional e incluso para el mercado internacional.</li>
        <li>Están en proceso de crecimiento, la pequeña tiende a ser mediana y aspira a ser grande.</li>
        <li>Obtienen algunas ventajas fiscales por parte del Estado que algunas veces las considera causantes menores dependiendo de sus ventas y utilidades.</li>
