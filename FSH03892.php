<p>La celda de carga de botón de carga LLB400 de FUTEK con disposiciones de montaje de botón está diseñada para aplicaciones de compresión en línea o prensa. El LLB400 estándar tiene una construcción muy robusta disponible en acero inoxidable de 17-4 PH, con un diámetro exterior de 1.23 y un cable de Teflón blindado trenzado de 4 conductores [3 m] de 10 pies [3 m] # 26 AWG. También encontrará opciones disponibles para salidas externas coincidentes.
<br>
Aunque tradicionalmente las celdas de carga de los botones de carga no son conocidas por su alta precisión, los ingenieros de FUTEK han disipado este concepto al mejorar continuamente la precisión de este producto. La celda de carga del botón de carga LLB400 ofrece una alta precisión. Tiene una no linealidad de ± 0.5% y una deflexión de 0.001 en nominal. El LLB400 estándar se puede modificar o personalizar para cumplir con sus requisitos y la mayoría de las capacidades se encuentran en nuestro inventario, por lo que están disponibles para el envío en 24 horas. Similar a nuestra línea completa de productos de Celdas de Carga, este modelo se fabrica en los EE. UU. Y utiliza tecnología de galga extensiométrica de lámina metálica.
