<li>48 canales de E / S digital</li>
<li>Puertos de E / S programables bidireccionales bajo control de software</li>
<li>Todas las líneas de E / S almacenadas en el tablero</li>
<li>Seis puertos de E / S bidireccionales de 8 bits</li>
<li>SMD, tarjeta corta</li>
<li>Se conecta directamente a DB-24PR, DB-24PD, DB-24RD, DB-24PRD, DB-16P8R, DB-24POR, DB-24SSR, DB-24C o cualquier tarjeta compatible con OPTO-22.</li>
<li>Un temporizador interno programable de 32 bits</li>
<li>Un conector DB37, un encabezado de caja de 50 pines</li>
<li>Un contador de eventos de 16 bits</li>
<li>Fuente de interrupción: 4 canales</li>
<li>Función de identificación de tarjeta para PIO-D48U</li>
<li>Resistencias pull-up o pull-down en líneas de E / S</li>
<li>Emular dos puertos industriales PPI 8255 (modo 0)</li>
