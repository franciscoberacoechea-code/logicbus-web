<p>Gateway esclavo CANopen a maestro Modbus RTU. En la red CANopen el I-7232D puede ser esclavo NMT, servidor SDO, productor PDO y consumidor PDO. Soporta hasta 10 modulos Modbus RTU para expansión de E/S. Montaje en Riel DIN. Requiere alimentación 10~30 Vdc<br>

El I-7232D CANopen para Modbus RTU Gateway es un producto ICP DAS CAN bus. El dispositivo permite que un maestro CANopen acceda a los dispositivos esclavos Modbus en cualquier red Modbus RTU. El protocolo Modbus RTU es un tipo de protocolo de aplicación basado en la red RS485. Esta puerta de enlace proporciona una manera fácil de conectar dispositivos Modbus RTU con la red CANopen. Estos dispositivos Modbus RTU pueden ser un PLC, un sensor Modbus RTU o módulos de la serie ICPDAS M-7000. También proporcionamos el software de utilidad para que los usuarios configuren los parámetros I-7232D y compilar el archivo EDS para la interfaz maestra CANopen. Los usuarios pueden aplicar fácilmente dispositivos Modbus RTU en aplicaciones CANopen con el I-7232D.</p>


