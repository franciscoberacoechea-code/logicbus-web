	  <div align="justify">  <p>
    
El pasado 12 de Octubre del 2011, se anuncio el lanzamiento de la nueva actualizaci&oacute;n para el <a href="https://www.logicbus.com.mx/pdf/36/csg110.pdf" target="_blank">CSG110</a> (Amplificador para celdas de carga).
    
Hace 10 a&ntilde;os, FUTEK vio la necesidad de un amplificador externo compatible con sus sensores. Despu&eacute;s de un largo tiempo de investigaci&oacute;n y desarrollo, se dio a conocer la primer edici&oacute;n del modelo <a href="https://www.logicbus.com.mx/pdf/36/csg110.pdf" target="_blank">CSG110</a>. Pero como la mayor&iacute;a de los productos industriales, la tecnolog&iacute;a evoluciona con el paso del tiempo creando nuevos componentes electr&oacute;nicos, es por esto que FUTEK decidi&oacute; realizar una revisi&oacute;n para hacer un producto con mejores caracter&iacute;sticas y desempe&ntilde;o.<br>
    <br>
    
En la actualizaci&oacute;n se hizo una revisi&oacute;n de 95% del producto logrando 5 mejoras utilizando las mas nuevas tecnolog&iacute;as en componentes electr&oacute;nicos:<br>
    <br>
    
    <span class="Estilo24">1)	Aprobaci&oacute;n CE</span> <bR>
    Con los criterios mas estrictos haci&eacute;ndolo compatible con todas las aplicaciones M&eacute;dicas, Industriales y de Consumo.<br>
    <br>
    
    <span class="Estilo24">2)	Reducci&oacute;n de ruido, mejorando el ancho de banda</span><br>
    Se logro una reducci&oacute;n de ruido de hasta 90% (10 veces menos ruido que el anterior <a href="https://www.logicbus.com.mx/pdf/36/csg110.pdf" target="_blank">CSG110</a>).<br>
    <span class="Estilo24"><br>
    3)	Protecci&oacute;n contra sobre voltajes</span><br>
    Se instalo una protecci&oacute;n especial para prevenir da&ntilde;os por corto circuito.<br>
    <br>
    
    <span class="Estilo24">4)	Cumplimiento RoHS</span><br>
    Se instalaron interruptores tipo DIP en vez de componentes internos, haciendo que el amplificador sea libre de materiales contaminantes.<br>
    <br>
    
    <span class="Estilo24">5)	25KHz de ancho de banda</span><br>
    Con la mejora de reducci&oacute;n de ruido, se logro la opci&oacute;n de elegir un amplificador con soporte de 25KHz de ancho de banda.</p>
