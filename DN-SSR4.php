<p>La DN-SSR4 incluye 4 relevadores normalmente abiertos de estado sólido, forma A. El usuario puede usar la DN-SSR4 para conmutar alto voltaje de hasta 240 VAC y hasta 4A. Cuatro indicadores LED (uno para cada relevador) prenden cuando su relevador asociado es activado. Cada salida está equipada con un varistor que deriva la sobrecarga de voltaje de la carga inductiva o del freno electromagnético par proteger el punto de contacto de relevador. Todas las salidas de relevador son accesibles a través de las terminales cableadas.</p>


