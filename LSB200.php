<p align="justify"> 
Las celdas de carga miniatura tipo S-Beam se han convertido en uno de los productos más destacados de nuestra serie de celdas de carga. Este modelo es ampliamente utilizado en aplicaciones para el pesaje de bolsas médicas así también para el control automático de retroalimentación y aplicaciones de procesos en línea. La perfecta combinación del tamaño, exactitud y por supuesto la seguridad de la protección contra sobrecarga hacen de este uno de nuestros modelos más solicitados. Con una altura de tan solo 0.75" el LSB200 es la mejor selección para lugares muy estrechos. El modelo estándar de esta celda de carga tiene rosca hembra y está construida en aluminio o en acero inoxidable y tiene un cable de 5 pies calibre 29 AWG de 4 hilos con protección de silicona. También está disponible con rosca métrica.<br><br>
