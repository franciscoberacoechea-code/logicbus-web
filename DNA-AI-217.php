          An A/D per channel configuration allows channels to be sampled simultaneously at rates up to 120 kS/s each (480 kS/s max aggregate entire board). The A/D per channel configuration virtually eliminates input cross talk and channel settling time issues even when connected to high impedance signal sources.<br>
          The DNx-AI-217 is fully isolated from the Cube/RACKtangle and is overvoltage protected up to &plusmn;40 V (power on or off). The inputs go into a high impedance mode when power is removed making the AI-217 ideal for use in redundant measurement/control applications.&nbsp;<br>
