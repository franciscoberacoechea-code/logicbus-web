<center><strong>Tarjeta de salida analógica de 14 bits y 16 canales detectada automáticamente por Windows. Incluye conector D-Sub CA-4002</strong></center><br>


<p>El PIO-DA16, PIO-DA8 y PIO-DA4 son placas D / A multicanal para el bus PCI para PC. El PIO-DA16 / 8/4 ofrece 16/8/4 canales de salida analógica de doble buffer. El rango de salida puede configurarse en diferentes rangos: ± 10V, ± 5V, 0 ~ 10V y salida de voltaje de 0 ~ 5V o 4 ~ 20mA, 0 ~ 20mA sumidero de lazo de corriente. El diseño innovador mejora varios inconvenientes de los tableros D / A convencionales.
</p><BR><br>

<strong>Caracteristicas</strong>

<ul>
<li>Soporta el bus PCI de +5 V para PIO-DA4/DA8/DA16</li>
<li>16 canales, salida analógica de 14 bits</li>
<li>Rango de voltaje de salida: ±10 V</li>
<li>Rango de corriente de salida: 0 ~ 20 mA (sink)</li>
<li>2 fuentes de interrupción de timer</li>
<li>Latch D/A de doble búffer</li>
<li>Calibración por software</li>
<li>Entrada Digital con 16 canales, Salida Digital con 16 canales</li>
<li>Un conector D-Sub, Dos conectores de cable plano con 20 pines</li>
<li>Se conecta directamente a DB-16P, DB-16R, DB-24C, DB-24PR y DB-24POR </li>

[Sólo para PISO-DA16U/DA8U/DA4U]
<li>Soporta los dos bus PCI +5 V y +3.3 V</li>
<li>Proteccion de aislamiento de voltaje de 2500 V DC</li>
<li>El puerto de entrada digital se puede poner en pull-high o pull-low</li>
<li>función de Card ID, </li>

[Sólo para PIO-DA16U/DA8U/DA4U]
