<br/>
Máxima protección para tu tranquilidad. Un patrón de exploración exclusivo de 32 pares de haces individuales y 154 haces de exploración cruzada proporciona una red de luz infrarroja para detectar obstrucciones. La protección de la puerta funciona 25 mm hasta 1800 mm por encima del umbral de la puerta y cumple con las normas EN 81-70. La sincronización óptica simplifica la conexión entre el borde y la fuente de alimentación.
<br>
<br>
Los cables de la fuente de luz y del receptor son intercambiables. Los cables de 5 metros están construidos con material de alta flexibilidad y están equipados con conectores resistentes al agua M8 de resistencia industrial. El reemplazo del cable es fácil. No hay necesidad de quitar el borde o abrir la fuente de alimentación.
<br>
<br>
Nuestra eficiente fuente de alimentación de voltaje universal se adapta a voltajes de alimentación CA o CC de 20 a 265 voltios y es perfecta para cualquier modernización. La caja de suministro es resistente, compacta y se monta en espacios reducidos o en la parte superior de la cabina. Cuenta con una tapa impermeable transparente para inspeccionar los indicadores de estado, los ajustes de los interruptores y el cableado. Un zumbador de la obstrucción viene estándar con la fuente o usted puede pedir una fuente llena ofrecida con el circuito que empuja.
<br>
<br>
Si prefiere la alimentación directa desde el controlador de puerta, la fuente de luz de bajo consumo y las matrices del receptor funcionan de 11 a 40 Vdc. La salida es push-pull, cortocircuito y protección contra sobretensiones. La polaridad de salida es conmutable para satisfacer las necesidades de entrada del controlador de puerta.
<br>
<br>
