<center><strong>Ethernet Industrial 10/100 BaseT no administrado de 4 puertos con interruptor de fibra óptica Dual BaseFX de 100 en caja de metal con conector ST.</strong></center><br>

<p>El NS-206F / NSM-206F es un Ethernet no administrado de 4 puertos con conmutador de puerto de fibra dual. Con la fibra óptica, puede evitar que el ruido interfiera con su sistema y admite transmisiones de alta velocidad (100 Mbps) y de alta distancia (hasta 15 km).<br>

El NS-206F / NSM-206F proporciona un amplio rango de potencia de 10 a 30 VDC para adaptarse a todos los estándares de potencia comunes que se encuentran en la automatización industrial, sin convertidores de potencia externos. La amplia entrada de potencia reduce los costos de instalación y mantenimiento.</p><BR>

<strong>Caracteristicas</strong>

<ul>
<li>Proporciona un puerto de fibra 2 x 100-FX más 4 puertos Ethernet.</li>
<li>Cada puerto admite una negociación automática de velocidad de 10/100 Mbps.</li>
<li>Control de flujo de contrapresión Full Duplex IEEE 802.3xy semidúplex.</li>
<li>Crossover automático MDI / MDI-X para plug-and-play.</li>
<li>Arquitectura de almacenamiento y reenvío.</li>
<li>Admite temperaturas de funcionamiento de 0 ~ +70 ° C.</li>
</ul>
