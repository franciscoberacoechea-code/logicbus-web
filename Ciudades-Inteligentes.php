<div align="center"><h2>E. Edificios Inteligentes</h2></div><br>
<p align="justify">Inmótica, que en si son edificios inteligentes, El término edificio inteligente se puede entender como la interacción del consumidor o usuario, entonces un edificio inteligente presenta una característica que se interprete como inteligente ya sea anticipar las necesidades del usuario o el manejo eficiente de información.<br>
Por lo anterior, esta rama se enfoca a dotar de técnicas de inteligencia artificial a los edificios corporativos, hoteles, edificios de gobierno, en general a lugares de concurrencia masiva, con la finalidad de contar con una calidad de trabajo.<br>
A diferencia de la Domotica, que esta busca el confort y calidad de vida de una persona, la Inmótica busca la calidad y confort de trabajo de varias personas, es un poco más complejo y ambicioso.</p>

