<li>Una expansión de puerto CAN para I-8000, iP-8000, ViewPAC-2000, WinPAC-8000, LinPAC-8000 y XPAC-8000-CE6</li>
<li>4096 registros CAN mensaje recibir tamaño de búfer</li>
<li>4096 registra el tamaño del búfer para el comando de I-8000 / iP-8000 / ViewPAC-2000 / WinPAC-8000 / LinPAC-8000 / XPAC-8000-CE6 a I-87120</li>
<li>Proporcione bibliotecas de funciones C / C ++ para enviar y recibir mensajes CAN</li>
<li>Se proporcionan demostraciones y utilidad</li>
<li>3 LED de indicación (LED Rx, Tx y Err)</li>
</ul>

