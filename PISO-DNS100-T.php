<p>El PISO-DNS100 ha completado la función esclava de DeviceNet de acuerdo con el servidor DeviceNet Group 2. Con la CPU incorporada 80186 80M Hz, esta tarjeta se puede aplicar en aplicaciones de transmisión alta. La sorprendente función es que 10 nodos esclavos se implementan dentro del PISO-DNS100. Admite hasta 512 bytes de datos de entrada y 512 bytes de salida. La velocidad de Baud de DeviceNet de 125-500 kbits / sy MACID se puede establecer a través de la configuración de la utilidad. La tarjeta PCI también tiene una interfaz DeviceNet aislada ópticamente.</p><BR>


<strong>Caracteristicas:</strong>
<ul>
<li>Versión DeviceNet: Volumen I y II, Versión 2.0</li>
<li>ID de esclavo programable y velocidad en baudios.</li>
<li>Velocidad en baudios: 125K, 250K, 500K</li>
<li>Soporte solo para el servidor 2</li>
<li>Modos de funcionamiento de E / S: Encuesta, Bit-Strobe, Cambio de</li>
<li>Estado / cíclico</li>
<li>Longitud de E / S: 512 Bytes máx. (Entrada / Salida) por esclavo</li>
<li>Nodo esclavo: 10 nodos (máx.) Dentro del tablero</li>
<li>No es compatible con UCMM.</li>
<li>LED: estado, ERR</li>
</ul>
