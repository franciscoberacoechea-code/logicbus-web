<p align="justify">El I-8212W es un módulo industrial cuatribanda GSM/GPRS con función de GPS (solo I-8213W) que funciona en frecuencias de GSM 850 MHz, EGSM 900 MHz, DCS 1800 MHz y PCS 1900 MHz. Estos módulos utilizan la red GSM/GPRS para la transferencia de datos conveniente y económica desde instrumentos remotos, medidores, computadoras o sistemas de control en datos en vivo o paquetes de datos. I-8212W tiene la pila TCP/IP integrada para que incluso los controladores simples con puertos de comunicaciones seriales puedan conectarse al módem sin la necesidad de una implementación especial del controlador. Con las características de I-8212W, los sistemas pueden ser aplicaciones de conexión SMS y GPRS con nuestras series PAC como iP-8000, WinPAC, LinPAC o XPAC.</p>

<strong>Características:</strong>
<ul>
<li>Módem cuatribanda GSM/GPRS que funciona en 850/900/1800/1900 MHz.</li>
<li>Protección contra ESD de 4 KV.</li>
<li>Diseñado para aplicaciones GPRS y SMS.</li>
<li>Soporte de servidor TCP, cliente TCP, conexión de cliente UDP de GPRS.</li>
<li>Soporta comandos estándar AT.</li>
<li>Indicadores LED para indicación de encendido, GSM y GPS (solo I-8213W).</li>
<li>Alta confiabilidad en entornos hostiles.</li>
<li>Soporte de 32 canales GPS y NMEA v0183 v3.01 (solo I-8213W).</li>
<li>PPS: salida de impulsos de 100 ms/s para la medición precisa del tiempo y del tiempo (solo I-8213W).</li>
<li>Soporte XP-8000, WinPAC-8000, LinPAC-8000, ViewPAC, iPAC-8000.</li>
</ul>

