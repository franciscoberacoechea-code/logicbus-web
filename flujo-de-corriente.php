    <p>El movimiento disperso de los "electrones libres" de un átomo hacia otro es normalmente igual en las diversas direcciones, de manera que ninguna parte del material en particular gana ni pierde electrones. Cuando los electrones hacen la mayor parte de los movimientos se producen en la misma direccion, de manera que parte del material pierde algunos electrones mientras que por otra parte empiece a ganar electrones, el movimiento neto o flujo se denomina <b>"Flujo de corriente"</b></p>
