                <p class="light-black">La caracterización de motores de cohetes sólidos, líquidos e híbridos se realiza a menudo con modelado por computadora y pruebas en tierra. Para combustibles experimentales, aerospike y otras boquillas experimentales de compensación de altitud, las pruebas en tierra son necesarias para caracterizar sus curvas de empuje y su I sp en condiciones de prueba estáticas. Para lograr esto, se acopla una celda de carga de la serie LCF entre el motor de cohete y el banco de pruebas de empuje. Además del empuje, al incorporar cuatro celdas de carga de 3 ejes en los soportes de la base del banco de pruebas del motor de cohete, se puede medir directamente el flujo de masa del motor y, en determinadas circunstancias, también se puede medir el empuje de escape vectorial. Banco de empuje de motor de cohete inspirado en Diseño del Laboratorio Suizo de Propulsión (SPL).</p>

                <p class="text-center light-black font-weight-bold">¿Cómo funciona?</p>
                <ol class="light-black">
                    <li class="mb-3">En esta aplicación de soporte de empuje de motor de cohete, el motor de cohete se enrosca en la celda de carga universal de la serie LCF.</li>
                    <li class="mb-3">El soporte de prueba del motor de cohete evita cualquier carga lateral sobre la celda, lo que garantiza que la celda de carga solo reciba cargas axiales.</li>
                    <li class="mb-3">El conjunto de la celda de carga está montado en un soporte de prueba de medición de empuje fijo que fija el motor (soporte de prueba de cohetes).</li>
                    <li class="mb-3">En línea con los soportes de la base se instalan las células de carga multieje MTA400/MTA600.</li>
                    <li class="mb-3">Mientras el motor está en funcionamiento, el empuje se mide con las celdas de carga de la serie LCF.</li>
                    <li class="mb-3">El flujo de masa y el arrastre (también conocido como “patada”) se capturan con celdas de carga MTA400/MTA600.</li>
                    <li class="mb-3">Los datos de empuje se pueden transmitir en vivo y registrar para su monitoreo y posterior revisión y comparación con modelos simulados con USB220 y SENSIT</li>
                    <li class="mb-3">Los datos de flujo másico de las 4 celdas de carga multieje se capturan, transmiten y registran con USB220 y SENSIT.</li>
                    <li class="mb-3">Cada eje del MTA400/MTA600 se captura con un USB220 independiente.</li>
                    <li class="mb-3">La salida de la celda de carga también se puede amplificar a través de la serie IAA para su captura por DAQ preexistentes.</li>
