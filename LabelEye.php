            <p>El LABEL • EYE® es un sensor de hueco o de ranura de propósito especial optimizado para detectar las etiquetas adhesivas que se adhieren a un rollo de papel. La banda de etiquetas se dirige desde un "rollo" a través de una banda de corte o alrededor de un borde afilado. A medida que la banda pasa alrededor del borde afilado de la placa peladora, la etiqueta adhesiva se desprende del material de soporte. La función de LABEL • EYE® es examinar el papel de respaldo para detectar el "espacio" entre las etiquetas y señalar a la máquina de etiquetado que detenga el mecanismo dispensador antes de que la etiqueta se desprenda completamente del material de soporte. Asegurando que la siguiente etiqueta estará perfectamente posicionada para ser aplicada al siguiente producto a medida que pasa sobre el transportador. </p><br>

