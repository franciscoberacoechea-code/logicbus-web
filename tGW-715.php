<center><strong>Módulo Modbus / TCP a RTU / ASCII gateway, 1 puerto RS 485/422, puerto Ethernet (10/100 Base-TX) con PoE</strong></center><br>

<p>La serie tGW-700 es un gateway Modbus TCP a RTU/ASCII que permite un host Modbus/TCP comunicarse con un dispositivo serial Modbus RTU/ASCII a través de una red ethernet, y eliminar la limitante de longitud de cable de los dispositivos seriales.  El módulo puede ser usado para crear aplicaciones de conexión a pares (al igual que serial-puente o serial-túnel), y puede enrutar datos sobre TCP/IP entre dos dispositivos seriales Modbus RTU/ASCII.<br><br>

DHCP minimiza errores de configuración causados por la configuración manual de direcciones IP, como conflictos de direcciones causados por la asignación de una misma dirección IP a más de una computadora.  El módulo tGW-700 soporta la función de cliente DHCP, la cual permite fácilmente obtener la información necesaria para la configuración TCP/IP desde un servidor DHCP.  El módulo también contiene UDP de respuesta que transmite su información de dirección IP en respuesta a una búsqueda UDP desde la utilidad eSearch, haciendo la administración local más eficiente.</p>

<strong>Características:</strong>
<ul>
<li>Gateway Modbus/TCP a RTU/ASCII rentable.</li>
<li>Soporta Modbus/TCP maestro y esclavo.</li>
<li>Soporta Modbus RTU/ASCII maestro y esclavo.</li>
<li>Contiene un procesador de 32 bit que eficientemente maneja el tráfico de red.</li>
<li>Ethernet 10/100 Base-TX, RJ-45 x 1 (Autonegociación, auto MDI/MDIX, indicadores LED).</li>
<li>Incluye entradas redundantes de poder: PoE (IEEE 802.3af, clase 1) y conector Jack DC.</li>
<li>Permite control de dirección RS485 automáticamente.</li>
<li>Soporta protocolos TCP, UDP, HTTP, DHCP, BOOTP y TFTP.</li>
<li>Soporta UDP de respuesta para detección de dispositivos.</li>
<li>Permite fácil actualización de firmware vía ethernet.</li>
<li>Contiene un servidor web para configuración.</li>
<li>Conector Macho DB-9 o terminal a tornillos para fácil cableado.</li>
<li>Factor de forma pequeña y bajo consumo de poder.</li>
<li>Cumple con RoHS.</li>
<li>Hecho con materiales retardantes de fuego (nivel UL94-V0).</li>
</ul>

<strong>Aplicaciones:</strong>
<ul>
<li>Automatización de fábricas, edificios y hogares.</li>
<li>Manejo y diagnóstico remoto.</li>
</ul> 
