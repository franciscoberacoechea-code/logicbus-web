              <h2><span>Pruebas de Límite de Máscara</span></h2>
            </div>
          </div>
        </center>

        <p align="justify">Ésta característica está especialmente diseñada para ambientes de producción y de depuración.
          Captura una señal desde un sistema de trabajo conocido y el PicoScope dibujará una máscara alrededor de él con
          tu tolerancia especificada. Conecta el sistema bajo prueba, y el PicoScope resaltará cualquier parte de la
          forma de onda que esté fuera del área de la máscara. Los detalles resaltados persisten en el display,
          permitiendo al osciloscopio retener fallas intermitentes mientras trabajas en algo más. La ventana de medición
          cuenta el número de fallas y puede mostrar otras mediciones y estadísticas al mismo tiempo.
          Los editores numéricos y gráficos de las máscaras (como se muestra en la imagen) pueden ser usados por
          separado o en combinación, permitiéndote introducir especificaciones precisas de la máscara y modificar las
          máscaras existentes. Puedes importar y exportar las máscaras como archivos.</p><br><br>

