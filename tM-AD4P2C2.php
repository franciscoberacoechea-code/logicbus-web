          <center><strong>Entrada analógica de 4 canales, entrada digital de 2 canales y módulo de salida digital de 2 canales.</strong></center><br>
          <p>El tM-AD4P2C2 es un módulo multifunción que incluye 4 canales de entrada analógicos, 2 canales de entrada digital y 2 canales de salida digital. El módulo ofrece un rango de entrada analógica programable que incluye 2 canales de entrada de tensión (± 1 V, ± 2,5 V, ± 5 V y ± 10 V) y 2 canales de entrada de corriente (± 20 mA, 0 ~ 20 mA y 4 ~ 20 mamá). Las entradas analógicas proporcionan una protección de sobrevoltaje de 120 VDC y una frecuencia de muestreo ajustable.<br><br>
            El módulo admite salida digital de tipo fregadero con protección contra cortocircuito y las salidas digitales se pueden utilizar como alarmas de límite de entrada de tensión. Las entradas digitales son de tipo fuente y todos los canales de entrada digital se pueden utilizar como contadores de 16 bits. Existen opciones para configurar los valores de encendido y de salida digital seguros. También se proporciona una protección ESD de 4 kV y un aislamiento intramódulo de 2500 VCC. El tM-AD4P2C2 admite los protocolos DCON, Modbus RTU y Modbus ASCII, que pueden configurarse mediante software.</p><br>

          <strong>Caracter&iacute;sticas </strong>
          <ul>
            <li>Multifunción (4 AI, 2 DI y 2 DO).</li>
            <li>2 Canales de Entrada de Voltaje y 2 Canales de Entrada de Corriente.</li>
            <li>Los canales de entrada digital se pueden utilizar como contadores de 16 bits.</li>
            <li>Los canales de salida digital se pueden utilizar como alarmas de límite de entrada de voltaje.</li>
            <li>4 kV Protección ESD y EFT.</li>
            <li>Protección de sobretensión de 120 VCC.</li>
            <li>Frecuencia de muestreo ajustable.</li>
            <li>Watchdog Dual.</li>
            <li>Aislamiento intra-módulo de 2500 V CC.</li>
            <li>Herramientas de configuración del valor de encendido.</li>
            <li>Herramientas de configuración de valores seguros.</li>
            <li>Amplio rango de temperatura de funcionamiento: -25 ~ +75°C.</li>
          </ul>

