<p align="justify">La tarjeta INET-410 conecta una i4xx Card Cage a una computadora con Windows a través de una tarjeta controladora INET-240 USB, INET-200 PCI o INET-230 PCMCIA. El INET-410 se conecta a la ranura que se encuentra más a la izquierda (ranura # 1) de una jaula de tarjetas i4xx. Al trabajar con los controladores i2x0, se requiere uno y solo un i410 por la jaula de tarjetas i4xx.</p>

<strong>El INET-410 ofrece las siguientes características:</strong>
<ul>
<li>Dos conectores Db25 permiten encadenar múltiples dispositivos i4xx Card Cage y i100 a una tarjeta controladora i2x0.</li>
<li>La luz roja de encendido del panel frontal muestra la presencia de 5V, 12V y -12V.</li>
<li>La luz verde de E / S del panel frontal parpadea cuando la computadora se comunica con la caja de tarjetas.</li>
<li>Incluye un cable Db25 macho a hembra de 3 metros (10 pies).</li>
</ul><br><br>

