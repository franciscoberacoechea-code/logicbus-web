          <p align="justify">El S203RC-D es un analizador de red trifásico completo con pantalla de alta visibilidad para uso exclusivo con sensores Rogowski. S203RC-D es adecuado para rangos de voltaje de hasta 600 VCA (50 Hz o 60 Hz) y corrientes máximas de hasta 1.000 A conectadas a las entradas. El instrumento puede suministrar todas las siguientes cantidades eléctricas: Vrms, Irms, Watt, VAR, VA Frequency, Active Energy Cosphs. Para las variables enumeradas anteriormente (excepto la frecuencia), están disponibles los valores de fase y el valor total de tres fases. Todos los valores se pueden adquirir a través de comunicación en serie, ya sea en coma flotante o en formato normalizado (excepto frecuencia y energía activa).</p>

          <strong>Características:</strong>
          <ul>
            <li>Doble MODBUS registra la energía producida / consumida.</li>
            <li>Cálculo de potencia promedio.</li>
            <li>Pantalla retroiluminada.</li>
            <li>Puerto de programación frontal mini-USB.</li>
            <li>Posibilidad de transmitir energía medida o la dirección de la corriente a través de la salida digital.</li>
            <li>Soporte de TV.</li>
            <li>Diagnósticos en la pantalla.</li>
