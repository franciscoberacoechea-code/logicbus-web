                        bajo costo
                        con 8 entradas analógicas de terminal común o cuatro diferenciales de 12 bits, 2 salidas
                        análogas de 10
                        bits, 4 terminales de tornillo, 28 líneas digitales bidireccionales y un contador de
                        eventos.<br><br>
