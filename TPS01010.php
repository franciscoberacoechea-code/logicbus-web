<p align="justify">El botón de carga en miniatura LLB300 de FUTEK está diseñado para aplicaciones de compresión en línea o de prensa. El LLB300 estándar tiene una construcción robusta disponible en acero inoxidable 17-4 PH, con un diámetro exterior de 0,74 pulg. Y un cable de teflón blindado en espiral de 4 conductores [3 m] # 29 AWG de 10 pies [3]. También encontrará opciones disponibles para salidas externas coincidentes. 
