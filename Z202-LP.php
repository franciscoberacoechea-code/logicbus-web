<p>Z202-LP es un convertidor universal para voltajes de CA o CC (0..500 Vac o 0..540 Vcc) y proporciona una salida aislada de 4..20mA. Es un dispositivo alimentado por bucle a través de la salida de bucle de 4..20mA. Es posible calibrar el instrumento en cualquier punto intermedio en el rango continuo de 0..500A. Un aislamiento galvánico de 3 vías entre la fuente de alimentación // entrada // circuitos de salida garantiza la integridad de sus datos.

</p><br>

<strong>Caracteristicas:</strong>
<ul>
<li>Alimentación desde el lazo de corriente (de 5~28 Vdc)</li>
<li>Entrada: 0~500 Vac ó 0~540 Vdc (con diferentes rangos seleccionables por DIP Switch)</li>
<li>Salida: 4~20 mA</li>
<li>Aislamiento galvánico de 3 vías (4.0 KVac)</li>
<li>Frecuencia: DC/20~400 Hz</li>
<li>Precisión de 0.3%</li>
<li>Tiempo de respuesta: < 100 ms de 10~90 %</li>
<li>Temperatura de operación: -20 a +65°C</li>
<li>Dimensiones: 17.5 x 100 x 112 mm</li>
</ul>

