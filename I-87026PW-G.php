<p>El 87026PW es un módulo multifunción que incluye 6 canales de entrada analógica, 2 canales de salida analógica, 2 canales de entrada digital, 2 canales de salida digital. Proporciona un rango de entrada programable en todas las entradas analógicas (+/- 150 mV, +/- 500 mV, +/- 1 V, +/- 5 V, +/- 10 V, +/- 20 mA, 0 ~ 20 mA o 4 ~ 20 mA), las salidas analógicas son de 12 bits a +/- 5 V, +/- 10 V, 0 ~ 20 mA o 4 ~ 20 mA y todas las salidas digitales se pueden configurar como salidas de alarma. Cada entrada analógica se puede configurar para un rango individual y proporciona una alta protección contra sobretensión de 240 Vrms. Las entradas / salidas de tensión y corriente son seleccionables por puente.</p>

Caracteristicas:
<ul>
<li>Multifunción (6AI, 2AO, 2DI y 2DO).</li>
<li>Admite el modo rápido y el modo normal.</li>
<li>Confi guración del canal individual.</li>
<li>Detección de cable abierto para salida de corriente.</li>
<li>Protección de sobrecarga y cortocircuito para salida digital.</li>
<li>Configuración configurable de Power-on Value.</li>
<li>Configuraciones configurables de valores seguros.</li>
<li>Protección de sobretensión de 240 Vrms para entrada de voltaje.</li>
<li>Protección de sobrevoltaje de 70 VDC para entrada digital.</li>
<li>Puente de voltaje seleccionable o entrada / salida actual.</li>
<li>Dual Watchdog.</li>
<li>± 4 kV Protección de contactos ESD.</li>
<li>Amplio rango de temperatura de funcionamiento: -25 ° C ~ +75 ° C.</li>
</ul>
