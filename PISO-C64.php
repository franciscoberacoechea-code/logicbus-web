<LI>Función de identificación de tarjeta para PISO-C64U y PEX-C64.</LI>
<LI>Estado de salida Readback para PISO-C64U y PEX-C64.</LI>
<LI>64 canales DO ópticamente aislados (colector abierto).</LI>
