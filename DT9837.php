  <p><strong>DAQ para Sonido y Vibración portable</strong><br>
La serie DT9837 son módulos de adquisición de  señales dinámicas de alta precisión ideales para mediciones portables de ruido,  vibraciones y acústicas. Cuatro sensores de 24 bits tipo IEPE (ICP) son  sincronizados con una entrada de tacómetro para proveer flujos de datos que son  comparados en tiempo. Realizado en material resistente, de tamaño pequeño y  alimentado por USB, lo hace ideal para aplicaciones de medición portable.<br>
