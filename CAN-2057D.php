<center><strong>Módulo esclavo DeviceNet de salida digital aislada de colector abierto de 16 canales.</strong></center><br>

<p>DeviceNet es un tipo de protocolo de red basado en el bus CAN y utilizado principalmente para la red integrada de control de la máquina, como control de máquinas industriales, monitoreo de motores de aeronaves, automatización de fábricas, control de equipos médicos, adquisición remota de datos, monitoreo ambiental y control de máquinas de embalaje, etc.
<br><br>
El CAN-2057D sigue la especificación DeviceNet Volumen I / II, Versión 2.0. El usuario puede acceder al estado de salida digital y configurar la configuración a través del archivo DeviceNet EDS. El CAN-2057D tiene 16 canales de salida digital con tipo de salida de colector abierto y se puede utilizar para desarrollar un sistema de control digital potente y rentable.</p>
<strong>Aplicaciones:</strong>
<ul>
  <li>Salida de alarma.</li>
  <li>Control del interruptor.</li>
</ul>
