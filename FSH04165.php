<p><b>El modelo LCB500-3000 lbs</b> es una celda de carga de tensión y compresión se puede usar para actuadores en línea o gatos hidráulicos con roscas macho / hembra. El modelo estándar de celda de carga de tensión y compresión LCB500 tiene roscas macho / hembra, es una unidad soldada y viene con un receptáculo Bendix. El Flexure está hecho de acero inoxidable, lo que lo hace muy duradero e ideal para pruebas de resistencia. Este modelo es muy adecuado para aplicaciones de capacidad de rango bajo a rango alto (100 lb - 5,000 lb).
<br><br>
Esta celda de carga de tensión y compresión tiene alta precisión, excelente resistencia a altas cargas extrañas y alta rigidez. Tiene una no linealidad de ± 0,25% y una deflexión de 0,002 a 0,005” nominal. La celda de carga de compresión y tensión LCB500 estándar utiliza tecnología de galgas extensométricas de lámina metálica.</p>

