<li>Aislamiento óptico de 2,500V</li>
<li>LEDs para indicar estado de relevadores</li>
<li>Terminales de tornillo para fácil cableado</li>
<li>Diodos integrados para proteger de malas conexiones de la fuente de poder externa</li>
