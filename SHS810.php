<p>El SHS810 es un osciloscopio portátil con características que normalmente se encuentran solo en instrumentos caros de mesa. Es ideal para mediciones de circuitos de aplicación de campo, depuración eléctrica, educación, investigación científica y control de calidad. Combina un sofisticado osciloscopio de 100MHz, un multímetro de 6000 cuentas y una grabadora de forma de onda en una unidad portátil con una brillante pantalla LCD TFT de 5.7 "a color. Con un ancho de banda de 100MHz, puede medir señales de un solo canal a una velocidad de 1GSa / s o ambos canales a 500MSa / s, con una memoria de muestra de 2Mpt para permitir el almacenamiento, reproducción y ampliación de las mediciones.
<br><br>
El registrador de datos incorporado tiene hasta 18 horas de tiempo de grabación, mientras que el Meter TrendPlot puede registrar datos de medición del multímetro durante un tiempo de hasta 6000 horas a 0.05Sa / s. El multímetro mide DCV, ACV, DCI, ACI, resistencia, diodo, capacitancia y continuidad.
 <br>
Voltaje de entrada: voltaje de entrada a través de BNC hasta CATII 300V y CATIII 150V Sonda estándar: 10X CAT II 400V Sonda opcional: 10X CAT II 1000V y 10X CAT III 600V Osciloscopio y multímetro de seguridad para CAT II 600V y CAT III 300V.
 <br>
El SHS810 ofrece 32 mediciones automáticas, 3 modos de medición del cursor, 4 filtros digitales (paso bajo, paso alto, paso de banda, límite de banda) así como también funciones matemáticas +, -, ×, ÷ y gráficos X / Y , así como la visualización de frecuencia FFT. Múltiples tipos de disparo incluyen ajustes de señal de video.
 <br><br>
Cuenta con un dispositivo USB para actualizaciones de software y capacidades de host USB para impresoras compatibles con PictBridge. SHS810 se conecta a una PC a través de un cable USB para el software de control EasyScope y puede guardar / recuperar formas de onda en una unidad flash USB. SHS810 puede guardar 2 grupos de formas de onda de referencia, 20 grupos de configuraciones y 10 grupos de formas de onda en su memoria interna, guardar datos de configuración, datos de forma de onda, imagen de interfaz de forma de onda y archivo CSV en una unidad flash USB.
 <br>
El SHS810 viene con un paquete de baterías recargables de litio de 7.4V 5000mAh que dura hasta 5 horas de uso continuo, pero también se proporciona un adaptador de CC, 100-240V 50 / 60Hz, 9V, adaptador de 4A DC.
 
