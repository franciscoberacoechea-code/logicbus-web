<p align="justify">La tarjeta de la serie PCISA-7520 proporciona una función de conversión RS-232 a RS-485 (o RS-422) que es exactamente igual a la serie I-7520. Está diseñado para una fácil instalación, alimentado desde la interfaz PCI o ISA pero sin las funciones PCI e ISA. La serie PCISA-7520 está equipada con un puerto serie RS-232 y un puerto serie RS-485. El puerto RS-232 está diseñado para comunicarse con la PC host local, el RS-485 está diseñado para comunicarse con el módulo IO remoto. </p>

<strong>Características:</strong>
<ul>
<li>No requiere fuente de alimentación externa</li>
<li>No requiere instalación de controlador</li>
<li>Protección de aislamiento de 3000 V DC</li>
<li>Velocidad de transferencia de conmutación automática, 300 ~ 115200 bps</li>
<li>Protección ESD para la línea de datos RS-232/422/485</li>
<li>Velocidad de transmisión de hasta 115200 bps.</li>
<li>Se puede utilizar en un bus ISA, un bus PCI o cualquier sistema con una interfaz RS-232</li>
</ul><br>

