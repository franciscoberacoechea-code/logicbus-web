<article>
  <p><b>Resumen de la aplicaci&oacute;n:</b>
La prueba de resistencia en materiales nos ayuda en el desarrollo de nuevos productos y la mejora de los que actualmente existen. 
Normalmente la prueba de fuerza se realiza sometiendo a estrés a un material y se observa la reacción que tiene a lo largo de la prueba.
El equipo más común con el que se realizan pruebas de fuerza son las prensas hidráulicas, que pueden aplicar distintas cargas sobre el material.
Este tipo de aplicaciones se pueden lograr utilizando la celda de carga <strong><a href="https://tienda.logicbus.com.mx/Pancake_c_1840.html" target="_blank">LCF</a></strong> para aplicaciones robustas.

</p>

<img src="imagenes/36/diagramas/manufactura/pruebas-de-fuerza-en-materiales.jpg" alt="Pruebas de fuerza en materiales" width="50%">

<div>
  <p><b>C&oacute;mo funciona:</b><br></p>
  <ol>
    <li style="color: black;">Los operadores instalaron la celda de carga tipo panqueque <strong><a href="https://tienda.logicbus.com.mx/Pancake_c_1840.html" target="_blank">LCF</a></strong> a una prensa hidráulica en un banco de pruebas para materiales.</li>
    <li style="color: black;">Planeada para mediciones de tensión, la celda de carga monitorea la fuerza aplicada al sujeto de prueba, en este caso, un pilar de concreto.</li>
    <li style="color: black;">A medida que la prensa aplica fuerza sobre el pilar de concreto, la celda de carga <strong><a href="https://tienda.logicbus.com.mx/Pancake_c_1840.html" target="_blank">LCF</a></strong> tomará las medidas de la fuerza y la enviará a un PLC a través del acondicionador de señal <strong><a href="https://tienda.logicbus.com.mx/Acondicionador-de-se%C3%B1al_c_1665.html" target="_blank">IAA</a></strong> de Futek.</li>
    <li style="color: black;">La celda de carga <strong><a href="https://tienda.logicbus.com.mx/Pancake_c_1840.html" target="_blank">LCF</a></strong> puede utilizarse en conjunto con alguno de los displays de Futek, tales como el <strong><a href="https://tienda.logicbus.com.mx/FSH03571_p_6818.html" target="_blank">IHH500</a></strong> o <strong><a href="https://tienda.logicbus.com.mx/FSH03633_p_6809.html" target="_blank">IPM650</a></strong> para análisis de datos.</li>
    <li style="color: black;">Pueden utilizarse también soluciones de <strong><a href="https://tienda.logicbus.com.mx/FSH03634_p_6807.html" target="_blank">USB</a></strong> para revisar los datos en el software SENSIT para medición y pruebas.</li>
