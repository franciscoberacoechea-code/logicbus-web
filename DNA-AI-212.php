          <br>
          An A/D per channel configuration allows simultaneous sampling at rates up to 100 S/s each (1200 S/s aggregate). The A/D per channel configuration virtually eliminates input cross talk and channel settling time issues.<br>
          <br>
          The DNx-AI-212 is an ideal, high accuracy thermocouple measurement device, offering offset and gain errors of less than 0.1&deg;C on all standard thermocouples (including J, K, T, S, E, R). This accuracy combined with the 350 VDC/Vrms channel-to-channel and channel-to-chassis isolation makes the board a perfect solution for industrial temperature measurement, even when using non-isolated thermocouples in high voltage environments. If higher isolation is required, please refer to the DNx-AI-282.<br>
          <br>
          Additionally, the DNx-AI-212 is designed to take advantage of the extremely accurate ADT 7420 digital temperature sensor which provides a dedicated CJC measurement. The CJC sensor is mounted externally on the DNA-STP-212 screw terminal panel. The software included will perform all required TC linearization and CJC compensation and return data in &deg;C, &deg;K, &deg;F or &deg;R when desired. An open thermocouple detection circuit has also been implemented.<br>
          <br>
          Software included with the DNx-AI-212 provides a comprehensive yet easy to use API that supports all popular Windows programming languages as well as supporting programmers using Linux and most real-time operating systems including QNX, RTX, VXworks and more. Finally, the UEIDAQ Framework supplies complete support for those creating applications in data acquisition software packages such as LabVIEW, MATLAB/Simulink, DASYLab or any application which supports ActiveX or OPC servers.
