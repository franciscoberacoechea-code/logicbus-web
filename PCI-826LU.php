      <td valign="top"><p align="justify">	
	<strong>Descripci&oacute;n General </strong><br><br>
El PCI-826LU es una tarjeta multifuncional de alto rendmiento que provee funciones de E/S anal&oacute;gicas y E/S digitales de alta velocidad. La tarjeta PCI-822LU tiene una interfaz universal que soporta los bus PCI 3.3 V y 5 V. &Eacute;sta tarjeta tiene un convertidor A/D continuo de 16 bits a 250 kS/s, 8 k muestras, hardware FIFO, un convertidor D/A de 16 bits con 2 canales. El PCI-826LU provee entradas digitales ya sea  32-canales en Modo Común o 16 canales diferenciales que son seleccionables por medio de jumpers. Est&aacute; equipada con controles de ganancia programables por medio de una PGA de alta velocidad. <br>
<br>
El PCI-826LU tiene la tarjeta de switch ID y resistencias pull-high/pull-low para las entradas digitales en la tarjeta. Los usuarios pueden configurar el Card ID en la tarjeta y reconocer la tarjeta por medio del software de ID, cuando se usan dos o mas tarjetas  PCI-826LU en una computadora. Las Resistencias pull-high/pull-low permiten especificar el estatus de las entradas digitales; cuando &eacute;stos canales est&aacute;n desconectados, el estado se quedar&aacute; en alto o en bajo en lugar de quedarse flotando.<br>
<br>
        La PCI-826LU provee 2 m&eacute;todos de disparo programables: disparo por software y pacer. La funci&oacute;n de b&uacute;squeda del canal A/D de la PCI-822LU es tan impresionante que es llamado MagicScan. El controlador MagicScan lleva a cabo la mayor&iacute;a del trabajo de obtener valores A/D como seleccionar los canales, configurar la ganancia, establecer el tiempo, disparo del AC y obtener datos. A&uacute;n en el modo de b&uacute;squeda de canal, puede tener diferentes c&oacute;digos de ganancia para cada canal, y la velocidad de muestreo puede llegar a 250kS/s en su totalidad. La PCI-826LU es &uacute;til para aplicaciones de una gama alta. <br>
