<center><strong>Convertidor USB a RS-485.</strong></center><br>

<p>El tM-7561 es un convertidor USB a RS-485 rentable. Al conectar el tM-7561 a una PC, obtiene un puerto <a href="https://www.logicbus.com.mx/convertidores_info#RS-485">RS-485</a> que le permite acceder a los dispositivos RS-485 a través de la interfaz USB. Al igual que el <a href="I-7520">I-7520</a>, el tM-7561 contiene un chip "Self-Tuner" que sintoniza automáticamente la velocidad en baudios y el formato de datos a la red RS-485. El módulo tM-7561 obtiene su potencia del puerto USB y no necesita una adaptación de potencia externa.</p>

<strong>Características:</strong>
<ul>
    <li>Totalmente compatible con USB 1.1 / 2.0 (alta velocidad).</li>
    <li>Indicador de alimentación y flujo de datos para la resolución de problemas.</li>
    <li>Protección de aislamiento de 2500 VDC en el lado RS-485.</li>
    <li>Driver Admite Windows 98 / ME / 2000 / XP (32/64-bit) / Vista (32/64-bit) / 7 (32/64-bit) / 8 (32/64-bit) / 10 / Linux.</li>
    <li>Pequeños ajustes de embalaje en su riel DIN.</li>
    <li>No se requiere una fuente de alimentación externa.</li>
    <li>Control de dirección automático RS-485.</li>
    <li>Temperaturas de funcionamiento, -25 ° C ~ +75 ° C.</li>
    <li>Bajo consumo de energía.</li>
    <li>Convertidor rentable.</li>
</ul>
	
