<p align="justify">Controlador de pantalla táctil programable<br />
ViewPAC-23W6 / ViewPAC-25W6 es la nueva generación de PAC basado en WinCE de ICP DAS. ViewPAC combina WinPAC, pantalla gráfica y teclado en una unidad. Equipa una CPU PXA270 (520MHz) con sistema operativo Windows CE.NET 5.0, conectividades variantes (USB, Ethernet, RS-232/485), 3 ranuras para expandir módulos de E / S, LCD TFT 3.5 "/5.7" y una goma teclado.<br />
Su sistema operativo, Windows CE.NET 5.0, tiene muchas ventajas, incluye capacidad dura en tiempo real, tamaño de núcleo pequeño, velocidad de arranque rápida, manejo de interrupciones a un nivel más profundo, control determinista alcanzable y bajo costo. El VP-23W6 / VP-25W6 también se presenta con el poderoso InduSoft Web Studio e ISaGRAF. InduSoft es la colección más poderosa e integrada de herramientas de desarrollo de e-automation que incluye todos los componentes necesarios para desarrollar Human Machine Interface (HMI) y los sistemas de Supervisión de Supervisión y Adquisición de Datos (SCADA). ISaGRAF es un software tipo PLC y es compatible con los cinco idiomas IEC61131-3 (LD, ST, FBD, SFC, FC).<br />
En comparación con las soluciones IPC + PLC tradicionales, ViewPAC reduce el costo general del sistema, el espacio y le ofrece todas las mejores características de IPC y PLC.</p>
<strong>funciones de software:</strong><br>
<ul>
CPU PXA 270 (32 bits y 520 MHz)
Panel frontal compatible con IP44
Teclado de goma con teclas 24/6
Audio con MIC-In y Line-Out
Número de serie de hardware de 64 bits para protección de software
3 ranuras para módulos de E / S de alto perfil
Amplia capacidad de expansión de E / S (Ethernet, RS-232/422/485, FRnet, bus CAN)
SRAM Dual Backup Backup (512 KB)
Incorporado un puerto Ethernet, 2 puertos serie (RS-232 y RS-485)
Temperatura de funcionamiento: -20 ~ +70 ° C
</ul>

<strong>funciones de software:</strong><br>
<ul>
ViewPAC-2xW6 Software Features
Windows CE.NET 5.0
Runtime InduSoft and ISaGRAF is ready
Remote Maintenance via FTP Server and VCEP software
Built-in OPC Server (Quicker)
Rich Software Solutions (VS.NET 2003/2005/2008 and eVC)
</ul>

