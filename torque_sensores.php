                <p align="justify">Un sensor de torque, es un transductor que convierte la torsi&oacute;n
                  mec&aacute;nica de entrada en una se&ntilde;al el&eacute;ctrica a la salida. Los sensores de torque
                  son tambi&eacute;n com&uacute;nmente conocidos como transductores de torque.</p>
                <p align="justify">La tecnolog&iacute;a de galgas extensiom&eacute;tricas facilita el dise&ntilde;o de
                  los sensores de torque mediante el siguiente proceso:</p>
                <ol>
                  <li> Dise&ntilde;o y fabricaci&oacute;n de una unidad de flexi&oacute;n o elemento flexor a base de
                    materiales de alta resistencia. </li>
                  <li> Uni&oacute;n de galgas extenciom&eacute;tricas a las partes m&aacute;s sensibles del elemento
                    flexor </li>
                  <li> Conexi&oacute;n de las galgas extensiom&eacute;tricas en una configuraci&oacute;n de puente de
                    Wheatstone considerando los efectos de la temperatura sobre el sensor/transductor
                    (compensaci&oacute;n)</li>
                  <li> Se realiza un proceso de calibraci&oacute;n con trazabilidad NIST. Se aplica un momento empleando
                    una carga de brazo de palanca ya sea en sentido horario (clockwise) o anti-horario
                    (counter-clockwise). Las galgas extensiom&eacute;tricas convierten la deformaci&oacute;n
                    mec&aacute;nica en un cambio en la resistencia el&eacute;ctrica proporcional a la carga aplicada
                  </li>
                </ol>
                <p align="justify">La tecnolog&iacute;a de estos sensores incluye dise&ntilde;os para sensores de torque
                  de reacci&oacute;n y rotaci&oacute;n, el primero utilizado para torques est&aacute;ticos
                  (reacci&oacute;n) y el segundo para torques din&aacute;micos y en movimiento (rotaci&oacute;n)</p>
                <p align="justify">Los sensores de reacci&oacute;n utilizan galas extensiom&eacute;tricas en
                  configuraci&oacute;n de puente completo con partes inm&oacute;viles que no requieren mantenimiento.
                  Pueden ser usados para comprobar el torque residual en sujetadores y determinar el torque para vencer
                  los efectos de la fricci&oacute;n.</p>
                <p align="justify">Los sensores de torque rotatorios ofrecen ventajas para realizar mediciones en el
                  desempe&ntilde;o de herramientas y maquinaria. Ofrecemos configuraciones de montaje sin contacto y son
                  capaces de detectar el torque din&aacute;mico en velocidades de hasta 12,000 RPM.</p>
                <p align="justify">La avanzada tecnolog&iacute;a de los sensores basados en galgas
                  extensiom&eacute;tricas es ampliamente conocida en muchas &aacute;reas de la industria por poseer:</p>
                <ul>
                  <li> Alta exactitud, la cual cumple con muchos est&aacute;ndares de calidad en la industria automotriz
                    y aeroespacial. </li>
                  <li> Construcci&oacute;n robusta en acero inoxidable o aluminio para dar mayor resistencia. </li>
                  <li> Garant&iacute;a de fabricaci&oacute;n para una larga duraci&oacute;n incluso en las mas rigurosas
                    condiciones de trabajo </li>
                  <li> Una amplia variedad de opciones de montaje, tama&ntilde;os y geometr&iacute;as. </li>
                  <li>Precio competitivo </li>
                  <li> Amplia variedad de capacidades desde 5 in-oz hasta 500,000 in-lbs. </li>
                  <li> Alta respuesta frecuencial acoplada con dise&ntilde;os mec&aacute;nicamente r&iacute;gidos </li>
                </ul>
                <p align="justify">Estos sensores de torque son empleados en muchas aplicaciones dentro de la industria
                  tales como M&eacute;dica, Automotriz, Aviaci&oacute;n, Aeroespacial, Computaci&oacute;n y
                  Automatizaci&oacute;n solo por mencionar algunas.</p>
                <p align="justify">La selecci&oacute;n de sensores de torque incluye sensores de torque de
                  reacci&oacute;n para aplicaciones est&aacute;ticas y sensores rotatorios para aplicaciones
                  din&aacute;micas, con las siguientes clasificaciones:</p>
                <ul>
                  <li> Sensor de torque de reacci&oacute;n para herramientas (dise&ntilde;ado como una parte incorporada
                    en herramientas para apretar tuercas (matraca) en procesos de ensamble autom&aacute;ticos) </li>
                  <li> Sensor de torque de reacci&oacute;n con bridas (sensores de torque de reacci&oacute;n con bridas
                    para montaje) </li>
                  <li> Sensores de torque de rotaci&oacute;n Hex Drive (destornillador Hexagonal/Allen) (para mediciones
                    de torque rotatorio sin contacto y anillos para aplicaciones en l&iacute;nea y disponibles con
                    encoders)</li>
                  <li> Sensor de torque de reacci&oacute;n de desarmador (usado para el ensamble de tornillos y
                    sujetadores con bajo torque)</li>
                  <li> Sensor de torque de rotaci&oacute;n de eje a eje (para mediciones de torque rotatorio sin
                    contacto y anillos para aplicaciones en l&iacute;nea y disponibles con encoders)</li>
                  <li> Sensor de torque de reacci&oacute;n de eje a eje (transductor de torque de reacci&oacute;n
                    montado en ejes) </li>
                  <li> Sensor de torque de reacci&oacute;n de extensi&oacute;n de socket (ampliamente usado en la
                    digitalizaci&oacute;n y verificaci&oacute;n del torque aplicado) </li>
                  <li> Sensor de torque de rotaci&oacute;n de eje cuadrado (para mediciones de torque rotatorio sin
                    contacto y anillos para aplicaciones en l&iacute;nea y disponibles con encoders)</li>
                  <li> Sensor de torque de reacci&oacute;n de eje cuadrado a brida (dise&ntilde;ados para
                    verificaci&oacute;n y comprobacion de dispositivos de medici&oacute;n de torque y herramientas de
                    sujeci&oacute;n) </li>
                  <li> Sensor de torque de reacci&oacute;n de eje cuadrado a eje cuadrado (transductores de torque de
                    reacci&oacute;n con eje cuadrado hembra) </li>
                  <li> Sensor de torque de reacci&oacute;n de llave dinamom&eacute;trica (com&uacute;nmente usado para
                    revisi&oacute;n de torque aplicado sobre un sujetador)</li>
                </ul>

