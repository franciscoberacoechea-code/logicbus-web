<p> 
La serie NS-200AF es un convertidor Ethernet (10 / 100Base-TX) a Fibra Óptica (100Base-FX). El Ethernet admite la función de autonegociación 10 / 100M y la función automática MDI / MDI-X.<br><br>

La serie NS-200AF está disponible en modelos que admiten una temperatura de funcionamiento de 0 a 70 ° C y una temperatura de funcionamiento extendida de -30 a 75 ° C
</p><BR>

<strong>Caracteristicas:</strong>
<ul>
<li>Crossover automático MDI / MDI-X para plug-and-play</li>
<li>Cada puerto admite una negociación automática de velocidad de 10/100 Mbps</li>
<li>Arquitectura de almacenamiento y reenvío</li>
<li>Full duplex IEEE 802.3x</li>
<li>Admite voltaje +12 ~ +48 V CC</li>
<li>Admite temperaturas de funcionamiento de 0 ° C ~ +70 ° C -30 a 75 ° C rango de temperatura de funcionamiento (modelos T)</li>
<li>Montaje en riel DIN para uso industrial</li>
