            <li> F&aacute;cil conexi&oacute;n de alimentaci&oacute;n y comunicaci&oacute;n serial para montaje en riel DIN.</li>
            <li> Comunicaci&oacute;n serial RS-485 con protocolo ModBus RTU.</li>
            <li> Distancia de transmisi&oacute;n de datos RS-485  de hasta 1,200 mts.</li>
            <li> Configuraci&oacute;n por  RS-232.</li>
            <li> La direcci&oacute;n  y el Baud Rate pueden ser configurados mediante DIP Switch.</li>
            <li>Montaje en Riel DIN.</li>
