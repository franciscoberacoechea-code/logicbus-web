<p>La pinza RG6 es una herramienta de fin de brazo de colaboración diseñada para una integración perfecta con los brazos de robot de colaboración de Universal Robots. La pinza RG6 elimina el dolor de cabeza con los kits de instalación y funciona sin cables externos, por lo que cualquier movimiento de robot se puede realizar sin preocuparse por la colocación del cable. Las pinzas colaborativas RG6 son las verdaderas soluciones Plug y Produce. La instalación rápida y la programación simple de las pinzas reduce el tiempo de implementación en un 30%. El RG6 estándar viene con protectores de seguridad y un solo soporte de montaje.</p>

