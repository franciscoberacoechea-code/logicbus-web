La PCI-DIO48H es una tarjeta digital de E/S de alta densidad . La PCI-DIO96H ofrece 48 bits de E/S digitales. Proporciona grupos de 24 bits de E/S basados en el 82C55, modo 0. Cada grupo proporciona un puerto A y un puerto B de 8 bits as&iacute; como un puerto C de 8 bits que puede ser dividido en 2 puertos C de 4 bits: Puerto C-Hi, Puerto C-LO. <br>
<br>
Los drivers de salida digital son chips 74S244 y proporcionan capacidades de corriente de 64 mA sink y 15 mA source.<br>
<br>
La PCI-DIO48H es plug-and-play. No tiene switches o jumpers en la tarjeta. Todas las direcciones de la tarjeta se configuran por medio del software.</td>
