        <p>I-7080B está inteligentemente diseñado para proporcionar monitoreo del sistema de acondicionamiento de señal
          y configuraciones de valores seguros. I-7080B es un módulo de entrada de contador / frecuencia con respaldo de
          batería. En caso de falla de energía, mantendrá las lecturas. Es una solución rentable para una amplia gama de
          valiosas señales y sistemas de control industrial. La utilidad DCON puede ayudar a los usuarios a configurar y
          probar el módulo de entrada de frecuencia / contador de alta velocidad I-7080. Se proporcionan muchas
          funciones de biblioteca y programas de demostración para permitir a los usuarios desarrollar programas
          fácilmente en sistemas operativos Windows, Linux y DOS. La interfaz de comunicación es el protocolo Modbus a
          través de RS-485. Los usuarios pueden montar los módulos en un riel DIN, panel o pared. Los módulos tienen un
          bloque de terminal de tornillo para conectarse a las señales.</p><BR>



