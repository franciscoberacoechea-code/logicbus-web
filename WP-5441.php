<center><strong>Controlador Windows CE.Net con Audio</strong></center><br>

<p align="justify">
WP-5441La serie ICP DAS WinPAC-5000 es la nueva generación de PAC (controlador de automatización programable). Está equipado con una CPU PXA270 (520 MHz) que ejecuta un sistema operativo Windows CE.NET 5.0, varias conexiones (VGA, USB, Ethernet, RS-232/485) y un bus de expansión de E / S.<br>
La serie WinPAC-5000 tiene muchas ventajas, entre las que se incluyen la capacidad en tiempo real, el tamaño del núcleo pequeño, la velocidad de arranque rápida, el manejo de interrupciones a un nivel más profundo, el control determinista posible y el bajo costo. El uso de Windows CE.NET 5.0 le brinda la capacidad de ejecutar software de control basado en PC como Visual Basic.NET, Visual C #, Visual C ++ incrustado, software SCADA, SoftPLC ... etc. Ofrece a los usuarios todas las mejores características de PLC tradicionales y PC con Windows.<br>
Para la expansión de hardware, también admite un bus de expansión de E / S. El bus de expansión de E / S se puede usar para implementar varias funciones de E / S como D / I, D / O, A / D, D / A, temporizador / contador, UART y otras funciones de E / S. Este bus puede implementar casi todo tipo de funciones de E / S. Pero el bus solo puede soportar una tabla. Hay más de 10 tableros disponibles para la serie WinPAC-5000, los usuarios pueden elegir uno de ellos para expandir las características de hardware.</p>

