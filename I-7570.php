<strong>Características:</strong>
<ul>
<li>Soporte HART armazón corto/largo.</li>
<li>Admite el modo HART Burst.</li>
<li>Soporte de modo HART punto a punto o multi-drop.</li>
<li>Admite la conexión de hasta 15 dispositivos esclavos HART.</li>
<li>Permitir dos maestros HART.</li>
<li>Proporcionar herramienta de utilidad para la configuración del módulo y la comunicación HART.</li>
<li>Proporcione el LED de indicación PWR / TxD / RxD.</li>
<li>COM 1 aislado: RS-232 / RS-422 / RS-485.</li>
<li>4KV ESD Protection.</li>
<li>Watchdog incorporado.</li>
<li>Resistencia de carga seleccionable de 250 Ω.</li>
<li>Soporte HART OPC Server provisto por HART COMMUNICATION FOUDATION.</li>
<li>La técnica de soporte FDT (herramienta de dispositivo de campo) y el software FDT a continuación se han probado correctamente.</li>
