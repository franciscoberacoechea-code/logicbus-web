          <p><b>Descripción del producto</b></p>

          <p>El sensor SMARTEYE® STEALTH-UV™ de Tri-tronics es un sensor especial diseñado para detectar la presencia de materiales fluorescentes invisibles contenidos en o añadidos a tizas, tintas, pinturas, grasas, pegamentos u abrillantadores ópticos que se encuentran en etiquetas, papel, Etc. El sensor contiene una fuente de luz de estado sólido ultravioleta (UV) que se utiliza para excitar los materiales luminiscentes para que fluorescan en el intervalo visible. El detector del sensor responde entonces a la luz fluorescente visible. Cuando el nivel de luz fluorescente recibido (mostrado en el indicador de contraste) alcanza un nivel de "4" o superior, los transistores de salida NPN y PNP cambiarán al estado opuesto. </p>

