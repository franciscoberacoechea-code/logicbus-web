    <p><b>C&oacute;mo funciona:</b><br></p>
    <ol>
      <li style="color: black;">Dos celdas de carga autoclavable se instalan en línea con los cables controlando el endoscopio.</li>
      <li style="color: black;">A medida que se mueve el endoscopio, las celdas de carga miden la fuerza requerida para mover el cabezal.</li>
      <li style="color: black;">La medición de fuerza se lee en el controlador del endoscopio permitiendo generar la retroalimentación apropiada para que el operador pueda realizar ajustes.</li>
      <li style="color: black;">La celda de carga se diseñan para soportar alta presión, temperatura y PH aparte de los medios que requiere la esterilización para llegar a estándares ISO/TC 198 y los IP69K.</li>
