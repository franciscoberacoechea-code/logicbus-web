<p align="justify"> 
El convertidor USB a interfaz serial aislado ofrece la facilidad de conectar dos dispositivo seriales a un puerto USB. Cada puerto serial DB9 macho puede ser configurado para RS-232, RS-422 o RS-485 por medio de dip switches accesibles a través de la cubierta. No hay necesidad de abrir el chasis, con esto se simplifica el servicio y la instalación en campo. El aislamiento óptico ayuda a prevenir daños causados por sobrecargas y lazos de tierra comúnmente encontrados en ambientes industriales. Cada puerto serial incluye LEDs que muestran la actividad de transmisión y recepción. Soporta una tasa de transmisión de datos de hasta 921.6 kbps.<br><br>
Los drivers y utilidades del software USB SeaCOM facilitan la instalación y operación utilizando los sistemas operativos Windows 98SE, ME, 2000, XP y Vista. Después de instalar el software, simplemente conecta el convertidor serial 2213 a tu puerto USB. El dispositivo inmediatamente es reconocido por el sistema mostrando ambos puertos seriales como puertos COM estándar, habilitando la compatibilidad con cualquier software. El convertidor 2213 se alimenta del bus USB, eliminando la necesidad de una fuente de poder externa.<br><br>
El convertidor 2213 tiene integrado un candado en el puerto USB el cual es completamente compatible con los cables USB estándar, al utilizar el cable USB que incluye el tornillo metálico de ajuste manual se provee una conexión segura al dispositivo y previene desconexiones de cables por accidente.</p><br>

