          <p align="justify"><strong>El módulo de adquisición de datos de entrada analógica universal de 8 canales admite entrada de corriente, entrada de tensión y entrada de termopar. Transmisible por protocolo Modbus RTU, RS-485 y DCON. Viene con el software gratuito EZ Data Logger para el registro de datos. </strong></p><br>
          <br>

          <p align="justify"> 
            El I-7019R es un módulo de entrada analógica que incluye 8 canales diferenciales de entrada analógica. La entrada de tensión, corriente o termopar se puede seleccionar para todos los canales de entrada analógica a través de un puente y cada canal se puede configurar para un rango individual. El rango de entrada de tensión puede ser de ± 15 mV a 10 V, el rango de entrada actual puede ser +4 a +20 mA, 0 a +20 mA, o ± 20 mA, y tipos J, K, T, E, R , S, B, N, C, L, M, LDIN43710 se puede utilizar para la entrada del termopar. Se pueden conectar hasta 8 tipos diferentes de entradas analógicas a un solo módulo. Se proporciona protección contra sobretensiones de hasta 240 Vrms. El módulo también presenta detección de cable abierto por canal para el termopar y tipos de entrada de +4 a +20 mA, y proporciona protección ESD de 4 kV así como aislamiento intramódulo de 3000 VDC. El M-7019R admite los protocolos Modbus RTU y DCON, que se pueden configurar a través del software, y todas las especificaciones de hardware son las mismas que las de la I-7019R.</p><BR>

          <strong>Características:</strong>
          <ul>
            <li>Entrada analógica universal de 8 canales</li>
            <li>Protección de sobretensión 240 Vrms</li>
            <li>Configuración individual del canal</li>
            <li>Puente seleccionable de entrada de voltaje, corriente o termopar</li>
            <li>Detección abierta de termopar</li>
            <li>Protección contra ESD de 4 kV</li>
            <li>Aislamiento intramódulo de 3000 VDC</li>
            <li>Dual Watchdog</li>
            <li>Amplio rango de temperatura de funcionamiento: -25 a + 75 ° C</li>
          </ul>

