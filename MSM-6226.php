<p>MSM-6226, 24 Fast Ethernet + 2 Gigabit L2 Managed Switch, implementado 24 10 / 100Mbps TP + 2 puertos de medios Gigabit dual con TP / SFP (o GBIC), es un conmutador estándar que cumple con todos los requisitos de IEEE 802.3 / u / x / z Gigabit, Fast Ethernet y especificaciones de Ethernet. El conmutador se puede gestionar a través del puerto serie RS-232 a través de una conexión directa o a través del puerto Ethernet que utiliza Telnet o la unidad de gestión basada en la web, asociada con el agente SNMP. Con el agente SNMP, el administrador de la red puede iniciar sesión en el switch para monitorear, configurar y controlar cada actividad portuaria de forma amigable. La administración general de la red se mejora y la eficiencia de la red también se mejora para acomodar aplicaciones de gran ancho de banda. Además, el conmutador cuenta con funciones integrales y útiles, como DHCP Option 82, QoS (Quality of Service), Spanning Tree, VLAN, Port Trunking, Bandwidth Control, La seguridad de puerto, SNMP / RMON e IGMPv3 Snooping capacidad a través del software inteligente. Es adecuado tanto para Metro-LAN como para aplicaciones de oficina. Otros, el aumento del interruptor admiten el ahorro de energía para reducir el consumo de energía con la técnica de administración de energía. Podría ahorrar eficientemente la energía del interruptor con la detección automática del tiempo de inactividad del cliente y del cable para proporcionar una potencia diferente.</p><BR>

<strong>Caracteristicas</strong>

<ul>
<li>2 medios dobles para la conexión de fibra flexible</li>
<li>Port Mirroring ayuda al supervisor a monitorear la red</li>
