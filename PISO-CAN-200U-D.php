<p>El PISO-CAN200U puede representar una solución económica de una placa CAN activa con bus PCI universal. Tiene 2 puertos de comunicación de bus CAN independientes con conector de terminal de tornillo de 5 pines o conector D-sub macho de 9 pines, y tiene la capacidad de cubrir una amplia gama de aplicaciones CAN. Además, PISO-CAN200U utiliza el nuevo controlador CAN Phillips SJA1000T y el transceptor 82C250, que proporcionan arbitraje de bus, detección de errores con corrección automática y función de retransmisión. Se puede instalar tanto en una ranura PCI de 3,3 V como de 5 V y es verdaderamente compatible con "Plug & Play"</p><BR>

<strong>Aplicaciones:</strong>
<ul>
<li>Aplicación de comunicación CAN bus.</li>
<li>Aplicación de protocolo DeviceNet, CANopen, CAN J1939, SDS (red amplia de sistema).</li>
<li>Sistema de control</li>
<li>Automatización de edificios</li>
<li>Automatización industrial</li>
<li>Adquisición de datos distribuidos.</li>
</ul><br>

<strong>Caracteristicas:</strong>
<ul>
<li>Compatible con CAN 2.0 partes A y B</li>
<li>Totalmente compatible con el estándar ISO 11898-2</li>
<li>Soporte CAN bardo desde 10 kbps ~ 1 Mbps</li>
<li>Aislamiento de pareja de fotos de 2500 Vrms en el bus CAN</li>
<li>Universal PCI admite buses PCI de 5 V y 3,3 V</li>
<li>Puente incorporado para seleccionar resistencia terminal de 120 O</li>
<li>Aislamiento galvánico de 3 kV</li>
<li>2 canales CAN independientes</li>
<li>Mapeo de memoria directa al controlador CAN</li>
<li>Proporcionar demos de VB6.0, VC ++ 6.0, Delphi, BCB6.0</li>
<li>Controlador LabView / DASYLab</li>
<li>Controlador compatible con Windows 98 / ME / NT / 2K / XP / 7dos.</li>
</ul>
