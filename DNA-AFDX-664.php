      <td colspan="2"><div align="justify">The DNA-AFDX-664 is a 2 channel AFDX/ARINC 664 (including the Boeing EDE protocol) communications interface for &ldquo;Cube&rdquo; I/O chassis. The board may be configured as two independent channels or one dual redundant channel. The network implementation fully supports 10, 100 and 1000 BASE-T speeds. The channels may operate as a receiver, transmitter or network/bus monitor.<br>
          <br>
          In input mode, the user may time tag inputs with resolutions as low as 10 microseconds. The input automatically provides error/integrity checking, though this feature may be disabled if the application requires. Receive filtering is also supported based on the VL, Port and error detection.<br>
            The Monitor mode allows the user to capture all network traffic, or may be set with automatic filtering so only the desired information is captured. The Monitor mode will also gather a variety of statistics from the bus/network. If desired, the monitor mode may be set to capture all UDP network traffic, regardless of whether it is configured based on the AFDX/664 protocol.<br>
            <br>
            Transmit channels automatically configure traffic shape via Bandwidth Allocation Gaps (BAG) with 1, 2, 4, 8, 16, 32, 64 or 128 mS timing. Transmission may be based on an automatic scheduler, or in a one-shot asynchronous mode. Both Uni-cast and Multicast VLs are fully supported. The board is designed to inject various errors if desired, including logical, timing and AFDX protocol errors. The transmitter will generate consecutive Sequence Numbers or they may be user-defined.
          
