<center><strong>Trajeta PCI express, proporciona 32 canales de entrada análoga simples o 16 diferenciales, 12 bit de resolución a una velocidad de muestreo máxima de 110kS/s, cuenta con 16 canales de entradas digitales y 16 canales de salida digital, 3 contadores/temporizadores, ganancia programable de 1, 2, 4, 8, rango de entrada de +/-10V, +/-5V, +/-2.5V, +/-1.25V.</strong></center><br>


<p>Las tarjetas PCI-1002LU / HU y PEX-1002LH son el producto de nueva generación que ICP DAS proporciona para cumplir con los requisitos de cumplimiento de RoHS y está diseñado como completamente compatible con PCI-1002L / H. Los usuarios pueden reemplazar el PCI-1002L / H por el PCI-1002LU / HU y PEX-1002L / H directamente sin modificación de software / controlador.<br>

La PCI-1002LU / HU admite bus PCI de 3,3 V / 5 V, mientras que la PEX-1002L / H es compatible con el bus PCI Express. Estas tarjetas son una familia de tarjetas A / D y presentan entradas analógicas de baja ganancia de 110 kS / s o de 44 kS / s de alta ganancia. Proporciona 32 entradas analógicas unipolares o 16 diferenciales de 12 bits, 16 entradas digitales y 16 canales de salida digital.<br>

El PEX-1002L / H también agrega un interruptor de identificación de tarjeta a bordo. Los usuarios pueden configurar la identificación de la tarjeta en una pizarra y reconocer la placa mediante la identificación a través del software cuando usan dos o más tarjetas PEX-1002L / H en una computadora. El PCI-1002LU / HU y el PEX-1002L / H brindan Los resistencias pull-high / pull-low permiten especificar el estado DI cuando los canales DI están desconectados; el estado de DI permanecerá en estado alto o bajo que no sea flotante.<br>

Estas tarjetas admiten varios sistemas operativos, como Linux, DOS, Windows 98 / NT / 2000 y Windows 7 / Vista / XP de 32/64 bits. El control DLL y Active X junto con varios programas de muestra de lenguaje basados ??en Turbo C ++, Borland C ++, Microsoft C ++, Visual C ++, Borland Delphi, Borland C ++ Builder, Visual Basic, C # .NET, Visual Basic.NET y LabVIEW se proporcionan con el fin de ayudar a los usuarios a desarrollar rápida y fácilmente sus propias aplicaciones.
</p><BR><br>

<strong>Caracteristicas</strong>

<ul>
<li>Conversor AD de alta velocidad de 12 bits, 100 kS / s.</li>
<li>32 entradas diferenciales single-ended / 16.</li>
<li>El máximo. la velocidad de muestreo es de baja ganancia de 110 kS / s o de alta ganancia de 44 kS / s.</li>
<li>PCI-1002LU / PEX-1002L: baja ganancia programable: 1, 2, 4, 8.</li>
<li>PCI-1002HU / PEX-1002H: alta ganancia programable: 1, 10, 100, 1000.</li>
<li>16 canales de entrada digital / 16 canales de salida digital.</li>
<li>Disparador interno / externo.</li>
<li>Tablero de tamaño medio.</li>
<li>El puerto de entrada digital se puede configurar para jalar alto o jalar bajo.</li>
<li>[PEX-1002L / H]</li>
<li>Admite PCI Express x1</li>
<li>Admite ID de tarjeta (conmutador SMD)</li>
<li>[PCI-1002LU / HU]</li>
<li>Tarjeta PCI universal, admite el bus PCI +5 V y +3.3 V.</li>
</ul><br>

<strong>Aplicaciones</strong>
