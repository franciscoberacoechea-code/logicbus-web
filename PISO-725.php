<center><strong>Salida de relé de 8 canales y placa de entrada digital aislada de 8 canales. Incluye conector D-Sub CA-4002.</strong></center><br>


<p>El PISO-725 es una tarjeta de interfaz de entrada / salida digital de 16 canales para computadoras de bus PCI. Se puede instalar en una ranura PCI de 5 V y admite el verdadero "Plug & Play" para obtener automáticamente recursos de E / S. El PISO-725 tiene un solo conector DB-37 y proporciona 8 salidas de relé electromecánicas y 8 entradas digitales aisladas / no aisladas. Las entradas digitales se pueden configurar como aisladas o no aisladas a través de un puente de hardware. Cada una de las entradas digitales generará una señal de interrupción si se cambia el estado, lo cual es muy útil cuando se monitorean los cierres / aperturas de contacto ya que no es necesario sondear continuamente las entradas. Los canales DI aislados utilizan una ruta de transmisión óptica corta para transferir una señal electrónica entre los elementos de un circuito y mantenerlos aislados eléctricamente. Con una protección de aislamiento de 3750 Vrms, estos canales DI permiten que las señales de entrada floten por completo para evitar bucles de tierra y aislar la computadora host de daños en los voltajes. Los relés se utilizan donde es necesario controlar un circuito utilizando una señal de baja potencia (con aislamiento eléctrico completo entre el control y los circuitos controlados), o donde varios circuitos deben ser controlados por una señal. Todos los relevadores se desactivan (desactivan) mientras se encienden y se lee el estado de encendido / apagado. El PISO-725 se puede utilizar en diversas aplicaciones, incluido el cierre de contacto, detección de voltaje externo, detección de carga y control de E / S. <br><br>
El PISO-725 es compatible con varias versiones del sistema operativo, como Linux, DOS, Windows 98 / NT / 2000 y Windows 7 / Vista / XP de 32/64 bits. El control DLL y Active X junto con varios programas de muestra de lenguaje basados ??en Turbo C ++, Borland C ++, Microsoft C ++, Visual C ++, Borland Delphi, Borland C ++ Builder, Visual Basic, C # .NET, Visual Basic.NET y LabVIEW se proporcionan para ayudar a los usuarios a desarrollar rápida y fácilmente sus propias aplicaciones.
</p><BR><br>

<strong>Caracteristicas</strong>

<ul>
<li>Bus PCI</li>
<li>Interrupción modificada por estado para todas las entradas digitales</li>
<li>Entradas digitales aisladas o no aisladas seleccionables por puente</li>
<li>8 salidas de relés electromecánicos (Forma C x4, Forma A x4)</li>
<li>Protección de aislamiento de imagen 3750 Vrms</li>
<li>Admite el estado de la salida del relé read read</li>
<li>LED para indicar el estado de salida</li>
<li>Un conector DB-37 para entrada y salida</li>
<li>Admite Plug & Play para obtener recursos de E / S</li>
<li>Ya no es necesario configurar manualmente la dirección de E / S y la IRQ</li>
</ul><br>

