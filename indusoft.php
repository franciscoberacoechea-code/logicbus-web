<li>Integración empresarial: conéctese fácilmente a ERP y sistemas de "back-office" utilizando conectividad de base de datos relacional incorporada</li>
<li>Reduzca el tiempo de inactividad: use tecnologías abiertas (ActiveX, .NET) para visualizar documentación, reparar videos o mensajes de audio</li>
