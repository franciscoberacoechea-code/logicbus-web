<center><strong>Módulo de 8 canales de salida de relevador FotoMOS tipo Form A.</strong></center><br>

<p style="text-align: justify;">Tanto el I-87069W como el I-87069PW cuentan con ocho canales de salida de retransmisión PhotoMOS. En comparación con los relés electromecánicos, los relés PhotoMOS proporcionan un tiempo de respuesta más rápido, mayor resistencia eléctrica, mayor vibración y resistencia a los golpes. Tampoco hay arcos, sin rebote y sin ruido de conmutación para el relé PhotoMOS. Existen opciones para configurar valores de encendido y salida digital seguros, y tanto el I-87069W como el I-87069PW incluyen ocho indicadores LED que se utilizan para mostrar el estado del canal y para proporcionar una protección de ESD de 4 kV.</p><br>


<strong>Caracteristicas:</strong>
<ul>
<li>8 salidas de relé PhotoMos</li>
<li>Protección contra ESD de 4 kV</li>
<li>Sin arcos, sin rebote y sin ruido de conmutación</li>
<li>Aislamiento de fotoacoplamiento</li>
<li>Embedded Dual Watchdog</li>
<li>Configuración del valor de encendido</li>
<li>Configuración de valores seguros</li>
<li>Amplio rango de temperaturas de funcionamiento: -25 ~ +75 ° C</li>
</ul>


