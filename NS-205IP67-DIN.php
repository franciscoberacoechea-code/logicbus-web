<p>Los conmutadores Ethernet NS-205-IP67 están diseñados para su uso en entornos industriales a prueba de agua / severos. El embalaje robusto y los conectores IP67 garantizan una protección total que puede soportar una variedad de condiciones extremas, tales como: altas temperaturas, golpes y vibraciones extremas, partículas de polvo e incluso inmersión en líquido. Se pueden montar directamente en cualquier máquina o conveniente superficie plana. Con todas sus características robustas, el conmutador sigue ofreciendo un alto nivel de funcionalidad, incluida la capacidad de admitir comunicaciones de dúplex completo y velocidades de transmisión de 10 Mbps / 100 Mbps. Con 1.4 Gbps de ancho de banda total, el conmutador puede manejar simultáneamente la comunicación de velocidad de cable completo en cada puerto. Un puerto de enlace ascendente dedicado permite la conexión a otros conmutadores sin el uso de un cable cruzado. No es necesaria la programación, como el interruptor aprende automáticamente las direcciones de red. La entrada de energía aislada de 10 a 30 V CC evita que los picos y las sobretensiones en la línea de alimentación dañen la fuente de alimentación. Están completamente enchufados y listos para salir de la caja.</p><br><br>

