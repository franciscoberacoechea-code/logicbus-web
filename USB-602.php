            <p style="Text-align:justify;margin:auto;">Registrador de datos con pantalla gráfica LCD, mide y almacena hasta 256,000 lecturas de temperatura
            (-30 °C a 80 °C, precisión 0.1 °C) y humedad (0 a 100% HR, precisión 0.1% HR). Alarmas audibles
            programables. Carcasa con protección IP67 / NEMA 4X. Incluye 2 pilas 1/2 AA, clip para montaje y cable micro
            USB</p><br>
