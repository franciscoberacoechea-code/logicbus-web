            <div align="center">
                <h2 class="subtitle blue">SENSORES FOTOELÉCTRICOS</h2>
            </div><br>
            <p align="justify"><a href="sensores-fotoelectricos">El sensor fotoeléctrico</a>, también llamados óptico, basa su funcionamiento en la emisión de un haz de luz que es interrumpido o reflejado por el objeto a detectar. En otras palabras detectan la presencia de un objeto por medio de un haz de luz. Tienen muchas aplicaciones en al ámbito industrial y son ampliamente utilizados. Típicamente están compuestos por una fuente de luz, un receptor de luz, dispositivos ópticos para guiar el haz de luz (lentes) y un circuito de salida.
            </p>
            <p align="justify"> Estos sensores fotoeléctricos, por ejemplo son como <b>“ojos artificiales”</b>, sin los cuales las técnicas de automatización seria hoy en día indispensables. Se utilizan siempre que se necesita una detección fiable y sin contacto de la posición exacta del objeto. Para ello, el materia de los objetos que se requieren detectar carece de importancia, dentro de la comparación con los detectores inductivos, los sensores fotoeléctricos disponen un alcance mucho más amplio.
            </p>

