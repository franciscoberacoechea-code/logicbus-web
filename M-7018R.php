          <center><strong>Módulo de adquisición de datos de entrada analógica de 8 canales. Soporta los tipos de entrada de corriente de 20 mA +/- (requiere opcional 125 ohmios resistencia externa), tipos de entrada de voltaje: +/- 15 mV, 50 mV +/- +/- 100 mV, +/- 500 mV, +/- 1V, +/- Entrada de 2.5V y termopar Tipos J, K, T, E, R, S, B, N y C. </strong></center><br>
