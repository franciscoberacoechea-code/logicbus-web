<p>PWM (modulación por ancho de pulso) es una poderosa técnica para controlar circuitos analógicos. Utiliza salidas digitales para generar una forma de onda con variante de ciclo de trabajo y frecuencia para controlar circuitos analógicos. CAN-2088C es un módulo esclavo PWM del protocolo <a href="convertidores_info#CAN">CANopen</a>. Tiene 8 canales de salida PWM y 8 canales de contador de alta velocidad. Se puede usar para desarrollar un sistema de control analógico potente y rentable.</p>
