<p align="justify">Diseñado utilizando el chip A/D de aproximación sucesiva Maxim MAX197, el SeaI/O-470E proporciona ocho entradas diferenciales o 16 de un solo extremo de 12 bits y dos canales de salida D/A de 12 bits. Las entradas A/D son seleccionables por software para rangos de 0-5V, 0-10V, +/-5V y +/-10V y cada canal se puede configurar mediante hardware para medir un bucle de corriente de 4-20mA. Los dos canales D/A de 12 bits se pueden seleccionar mediante puentes para rangos de salida de 0-5V y 0-10V.
<br><br>
Además, el módulo SeaI/O-470E proporciona ocho entradas aisladas ópticamente clasificadas para 5-30V DC y cuentan con aislamiento externo de 300V, mientras que ocho salidas de colector abierto pueden absorber hasta 580mA, ideal para conmutar dispositivos de 24V que se encuentran comúnmente en entornos industriales. Perfecto para una variedad de aplicaciones de adquisición/control de datos y de prueba y medición, el SeaI/O-470E incluye terminales de tornillo extraíbles, que simplifican las conexiones de cableado de campo. El SeaI/O-470E recibe alimentación de su fuente de 9-30V DC, o seleccione entre una variedad de opciones de fuente de alimentación Sealevel.
<br><br>
Comuníquese con el SeaI/O-470E usando el protocolo Modbus TCP estándar de la industria o use las bibliotecas de software Sealevel SeaMAX API de su programa de aplicación. Los controladores y las utilidades del <strong><a href="software-seamax" target="_blank">software SeaMAX </a></strong> de Sealevel facilitan la instalación y el funcionamiento con los sistemas operativos Microsoft Windows 10 y 8.
<br><br>
La aplicación Sealevel Modbus Connect para iOS le permite acceder a los registros, bobinas y E/S discretas de sus dispositivos Sealevel Modbus y está disponible en la App Store. Utilice la aplicación para acceder de forma remota a E/S en el campo o para realizar pruebas y solucionar problemas durante el desarrollo de la aplicación.
<br><br>
Amplíe su red de E/S con los productos de la serie SeaI/O N. Los módulos SeaI/O están disponibles con relés Reed y Forma C , entradas ópticamente aisladas, interfaces TTL , funcionalidad A/D y D/A. Se pueden agregar hasta 246 módulos de expansión adicionales utilizando conectores de paso convenientes. 
