<center><strong>Controlador Ethernet incorporado en rack: flash 256/512K, 256/512k SRAM, conexión 10BaseT, sistema operativo MiniOS7. Disponible en 4 y 8 ranuras de capacidad (4 x ranura: 256k/256k).</strong></center><br>


<p>La I-8430 y la I-8830 son unidades de E/S Ethernet integradas que utilizan el protocolo DCON Firmware. ICPDAS proporciona varios módulos de E/S, como entrada/salida analógica, entrada/salida digital y módulos de contador/frecuencia, que se pueden utilizar en aplicaciones remotas de adquisición y control de datos para monitoreo de ambiente, administración de energía y automatización de fábrica, etc. a través de puerto Ethernet o puerto RS-232.<br> 

La CPU es un 80188 de 8 bits (40MHz). Además de las funciones originales (entrada, salida, valor de encendido, valor seguro, valor límite alto, valor límite bajo) del módulo de E/S, el firmware proporciona funciones adicionales para permitir que los módulos de E/S en diferentes ranuras se combinen juntos . Por ejemplo, si el valor del canal de un módulo AI está por encima de un valor límite alto predefinido, o por debajo de un valor límite inferior predefinido, la información se puede pasar inmediatamente a otro módulo DO para activar la alarma o la luz.
Se proporcionan varios kits de desarrollo de software (SDK) y demos, como DLL, ActiveX, controlador Labview, controlador de Indusoft, controlador de Linux, servidor OPC, etc.<br>

Aunque todos los controladores SDK admiten solo la interfaz del puerto COM, los usuarios también pueden usar el SDK instalando la utilidad VxComm. La utilidad VxComm puede crear un puerto COM virtual para mapear el puerto Ethernet, luego los módulos de E/S se pueden agregar fácilmente a la I-8430/I-8830 y se pueden integrar rápidamente en un sistema existente.
</p><BR><br>


