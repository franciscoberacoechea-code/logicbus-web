<p>El LBS312XX controlador remoto de la serie GSM GPRS, es marcador universal GSM, así como un control remoto GSM GPRS y unidad de alarma. Proporciona múltiples salidas digitales de relevador(120VAC/3A, 24VDC 3A,), hasta 6 entradas digitales (Opto-aislado, contacto activo, 3~24VDC, completamente aislado). Puede ser usado como contador de pulso de salida, 2 salidas de temperatura para DS18B20, entrada analógica múltiple (ambos de 0-20mA y 0-5V, resolución de 12 bits), puerto RS485 (Soporta Protocolo Modbus RTU, más protocolos pueden ser agregados de acuerdo a los requerimientos de la aplicación) Puerto serie RS232 y un puerto USB reservado para configuración y descarga de actualización de firmware desde el sitio por el usuario. Permite monitorear y controlar una alarma, estaciones remotas, equipos o máquinas a través de SMS o GPRS. Puede transmitir datos desde el aparato (termómetro, medidor de humedad, medidor eléctrico, flujo metro, PLC) al usuario o centro de monitoreo por GPRS.</p>

<strong>Caracter&iacute;sticas:</strong>
<ul>
<li>Modulo GPRS Siemens MC55i de cuatro bandas y procesador de alta densidad y rendimiento linea ARM 32 bits MCU incluido</li>
<li>Tunel transparente de datos seriales utilizando la red de bajo costo SMS/GPRS network</li>
<li>Envia datos v&iacute;a GPRS o SMS en tiempos programados o cuando ocurra algun evento</li>
<li>Conexión directa a la red de GSM GPRS</li>
<li>Configuración remota mediante mensajes SMS o GPRS; </li>
<li>Soporta nombres de dominio dinámico o la dirección IP estática;</li>
<li>Soporta los protocolos SMS, GPRS UDP y TCP;</li>
<li>Soporta el protocolo Modbus RTU;</li>
<li>1 puerto USB y 1 Puerto serial RS485 </li>
</ul>

