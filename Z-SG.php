<div align="center">
  <strong>El <a href='https://tienda.logicbus.com.mx/Z-SG_p_4195.html'>Z-SG</a> es un acondicionador de celdas de carga  (4 o 6 hilos) con salida analoga de voltaje o corriente y comunicacion Modbus RTU.
 <br><br>
Su entrada y salida puede ser configurable mediante su puerto RS-232 y software gratuito. Este equipo tiene una entrada seleccionable para leer de 1 a 64mV/V y salida seleccionable de 0 a 20mA, 4 a 20mA o 0 a 10Vdc, 0 a 5Vdc.</strong>
</div><br><br>



<strong>Caracteristicas</strong>
<ul>
<li>Para celdas de carga de 4 o 6  hilos</li>
<li>Salida de excitacion de 5Vdc</li>
<li>Resolucion de 24bits</li>
<li>Entrada/Salida analoga configurable por software</li>
<li>Puerto RS-232 para configuracion (Requiere cable modelo PM001600)</li>
<li>Configuracion de Tara con boton externo</li>
<li>Frecuencia de muestreo de 12.53Hz a 151.71Hz</li>
<li>Se alimenta de 10 a 40Vdc o 19 a 28Vac</li>
<li>Proteccion contra descarga electroestatica de hasta 4Kv</li>
<li>Aislamiento entre comunicacion, fuente de poder y salida analoga de 1500 Vac</li>
<li>Montaje en riel DIN</li>
</ul>
