<center><strong>Módulo de adquisición de datos de entrada de alta tensión y entrada analógica de 8 canales transmisible sobre Modbus RTU y RS-485. Admite tipos de entrada +/- 50V y +/- 150V DC. Admite temperaturas de funcionamiento entre -25 a 75 ° C.</strong></center><br>
 <br>

<p> 
El I-7017R es un módulo de entrada analógica de 8 canales con un mecanismo de protección de muy alta calidad donde la protección contra sobretensión es de 240 Vrms. El tipo de entrada incluye voltaje y corriente. La I-7017R es una versión mejorada de la I-7017, con la única diferencia de que la I-7017R es mucho más adecuada para entornos críticamente severos. La frecuencia de muestreo de la I-7017R es ajustable, lo que significa que se puede seleccionar el modo rápido o el modo normal. La I-7017R también tiene una protección ESD de 4 kV así como un aislamiento intramódulo de 3000 VDC. El I-7017R-A5 es un módulo de entrada analógica de 8 canales especialmente diseñado para la entrada de alta tensión, y tiene un rango de entrada de entre -50 V ~ +50 V o -150 V ~ +150 V. El M-7017R y el M-7017R-A5 tiene las mismas especificaciones que el I-7017R y el I-7017R-A5, pero proporciona soporte adicional para el protocolo Modbus RTU y el protocolo DCON.
</p><BR>

<strong>Caracteristicas:</strong>
<ul>
<LI>Entrada de alto voltaje</LI>
<LI>Tasa de muestreo ajustable</LI>
