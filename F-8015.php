<center><strong>Módulo de entrada RTD de 8 canales (cubierta gris) (RoHS).</strong></center><br>

<p>El F-8015 es un módulo de entrada RTD de 16 bits y 8 canales que presenta un rango de entrada programable en todos los canales. Este módulo tiene una precisión de ± 0.05% para una aplicación altamente precisa. Además, el F-8015 proporciona aislamiento óptico de 3000VDC entre canales y bus de fondo. Si algún alto voltaje o corriente daña estos canales, este módulo no afectará a otros componentes en el sistema iDCS-8000.</p>

Caracteristicas:
<ul>
<li>8 canales de entrada RTD.</li>
<li>Escala up / down definida por el usuario.</li>
<li>Detección de cable abierto.</li>
<li>Conformidad con la RoHS.</li>
<li>Aislamiento de 3000 VDC desde la entrada al plano posterior.</li>
<li>Aislamiento de 3000 VDC desde la entrada al suelo del bastidor.</li>
<li>Redundancia.</li>
<li>Tiempo de conmutación redundante rápido (< 100us).</li>
</ul>
