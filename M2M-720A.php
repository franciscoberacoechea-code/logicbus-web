<p>M2M-720A es un módulo especialmente diseñado para una solución de mantenimiento remoto con flujo de voz.  Este módulo ofrece 2 principales tecnologías sobre red: flujo de voz y conexión a par.  La conexión a par significa que el usuario puede operar un dispositivo de puerto COM remoto vía Ethernet con el protocolo TCP/IP como si fuera un puerto COM local y el flujo de voz significa que el usuario puede hablar a un operador remoto mientras se operan dispositivos COM de manera remota. <br><br>
Además, M2M-720A integra la tecnología Virtual COM.  Esto puede resolver la insuficiencia de un puerto COM real en la PC.  Aplicando esta tecnología, el ingeniero de mantenimiento puede realizar el monitoreo y mantenimiento de manera remota sin imporar tiempo y lugar.</p>

