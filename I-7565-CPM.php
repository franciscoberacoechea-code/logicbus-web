<p>El I-7565-CPM se desarrolló como una red CANopen estandarizada con capacidades de configuración altamente flexibles. Es una solución maestra CANopen de interfaz USB, y tiene una CPU 186 MHz de 80 MHz. Hay un intérprete de protocolo CANopen, firmware I-7565-CPM, que se ejecuta en el I-7565-CPM. El usuario puede usar este convertidor para procesar el protocolo CANopen sin aumentar mucho la carga de la PC. Las API enriquecidas de la biblioteca I-7565-CPM y la herramienta de utilidad fácil de usar pueden satisfacer los requisitos de una variedad y aplicaciones CANopen complejas.

</p>

<strong>Caracteristicas:</strong>
<ul>
<li>NMT: Maestro</li>
<li>Versión CANopen: DS-301 v4.02</li>
<li>Control de errores: protocolo de protección de nodos</li>
<li>Permiten recepciones EMCY</li>
<li>Proporciona funciones PDO dinámicas</li>
<li>Soporte de protocolo SYNC</li>
<li>Se admiten varios tipos de transmisión de PDO</li>
<li>Soporte de SDO para descargar / cargar el protocolo de segmento</li>
<li>Proporciona la velocidad en baudios estándar de CANopen</li>
<li>Indicador LED PWR, ACT, ERR y Tx / Rx</li>
<li>Permite max. 10 esclavos CANopen</li>
</ul>

