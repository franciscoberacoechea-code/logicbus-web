<p>La W WinCON-8337 aprovecha al máximo ICS Triplex <a href="isagraf">ISaGRAF</a> de IEC-1131 compatibles con la suite de desarrollo. Con una WinCON ISaGRAF equipadas, los usuarios pueden cómodamente integrar los programas desarrollados en cualquiera de las normas IEC-61131-3, que incluye: diagrama de función secuencial, diagrama de bloques de funciones, texto estructurado, lista de instrucciones, esquema de mando, y el diagrama de flujo. Los usuarios ISaGRAF también se benefician de un conjunto ampliado de las capacidades específicas de WinCON, permitido exclusivamente por el tiempo de ejecución ISaGRAF.<br><br>
 
La plataforma W-8000 cuenta con varias configuraciones de software de gran alcance, permitiendo a los usuarios maximizar la productividad, mientras que mantiene la cómoda familiaridad de los protocolos de comunicación estándar de la industria y sistemas operativos. Con una larga relación con Microsoft y Red Hat Linux, los usuarios W-8000 PAC tienen la libertad de elegir no sólo su entorno operativo estándar, sino también la flexibilidad para dictar tanto su lógica y tiempos de ejecución HMI. Los usuarios se benefician de estos entornos de desarrollo familiares como: Microsoft Embedded Visual C + +, Visual Basic NET y Visual C # para desarrollar sus aplicaciones. Al ofrecer un completo software, SDK, Wincon de servicios públicos y empresas de servicios públicos WinConOPC Sever, el tiempo de desarrollo se reduce drásticamente.<br><br>

El MCU (unidad de control principal) de Wincon-8337 es el motor de la W-8337. Cada MCU cuenta con un Módulo Procesador Central (CPM) y una fuente de alimentación de amplio rango. El CPM es un potente motor de procesamiento integrado que incluye una CPU, el interior 32M bytes de memoria flash y 64MB SDRAM bytes. El CPM ofrece un medio adicional de memoria Compact Flash tipo de formato II.El puerto Ethernet es también parte de la configuración básica. La CPM está equipado con el interfaz de PC: PS / 2 (teclado y ratón), puerto VGA y un puerto USB. Además de sistemas de interfaces o conexiones de bus de campo, tales como Modbus / TCP y CANopen DeviceNet / están disponibles en el MCU básicos de Wincon.</p>
	
