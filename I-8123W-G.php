<p align="justify">El I-8123W sigue la especificación CiA CANopen DS-301 V4.02. Es un maestro CANopen de alto precio / rendimiento. Con la MCU de la serie ViewPAC o WinPAC (unidad de control principal), se puede aplicar generalmente en la automatización industrial, la automatización de edificios, el vehículo y la red de control integrado.<br><br>
Además, debido a la característica de crear el firmware del protocolo CANopen en su interior, los usuarios pueden acceder fácilmente a los dispositivos esclavos a través de I-8123W sin estudiar o manejar el complejo protocolo CANopen. Es útil reducir el tiempo del ciclo de desarrollo y permitir a los usuarios configurar su aplicación CANopen más rápida y fácilmente.</p>

<strong>Características:</strong>
<ul>
<li>NMT Master.</li>
<li>Versión CANopen: DS-301 V4.02.</li>
<li>Soporte Node Guarding y Heartbeat Consumer.</li>
<li>control de errores protocolo.</li>
<li>Proporcionar interrupción de control de error EMCY y NMT.</li>
<li>función de servicio.</li>
<li>Proporcionar "modo de escucha maestra".</li>
<li>Proporcionar Dynamic PDO, acíclico y cíclico.</li>
<li>transmisión.</li>
<li>Soporta la MCU de la serie ViewPAC y WinPAC.</li>
</ul>

