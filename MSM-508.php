<center><strong>Conmutador gestionado Industrial Ethernet 10/100 Base-T de 8 puertos con caja de metal.</strong></center><br>


<p>El MSM-508 es un conmutador gestionado de capa 2 Ethernet Industrial (10 / 100Base-TX) de 8 puertos. MSM-508 admite la función de autonegociación 10/100 M y la función MDI / MDI-X automática. Puede cambiar automáticamente la velocidad de transmisión (10 Mbps o 100 Mbps) para las conexiones correspondientes. Los conectores del puerto Ethernet están blindados RJ-45. Los conectores blindados RJ-45 ofrecen un entorno Ethernet de alta confiabilidad para control industrial y automatización. <br><br>

Se puede gestionar a través del puerto RS-232 a través de una consola serie o un puerto Ethernet mediante telnet o navegador web. Además, el conmutador admite muchas funciones gestionadas potentes, como la VLAN basada en etiquetas 802.1Q, la VLAN basada en puertos, la QoS 802.1p (calidad de servicio), la interconexión de puertos, el árbol de expansión, las pruebas de cables y la duplicación de puertos. Las técnicas integradas ICP DAS Cyber-Ring permiten colocar múltiples interruptores en un anillo redundante. El conmutador detecta y se recupera de una falla de enlace de fibra o cobre dentro de aproximadamente 50 ms, para la mayoría de las aplicaciones un proceso sin interrupciones. Compatible con Modbus / TCP, Modbus / RTU y OPC, la aplicación SCADA puede monitorear el estado del puerto Ethernet con protocolo Modbus o OPC. <br><br>

MSM-508 proporciona dos entradas de alimentación que se pueden conectar simultáneamente a fuentes de alimentación de CC en vivo. Si una de las entradas de alimentación falla, la otra fuente en vivo actúa como una copia de seguridad para admitir automáticamente las necesidades de energía del MSM-508. Y, la facilidad de salida de retransmisión puede entregar una señal de advertencia mientras falla la alimentación dual o el enlace de red..</p><BR>

<strong>Caracteristicas</strong>

<ul>
<li>Crossover automático MDI / MDI-X para plug-and-play.</li>
<li>Cada puerto admite una negociación automática de velocidad de 10/100 Mbps.</li>
<li>Arquitectura de almacenamiento y reenvío.</li>
<li>Control de flujo de contrapresión Full Duplex IEEE 802.3xy semidúplex.</li>
<li>Ancho de banda de memoria de alto rendimiento de 3.2Gbps.</li>
<li>Frame buffer memory: 1 Mbit.</li>
<li>Motor de búsqueda integrado con direcciones MAC dedicadas 2048 unicast.</li>
<li>Entradas de alimentación redundantes +12 ~ + 48V DC.</li>
<li>Alarma de falla de energía por salida de relé.</li>
<li>Admite temperaturas de funcionamiento de -40 ° C ~ + 75 ° C.</li>
<li>Montaje en raíl DIN y orificio de tornillo para el kit de montaje en pared.</li>
