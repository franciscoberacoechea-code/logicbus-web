<p align="justify">La interfaz serie 7108 de bajo perfil PCI proporciona un puerto serie aislado ópticamente configurable para RS232, RS-422 o RS-485. La placa es capaz de velocidades de datos de 921.6K bps y maneja automáticamente la activación/desactivación del transmisor RS-485.<br><br>
El 7108 utiliza un UART 16C850 para proporcionar FIFO Tx/Rx de 128 bytes para una máxima confiabilidad en aplicaciones que requieren un uso intensivo de datos. La placa es compatible con MD1 Low Profile y Universal Bus (3.3V y 5V) y las opciones de pedido permiten la elección de UART para velocidades de transmisión personalizadas y protocolos de 9 bits.<br><br>
El controlador y las utilidades del software SeaCOM de Sealevel hacen que la instalación y operación sean fáciles de usar con los sistemas operativos Microsoft Windows o Linux.<br>
El 7108 es compatible con cualquier ranura PCI de bajo perfil. Si tiene una ranura PCI de tamaño estándar, asegúrese de seleccionar el soporte de perfil estándar.</p>

