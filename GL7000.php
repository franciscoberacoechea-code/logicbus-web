<p align="justify">GL7000 Data Platform es una <b>plataforma de adquisición basada en módulos con un mecanismo independiente que proporciona pruebas complejas de voltaje, temperatura, voltaje de alta velocidad, alto voltaje, acelerómetros y medidores de tensión.</b> El sistema independiente hace que los datos se pongan en marcha de forma rápida y precisa. Las mediciones para diferentes aplicaciones se pueden agregar con módulos específicos de señal. La capacidad de muestreo máxima de 1MS / s también proporciona una capacidad de grabación de señal dinámica para aplicaciones que involucran señales de cambio rápido. Al proporcionar un verdadero sistema de prueba independiente con pantalla táctil o software basado en PC, se abre un ciclo de inicio rápido para un sistema de prueba escalado.</p><br><br>

<strong>Características</strong><br>
<ul>
<li>Filtro de paso bajo analógico (Anti-Aliasing) para la cancelación de ruido.</li>
<li>Módulos de entrada versátiles para varios niveles de señal.</li>
<li><b>Sistema autónomo</b> con capacidad para mejorar el requisito de la señal de prueba futura.</li>
<li>Capacidad de memoria mejorada para grabación extendida en cuatro medios de memoria diferentes.</li>
<li>Usos de software compatibles con nuestros otros instrumentos portátiles GL Datalogger.</li>
<li>Paquete de software incluido con la compra de la plataforma.</li>
</ul>

