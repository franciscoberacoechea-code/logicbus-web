                    <h2><span>Tipos de osciloscopios</span></h2>
                  </div>
                </div>
              </center>
              <br>
              <p>Los equipos electrónicos se dividen en dos tipos: Analógicos y Digitales. Los primeros
                trabajan con variables continuas mientras que los segundos lo hacen con variables discretas. Los
                primeros
                trabajan directamente con la señal aplicada, está una vez amplificada desvía un haz de electrones en
                sentido
                vertical proporcionalmente a su valor. En contraste los osciloscopios digitales utilizan previamente un
                conversor analógico-digital (A/D) para almacenar digitalmente la señal de entrada, reconstruyendo
                posteriormente esta información en la pantalla.<br>
                Ambos tipos tienen sus ventajas e inconvenientes. Los analógicos son preferibles cuando es prioritario
                visualizar variaciones rápidas de la señal de entrada en tiempo real. Los osciloscopios digitales se
                utilizan
                cuando se desea visualizar y estudiar eventos no repetitivos (picos de tensión que se producen
                aleatoriamente).</p>
