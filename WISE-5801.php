<p> 
WISE (Web Inside, Smart Engine) es una serie de productos desarrollada por ICP DAS que funciona como unidades de control para su uso en control y monitoreo lógico remoto en diversas aplicaciones industriales. WISE ofrece una interfaz de sitio web intuitiva y fácil de usar que permite a los usuarios implementar la lógica de control IF-THEN-ELSE en los controladores a solo unos clics de distancia; no se requiere programación. Con sus características potentes y fáciles de usar, minimizará la curva de aprendizaje, acortará el tiempo de comercialización y reducirá drásticamente el esfuerzo y el gasto en el desarrollo del sistema.<br><br> 

WISE-5801 admite un bus de expansión de E / S para implementar diversas funciones de E / S, como D / I, D / O, A / D y D / A de acuerdo con la XW-Board. Además, también es compatible con los módulos de E / S remotas ICP DAS I-7000 y los dispositivos esclavos Modbus RTU. Basado en el módulo de E / S de variedad de I-7000 y la capacidad de conexión con dispositivos esclavos Modbus RTU, WISE-5801 puede proporcionar al usuario más flexibilidad en el campo de aplicación.<br><br> 

WISE-5801 es compatible con el protocolo Modbus TCP / RTU para una integración perfecta con el software SCADA disponible. Incluye todas las ventajas que los controladores de la serie WISE pueden proporcionar. Además, WISE-5801 proporciona la función de registrador de datos con tarjeta microSD, puede registrar el valor del canal de E / S por desencadenante de evento o período de tiempo regular. Los archivos de datos pueden enviarse por correo electrónico o FTP. Todas las configuraciones se pueden completar a través del navegador.<br><br> 

Además de los méritos heredados de la serie WISE existente, WISE-5801 incluso proporciona más apoyos en las funciones de E / S. Permite conectar con una amplia gama de XW-Boards, módulos de E / S remotas I-7000 y dispositivos esclavos Modbus RTU que permiten a los usuarios elegir libremente los módulos de E / S más adecuados. Con la tarjeta microSD, proporciona la función del registrador de datos para registrar en tiempo real los datos de E / S del controlador y enviar los archivos de datos por FTP o correo electrónico a un horario programado al centro de control para una administración de administración o análisis de datos adicionales. WISE-5801 también presenta la función de envío de SMS para el informe de alarma y la función de recepción de comando SMS.</p><BR>




