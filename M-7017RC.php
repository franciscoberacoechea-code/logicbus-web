<center><strong>Entrada de voltaje y entrada de voltaje de 8 canales, módulo de adquisición de datos de entrada analógica, transmisible a través de Modbus RTU y RS-485, versión de entrada actual. Admite temperaturas de funcionamiento entre -25 ° C y 75 ° C (-13 ° F ~ + 167 ° F).</strong></center><br>
 <br>

<p> 
El I-7017C es un módulo de entrada de corriente de 8 canales que está diseñado específicamente para medir solo la corriente. Su diseño fácil de usar ahorra tiempo y esfuerzo al medir una corriente gracias a una resistencia incorporada, lo que significa que ahora puede medir la corriente directamente. La I-7017RC es una versión mejorada de la I-7017C, con la única diferencia de que la I-7017RC es mucho más adecuada para entornos críticamente severos. El I-7017RC también tiene una protección ESD de 4 kV y +/- 200 VCC de voltaje común como protección de entrada de corriente, y también cuenta con un aislamiento intramódulo de 3000 VDC y detección de cable abierto para una entrada de 4 ~ 20 mA. La frecuencia de muestreo de la I-7017RC y la I-7017FC es ajustable, lo que significa que se puede seleccionar el modo rápido o el modo normal. El M-7017C y el M-7017RC tienen las mismas especificaciones que los modelos I-7017C y M-7017RC, pero brindan soporte adicional para el protocolo Modbus RTU y el protocolo DCON.
</p><BR>

