          <p align="justify">El sistema de validación de congelador de ultra baja temperatura puede medir y registrar datos tan bajos como -86°C. Puede ser colocado en congeladores pequeños y grandes de configuraciones variantes. El sistema proporciona un mapeo completo de temperatura autónomo y solución de validación para congeladores, asegurando el almacenamiento uniforme y condiciones de prueba. El ULT90 incluye una estación USB con 6 pies de cable (IFC300), 9 registradores Cryo-Temp, software seguro y protocolos de validación IQ/OQ/PQ.
            <br><br>
            Para grandes congeladores, los registradores pueden ser trazados en una gráfica para mostrar variaciones en diferentes partes del congelador. Finalmente, como falta de seguimiento a la temperatura externa del congelador, puede invalidar la temperatura interna, se puede incluir un Cryo-Temp adicional para colocarlo fuera del congelador.</p>

          <STRONG>Características:</STRONG>
          <ul>
            <li>Certificados de calibración trazables a NIST</li>
            <li>Cumple con la norma FDA 201 CFR Parte 11</li>
