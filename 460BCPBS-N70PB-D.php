<strong>¿Cómo uso 460BCPBS-N70PB en mi aplicación?</strong><br><br>
Los datos BACnet / IP se asignarán a 10 ranuras PROFIBUS DP. La ranura puede consistir en hasta
244 bytes de datos de sus dispositivos de servidor BACnet / IP. Al escribir desde su Controlador PROFIBUS a sus Servidores BACnet / IP habrá más
a 10 ranuras cada una definida por los mismos tipos. Los datos en esas ranuras se pueden asignar a su Dispositivos BACnet / IP.<br><br>

