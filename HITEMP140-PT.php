<div align="justify"><p>El HiTemp140-PT es un registrador de datos de temperatura sumergible que puede operar hasta 140 ° C (284 ° F) y tiene una precisión de +/- 0.1 ° C (0.18 ° F). El HiTemp140-PT viene en dos longitudes de sonda diferentes, ambos estilos de sonda cuentan con una sonda de acero inoxidable flexible de 24 pulgadas. El HiTemp140-PT-1 tiene una punta de sonda de 1 pulgada y el HiTemp140-PT-5 tiene una punta de sonda de 5 pulgadas. Ambas sondas pueden medir temperaturas extendidas de hasta 350 ° C (662 ° F). La sonda es duradera y se puede girar, doblar o inclinar en cualquier dirección, lo que facilita el registro de temperaturas dentro de botellas, viales u otros lugares difíciles de alcanzar. El HiTemp140-PT registra las lecturas de fecha y hora, y tiene una memoria de estado sólido no volátil que conserva los datos incluso si la batería se descarga.<br>

Usando el último software de MadgeTech, iniciar, detener y descargar el HiTemp140-PT es simple y fácil. Para usar, simplemente coloque el HiTemp140-PT en la estación de acoplamiento IFC400 o IFC406 (se vende por separado). Usando el software, se puede elegir un inicio inmediato o diferido, así como también la velocidad de lectura. Arranque el registrador de datos, extráigalo de la estación de acoplamiento y el dispositivo estará listo para ser desplegado.<br>

Los datos gráficos, tabulares y de resumen se proporcionan para el análisis y los datos se pueden ver en ° C, ° F, K o ° R. Los datos también se pueden exportar automáticamente a Excel® para realizar más cálculos.</p>

