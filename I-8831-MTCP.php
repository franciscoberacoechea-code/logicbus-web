                <p> <strong>Introducción:<br><br>
                  </strong>La serie I-800E-MTCP son unidades de E/S Modbus/TCP con el protocolo de comunicación
                  Modbus. Soportan la mayoría de los módulos de la serie E/S 8K y 87K, como entradas
                  digitales, salidas digitales, entradas y salidas digitales, entradas analógicas, etc... Los
                  usuarios pueden integrar de una manera fácil y rápida las E/S remotas al software SCADA
                  como la adquisición de datos y monitoreo para aplicar al monitoreo del ambiente, manejo de
                  potencia, automatización de fábricas, etc.</p>
              </div>
