<p align="justify">El I-87H17W es un módulo de entrada analógica HART. Puede medir 4 ~ 20mA de corriente y actúa como maestro HART, lo que permite la comunicación con los dispositivos de campo HART. Su diseño fácil de usar ahorra mucho trabajo al medir la corriente debido a una resistencia incorporada. Ahora, los usuarios pueden medir la corriente directamente sin resistencia externa. La velocidad en baudios de I-87H17W es variable y admite el protocolo DCON. De lo contrario, ICP DAS también proporciona una biblioteca API para que los usuarios desarrollen su propio programa en entornos VC, VB, C # o VB.Net.</p>

Caracterísiticas:
<ul>
<li>Capacidad de entrada analógica con o sin HART.</li>
<li>Adquisición de datos HART en tiempo real.</li>
<li>Acceso completo de lectura / escritura a toda la información del dispositivo.</li>
<li>Soporta entrada de corriente de 4 ~ 20 mA.</li>
<li>Transmisores de 2 o 4 hilos de HART.</li>
<li>Con una resistencia incorporada.</li>
<li>Detección de cable abierto.</li>
<li>Protección ESD de 4 kV.</li>
<li>Aislamiento intramódulo de 2500 VDC.</li>
<li>Watchdog incorporado.</li>
<li>Conformidad con la RoHS.</li>
<li>Admite el protocolo DCON.</li>
<li>Proporcionar biblioteca de API y demostraciones.</li>
<li>Compatible con las series XPAC, WinPAC, I-87Kx, RU-87Px, USB-87Px, ET-87Px.</li>
</ul>
