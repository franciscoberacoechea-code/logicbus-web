<center><strong>Módulo multifunción BACnet/IP.</strong></center><br>

<p>El ECAT-2045 es un módulo de E/S esclavo industrial construido en 16 salidas digitales. Está equipado con el protocolo EtherCAT * y se instala mediante una conexión en cadena tipo margarita que proporciona un sistema más escalable con menos cables. Los usuarios pueden obtener el estado de entrada y salida no solo a través de los datos del proceso sino también a través de sus indicadores LED. El ECAT-2045 ha pasado y fue verificado por la herramienta de prueba de conformidad, por lo tanto, el maestro o configurador de EtherCAT elegible puede ser manipulado de forma sencilla y se puede implementar sus diversas aplicaciones fácilmente.</p>
Características:
<ul>
<li>Procesamiento sobre la marcha: EtherCAT.</li>
<li>Potente MCU maneja el tráfico de red eficiente.</li>
<li>2 x interfaz de bus RJ-45.</li>
<li>Distancia entre estaciones hasta 100 m (100 BASE-TX).</li>
<li>Soporte de conexión de cadena tipo daisy.</li>
<li>Prueba de conformidad de la herramienta EtherCAT verificada.</li>
<li>Conector de bloque de terminales extraíble.</li>
<li>Indicadores LED para el estado de salida.</li>
<li>Salidas digitales incorporadas aisladas de 32 canales.</li>
<li>Compatible con RoHS.</li>
<li>Protección ESD 4 KV de contacto para cada canal.</li>
</ul>
