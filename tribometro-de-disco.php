          <div>
              <p><b>C&oacute;mo funciona:</b><br></p>
              <ol>
                <li style="color: black;">Una muestra de material se adjunta al sensor de torque y empuje biaxial <strong><a href="https://tienda.logicbus.com.mx/MBA500_c_1950.html">MBA500</a></strong> junto a un actuador lineal.</li>
                <li style="color: black;">Un motor gira el disco a un rango de RPMs específico.</li>
                <li style="color: black;">El actuador lineal presiona la muestra hacia el disco giratorio.</li>
                <li style="color: black;">El sensor <strong><a href="https://tienda.logicbus.com.mx/MBA500_c_1950.html">MBA500</a></strong> captura la fuerza aplicada y el torque generado por el disco de muestra.</li>
                <li style="color: black;">La salida del sensor <strong><a href="https://tienda.logicbus.com.mx/MBA500_c_1950.html">MBA500</a></strong> se captura en el <strong><a href="https://tienda.logicbus.com.mx/FSH03927_p_14415.html">USB220</a></strong> de alta resolución.</li>
                <li style="color: black;">Los datos que entrega el <strong><a href="https://tienda.logicbus.com.mx/FSH03927_p_14415.html">USB220</a></strong> se registra en la computadora mediante el software Sensit.</li>
                <li style="color: black;">Para una conexión directa a un microprocesador, se puede conectar el controlador digital IDC305 para conocer los datos de torque y empuje mediante SPI.</li>
                <li style="color: black;">Adicionalmente, el acondicionador de señal <strong><a href="https://tienda.logicbus.com.mx/Acondicionador-de-se%C3%B1al_c_1665.html">IAA</a></strong> puede entregar la salida analógica de voltaje o corriente a un PLC o DAQ.</li>
              </ol>
