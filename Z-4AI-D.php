<strong><center>Convertidor de señales A/D con 4 entradas</center></strong>

<div align="right">
<a href="https://tienda.logicbus.com.mx/Z-4AI-D_p_4150.html" title="Ir a Tienda" target="_blank"><img src="images/shopping_cart.png" alt="Comprar"></a>
