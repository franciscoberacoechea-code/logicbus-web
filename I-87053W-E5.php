<center><strong>Módulo de entrada digital aislado de 16 canales y 68-150 V CC con contadores de 16 bits (cubierta gris) (RoHS).</strong></center><br>

<p>El I-87053W-E5 proporciona 16 canales para la entrada digital de alta tensión, cada uno de los cuales cuenta con aislamiento de fotoacoplamiento. El nivel de voltaje de entrada puede ser tan alto como 150 VDC. Además, se puede seleccionar la entrada digital del receptor o del tipo de fuente a través de conexiones de cable, y todos los canales se pueden usar como contadores de 16 bits. La distancia efectiva para contacto seco es de hasta 500 metros. El I-87053W-E5 también proporciona 16 indicadores LED que se pueden usar para monitorear el estado del canal DI. La protección ESD de 4 kV y el aislamiento intramódulo de 3750 VDC también se proporcionan para mejorar las capacidades de inmunidad contra el ruido en entornos industriales.</p>

