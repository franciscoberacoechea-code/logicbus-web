<p align="justify">El GL980 es un registrador de datos independiente de 8 canales adecuado para la medición de voltaje y RMS real. Las entradas analógicas también son adecuadas para el uso con termopares tipo K, J, E, T, R, S, B, N y W, 0-500 V o humedad (a través del sensor B-530). El GL980 viene con una amplia pantalla LCD TFT a color de 7 "de ancho con forma de onda u opciones digitales. La RAM interna permite hasta 4 millones de lecturas por canal y la ranura de la tarjeta SD permite hasta 4 GB de tarjetas de memoria. El puerto USB incorporado permite la transferencia de datos a una PC o computadora portátil y un puerto Ethernet permiten la conexión a una LAN. El GL980 también permite las funciones del servidor FTP y la sincronización NTP con los puertos Ethernet o WLAN. También se pueden enviar correos electrónicos para enviar información cuando se producen alarmas, o alertas de energía, comunicaciones o problemas de memoria</p><br><br>

<strong>Características</strong><br>
<ul>
<li>Muestreo simultáneo de alta velocidad de 8 canales.</li>
<li>Incluye medición de 500 V con convertidor A / D de 16 bits.</li>
<li>Pantalla LCD TFT de 7 "de ancho con opción de forma de onda o forma digital</li>
<li>Sistema de menú de teclado fácil de usar</li>
<li>Gran RAM incorporada (4 millones de muestras por canal)</li>
<li>Memoria flash incorporada (4GB)</li>
<li>Ranuras para tarjetas de memoria SD (adecuadas para tarjetas de memoria tipo SDHC de hasta 32 GB)</li>
<li>Batería opcional para medición en zonas remotas.</li>
<li>Registre los datos directamente en la memoria USB</li>
<li>Software libre para revisar / analizar datos.</li>
</ul><br>

<strong>Aplicaciones</strong><br>
<ul>
<li>Caudal y ensayo de temperatura en calentadores de agua.</li>
<li>Medición del rendimiento de aislamiento térmico de viviendas residenciales.</li>
<li>Test de rendimiento de inversores para aire acondicionado.</li>
<li>Medición de tensión y temperatura de generadores.</li>
<li>Pruebas de rendimiento de lavadora y secadora</li>
<li>Medición para pruebas de componentes de frenos.</li>
</ul>

