<h2>Resumen de la aplicación.</h2>
La medición de la tensión del alambre es una parte integral para los fabricantes de fibras, cables e incluso tejidos. Las celdas de carga miniatura se utilizan para medir la tensión o las fuerzas de compresión de los cables.

<h2>Productos en uso</h2>
El <a href="https://tienda.logicbus.com.mx/LSB200_c_1670.html" target="_blank">LSB200</a> Jr. Celda de carga en forma de S en miniatura emparejada con las <a href="https://tienda.logicbus.com.mx/Mdulos-USB_c_1662.html" target="_blank">soluciones USB</a> de <a href="futek">FUTEK</a> y el <a href="https://tienda.logicbus.com.mx/FSH03189_p_8987.html" target="_blank">software de prueba y medición SENSIT</a>.

