<center><strong>* Para uso en modo múltiple * Ethernet Industrial 10 / 100BaseT no gestionada de 5 puertos a 100BaseFX Switch de fibra en caja de metal que asegura los datos mediante la transmisión de fibra óptica para proporcionar inmunidad contra interferencia EMI / RFI. (Conector ST; modo múltiple)</strong></center>
 <br><br>

<p>Ethernet se utiliza para transmitir una señal de hasta 2 km (6,600 pies), y es la solución perfecta para aplicaciones donde la transmisión debe protegerse de la exposición eléctrica, sobretensiones, rayos o corrosión química.<br><br>

El NSM-205FT funciona en modo half o full duplex. En modo dúplex completo, el rango es de 2 km con cables de fibra de 62.5 / 125μm; en modo semidúplex, el rango es de 412 m con cables de fibra de 62.5 / 125μm.<br>

El Ethernet admite la función de autonegociación 10 / 100M y la función automática MDI / MDIX.<br>

NSM-205FT proporciona dos entradas de alimentación que se pueden conectar simultáneamente a fuentes de alimentación de CC en vivo. Si una de las entradas de alimentación falla, la otra fuente en vivo actúa como una copia de seguridad para respaldar automáticamente las necesidades de energía del NSM-205FT.</p><br><br>

<strong>Caracter&iacute;sticas:</strong>
<ul>
<li>Crossover automático MDI / MDI-X para plug-and-play</li>
<li>Cada puerto admite una negociación automática de velocidad de 10/100 Mbps</li>
<li>Arquitectura de almacenamiento y reenvío</li>
<li>Control de flujo de contrapresión Full Duplex IEEE 802.3xy semidúplex</li>
<li>Ancho de banda de memoria de alto rendimiento de 3.2Gbps</li>
<li>Frame buffer memory: 512 Kbit</li>
<li>Motor de búsqueda integrado con direcciones MAC dedicadas de 1 K unicast.</li>
<li>Entradas de alimentación redundantes +10 ~ + 30V DC</li>
<li>Alarma de falla de energía por salida de relé</li>
<li>Admite temperaturas de funcionamiento de 0 ° C ~ + 70 ° C</li>
<li>Montaje en riel DIN para uso industrial</li>
</ul>


