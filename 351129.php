<p>ASK 4S Terminales prácticos de fusibles de tornillo de la serie 4S para normas americanas, voltaje nominal 750 V, corriente nominal de 6.3 A. Es necesario un destornillador para instalar el cable en el bloque de terminales. Son adecuados para su uso con o sin virolas. Para que la conexión sea suficiente para insertar el cable en el terminal, la serie ASK 4S proporciona un montaje más práctico.
Los accesorios de los terminales, como las placas finales y las conexiones cruzadas, agilizan el proceso de montaje como en los terminales de prueba. Se pueden proporcionar soluciones de marcado especiales para cada sección transversal mediante el etiquetado del plóter.</p><br>
	

