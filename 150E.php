<p align="justify">Módulo de control y monitoreo con cuatro salidas a relevador tipo C de alta densidad a través de cualquier conexión Ethernet 10/100BaseT. Los relevadores tipo C soportan cargas de hasta 6A a 250 Vac y de 5A a 60 Vdc. Cada bloque de terminales a tornillo de 3.5mm comparte un común e incluye normalmente abiertos y normalmente cerrados para facilitar el cableado de campo.
<br><br>
El 150E se alimenta a través de un bloque de terminales a tornillo extraíbles. Su diseño facilita el mecanismo de sujeción, lo que simplifica la instalación en campo. El módulo se alimenta de una fuente de 9 a 30Vdc.
<br><br>
El 150PoE es un dispositivo alimentado a través de un dispositivo Ethernet (PoE) Clase 0 (IEEE 802.3af-2003). Esto permite que la energía y los datos que se transfieran a través de un cable CAT5 y elimina la necesidad de una fuente de alimentación externa. Con PoE, se puede alimentar el equipo, abastecimiento de energía incluyendo switches PoE (midspans) e inyectores. 
<br><br>
Incluye un clip de plástico desmontable que encaja en el carril DIN de 35mm. El clip también se puede fijar a cualquier superficie plana, como una pared o debajo de un mostrador. Su rango de temperatura en operación para sus E/S digitales es de 0°C a 70°C. Sus LEDs de estado del frente muestran la alimentación y la actividad de las E/S. Además, en el puerto Ethernet (RJ45) encienden cuando existe actividad de comunicación.

<br><br>
Comuníquese con los módulos de E / S digitales Ethernet eI / O utilizando el protocolo Modbus TCP estándar de la industria o use las bibliotecas de software SeaMAX API de su programa de aplicación. Los controladores y las utilidades del <strong><a href="software-seamax" target="_blank">software SeaMAX </a></strong> facilitan la instalaci&oacute;n y operaci&oacute;n usando los sistemas operativos Windows 10 y 8. <br></p>


