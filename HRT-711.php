<li>Proporcione la tabla de direcciones Modbus para los datos del comando HART</li>
<li>Proporcione la información de diagnóstico del módulo HRT-711 y el dispositivo HART</li>
<li>Proporcione el comando enviar/recibir HART para acceder al dispositivo HART</li>
<li>Proporcione el archivo de configuración del módulo "Cargar/Guardar" para aplicarlo rápidamente a otros HRT-711</li>
</ul>

