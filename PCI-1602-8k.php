<center><strong>Tarjeta de E / S analógica y digital de alto rendimiento de 100KS / s de 16 bits</strong></center><br>


<p>La serie PCI-1602 / 1602F es una familia de placas de adquisición de datos de alto rendimiento y alta resolución para el bus PCI. Cuenta con una adquisición de datos continua, sin interrupciones, de 100 KHz para PCI-1602 (200 KHz para PCI-1602F) en DOS y Windows. La familia PCI-1602 tiene la misma arquitectura de hardware que PCI-1802L. El PCI-1602 proporciona 32 entradas análogas de terminal simple o 16 diferenciales. Al igual que la familia PCI-1802, la serie PCI-1602 presenta una función de "Escaneo mágico", función M, función X y función de captura continua.
</p><BR><br>

<strong>Caracteristicas</strong>

<ul>
<ul>
<li>Bus PCI (v2.1), 33 MHz 5 V 32 bits.</li>
<li>PCI-1602: convertidor A / D de 100 kHz de 16 bits</li>
<li>PCI-1602F: convertidor A / D de 16 bits a 200 KHz</li>
<li>PCI-1602 / PCI-1602F:</li>
<ul>
<li>32 entradas Terminal simple / 16 diferenciales</li>
<li>Memoria intermedia de palabra FIFO de 8K</li>
</ul>
<li>Las velocidades de muestreo de canal simple o múltiple son: </li>
<ul>
    <li>PCI-1602: 100K muestras / s </li>
    <li>PCI-1602F: 200K de muestra / s</li>
    </ul>
<li>Tres factores desencadenantes externos diferentes:</li>
<ul>
<li>post-disparo</li>
<li>pre-disparador</li>
<li>gatillo medio</li>
</ul>
<li>16 canales de entrada digital / 16 canales de salida digital</li>
<li>PCI-1602 proporciona baja ganancia programable: 0.5, 1, 2, 4, 8</li>
<li>Disparador interno / externo.</li>
<li>Dos DAC programables independientes de 12 bits</li>
<ul>
<li>Rendimiento de 2 MHz por canal (máximo)</li>
</ul>
<li>Alta Velocidad de transferencia de datos de palabras 2.7 M </li>
