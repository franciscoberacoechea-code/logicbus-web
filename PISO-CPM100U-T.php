<p>El PISO-CPM100U ha seguido la especificación CiA CANopen DS-301 V4.02. Con la CPU incorporada 80186 80M Hz, esta tarjeta se puede aplicar en aplicaciones de transmisión alta. El microcontrolador integrado de 16 bits con O.S. en tiempo real, MiniOS7, permite muchas funciones, como transmisión y recepción de mensajes en tiempo real, filtrado, preprocesamiento y almacenamiento de mensajes CAN. Es compatible con la marca de tiempo del mensaje PDO con una precisión de al menos 1 ms. Surtidos con la herramienta gratuita (CPM_Utility), los usuarios pueden administrar e integrar fácilmente con dispositivos industriales CANopen.</p><BR>


<strong>Caracteristicas:</strong>
<ul>
<LI>NMT: Maestro</LI>
<LI>Versión CANopen: DS-301 v4.02</LI>
<LI>Control de errores: protocolo de protección y Heart Beat</LI>
<LI>Soporte EMCY recibiendo</LI>
<LI>Proporcionar funciones PDO dinámicas</LI>
<LI>Proporcione 5 juegos de transmisión cíclica SYNC</LI>
<LI>El tipo de transmisión de PDO es compatible</LI>
<LI>Admite la arquitectura Multi-Master a Single-Slave</LI>
<LI>Selección automática con modo expedición o modo segmento</LI>
<LI>Soporte de carga de archivo EDS</LI>
<LI>Soporte Windows 2K / XP</LI>
</ul>
