      Suppose  you examine more closely what happens inside a material when an electron current bening to flow. The protons have a positive charge, the electrons a negative charge, and the neutrons have no charge at all. If an atom loses several of its free electrons, it then has a positive charge since there are more protons that electrons. You know that like charges repel each other and unlike charges attract. About each positive or negative charge, unseen lines offorce radiate in all directions and the area occupied by these lines is called an <b>&#34Electric Field&#34</b>.
    </p>
    <p>
      If an electrons comes near a positive charge, the two fields reach out and attract each other even though there may be some distance between them. It is the attraction between the positive charge on the nucleus and the electrons in the outer orbit that determine the electrical characteristics of a material. If the atom of a particular material is so constructed that there is a very small attraction between the positive nucleus and the outer electrons, the outer electrons are free to leave the atom when they are under the influence of electric fields.
    </p>
