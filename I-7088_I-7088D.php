          <p>El I-7088 tiene 8 canales de salida PWM y 8 entradas de contador y se puede utilizar para desarrollar sistemas de control analógicos potentes y rentables. PWM (modulación por ancho de pulso) es una poderosa técnica para controlar circuitos analógicos que usa salidas digitales para generar una forma de onda con variante Duty Cycle (La fracción de tiempo que un sistema está en un estado "activo") y frecuencia para controlar circuitos analógicos y ser utilizado para controlar la posición / velocidad de los motores, atenuar el brillo de las lámparas, controlar la velocidad de los ventiladores, etc.<br>

            El I-7088 también guardará automáticamente el valor del contador en EEPROM si se interrumpe o se pierde la fuente de alimentación.</p><BR>

          <strong>Características:</strong>
          <ul>
            <li>Generación automática de hardware de salidas PWM sin intervención del software</li>
            <li>Frecuencia de salida PWM de 1Hz ~ 500KHz con ciclo de trabajo de 0.1% ~ 99.9%</li>
            <li>Modo de activación de software y hardware para salida PWM</li>
            <li>Salida PWM individual y síncrona. Usando el modo de activación por software, puede configurar la configuración de todos los canales PWM y luego activarlos individualmente o todos al mismo tiempo.</li>
            <li>Modo de ráfaga de funcionamiento PWM para modo de espera</individualmente>
            <li>El canal DI se puede configurar como un canal de entrada digital simple o como una fuente de activación de hardware para la salida PWM.</li>
          </ul><br>

          <strong>Aplicaciones:</strong>
          <ul>
            <li>Controlar la posición / velocidad de los motores</li>
            <li>Atenuar el brillo de las lámparas</li>
            <li>Controlando la velocidad de los fanáticos</li>
          </ul>


