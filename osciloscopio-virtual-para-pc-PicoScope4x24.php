          <p><strong>Ahora puedes medir lo desde pequeñas señales hasta altos voltajes</strong></p>

          <p>La serie PicoScope 4000 posee rangos de entrada de ±50mV hasta ±100 V así que puedes medir desde pequeñas señales de sensores hasta altos voltajes de fuentes de alimentación y motores.</p>

          <p><strong>La conveniencia y la velocidad que necesitas</strong></p>

          <p>Gracias a su avanzado buffer de 32 mega muestras que está siempre encendido, nunca habrá problemas entre el tamaño del buffer y el rendimiento. La serie PicoScope 4000 siempre maximiza tanto el tamaño del buffer como la frecuencia de actualización del display al mismo tiempo. Ahora puedes fácilmente capturar el detalle de cada forma de onda sin comprometer el funcionamiento del equipo.</p>

          <p><strong>Paquete de software completo</strong></p>


          <p>El PicScope 4224 y 4424 incluyen el PicoScope Osciloscope Software. Una completa aplicación de pruebas y medición. Así como un osciloscopio completamente funcional con características avanzadas tales como persistencia digital, funciones matemáticas y mediciones automáticas, el software PicScope te permite usar tu PicoScope 4224 o el 4424 como un analizador de espectros, es totalmente gratuito y regularmente actualizado con nuevas características y mejoras y siempre podrás descargar las más nuevas actualizaciones. Sabemos que podrías querer escribir tu propio software o usar software de terceros para controlar tus osciloscopios. No hay problema, también contamos con un kit de desarrollo gratuito que contiene drivers y códigos de ejemplo.</p>

          <p><strong>Tu poderoso osciloscopio de alta resolución</strong></p>

          <p>Tanto con el de 2 canales como con el de 4 canales el ancho de banda análogo es de 20 MHz, frecuencia de 80 Mega muestras por segundo en tiempo real, 12-16 bits de resolución, 1% de exactitud un amplio rango de entrada, un PicoScope USB serie 4000 es un osciloscopio poderoso y de alta resolución que llenara todas tus necesidades.</p>


