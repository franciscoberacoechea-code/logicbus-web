<center><strong>Módulo esclavo CANopen de entradas analógicas de 8 canales.</strong></center><br>

<p>CANopen es un tipo de protocolo de red basado en el bus <a href="convertidores_info#CAN">CAN</a> y utilizado principalmente para sistemas de red integrados, como control de maquinaria industrial, sistema de control de vehículo, automatización de fábrica, control de equipos médicos, adquisición remota de datos, monitoreo ambiental y control de máquinas de empaquetado. etc.
<br><br>
El módulo CAN-2017C sigue el CiA DS-301 versión 4.02 y DSP-401 versión 2.1. Es fácil acceder al estado de la entrada analógica diferencial y configurar la configuración mediante el protocolo CANopen estándar. El CAN-2017C ha pasado la validación de la herramienta de prueba de conformidad CANopen de CiA. Por lo tanto, el archivo EDS proporcionado es estándar para cualquier otro maestro CANopen estándar. Al utilizar la entrada analógica de 8 canales y los maestros CANopen, puede construir rápidamente una red CANopen para satisfacer sus necesidades.</p>
  
