<script>
(function () {
  var bar = document.getElementById('lbBar');
  if (!bar) return;
  var tabbar = document.getElementById('lbTabbar');
  var root = document.documentElement;
  var desk = window.matchMedia('(min-width: 1280px)');
  var panels = ['mega', 'drawer', 'search'];
  var tabIds = { mega: 'lbTabProducts', drawer: 'lbTabMenu', search: 'lbTabSearch' };
  var megaLi = bar.querySelector('.lb-item.has-mega');
  var mega = document.getElementById('lbMega');
  var drops = [].slice.call(bar.querySelectorAll('.lb-item.has-drop'));
  var cats = [].slice.call(bar.querySelectorAll('.lb-cat'));
  var timers = {};

  function isOpen(n) { return bar.classList.contains('is-' + n); }

  function sync() {
    var any = false;
    panels.forEach(function (n) {
      var on = isOpen(n);
      any = any || on;
      var t = document.getElementById(tabIds[n]);
      if (t) { t.classList.toggle('is-on', on); t.setAttribute('aria-expanded', on ? 'true' : 'false'); }
    });
    var sb = document.getElementById('lbSearchBtn');
    if (sb) sb.setAttribute('aria-expanded', isOpen('search') ? 'true' : 'false');
    var mt = document.getElementById('lbMegaToggle');
    if (mt) mt.setAttribute('aria-expanded', isOpen('mega') ? 'true' : 'false');
    megaLi.classList.toggle('is-open', isOpen('mega'));
    root.classList.toggle('lb-lock', !desk.matches && any);
  }

  function setDrop(d, on) {
    d.classList.toggle('is-open', on);
    var b = d.querySelector('.lb-toggle');
    if (b) b.setAttribute('aria-expanded', on ? 'true' : 'false');
  }
  function closeDrops(except) { drops.forEach(function (d) { if (d !== except && d !== megaLi) setDrop(d, false); }); }

  function activate(cat) {
    cats.forEach(function (c) {
      var on = c === cat;
      c.classList.toggle('is-active', on);
      c.querySelector('.lb-cat-link').setAttribute('aria-expanded', on ? 'true' : 'false');
    });
  }
  function deactivate() { activate(null); }

  function closeAll(except) {
    panels.forEach(function (n) { if (n !== except) bar.classList.remove('is-' + n); });
    if (except !== 'drawer') closeDrops();
    sync();
  }
  
  function open(n) {
    clearTimeout(timers.mc);
    closeAll(n);
    bar.classList.add('is-' + n);
    if (n === 'mega') { if (desk.matches) activate(cats[0]); else deactivate(); }
    sync();
    if (n === 'search') setTimeout(function () {
      var i = bar.querySelector('.lb-search-panel .gsc-input');
      if (i) i.focus();
    }, 120);
  }
  
  function toggle(n) {
    if (isOpen(n)) { bar.classList.remove('is-' + n); sync(); } else open(n);
  }

  /* Botones */
  function on(id, fn) { var el = document.getElementById(id); if (el) el.addEventListener('click', fn); }
  on('lbTabProducts', function () { toggle('mega'); });
  on('lbTabSearch', function () { toggle('search'); });
  on('lbTabMenu', function () { toggle('drawer'); });
  on('lbSearchBtn', function () { toggle('search'); });
  on('lbBackdrop', function () { closeAll(); });
  on('lbMegaToggle', function (e) { e.preventDefault(); if (desk.matches) toggle('mega'); else open('mega'); });
  [].slice.call(bar.querySelectorAll('[data-close]')).forEach(function (b) {
    b.addEventListener('click', function () { closeAll(); });
  });

  /* Mega menu en escritorio: apertura con retardo corto para evitar aperturas accidentales */
  function megaIn() {
    if (!desk.matches) return;
    clearTimeout(timers.mc);
    if (isOpen('mega')) return;
    var other = isOpen('search') || drops.some(function (d) { return d !== megaLi && d.classList.contains('is-open'); });
    clearTimeout(timers.mo);
    timers.mo = setTimeout(function () { open('mega'); }, other ? 0 : 120);
  }
  function megaOut() {
    if (!desk.matches) return;
    clearTimeout(timers.mo);
    clearTimeout(timers.mc);
    timers.mc = setTimeout(function () { if (isOpen('mega')) { bar.classList.remove('is-mega'); sync(); } }, 250);
  }
  [megaLi, mega].forEach(function (el) {
    el.addEventListener('mouseenter', megaIn);
    el.addEventListener('mouseleave', megaOut);
  });
  megaLi.addEventListener('focusin', function () { if (desk.matches && !isOpen('mega')) open('mega'); });
  megaLi.addEventListener('keydown', function (e) {
    if (e.key === 'ArrowDown' && desk.matches) {
      e.preventDefault();
      if (!isOpen('mega')) open('mega');
      var l = mega.querySelector('.lb-cat-link');
      if (l) l.focus();
    }
  });

  /* Categorias */
  cats.forEach(function (c) {
    var link = c.querySelector('.lb-cat-link');
    var hasKids = !!c.querySelector('.lb-cat-grid');
    c.addEventListener('mouseenter', function () { if (desk.matches) activate(c); });
    link.addEventListener('focus', function () { if (desk.matches) activate(c); });
    link.addEventListener('click', function (e) {
      if (!desk.matches && hasKids) {
        e.preventDefault();
        if (c.classList.contains('is-active')) deactivate(); else activate(c);
      }
    });
  });

  /* Dropdowns simples (Nuestros Sitios y Atencion al Cliente) */
  drops.forEach(function (d) {
    if (d === megaLi) return;
    var btn = d.querySelector('.lb-toggle');
    d.addEventListener('mouseenter', function () {
      if (!desk.matches) return;
      clearTimeout(d._t);
      if (isOpen('mega') || isOpen('search')) { bar.classList.remove('is-mega'); bar.classList.remove('is-search'); sync(); }
      closeDrops(d);
      setDrop(d, true);
    });
    d.addEventListener('mouseleave', function () {
      if (!desk.matches) return;
      clearTimeout(d._t);
      d._t = setTimeout(function () { setDrop(d, false); }, 250);
    });
    d.addEventListener('focusin', function () { if (desk.matches) { closeDrops(d); setDrop(d, true); } });
    d.addEventListener('focusout', function (e) {
      if (desk.matches && !d.contains(e.relatedTarget)) { d._t = setTimeout(function () { setDrop(d, false); }, 200); }
    });
    btn.addEventListener('click', function (e) {
      e.preventDefault();
      if (desk.matches) { setDrop(d, true); return; }
      var was = d.classList.contains('is-open');
      closeDrops();
      setDrop(d, !was);
    });
  });

  /* Teclado y clics fuera */
  document.addEventListener('keydown', function (e) {
    if (e.key === 'Escape') { closeAll(); return; }
    if (e.key === '/' && desk.matches) {
      var t = e.target, tag = t && t.tagName ? t.tagName.toLowerCase() : '';
      if (tag === 'input' || tag === 'textarea' || tag === 'select' || (t && t.isContentEditable)) return;
      e.preventDefault();
      open('search');
    }
  });
  document.addEventListener('click', function (e) {
    if (!bar.contains(e.target) && !(tabbar && tabbar.contains(e.target))) closeAll();
  });

  function onDeskChange() {
    closeAll();
    deactivate();
  }
  if (desk.addEventListener) desk.addEventListener('change', onDeskChange); else desk.addListener(onDeskChange);

  sync();
})();
</script>