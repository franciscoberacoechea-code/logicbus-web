<p>El ET-7042, es un módulo Ethernet que posee un servidor web integrado que permite configurar el módulo, controlar y monitorear las E/S desde cualquier navegador web. Con la función web HMI, no es necesario programar ni tener habilidades en HTML; la creación de páginas web dinámicas y atractivas para el control y monitoreo de entradas/salidas será divertido para los ingenieros. El ET-7042 ofrece a los usuarios un acceso fácil y seguro desde cualquier lugar y a cualquier hora. Además, el ET-7042 soporta también el protocolo Modbus/TCP, lo cual hace una perfecta integración entre este dispositivo y software SCADA.<br><br>
El ET-7042 provee 16 canales aislados de salida de colector abierto (sink). Cada canal de salida soporta una corriente de 100mA @5~30Vdc.</p><BR>

