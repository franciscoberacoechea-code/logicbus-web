<center><strong>Tarjeta PCI Express con 8 entradas digitales aisladas y 8 salidas de relé. Incluye un conector CA-4002 D-Sub y un Kit de desarrollo de software con programas de demostración.</strong></center><br>

<p>El PCI-P16POR16 es una tarjeta PCI compatible con el bus PCI de 5 V, mientras que el PEX-P8POR8i/PEX-P16POR16i es una tarjeta PCI Express. Cada uno contiene 8 o 16 canales de entrada ópticamente aislados y 8 o 16 canales de salida de retransmisión PhotoMos. Tanto los canales DI aislados como los canales de retransmisión PhotoMos usan una ruta de transmisión óptica corta para transferir una señal electrónica entre los elementos de un circuito y mantenerlos aislados eléctricamente. El PCI-P16POR16 proporciona 5000 Vrms y PEX-P8POR8i/P16POR16i proporcionan 2000 VDC para la protección de aislamiento del canal DI, permitiendo que las señales de entrada floten por completo para reducir los bucles de tierra, bloquear los picos de tensión y aislar la computadora host de tensiones dañinas . Los relés PhotoMos se utilizan cuando es necesario controlar un circuito con una señal de baja potencia (con aislamiento eléctrico completo entre el control y los circuitos controlados), o donde varios circuitos deben controlarse con una señal. El PEX-P16POR16i es totalmente compatible con el PCI-P16POR16, y los usuarios pueden reemplazar fácilmente el PCI-P16POR16 con el PEX-P16POR16i sin necesidad de modificar el software/controlador cuando usan computadoras PCI Express. 
<br><br>
El PEX-P16POR16i/PEX-P8POR8i también agrega un interruptor de ID de tarjeta a bordo. Los usuarios pueden configurar la identificación de la tarjeta y luego reconocer la placa mediante la identificación a través del software cuando usan dos o más tarjetas PEX-P16POR16i/PEX-P8POR8i en una computadora. El PCI-P16POR16 y el PEX-P16POR16i/PEX-P8POR8i pueden utilizarse en diversas aplicaciones, como controlar el estado ON/OFF de dispositivos externos, controlar relés externos o pequeños interruptores de potencia, activar alarmas, cerrar contactos, detectar tensiones externas o interruptores , etc. 
<br><br>
Estas tarjetas admiten varias versiones del sistema operativo, como Linux, DOS, Windows 98/NT/2000 y Windows 7/Vista/XP de 32/64 bits. El control DLL y Active X junto con varios programas de muestra de lenguaje basados ??en Turbo C ++, Borland C ++, Microsoft C ++, Visual C ++, Borland Delphi, Borland C ++ Builder, Visual Basic, C # .NET, Visual Basic.NET y LabVIEW se proporcionan para ayudar a los usuarios a desarrollar rápida y fácilmente sus propias aplicaciones.</p>
  
