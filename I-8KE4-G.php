<center><strong>Unidad de Adquisición de Datos de E / S Ethernet Embebida, comunicable a través del protocolo RS-232 y Modbus TCP. Se puede usar en aplicaciones remotas de adquisición y control de datos. Admite temperaturas de funcionamiento entre -25 ° C y + 75 ° C (-13 ° F ~ 167 ° F).</strong></center><br>


<p>I-8KE4 e I-8KE8 son unidades de E / S Ethernet integradas que utilizan el protocolo DCON Firmware.ICP DAS USA ofrece varios módulos de E / S de adquisición de datos para aplicaciones remotas de monitoreo y control en la supervisión del entorno, alimentación gestión y automatización de fábrica, etc. a través de puerto Ethernet o puerto RS-232. La CPU es un 80186-80 de 16 bits (80 MHz). Además de las funciones originales (entrada, salida, valor de encendido, valor seguro, valor límite alto, valor límite bajo) del módulo de E / S, el firmware proporciona funciones adicionales para permitir que los módulos de E / S en diferentes ranuras se combinen juntos . Por ejemplo, si el valor del canal de un módulo AI está por encima de un valor límite alto predefinido, o por debajo de un valor límite inferior predefinido, la información se puede pasar inmediatamente a otro módulo DO para activar la alarma o la luz. Se proporcionan varios kits de desarrollo de software (SDK) y demos, como DLL, ActiveX, controlador Labview, controlador de Indusoft, controlador de Linux, servidor OPC, etc. Aunque todos los controladores SDK admiten solo la interfaz del puerto COM, los usuarios también pueden usar el SDK instalando la utilidad VxComm. La utilidad VxComm puede crear un puerto COM virtual para mapear el puerto Ethernet, luego los módulos de E / S se pueden agregar fácilmente a la I-8KE4 / I-8KE8 y se pueden integrar rápidamente en un sistema existente.
</p><BR><br>


<strong>Caracteristicas:</strong>
<ul>
  <li>Admite IPv4.</li>
  <li>Admite la interfaz de comunicación Ethernet o RS-232.</li>
  <li>Admite el protocolo de comunicación DCON</li>
  <li>Dual Bus diseñado para admitir </li>
  <li>módulos de E / S de la serie I-8K e I-87K , como DI / DO, AI / AO, </li>
  <li>módulos de contador / frecuencia</li>
  <li>La ranura de expansión de E / S compacta permite la instalación rápida de varios módulos de E / S de 8K y 87K</li>
</ul>

