<center><strong>Salida PWM de 8 canales y módulo de entrada digital aislado de 8 canales.</strong></center><br>

<p align="justify">PWM (modulación por ancho de pulso) es una poderosa técnica para controlar circuitos analógicos. Utiliza salidas digitales para generar una forma de onda con variante de ciclo de trabajo y frecuencia para controlar circuitos analógicos. I-8088W tiene 8 canales de salida PWM y 8 entradas digitales. Se puede usar para desarrollar un sistema de control analógico potente y rentable.</p>

<strong>Caracteristicas:</strong>
<ul>
<li>Generación automática de salidas PWM por hardware, sin intervención del software.</li>
<li>Frecuencia de salida PWM de 10 Hz a 500 kHz (no continua) con ciclo de trabajo de 0.1% ~ 99.9%</li>
<li>Modo de activación de software y hardware para salida PWM</li>
<li>Salida PWM individual y síncrona</li>
<li>Al usar el modo de activación por software, puede configurar la configuración de todos los canales PWM y luego activarlos uno por uno o todos al mismo tiempo.</li>
<li>Modo de ráfaga de funcionamiento PWM para modo de espera</li>
<li>El canal DI se puede configurar como un canal de entrada digital simple o una fuente de activación de hardware de la salida PWM.</li>
</ul>



