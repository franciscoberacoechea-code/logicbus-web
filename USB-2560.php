  <li>Admite alta velocidad (480 Mbps) y velocidad máxima (12 Mbps).</li>
  <li>Solo admite modo autoalimentado +10 ~ +30 V CC de entrada de alimentación (adaptador de alimentación incluido para USB-2560/S).</li>
  <li>Admite el estado del puerto de bajada con LED.</li>
  <li>Montaje en Riel DIN.</li>
