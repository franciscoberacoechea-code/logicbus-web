          <p>I-7067 es un módulo de adquisición de datos de salida de relé de 7 canales para el monitoreo del sistema de acondicionamiento de señales. Al proporcionar una configuración de valor segura, I-7067 es una solución rentable para una amplia gama de señales y sistemas de control industrial. La utilidad DCON puede ayudar a los usuarios a configurar y probar el módulo de salida de relé I-7067. Las diversas funciones de la biblioteca y los programas de demostración que proporciona facilitan a los usuarios el desarrollo de programas en los sistemas operativos Windows, Linux y DOS. I-7067 se comunica a través del protocolo Modbus a través de RS-485. Los usuarios pueden montar el módulo en un riel DIN, panel o pared. Los módulos tienen un bloque de terminales de tornillo para conectarse a las señales. El módulo de adquisición de datos de salida de relé I-7067 se puede utilizar en varias aplicaciones, como automatización y control industrial, automatización de fábrica, monitoreo remoto, etc.</p><BR>

