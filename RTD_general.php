    <tr>
      <td height="31" colspan="2" valign="top"><div align="justify">Los <strong>RTD </strong> son sensores  de temperatura resistivos. En ellos se aprovecha el efecto que tiene la temperatura en la conducci&oacute;n de los electrones  para que, ante un aumento de temperatura, haya un aumento de la resistencia el&eacute;ctrica  que presentan.</div></td>
    </tr>
    <tr>
      <td height="20" colspan="2" valign="top">&nbsp;</td>
    </tr>
    <tr>
      <td height="31" colspan="2" valign="top"> <div align="justify">Este efecto suele aproximarse a un sistema de primer o segundo orden para facilitar los c&aacute;lculos. Los sensores RTD suelen ir asociados a montajes el&eacute;ctricos tipo Puente de Wheatstone, que responden a la variaci&oacute;n de la resistencia el&eacute;ctrica por efecto de la temperatura para originar una se&ntilde;al anal&oacute;gica de 4-20 mA que es la que se utiliza en el sistema de control correspondiente como se&ntilde;al de medida. </div></td>
