          <p>Los transductores de corrientes que ofrece logicbus se utilizan para aplicar corrientes inductivas elevadas medidas en los Transductores de Corriente. Transductores de corriente para profesionales para la inspección y control sistemas de regulación y control. Los transductores de corriente transforman corrientes de 1 A o 5 A en por ejemplo 4 ... 20 mA o 0 ... 10 V. Sin embargo, los transductores se utilizan además para transformar corrientes de proceso en otra señal normalizada. Junto a estas dos funciones, los transductores también se emplean como transductores aislados, lo que significa que la señal de entrada y de salida asciende respectivamente a 4...20 mA, y que estos están separados galvánicamente. Esto representa una ventaja cuando otros transductores no disponen de entradas y salidas separadas galvánicamente. Los transductores de corrientes se montan con frecuencia en combinación con convertidores de corriente en la tecnología energética. La señal emitida por los transductores pueden ser valoradas por un sistema de visualización o un analizador de red. Esto aporta una gran seguridad, ya que en la tecnología de procesos no aparecen corrientes elevadas
