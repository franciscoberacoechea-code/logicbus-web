                <center><strong>Módulo de 8 canales de salida de relevador, servidor web integrado para lógica de control IF-THEN-ELSE, alimentación y comunicación a través de Ethernet y Modbus TCP.</strong></center><br>
                <br>

                <p> 
                    WISE-7167 sigue la especificación Power-over-Ethernet (PoE) de IEEE 802.3af (clasificación, Clase 1). Puede ser alimentado por el puerto Ethernet PoE, que agrega más flexibilidad y mayor eficiencia para los usuarios. De esta manera, puede simplemente el diseño del sistema, ahorrar espacio, reducir cables y costos. En el caso de un entorno no PoE, el controlador WISE-7151 también puede ser alimentado por fuentes de alimentación auxiliares como adaptadores de CA o batería, etc.<br><br>

                    El controlador WISE-7167 se comunica a través del protocolo Modbus TCP para integrarse fácilmente con el software SCADA. Cuenta con salidas de relé de potencia de 8 canales. Cada relé de potencia admite una clasificación de contacto de 5 A a 250 VCA o 5 A a 30 V CC.
                </p><br>

                <strong>Caracteristicas:</strong>
                <ul>
                    <li>Puede enviar alarmas de correo electrónico y SMS a los usuarios según las condiciones configurables</li>
                    <li>Servidor web incorporado para una fácil configuración</li>
                    <li>Motor de reglas IF-THEN-ELSE incorporado para control lógico</li>
                    <li>No se requieren habilidades de programación. La configuración se puede hacer en un navegador web regular con unos pocos clics.</li>
                    <li>Admite operaciones de E / S, contador, temporizador y correo electrónico</li>
                    <li>Se comunica a través de Modbus TCP y puede integrarse con Modbus I / O y el software SCADA.</li>
                    <li>Cumpla con el estándar IEEE 802.3af Power over Ethernet (PoE)</li>
                    <li>Equipado con puerto Ethernet 10/100 Base-TX</li>
                    <li>Aislamiento bidireccional / Protección ESD</li>
                    <li>16 Entrada digital de contacto húmedo (sumidero, fuente)</li>
                    <li>Tipo de OD: 8 Power Relay (Forma A)</li>
                </ul>
                <br>

                <strong>Aplicaciones:</strong>
                <ul>
                    <li>Automatización de edificios</li>
                    <li>automatización de fábricas</li>
                    <li>automatización de máquinas</li>
                    <li>mantenimiento remoto</li>
                    <li>diagnóstico remoto</li>
                    <li>equipos de prueba</li>
                </ul>
