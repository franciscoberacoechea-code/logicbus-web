                  </li>
                  <br>
                  La función modbus soporta 4 registros habilitados (iMemory_AI, iMemory_AO, iMemory_DI,
                  iMemory_DO), puedes usarlo para guardar datos definidos por el usuario (como datos E/S expandidos).
                  Cuando el cliente Modbus/TCP query a la unidad de control principal I-8000E -MTCP, La función
                  principal de Modbus regresará los datos de 4 registros al cliente.
                </ul>
              </div>

