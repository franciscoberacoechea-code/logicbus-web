<p><a href="convertidores_info#CAN">CAN</a> (Controlador de área de red) es un sistema de bus serial especialmente creado para estructurar redes de dispositivos industriales inteligentes e construir sistemas de control automáticos.  El I-7565 es un dispositivo rentable para el acoplamiento del bus CAN a la PC mediante la interfaz USB estándar.  Ahora en días, la interfaz está presente en cada PC y es soportada por MS-Windows 98, Me, 2000 y XP.  Al establecer la conexión entre el I-7565 y la PC durante el funcionamiento de la computadora, la PC automáticamente carga el controlador del dispositivo (hot plug & play).</p>

