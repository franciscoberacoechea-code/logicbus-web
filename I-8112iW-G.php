<center><strong>Módulo de E/S de adquisición de datos de alto rendimiento con 2 puertos RS-232 aislados.</strong></center><br>

<p align="justify">El I-8112iW-G proporciona 2 puertos serie aislados RS-232. Está equipado con un hardware FIFO de 128 bytes para cada puerto y ofrece velocidades de hasta 115.2 kbps con soporte para comunicación full-duplex.<br><br>
En el duro entorno industrial, los dispositivos de protección de ESD a bordo pueden desviar esta carga potencialmente dañina de los circuitos sensibles y proteger el I-8112iW del daño permanente.<br><br>
Los módulos de comunicación en serie están diseñados para su uso con dispositivos inteligentes como lectores de código de barras, impresoras en serie, sensores inteligentes, equipos de instrumentación, computadoras y casi cualquier dispositivo con puerto RS-232.</p>

<strong>Caracteristicas:</strong>
<ul>
<li>Módulo de alto perfil.</li>
<li>Puerto en serie con +/- 4 kV de protección ESD.</li>
<li>Velocidad en baudios de hasta 115200 bps.</li>
<li>Bajo consumo de energía.</li>
<li>Hecho de materiales ignífugos (nivel UL94-V0).</li>
<li>Aislamiento de 2500 Vrms.</li>
<li>Hardware FIFO interno de 128 bytes para cada puerto.</li>
<li>Indicadores LED para TxD, RxD y estado de energía.</li>
<li>En conformidad con RoHS y sin halógeno.</li>
</ul>



