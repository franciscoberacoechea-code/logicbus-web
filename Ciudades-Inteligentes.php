<p align="justify">La tecnología evoluciona exponencialmente, una de las ramas principales que ha estado creciendo, es la Automatización, teniendo ejemplos como lo son cuestiones cotidianas como el abrir un portón, tener siempre agua caliente y/o cuestiones sofisticadas como el llegar a casa y contar con la iluminación que a nosotros nos gusta, sonando la música preferida, pero aquí no paramos, existen la tendencia de tener mayor confort, ya que la suma del bienestar es también al momento de ir a nuestro trabajo, tengamos vías de acceso rápido, sabiendo de antemano donde estacionarnos para evitar perdida de tiempos, despreocuparnos de nuestros bienes, teniendo opciones de monitorearlos, este concepto se le empieza a denominar Ciudades Inteligentes.<br>
Como parte del contenido desarrollado en base a la automatización de las ciudades inteligentes, hemos entrevistado al Director de la empresa Logicbus SA de CV el Ingeniero Blasioz Valenzuela, quien amablemente nos ha prestado de su valioso tiempo para responder algunas preguntas.</p><br>

<div align="center"><h2>¿QUÉ SON LAS CIUDADES INTELIGENTES?</h2></div><br>
<p align="justify">En general, una definición que le podemos dar a una Ciudad Inteligente, sería aquella ciudad en la cual se utilizan de forma intensiva las tecnologías de la información y la comunicación (TIC), tanto para la creación, e incluso para el mejoramiento de cada uno de los componentes que conforman la ciudad.
Es decir, una Ciudad Inteligente, es considerada como tal cuando soluciones intensivas en TIC son parte de ella, de forma que tiende a desarrollar una gran capacidad para procesar y transformar información, capaz de crear y recopilar datos masivamente, para hacer mejores y más eficientes sus procesos y servicios. Abriendo la puerta a una mejor calidad de vida, basada en el uso de estos recursos.
Ahora bien, seguramente te estarás preguntando, cuáles son esas TIC de las cuales tanto se hace énfasis. Pues a continuación describiremos algunas, para que tengas una idea más clara.</p><br>

<div align="center"><h2>COMPONENTES DE LAS CIUDADES INTELIGENTES</h2></div><br>

<h2>A. La industria automotriz</h2><br>

<p align="justify">En las ciudades, la movilidad es de vital importancia, y más cuando las personas se deben trasladar a distancias extensas. Actualmente tenemos trasporte que recorre distancias largas, pero aun con esto tenemos que trasladarnos de alguna manera de la terminal a nuestro lugar de destino, se tiene la posibilidad de tener nuestro propio vehículo, pero esto es beneficioso cuando no son horas pico, puesto que dentro de estos horarios se detiene el tránsito, se genera mayor contaminación y la calidad de vida no es la apropiada.
Una propuesta que se ha estado desarrollando es un coche urbano limpio y eficiente, que promete una movilidad personal a bajo costo, solucionando a gran medida el trasporte público.

