<p align="justify">El modelo LCB500 es una celda de carga de tensión y compresión (puede usarse como extremo de barra con placas de montaje) para actuadores en línea o gatos hidráulicos con roscas macho / hembra. El modelo estándar de celda de carga de tensión y compresión LCB500 tiene roscas macho / hembra, es una unidad soldada y viene con un receptáculo Bendix. El Flexure es ideal para pruebas de resistencia.

Esta celda de carga de tensión y compresión tiene alta precisión, excelente resistencia a altas cargas extrañas y alta rigidez. Tiene una no linealidad de ± 0.25% y una desviación de 0.002 a 0.005” nom. La celda de carga de tensión y compresión LCB500 estándar se puede modificar o personalizar para cumplir con sus requisitos.</p>

