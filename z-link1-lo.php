<li>Cumple con las normas ETSI y el cifrado de datos AES128</li>
<li>Z-LINK1-LO puede operar en base a entradas-salidas remotas o en modo puente con comunicación en modo punto a punto o punto a multi-punto</li>
<li>La tecnología LoRa permite al radio del módem lograr una gran cobertura (aumenta 1 km con antena externa), con un poder de 40mW en transmisión con máxima inmunidad al ruido y sensibilidad.</li>
