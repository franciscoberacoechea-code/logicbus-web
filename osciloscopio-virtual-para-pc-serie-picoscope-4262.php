            <li>Alimentado por USB</li>
          </ul>

          <p>La mayoría de los osciloscopios digitales han sido diseñados para ver señales digitales rápidas. La tendencia ha sido utilizar la nueva tecnología únicamente para aumentar la velocidad de muestreo y el ancho de banda. Sin embargo, con el PicoScope 4262, nos hemos centrado en lo que es importante para medir señales analógicas: aumentar la resolución, mejorar el rango dinámico y reducir el ruido y la distorsión.</p>

          <p>El resultado es un osciloscopio / analizador de FFT que tiene un nivel de rendimiento para avergonzar a la mayoría de los analizadores de audio, pero tiene un ancho de banda de 5 MHz, lo que lo hace igualmente adecuado para señales de vibración y ultrasonido, así como una amplia gama de tareas de medición de precisión.</p>

          <p>Muchas aplicaciones, como el análisis de vibración, requieren capturas largas a altas tasas de muestreo, lo que requiere una memoria de captura profunda. El PicoScope 4262 tiene una memoria intermedia de muestra de 16 millones, por lo que puede capturar a 10 MS / s para bases de tiempo de hasta 100 ms / div. Si necesita más tiempo, el modo de transmisión USB puede muestrear directamente en la memoria de la PC.</p>

          <h2>Pantalla avanzada</h2>

          <p>El software PicoScope dedica casi toda el área de visualización a la forma de onda. Esto asegura que la cantidad máxima de datos se vea a la vez. El área de visualización es mucho más grande y de mayor resolución que con un alcance de mesa tradicional.</p>

          <p>Con una gran área de visualización disponible, también puede crear una visualización de pantalla dividida personalizable y ver múltiples canales o diferentes vistas de la misma señal al mismo tiempo. Como muestra el ejemplo, el software incluso puede mostrar múltiples trazados de osciloscopio y analizador de espectro a la vez. Además, cada forma de onda que se muestra funciona con ajustes individuales de zoom, panorámica y filtro para una máxima flexibilidad.</p>

          <p>El software PicoScope se puede controlar mediante métodos abreviados de mouse, pantalla táctil o teclado.</p>


          <h2>Analizador de espectro FFT</h2>

          <p>La vista de espectro representa la amplitud frente a la frecuencia y es ideal para encontrar ruido, interferencia o distorsión en las señales. El analizador de espectro en PicoScope es del tipo de Transformada Rápida de Fourier (FFT) que, a diferencia de un analizador de espectro de barrido tradicional, puede mostrar el espectro de una forma de onda única y no repetitiva.</p>

          <p>Una amplia gama de configuraciones le permite controlar el número de bandas de espectro (bandejas FFT), tipos de ventanas, escala (incluido log / log) y modos de visualización (instantánea, promedio o retención de pico).</p>

          <p>Puede visualizar múltiples vistas de espectro junto con vistas de osciloscopio de los mismos datos. Un conjunto completo de mediciones automáticas en el dominio de la frecuencia se puede agregar a la pantalla, incluyendo THD, THD + N, SNR, SINAD y IMD. Se puede aplicar una prueba de límite de máscara a un espectro e incluso puede utilizar el modo AWG y el espectro juntos para realizar un análisis de red escalar barrida.</p>

          <h2>Generador de función y forma de onda arbitraria</h2>

          <p>El PicoScope 4262 tiene un generador de funciones incorporado de 20 kHz (seno, cuadrado, triángulo, voltaje de CC, rampa, sinc, gaussiano, medio seno, ruido blanco y PRBS). El generador de funciones ofrece un excelente rendimiento de distorsión de onda sinusoidal de 102 dB SFDR.</p>

          <p>Además de los controles básicos para establecer el nivel, el desplazamiento y la frecuencia, los controles más avanzados le permiten barrer en un rango de frecuencias. Combinado con la opción de retención de pico de espectro, esto constituye una herramienta poderosa para probar las respuestas de amplificador y filtro.</p>

          <p>Las herramientas de activación permiten que se produzcan uno o más ciclos de una forma de onda cuando se cumplen varias condiciones, como la activación del alcance o el fallo de una prueba de límite de máscara.</p>

          <p>Además de las formas de onda estándar disponibles en el generador de funciones, se pueden crear formas de onda personalizadas utilizando el generador de formas de onda arbitrarias (AWG) de 16 bits / 192 kS / s. Las formas de onda AWG se pueden crear o editar con el editor incorporado, importarse desde las trazas del osciloscopio o cargarse desde una hoja de cálculo.</p>

