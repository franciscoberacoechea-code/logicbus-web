<strong><center>Convertidor/aislador de voltaje AC/DC a corriente DC, con entrada AC/DC (0~500Vac/ 0~540Vdc) configurable por DIP Switch y salida 4 a 20mA. Aislamiento galvanico de 3 vias (alimentacion, entrada y salida). Montaje en riel DIN. Alimentacion de 5~28Vdc</center></strong>

<div align="right">
