<center><strong>Módulo de comunicación del bus CAN inteligente de 1 puerto.</strong></center><br>


<p>CAN (Controller Area Network) es un bus de comunicación serial especialmente adecuado para interconectar dispositivos inteligentes para construir sistemas o subsistemas inteligentes. Admite de manera eficiente el control distribuido en tiempo real con un nivel muy alto de seguridad. En las redes CAN, no hay direccionamiento de suscriptores o estaciones en el sentido convencional, sino que se transmiten mensajes priorizados. Como controlador CAN independiente, I-8120W con MCU (unidad de control principal) WinPAC-8000 / ViewPAC-2xWx / XPAC-8000 / XPAC-8000-CE6 representa una solución económica. Tiene un puerto de comunicación CAN con conector de terminal de tornillo de 5 pines, y es útil para una amplia gama de aplicaciones CAN. Además, I-8120W usa el nuevo Phillips SJA1000T y el transceptor 82C250, que proporcionan funciones específicas de retransmisión CAN 2.0A y 2.0B, arbitraje de bus y detección de errores. Combinando los beneficios de la MCU de la serie WinPAC-8000 / ViewPAC-2xWx / XPAC-8000 / XPAC-8000-CE6 sin aumentar en gran medida la carga de la CPU, podría ser un potente servidor de dispositivo programable con varios CAN procesando el programa en la CPU 186 -8120W. También se puede comunicar con otros tipos de interfaz de comunicación, como los puertos RS-232 / RS-485 / Ethernet para que sean un servidor de dispositivo programable. Por lo tanto, los usuarios pueden diseñar las distintas aplicaciones entre diferentes protocolos de comunicación.
</p><BR><br>


