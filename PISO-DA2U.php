<center><strong>PCI universal, incluye 2 canales independientes de salida análoga de 12 bit, aislamiento de protección del bus y canal de 3750 VDC, Salida unipolar o bipolar disponible para cada convertidor de +/- 10V, +/-5V, 0-10V, 0-5V, 0-20mA y 4-20mA. Cuenta con software para calibración. Provee de dos conectores DB9 macho.</strong></center><br>

<p style="text-align: justify;">El PISO-DA2U tiene 2 canales de salida analógica con protección de aislamiento de alto voltaje y proporciona una interfaz PCI universal (3.3 V / 5 V). El PISO-DA2U es totalmente compatible con el PISO-DA2, y los usuarios pueden reemplazar el PISO-DA2 por el PISO-DA2U directamente sin modificación de software / controlador.<br>

Los componentes de aislamiento de alta calidad incorporados en el PISO-DA2U lo hacen con 3750 VDC de tipo bus y aislamiento de canal de canal, y ofrecen capacidades duraderas. Para el PISO-DA2U, los rangos de salida de voltaje son +/- 10 V, +/- 5 V, 0 ~ + 10 V y 0 ~ + 5 V y los rangos de salida de corriente son 0 ~ 20 mA y 4 ~ 20 mA. Además, el PISO-DA2U también presenta las siguientes ventajas gracias a la innovación de ICP DAS:<br>

1. Calibración precisa y fácil de usar:

ICP DAS proporciona la calibración del software en lugar de la calibración manual, de modo que ya no se requieren jumpers y trim-pots. Los datos de calibración se pueden guardar en la EEPROM para uso a largo plazo.<br>

2. Configuración de canal a canal:

Cada canal se puede configurar individualmente como salida de tensión o corriente con un rango de salida diferente.<br>

3. Identificación de la tarjeta:

ICP DAS proporciona la función de identificación de tarjeta para PISO-DA2U. Los usuarios pueden establecer una identificación de tarjeta para cada tarjeta de modo que cuando se utilizan más de dos placas en una computadora en el mismo momento, los usuarios pueden reconocerlas instantáneamente una a una.<br>

PISO-DA2U es compatible con una amplia gama de sistemas operativos como Linux, DOS, Windows 98, Windows 2000, Windows NT y Windows XP de 32 bits. Además, ICP DAS proporciona todos los DLL y Active X para los usuarios, y muestra programas que abarcan desde Turbo C ++, Borland C ++, Microsoft C ++, Visual C ++, Borland Delphi, Borland C ++ Builder, Visual Basic, C # .NET, Visual Basic.NET y ¡LabView también se proporciona para un aprendizaje intuitivo y rápido!</p>

