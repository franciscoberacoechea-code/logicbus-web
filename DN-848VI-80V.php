        <p>La serie DN-800V es un atenuador de entrada de voltaje. El rango de entrada máximo es de ± 80 V a +/- 600 V y
          puede atenuarse a ± 10 V. La versión "I" proporciona aislamiento de intra-módulos de 3000 VCC y aislamiento de
          canal a canal de 3000 VCC para evitar la interferencia de ruido de las entradas a las salidas o canal a canal
          Se puede usar con módulos de entrada analógica como I-7017 e I-87017, etc. para medir el alto voltaje.</p>

        <strong>Características:</strong>
        <ul>
          <li>Entrada de fuente de CA / CC.</li>
          <li>Medición de entrada de alto voltaje.</li>
          <li>Relación de atenuación lineal.</li>
          <li>Alta impedancia de entrada.</li>
          <li>Aislamiento de canal a canal para DN-848VI-10V, DN-848VI-80V, DN-848VI-150V y DN-843VI-600V.</li>
          <li>Aislamiento de canal a canal para DN-848VI-10V, DN-848VI-80V y DN-848VI-150V.</li>
          <li>Protección contra ESD de 4 kV.</li>
          <li>Protección contra sobretensiones de 3 kV.</li>
          <li>Conformidad con la RoHS.</li>
          <li>Temperatura de funcionamiento: -25 ° C ~ +75 ° C.</li>
          <li>Conexión de cable fácilmente.</li>
