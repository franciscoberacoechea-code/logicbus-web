        <p>
          El sensor de torque de reacción TFF400 de FUTEK con Thru Hole Center presenta una solución de montaje de brida
          a brida con medidas de torsión que van desde +/- 5 in-oz hasta 500 in-lb ( ± 0.04 Nm a 60 Nm) y una rigidez
          torsional de 325 in-oz / rad a 199,000 in-lb / rad. El TFF400 utiliza tecnología de galgas extensométricas de
          lámina de metal y cuenta con protección de sobrecarga para unidades de baja capacidad para ayudar a prevenir
          daños por sobrecarga que pueden ocurrir durante la instalación.</p><br>

