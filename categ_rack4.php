<strong>Unidad esclavo de E/S programable con protocol <a href="Modbus">Modbus </a></strong><br>
<p align="justify">Modbus es un protocolo ampliamente conocido en el campo de manufactura industrial y monitoreo ambiental. Es útil para aplicaciones de E/S distribuiidas de maestro-esclavo. La unidad es tiene pre-instalado un firmware Modbus. Por lo tanto, la PC, HMI o PLC puede usar Modbus/TCP y Modbus/RTU para comunicarse con módulos de E/S en la unidad por medio de la interfaz RS-232/485 o de Ethernet.
<br><br>
Además de la funcionalidad de esclavo E/S, también es un controlador programablebasado en lenguaje C que tiene equipado un sistema operativo MiniOS7. Los usuarios pueden usar compiladores C que pueden crear archivos ejecutables (*.exe) de 16 bits para desarrollar un programa y después descargarlo al controlador. Estp deja que el controlador funciones de manera autónoma. Existen 2 versiones de compilador sin cargo (Turbo C 2.0 y Turbo C++ 1.01), se sugiere a los usuarios usar el Turbo C++ 1.01 
<br><br>
Usando las herramientas de desarrollo del software proporcionamos, se puede configurar el firmware. El SDK proporciona ricas funciones para comunicaciones Modbus, como Modbus/maestro/esclavo TCP, Modbus/RTU maestro/esclavo, Modbus/ASCII maestro, etc. </p>

