      <td colspan="2"><div align="justify">The UEIModbus&trade; cubes are compact, rugged, Ethernet based data acquisition and control interface that communicates with a host computer or PLC over Modbus TCP. The UEIModbus 300-1G provides slots for 3 I/O boards and is 4" x 4" x 4". Its flexibility allows you to configure one or more cubes to match the specific I/O requirements of your application. The UEIModbus is ideally suited for a wide variety of industrial monitoring and control applications. The Modbus messaging protocol was developed by Modicon in 1979 and is used to establish master-slave/client-server communication between intelligent devices. It is a defacto standard, truly open and the most widely used network protocol in the industrial manufacturing environment. Modbus devices communicate using a master-slave configuration. Only one device (the master) can initiate transactions (called queries). The other devices (slaves) respond by supplying the requested data to the master, or by taking the action requested in the query. The UEIModbus 300-1G Cube functions as a Modbus slave that is easily accessed by any software client acting as a Modbus master. Most popular HMI software supports the Modbus protocol.<br>
          <br>
          The UEIModbus supports all AI, AO, DI, DO and CT layers that are compatible with UEI&rsquo;s Cube architecture. Analog input channels are read using two input registers encoded as a single 32-bit floating point value. Analog output channels are written to using two holding registers encoded as one 32-bit floating point value. Digital input ports are read using one or two input registers (depending on the port width). Each digital input line is also available as a discrete input register. Digital output ports are written using one or two holding registers (depending on the port width) and similar to the digital inputs, each digital output line is also available as a coil register. Counter or quadrature encoder inputs are read using one or two input registers (depending on the counter resolution).<br>
          <br>
          The heart of every UEIModbus system is the Cube. Each UEIModbus Cube consists of two primary subsections: a Core Module and I/O slots or layers. The Core Module occupies the top portion of the Cube and provides the PowerPC CPU running the Modbus TCP server software. The core modules also provides the dual Gigabit Ethernet Network Interface Controller (NIC), indicator lights, timing/trigger interface, configuration ports and internal power supply. It&rsquo;s the brains of the Cube and controls the unit&rsquo;s operations including reading and writing to the I/O boards in the cube.<br>
          <br>
          The remainder of the UEIModbus Cube is dedicated to I/O slots or layers. These slots are populated with I/O modules selected to match your application. With over 30 different I/O boards available, we&rsquo;re sure to have just what your application requires. We offer: Analog input boards to measure voltage, current, strain gages, thermocouples and more, Analog output boards with outputs to &plusmn;40V or &plusmn;50 mA, Digital I/O interfaces for logic and &ldquo;real-world&rdquo; signal levels, counters/timers, and quadrature encoder inputs.<br>
