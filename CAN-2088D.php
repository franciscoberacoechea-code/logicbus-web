<center><strong>PWM de 8 canales y contador de alta velocidad de 8 canales y entrada digital</strong></center><br>

<p>El módulo esclavo DeviceNet de 8 canales PWM y 8 canales de alta velocidad de 32 bits de contador y entrada digital, admite temperaturas de funcionamiento de -25 ° C ~ + 75 ° C (-13 ° F ~ + 167 ° F).</p>

<strong>Características: </strong>
<ul>
<li>La aplicación CAN-2088DPWM (modulación de ancho de pulso) es una técnica poderosa para controlar circuitos analógicos.</li>
<li>Utiliza salidas digitales para generar una forma de onda con variante de ciclo de trabajo y frecuencia para controlar circuitos analógicos.</li>
<li>CAN-2088D es un módulo esclavo PWM del protocolo DeviceNet.</li>
<li>Tiene 8 canales de salida PWM y 8 canales de contador de alta velocidad.</li>
<li>Se puede usar para desarrollar un sistema de control analógico potente y rentable.</li>
</ul>
<strong>Aplicaciones: </strong>
<ul>
<li>Controlar la posición / velocidad de los motores.</li>
<li>Atenuar el brillo de las lámparas.</li>
<li>Controlando la velocidad de los fanáticos.</li>
<li>Contador de alta velocidad.</li>
</ul>
