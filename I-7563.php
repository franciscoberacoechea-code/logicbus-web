<p>El I-7563 es un módulo rentable para transferir datos en serie a través de USB. Le permite conectar sus dispositivos serie a sistemas que usan una interfaz USB. Al conectar el I-7563 a una PC, obtendrá un puerto COM en el sistema.<br>
El I-7563 contiene "Auto-sintonizador", este chip sintoniza automáticamente la velocidad de transmisión en baudios y el formato de datos a la red <a href="https://www.logicbus.com.mx/convertidores_info#RS-485">RS-485</a>. El módulo I-7563 deriva su energía del puerto USB y no necesita ningún adaptador de corriente.
<br><br>
El I-7563 es un convertidor RS-485 USB a 1 canal con un concentrador RS-485 de 3 vías. Cada canal contiene su propio IC controlador RS-485, por lo que puede admitir el cableado en forma de estrella.</p>

        <ul><strong>Caracter&iacute;sticas:</strong>
          <li>Compatibilidad: USB 1.1 y 2.0 est&aacute;ndar.</li>
          <li>Especificaciones USB 1.1 de alta velocidad.</li>
          <li>Puerto de entrada: USB.</li>
          <li>Puerto de salida: RS-485 de tres v&iacute;as.</li>
          <li>Velocidad: "Self Tuner".</li>
          <li>Protecci&oacute;n de aislamiento de 3000 Vdc.</li>
          <li>256 m&oacute;dulos max.(todos los canales).
            <ul>
              <li>Red RS-485 sin repetidor.</li>
              </ul>
          </li>
          <li>2048 m&oacute;dulos max. (todos los canales).
            <ul>
              <li>Red RS-485 con repetidor.</li>
              </ul>
          </li>
          <li>Petici&oacute;n de repetidor: 4,000 pies o sobre 256 m&oacute;dulos.</li>
          <li>Instalaci&oacute;n Plug and Play.</li>
          <li>El I-7563 obtiene energ&iacute;a desde el puerto USB; no necesita una fuente externa.</li>
          <li>Soporta controladores para Windows 98/ME/2000/XP y Linux.</li>
          <li>Montaje: Riel-DIN.</li>
        </ul>
     
