<p align="justify">La serie μPAC-5000 es un controlador de automatización programable del tamaño de la palma de la mano. Tiene una CPU 80186, SRAM, Flash, puerto Ethernet, puerto RS-232 y RS-485. Con un sistema operativo tipo DOS (MiniOS7) y un firmware desarrollado en su interior, puede actuar como una pequeña PC.<br>
ICP DAS proporciona kits de herramientas de desarrollo de software fáciles de usar (servidor X, marco MiniOS7, VxComm, bibliotecas Modbus). Los usuarios pueden usarlos para integrar fácilmente dispositivos serie para tener capacidad de comunicación Ethernet / Internet y mediante el protocolo Modbus estándar para comunicarse con el software SCADA (Indusoft, ISaGARF, DasyLab, Trace Mode, Citect, iFix, etc.).<br>
Para la expansión de hardware, también admite un bus de expansión de E / S. El bus de expansión de E / S se puede usar para implementar varias funciones de E / S como D / I, D / O, A / D, D / A, temporizador / contador, UART y otras funciones de E / S. Este bus puede implementar casi todo tipo de funciones de E / S. Pero el bus solo puede soportar una tabla. Hay más de 10 tableros disponibles para la serie μPAC-5000, puede elegir uno de ellos para expandir las características del hardware.</p>
