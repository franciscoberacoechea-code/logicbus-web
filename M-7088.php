<center><strong>Salida PWM de 8 canales y módulo de entrada digital de contador de alta velocidad de 8 canales (frecuencia), transmisible a través de RS-485 y Modbus RTU, con entrada de voltaje</strong></center><br>
 <br>

<p> 
El I-7088 proporciona una salida PWM (modulación de ancho de pulso) de 8 canales y una entrada de contador de 8 canales, y se puede utilizar para desarrollar sistemas de control analógico potentes y rentables. PWM es una poderosa técnica para controlar circuitos analógicos que usa la salida digital para generar una forma de onda con un ciclo de trabajo variable y frecuencia que luego puede usarse para controlar un circuito analógico en aplicaciones tales como controlar la posición o velocidad de los motores, el brillo de lámparas, o la velocidad de los ventiladores, etc. Se puede usar el modo de ráfaga o el modo continuo para la salida de PWM dependiendo de la aplicación. Además, todos los canales de entrada digital se pueden usar como contadores de alta velocidad con una velocidad de hasta 1 MHz. El M-7088 admite los protocolos Modbus RTU y DCON, que se pueden configurar a través del software, y todas las especificaciones de hardware son las mismas que las de la I-7088. El I-7088 (D) / S y el M-7088 (D) / S permiten aumentar la tensión de carga de +3.5 a +50 V para la salida PWM (modulación de ancho de pulso) de 8 canales y la señal de 8 canales contador de velocidad.
</p><BR>

<strong>Caracteristicas:</strong>
<ul>
<li>Salida PWM de 8 canales y entrada de contador de 8 canales.</li>
<li>Modo de ráfaga y modo continuo para salida PWM.</li>
<li>Modo de activación de software y hardware para salida PWM.</li>
<li>Salida PWM individual y síncrona.</li>
<li>Contadores de alta velocidad.</li>
<li>Protección contra ESD y EFT de 4 kV.</li>
<li>Dual Watchdog.</li>
<li>Amplio rango de temperatura de funcionamiento: -25 a + 75 ° C.</li>
</ul>
