<center><strong>Módulo de entrada digital aislado de 8 canales de 10-80 VCA con contadores de 16 bits, transmisible a través de RS-485, admite temperaturas de funcionamiento de -25 ~ 75 ° C.</strong></center><br>

<p>El M-7059 ofrece un diferencial de 8 canales para la entrada digital de CA, cada uno de los cuales cuenta con aislamiento de fotoacoplamiento para canal a canal. Su nivel de voltaje está en 80 V ~ 250 VAC. Todos los canales DI también se pueden usar como contadores de 16 bits. M-7059D tiene 8 indicadores LED para el estado del canal DI. La protección 4KV ESD y el aislamiento intramódulo 4000V son estándar.</p><BR>

<strong>Caracteristicas</strong>

<ul>
<li>Entradas digitales de CA</li>
<li>Entradas diferenciales</li>
<li>Aislamiento de fotoacoplamiento</li>
<li>DI se puede usar como contadores</li>
<li>Protección contra ESD de 4 kV</li>
<li>Voltaje de aislamiento de 4000 Vrms</li>
<li>Dual Watchdog</li>
<li>Conformidad con la RoHS</li>
<li>Amplia gama de temperatura de funcionamiento: -25 ~ 75 ° C</li>
</ul>
