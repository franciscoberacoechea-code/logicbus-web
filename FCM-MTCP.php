<center><strong>Módulo de comunicación de campo con esclavo Modbus / TCP (cubierta gris) (RoHS).</strong></center><br>

<p>El FCP-MTCP es un módulo de comunicación para el sistema iDCS-8000. Admite el esclavo Modbus / TCP, el protocolo industrial más conocido, para los PLC o controladores que admiten el maestro Modbus / TCP. Este módulo también ofrece LED para indicar el diagnóstico del sistema y el estado de la conexión Ethernet localmente. Además, se proporcionan dos interruptores rotativos para configurar instantáneamente ID (dirección IP) para otro FCM-MTCP. Además, el módulo ofrece aislamiento de 1000 VDC entre canales y bus de fondo. Si cualquier alto voltaje o corriente daña los canales, el sistema (placas base, otros módulos y la unidad de control) no se verán afectados debido al beneficio del aislamiento.</p>

Caracteristicas:
<ul>
<li>Modbus / TCP esclavo.</li>
<li>Intercambiables en caliente.</li>
<li>Permitir 4 conexiones de acceso simultáneamente.</li>
<li>Conformidad con la RoHS.</li>
<li>Aislamiento de 1000 VDC.</li>
<li>Redundancia.</li>
</ul>
Aplicaciones:
<ul>
<li>Automatización de edificios.</li>
<li>Automatización industrial.</li>
<li>Automatización de máquinas.</li>
<li>Mantenimiento remoto.</li>
<li>Diagnóstico remoto.</li>
<li>Equipo de pruebas.</li>
</ul>
