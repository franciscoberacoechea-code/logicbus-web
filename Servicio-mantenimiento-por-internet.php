<div align="center"><h2>II. PROCESO DE CONSULTA </h2></div><br>
<p>Los ingenieros de los fabricantes de equipos industriales siempre tienen que visitar el lugar cuando sus clientes solicitan asistencia técnica. Debido a que los usuarios de equipos industriales generalmente no pueden hacer frente a los problemas del programa por sí mismos, y este tipo de problema siempre es difícil de manejar sin estar en el lugar. La ocurrencia de este tipo de problema indica que costará mucho el gasto de tráfico de los fabricantes y el tiempo de inactividad de los usuarios, especialmente para aquellos en diferentes países.</br></br>

<div align="center"><h2>QUÉ PASA SI LOS INGENIEROS PUEDEN EDITAR Y MANTENER EL PROGRAMA A TRAVÉS DE INTERNET?</h2></div><br>

<p align="justify">ICP DAS proporciona tales soluciones para este tipo de problema. Mediante el uso de los PAC μPAC-7186 emparejados, se puede vincular un dispositivo remoto a la computadora del fabricante por Internet y dejar que los encargados de mantenimiento diagnostiquen, editen, depuren y mantengan su programa. ¡ Incluso la actualización del firmware también está disponible<br>
En la siguiente imagen se muestra, un μPAC-7186 está conectado a la computadora del fabricante y el otro está conectado al PLC remoto del equipo. Mediante la conexión por pares a través de Internet, el programa del PLC se puede mostrar en la pantalla del fabricante. El mantenedor del fabricante puede editar el programa mediante herramientas de desarrollo local o cargar nuevos programas al PLC.
