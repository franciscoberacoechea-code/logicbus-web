      <td colspan="2">
        <p>Los rack, también conocidos  como gabinetes o chasis, es la parte medular de un sistema PLC, ya que permiten  la conexión física o ensamble a todos los componentes de Entrada/Salida, de  igual manera, funciona como vinculo de comunicación o bus de comunicación entre  dichas partes.</p>
        <p>DeviceNet es un protocolo de red basado en el bus CAN, utilizado principalmente en redes embebidas para control de maquinaria industrial 
          como: equipo textil, impresoras, maquinas de inyección, empaquetadoras, etc. DeviceNet es una red de bajo nivel especializada en la
          comunicación de dispositivos simples (sensores, actuadores) con equipo de alto nivel (controladores). Permite intercambio de datos 
          entre los diferentes nodos de una forma organizada y determinista. Esta red define un esquema de conexión para facilitar el desarrollo 
          de aplicaciones que involucren comunicación entre múltiples puntos que requieren compartir información.</p>
      <p>Las unidades CAN-8124/8224/8424 basadas en un diseño modular ofrecen buenas características al usuario y flexibilidad en el manejo y 
      adquisición de los datos. Además, estos dispositivos cuentan con un software que permite configurarlos y crear archivos EDS 
      (hoja electrónica de datos) para módulos de entradas/salidas específicos presentes en la red. El usuario puede conectar fácilmente los 
      módulos CAN-8124/8224/8424 dentro de una red de DeviceNet. </p></td></tr>
