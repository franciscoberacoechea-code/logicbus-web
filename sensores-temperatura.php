            <p><strong>Termopares -</strong> son los más utilizados en los dispositivos de medición de temperatura. Al
                estar
                conectados en pares, son simples y eficientes que dan salida a un voltaje DC muy pequeño proporcional a
                la
                diferencia de temperaturas entre dos juntas en un circuito termoeléctrico cerrado.</p>

            <p><strong>RTD –</strong> Miden la temperatura mediante la correlación de la resistencia del elemento del
                RTD
                con la temperatura. La mayoría de los RTD consiste en un pedazo de alambre enrollado bien envuelto con
                un
                núcleo de cerámica o vidrio alrededor.
                Los RTD son inmunes al ruido eléctrico y adecuado para medir la temperatura en ambientes industriales,
                por
                ejemplo, alrededor de motores, generadores y equipos de alta tensión.</p>

            <p><strong>Termistores –</strong> Usan electrodos internos que detectan el calor y lo miden a través de
                impulsos
                eléctricos. Dicho de otras palabras un termistor es un resistor sensible a la temperatura. Existen dos
                tipos:
            </p>

            <ul>
                <li>Termistores NTC - Un termistor NTC debe elegirse cuando es necesario un cambio continuo de la
                    resistencia
                    en una amplia gama de temperaturas. Ofrecen estabilidad mecánica, térmica y eléctrica, junto con un
                    alto
                    grado de sensibilidad. </li>
                <li>Termistores PTC - deben elegirse cuando se requiere un cambio drástico en la resistencia a una
                    temperatura
                    específica o nivel de corriente.</li>
            </ul>

            <p><strong>Infrarrojo -</strong> Los sensores de temperatura infrarrojos o sondas de temperatura por
                infrarrojos, son sensores para medida de temperatura sin contacto. Esto permite realizar medidas de
                temperatura con alta precisión para rangos amplios de temperatura.</p>

