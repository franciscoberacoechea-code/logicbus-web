      <td colspan="2"><div align="justify">The DNR-AI-255 is a two-channel Synchro/Resolver input and output boards for powerful RACKtangle&reg; I/O chassis. The board is suitable for a wide variety of test, measurement and control applications as well as for simulated outputs for test and simulator applications. The board may be configured as two inputs, two outputs, or one input and one output.<br>
          <br>
          The board provides 2 input channels that will monitor either 3-wire synchros or 4-wire resolvers. The board's high precision circuitry combined with each channel&rsquo;s independent 16-bit A/D converter allow measurement accuracies up to &plusmn;2.6 arc-minutes. The inputs may be read at rates up to 800 rps, depending upon the reference frequency.<br>
          <br>
          Each channel provides its own programmable reference with outputs independently programmable from 2 to 28 Vrms at frequencies from 50 to 4,000 Hz and up to 1.2 VA. The DNR-AI-255 also provides two channels of synchro or resolver output that are ideal for driving such items as attitude indicators or as a test source for a wide variety of synchro or resolver input devices. The outputs each accept an independent reference signal and offer 16-bit output resolution. Each channel will drive up to 28 Vrms at 1.2 VA without external buffering.<br>
          <br>
          The board offers 350 Vrms of isolation between channels as well as between the I/O connections and the RACKtangle chassis. Like all DNx I/O boards, the DNA-AI-255 offers operation in harsh environments and has been tested to 5g vibration, 50g shock, -40 to +85 &deg;C temperatures, and altitudes up to 70,000 feet in Cube based systems.<br>
          <br>
      Software for the DNR-AI-255 is provided as part of the UEI Framework. The framework provides a comprehensive yet easy to use API that supports all popular Windows programming languages as well as supporting programmers using Linux and most real-time operating systems including QNX, RTX, RT Linux and more. Finally, the Framework supplies complete support for those creating applications in LabVIEW, MATLAB/Simulink, DASYLab or any application supporting ActiveX or OPC servers.</div></td>
