<p align="justify">Z109REG2 es un convertidor universal avanzado capaz de gestionar todas las señales analógicas (mA, V, PT100, Pt1000, Pt500, Ni100, TCs, Ohms) y convertirlo / aislarlo en señales mA / V estándar. El dispositivo se puede configurar a través de dip-switches, software para PC o dispositivos de mano. Un contacto digital está disponible como ALARMA o STROBE (multiplexación). Se puede solicitar con una fuente de alimentación baja o alta. Un aislamiento galvánico de 3 vías entre la fuente de alimentación // los circuitos de entrada / salida asegura la integridad de sus fechas.</p>

<strong>Caracteristicas:</strong>
<ul>
<li>Entrada universal: tensión, corriente, termopares, termorresistencias, potenciómetro, reóstato.</li>
<li>Alimentación del sensor en técnica de 2 cables: 20 Vcc estabilizada, 20 mA máx.</li>
<li>protegida contra cortocircuito.</li>
<li>Medición y retransmisión en salida analógica aislada, con salida en tensión y en corriente activa/pasiva.</li>
<li>Selección mediante conmutadores DIP de: tipo de entrada, START-END, modo de salida (elevación de cero, inversión escala), tipo salida (mA o V).</li>
<li>Indicación en placa frontal de presencia de alimentación, fuera de escala o error de configuración, estado alarma.</li>
<li>Salida contacto de alarma de relé (spst), configurable mediante PC.</li>
<li>Entrada de STROBE para activar la salida analógica por mando de un PLC (como alternativa al contacto de alarma).</li>
<li>Posibilidad de programación mediante PC de inicio y final escala, tipos de entrada adicionales, extracción de raíz, filtro, burn-out, etc.</li>
<li>Aislamiento entre alimentación y salida retransmitida o entradas de medición: 3750 Vac.</li>
<li>Aislamiento entre entradas de medición y salida retransmitida: 1500 Vac</li>
</ul>

