	    <p>El USB-1602HS-2AO muestrea las dos entradas anal&oacute;gicas, entradas digitales y entradas de contadores simult&aacute;neamente. Puede sincronizar operaciones de entradas y salidas anal&oacute;gicas y digitales a tasas de hasta 1 MS/s, cun un desempe&ntilde;o agregado de 8 MS/s. </p>
