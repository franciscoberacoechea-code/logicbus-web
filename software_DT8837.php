<strong>Software incluido:</strong>
  <p><strong>VIBpoint Framework (Evaluación)</strong> – Esta aplicación soporta las  series del DT9837, y los módulos DT9838, DT9839, DT9839E, DT9847. Descubre y  selecciona el hardware disponible, configúralo y guarda las configuraciones,  obtiene y muestra datos, realiza operaciones FFT de canal sencillo y doble,  guarda información al disco, archivo o ábralo en MS Excel.</p>
  <p><strong>Controlador DT8837 IVI-COM</strong> –Este controlador provee acceso a  las funciones del modulo DT8837  a través  de un Servidor COM. El controlador trabaja con cualquier ambiente de  desarrollo  que soporte programación COM incluyendo  MATLAB, Visual Basic .NET, Visual C# .NET, Agilent VEE Pro, LabVIEW,  LabWindows, y otros.</p>
  <p><strong>Software de Soporte:</strong></p>
  <p><strong>Eureka Discovery Utility</strong> – Ayuda a localizar o descubrir todos los instrumentos LXI (Ethernet) que están conectados a tu sistema y provee la siguiente información sobre tu instrumento: Dirección IP, Fabricante, modelo, serial, versión de firmware que corre en tu instrumento. Además, puedes usar esta utilidad para configurar las opciones del Windows Firewall y actualizar el firmware de tu instrumento LXI de Data Translation.</p>
  <p><strong>Soporte SCPI</strong> – SCPI (Comandos Estandar para Instrumentos Programables) es un lenguaje de programación universal para pruebas electrónicas e instrumentos de medición, basado en IEEE 488.1 y IEEE 488.2. VOLTpoint, TEMPpoint y MEASURpoint son compatibles con el lenguaje de SCPI. Puedes utilizar comandos de SCPI sobre VISA o sockets. La instalación incluye el manual de programación de SCPI para instrumentos de medición LXI, la documentación para su instrumento y ejemplos de programas escritos en Visual C# y Visual C++.</p>
  <p><strong>Utilería de Calibración de DT8837</strong> – Permite calibrar las  entradas y salidas análogas del dispositivo en el campo. Usando esta utilería puede  revertir a los valores de fábrica para cualquier canal. Esta utilería incluye  archivo de ayuda que describe el equipo y el proceso requerido para la calibración.</p>

