<p>La serie DL-300 de dispositivos Data Logger puede usarse para registrar información de CO, CO2, temperatura, humedad y punto de rocío, incluidas las marcas de fecha y hora, y puede almacenar hasta 450,000 registros descargables.<br><br>

Se puede acceder a los datos en tiempo real desde el registrador de datos DL-300 desde cualquier lugar y en cualquier momento utilizando el software gratuito de Windows, la aplicación iOS o la aplicación Android.<br><br>

Se proporciona soporte para protocolos industriales populares como DCON, Modbus RTU y Modbus TCP, así como el protocolo de conectividad emergente máquina a máquina (M2M) /) IoT (Internet de las cosas) - MQTT. El registrador de datos DL-300 se puede conectar a través de interfaces de comunicación ampliamente utilizadas, como RS-485, Ethernet y PoE, lo que significa que el dispositivo se puede integrar fácilmente en los sistemas HMI o SCADA existentes, y es fácil de mantener en un sistema de control distribuido.

</p><br>


