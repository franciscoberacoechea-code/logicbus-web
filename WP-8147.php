<center><strong>ISaGRAF IEC61131 basado en Windows Controlador de automatización programable (PAC) con Windows CE .NET 5.0 OS, VGA, Ethernet, USB, RS-485 y puertos RS-232 y 1 ranura de E / S. Admite temperaturas de funcionamiento entre -25C y 75C (-13F ~ 167F).</strong></center><br>


<p>La serie ISaGRAF WinPAC-8000 (WP-8137/8437/8837 / 8147/8447/8847) es la nueva generación de PAC. Cada uno está equipado con una CPU PXA270 (520 MHz), una variedad de puertos de entrada / salida (VGA, USB, Ethernet, RS-232/485) y una gama de ranuras de E / S que se pueden utilizar para integrar alto rendimiento paralelo Módulos de E / S (serie I-8K de alto perfil) o módulos de E / S en serie (serie I-87K de alto perfil). Los beneficios de ejecutar Windows CE 5.0 en un dispositivo WinPAC incluyen capacidad dura en tiempo real, tamaño de núcleo pequeño, velocidad de arranque rápida, manejo de interrupciones a un nivel más profundo y control determinista alcanzable. Los dispositivos WinPAC también son capaces de ejecutar ISaGRAF y el software de control basado en PC, como Visual Basic .NET, Visual C #, etc., que proporcionan todas las mejores características de los PLC tradicionales y PC con capacidad para Windows.
</p><BR><br>


<strong>Caracteristicas:</strong>
<ul>
<li>PXA270, CPU a 520 MHz</li>
<li>Windows CE 5.0</li>
<li>Embedded ISaGRAF Ver.3 SoftLogic (IEC 61131-3)</li>
<li>Capacidad dura en tiempo real</li>
<li>Salida de puerto VGA</li>
<li>Modbus RTU / TCP (maestro, esclavo)</li>
<li>Admite eLogger HMI</li>
<li>Entradas de energía redundantes</li>
<li>Temperatura de funcionamiento: -25 ~ +75 ° C</li>
</ul>

