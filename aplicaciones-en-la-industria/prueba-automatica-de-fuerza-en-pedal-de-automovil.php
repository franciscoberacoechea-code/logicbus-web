                <p class="light-black">Los sensores de celda de carga de pedal FUTEK son adecuados para pruebas automotrices en apoyo de las siguientes normas:</p>
                <ul>
                    <li class="mb-3">SAE J2909: Procedimiento de prueba de distancia de frenado en seco y mojado para vehículos livianos (prueba de freno).
