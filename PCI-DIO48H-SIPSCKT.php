<strong>Descripción General</strong><br>
<p align="justify">La PCI-DIO48H/SIPSCKT es una tarjeta digital de E/S de alta densidad con sockets SIP para instalar resistencias pull-up/pull-down. La PCI-DIO48H/SIPSCKT ofrece 48 bits de E/S digitales. Proporciona grupos de 24 bits de E/S basados en el 82C55, modo 0. Cada grupo proporciona un puerto A y un puerto B de 8 bits así como un puerto C de 8 bits que puede ser dividido en 2 puertos C de 4 bits: Puerto C-Hi, Puerto C-LO.<br><br>
Los drivers de salida digital son chips 74S244 y prporcionan capacidades de corriente de 64 mA sink y 15 mA source.<br>
El uso de resistencias pull-up y pull-down son importantes si necesitas configurar un valor fijo para evitar que el valor de entrada sea flotante</p><br>


