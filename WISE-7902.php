<center><strong>Módulo PoE de E / S remota de FRnet con MiniOS7</strong></center><br>
 <br>

<p> 
WISE (Web Inside, Smart Engine) es una serie de productos desarrollada por ICP DAS que funciona como unidades de control para su uso en control y monitoreo lógico remoto en diversas aplicaciones industriales. WISE ofrece una interfaz de sitio web intuitiva y fácil de usar que permite a los usuarios implementar la lógica de control IF-THEN-ELSE en los controladores a solo unos clics de distancia; no se requiere programación Con sus características potentes y fáciles de usar, minimizará la curva de aprendizaje, acortará el tiempo de comercialización y reducirá drásticamente el esfuerzo y el gasto en el desarrollo del sistema.<br><br>

WISE-7902 sigue la especificación IEEE 802.3af (clasificación, clase 1) de alimentación sobre Ethernet (PoE). Permite recibir energía de la red habilitada para PoE mediante pares Ethernet (cable Ethernet de categoría 5). Esta característica proporciona una mayor flexibilidad y una mayor eficiencia, por lo tanto, simplifica el diseño de los sistemas, ahorra espacio, reduce los cables y elimina la necesidad de enchufes eléctricos dedicados. Mientras tanto, en el caso de un entorno no PoE, WISE-7902 aún podrá recibir energía de fuentes de alimentación auxiliares como adaptadores de CA o batería, etc.<br><br>

Este módulo WISE-7902 es compatible con el protocolo Modbus / TCP para una integración perfecta con el software SCADA disponible. Admite un bus de expansión de E / S para implementar diversas funciones de E / S, como D / I y D / O, de acuerdo con el uso de los módulos de FRnet: FR-2053T, FR-2054T y FR-2057T.</p><BR>

<strong>Caracteristicas:</strong>
<ul>
<li>Servidor web incorporado para la configuración de reglas IF-THEN-ELSE</li>
<li>Enigne regla IF-THEN-ELSE enigne para la operación lógica</li>
<li>No más programación. ¡Simplemente haz clic y termina!</li>
<li>Soporte IO, contador, temporizador, operaciones de correo electrónico</li>
<li>Protocolo Modbus / TCP para la integración sin fisuras del software SCADA</li>
<li>Energía sobre Ethernet (PoE) compatible con IEEE 802.3af</li>
<li>10/100 Base-TX Ethernet</li>
<li>Bus de expansión de E / S</li>
<li>Soporta módulos FRnet: FR-2053T, FR-2054T, FR-2057T</li>
</ul>
<br>

<strong>Aplicaciones:</strong>
