            <p>El <strong>osciloscopio</strong> es básicamente una herramienta que permite ver resultados gráficos de las señales eléctricas. Este dispositivo incluye una pantalla en donde se muestran las gráficas de la señal eléctrica aplicada en función del tiempo. Un <strong>osciloscopio</strong> puede medir hasta miles de magnitudes físicas, solo que se necesita la sonda adecuada que pueda convertir la magnitud para medir en una señal eléctrica. Debido a la inmensa diversidad de medidas y magnitudes que pueden ser estudiados con los <strong>osciloscopios</strong>, estos se utilizan en campos que abarcan desde la medicina hasta la mecánica del automóvil.</p>
            <p>A la vista de todos, un <strong>osciloscopio</strong> es como una televisión portátil, salvo una rejilla que es ocupada por la pantalla y el mayor número de controles que lo contiene, les presentaremos en la siguiente figura la representación de estos controles distribuidos en 5 secciones:</p>
