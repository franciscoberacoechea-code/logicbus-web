<p align="justify">El SeaI / O-570E, diseñado con el chip A / D de Linear Technology LTC1867, proporciona ocho entradas analógicas de 16 bits de extremo único, ocho entradas aisladas ópticamente y ocho salidas de relé en forma C.
<br> Las entradas A / D son seleccionables por software independientemente para rangos de +/- 5V o +/- 15V y cuentan con una alta impedancia de entrada, lo que permite una fácil conexión a una variedad de sensores. Las entradas A / D admiten selecciones flotantes / no referenciadas o referenciadas en tierra. Esto hace que las entradas A / D sean ideales para medir fuentes de señales flotantes, como salidas de transformadores, termistores y dispositivos alimentados por batería. Además, las entradas A / D pueden operar en modo bipolar o unipolar, y un interruptor DIP permite una tensión de polarización de +5 a través de una resistencia de 10K para el modo de entrada de termistor.
<br><br>
El módulo SeaI / O-570E cuenta con ocho entradas aisladas ópticamente para 5-30V DC y proporciona un aislamiento externo de 3500V DC, mientras que los relés de Forma C se pueden configurar como normalmente abiertos o normalmente cerrados y pueden conmutar cargas de CC de hasta 24 W. Perfecto para una variedad de aplicaciones de adquisición / control de datos y de prueba y medición, el SeaI / O-570E incluye bloques de terminales extraíbles, que simplifican las conexiones de cableado de campo. 
<br><br>
El SeaI / O-570E se alimenta desde su fuente de 9-30V DC, o se selecciona de una variedad de opciones de fuente de alimentación de Sealevel. Los módulos funcionan en un amplio rango de temperatura de operación de -20C a + 70C y el rango de temperatura extendido es opcional.
<br><br>
Comuníquese con el SeaI / O-570E utilizando el protocolo Modbus TCP estándar de la industria o use las bibliotecas de software SeaMAvel API de Sealevel desde su programa de aplicación. Los controladores y utilidades del software SeaMAX de Sealevel facilitan la instalación y el funcionamiento con los sistemas operativos Microsoft Windows 10 y 8. 
<br><br>
La aplicación Sealevel Modbus Connect para iOS le permite acceder a los registros, bobinas y E/S discretas de sus dispositivos Sealevel Modbus y está disponible en la App Store. Utilice la aplicación para acceder de forma remota a la E/S en el campo o para realizar pruebas y solucionar problemas durante el desarrollo de la aplicación.
<br><br>
Amplíe su red de E/S con los productos de la serie N de SeaI / O. Los módulos SeaI / O están disponibles con relés Reed y Form C, entradas aisladas ópticamente, interfaces TTL, funcionalidad A / D y D / A. Se pueden agregar hasta 246 módulos de expansión adicionales usando los conectores de paso convenientes.
