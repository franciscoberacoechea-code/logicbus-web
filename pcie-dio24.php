<h1>PCIe-DIO24</h1><BR>

<center>
<img src="imagenes/01/pcie-dio24.jpg" alt="PCIe-DIO24" title="PCIe-DIO24" width="40%" class="image_productos">
</center><br>

<div align="right"><a href="https://tienda.logicbus.com.mx/PCIE-DIO24_p_1259.html" title="Ir a Tienda" target="_blank"><img src="images/shopping_cart.png" alt="" border=0 width="40"></a></div><br>

<center><strong>La placa digital PCIe-DIO24 tiene bus PCI Express. Las características incluyen 24 DIO, lógica seleccionable, salida de alta corriente y emulación de modo 0 82C55.</strong></center><br><br>

<p align="justify">El PCIe-DIO24 proporciona 24 líneas de E/S digital con niveles lógicos seleccionables de 3.3 V y 5 V. Las 24 líneas DIO están organizadas en tres grupos de 8 bits cada uno (Puerto A, Puerto B y Puerto C). El puerto C se puede dividir en dos puertos de cuatro bits (Puerto C-HI y Puerto C-LO). La dirección de cada puerto se puede configurar de forma independiente con software para entrada o salida. Las salidas digitales son lógicas de HC y pueden generar y hundir 2.5 mA. El PCIe-DIO24 tiene una red de resistencia de 10 k asociada con cada puerto digital. Puede configurar cada puerto para desplegar o desplegar con software. Al encender y reiniciar, la configuración de cada puerto se lee desde la EEPROM. La placa se envía con cada puerto configurado en el estado de pull-up. Las líneas de E/S digitales son accesibles a través de un conector tipo D de 37 pines. La placa tiene dos fusibles individuales de golpe lento clasificados a 0,375 amperios para proteger las salidas + VDIO y + 12V en el conector. Se proporciona un fusible de repuesto. Los programas de software escritos con la Biblioteca Universal para dispositivos USB-DIO24/37, PCI-DIO24 y CIO-DIO24 son totalmente compatibles con PCIe-DIO24. La alimentación es proporcionada por la ranura PCI Express. La placa PCIe-DIO24 es completamente plug-and-play. Todas las direcciones de la placa son establecidas por el software plug-and-play de la placa. La configuración de la placa es controlada por el BIOS del sistema.</p><br>

<strong>Características:</strong>
<ul>
<li>24 canales de E/S digitales con niveles lógicos seleccionables de 3.3 V y 5 V:<br>Puerto A 8 bits, Puerto B 8 bits, Puerto C 8 bits (que se pueden dividir en 4 bits C-HI y 4 bits C-LO)</li>
<li>Conecta y reproduce</li>
<li>Emula el modo cero 82C55.</li>
<li>Software seleccionable con configuraciones de resistencia de pull-up y pull-down</li>
<li>Se accede a las líneas de E/S digitales a través de un conector tipo D de 37 pines</li>
<li>Compatibilidad de software y conector con PCI-DIO24 y CIO-DIO24</li>
</ul>

