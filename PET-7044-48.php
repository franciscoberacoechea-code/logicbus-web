<p>PET-7044-48 proporciona 8 salidas de colector abierto aislado (tipo sumidero) y 8 canales de entrada digital de contacto húmedo (sumidero, tipo fuente). Cada canal de salida admite una corriente de 300mA @ 10 ~ 40VDC y cada canal de entrada digital admite entrada de contador (32 bits y 500Hz máximo). <br>
El Power-over-Ethernet (PoE) permite transferir energía y datos a través de un solo cable Ethernet, por lo que el dispositivo puede operar únicamente a partir de la potencia que recibe a través del cable de datos. Esta innovación permite una mayor flexibilidad en el diseño de la oficina, una mayor eficiencia en el diseño de sistemas y un tiempo de respuesta más rápido en la configuración e implementación. <br>
PET-7044-48 cuenta con verdadera potencia IEEE 802.3af (clasificación, Clase 1) sobre Ethernet (PoE) utilizando ambos pares de Ethernet (cable Ethernet de Categoría 5). PET-7044-48 puede recibir energía de una fuente de alimentación auxiliar, como adaptadores de CA y baterías, además de la red habilitada para PoE. Esta es una característica deseable cuando el requisito de potencia total del sistema excede la capacidad de carga del PSE. Con la opción de alimentación auxiliar, PET-7044-48 se puede utilizar en un sistema Ethernet estándar (no PoE). <br>
PET-7044-48 es un módulo de E / S Ethernet PoE basado en web que cuenta con un servidor web incorporado, que permite la configuración, el monitoreo de E / S y el control de E / S a través de un navegador web común. Con la función HMI web, no se necesitan habilidades de programación o HTML; la creación de páginas web dinámicas y atractivas para la supervisión de E / S y el control de E / S puede ser divertido. ¡PET-7044-48 ofrece un acceso fácil y seguro para los usuarios en cualquier momento y en cualquier lugar! PET-7044-48 también es compatible con el protocolo Modbus / TCP para una perfecta integración de PET-7044-48 con el software SCADA.<BR></p>        

