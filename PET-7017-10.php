<p>El PET-7000, un módulo de E / S Ethernet basado en web, cuenta con un servidor web incorporado que permite la configuración, el monitoreo de E / S y el control de E / S simplemente usando un navegador web común. El control remoto es tan fácil como navegar por Internet.<BR>

Además, con la función HMI web, no se requieren más habilidades de programación o HTML; la creación de páginas web dinámicas y atractivas para el monitoreo de E / S y control de E / S sería divertido para los ingenieros para siempre. ¡El PET-7000 ofrece un acceso fácil y seguro para los usuarios desde cualquier lugar y en cualquier momento! Además, el PET-7000 también es compatible con el protocolo Modbus / TCP que hace una integración perfecta con el software SCADA.<BR>

Además, PET-7000 presenta "PoE" que no solo los datos, sino también la energía se transmite a través de un cable Ethernet. Esta característica hace que la instalación de PET-7000 sea sencilla. Imagine que ya no necesita cables innecesarios, solo un cable Ethernet se encarga de todo en el campo.<BR>

El ET-7017-10 es un módulo de entradas analógicas de 16 bits, 10 canales o 20 canales de salida única que proporciona un rango de entrada programable en todos los canales analógicos (+/- 150 mV, +/- 500mV, +/- 1 V, +/- 5 V, +/- 10 V, +/- 20 mA, 0 ~ 20 mA y 4 ~ 20 mA). Cada canal analógico puede configurar un rango individual y tiene una protección de sobretensión de 240 Vrms. Puente seleccionable para entrada de voltaje o corriente. La tasa de muestreo de PET-7017 es variable; hay modo rápido y modo normal para su consideración. PET-7017 también tiene calificación para protección de ESD de 4 kV así como aislamiento intramódulo de 3000 VDC.<BR></p>        

