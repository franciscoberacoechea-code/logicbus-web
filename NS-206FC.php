<center><strong>Ethernet Industrial Ethernet 10/100 de 4 puertos, no gestionada, con interruptor de fibra óptica Dual BaseFX doble con conector SC. Admite temperaturas de funcionamiento de 0 ° C ~ + 70 ° C.</strong></center><br>

<p>El NS-206FC (conector SC; modo múltiple) es un Industrial 10/100 Base-T (X) no gestionable de 4 puertos con conmutador dual de base 100 FX que asegura la transmisión de datos mediante la transmisión de fibra óptica para proporcionar inmunidad frente a EMI / Interferencia RFI. Utiliza Ethernet para transmitir una señal de hasta 2Km (6,600 pies), y es la solución perfecta para aplicaciones donde la transmisión debe protegerse contra la exposición eléctrica, sobrevoltajes, rayos o corrosión química. El NS-206FC funciona en modo dúplex medio o completo. En modo dúplex completo, el rango es de 2Km con cables de fibra de 62.5 / 125μm; en modo half duplex, el rango es de 412 m con cables de fibra de 62.5 / 125μm. El NS-206FC puede ampliar su LAN en una configuración de conexión en cadena. Por favor refiérase a Hardware. El Ethernet admite la función de autonegociación 10 / 100M y la función automática MDI / MDIX.</p><BR>

<strong>Caracteristicas</strong>

<ul>
<li>Crossover automático MDI / MDI-X para plug-and-play.</li>
<li>Cada puerto admite una negociación automática de velocidad de 10/100 Mbps.</li>
<li>Arquitectura de almacenamiento y reenvío.</li>
<li>Control de flujo de contrapresión Full Duplex IEEE 802.3xy semidúplex.</li>
<li>Ancho de banda de memoria de alto rendimiento de 1.6 Gbps.</li>
<li>Frame buffer memory: 256 Kbit.</li>
<li>Motor de búsqueda integrado con direcciones MAC dedicadas de 1 K unicast.</li>
<li>Admite voltaje +10 ~ + 30Vdc.</li>
<li>Admite temperaturas de funcionamiento de 0 ° C ~ + 70 ° C.</li>
<li>Montaje en raíl DIN para uso industrial.</li>
</ul>
