<center><strong> Ethernet Industrial 10/100 BaseT de 4 puertos no administrada con conmutador de fibra dual Dual BaseFX con conector SC.</strong></center><br>

<p>El NSM-206FCS (conector SC, monomodo) es un Industrial 10/100 Base-T (X) de 4 puertos no gestionado con conmutador dual 100 Base-FX que asegura la transmisión de datos mediante la transmisión de fibra óptica para proporcionar inmunidad frente a EMI / Interferencia RFI. Utiliza Ethernet para transmitir una señal de hasta 15 Km, y es la solución perfecta para aplicaciones donde la transmisión debe protegerse contra la exposición eléctrica, sobrevoltajes, rayos o corrosión química. El NSM-206FCS funciona en modo dúplex completo. En modo dúplex completo, el alcance es de 15 Km con cables de fibra de 8.3 / 125, 8.7 / 125, 9/125 o 10/125 μm. El NSM-206FCS puede ampliar su LAN en una configuración de conexión en cadena. Por favor refiérase al Manual del Usuario. NSM-206FCS proporciona dos entradas de alimentación que se pueden conectar simultáneamente a fuentes de alimentación de CC en vivo.</p><BR>

<strong>Caracteristicas</strong>

<ul>
<LI>Crossover automático MDI / MDI-X para plug-and-play.</LI>
<LI>Cada puerto admite una negociación automática de velocidad de 10/100 Mbps.</LI>
<LI>Arquitectura de almacenamiento y reenvío.</LI>
<LI>Control de flujo de contrapresión Full Duplex IEEE 802.3xy semidúplex.</LI>
<LI>Ancho de banda de memoria de alto rendimiento de 1.6 Gbps.</LI>
<LI>Entradas de alimentación redundantes +10 ~ + 30V DC.</LI>
<LI>Alarma de falla de energía por salida de relé.</LI>
<LI>Admite temperaturas de funcionamiento de 0 ° C ~ + 70 ° C.</LI>
<LI>IP20, resistente carcasa de metal de alta resistencia.</LI>
<LI>Carril DIN; Montaje en la pared.</LI>
</ul>
