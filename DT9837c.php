<tr><td colspan="3"><div align="justify">
  <p><strong>DAQ para Sonido y Vibración portable</strong><br>
La serie DT9837C son módulos de adquisición de  señales dinámicas de alta precisión ideales para mediciones portables de ruido,  vibraciones y acústicas. Cuatro sensores de 24 bits tipo IEPE (ICP) son  sincronizados con una entrada de tacómetro para proveer flujos de datos que son  comparados en tiempo. Realizado en material resistente, de tamaño pequeño y  alimentado por USB, lo hace ideal para aplicaciones de medición portable.<br>
Características</p>
  <ul>
    <li>4 canales simultáneos de 24 bits Delta-Sigma Análogos/Digitales</li>
    <li>Soporte para entradas IEPE, incluyendo el uso de  una fuente de corriente de 4mA</li>
    <li>Hasta 52.7 kHz por canal</li>
    <li>Sincroniza múltiples módulos para cada canal de expansión  usando el conector de sincronización Ethernet RJ45 (LVDS)</li>
    <li>Opción de BNC o OEM disponibles</li>
  </ul>
