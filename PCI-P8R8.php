<center><strong>Tarjeta PCI con 8 entradas digitales aisladas y 8 salidas de relevador.</strong></center><br>


<p>El PCI-P8R8 proporciona salida de relé electromecánico de 8 canales y entrada ópticamente aislada de 8 canales. El PCI-P8R8 se puede utilizar en diversas aplicaciones, incluidas conmutación de carga, conmutación externa, cierre de contacto y otras. El PCI-P16R16 tiene uno de 37 pines D-Sub y uno de 40 pines conectores de cabecera y la función es igual a dos PCI-P8R8.<br>
El PISO-P16R16U es una versión PCI universal de la tarjeta PCI-P16R16, puede instalarse en un bus PCI de 5V o 3.3V.</p><br>

<strong>Caracteristicas</strong>

<ul>
<li>Bus PCI de 32 bits + 5V (PCI-P8R8, PCI-P16R16)</li>
<li>Bus PCI de 32 bits + 5V y + 3.3V (PISO-P16R16U)</li>
<li>Salida de relé electromecánico de 8/16 canales</li>
<li>Entrada digital ópticamente aislada de 8/16 canales</li>
<li>Entrada de señal AC / DC</li>
<li>Entrada de señal de CA con filtro</li>
<li>Indicación de LED a bordo para el estado del relé</li>
<li>Interruptor dip cardID integrado (PISO-P16R16U).</li>
</ul>
