        <p>El I-8094F es un módulo de control de servomotor de pasos / pulsos de 4 ejes que se puede usar en cualquiera
          de los controladores de la serie ICP DAS I-8000 y PAC, y es adecuado para aplicaciones de movimiento de
          propósito general. El I-8094F tiene todas las funciones del I-8094 con la adición de un puerto FRnet, que
          permite que las E / S remotas rápidas del módulo se expandan fácilmente. Este FRnet de dos hilos puede
          escanear automáticamente sus canales 128 DI y 128 DO en un período de 2,88 ms.
          <br><br>
          Además de su amplio rango de velocidad, este controlador de movimiento inteligente también tiene una variedad
          de funciones de control de movimiento integradas, como interpolación lineal de 2/3 ejes, interpolación
          circular de 2 ejes, aceleración / desaceleración de T / S, numerosas sincronizaciones acciones, búsqueda
          automática, y otros. Una gran ventaja es que la mayoría de las funciones de control de movimiento I-8094F son
          realizadas por el ASIC de movimiento de alto rendimiento con poca carga en el procesador. Mientras se manejan
          los motores, el estado de movimiento y el estado de los otros canales de E / S en los módulos I-8000 o PAC,
          aún se pueden monitorear.
          <br><br>
          Como los requisitos de carga de la CPU de la I-8094F son mínimos, se pueden usar uno o más módulos de
          movimiento con un solo controlador I-8000 o PAC. ICP DAS también proporciona una amplia gama de funciones y
          ejemplos que se pueden utilizar para reducir la necesidad de programación adicional, lo que la convierte en
          una solución altamente rentable para los desarrolladores de aplicaciones de control de movimiento.
        </p>

        Caracteristicas:
        <ul>
          <li>Control de movimiento independiente de 4 ejes.</li>
          <li>Soporte para funciones de volante y jog.</li>
          <li>Función de interpolación circular de 2/3 ejes lineal / 2 ejes.</li>
          <li>Función de interpolación continua.</li>
          <li>Aceleración y desaceleración de curva T / S programables.</li>
          <li>Una velocidad de salida de pulso máxima de 4 Mpps para cada eje.</li>
          <li>Tipos de salida de impulsos: CW / CCW o PULSE / DIR.</li>
          <li>Contador de codificador de 32 bits para cada eje.</li>
          <li>Tipos de entrada de impulsos del codificador: fase A / B o arriba / abajo.</li>
          <li>Homing automático programable para cada eje.</li>
          <li>Posición de administración de comparación y límites de software.</li>
          <li>Una amplia gama de acciones sincrónicas (acciones desencadenadas por eventos).</li>
          <li>E / S remotas ampliables: 128 DI y 128 DO a través de una interfaz FRnet de dos hilos.</li>
        </ul>
