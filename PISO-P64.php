<center><strong>Tarjeta de salida digital de 64 canales, abierta y aislada ópticamente. Incluye CA-4037B capaz y dos conectores CA-4002 D-Sub.</strong></center><br>


<p>La tarjeta PEX-P64 y PISO-P64U es el producto de nueva generación que ICP DAS proporciona para cumplir con los requisitos de cumplimiento de RoHS. La nueva tarjeta PEX-P64 y PISO-P64U está diseñada como un reemplazo directo para el PISO-P64, y los usuarios pueden reemplazar el PISO-P64 por el PEX-P64 y PISO-P64U directamente sin modificación de software / controlador.<br>

La tarjeta PCI universal PISO-P64U (-24V) admite bus PCI de 3,3 V / 5 V, mientras que la PEX-P64 (-24V) es compatible con el bus PCI Express. Estas tarjetas proporcionan 64 canales de entrada digital (DI) ópticamente aislados que utilizan una fuente de alimentación interna o externa que se puede seleccionar a través de un puente. La energía interna es proporcionada por un convertidor DC / DC aislado a bordo que proporciona aislamiento de 3000 VDC y se utiliza para conectar dispositivos de entrada de contacto seco. Estos canales DI se organizan en cuatro bancos aislados cuando se utilizan cuatro fuentes de alimentación externas aisladas. Los canales DI 0 ~ 15 se asignan al banco A, los canales DI 16 ~ 31 se asignan al banco B, los canales DI 32 ~ 47 se asignan al banco C, y los canales DI 48 ~ 63 se asignan al banco D. Los acopladores fotográficos incorporados proporcionan Aislamiento de 3750 Vrms, y actúa como interfaz para señales lógicas de campo, elimina problemas de bucle de tierra y aísla la computadora host de tensiones dañinas. Estas tarjetas contienen un solo conector DB-37 y un único conector macho de 40 pines, cada uno de los cuales contiene 32 canales de entrada. <br><br>

El PEX-P64 (-24V) y el PISO-P64U (-24V) también agregan un interruptor de identificación de tarjeta a bordo. Los usuarios pueden establecer la identificación de la tarjeta y luego reconocer la placa mediante la identificación a través del software cuando usan dos o más tarjetas PEX-P64 y PIO-P64U en una computadora. <br>

Estas tarjetas son compatibles con varias versiones del sistema operativo, como Linux, DOS, Windows 98 / NT / 2000 y Windows 8/7 / Vista / XP de 32/64 bits. El control DLL y Active X junto con varios programas de muestra de lenguaje basados ??en Turbo C ++, Borland C ++, Microsoft C ++, Visual C ++, Borland Delphi, Borland C ++ Builder, Visual Basic, C # .NET, Visual Basic.NET y LabVIEW se proporcionan para ayudar a los usuarios a desarrollar rápida y fácilmente sus propias aplicaciones.
</p><BR><br>

<strong>Caracteristicas</strong>

<ul>
<li>Soporta el bus PCI +5 V para PISO-P64.</li>
<li>Soporta el bus PCI +3.3 V / + 5 V para PISO-P64U (-24V).</li>
<li>Soporte PCI Express x1 para PEX-P64 (-24V).</li>
<li>Función de ID de tarjeta para PISO-P64U (-24V) y PEX-P64 (-24V).</li>
<li>Entrada digital ópticamente aislada de 64 canales.</li>
<li>Convertidor DC / DC incorporado que proporciona aislamiento de 3000 VDC.</li>
<li>Cuatro bancos aislados cuando utilizan cuatro fuentes de alimentación externas aisladas.</li>
<li>Protección de aislamiento de imagen 3750 Vrms.</li>
<li>Potencia interna o externa seleccionable para DI.</li>
</ul>
