 <strong>Módulo de entrada analógica RTD de 6 canales con eliminación de resistencia de cable RTD a 3 hilos. Admite los tipos RTD de Pt100, Pt1000, Ni120, Cu100 y Cu1000. Se puede comunicar a través de Modbus RTU y RS-485. Admite temperaturas de funcionamiento entre -25 a 75 ° C (-13F ~ 167F).</strong><br>
 </div>
 <br>

<p>El I-7015 es una serie de módulos de entrada RTD de 6 canales que se utilizan para medir temperaturas usando sensores RTD y cada canal se puede conectar a un tipo de sensor diferente. El I-7015P / M-7015P está diseñado específicamente para la medición de RTD a larga distancia, y cuenta con compensación automática para RTD de tres cables, lo que significa que se pueden obtener mediciones precisas independientemente de la longitud de los cables. La serie I-7015 es totalmente compatible con RoHS y cuenta con protección ESD de 4 kV y aislamiento intramódulo de 3000 VDC. El M-7015 / M-7015P es compatible con los protocolos Modbus RTU y DCON, que se pueden configurar mediante software, y todas las especificaciones de hardware son las mismas que las de la I-7015 / I-7015P.</p><br>

<strong>Características:</strong>
<ul>
<li>Entrada RTD de 6 canales.</li>
<li>Entrada RTD de 3 hilos con eliminación de resistencia del cable.</li>
<li>Alta resolución: 16 bits.</li>
<li>Configuración individual del canal.</li>
<li>Detección de cables abiertos.</li>
<li>Protección contra ESD de 4 kV.</li>
<li>Protección EFT de 4 kV.</li>
<li>Aislamiento intramódulo de 3000 VDC.</li>
<li>Dual Watchdog.</li>
<li>Amplio rango de temperatura de funcionamiento: -25 a + 75 ° C.</li>
</ul><br>



