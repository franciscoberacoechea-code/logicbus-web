<center><img src="https://www.logicbus.com.mx/imagenes/articulo/DATALOGGERS.png" class="image_productos" width ="60%" alt="ADVANCED DATALOGGER (REGISTRADOTES DE DATOS AVANZADOS)" title="ADVANCED DATALOGGER (REGISTRADOTES DE DATOS AVANZADOS)"></center>
        <p style="text-align: right; font-size: 15px" align="right"><b>By: Estrada Roque Jose Antonio - 26 de diciembre del 2018</b></p><br>
        
<p align="justify">En uno de los artículos anteriores, se expuso acerca de los dataloggers (registradores de datos), la cual un <a href="registro-de-datos-datalogger">Datalogger</a> es un dispositivo electrónico que hace registrar mediciones ordenadas en el tiempo, que viene proveniente de diferentes sensores. Cada una de las mediciones son almacenados en una memoria, junto con su hora y fecha, estos son pequeños, se atraen con baterías y están formados por un microcontrolador, una memoria para acumulación de los datos y diferentes sensores, y la gran mayoría utilizan la pc como interfaz para sistematizar al dispositivo y consultar la información recogida.<br><br>

Gracias a la tecnología que ha podido dar grandes saltos y de esta manera se puede obtener registradores más avanzados e independientes, las cuales no se necesitan de ninguna supervisión, la cual obtendrá un buen funcionamiento haciendolo más confiable y automáticos para trabajar en largos lapsos de tiempo, esto quiere decir, que estos dataloggers avanzados son muy estables en comparación a una computadora.

</p><br>

<center><img src="https://www.logicbus.com.mx/imagenes/articulo/DATALOGGER1.PNG" class="image_productos" width ="50%" alt="Figura 1. Registradores de datos avanzados de SENECA" title="Figura 1. Registradores de datos avanzados de SENECA"></center><p><center><p><center><b>Figura 1. Registradores de datos avanzados de SENECA</b></center></p><br>

<p align="justify">En <a href="https://tienda.logicbus.com.mx/">Logicbus</a> contamos con productos de REGISTRADORES DE DATOS AVANZADOS de la marca SENECA que hoy en día son vendidos en el mercado industrial, ya que es todo gracias al avance tecnológico que se puede tener estos productos al alcance.<br><br>

Logicbus presenta a los productos <a href="https://tienda.logicbus.com.mx/Z-GPRS3_p_13218.html">Z-GPRS3</a>, <a href="https://tienda.logicbus.com.mx/Z-LOGGER3_p_13221.html">Z-LOGGER3</a> y Z-UMTS, estos registradores de datos avanzados permien satisfacer las crecientes necesidades de recopilación de los datos, así como en el análisiS en tiempo real y la integración de sistemas de TI que están en línea con los nuevos conceptos de productivad y la comunicación en la industria 4.0 y el Internet de las Cosas (IoT). Estos Dataloggers son diseñados a cumplir a distancia.<br><br>

Las funciones de alarma, telemetría y registro de datos están disponibles con E / S incorporadas, software de supervisión y programación, interfaces Ethernet, puertos serie RS485 Modbus Rtu, módem 2G / 3G + y receptor GNSS / GPS / GLONASS.<br><br>

Opcionalmente, los registradores de datos se pueden combinar con Cloud BOX, una solución IoT / Cloud propuesta por SENECA que le permite centralizar datos, administrar conexiones remotas, crear páginas de supervisión personalizadas para múltiples usuarios.</p>

<h2><b>FUNCIONES ADVANCED DATALOGGER</b></h2>
<p align="justify">Z-GPRS3, Z-LOGGER3 y Z-UMTS son unidades de alto rendimiento y están configuradas como unidad maestra del sistema de E / S remotas Seneca Z-PC Line. Ofrecen una potente integración de seguridad con sistemas de terceros gracias a los estándares tecnológicos de Seneca. Estos módulos funcionan con 8 E / S incorporadas, 2 interfaces seriales con protocolo Modbus RTU, 1 puerto Micro USB y 1 puerto Ethernet de 10/100 Mbps. Los modelos con módem 2G / 3G + / GNSS + admiten diferentes tipos de SIM. Estos registradores de datos están equipados con 8 MB de memoria Flash y ranura para tarjeta Micro SD de hasta 32 GB.<br><br>

Los registradores de datos avanzados de SENECA aseguran una programación flexible permitida por un software dedicado diseñado por Seneca para el desarrollo de las lógicas de control (SEAL). Estos módulos se complementan con un servidor web incorporado, una aplicación para la gestión de comandos SMS, una herramienta de importación y visualización de datos (Log Factory). Además, la HMI ‘Cloud BOX’ permite el telemetría en tiempo real, el envío de comandos RTU, el análisis de archivos de registro, el registro de eventos y alarmas a través de páginas web personalizables mediante un widget. SENECA ofrece una potente integración de seguridad con sistemas Scada, Cloud, bases de datos y plataformas web de terceros que ya están disponibles en las plantas.</p>

