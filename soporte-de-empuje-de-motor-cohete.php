  <p><b>C&oacute;mo funciona:</b><br></p>
  <ol>
    

<li style="color: black;">En esta aplicaci&oacute;n, el motor cohete se enrosca en la celda de carga universal de la serie LCF. </li>
<li style="color: black;">El soporte del motor evita cualquier carga lateral de la celda, lo que garantiza que las celdas de carga solo reciban cargas axiales.</li>
<li style="color: black;">El conjunto de celdas de carga est&aacute; montado en un banco de pruebas fijo que asegura el motor.</li>
<li style="color: black;">En l&iacute;nea con los soportes de la base, se instalan las celdas de carga multi eje MTA400/ MTA600.</li>
<li style="color: black;">Mientras el motor est&aacute; funcionando, el empuje se mide con las celdas de carga de la serie LCF.</li>
<li style="color: black;">El flujo masivo y el arrastre (tambi&eacute;n conocido como patada) se capturan con las celdas de carga MTA400/MTA600.</li>
<li style="color: black;">Los datos del empuje se pueden transmitir en vivo y registrar para su monitoreo, revisi&oacute;n y comparaci&oacute;n posteriores con m&oacute;dulos simulados con USB220 y SENSIT.</li>
<li style="color: black;">El flujo de datos masivo de las 4 celdas de carga se capturan, transmiten y registran con USB220 y SENSIT.</li>
<li style="color: black;">Cada eje del MTA400/MTA600 se captura con un USB220 separado.</li>
<li style="color: black;">La salida de la celda de carga tambi&eacute;n se puede amplificar a trav&eacute;s de la serie IAA para su captura mediante DAQ preexistente.</li>

	
	
	
