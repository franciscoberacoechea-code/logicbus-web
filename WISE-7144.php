				<center><strong>MMódulo de 8 canales aislados de salida digital tipo sink de colector abierto, 8 canales de entrada digital aislados, servidor web integrado para lógica de control IF-THEN-ELSE, alimentación y comunicación a través de Ethernet y Modbus TCP.</strong></center><br>
