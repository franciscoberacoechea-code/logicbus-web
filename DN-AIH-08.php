        <p>El DN-AIH-08 es una placa de terminación para el módulo de entrada analógica HART. Esta placa de terminación
          no solo mide la señal analógica sino que también proporciona una fuente de alimentación aislada para los
          dispositivos de campo. En otras palabras, esta placa admite tanto el bucle activo como el pasivo. Además, si
          la placa también tiene protección contra cortocircuitos para la potencia aislada, la corriente de bucle estará
          limitada cuando el circuito se cortocircuite o la corriente sea demasiado grande. Además, el fusible extraíble
          puede proteger el dispositivo de bucle cuando se produce una corriente de entrada alta, estos fusibles también
          tienen un indicador físico cuando se rompen.</p>
