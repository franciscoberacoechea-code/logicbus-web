<center><strong>Controlador integrado con pantalla / desarrollo de siete dígitos de cinco dígitos</strong></center><br>


<p>La I-8410 y la I-8810 son unidades de E / S en serie incorporadas que utilizan el firmware de protocolo DCON. Ofrece varios módulos de E / S, como entrada / salida analógica, entrada / salida digital y módulos de contador / frecuencia, que se pueden utilizar en aplicaciones remotas de adquisición y control de datos para la supervisión del entorno, la gestión de energía y la automatización de fábrica, etc. La CPU es un 80188 de 8 bits (40MHz). Además de las funciones originales (entrada, salida, valor de encendido, valor seguro, valor límite alto, valor límite bajo) del módulo de E / S, el firmware proporciona funciones adicionales para permitir que los módulos de E / S en diferentes ranuras se combinen juntos . Por ejemplo, si el valor del canal de un módulo AI está por encima de un valor límite alto predefinido, o por debajo de un valor límite inferior predefinido, la información se puede pasar inmediatamente a otro módulo DO para activar la alarma o la luz. Se proporcionan varios kits de desarrollo de software (SDK) y demos, como DLL, ActiveX, controlador Labview, controlador de Indusoft, controlador de Linux, servidor OPC, etc. Los módulos de E / S se pueden agregar fácilmente a la I-8410 / I-8810 y puede integrarse rápidamente en un sistema existente.
</p><BR><br>


<strong>Caracteristicas:</strong>
<ul>
<li>Admite la interfaz de comunicación RS-232 o RS-485.</li>
<li>Admite el protocolo de comunicación DCON.</li>
<li>Dual Bus diseñado para admitir módulos de E / S de la serie I-8K e I-87K, como DI / DO, AI / AO, módulos de contador / frecuencia.</li>
<li>La ranura de expansión de E / S compacta permite la instalación rápida de arios módulos de E / S de 8K y 87K.</li>
</ul>

