<p>El PET-7016 es un módulo medidor de tensión con 2 canales de entrada analógica, 1 canal de salida de tensión de excitación, 2 canales de entrada digital y 2 módulos de salida digital. Proporciona varias entradas de entrada analógicas programables (+/- 1 mV, +/- 50 mV, +/- 100 mV, +/- 500 mV, +/- 1 V y +/- 2.5 V) y admite puente completo , medio puente y cuarto de puente. El rango para cada entrada analógica se puede configurar de forma individual. La salida de voltaje de excitación puede estar en el rango de 0 ~ 10 V con una eficiencia de conducción de 60 mA. Las salidas digitales también se pueden configurar como salidas de alarma. El PET-7016 también puede proporcionar mediciones de medidor de tensión de larga distancia que compensa la pérdida de voltaje resultante de las mediciones a larga distancia.</p>        

<strong>Caracteristicas:</strong>
<ul>
<li>Servidor web incorporado.</li>
<li>Web HMI.</li>
<li>Soporte para protocolos Modbus TCP y Modbus UDP.</li>
<li>Seguridad de comunicación.</li>
<li>Dual Watchdog.</li>
<li>Amplio rango de temperatura de funcionamiento: -25 ~ + 75 ° C.</li>
<li>Conexión de par de E / S.</li>
<li>E / S incorporada.</li>
<ul>
<li>Entrada del medidor de tensión: 2 canales.</li>
<li>DI / contador: 2 canales.</li>
<li>DO: 2 canales.</li>
</ul>
</ul>

<strong>Aplicaciones:</strong>
<li>Automatización de edificios.</li>
<li>Automatización industrial.</li>
<li>Automatización de máquinas.</li>
<li>Mantenimiento remoto.</li>
<li>Diagnóstico remoto.</li>
<li>Equipo de pruebas.</li>


