                    <h2><span>Osciloscopios analógicos vs digitales</span></h2>
                  </div>
                </div>
              </center>
              <br>

              <p align="justify">En la actualidad los osciloscopios analógicos están siendo desplazados en gran medida
                por los
                osciloscopios digitales, entre otras razones por la facilidad de poder transferir las medidas a una
                computadora personal o pantalla LCD.
                En el osciloscopio digital la señal es previamente digitalizada por un conversor analógico digital. Al
                depender la fiabilidad de la visualización de la calidad de este componente, esta debe ser cuidada al
                máximo.<br>
                Las características y procedimientos señalados para los osciloscopios analógicos son aplicables a los
                digitales. Sin embargo, en estos se tienen posibilidades adicionales, tales como el disparo anticipado
                (pre-triggering) para la visualización de eventos de corta duración, o la memorización del oscilograma
                transfiriendo los datos a un PC. Esto permite comparar medidas realizadas en el mismo punto de un
                circuito o
                elemento. Existen asimismo equipos que combinan etapas analógicas y digitales.<br>
                La principal característica de un osciloscopio digital es la frecuencia de muestreo, la misma
                determinara el
                ancho de banda máximo que puede medir el instrumento, viene expresada generalmente en MS/s (millones de
                muestra por segundo).<br>
                La mayoría de los osciloscopios digitales en la actualidad están basados en control por FPGA (del inglés
                Field
                Programmable Gate Array), el cual es el elemento controlador del conversor analógico a digital de alta
                velocidad del aparato y demás circuiteria interna, como memoria, buffers, entre otros.<br>
                Estos osciloscopios añaden prestaciones y facilidades al usuario imposibles de obtener con circuitería
                analógica, como los siguientes:</p>
              <li>Medida automática de valores de pico, máximos y mínimos de señal. Verdadero valor eficaz.</li>
              <li>Medida de flancos de la señal y otros intervalos.</li>
