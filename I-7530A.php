<p>El I-7530A está diseñado para liberar la potencia del bus CAN mediante el método de comunicación RS-232/485/422. Convierte con precisión mensajes entre redes CAN y RS 232/485/422. Este módulo le permite comunicarse fácilmente con dispositivos CAN desde cualquier PC o dispositivo con interfaz RS-232/485/422. El dispositivo programable RS 232/485/422 (por ejemplo: PC, PLC o PAC) puede usar el puerto serie para conectarse a la red CAN a través de la I-7530A.</p>

<strong>Caracter&iacute;sticas:</strong>
		<ul>
<li>Compatible con la especificación CAN 2.0A y 2.0B</li>
<li>Totalmente compatible con el estándar ISO 11898-2</li>
<li>Soporta diferentes velocidades de transmisión de 10 kbps a 1 Mbps</li>
<li>Puente para resistencia de terminación de 120 O</li>
<li>Software configurable CAN y RS-232 / RS-422 / Parámetros de comunicación RS-485</li>
<li>1000 cuadros en CAN buffer recibido, 900 cuadros en RS-232 / RS-422 / RS-485 recibió buffer</li>
<li>Watchdog inside</li>
<li>Proporcionar la comunicación transparente entre el Dispositivos RS-232 / RS-485 / RS-422 a través del bus CAN</li>
<li>Habilite diferentes dispositivos RS-232 / RS-485 / RS-422 en un grupo individual en la red de bus CAN (Modo de comunicación full-duplex de RS-232 / Los dispositivos RS-422 no son compatibles)</li>
		</ul>

