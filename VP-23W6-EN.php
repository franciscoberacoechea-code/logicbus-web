<p align="justify">Las aplicaciones IWS se ejecutan en microordenadores conectados en tiempo real a máquinas o procesadores a través de controladores programables WinPAC, dispositivos de E / S remotas y otros equipos de adquisición de datos. Estas aplicaciones consisten en pantallas de interfaz de operador animadas, dispositivos de E / S enrollables, una base de datos de etiquetas de aplicación y módulos opcionales como monitores de alarma, gráficos de tendencias, recetas, programadores y un sistema de seguridad.</p>
<ul>
Se proporciona un lenguaje de scripts intuitivo con más de 100 funciones estándar.
Cumple con los estándares de la industria tales como Microsoft.NET, OPC, DDE, ODBC, XML.
Completo entorno de tiempo de ejecución basado en WinCE (CE View).
Biblioteca dinámica de símbolos - personalizable.
Contenedor ActiveX (Windows NT / 2000 / XP / CE).
Se admite el correo electrónico automático (SMTP) y la interfaz de conexión de acceso telefónico.
Proporcionar seguridad de niveles múltiples para aplicaciones, incluidos Internet e Intranet.
</ul>

<strong>Características geerales de ISaGRAF:</strong><br>
<ul>
Admite cinco idiomas IEC61131-3, LD, ST, FBD, SFC, IL más FC.
Protocolo Modbus RTU / TCP para integrar al software SCADA y HMI.
Controlador a Controlador Intercambio de datos a través de Ethernet: Ebus.
Todos los módulos de E / S de la serie I-7000 e I-87K pueden integrarse como módulos de E / S remotas.
E / S de escaneo automático: escanea automáticamente las placas de E / S y declara las variables de E / S.
Movimiento: el control de movimiento está disponible cuando las placas I-8091 están integradas.
HMI Web: supervisa y controla el controlador local o remoto a través de Internet Explorer que se ejecuta en su PC.
</ul>

