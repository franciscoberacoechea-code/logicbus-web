<center><strong>Tarjeta PCI, cuenta con 168 canales de entrada/salida digital, proporciona de interrupciones programables, velocidad de respuesta alrededor de los 0.77 us (1.3 MHz máximo), bus de datos de 8 bits, provee de un conector DB37 hembra.</strong></center><br>


<p>La tarjeta PIO-D168U es el producto de nueva generación que proporciona ICP DAS para cumplir con los requisitos de cumplimiento de RoHS. La nueva tarjeta PIO-D168U está diseñada como un reemplazo directo para el PIO-D168, y los usuarios pueden reemplazar el PIO-D168 por el PIO-D168U directamente sin modificación de software / controlador.<br>

La tarjeta PCI universal PIO-D168U admite bus PCI de 3,3 V / 5 V, mientras que la PIO-D168 admite bus PCI de 5 V. Estas tarjetas proporcionan 168 líneas de E / S digitales TTL, y estas líneas se agrupan en dieciocho puertos bidireccionales de 8 bits. Cada tres puertos en un conector se agrupan y nombran como puerto A (PA), puerto B (PB) y puerto C (PC), respectivamente. Todos los puertos se configuran como entradas al encender o restablecer.<br>

El PIO-D168U también agrega un interruptor de ID de tarjeta a bordo. Los usuarios pueden establecer la identificación de la tarjeta y luego reconocer la placa mediante la identificación a través del software cuando usan dos o más tarjetas PIO-D168U en una computadora.<br>

El PIO-D168 / D168U es compatible con varios sistemas operativos, como Linux, DOS, Windows 98 / NT / 2000 y Windows XP / 2003 / Vista / 7 de 32 bits / 64 bits. También proporciona el control DLL y Active X, y varios programas de muestra de lenguaje en Turbo C ++, Borland C ++, Microsoft C ++, Visual C ++, Borland Delphi, Borland C ++ Builder, Visual Basic, C # .NET, Visual Basic.NET y LabVIEW para ayudar usuarios para desarrollar rápida y fácilmente sus aplicaciones.
</p><BR><br>

<strong>Caracteristicas</strong>

<ul>
<li>Admite el bus PCI de +5 V para PIO-D168</li>
<li>Admite el bus PCI +3.3 V / + 5 V para PIO-D168U</li>
<li>Doble lado SMT, tarjeta corta, ahorro de energía</li>
<li>Conéctate directamente a DB-24P, DB-24R, DB-24PR, DB-24SSR, DB-24POR y otra placa hija compatible con OPTO-22</li>
<li>168 líneas de E / S</li>
<li>Emular 7 puertos industriales 8255 PPI (modo 0)</li>
<li>Interrupción programable</li>
<li>Función de identificación de tarjeta para PIO-D168U</li>
<li>Seis conectores de cable plano de 50 pines y uno de 37 pines</li>
<li>Conector D-sub</li>
<li>Retraso de estado de salida</li>
<li>El tiempo de respuesta DIO es de aproximadamente 0,77 µs (1,3 MHz máx.)</li>
</ul>
