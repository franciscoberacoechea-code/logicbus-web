            <div class="col-12 col-md-7 text-center">
                <p class="text-center light-black font-weight-bold">¿Qué son los sistemas Fly-by-Wire?</p>
                <p class="light-black text-justify">Fly-by-wire es un sistema de control de vuelo automatizado que procesa la entrada de comandos realizada por el piloto o el piloto automático y envía los comandos correspondientes a los actuadores de la superficie de control de vuelo. Este arreglo electrónico automatizado reemplaza los sistemas de control de vuelo mecánicos e hidráulicos tradicionales (palancas, varillas, cables y poleas) para que el piloto controle de forma remota las superficies de control.</p>
                <p class="light-black text-justify">La computadora de control de vuelo (FCC) de la aeronave monitorea sensores en toda la aeronave para realizar ajustes automáticos en los actuadores de la superficie de control de vuelo para mejorar la seguridad y el rendimiento del vuelo, según las leyes de control de vuelo. FbW es básicamente un sistema de control de bucle cerrado automatizado y sus elementos básicos son:</p>
                <ul class="light-black text-justify">
                    <li class="mb-3">Entrada de referencia proporcionada por el piloto automático o el piloto a través del yugo, la palanca lateral, los pedales o cualquier otro elemento de actuación.</li>
                    <li class="mb-3">La computadora de control de vuelo (FCC), que calcula cuánto se desvían las variables aerodinámicas actuales de la aeronave respecto de la entrada de referencia y qué acción debe ordenarse a los actuadores para maniobrar la aeronave de manera segura de acuerdo con las leyes de control de vuelo.</li>
                    <li class="mb-3">Los actuadores de control de superficie, que traducen la señal de comando de la FCC en fuerza/par hidromecánico para cambiar la posición/ángulo de los controles de superficie (timón, elevadores, slats, spoilers, flaps y alerones). Son directamente responsables de cambiar el eje principal de rotación de la aeronave (balanceo, cabeceo y guiñada).</li>
                    <li class="mb-3">Instrumentación o sensores de la aeronave, que proporcionan la retroalimentación de respuesta a la FCC para compararla con la entrada de referencia y realizar una estimación.</li>
                </ul>
                <p class="text-center light-black font-weight-bold">¿Cómo se utilizan los sensores de fuerza en los sistemas FbW?</p>
                <p class="light-black text-justify">Los sensores de fuerza y torsión multieje se utilizan con frecuencia en el entorno de pruebas de vuelo para validar el diseño del sistema de control en función de las leyes de control de vuelo. Las células de carga y los sensores multieje se agregan al sistema de control durante la fase de verificación y validación para verificar y calibrar los parámetros de los bucles de control fly-by-wire. Los controles de vuelo deben validarse durante la fase de diseño del producto y requieren una auditoría extrema antes de su uso en vuelo.</p>
                <p class="text-center light-black font-weight-bold">¿Cómo funciona?</p>
                <ol class="light-black text-justify">
                    <li class="mb-3"><b>Palanca lateral</b>: durante la fase de validación del producto, la celda de carga de cambio de marchas MAU300 proporciona a los ingenieros de control de vuelo y de control de calidad las herramientas adecuadas para medir la fuerza aplicada a los controles de vuelo de la palanca lateral . Para garantizar que este mecanismo funcione correctamente, la celda de carga de cambio de marchas multieje MAU300 de FUTEK se puede instalar en el eje de cada palanca lateral de control de vuelo.</li>

                    <li class="mb-3"><b>Yugo</b>: Los pilotos dependen en gran medida de la columna de control (yugo) para guiar el cabeceo y el balanceo de un avión. Al girar el yugo, el piloto maniobra el eje de alabeo. Al impulsar el yugo hacia adelante y hacia atrás, ese piloto puede ajustar el eje de elevación y cabeceo. Para garantizar que la columna de control esté funcionando correctamente, los ingenieros de control de vuelo y garantía de calidad pueden instalar el sensor biaxial de par y empuje MBA500 de FUTEK para medir las fuerzas y los pares aplicados al control de vuelo del yugo . El sensor de fuerza multieje MBA500 realiza mediciones tanto en la dirección Mz (el balanceo) como en la Fz (el cabeceo).</li>

                    <li class="mb-3"><b>Mango del acelerador</b>: El nanosensor QLA414 o el sensor de fuerza de pellizco LMD300 se pueden usar en los botones de actuación del mango del acelerador para medir la fuerza de pellizco o presión ejercida por el piloto.</li>

                    <li class="mb-3"><b>Pedales</b>: Los pedales controlan la superficie de control del timón, que puede moverse hacia la izquierda y hacia la derecha presionando el pedal piloto del timón correspondiente. El uso de sensores de fuerza de pedal LAU220 permite a los ingenieros auditar la precisión de estos controles. Utilizando los sensores de fuerza de pedal LAU de FUTEK, los ingenieros de control de calidad pueden medir la fuerza necesaria para operar cada control de vuelo del pedal del timón mientras dirige e impulsa el avión durante el vuelo.</li>

                    <li class="mb-3"><b>Actuador de controles de superficie</b>: durante la validación del diseño del producto, el ingeniero de control debe medir la fuerza de actuación que se aplica a la superficie de control. Esto ayuda a garantizar que se ejerza la fuerza necesaria y que el bucle de control esté calibrado correctamente y funcione como se espera. La celda de carga de extremo de varilla LCB se instala entre el actuador y la superficie de control de vuelo para medir la fuerza de actuación real ejercida y calibrar correctamente el bucle de servo del actuador mediante retroalimentación de fuerza adicional.</li>
                </ol>
