<center><strong>Módulo de Entrada/Salida esclavo EtherCAT con 8 canales DO aislado y 8 canales DI (RoHS).</strong></center><br>

<p>El ECAT-2055 está construido en 8 entradas digitales aisladas y 8 salidas digitales. Los usuarios pueden obtener el estado de entrada y salida no solo a través de los datos del proceso sino también a través de sus indicadores LED. Ha pasado y verificado por la herramienta de prueba de conformidad, por lo tanto, el maestro o configurador EtherCAT elegible puede manipularlo e implementar fácilmente sus diversas aplicaciones.</p>
Características:
<ul>
<li>Procesamiento sobre la marcha: EtherCAT.</li>
<li>Potente MCU maneja el tráfico de red eficiente.</li>
<li>2 x interfaz de bus RJ-45.</li>
<li>Distancia entre estaciones hasta 100 m (100BASE-TX).</li>
<li>Soporte de conexión de cadena tipo daisy.</li>
<li>Prueba de conformidad de la herramienta EtherCAT verificada.</li>
<li>Conector de bloque de terminales extraíble.</li>
<li>Indicadores LED para el estado de E / S.</li>
<li>E / S digital incorporada: 8 DI y 8 DO.</li>
<li>Compatible con RoHS.</li>
<li>Protección ESD 4 KV de contacto para cada canal.</li>
</ul>
Aplicaciones:
<ul>
<li>Herramientas semiconductoras.</li>
<li>Formación de metal.</li>
<li>Embalaje.</li>
<li>Moldeo por inyección.</li>
<li>Sistemas de ensamblaje.</li>
<li>Máquinas de impresión.</li>
<li>Robótica.</li>
</ul>
