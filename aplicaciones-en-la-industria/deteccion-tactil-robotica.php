                <p class="light-black font-weight-bold">¿Qué es un sensor táctil?</p>

                <p class="light-black">Un sensor táctil (también conocido como sensor de fuerza en la punta de los dedos) es un dispositivo que mide las fuerzas en respuesta a la interacción física con el entorno. El sentido del tacto en los seres humanos se basa en el sentido biológico del tacto provocado por la estimulación mecánica de la piel. Los sensores táctiles se utilizan en robótica, hardware informático y sistemas de seguridad. Una aplicación común de los sensores táctiles es en las manos y los dedos robóticos (es decir, detección táctil robótica).</p>

                <p class="light-black font-weight-bold">¿Por qué son tan importantes los sensores táctiles en las aplicaciones robóticas?</p>
                <p class="light-black">Uno de los principales desafíos que enfrenta la industria robótica hoy en día es que la destreza de los dedos impide que los sistemas robóticos convencionales realicen aproximadamente el 95% de todos los trabajos manuales . Preparar una bebida, doblar una servilleta, limpiar una lámpara de araña, etc. requiere una destreza extrema. Reemplazar este tipo de trabajo manual con robots requiere medir y controlar con precisión la fuerza de agarre del robot para aumentar la destreza y asegurarse de que los objetos frágiles no sean aplastados por la pinza (es decir, la manipulación de obleas de semiconductores). Aunque las celdas de carga son sensores confiables para la medición de fuerza, históricamente han estado limitadas por su construcción voluminosa.</p>

                <p class="light-black">Las celdas de carga de botón de carga nanométrica múltiple se utilizan como un sensor táctil para medir la fuerza táctil producida por un robot industrial. Al integrar estos microbotones de carga en los efectores finales de los brazos robóticos (también conocidos como EOAT o peaje de extremo de brazo), pinzas o incluso manos humanoides, los investigadores pueden monitorear y ajustar con precisión la fuerza aplicada, lo que garantiza que los objetos sensibles se manipulen con cuidado. El modelo QLA424 con solo 3,91 mm de diámetro x 4,24 mm de altura y ±0,5 % de no linealidad es particularmente adecuado para tareas de alta precisión en I+D o aplicaciones de nicho, como pinzas industriales o efectores finales que realizan funciones específicas.</p>

                <p class="dark-gray">QIA128 - Acondicionamiento de señal digital en miniatura y de bajo consumo</p>
                <p class="light-black">El QIA128 es una solución de acondicionamiento de señal ideal para sensores robóticos táctiles, que ofrece un diseño compacto con un tamaño de tan solo 8 mm x 8 mm, lo que lo hace perfecto para aplicaciones donde el espacio es limitado. Su consumo de energía ultrabajo de solo 60 mW garantiza un funcionamiento eficiente, mientras que la alta tasa de muestreo de hasta 1300 muestras por segundo (SPS) combinada con hasta 18,4 bits de resolución libre de ruido (NFR) permite un procesamiento de señal preciso y confiable. El QIA128 también cuenta con interfaces de salida digital SPI/UART, lo que permite una integración perfecta en sistemas robóticos avanzados donde la medición de fuerza precisa y el espacio de ensamblaje mínimo son fundamentales.</p>

                <p class="text-center light-black font-weight-bold">¿Cómo funciona?</p>

                <ol class="light-black">
                    <li class="mb-3">A medida que los laboratorios de investigación continúan explorando el mundo de la robótica, existe una mayor necesidad de productos de prueba y medición de alta precisión, especialmente en el espacio de detección táctil robótica.</li>
                    <li class="mb-3">Esta aplicación muestra cinco botones de carga nanométrica (también conocidos como sensores de fuerza en la punta de los dedos) montados en la punta de cada dedo robótico. A medida que la mano robótica manipula diferentes objetos, los sensores táctiles recogen la fuerza necesaria para manipular esos objetos en particular.</li>
                    <li class="mb-3">La integración de botones de carga nano con QIA128 proporciona un acondicionamiento de señal compacto, eficiente y preciso para sensores robóticos táctiles, con altas tasas de muestreo, excelente resolución, bajo consumo de energía y salida digital perfecta para aplicaciones robóticas con limitaciones de espacio.</li>
