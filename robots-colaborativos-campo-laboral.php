      <h2 class="subtitle blue text-center mt-5 mb-3">Introducción</h2>
      <p>En el campo industrial es muy común observar el empleo de robots, que llevan a cabo tareas simples o en su caso complejas, ayudando a realizar de manera más ágil y rápida las actividades que en un principio se le dificultaba al humano. Desarrollando la interacción humano computadora (IHC) que en sus inicios generaba miedo e incertidumbre. Sin embargo, observamos que hoy en día, que ésta interacción se da de manera fluida y por si fuera poco el uso de robots colaborativos es ya una necesidad en las actividades industriales para <a class="blue link-orange" href="https://www.logicbus.com.mx/">automatizar</a> y optimizar procesos industriales repetitivos y monótonos.</p>
      <p>Apoyándose de un sistema de control que está definido como un conjunto de componentes que pueden regular su propia conducta o la de otro sistema con el fin de lograr un funcionamiento predeterminado, de modo que se reduzcan las probabilidades de fallos y se obtengan los resultados buscados.</p>
      <p>Hoy en día los procesos de control son síntomas del proceso industrial que estamos viviendo. Estos sistemas se usan típicamente en sustituir un trabajador pasivo que controla una determinado sistema (ya sea eléctrico, mecánico, etc.) con una posibilidad nula o casi nula de error, y un grado de eficiencia mucho más grande que el de un trabajador. Los sistemas de control más modernos en ingeniería automatizan procesos en base a muchos parámetros y reciben el nombre de controladores de automatización programables (PAC).</p>

