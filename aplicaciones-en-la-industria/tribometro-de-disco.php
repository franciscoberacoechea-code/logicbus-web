                <p class="light-black">Para comprender las propiedades de materiales como las pastillas de freno y recubrimientos resistentes a los arañazos, es esencial medir su coeficiente de fricción y su vida útil. Para lograr esto, se utiliza un tribómetro que, al incorporar un sensor de carga de múltiples ejes, permite obtener mediciones precisas de fricción y la duración de los materiales en uso.</p>

                <p class="text-center light-black font-weight-bold">¿Cómo funciona?</p>
                <ol class="light-black">
                    <li class="mb-3"><b>Configuración del Tribómetro:</b>
                        <ul>
                            <li>En este caso, se adjunta una muestra del material a un <b>MBA500 Torque and Thrust Biaxial Sensor</b> que está acoplado a un actuador lineal.</li>
                            <li>Un motor hace girar un disco a una velocidad predeterminada (RPM), simulando las condiciones de fricción del material durante su uso.</li>
                        </ul>
                    </li>
                    <li class="mb-3"><b>Prueba de Fricción y Aplicación de Fuerza:</b>
                        <ul>
                            <li>El actuador lineal presiona la muestra del material contra el disco giratorio, creando fricción entre ambas superficies.</li>
                            <li>El <b>MBA500</b> captura la fuerza aplicada y el torque generado cuando el material entra en contacto con el disco, proporcionando datos precisos sobre la resistencia al desgaste.</li>
                        </ul>
                    </li>
                    <li class="mb-3"><b>Captura y Procesamiento de Datos:</b>
                        <ul>
                            <li>La salida del <b>MBA500</b> es capturada por dos unidades de <b>USB220 High-Resolution USB Solutions</b>, lo que permite transmitir los datos de alta resolución a una PC.</li>
                            <li>Los datos se registran y se analizan mediante el software <b>SENSIT™</b> de FUTEK, que permite obtener gráficos y registros detallados sobre el comportamiento del material bajo condiciones de fricción.</li>
                        </ul>
                    </li>
                    <li class="mb-3"><b>Conexión a Microprocesador o PLC:</b>
                        <ul>
                            <li>Para aplicaciones de control avanzado, el <b>IDC305 Digital Controller</b> se puede utilizar para transmitir los datos de torque y empuje directamente a través de <b>SPI</b> a un microprocesador.</li>
                            <li>Alternativamente, los amplificadores de la serie <b>IAA</b> pueden proporcionar señales analógicas amplificadas (en voltaje o corriente) que se pueden enviar a un <b>PLC</b> o a un sistema de <b>adquisición de datos (DAQ)</b> para su posterior análisis.</li>
                        </ul>
                    </li>
                </ol>
                <p class="text-center light-black font-weight-bold">Ventajas del Sistema</p>
                <ul class="light-black">
                    <li class="mb-3"><b>Medición de Alta Precisión</b>: El uso del MBA500 permite realizar pruebas con gran exactitud en la fricción y la durabilidad de materiales como pastillas de freno y recubrimientos resistentes al desgaste.</li>
                    <li class="mb-3"><b>Análisis Completo del Material</b>: Al capturar tanto el torque como la fuerza de empuje, se obtienen datos detallados que permiten estudiar el comportamiento del material bajo condiciones de fricción y desgaste.</li>
                    <li class="mb-3"><b>Versatilidad y Conectividad</b>: La opción de capturar datos en tiempo real y su facilidad de conexión con dispositivos como PLC o microprocesadores facilita su integración en diversas aplicaciones industriales.</li>
                </ul>

                <p class="light-black">Este sistema proporciona a los ingenieros y fabricantes una herramienta eficiente para evaluar y mejorar la durabilidad de materiales utilizados en productos de alta exigencia como componentes de automóviles y recubrimientos industriales.</p>
