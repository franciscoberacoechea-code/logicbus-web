<p align="justify">El I-87018W es un módulo de entrada analógica de 8 canales que proporciona entrada de corriente y entrada de voltaje, así como entrada de termopar.<br><br>
El I-87018RW es una versión mejorada de I-87018W con un mecanismo de protección de muy alta calidad donde la protección contra sobretensiones puede ser tan alta como 240 Vrms. El tipo de entrada se puede configurar en corriente o voltaje, así como termopar. La única diferencia entre los dos módulos es que el I-87018RW es más adecuado para entornos críticamente severos. Además, la característica de detección de termopar abierta recién agregada hace que la I-87018RW sea más atractiva que nunca. Tanto la I-87018W como la I-87018RW también cuentan con protección ESD de 4 kV y aislamiento intramódulo de 3000 VDC.</p>

<strong>Características:</strong>
<ul>
<li>Entrada analógica de 8 canales.</li>
<li>Entrada de corriente, entrada de voltaje y entrada de termopar.</li>
<li>Alta resolución: 16 bits.</li>
<li>Aislamiento intramódulo de 3000 VDC.</li>
<li>Detección abierta de termopar.</li>
<li>240 Vrms Protección contra sobretensión.</li>
<li>Protección contra ESD de 4 kV.</li>
<li>RoHS.</li>
<li>Amplio rango de temperatura de funcionamiento: -25 a + 75 ° C.</li>
</ul>

