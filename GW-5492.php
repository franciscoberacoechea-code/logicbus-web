<center><strong>Gateway Servidor BACnet/IP a Modbus RTU Maestro, 1 puerto RS-232, 1 puerto RS-485, 1 puerto Ethernet 10/100 Base-TX. Alimentación de +10 ~ +30 VDC.</strong></center><br>

<p>El GW-5492 es un Gateway entre Modbus RTU y BACnet/IP totalmente configurable. El GW-5492 es un BACnet / IP como servidor y Modbus RTU como Maestro que hacen posible que los dispositivos Modbus RTU sean accesibles en una Red BACnet.<br><br>
El protocolo BACnet ha sido diseñado específicamente para satisfacer las necesidades de comunicación en la construcción de sistemas de automatización y control para aplicaciones como calefacción, ventilación, control de aire acondicionado, etc.<br><br>
El GW-5492 contiene un gran número de objetos BACnet (AI, AO, AV, BI, BO, BV, MSI, MSO, MSV) ofreciendo flexibilidad en la asignación de registros Modbus RTU a cualquier combinación de objetos BACnet. BIBBs múltiples (DS-RP-B, DS-RPM-B, DS-WP-B, DS-WPM, DS-COV-B, etc.) son compatibles. Todos los datos de transferencia son configurables mediante un navegador Web estándar. </p>

<div align="center">
<img src="imagenes/02/BMGW-AP.jpg" width="50%" alt="BACnet" title="BACnet" class="image_productos">
</div>

<strong>Aplicaciones:</strong>
  <ul>
    <li> Automatización de edificios.</li>
    <li> Control de aire acondicionado, calefacción y ventilación.</li>
    <li> Control de iluminación.</li>
    <li> Control de accesos.</li>
    <li> Sistemas de detección de incendios.</li>
  </ul>
<strong>Características generales:</strong>
  <ul>
        <li> Forma rápida y rentable para la integración de redes.</li>
        <li> Indicación por LED de estado de comunicación y alimentación.</li>
        <li> Leer / Escribir a cualquier registro Modbus a través de BACnet.</li>
        <li> No requiere programación.</li>
        <li> Mapeo de registro Modbus configurado vía Web.</li>
  </ul>
<strong>BACnet:</strong>
  <ul>
    <li> Totalmente compatible con servidor BACnet / IP.</li>
    <li> Soporta un máximo de 200 objetos de cualquiera de los tipos: entrada analógica, salida analógica, variable análoga, entrada binaria, salida binaria, variable binaria, entrada Multi-estado, salida Multi-estado.</li>
    <li> BIBB (BACnet Interoperability Building Blocks) soportados: DS-RP-B, DS-RPM-B, DS-WP-B, DS-WPM-B, DS-COV-B, DM-DDB-B, DM-DOB-B , DM-DCC-B, DM-TS-B, DM-UTC-B, DM-RD-B.</li>
  </ul>
<strong>Modbus RTU:</strong>
  <ul>
    <li> Modbus RTU esclavo totalmente configurables por el usuario.</li>
    <li> Soporta Coils, Input Register, Holding Register.</li>
    <li> Soporta los siguientes códigos de función 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x10, 0x0F.</li>
    <li>Velocidades de transmisión compatibles: 2400, 4800, 9600, 19200, 57600, 115200 bps.</li>
  </ul>
<strong>Software:</strong>
  <ul>
    <li> Configuración a través de un navegador web estándar.</li>
    <li> Dispone de una interfaz para la configuración de la Red Modbus.</li>
    <li> Dispone de una interfaz para la configuración BACnet.</li>
  </ul>

