<h2>Conclusion</h2>
<p align="justify">Como se ha ido desarrollando el tema, observamos una evolución de lo que antes era una simple casa y que gradualmente ha crecido pasando por un conjunto de casas, un poblado, una ciudad, una metrópoli, a lo que ahora se están convirtiendo a ciudades inteligentes.
Aún nos queda camino por recorrer, pero observamos que los cambios ya los estamos viviendo, y que en la mayoría pasan desapercibidos.<br>
Y podemos ver que los nuevos retos ya los estamos viviendo, ya que con un cambio así, también se vienen cambios en las estructuras culturales, en los nuevos roles de trabajo, y el mantenimiento que se debe realizar para los sistemas que se están implementando.<br>
