        <p class="subtitulo"><b>Tarjeta PCI Express con 4 puertos seriales configurables individualmente como RS-232/422/485. Incluye cable modelo CA143 de 36 pulgadas de largo con 1 conector DB37 macho a 4 puertos DB9 macho.  Incluye bracket PCI estandar. Compatible con Windows y Linux</b></p>


        <p>La interfaz serial PCI Express 7404e proporciona cuatro puertos seriales multifunción, cada uno de ellos configurable individualmente en campo para RS-232, RS-422 o RS-485. Cada puerto serie utiliza un UART 16C954 con FIFO Tx / Rx de 128 bytes que permite velocidades de datos de 921.6K bps para comunicaciones confiables de alta velocidad en aplicaciones de uso intensivo de datos. Este UART de alto rendimiento incluye soporte de trama de 9 bits y es compatible con las aplicaciones de software heredadas 16550. Además, la placa deriva un reloj de 62.5 MHz del enlace PCI Express. Este reloj de ultra alta velocidad está dividido por un preescalar de reloj flexible de 8 bits con 1/8 pasos para proporcionar soporte para la gama más amplia de velocidades de transmisión estándar y no estándar.<br>

        En el modo RS-485, la placa proporciona control automático del controlador RS-485 en hardware, eliminando la necesidad de control de software de aplicación. Esto permite que el 7404e se use con aplicaciones de comunicaciones en serie estándar y elimina el riesgo de contención del bus y corrupción de datos. Además, la terminación de red RS-485, crítica para la comunicación robusta de múltiples caídas, se puede agregar selectivamente al circuito a través de interruptores DIP. En el modo RS-232, todas las señales de control del módem se implementan para una compatibilidad máxima con una variedad de periféricos en serie.<br>

        El controlador y las utilidades del software Sealevel SeaCOM facilitan la instalación y operación con los sistemas operativos Microsoft Windows y Linux.<br>

        El 7404e es una placa PCI Express X1 compatible con cualquier ranura PCI Express. La placa se envía con un cable de 36 pulgadas (Artículo # CA143) que termina en cuatro conectores DB9M.</p>

