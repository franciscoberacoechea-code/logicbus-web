<center><strong>Módulo de salida digital aislado de 32 canales.</strong></center><br>

<p style="text-align: justify;">El módulo I-8041W / I-8041PW ofrece 32 canales de salida digital, cada uno de ellos con aislamiento Photocouple y admite salida de tipo sink con un colector abierto. La I-8041W / I-8041PW incluye 32 indicadores LED que se pueden usar para monitorear el estado de los canales de salida digital. Se proporciona protección de 4 kV ESD y aislamiento intramódulo de 3750 Vrms como estándar. El I-8041W / I-8041PW se puede emparejar con un tablero secundario, como el DN-37-381-A para facilitar el cableado, o el DN-8K32R para la salida de relevo. El I-8041PW integra funcionalidad de sobrecorriente, sobrevoltaje y cortocircuito. Recomienda seleccionar la versión "PW" del módulo de salida digital para uso industrial.</p><br>

<strong>Caracteristicas:</strong>
<ul>
<li>Salida de colector abierto de 32 canales</li>
<li>Salida digital tipo fregadero</li>
<li>Protección contra cortocircuitos, protección contra sobretensiones y sobrecarga </li>
<li>Protección para I-8041PW</li>
<li>3750 Vrms aislamiento intramódulo</li>
<li>Cada canal digital tiene su propio LED de estado</li>
<li>Carpetas de datos opcionales</li>
</ul>



