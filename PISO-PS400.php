<center><strong>PCI Bus, tarjeta de control de movimiento de 4 ejes de alta velocidad.</strong></center><br>


<p>El PISO-PS400 es una tarjeta de control de servomotor paso a paso/tipo de pulso de 4 ejes que se puede usar en cualquier IPC con un bus PCI de 5 V, y es adecuado para aplicaciones de control de movimiento de propósito general. Esta tarjeta está equipada con un FRnet Master que permite expandir fácilmente las E/S remotas rápidas del IPC. La interfaz FRnet de dos hilos permite un máximo de 128 canales DI y 128 canales DO, que se escanean automáticamente en un período de 2,88 ms.<br>

Además de su amplio rango de velocidad, este controlador de movimiento inteligente también tiene una variedad de funciones de control de movimiento integradas, como interpolación lineal de 2/3 ejes, interpolación circular de 2 ejes, aceleración/desaceleración de T/S, numerosas sincronizaciones acciones, búsqueda automática, y otros. Una gran ventaja es que la mayoría de las funciones de control de movimiento PISO-PS400 se realizan mediante el movimiento ASIC de alto rendimiento con poca carga en el procesador. El estado de movimiento, FRnet I/O y las otras tarjetas de E/S en el IPC pueden monitorearse mientras se manejan los motores.<br><br>

Como los bajos requisitos de carga de la CPU del PISO-PS400 son mínimos, se pueden usar una o más tarjetas de movimiento con un solo IPC. ICP DAS también proporciona una variedad de funciones y ejemplos que se pueden utilizar para reducir la necesidad de programación adicional, convirtiéndola en una solución altamente rentable para los desarrolladores de aplicaciones de control de movimiento.
</p><BR><br>

<strong>Caracteristicas</strong>
<ul>
<li>Control de movimiento independiente de 4 ejes.</li>
<li>Soporte para funciones de volante y jog.</li>
<li>Función de interpolación circular de 2/3 ejes lineal/2 ejes.</li>
<li>Función de interpolación continua.</li>
<li>Aceleración y desaceleración de curva T/S programables.</li>
<li>Una tasa de salida de pulso máxima de 4 Mpps para cada eje.</li>
<li>Tipos de salida de impulsos: CW/CCW o PULSE/DIR.</li>
<li>Contador del codificador de 32 bits para cada eje.</li>
<li>Tipos de entrada de impulsos del codificador: fase A/B o arriba/abajo.</li>
<li>Homing automático programable para cada eje.</li>
<li>Posición de administración de comparación y límites de software.</li>
<li>Una amplia gama de acciones sincrónicas (acciones desencadenadas por eventos).</li>
<li>E/S remota expansible: 128 DI y 128 DO mediante una interfaz FRnet de dos hilos.</li>
</ul>
