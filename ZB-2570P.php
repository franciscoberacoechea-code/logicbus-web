  Red ZigBee <BR>
El ZB-2570P es un convertidor  ZigBee maestro. Este ofrece  interfaz Ethernet/RS-485/RS-232. Los dispositivos que tienen una interfaz Ethernet/RS-485/RS-232 son capaces de ser conectados con los m&oacute;dulos ZB-2570/2570P/2571/2571P. Mediante la distribuci&oacute;n del ZigBee maestro y esclavo en el campo, los usuarios pueden crear f&aacute;cilmente una red inal&aacute;mbrica que puede ser utilizada para monitoreo  y control. <br>
<br>
Interfaz de usuario amigable <br>
Dispone de una herramienta para la configuraci&oacute;n compatible con Windows. S&oacute;lo cuatro pasos son necesarios para establecer al ZB-2570P y estar&aacute; listo para usarse. La herramienta permite a los usuarios elegir  diferentes modos de operaci&oacute;n  dependiendo del tipo de aplicaci&oacute;n, y varias de las  variables necesarias  de ZigBee como el PAN ID, etc.<br>
<br>
  
¿Cu&aacute;les son  los beneficios de usar ZigBee?<br>
ZigBee es  una especificaci&oacute;n basada en el est&aacute;ndar IEEE 802.15.4  para redes inal&aacute;mbricas personales (WPANs).
Est&aacute; dirigido a aplicaciones que requieren la creaci&oacute;n de redes seguras, cuenta con una gran flexibilidad para la expansi&oacute;n de redes, se pueden agregar  nuevos nodos en cualquier momento. Tambi&eacute;n es ampliamente utilizado en el campo de control industrial, en hospitales, laboratorios y en la automatizaci&oacute;n de edificios. Tres topolog&iacute;as est&aacute;n definidas en el est&aacute;ndar IEEE 802.15.4: Estrella, Cluster Tree  y  malla. El alcance de transmisi&oacute;n t&iacute;pica es de 700 m.

