      <p class="text-justify paragraph" itemprop="text"> Como ya sabemos, el voltaje y la resistencia afectan la intensidad de corriente en un circuito, y que el voltaje cae a través de una resistencia. Las relaciones básicas de la intensidad de la corriente, voltaje y resistencia son las siguientes mencionadas: </p>
      <ol align="justify" itemprop="text" class="text-justify paragraph">
