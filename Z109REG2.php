<p align="justify">Es un convertidor universal avanzado capaz de gestionar todas las señales analógicas (mA, V, PT100, Pt1000, Pt500, Ni100, TCs, Ohms) y convertirlo/aislarlo en señales mA/V estándar. El dispositivo se puede configurar a través de dip-switches, software para PC o dispositivos de mano. Un contacto digital está disponible como ALARMA o STROBE (multiplexación). Se puede solicitar con una fuente de alimentación baja o alta. Un aislamiento galvánico de 3 vías entre la fuente de alimentación // los circuitos de entrada/salida asegura la integridad de sus fechas.</p>

<strong>Caracteristicas:</strong>
<ul>
<li>Entrada universal de Voltaje, Corriente, RTD, Termopar, Potenciómetro o Reóstato</li>
<li>Salida análoga de Voltaje o Corriente</li>
<li>Salida de relevador para alarma</li>
<li>Resolución de 15 bits + signo</li>
<li>Precisión de 0.1%</li>
<li>DIP Switch para seleccionar tipo de entrada y salida</li>
<li>Con opción de configuración vía Software</li>
<li>Alimentación: Z109REG2: 9-40 Vdc, 19-28 Vac</li>
</ul>

