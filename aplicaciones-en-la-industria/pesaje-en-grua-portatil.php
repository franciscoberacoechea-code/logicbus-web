                    <li class="mb-3">Instalada en el cable de la grúa, la celda de carga Pancake de FUTEK (Serie LCF) mide el peso de la carga, así como la resistencia del cable mientras maniobra la carga.</li>
                    <li class="mb-3">Estas mediciones pueden amplificarse a través de un amplificador analógico de la serie IAA a un PLC, mostrarse en una pantalla digital (IPM650 o IHH500) o transmitirse directamente a una PC utilizando las soluciones USB de FUTEK.</li>
