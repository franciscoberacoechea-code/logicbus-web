                <p>Este switch industrial ofrece dispersión LAN rápida, fácil de utilizar y confiable. Es ideal para
                  casi cualquier configuración. Tiene función MDI/MDIX. Puede conectar 8 estaciones de trabajo y
                  conmutar automáticamente la velocidad de transmisión (10 Mbps o 100 Mbps) para conexiones
