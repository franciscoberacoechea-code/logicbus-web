<p>El NB1600 Wireline es la mejor opción para la comunicación LAN-LAN y actúa como servidor de dispositivo, firewall industrial, enrutador VPN, convertidor de protocolo, módulo de E / S o IPC simple.<br>
Para proyectos pequeños y medianos, use este producto en el lado central como un servidor VPN.<br>
El firewall industrial NB1600 separa la red local y otras de la LAN de fábrica y permite la conexión de un sistema a un servidor central utilizando solo una conexión VPN. El uso del puerto TCP 80 para la VPN permite pasar la mayoría de los firewalls en una fábrica o en el lado del cliente.<br>
Configurado como un servidor VPN, se pueden terminar hasta 10 conexiones OpenVPN en el dispositivo. Todas las configuraciones y claves se pueden generar mediante la potente interfaz web.<br>
En su función de servidor de dispositivos, puede convertir tanto la interfaz serie como la interfaz USB a IP para permitir el acceso remoto a la interfaz. Cualquier PC que tenga conexión IP al enrutador NetModule puede usar el dispositivo remoto USB o RS-232 como si estuviera directamente conectado. Esto permite que el uso del controlador original sea posible.<br>
La E / S digital puede configurarse y programarse desde cualquier dispositivo directamente conectado o desde un control remoto. Con base en el cambio de estado de los puertos de entrada, se puede informar a una aplicación, el comportamiento del NB1600 puede ser.<br>
Usando el SDK, los usuarios pueden programar el NB1600 usando un simple script para implementar todo tipo de aplicaciones. El preprocesamiento se puede hacer directamente en el enrutador, que puede guardar un IPC adicional.<br>
Otras características y servicios son el servidor DHCP, el proxy DNS, el agente DNS dinámico, el agente SNMP, el servidor Telnet, el servidor SSH, el servidor web y el correo electrónico y SMS. El en-documento es operado por el Administrador Web o por medio de la línea de comandos.<br>
La actualización del firmware se puede realizar fácilmente desde una ubicación remota de forma segura y también a la actualización de la configuración. Con la interfaz SNMP, NetBox puede integrarse en un sistema de administración de red para supervisión.
</p><br>

