<center><strong>Tajeta PCI, cuenta con 16 canales de entrada digitales aisladas y 16 canales de salida a colector abierto, 12 contadores/temporizadores independientes de 16 bit.</strong></center><br>


<p>El PCI-TMC12A es un temporizador / contador de propósito general PCI-Bus y una placa de E / S digital. Proporciona doce canales de temporizador / contador de 16 bits. La fuente de reloj interno Tw (8M / 1.6M y 0.8M / 80K) se selecciona mediante puentes. Cuatro chips 8254 proporcionan una variedad de potentes modos de temporizador / función de contador que combinan con sus aplicaciones industriales y de laboratorio.
</p><BR><br>

<strong>Caracteristicas</strong>

<ul>
<li>A bordo de cuatro 8254 chips temporizador / contador</li>
<li>Doce temporizadores / contadores independientes de 16 bits</li>
<li>Doce entradas de reloj externo</li>
<li>Doce entradas de control de puerta externa</li>
<li>Doce salidas de temporizador / contador</li>
<li>El temporizador / contador de 16 bits se puede conectar a 32/48 bits</li>
<li>La entrada de la puerta puede ser desde el temporizador externo / previo / salida de contador</li>
<li>Cuatro fuentes de interrupción</li>
<li>Dos fuentes de reloj interno</li>
<li>16 canales de D / I y D / O</li>
<li>El antiguo programa diseñado para tmc12 se puede ejecutar en tmc12A sin ninguna modificación</li>
<li>Mecanismo de interrupción flexible</li>
<li>Mecanismo de hardware para la generación de 2 inicios de reloj</li>
</ul><br>

<strong>Software</strong>
<ul>
<li>Toolkit para DOS</li>
<li>Toolkit para Windows 95/98</li>
<li>Toolkit para Windows NT</li>
<li>Toolkit para Windows 2000 / XP</li>
<li>Kit de herramientas de LabVIEW para Windows</li>
<li>Toolkit para OCX 95/98</li>
<li>Toolkit para OCX NT</li>
<li>Driver para LINUX</li>
</ul>
