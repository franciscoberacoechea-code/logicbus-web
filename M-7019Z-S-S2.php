<center><strong>Entrada de corriente y entrada de voltaje universal de 10 canales, módulo de entrada analógica (entrada de termopar), transmisible a través de RS-485. Admite temperaturas de funcionamiento entre -25 ° C ~ 75 ° C (-13 ° F ~ + 167 ° F).</strong></center><br>
 <br>

<p> 
El M-7019Z es un módulo de entrada analógica universal de 10 canales con una interfaz RS-485 especialmente diseñada para mediciones de termopar extremadamente precisas y cuenta con compensación automática de unión fría para cada canal para garantizar la consistencia de la salida de temperatura y la salida de temperatura estable en el campo. El diseño innovador del modelo mejorado asegura que la medición del termopar sea más precisa que con el diseño anterior. Además de las entradas de termopar, la M-7019Z también admite entradas de voltaje y corriente. El rango de entrada de tensión puede ser de +/- 15 mV a +/- 10 V, y el rango de entrada de corriente puede ser de 4 ~ 20 mA, 0 ~ 20 mA o +/- 20 mA. Se pueden conectar hasta 10 entradas analógicas de diferentes tipos a un solo módulo. Se proporciona protección contra sobretensiones de hasta 240 Vrms. El módulo también presenta detección de cable abierto por canal para termopar y entradas de 4 ~ 20 mA.</p><BR>

<strong>Caracteristicas:</strong>
<ul>
<LI>Entrada analógica de 10 canales</LI>
<LI>Configuración individual del canal</LI>
<LI>Detección abierta de termopar</LI>
<LI>Consistencia de salida de temperatura</LI>
<LI>Salida de temperatura estable en el campo</LI>
<LI>Protección de sobretensión 240 Vrms</LI>
<LI>Puente seleccionable de voltaje o entrada de corriente</LI>
<LI>Protección contra ESD de 4 kV</LI>
<LI>Dual Watchdog</LI>
<LI>Aislamiento intramódulo de 3000 VDC, campo a lógica</LI>
<LI>Amplio rango de temperatura de funcionamiento: -25 ° C ~ +75 ° C</LI>
</ul>
