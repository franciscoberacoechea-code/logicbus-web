<p> 
M-7019Z es una interfaz RS-485 y un módulo de entrada de termopares de 10 canales. El rango de entrada analógica es seleccionable por software y admite +/- 15 mV, +/- 100 mV, +/- 150 mV, +/- 500 mV, +/- 1 V, +/- 2.5 V, +/- 5 V, +/- V10, +/- 20 mA, 0 ~ 20 mA, y termopar de tipo J, K, T, E, R, S, B, N, C, L, M y LDIM43710. I-87019ZW utiliza un diseño de terminal externo y toma la consistencia de la salida de temperatura del termopar.</p><BR>

<strong>Caracteristicas:</strong>
<ul>
<li>Entrada analógica de 10 canales</li>
<li>Configuración individual del canal</li>
<li>Detección abierta de termopar</li>
<li>Consistencia de Salidas de Temperatura</li>
<li>Salida de temperatura estable en el campo</li>
<li>Protección de sobretensión 240 Vrms</li>
<li>Puente seleccionable para entrada de voltaje o corriente</li>
<li>Protección contra ESD de 4 kV</li>
<li>Dual Watchdog</li>
<li>Aislamiento intramódulo de 3000 VDC, campo a lógica</li>
<li>Amplia gama de temperatura de funcionamiento: -25 ° C ~ 75 ° C</li>
<li>RoHS</li>
</ul>
