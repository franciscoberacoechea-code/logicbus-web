      <td colspan="2"><div align="justify">The DNA-SL-501-804 and DNR-SL-501-804 are 4-port serial communications layers for popular &ldquo;Cube&rdquo; and RACKtangle I/O chassis respectively. The boards offer fully isolated serial interfaces, software-configurable as RS-232 or RS-485. DNA/DNR-SL-501-804 supports up to 4 Mbit/s transfer speed in RS-485 mode or up to 256 Kb/s in RS-232 mode. The DNx-SL-501-804 is a special, high speed version of the popular DNx-SL-501 board. The boards use a 16550C UART emulation on each port (FIFO mode only) and support half- and full-duplex mode over RS-485.
          <div><br>
            The DNA/DNR-SL-501-804 is compatible with RS-422 networks when used in RS-485 mode. The layer provides 200&Omega; software-selectable TX and/or RX termination for RS-485 communications. The DNA/ DNR-SL-501-804 is an ideal solution for connecting serial based data acquisition devices to the Ethernet as well as interfacing to a wide variety of serial based devices and legacy DAQ systems. In addition to standard serial I/O features, the DNx-SL-501-804 offers a series of additional functions. These functions include:<br>
            <ul>
              <br>
              <li>Fully customizable baud rates generated by programmable PLL on per-channel basis from 300baud to 4Mbaud</li>
              <li>Programmable inter-character delay (required to drive/simulate some avionics instruments)</li>
              <li>Programmable inter-frame delay (used to schedule frames at different rate)</li>
              <li>Automatic repeat of the last frame if new data is not sent from the host on time (required to keep &ldquo;inop&rdquo; flag happy on many avionic devices)</li>
              <li>None/Even/Odd/Space/Mark parity in 8-bit mode and per- symbol programmable in 9-bit mode</li>
              <li>Automatic in-hardware or software flow control</li>
              <li>Asynchronous event mode with loop closure in 100us (for avionics expecting immediate reply)</li>
              <li>Echo suppression in half-duplex mode (for 422 mode)</li>
              <li>Timeout programmable in 10us, 100us or 1ms intervals</li>
            </ul>
