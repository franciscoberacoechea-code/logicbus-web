<p align="justify">El modelo LLB130 es una celda de carga miniatura en forma de botón, construida para presionar o para aplicaciones de compresión. El modelo estándar de la celda de carga miniatura LLB130 tiene una robusta construcción disponible en acero inoxidable 17-4 con un diámetro exterior de .38".<br><br>
Aunque las celdas de carga en forma de botón tradicionalmente no son conocidas por su alta exactitud, nuestros ingenieros han disipado este concepto por un mejoramiento continuo de la exactitud de este producto. La celda de carga miniatura ofrece una alta exactitud, posee no linealidad de ±0.5% y desviación nominal de 0.002". El modelo estándar LLB130 puede ser modificado y personalizado de acuerdo a tus requerimientos y la mayoría de las capacidades se encuentran en nuestro inventario teniéndolos disponibles para su envío en 24hrs. Similar a nuestra línea de productos de celdas de carga este modelo es fabricado en USA y usa la tecnología de galgas extensiométricas de hojas de metal.</p><br>


