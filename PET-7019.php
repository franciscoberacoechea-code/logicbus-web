<p>El Power-over-Ethernet (PoE) permite que los datos y la energía se transfieran por un sólo cable de Ethernet para que un dispositivo pueda operar desde la energía que recibe mediante el cable de datos. Ésta innovación permite una mayor flexibilidad en el diseño de oficinas, una eficiencia mas alta en el diseño de sistemas y más rapidez en la implementación. <br>

El PET-7019 ofrece compatibilidad con IEEE 802.3af (clasificación, Clase 1) Power over Ethernet (PoE) usando los dos pares de Ethernet (Cable Ethernet Categoría 5). El PET-7019 puede recibir energía de una fuente auxiliar como adaptadores AC y baterías, además de la red PoE. Ésta es una característica deseable cuando la energía total del sistema requerida excede la capacidad de carga de PSE. <br>

El PET-7019, es un módulo Ethernet que posee un servidor web integrado que permite configurar el módulo, controlar y monitorear las E/S desde cualquier navegador web. Con la función web HMI, no es necesario programar ni tener habilidades en HTML; la creación de páginas web dinámicas y atractivas para el control y monitoreo de entradas/salidas será divertido para los ingenieros. El PET-7019 ofrece a los usuarios un acceso fácil y seguro desde cualquier lugar y a cualquier hora.<br>

Además, el PET-7019 soporta también el protocolo Modbus/TCP, lo cual hace una perfecta integración entre este dispositivo y software SCADA.<br>

El PET-7019 es un modulo de 16 bits, con 8 canales de entradas análogas diferenciales y 4 canales de de salidas digitales que proporciona rangos de entradas programables en todos los canales análogos (±15 mV, ±50 mV, ±100 mV, ±500 mV, ±1 V, ±2.5 V, ±20 mA, 0 ~ 20 mA, 4 ~ 20 mA y termopares) y las salidas análogas se pueden configurar con alarmas. Cada canal análogo permite ser configurado con rangos individuales y tienen protección de sobre voltaje de 240 VAC.<BR></p>        

<strong>Caracteristicas:</strong>
<ul>
<li>PoE compatible con IEEE 802.3af</li>
<li>Servidor web integrado</li>
<li>Seguridad de comunicación</li>
