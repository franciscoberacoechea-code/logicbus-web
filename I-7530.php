<p>Conversor inteligente de <a href="convertidores_info#RS-232">RS-232</a> a <a href="convertidores_info#CAN">CAN</a> con utilidad de software y conector DB9 hembra. Con aislamiento de 3000 V en el lado CAN y watchdog incorporado. Admite temperaturas de funcionamiento entre -25 a 75 ° C (-13F ~ 167F).
<br>
En el modo de conexión de pares, I-7530 se puede usar para conectar PC con otros dispositivos RS-232 al mismo tiempo. I-7530 también puede habilitar dispositivos programables RS-232 como PC's, controladores embebidos <a href="I-8411">I-8411</a> / <a href="I-8431">I-8431</a> / <a href="I-8811">I-8811</a> / <a href="I-8831">I-8831</a> para ser el maestro de una red CAN.

<h3>Aislamiento de 3000V en el lado CAN.</h3>
El puerto CAN de la I-7530 está aislado con aislamiento de 3000V. Este aislamiento puede proteger los dispositivos RS-232 locales de la señal de daños proveniente de la red CAN.

<h3>Watchdog interno.</h3>
El watchdog es un circuito de reinicio de hardware para monitorear el estado de la operación. Cuando se trabaja en un ambiente hostil o ruidoso, el I-7530 puede apagarse por la señal externa. El circuito puede permitir que el I-7530 trabaje continuamente y nunca se detenga.

<h3>Visualización del indicador de encendido y error.</h3>
Hay dos indicadores en la I-7530. El indicador de alimentación puede ayudar al usuario a verificar si la I-7530 está en modo de espera o transmitiendo / recibiendo mensajes. El indicador de error se encenderá cuando ocurran algunos errores en la I-7530.</p>

