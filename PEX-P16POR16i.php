<center><strong>Tajeta PCI express, 16 entradas digitales aisladas y 16 salidas a relevador PhotoMos, aislamiento en voltaje de 2000 VDC, bus de datos de 16 bit.</strong></center><br>


<p>La PEX-P16POR16i es una tarjeta PCI Express que contiene 16 canales de entrada ópticamente aislados y 16 canales de salida de retransmisión PhotoMos. Tanto los canales DI aislados como los canales de retransmisión PhotoMos usan una ruta de transmisión óptica corta para transferir una señal electrónica entre los elementos de un circuito y mantenerlos aislados eléctricamente. Los canales DI proporcionan una protección de aislamiento de 2000 V CC, lo que permite que las señales de entrada floten por completo para reducir los bucles de tierra, bloquear los picos de tensión y aislar la computadora host de tensiones dañinas. Los relés PhotoMos se utilizan cuando es necesario controlar un circuito con una señal de baja potencia (con aislamiento eléctrico completo entre el control y los circuitos controlados), o donde varios circuitos deben controlarse con una señal.<br>

El PEX-P16POR16i se puede utilizar en diversas aplicaciones, como controlar el estado ON/OFF de dispositivos externos, controlar relés externos o pequeños interruptores de potencia, activar alarmas, cerrar contactos, detectar voltajes o conmutadores externos, etc. El PEX-P16POR16i es totalmente compatible con el PCI-P16POR16, y los usuarios pueden reemplazar fácilmente el PCI-P16POR16 con el PEX-P16POR16i sin necesidad de modificar el software/controlador cuando usan computadoras PCI Express. La tarjeta se puede instalar en una ranura PCI Express de 3,3 V/12 V y admite el verdadero "Plug & Play", con dos conectores DB-37 provistos para facilitar el cableado.<br>

El PEX-P16POR16i también agrega un interruptor de ID de tarjeta a bordo. Los usuarios pueden configurar la identificación de la tarjeta y luego reconocer la placa mediante la identificación a través del software cuando usan dos o más tarjetas PEX-P16POR16i en una computadora.
</p><BR><br>

