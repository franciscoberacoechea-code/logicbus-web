	    <p> La USB-1602HS-2AO es una tarjeta  multifunci&oacute;n de alta velocidad para medici&oacute;n y control soportada bajo los sistemas operativos de Microsoft® Windows®. Tiene cuatro entradas anal&oacute;gicas referenciadas a tierra de 16 bits, con un  convertidor  A/D por canal y un muestreo m&aacute;ximo de 2MHz por canal. El rango de entrada es programable mediante el software para ±10 V, ±2.5 V, or ±500 mV. Tambi&eacute;n tiene 2 salidas anal&oacute;gicas s&iacute;ncronas de  ±10 V y 16 bits, que puede generar formas de onda de hasta 1MHz por canal; 16 entradas digitales s&iacute;ncronas y  16 salidas digitales s&iacute;ncronas; cuatro contadores de 16 bits o de 32 bits  (que pueden ser configuradas); dos temporizadores/generadores PWM; y tres detectores de cuadratura de 16 bits o 32 bits para medir la posici&oacute;n lineal y rotatoria. </p>
