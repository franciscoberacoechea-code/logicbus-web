    <tr align="right">
      <td><div align="justify">Modbus es un protocolo ampliamente conocido en el campo de manufactura industrial y monitoreo de ambiente. Es un conjunto de aplicaciones de E/S distribuidas de maestro-esclavo. La PC, HMI o PLC pueden usar los protocolos Modbus/TCP o Modbus/RTU para comunicarse con los m&oacute;dulos de E/S que usan un protocolo Modbus/RTU y se conectan a cualquier puerto COM.<br>
          <br>
	  Es un controlador programable basado en el lenguaje C que tiene un sistema operativo MiniOS7. Los usuarios pueden usar compiladores C que pueden crear un archivo ejecutable (*.exe) para desarrollar un programa y luego bajarlo al controlador. Eso dejar&aacute; que el controlador funcione de forma aut&oacute;noma. Hay dos versiones de compiladores (Turbo C 2.0 y Turbo C++ 1.01), se sugiere que se use el  Turbo C++ 1.01.<br>
	  <br>
	  Usando las herramientas de desarrollo del software que se proveen, se puede personalizar el firmware. El SDK provee funciones para comunicaci&oacute;n Modbus, como Modbus/TCP maestro/esclavo,  Modbus/RTU maestro/esclavo, Modbus/ASCII maestro, ... etc. Adem&aacute;s, al llamar las funciones del puerto COM (como IsCom, ReadCom, ToCom, etc) puedes convertir otros protocolos no est&aacute;ndares al protocolo Modbus/TCP o Modbus/RTU. Es decir, el controlador puede ser un convertidor de protocolos tambi&eacute;n.</div>        
