<center><strong>Módulo de 8 canales de salida de DC de relevadores de estado sólido.</strong></center><br>

<p style="text-align: justify;">El módulo I-87066W proporciona 8 canales de salida de relé de estado sólido (SSR) de DC. En comparación con los relés electromecánicos, la tecnología SSR proporciona un tiempo de respuesta más rápido y una mayor resistencia eléctrica. La integración de la tecnología DC SSR también elimina el potencial de ruido de arco, rebote y conmutación. El I-87066W incluye 8 indicadores LED que se pueden usar para monitorear el estado de la salida SSR, y hay opciones disponibles para configurar el encendido y los valores seguros. La protección ESD de 4 kV y el aislamiento intramódulo de 3000 VDC también se proporcionan para mejorar las capacidades de protección contra el ruido del módulo en entornos industriales hostiles.</p><br>


<strong>Caracteristicas:</strong>
<ul>
<li>Salida de 8 canales DC SSR</li>
<li>Salida de relé de estado sólido de DC forma A</li>
<li>Tiempo de operación / liberación rápido</li>
<li>Sin ruidos de arco, rebote o conmutación</li>
<li>Aislamiento intramódulo de 3000 VDC</li>
<li>Valor de encendido configurable</li>
<li>Valor seguro configurable</li>
<li>Tiempo de vida ilimitado del relé</li>
<li>Protección contra ESD de 4 kV</li>
<li>RoHS</li>
<li>Amplio rango de temperatura de funcionamiento: -25 a + 75 ° C</li>
</ul>



