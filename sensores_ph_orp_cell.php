      <h2 align="center">Sensor de pH </h2>
        <p align="justify">Un medidor de pH mide esencialmente el potencial electroquímico entre un líquido conocido en el interior del electrodo de vidrio (membrana) y un fuera de líquido desconocido. Debido a que el bulbo de vidrio fino permite principalmente los iones dehidrógeno ágil y pequeño para interactuar con el vidrio, el electrodo de vidrio mide el potencial de electro-química de los iones de hidrógeno o el potencial de hidrógeno</p>
      <h2 align="center">Sensor ORP ó Redox</h2>
      <p align="justify">ORP (Oxido-reduction potential o REDOX) es una abreviación para Potencial de Oxido-Reducción, es una medida de la actividad de reducción u oxidación en una solución. Es un parámetro útil para el monitoreo y control de reacciones químicas, como por ejemplo: reducción de cromato, destrucción de cianuro, control de ozono o cloro.</p>
      
      <h2 align="center">Sensor Cell (Celda de Conductividad)</h2>
      <p align="justify">La conductividad de una solución se determina midiendo su resistencia eléctrica. El tipo más sencillo de celda de conductividad utilizada consta de dos electrodos similares. La tensión alterna aplicada a uno de los electrodos hace que los iones que se encuentran en la solución se muevan en dirección a dicho electrodo. Mientras más iones haya en la solución, mayor será la corriente que fluye entre los mismos. El conductímetro calcula en base a la corriente medida y a la ley de Ohm la conductancia de la solución y luego, tomando en cuenta los datos de la celda, la conductividad</p>
