        </div><br>


        <p align="justify">Registrador de datos USB, autónomo, mide y almacena más de 250,000 lecturas de temperatura y
          humedad relativa en un rango de -30°C ~ 80°C (22°F ~ 176°F) y rango de 0 ~ 100% de humedad relativa a una
          resolución de 0.1°C y 0.1%. Mediante el software incluido USB-500/600 Data Logger, los usuarios pueden
          configurar rápidamente el registrador de datos y visualizar los datos descargados con la conexión del
          dispositivo al puerto USB de la PC utilizando el cable proporcionado.<br><br>

          <strong>Intervalo de muestreo</strong><br>
          El equipo puede ser programado con intervalos de muestreo desde 10 segundos hasta 2 horas. El registrador
          almacena los datos y luego los carga a la computadora mediante USB cuando la colección está completa.<br><br>

          <strong>Modos inteligentes del registrador</strong><br>
          El usuario puede configurar el dispositivo para iniciar el registro de datos en alguna de los siguientes
          modos:<br>

        <ul>
          <li>Iniciar inmediatamente</li>
          <li>Iniciar cuando el botón del registrador es presionado</li>
          <li>Iniciar en la fecha y hora seleccionadas</li>
          <li>Iniciar en base a una condición de temperatura</li>
        </ul><br>

        <strong>Alarmas</strong><br>
        Provee opciones de alarma alta y alarma baja que pueden configurarse por software. Los usuarios también pueden
        habilitar que la alarma sea mantenida para que el estado de la alarma continúe aún si el valor registrado ya no
        se encuentra en una condición de alarma. La opción de alarma mantenida permite que los usuarios sean notificados
        de una condición de alarma sin que sea necesario descargar los datos del registrador. Las alarmas están
        indicadas por patrones de intermitencia de los LEDs. Este dispositivo también tiene una pantalla LCD e
        indicadores audibles de alarma.<br><br>

        <strong>Pantalla LCD en tiempo real</strong><br>
        La pantalla LCD puede mostrar:<br>
        <ul>
          <li>Valores de temperatura y humedad actuales y máximos/mínimos almacenados</li>
          <li>Pantalla gráfica de temperatura/humedad</li>
          <li>Modo de inicio de registro (si el registro no inicia inmediatamente)</li>
          <li>Indicadores de alarma</li>
          <li>Icono animado que indica si el dispositivo está registrando datos</li>
          <li>Indicador de modo bloqueado cuando el botón de inicio/paro está deshabilitado</li>
        </ul><br>

        <strong>Sesión de registro múltiple</strong><br>
        Los usuarios pueden iniciar y parar el registro mediante software o utilizando los botones del registrador. Esta
        característica permite el almacenamiento de múltiples sesiones de registro entre descargas.<br><br>

        <strong>Características:</strong><br>
        <ul>
          <li>Rangos de medición de -30°C ~ 80°C y 0 ~ 100% de humedad relativa</li>
          <li>Intervalos de registro entre 10 segundos y 2 horas</li>
          <li>Modos de inicio inmediato, retardado, al presionar botón, o lanzado por temperatura/RH</li>
          <li>Protección a prueba de agua IP67</li>
          <li>La pantalla gráfica LCD muestra las lecturas en tiempo real, gráficas y estado actual</li>
          <li>Almacena más de 250000 mediciones</li>
          <li>Imanes integrados para montaje</li>
        </ul><br>

        <strong>Software:</strong><br>
        <ul>
          <li>Incluye software fácil de utilizar para configurar los parámetros de intervalo de muestreo, alarmas, hora
            de inicio, y muchas otras aplicaciones</li>
          <li>Despliegue, grafique y guarde datos en formatos como .csv para importar a Microsoft Excel</li>
          <li>Sistemas operativos soportados: Windows 8/7/Vista SP2/XP SP3, de 32 o 64 bits</li>
        </ul>
