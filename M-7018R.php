          <p> 
            El I-7018 / M-7018 es un módulo de entrada analógica de 8 canales que proporciona entrada de corriente y tensión, así como entrada de termopar. La I-7018R / M-7018R es una versión mejorada de la I-7018 / M-7018 que incluye un mecanismo de protección de alta calidad en el que la protección contra sobretensiones puede ser tan alta como 240 Vrms. La I-7018R / M-7018R es más adecuada para entornos críticamente duros, y la característica de detección de termopar abierta recién agregada hace que la I-7018R / M-7018R sea más atractiva que nunca. La I-7018 / M-7018 / I-7018R / M-7018R también cuenta con protección ESD de 4 kV y aislamiento intramódulo de 3000 VDC. Las especificaciones para los modelos M-7018 y M-7018R son las mismas que las I-7018 y I-7018R, pero brindan soporte adicional para el protocolo Modbus RTU y el protocolo DCON.</p><BR>

          <strong>Características:</strong>
          <ul>
            <LI>La protección contra sobretensión puede ser de hasta 240 Vrms</LI>
