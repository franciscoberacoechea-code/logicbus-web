            <strong>Descripción del producto</strong><br>

            
            <p>El sensor de marca de registro SMARTEYE® X-PRO XP10 detecta de forma fiable la posición de las marcas de registro en varias bandas de material que corren a muy alta velocidad. La frecuencia de conmutación del sensor es 50Khz con una repetibilidad de 5us. Esto proporciona una estabilidad sin precedentes de la posición de la marca. Es ideal en procesos donde el tiempo es crítico, como la impresión a alta velocidad. No todas las aplicaciones de alta velocidad son aplicaciones de marcas de registro. Con sólo pulsar unos pocos botones, este sensor de doble función puede configurarse para funcionar como un sensor fotoeléctrico estándar para cualquier aplicación de alta velocidad. El sensor se utiliza principalmente con fibra óptica de vidrio y plástico, pero puede configurarse con cualquiera de nuestros bloques ópticos para adaptarlo a su aplicación. Además, este sensor tiene 5 posiciones de memoria para el almacenamiento y recuperación de la configuración del sensor. La recuperación de los ajustes se puede hacer de forma remota a través de una interfaz de un solo cable. Puede ser montado de lado o montado en riel DIN. Fabricado en encapsulado Epoxi, es resistente y resistente a las vibraciones. </p><br>

