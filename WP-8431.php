<center><strong>Controlador estándar WinPAC-8000 con conexiones de alta resolución VGA, USB, Ethernet, RS-232/485 y 4 ranuras de E / S, Windows CE.NET 5.0.</strong></center><br>


<p>WinPAC-8000 es el PAC de segunda generación. Equipa CPU PXA270 (520MHz) con sistema operativo Windows CE .NET 5.0, conectividades variantes (VGA, USB, Ethernet, RS-232/485) y ranuras 1/4/8 para módulos de E / S paralelos de alto rendimiento (alto perfil I-8K series) y módulos de E / S de tipo serie (módulos I / O de alto perfil I-87K). Su sistema operativo, Windows CE 5.0, tiene muchas ventajas, incluida la capacidad dura en tiempo real, tamaño de núcleo pequeño, velocidad de arranque rápida, manejo de interrupciones a un nivel más profundo, control determinista alcanzable y bajo costo. El uso de Windows CE 5.0 en WinPAC-8000 le da la capacidad de ejecutar software de control basado en PC como Visual Basic.NET, Visual C #, Embedded Visual C ++, software SCADA, Soft PLC ... etc.
</p><BR><br>


<strong>Caracteristicas:</strong>
<ul>
<li>Windows CE.Net 5.0</li>
<li>Mantenimiento remoto a través del servidor FTP y el software VCEP</li>
<li>Servidor OPC integrado (NAPOPC_CE5)</li>
<li>Rich Software Solutions (VS.Net 2003/2005/2008 y eVC)</li>
<li>Actualización de aplicaciones de WinCon a WinPAC Just Copy and Play</li>
<li>Puerto VGA incorporado</li>
<li>Capacidad de intercambio en caliente del módulo de E / S (estará disponible)</li>
<li>(Para los módulos de perfil alto I-87K solamente)</li>
<li>Capacidad de expansión de E / S enriquecida (RS-232/485, Ethernet, FRnet, CAN)</li>
<li>Disco flash incorporado (31 MB para WP-8x4x, 63 MB para WP-8x3x)</li>
<li>Temporizador de doble vigilancia</li>
<li>SRAM con respaldo de batería doble (512 KB)</li>
<li>Puertos Ethernet dobles</li>
<li>Entrada de energía redundante</li>
<li>El diseño de la carcasa con ventilación permite una operación entre -25 ° C ~ + 75 ° C</li>
</ul>

