  <p><b>Resumen de la aplicaci&oacute;n:</b><br>
    <strong>¿Qué son los frenos por sistema cableado?</strong>
    Son una tecnología nueva, que se usa actualmente en la Fórmula 1 para los autos de carreras. El sistema, que es más rápido y preciso que los frenos tradicionales, controla los frenos de un auto de forma electrónica.
 </p>
 <p>
    <strong>¿Cómo funcionan estos sistemas?</strong>
    No hay una conexión física entre los frenos y el pedal. En su lugar, los pedales funcionan como un simulador, que mide la fuerza y comunica de inmediato estos datos a una unidad de control de frenos. Esta unidad procesa los datos y envía un comando a los actuadores electrohidráulicos para que los frenos se activen.

  </p>
