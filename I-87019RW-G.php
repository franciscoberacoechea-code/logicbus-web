<p align="justify">I-87019RW cuenta con un mecanismo de protección extremadamente excelente donde la protección contra sobretensión es de hasta 240 Vrms. Tiene un rango de entrada más amplio para el voltaje en comparación con el I-87018R. I-87019RW mide voltaje desde +/- 15 mV ~ +/- 10 V. Su tipo de entrada también incluye corriente y termopar. Un diseño intuitivo se mantiene en este modelo; elegir medir la corriente o el voltaje es simplemente por medio de un puente. Ya no se necesita una resistencia externa. Ocho de sus canales de entrada se pueden configurar individualmente con diferentes tipos de entrada analógica. Además, I-87019RW también tiene detección de termopar abierta y muchos mecanismos de protección.</p>

<strong>Características:</strong>
<ul>
<li>Entrada de corriente, entrada de voltaje y entrada de termopar.</li>
<li>Rango de entrada más amplio para voltaje.</li>
<li>240 Vrms Protección contra sobretensión.</li>
<li>Configuración de canal individual.</li>
<li>Configuración de puente para medición de corriente o voltaje.</li>
<li>Detección abierta de termopar.</li>
<li>Protección contra ESD de 4 kV.</li>
<li>Aislamiento intramódulo de 3000 VDC.</li>
<li>RoHS.</li>
<li>Amplio rango de temperatura de funcionamiento: -25 ~ + 75 ° C.</li>
</ul>

