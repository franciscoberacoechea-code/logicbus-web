<center><strong>Unmanaged 8-Port Industrial 10/100 Base-T con 100 Base-FX Fiber Switch con conector SC; Modo singular.</strong></center><br>


<p>El NS-209F / NSM-209F es un Ethernet no administrado de 8 puertos con 1 conmutador de puerto de fibra. Con la fibra óptica, puede evitar que el ruido interfiera con su sistema y admite transmisiones de alta velocidad (100 Mbps) y de alta distancia (hasta 30 km).<br>

El NS-209F / NSM-209F proporciona un amplio rango de potencia de 12 a 48 VDC para adaptarse a todos los estándares de potencia comunes que se encuentran en la automatización industrial, sin convertidores de potencia externos. La amplia entrada de potencia reduce los costos de instalación y mantenimiento.</p><BR>

<strong>Caracteristicas</strong>

<ul>
<li>Proporciona un puerto de fibra 1 x 100-FX más 8 puertos Ethernet.</li>
<li>Cada puerto admite una negociación automática de velocidad de 10/100 Mbps.</li>
<li>Control de flujo de contrapresión Full Duplex IEEE 802.3xy semidúplex.</li>
<li>Crossover automático MDI / MDI-X para plug-and-play.</li>
<li>Arquitectura de almacenamiento y reenvío.</li>
<li>Admite temperaturas de funcionamiento de -10 ~ +75 ° C.</li>
