<center><strong>Convertidor de Ethernet a HART.</strong></center><br>

<p>I-7547 es un convertidor de Ethernet a HART especialmente diseñado como el dispositivo maestro del protocolo HART. Al conectar la I-7547 a la PC a través de Ethernet e instalar la utilidad VxComm, permitirá a los usuarios acceder a los dispositivos HART a través del puerto COM virtual de la PC. Por lo tanto, los usuarios pueden hacer que la recolección de datos y el procesamiento de la red HART sean más fáciles y rápidos al aplicar la I-7547. Además, también ofrecemos la herramienta gratuita HC_Tool para la configuración del módulo y la prueba de comunicación HART fácilmente.</p>

<strong>Características:</strong>
<ul>
<li>Soporte HART armazón corto/largo.</li>
<li>Admite el modo HART Burst.</li>
<li>Soporte de modo HART punto a punto o multi-drop.</li>
<li>Admite la conexión de hasta 15 dispositivos esclavos HART.</li>
<li>Permitir dos maestros HART.</li>
<li>Proporcione la utilidad HC_Tool para la configuración del módulo y la comunicación HART.</li>
<li>Soporte de actualización de firmware a través de Ethernet.</li>
<li>Proporcione el LED de indicación PWR / TxRx.</li>
<li>4KV ESD Protection.</li>
<li>Watchdog incorporado.</li>
<li>Resistencia de carga seleccionable de 250 Ω.</li>
<li>Proporcione cuatro canales HART.</li>
<li>Admite la técnica VxComm.</li>
<li>Servidor web incorporado para la configuración de red.</li>
<li>Soporte HART Pair-Connection (FW_v1.03).</li>
<li>La técnica de soporte FDT (herramienta de dispositivo de campo) y el software FDT a continuación se han probado correctamente.</li>
</ul>
<strong>Aplicaciones:</strong>
<ul>
<li>Medición actual.</li>
<li>Aplicación de la industria petroquímica.</li>
<li>Monitoreo del medio ambiente.</li>
<li>Monitoreo de túneles.</li>
<li>Monitorear el sistema.</li>
<li>Monitoreo del edificio.</li>
</ul>

