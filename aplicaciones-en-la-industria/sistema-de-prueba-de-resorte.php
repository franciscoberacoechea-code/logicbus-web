                    <li class="mb-3">Verificación de calidad: El sistema permite realizar inspecciones de control de calidad eficientes, asegurando que cada resorte cumpla con los estándares de diseño y resistencia especificados.</li>
                    <li class="mb-3">Aplicación de la Ley de Hooke: Con los datos obtenidos, los ingenieros pueden calcular la rigidez del resorte, lo que es crucial para validar sus características de diseño y rendimiento en diferentes aplicaciones.</li>
                    <li class="mb-3">Transmisión de datos en tiempo real: La capacidad de enviar los datos de fuerza a un sistema digital permite un análisis rápido y detallado, optimizando los procesos de prueba y análisis.</li>
