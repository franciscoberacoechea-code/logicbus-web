<p align="justify">El módulo Z109S-DI es una fuente de alimentación con aislador galvánico para el bucle de corriente. Convierte una señal de entrada en una corriente en el rango 0 / 4..20mA y realiza la medición y la retransmisión de la señal en una salida analógica aislada en el rango 0/4 - 20 mA. El módulo puede suministrar un sensor de 2 hilos con 20 V de voltaje estabilizado y 20 mA de corriente máxima protegida contra cortocircuitos. El aislamiento galvánico de 3 vías alcanza 3,500 Vca equivalente a un voltaje de pulso de 6,4 kV. Z109S-DI es muy útil en aplicaciones del sector energético.</p>

<strong>Caracteristicas:</strong>
<ul>
<li>CÓDIGO DE ORDEN : Z109S-DI</li>
<li>DESCRIPCIÓN:  Aislador de bucle de corriente de amplio rango</li>
<li>FUENTE DE ALIMENTACIÓN: 10..40 Vcc, 19..28 Vca</li>
<li>ENTRADA:  0 / 4..20 mA, suppilo de bucle estabilizado de 20 V CC, impedancia de entrada 50</li>
<li>SALIDA: Corriente 0 / 4..20 mA</li>
<li>TIEMPO DE RESPUESTA:  < 200 μs, frecuencia de corte (-3dB) 6kHz</li>
<li>AISLAMIENTO:  3.500 Vca a 3 vías</li>
<li>AISLAMIENTO DE SEGURIDAD: < 300 V ~ referido al suelo CAT II</li>
<li>VOLTAJE DE PULSO: 6,5 kV</li>
<li>TRANSDUCTOR DE POTENCIA:  Técnica de 2 hilos (máx. 20 mA)</li>
<li>DIMENSIÓN:  100x 112 x 18 mm (lxhxw)</li>
<li>MONTAJE:  Carril DIN 46277</li>
<li>CASO: PBT, negro</li>
</ul>

