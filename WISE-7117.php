<center><strong>Módulo de 8 canales de entrada análoga con protección de alto voltaje, 4 canales de salida digital aislados, servidor web integrado para lógica de control IF-THEN-ELSE, alimentación y comunicación a través de Ethernet y Modbus TCP.</strong></center><br>
 <br>

<p> 
WISE (Web Inside, Smart Engine) es una serie de productos desarrollada por ICP DAS que funciona como unidades de control para su uso en control y monitoreo lógico remoto en diversas aplicaciones industriales. WISE ofrece una interfaz de sitio web intuitiva y fácil de usar que permite a los usuarios implementar la lógica de control IF-THEN-ELSE en los controladores a solo unos clics de distancia; no se requiere programación Con sus características potentes y fáciles de usar, minimizará la curva de aprendizaje, acortará el tiempo de comercialización y reducirá drásticamente el esfuerzo y el gasto en el desarrollo del sistema.<br><br>

WISE-7117 sigue la especificación IEEE 802.3af (clasificación, clase 1) de alimentación a través de Ethernet (PoE). Permite recibir energía de la red habilitada para PoE mediante pares Ethernet (cable Ethernet de categoría 5). Esta característica proporciona una mayor flexibilidad y una mayor eficiencia, por lo tanto, simplifica el diseño de los sistemas, ahorra espacio, reduce los cables y elimina la necesidad de enchufes eléctricos dedicados. Mientras tanto, en el caso de un entorno que no sea PoE, WISE-7117 aún podrá recibir energía de fuentes de alimentación auxiliares como adaptadores de CA o batería, etc.<br><br>

Este módulo multifuncional WISE-7117 es compatible con el protocolo Modbus / TCP para una integración perfecta con el software SCADA disponible. Incluye 16 entradas analógicas diferenciales de 8 canales y salidas digitales de 4 canales. Cada canal analógico puede configurar un rango individual y tiene una protección de sobrevoltaje de 240Vrms. Puente seleccionable para entrada de voltaje o corriente.</p><BR>

<strong>Caracteristicas:</strong>
<ul>
<li>Servidor web incorporado para la configuración de reglas IF-THEN-ELSE</li>
<li>Motor de reglas IF-THEN-ELSE incorporado para operación lógica</li>
<li>No más programación. ¡Simplemente haz clic y termina!</li>
<li>Soporte IO, contador, temporizador, operaciones de correo electrónico</li>
<li>Protocolo Modbus / TCP para la integración sin fisuras del software SCADA</li>
<li>Energía sobre Ethernet (PoE) compatible con IEEE 802.3af</li>
<li>10/100 Base-TX Ethernet</li>
<li>Tipo AI: 8 Diferencial (mV, V, mA)</li>
<li>Tipo de DO: 4 salidas de colector abiertas</li>
<li>La protección contra sobretensión es de hasta 240 Vrms</li>
<li>Aislamiento bidireccional / protección ESD</li>
</ul>
