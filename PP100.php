        <p>El crecimiento de robots colaborativos que pueden trabajar de forma segura al lado de las personas hace automatización accesible para una nueva generación de aplicaciones. Sin embargo, esta accesibilidadse ha producido a costa de precios más altos, la pérdida de funciones y un tiempo de ciclo reducido. 
        <br>
        El PP100 es el único robot cartesiano colaborativo del mundo. Su diseño mecánico único ofrece un precio inferior a la mayoría de los robots de colaboración y reduce los costos generales de las aplicaciones de sobremesa. Este robot liviano está disponible con 2 ejes (XZ) o 3 ejes (XYZ) y una opción Theta / Servo Gripper. Puede ser transportado por una persona, montado en una mesa y, al enchufar solo un cable de alimentación de CA y un cable Ethernet,listo para funcionar, lo que reduce en gran medida el tiempo y el costo de integración. El controlador, las fuentes de alimentación y el uso del cableado están integrados dentro de la estructura del robot, simplificando las instalaciones y permitiendo que el PP100 se monte sobre el trabajo existente áreas y equipos tales como cintas transportadoras. Los diseño cartesiano colaborativo permite extremadamente celdas de trabajo pequeñas y económicas que tienen un impacto mínimo en la producción existente. 
        <br><br>
        Los robots colaborativos potencialmente permiten la creación de un entorno de fabricación mixto donde las personas pueden ingresar y trabajar eficientemente alrededor de los robots sin la pérdida de rendimiento. Sin embargo, otros robots "colaborativos" deben moverse lentamente o usar un modo colaborativo de velocidad reducida, lo que afecta la producción cuando los usuarios están cerca. La combinación única de PP100 de la velocidad y la seguridad permiten su funcionamiento a toda velocidad y ofrecen un rendimiento industrial con fuerzas de colaboración estándar ISO seguras, por lo que los operadores pueden moverse libremente alrededor del robot sin preocuparse por su seguridad o pérdida de productividad. 
        <br>
        Las geometrías complejas de los robots colaborativos de 6 ejes dificultan la tarea de los operadores, mientras que la geometría cartesiana simple del PP100 es particularmente fácil de enseñar para los nuevos usuarios, ya que cualquier combinación de posición y movimiento es intuitiva y posible. Además, muchos robots colaborativos usan un entorno de programación con funciones limitadas para simplificar la configuración de nuevos usuarios. Los robots de colaboración de Precise Automation ofrecen la flexibilidad de una interfaz basada en web fácil de usar y un entorno de programación avanzada opcional tan capaz como cualquier robot industrial. La interfaz fácil de usar Guidance Motion es accesible desde cualquier dispositivo habilitado para la web y permite a los técnicos u operadores configurar y enseñar rápida y fácilmente al PP100 para realizar un trabajo real.</p>



