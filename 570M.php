<br><br>
Las entradas A / D son seleccionables independientemente por software para rangos de +/- 5V o +/- 15V y cuentan con una alta impedancia de entrada, lo que permite una fácil conexión a una variedad de sensores. Las entradas A / D admiten selecciones flotantes / no referenciadas o referenciadas en tierra. Esto hace que las entradas A / D sean ideales para medir fuentes de señales flotantes , como salidas de transformadores, termistores y dispositivos alimentados por batería. Además, las entradas A / D pueden operar en modo bipolar o unipolar, y un interruptor DIP permite una tensión de polarización de +5 a través de una resistencia de 10K para el modo de entrada de termistor.
<br><br>
El módulo SeaI / O-570M cuenta con ocho entradas aisladas ópticamente para 5-30V DC y proporciona un aislamiento externo de 3500V DC, mientras que los relés de Form C se pueden configurar como normalmente abiertos o normalmente cerrados y pueden conmutar cargas de CC de hasta 24 W. Perfecto para una variedad de aplicaciones de adquisición / control de datos y de prueba y medición, el SeaI / O-570M incluye bloques de terminales extraíbles, que simplifican las conexiones de cableado de campo.
<br><br>
El SeaI / O-570M se alimenta desde su fuente de 9-30V DC, o se selecciona de una variedad de opciones de fuente de alimentación de Sealevel. Los módulos funcionan en un amplio rango de temperatura de operación de -20C a + 70C y el rango de temperatura extendido es opcional.
Comuníquese con el SeaI / O-570M utilizando las librerias de software Seamavel API de SeaMAX o use cualquier dispositivo compatible con Modbus RTU. Los controladores y las utilidades del software SeaMAX de Sealevel facilitan la instalación y el funcionamiento con los sistemas operativos Microsoft Windows 10 y 8.
