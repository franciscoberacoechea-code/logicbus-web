<h1><br>DN-PR4 </h1>

<div align="center">
  <img src="imagenes/02/dn-pr4.jpg" alt="DN-PR4" title="DN-PR4" class="image_productos" width="20%">
</div><br>

<strong><center>Tarjeta con 4 relevadores forma C (SPDT) con capacidad de 5A a 250VAC/30VDC.</center></strong>

<div align="right">
<a href="https://tienda.logicbus.com.mx/DN-PR4_p_2461.html" title="Ir a Tienda" target="_blank"><img src="images/shopping_cart.png" alt="Comprar"></a>
</div> <br>

<p>El DN-PR4 cuenta con un montaje de riel DIN y cuatro relés de potencia electromecánicos de forma C para una conmutación eficiente de la carga mediante control programado. El contacto de cada relé puede controlar una carga de 5 A a 250VAC / 30VDC. 
El relé se energiza al aplicar una señal de voltaje de + 24 V al canal de relé apropiado. Cada salida está equipada con un LED para mostrar su estado. Cada salida está equipada con un varistor que evita la sobretensión de la carga inductiva o el freno electromagnético para proteger el punto de contacto del relé. Se puede acceder a todas las salidas de relé y control a través de los terminales de cableado.
</p><br>


<strong>Características</strong>
<ul>
<li>4 Relés Forma C (SPDT)</li>
<li>Terminales de cableado industrial para cableado de salida fácil</li>
<li>Cambie hasta 5A a 250VAC / 5A a 30VDC</li>
<li>LEDs indicaron estado de relé</li>
<li>Diodos incorporados para proteger contra la conexión incorrecta de la fuente de alimentación externa.</li>
<li>Varistor diseñado para proteger el pico de alto voltaje de cada canal</li>
<li>Montaje en carril DIN</li>
<li>Se conecta directamente a los módulos ICP CON I-7000, salida aislada ISO-730, salida ISO-C64, salida aislada ISO-P32C32 ... etc.</li>
</ul><br>

<strong>Aplicaciones</strong>
<ul>
<li>Control de encendido / apagado</li>
<li>Gestión energética</li>
<li>Automatización de pruebas</li>
<li>Control de procesos</li>
</ul>


