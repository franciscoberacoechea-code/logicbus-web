<h2>Caracteristicas</h2><br>
<p align="justify">El controlador de automatización programable VP-25W6 ViewPAC es la nueva generación de PAC basado en WinCE de ICP DAS. ViewPAC combina el controlador WinPAC, la pantalla gráfica y el teclado en una unidad. Equipa una CPU PXA270 (520MHz) con sistema operativo Windows CE.NET 5.0, conectividades variantes (USB, Ethernet, RS-232/485), 3 ranuras para expandir módulos de E / S, LCD TFT 3.5 "/5.7" y una goma teclado.<br />
Windows CE.NET 5.0 incluye capacidad dura en tiempo real, tamaño de núcleo pequeño, velocidad de arranque rápida, manejo de interrupciones y control determinista. El VP-25W6 también incluye el sofisticado software de InduraSoft Web Studio SCADA y el software ISaGRAF IEC-61131.InduSoft es una potente colección integrada de entorno de desarrollo de software de desarrollo que incluye todos los componentes necesarios para desarrollar una interfaz hombre-máquina (HMI) y control de supervisión. Sistemas de Adquisición de Datos (SCADA). ISaGRAF es un software de tipo PLC y es compatible con los cinco lenguajes IEC61131-3 (lógica de escalera, texto estructurado, diagrama de bloques de función, diagrama de flujo secuencial)<br />
En comparación con las soluciones IPC + PLC tradicionales, ViewPAC reduce el costo general del sistema, el espacio y le ofrece todas las mejores características de IPC y PLC.</p>

