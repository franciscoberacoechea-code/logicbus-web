                    <p>El <strong>osciloscopio</strong> es una de las herramientas más importantes que existen hoy en día, el funcionamiento de este aparato está basado en la posibilidad de desviar un haz de electrones por medio de creaciones de campos eléctricos y magnéticos. Existen muchos aparatos que son capaces de medir diferentes magnitudes, como los que miden las tensiones (voltímetros), intensidades (amperímetros), potencias (vatímetros), etc. Pero hoy en día el <strong>osciloscopio</strong> es uno de los aparatos de medidas más importantes, no solo se puede averiguar el valor de una magnitud, sino que, entre muchas cosas, y como muestra de sus resultados, son representadas con gráficas. Estas gráficas se van a refregar en las pantallas de los osciloscopios, debido al movimiento de un haz de electrones sobre una pantalla de fósforo.</p>
