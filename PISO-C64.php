<center><strong>Tarjeta de salida digital de 64 canales, abierta y aislada ópticamente. Incluye CA-4037B capaz y dos conectores CA-4002 D-Sub.</strong></center><br>


<p>El PISO-C64 tiene 64 canales de salidas digitales ópticamente aisladas, dispuestas en dos bancos aislados. Cada salida digital ofrece un transistor Darlington y diodo de supresión integral para carga inductiva. Los canales de salida aislados están diseñados en el grupo C y el grupo D. El suministro de energía del puerto de entrada puede usar energía externa o la potencia desde el lado de la PC usando el convertidor CC / CC. La fuente de alimentación del puerto de salida debe usar alimentación externa. Esta placa de interfaz se instala fácilmente en cualquier PC compatible con PC / AT / XT. La placa interactúa con las señales lógicas de campo, lo que elimina los problemas de bucle de tierra y aísla la computadora host de tensiones dañinas. El ISO-C64 tiene un conector D-Sub de 37 pines y un conector macho de 40 pines. Los usuarios pueden conectar la señal digital a través del segundo conector D-Sub. Cada conector D-Sub contiene 32 canales de salida.
</p><BR><br>

<strong>Caracteristicas</strong>

<ul>
