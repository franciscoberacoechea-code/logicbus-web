	<b>Descripción del producto</b>
<br>
<br>
El nuevo osciloscopio de Super Fósforo de la serie SDS1000X-E de SIGLENT está disponible en un ancho de banda de 200 MHz. Tiene una tasa de muestreo máxima de 1 GSa/s y una longitud de registro estándar de 14 Mpts. Para facilitar su uso, se puede acceder a las funciones más utilizadas con su diseño de panel frontal fácil de usar.
<br/>
<br/>
La serie SDS1000X-E emplea una nueva generación de tecnología SPO (Super Osciloscopio de Fósforo) que proporciona excelente fidelidad y rendimiento de señal. El ruido del sistema es también más bajo que los productos similares en la industria. Viene con un rango mínimo de entrada vertical de 500 uV / div, un innovador sistema de disparo digital con alta sensibilidad y baja fluctuación de fase, y una velocidad de captura de forma de onda de 400.000 fotogramas por segundo. El SDS1000X-E también emplea una función de visualización de grados de intensidad de 256 niveles y un modo de visualización de temperatura de color que no se encuentra en otros modelos de esta clase. La última oferta de osciloscopios de Siglent ofrece múltiples modos de disparo potentes, incluyendo la activación de bus serial. La decodificación ofrece configuraciónes estándar incluyendo IIC, SPI, UART, CAN, LIN. El historial de la grabación de la forma de onda y el disparo secuencial permiten la grabación y análisis de la forma de onda extendida. Otra potente adición es la nueva función matemática FFT de 1 millón de puntos que proporciona a la SDS1000X-E una resolución de alta frecuencia cuando observa espectros de señal. El nuevo diseño también incluye un co-procesador de hardware que ofrece mediciones de forma rápida y precisa. Las características y el rendimiento de la nueva SDS1000X-E de Siglent no se pueden equiparar a ningun otro producto de este rango de precio.
