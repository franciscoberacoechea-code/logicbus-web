<h3 align="center">Diagramas de aplicaciones<br>Tanque dispensador</h3>

<center><img src="imagenes/36/llb350_app_01.jpg" alt="Diagramas de aplicaciones" title="Diagramas de aplicaciones" width="30%" class="image_productos"></center><br>

<p align="justify">En esta aplicación las celdas de carga son usadas para controlar la distribución del material mientras se está monitoreando el nivel del contenido de tanque. La celda de carga con un amplificador en línea puede estar directamente conectada a un PLC o computadora para la retroalimentación del control o a uno de los instrumentos con opción de alarma o salida análoga. Un sonido de alarma puede ser conectado a el PLC, computadora o el display para avisar cuando el proceso está completo o cuando el tanque está lleno o vacío.</p><br>

<h3 align="center">Control del nivel de dos tanques</h3>

<center><img src="imagenes/36/llb350_app_02.jpg" alt="Diagramas de aplicaciones" title="Diagramas de aplicaciones" width="30%" class="image_productos"></center><br>

<p align="justify">Como se muestra en la imagen de esta aplicación, el volumen de uno o varios contenedores sin importar su figura o forma pueden ser monitoreados y controlados durante un proceso automatizado usando celdas de carga e instrumentos para mostrar los valores mientras se activa o desactiva el sistema, requiriendo la utilización de instrumentos con puntos de alarmas o la interacción con un PLC o computadora vía instrumentos con salida análoga o RS232 y USB.</p><br>

<h3 align="center">Torre de viento</h3>

<center><img src="imagenes/36/llb350_app_03.jpg" alt="Diagramas de aplicaciones" title="Diagramas de aplicaciones" width="30%" class="image_productos"></center><br>

<p align="justify">Usando una o varias celdas de carga, puedes monitorear la tensión inducida por la actividad de fuertes vientos en las torres localizadas en áreas remotas. La celda de carga está conectada a un amplificador en línea y a un sistema de adquisición de datos para grabar todos los datos y hacerlos disponibles a través de una conexión de Internet vía teléfono celular y así pueda ser monitoreada toda la actividad por Internet donde sea y cuando sea.</p><br>

