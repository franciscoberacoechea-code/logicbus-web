<LI>Aislamiento intramódulo de 3000 VDC</LI>
<LI>Dual Watchdog</LI>
<LI>Conformidad con la RoHS</LI>
<LI>Amplia gama de temperaturas de funcionamiento: -25 ~ + 75 ° C</LI>
</ul>
