<p>Los contactares proporcionan un control remoto por cable, primordialmente de motores eléctricos y sistemas de compensación y calefacción. Protegen a los instrumentos y equipos contra corrientes de sobrecarga mediante el uso de relevadores térmicos.
 <br>
Requieren una corriente muy baja en su bobina de activación ~40mA, lo que permite que un PLC con salidas de relevador (magnético o estado sólido) pueda controlar grandes cargas de corriente (hasta 20A) y con una sola salida controlar el estado de tres fases.
 <br>
La bobina se activa con 110VAC. Los contactores permiten la instalación en Riel Din, lo que lo hace de fácil instalación.

