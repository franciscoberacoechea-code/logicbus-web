  <strong>Tarjeta INET-4xx con 28 canales de E/S digitales: 12x Entradas / Salidas Digitales Universales (20mA sink, -10V..30V) + 16xEntradas / Salidas Digitales (200mA sink, -10V..30V).</strong>
