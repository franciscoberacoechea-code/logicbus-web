          <center><strong>Módulo DAQ con 4 entradas digitales y 5 salidas a relevador Forma A (250Vac@5A o 30Vdc@5A) con 9 LEDs indicadores de estado. Interfaz RS-485 soporta protocolos Modbus RTU y DCON. Incluye software gratuito EZ Data Logger. Requiere alimentación 10 a 30 Vdc</strong></center><br>

          <p>M-7065 es un módulo de adquisición y control de datos, entrada / salida digital. El módulo se puede controlar de forma remota utilizando un conjunto de comandos, que llamamos el protocolo DCON. La comunicación entre el módulo y el host se realiza en formato ASCII a través de un estándar de bus serie bidireccional RS-485. Las tasas de baudios son programables por software y se pueden seleccionar velocidades de transmisión de hasta 115.2K baudios. La funcionalidad de la serie M-7000 es la misma que la de la serie I-7000, excepto que la serie M-7000 ofrece soporte extendido para el protocolo Modbus RTU.</p><BR>

          <strong>Características</strong>

          <ul>
            <li>4 canales de entrada digital y 5 canales de salida de relé</li>
            <li>Forma A Salida de relé de potencia</li>
            <li>Fregadero y tipo de fuente para entrada digital</li>
            <li>Los canales de entrada digital se pueden usar como contadores de 16 bits</li>
            <li>Configuraciones Confiables de Power-on Value</li>
            <li>Configuraciones de valor seguro configurables</li>
            <li>Dual Watchdog</li>
            <li>Amplia gama de temperaturas de funcionamiento: -25 ~ + 75 ° C</li>
          </ul>
