<div align="center">
  <strong>Kit de Diagnóstico Automotriz con 4 canales</strong>
</div><br>

<p align="justify">El kit de osciloscopio de uso automotriz PicoScope 4423 puede ser utilizado para medir y probar prácticamente todos los componentes y circuitos eléctricos y electrónicos de cualquier vehículo moderno como:</p>
<ul>
<li>Circuito de encendido (primario y secundario)</li>
<li>Inyectores y bombas de combustible</li>
<li>Circuitos de arranque y carga</li>
<li>Baterías, alternadores y motores de arranque</li>
<li>Longitud de onda, flujo de aire , golpes y sensores MAP</li>
<li>Relevadores, bujías, temporizadores </li>
</ul><br>

<strong>Preparado para el futuro</strong><br>

<p align="justify">A diferencia de una herramienta de diagnóstico de una serie de automóviles serie, el PicoScope 4423 es compatible con cualquier marca o modelo de automóvil ya sea de gasolina, diesel, eléctrico o híbrido . 
<br><br>
El PicoScope 4423 ofrece una mezcla inigualable de características de resolución, buffer de memoria, frecuencia de muestreo, ancho de banda y de software. Señales rápidas y complejas como el bus CAN y FlexRay no son un problema, ya que este dispositivo es capaz de realizar mediciones de estos  buses lo que garantiza su PicoScope 4423 podrá ser utilizado durante muchos años.</p><br>

<strong>Fácil de usar</strong><br>

<p align="justify">El PP903 es potente y flexible, ha sido diseñado para facilitar su uso a usuarios con poca expericneica en uso de osciloscopios como para expertos.
<br><br>
El PicoScope 4423 toma su alimentación desde el puerto USB del PC de modo que no se requieren baterías o cables de alimentación , por lo que es adecuado para su uso tanto para el diagnóstico automotor y móvil como en el taller.</p><br>

<strong>Software automotriz Potente</strong><br>

<p align="justify">El PP903 incluye el potente software de diagnóstico automotriz PicoScope Automotive. Usar esta herramienta es rápido y fácil, sólo tiene que seleccionar el sensor o circuito a medir y el software se cargará automáticamente la configuración necesaria y le dará los detalles de qué instrumentos utilizar para las mediciones y cómo conectarlos, también recomendaciones y muestras sobre la forma de onda que se obtiene e información técnica general sobre el componente que se está probando.
<br><br>
El PP903 incluye la herramienta PicoDiagnostics con la que el usuario puede hacer un chequeo completo del motor . Con tan sólo una simple conexión a la batería se puede realizar una prueba de equilibrio del cilindro, detectar fallas y realizar una prueba de compresión. También es posible realizar pruebas del sistema eléctrico, motor de arranque y alternador. Los resultados se muestran en un gráfico de barras que puede ser fácilmente interpretado.
<br><br>
Todo el software de automoción del PP903 es gratuito.</p>

