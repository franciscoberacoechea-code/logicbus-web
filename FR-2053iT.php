<h3>Caracteristicas</h3>
<h4>Introducción</h4>
<p>El FR-2053TA tiene 16 canales aislados de entrada Sink/Source, mientras que el FR-2057TA tiene 16 canales de salida de fuente aislada. El módulo de E/S FR-2000 tiene una interfaz FRnet. Los usuarios pueden conectar en cadena varios módulos FR-2000 juntos. A través de FRnet, los módulos FR-2000 pueden extender el control remoto de E/S de PC, PAC y PLC fácilmente. Más información sobre la creación de redes de FR-2053TA/2057TA; consulte la bibliografía relacionada con I-7188EF, I-8172, FRB-100/200/200U.</p>

