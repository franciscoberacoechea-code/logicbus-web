                  persistencia digital, funciones matemáticas y mediciones automáticas, el software PicScope te permite
                  usar tu PicoScope 4224 o el 4424 como un analizador de espectros, es totalmente gratuito y
                  regularmente actualizado con nuevas características y mejoras y siempre podrás descargar las mas
                  nuevas actualizaciones.Sabemos que podrías querer escribir tu propio software o usar software de
                  terceros para controlar tus osciloscopios. No hay problema, también contamos con un kit de desarrollo
                  gratuito que contiene drivers y códigos de ejemplo.<br><br>

