<center><strong>3G WCDMA Ahorro de energía PAC con cargador solar (RoHS).</strong></center><br>

<p>La serie G-4513 es PAC de ahorro de energía M2M (Machine to Machine) con un transceptor celular y un cargador solar. Puede ser utilizado en el monitoreo hidrológico o sistema de monitoreo deslave. Con el modelo de GPS opcional, el G-4513 también puede ser un sistema de seguimiento por GPS para la gestión del vehículo o el sistema marítimo. Las características de la serie G-4513-3GWA: cargador solar, módulo 3G, interfaz Ethernet, módulo GPS opcional, 3 entradas digitales, 3 salidas digitales, 8 entradas analógicas, 1 salida de relé.</p>

Caracteristicas:
<ul>
<li>Embedded MiniOS7, antivirus.</li>
<li>Soporta GSM 850/900/1800/1900 MHz.</li>
<li>Soporta WCDMA 850/900/1900/2100 MHz.</li>
<li>Cargador solar para batería de plomo.</li>
<li>Controlador Ethernet 10/100 Base-TX compatible.</li>
<li>Puerto COM: COM1 (5 cables RS232), COM2 (RS-485).</li>
<li>E / S: 3 DI, 3 DO, 8 AI, 1 relé DO.</li>
<li>Soporte de tarjeta SD.</li>
<li>Built-in RTC, NVRAM, EEPROM.</li>
<li>Pantalla LCD de 128 * 64 puntos (opción).</li>
<li>GPS: 32 canales con seguimiento All-In-View (opción).</li>
<li>Soporta TCP, conexión de cliente UDP a través de GPRS.</li>
<li>Alta fiabilidad en entornos hostiles.</li>
<li>Montaje en riel DIN.</li>
</ul>
