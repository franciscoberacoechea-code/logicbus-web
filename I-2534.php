<center><strong>Switch industrial de cuatro puertos Bus CAN. Compatible con CAN 2.0A y 2.0B. Instalación en riel DIN. Alimentación +10 ~ +30 VDC, soporta múltiples velocidades de transmisión.</strong></center><br>

<p>El I-2534 es un tipo de interruptor de bus CAN. Hay cuatro canales CAN independientes que ofrecen un diseño flexible de la topología de inicio o red de árbol. Esta nueva topología podría resolver el complejo Aplicación de bus CAN, como maquinaria industrial, automatización de edificios, automatización de vehículos, etc. Además, el I-2534 integra e intercambia datos entre diferentes redes CAN que tienen diferente velocidad de transmisión Ayuda a los usuarios a extender el sistema de red CAN. El I-2534 podría aumentar el número máximo de nodos CAN en la red CAN dividiendo la red CAN en varias subredes. En adicional, también se admiten la velocidad de transmisión CAN CAN definida por el usuario y la configuración del filtro CAN.</p>


<ul>
<strong>Especificaciones:</strong>

<li>4 puertos de comunicación CAN</li>
<li>Compatible con la especificación CAN 2.0A y 2.0B</li>
<li>Totalmente compatible con el estándar ISO 11898-2</li>
<li>Velocidad en baudios: 5 k, 10 k, 20 k, 33,3 k, 50 k, 62,5 k, 83,3 k,</li>
<li>125 k, 250 k, 500 k, 800 k, 1 M bps y definido por el usuario</li>
<li>El filtro de bus CAN es configurable</li>
<li>Búfer de 100 marcos de datos para cada canal CAN</li>
<li>Flujo máximo de datos de hasta 2500 fps para todos los canales CAN</li>
<li>Velocidad de transmisión seleccionable por interruptor giratorio</li>
<li>Resistencia de terminación seleccionable de 120O mediante interruptor DIP</li>
<li>LED para estado CAN.</li>
</ul>

