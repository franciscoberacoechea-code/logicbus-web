<div align="center">
  <strong>Tarjeta con 20 SE/10 DIFF entradas de voltaje, multiplexor, 4 E/S digitales.</strong>
</div><br>

<p align="justify">Este módulo amplificador ofrece 20 SE/10 DIFF canales de entrada de voltaje, cada cual se puede programar de manera independiente con el software para Windows que soporta la conexión directa a mucho tipos de sensores. 
<br><br>
Este módulo no contiene un convertidor A/D, y además internamente encamina el voltaje medido a un módulo A/D en cualquier parte de la caja para tarjetas. Al menos debe haber instalado un módulo A/D con la finalidad de medir un voltaje con este módulo. 
<br><br>
Cada uno de los 10 canales diferenciales soporta conexión directa a algunos de los siguientes tipos de sensores: voltaje, termopar, termistor, RTD, celda de carga, galga extensiométrica, potenciómetro, corriente, resistencia. El rango de entrada de voltaje en cada canal es independientemente programable a uno de: +/-20mV, +/-40mV, +/-80mV, +/-2.5V, +/-5V, +/-10V, 0 a 5V, 0 a 10V.</p>

<strong>Caracteristicas:</strong>
<ul>
<li>Se conecta a una ranura de la caja de tarjetas de instruNet.</li>
<li>20 SE/10 DIFF canales de entrada de voltaje.</li>
<li>4 E/S digitales universales (20mA sink, -10V~30V).</li>
<li>Se conecta directamente a sensores: voltaje, termopar, termistor, RTD, celda de carga, galga extensiométrica, potenciómetro, corriente, resistencia.</li>
<li>Se requiere de un módulo A/D adicional para medir voltaje.</li>
</ul><br><br>

