<center><strong>Controlador de automatización programable ISaGRAF Ethernet con 8 ranuras de E / S (doble LAN: 10/100 Mbps) y Windows CE.NET 5.0.</strong></center><br>


<p>La serie WinPAC-8x47 (WP-8147/8447/8847) es la nueva generación basada en WinCE ISaGRAF PAC (controlador de automatización programable) de ICP DAS. Equipa una CPU PXA270 (520 MHz) con sistema operativo Windows CE.NET 5.0, conectividad de variante (10/100 puertos Ethernet Base-TX dobles, 2 o 4 puertos RS-232/485, 1 VGA, 1 puerto USB) y 1 / 4/8 ranuras para módulos de E / S de alto rendimiento de tipo paralelo (serie I-8K de alto perfil) y módulos de E / S de tipo serie (módulos de E / S de alto perfil Hot-Swap I-87K). Los recuerdos vienen con SRAM de 128 MB, SRAM con respaldo de batería dual de 512 KB, FLASH de 96 MB y microSD de 1 GB. Para soporte redundante: Temporizadores Dual Watchdog, entradas de alimentación redundantes, SRAM de respaldo de batería doble, puertos Ethernet duales. ¡La serie WinPAC-8x47 actualizará tu sistema! 
</p><BR><br>


<strong>Caracteristicas Generales:</strong>
<ul>
<li>PXA270, CPU a 520 MHz</li>
<li>Windows CE 5.0</li>
<li>Embedded ISaGRAF Ver.3 SoftLogic (IEC 61131-3)</li>
<li>Capacidad dura en tiempo real</li>
<li>Salida de puerto VGA</li>
<li>Modbus RTU / TCP (maestro, esclavo)</li>
<li>Admite eLogger HMI</li>
<li>Entradas de energía redundantes</li>
<li>Temperatura de funcionamiento: -25 ~ +75 ° C</li>
</ul>

