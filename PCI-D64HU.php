<center><strong>40 MB/s de alta velocidad 32-CH DI y 32-CH DO tarjeta universal PCI DIO.</strong></center><br>


<p>PCI-D64HU es una tarjeta de E/S digital de alta velocidad que consta de 32 canales de entrada digital y 32 canales de salida digital. Los diseños de alto rendimiento hacen que esta tarjeta sea perfecta para aplicaciones de transferencia de datos de alta velocidad y generación de patrones.<br>

El PCI-D64HU realiza la transferencia de datos de alta velocidad mediante el bus-masterización de DMA a través del bus PCI de 32 bits. La velocidad máxima de transferencia de datos puede ser de hasta 40 MB por segundo. Se admiten varios modos de transferencia de E/S digitales, como control de E/S programadas directas, control de marcapasos del temporizador, modo de reloj externo y modo de intercambio de manos. Es una interfaz de conexión confiable y rentable que funciona en su sistema informático para controlar los periféricos de alta velocidad.
</p><BR><br>

<strong>Caracteristicas</strong>

<ul>
<li>Admite bus PCI universal de 32 bits y 33 MHz</li>
<li>32-CH 5 V entradas digitales TTL</li>
<li>32-CH 5 V salidas digitales TTL</li>
<li>dispersión de masterización de bus 2-CH/recopilación de DMA</li>
<li>Velocidad de transferencia de datos de hasta 40 MB/s para cada canal</li>
<li>Admite 4 modos de transferencia de datos:</li>
<ul>
<li>Modo de control de programa directo</li>
<li>Modo de marcapasos del temporizador interno</li>
<li>Modo de reloj externo (solo DI)</li>
<li>Modo de apretón de manos</li>
</ul>
<li>A bordo 1 k/2 k DWORD FIFO para DI/DO respectivamente</li>
<li>DO FIFO admite el modo de buffer de anillo</li>
<li>No hay carga de bus en la aplicación de generación de patrones repetitiva</li>
<li>Filtro digital de entrada programable para todas las señales de entrada, incluidas las señales de activación y disparo</li>
</ul>
