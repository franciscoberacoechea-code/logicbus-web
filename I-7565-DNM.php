<p>I-7565-DNM puede representar una solución económica para aplicaciones DeviceNet y ser un dispositivo maestro DeviceNet en una red DeviceNet.  Es un "set de conexión maestro-esclavo predefinido".  I-7565-DNM soporta el grupo 2 solo servidor y las funciones UCMM para comunicación con dispositivos eclavos.  Tiene un puerto de comunicación CAN independiente y tiene la habilidad de cubrir un amplio rango de aplicaciones DeviceNet.</p><BR>

<strong>Caracteristicas:</strong>
<ul>
<LI>Totalmente compatible con  USB 1.1/2.0</LI>
<LI>No requiere de alimentación externa, toma la alimentación del puerto USB</LI>
<LI>MAC ID maestro programable y velocidad de transmisión</LI>
<LI>Velocidad de transmisión: 125K, 250K, 500K</LI>
<LI>Modos de operación E/S: Poll, Bit-Strobe, cambio de estado/cíclico</LI>
<LI>Longitud E/S: 512 Bytes max. (Entrada/Salida) por esclavo</LI>
<LI>Nodo esclavo: 63 nodos máximo</LI>
<LI>Soporta auto búsqueda de dispositivos esclavos</LI>
<LI>Soporta adición y eliminación de dispositivos</LI>
<LI>Auto reconexión cuando la conexión se pierde</LI>
<LI>LED de estatus: RUN, MS, NS</LI>
<LI>Software gratuito para Windows</LI>
<LI>Driver soportado por Windows 98/ME/2000/XP/Linux</LI>
