La PCI-DIO96H/SIPSCKT es una tarjeta digital de E/S de bajo costo, con sockets SIP para instalar resistencias pull-up/pull-down. La PCI-DIO96H/SIPSCKT ofrece 24 bits de E/S digitales. Esta basado en el chip 82C55, que es un poderoso chip de 24 bits que funciona como 2 puertos de 8 bits (Puerto A y B) y un tercer puerto de 8 bits (Puerto C) que pueden ser divididos en 2 puertos de 4 bits (Puerto C-HI y C-LO). El uso de resistencias pull-up y pull-down son importantes si necesitas configurar un valor fijo para evitar que el valor de entrada sea flotante. </td>
