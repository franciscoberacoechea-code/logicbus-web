<ul>
<li>Visualización simultánea de CO, CO2, temperatura, humedad y punto de rocío</li>
<li>Rango de medición</li>
<li>CO: 0 ~ 1000 ppm</li>
<li>CO2: 0 ~ 9999 ppm</li>
<li>Sensor de CO2 infrarrojo no dispersivo (NDIR)</li>
<li>2.8 "pantalla táctil LCD</li>
<li>Capaz de almacenar hasta 450,000 registros con sellos de fecha y hora</li>
<li>Interfaz de configuración basada en web y pantalla táctil</li>
<li>Incluye la utilidad de software gratuita, la aplicación iOS y la aplicación para Android</li>
<li>Capaz de mostrar mensajes multilingües en la pantalla</li>
<li>Admite los protocolos DCON, Modbus RTU, Modbus TCP y MQTT</li>
<li>Incluye interfaces de comunicación RS-485 / Ethernet / PoE</li>
<li>Salida de relé para alarma audible / visual o control de dispositivo IAQ</li>
<li>Aprobación de protección IP 65</li>
</ul>


