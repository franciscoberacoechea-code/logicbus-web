        <p align="justify">El GW-7228 es una solución que proporciona una conversión de protocolo entre J1939 y Modbus RTU. Para la red J1939, el GW-7228 admite PDU1, PDU2, tipo específico de transmisión y destino de mensajes J1939. Desde la vista de la red Modbus RTU, el GW-7228 es un esclavo Modbus RTU para responder la solicitud desde Modbus RTU maestro. Proporcionamos software de utilidad para que los usuarios configuren los parámetros de J1939 / Modbus RTU del GW-7228. Los campos de aplicación pueden ser aplicaciones de trenes de potencia Diesel, redes en vehículos para camiones y autobuses, etc.

