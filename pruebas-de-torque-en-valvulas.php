    <p><b>C&oacute;mo funciona:</b><br></p>
    <ol>
      <li style="color: black;">En esta aplicación, un sensor de torque a reacción se monta entre el actuador (válvula eléctrica) y la base.</li>
      <li style="color: black;">El vapor de la válvula pasa libremente sin entrar en contacto con el sensor de torque.</li>
      <li style="color: black;">El sensor de torque a reacción mide la torsión requerida por el actuador para operar la válvula.</li>
