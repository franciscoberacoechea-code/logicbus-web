                <h2 class="subtitle blue">FUNCIÓN DE UN SENSOR FOTOELÉCTRICO</h2>
            </div><br>
            <p align="justify">Los <a href="https://tienda.logicbus.com.mx/Fotoelectricos_c_3014.html"> sensores fotoeléctricos</a> son dispositivos considerados como sensores de movimiento activos, los cuales, ellos trabajan al enviar destellos de ondas de sonidos ultrasónicas, después de las cuales el sensor espera a que la energía se refleje en su regreso.<br><br> A continuación se explicara 3 funciones que son útiles en el uso de un sensor fotoeléctrico:
            </p><br>

            <h3 class="med blue">a) Modelo Reflectivo</h3><br>

            <center><img src="https://www.logicbus.com.mx/imagenes/articulo/fotoelectricos02.gif" class="image_productos" width="40%" alt="Figura 2. Modelo Reflectivo" title="Figura 2. Modelo Reflectivo"></center>
            <p>
                <center><b>Figura 2. Modelo Reflectivo</b>
            </p>
            </center><br>

            <p align="justify">En esta primera función, tanto el emisor de luz como los elementos receptores, están contenidos en una sola carcasa. El sensor recibe la luz reflejada desde el objeto.</p><br>

            <h3 class="med blue">b) Modelo de Barrera</h3><br>

            <center><img src="https://www.logicbus.com.mx/imagenes/articulo/fotoelectricos03.gif" class="image_productos" width="50%" alt="Figura 3. Modelo de barrera" title="Figura 3. Modelo de barrera"></center>
            <p>
                <center><b>Figura 3. Modelo de barrera</b>
            </p>
            </center><br>

            <p align="justify">En la siguiente función, el transmisor y el receptor están separados. Cuando el objeto se encuentra entre el transmisor y el receptor, se interrumpe la luz y manda una alerta.</p>
            <br>

            <h3 class="med blue">c) Modelo Retroreflectivo</h3><br>

            <center><img src="https://www.logicbus.com.mx/imagenes/articulo/fotoelectricos04.gif" class="image_productos" width="50%" alt="Figura 4. Modelo Retroreflectivo" title="Figura 4. Modelo Retroreflectivo"></center>
            <p>
                <center><b>Figura 4. Modelo Retroreflectivo</b>
            </p>
            </center><br>

            <p align="justify">En esta última función, tanto el emisor de luz como los elementos receptores, están contenidas en un mismo recinto. La luz del elemento emisor incide en el reflector y regresa al elemento receptor de luz. Cuando hay un objeto presente, se interrumpe la luz.</p>

