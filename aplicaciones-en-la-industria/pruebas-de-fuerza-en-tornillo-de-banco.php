                <p class="light-black">Sujetar una pieza de metal para mecanizarla puede ser una tarea muy complicada para los operadores de máquinas CNC. La sujeción de la prensa debe lograr el equilibrio exacto entre aplicar la cantidad correcta de fuerza para evitar que la pieza se mueva durante el corte y mantener la presión de la fuerza de sujeción lo suficientemente baja para que la pieza de metal no se deforme.</p>
                <p class="light-black">El uso de un sensor de celda de carga para medir la fuerza de sujeción hace que el proceso sea más seguro, más fácil y más eficiente. Esta nota de aplicación ilustra cómo se han aplicado un sensor de celda de carga y un indicador digital para probar y medir la fuerza de sujeción de la mordaza de la prensa mientras el maquinista aprieta el tornillo de la prensa con una llave dinamométrica. Los datos de medición permiten al maquinista monitorear y controlar fácilmente la presión de la mordaza de la prensa. El mismo método se puede utilizar para medir la fuerza de sujeción de una prensa de banco.</p>
                <p class="light-black">Asimismo, los sensores de par rotatorio se pueden utilizar como herramienta de auditoría y calibración de llaves dinamométricas. Esta aplicación utiliza el sensor de par rotatorio TRD de FUTEK para verificar la precisión de una llave dinamométrica. FUTEK cuenta con un laboratorio de calibración acreditado por A2LA para respaldar aplicaciones críticas relacionadas con la herramienta de calibración de llaves dinamométricas.</p>

                <p class="text-center light-black font-weight-bold">¿Cómo funciona?</p>
                <ol class="light-black">
                    <li class="mb-3">En esta aplicación, la celda de carga LCA o un botón de carga LLB se monta en las mordazas de la prensa CNC. También se instala un sensor de par giratorio TRD en el tornillo de la prensa.</li>
                    <li class="mb-3">A medida que el maquinista aprieta el tornillo de la prensa, el sensor de torque giratorio TRD de FUTEK mide el torque que se aplica y la celda de carga entre las mordazas de la prensa mide la fuerza de sujeción.</li>
                    <li class="mb-3">Estas mediciones se envían directamente a un instrumento emparejado que proporciona voltaje de excitación y acondiciona la señal (filtración, amplificación, digitalización). Según la selección del acondicionador de señal, el operador puede ver los datos en una pantalla de carga digital o transmitirlos directamente a una PC o un PLC/DAQ para el registro de datos, el enclavamiento de seguridad del bucle de control o la activación de alarmas.</li>
                    <li class="mb-3">Si los datos de medición de fuerza muestran alguna anomalía, el operador puede ajustar la fuerza de sujeción utilizando la llave dinamométrica.</li>
