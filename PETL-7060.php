<p> 
PETL-7060 es un módulo de E / S Power-over-Ethernet (PoE) basado en IP con funciones de E / S digitales. Es compatible con Modbus TCP y se comunica a través de Ethernet. Poder comunicarse a través de Modbus TCP hace que sea fácil para PETL-7060 integrarse con el software HMI y SCADA, así como con otros PLC y E / S. Basado en el éxito de nuestro PET-7000serie, los módulos de E / S Ethernet de la serie PETL-7000 también tienen un servidor web incorporado y una HMI web, lo que permite una fácil configuración en un navegador web común. El PETL-7060 también admite E / S digital, como entrada digital de contacto húmedo (sumidero, fuente) y salida digital de relé de potencia. El módulo también es compatible con la conexión de par Digital Input to Digital Output a través de Ethernet. Después de la configuración, el PETL-7060 puede sondear el estado de los canales de entrada digitales locales y escribir continuamente en un dispositivo de salida digital remota a través de la red Modbus TCP.<br><br>

El PETL-7060 está equipado con doble watchdog: CPU watchdog y host watchdog. El regulador de CPU se reinicia automáticamente cuando el firmware incorporado falla. El controlador de host supervisa el controlador del host (PC o PLC) y la salida del módulo puede pasar al estado predefinido (valor seguro) cuando falla el host. Viene con dos conectores de bloque de terminales extraíbles para facilitar el cableado, y cuenta con una potente MCU ARM de 32 bits para manejar el tráfico de red eficiente. El módulo de E / S digital PETL-7060 PoE ofrece una verdadera conexión IEEE 802.3af (clasificación, Clase 1) a través de Ethernet (PoE) utilizando un cable Ethernet estándar de categoría 5 para recibir energía de un conmutador PoE como el NS-205PSE . Cuando no hay un conmutador PoE en el sitio, el PETL-7060 también puede tomar la entrada de potencia de los adaptadores de CC.</p><BR>


