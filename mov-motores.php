          <tr>
            <td colspan="3">
              <p>Los motores paso a paso son ideales para la construcción de mecanismos en donde se requieren
                movimientos muy precisos. La característica principal de estos motores es el hecho de poder moverlos un
                paso a la vez por cada pulso que se le aplique. Este paso puede variar desde 90° hasta pequeños
                movimientos de tan solo 1.8°, es decir, que se necesitarán 4 pasos en el primer caso (90°) y 200 para el
                segundo caso (1.8°), para completar un giro completo de 360°.</p>
              <p>Estos motores poseen la habilidad de poder quedar enclavados en una posición o bien totalmente libres.
                Si una o más de sus bobinas está energizada, el motor estará enclavado en la posición correspondiente y
                por el contrario quedará completamente libre si no circula corriente por ninguna de sus bobinas.</p>
