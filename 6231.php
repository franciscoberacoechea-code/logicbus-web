  <p>Ofrece 8 canales de E/S  digital. Las 8 líneas son accesibles mediante el conector DSUB hembra de 9 pines ubicado en el panel posterior de la unidad. Cada bit de E/S digital puede ser programado individualmente para ser entrada o salida.</p>
      <br>
