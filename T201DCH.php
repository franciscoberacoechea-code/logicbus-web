          <p align="justify">La serie T201 incluye transductores de corriente CA / CC diseñados para convertir el valor de corriente medido (hasta 300 A) en una señal normalizada industrial de 4.20 mA o 0.10 V. La mayoría de la serie T201 está certificada por UL y se caracteriza por un bajo consumo de energía, un rango de medición que se puede ajustar libremente a través de interruptores DIP y una clase de alta precisión que evita la deriva térmica. La serie T201 está disponible en 12 modelos con diferentes principios de medición: rectificado promedio, balance magnético (tecnología patentada), Efecto Hall o TRMS con rango de entrada bipolar. Tres modelos incluyen un puerto RS485 que admite el protocolo Modbus RTU.<br><br>
            T201DCH300-LP es un transductor de corriente CA / CC aislado, sin contacto, con un tamaño muy compacto (dimensiones generales inferiores a 96,5 x 68 x 26 mm). La función y el aspecto del dispositivo son muy similares a los de un CT estándar activo, pero con la característica notable de medir el componente de CC de CC y CA de la corriente. Por su resistencia eléctrica, facilidad de uso y dimensiones compactas, el transductor T201DCH300-LP se adapta a cualquier tipo de medición de corriente de hasta 300 Adc / Aac y varias aplicaciones (baterías, cargadores de baterías, paneles solares, unidades de energía, cargas de CC y CA, etc.)<br><br>
            T201DCH es un transductor aislado, sin contacto de corriente directa y alterna TRMS. La Función del dispositivo y la apariencia son muy similares a los de un CT estándar, pero con la característica adicional y notable de la medición del paso de la corriente continua. Por su resistencia eléctrica, la facilidad de uso y dimensiones compactas, el T201DCH se adapta a cualquier tipo de medición de corriente de hasta 50 Adc o 50 Aac.</p><br>

