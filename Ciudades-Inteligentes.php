<p align="justify">Otro aspecto a considerar es el tránsito, al momento de iniciar nuestro viaje utilizando los vehículos inteligentes sabiendo de antemano que utilizaremos un estacionamiento inteligente, el trayecto mejora pero aun seguiríamos retrasándonos derivado del tránsito<br>
Dado lo anterior, existen iniciativas e investigaciones que apuntan a una mejor alternativa del control del tráfico, esto abre paso a los semáforos inteligentes, este funciona dependiendo de la densidad de vehículos, tomando como los datos de entrada mediante cámaras web, y mediante alguna técnica de programación se determina la mejor opción para la duración del tiempo que tiene que esperar cada vehículo para pasar.</p>

