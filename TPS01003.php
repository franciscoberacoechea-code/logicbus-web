<p>El modelo LCB200 es una celda de carga de extremo de barra (tensión/compresión) diseñada para aplicaciones que involucran actuadores en línea o gatos hidráulicos con roscas macho/hembra. El modelo estándar de Celda de carga de extremo de barra LCB200 (Tensión/Compresión) tiene roscas macho/hembra, construidas con un robusto acero inoxidable 17-4PH y pesa aproximadamente 3.5 oz. Este modelo es muy adecuado para los requisitos de capacidad de rango medio (1,000 lb - 3,000 lb) que ofrecen alta resistencia y excelente precisión. Para cualquier aplicación que requiera un mayor rango de capacidad, consulte <b>LCB400, LCB450 y LCB500</b>
<br><br>
<p>Esta celda de carga de extremo de barra (tensión/compresión) tiene una alta precisión y una gran rigidez. Tiene una no linealidad de ± 0.5%, resistencia de puente de 1000 ohmios y deflexión de 0.001” nominal. La Celda de carga de extremo de barra LCB200 estándar (Tensión/Compresión) se puede modificar o personalizar para satisfacer sus requisitos y utiliza tecnología de galga extensométrica de lámina metálica.</p>

<strong>Características:</strong><br>
<ul>
<li>Peso ligero</li>
<li>Opción de salida emparejada externa disponible</li>
<li>Clasificación de fatiga disponible</li>
<li>Opción de cable de teflón</li>
<li>Roscas hembra/macho</li>
<li>Baja deflexión</li>
<li>Construcción de acero inoxidable 17-4</li>
<li>Tanto en tensión como en compresión</li>
<li>Aplicaciones de capacidad de rango medio</li>
<li>Utiliza tecnología de medidor de deformación de lámina metálica</li>
</ul>

