              <div align="justify">
                <p>El ET-7018Z/S es un módulo Ethernet de E/S que integra un servidor web mediante el cual se puede
                  configurar, monitorear y controlar las entradas y salidas a través de cualquier navegador web. Con la
                  función HMI web los usuarios pueden crear paginas dinámicas y atractivas para el monitoreo y control
                  de sus E/S sin necesidad de poseer conocimientos en programación o HTML. El ET-7018Z/S ofrece un fácil
                  y
                  seguro acceso a los usuarios desde cualquier lugar en cualquier momento, también soporta el protocolo
                  Modbus/TCP que permite una fácil integración con software SCADA.</p>

                <p>El ET-7018Z/S es un modulo de 16 bits, con 10 canales de entradas análogas diferenciales y 6 canales
                  de
                  salidas digitales que proporciona rangos de entradas programables en todos los canales análogos (±15
                  mV, ±50 mV, ±100 mV, ±500 mV, ±1 V, ±2.5 V, ±20 mA, 0 ~ 20 mA, 4 ~ 20 mA y termopares) y las salidas
                  análogas se pueden configurar con alarmas. Cada canal análogo permite ser configurado con rangos
                  individuales y tienen protección de sobre voltaje de 240 VAC.</p>

                <p>Características:</p>
                <ul>
                  <li>Servidor web integrado</li>
                  <li>Función HMI web</li>
                  <li>Seguridad de comunicación</li>
                  <li>Protocolo Modbus/TCP</li>
                  <li>Aislamiento de dos vías</li>
                  <li>Doble watchdog integrado</li>
                  <li>Ethernet 10/100 Base-TX</li>
                  <li>Tipo de entrada análoga: 10 diferenciales (mV, V, mA, Termopar)</li>
                  <li>Tipo de salida digital: Colector abierto</li>
                  <li>Protección de sobre voltaje hasta 240 Vrms</li>
                </ul>
