          <p>I-7017C es una solución rentable para una amplia gama de valiosas señales y sistemas de control industrial. La utilidad DCON puede ayudar a los usuarios a configurar y probar los módulos de entrada analógica I-7017C. Se proporcionan muchas funciones de biblioteca y programas de demostración para permitir a los usuarios desarrollar programas fácilmente en sistemas operativos Windows, Linux y DOS. Los usuarios pueden montar los módulos en un riel DIN, panel o pared. Los módulos tienen un bloque de terminal de tornillo para conectarse a las señales. I-7017C viene con el software EZ Data Logger GRATIS.</p><br>

          <strong>Características:</strong>
          <ul>
            <li>Solo entrada actual.</li>
            <li>Resistencia incorporada para simplificar la medición actual.</li>
            <li>Detección de cable abierto para entrada de 4 ~ 20 mA.</li>
            <li>Aislamiento intramódulo de 3000 VDC.</li>
            <li>Protección contra ESD de 4 kV.</li>
            <li>Conformidad con la RoHS.</li>
            <li>Amplia gama de temperaturas de funcionamiento: -25 ~ + 75 ° C.</li>
          </ul><br>



