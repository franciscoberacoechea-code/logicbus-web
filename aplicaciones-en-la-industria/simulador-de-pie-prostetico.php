                <ol class="light-black">
                    <li class="mb-3"><b>Montaje y Función del LCM200:</b>
                        <ul>
                            <li>Un extremo de la <b>LCM200</b> está conectado al <b>cable de control</b> que se acopla al <b>actuador del cable servomotor</b>, funcionando como un sensor de análisis de marcha.</li>
                            <li>El <b>extremo opuesto</b> de la <b>LCM200</b>se monta en el <b>talón de la prótesis</b>.</li>
                        </ul>
                    </li>
                    <li class="mb-3"><b>Simulación de la Marcha y Medición de Fuerza:</b>
                        <ul>
                            <li>A medida que el individuo camina, el <b>cable</b> tira del <b>talón de la prótesis</b>, imitando el torque generado al caminar por el <b>tendón de Aquiles</b>.</li>
                            <li>La <b>fuerza</b> utilizada para activar el <b>talón</b> es medida por la <b>LCM200</b>, proporcionando datos precisos sobre las fuerzas involucradas en la marcha.</li>
                        </ul>
                    </li>
                    <li class="mb-3"><b>Visualización de los Resultados:</b>
                        <ul>
                            <li>La <b>fuerza medida</b> por la <b>LCM200</b>se muestra mediante el <b>IPM650 Digital Panel Meter</b>, el <b>IHH500 Handheld Display</b>, o en una <b>PC</b> utilizando el <b>USB220 High Resolution Output Module</b> y el software <b>SENSIT™</b> de FUTEK.</li>
                        </ul>
                    </li>
                    <li class="mb-3"><b>Cierre del Circuito de Control:</b>
                        <ul>
                            <li>Los instrumentos conectados a la <b>PC</b> a través del puerto <b>USB 2.0</b> controlan el <b>motor servomotor</b>, cerrando el circuito de control y permitiendo que el sistema se adapte activamente a la marcha del individuo en tiempo real.</li>
                        </ul>
                    </li>
                    <li class="mb-3"><b>Monitoreo y Ajuste con SENSIT™:</b>
                        <ul>
                            <li>Con el uso del <b>IDA100</b>, la salida amplificada del <b>amplificador</b> puede ser simultáneamente <b>monitoreada y ajustada</b> en un <b>PC con el software SENSIT™</b> de FUTEK, proporcionando salida analógica de alta velocidad para <b>PLC y Controladores de Movimiento</b>.</li>
                        </ul>
                    </li>
                </ol>
                <p class="text-center light-black font-weight-bold">Beneficios de la Celda de Carga LCM200 en Prótesis Robóticas</p>
