<center><strong>Módulo Ethernet de adquisición de datos con 6 salidas de relevador 1A @ 60 Vdc/Vac (PhotoMOS form A), 6 entradas digitales aisladas, comunicación Ethernet 10/100 Base Tx y Modbus TCP.</strong></center><br>

<div align="right">
<a href="https://tienda.logicbus.com.mx/ET-7065_p_1570.html" title="Ir a Tienda" target="_blank"><img src="images/shopping_cart.png" border=0 alt="Comprar"></a>
</div> <br>

<p>El ET-7065, es un módulo que permite controlar entradas y salidas digitales mediante Ethernet, este módulo incluye un servidor web integrado, el cual permite configurar el dispositivo, monitorear y controlar las entradas y salidas desde un simple navegador web. El control y supervisión remotos son tan sencillos como navegar en Internet. <BR>

Con la función web HMI, no es necesario programar ni tener habilidades en HTML; la creación de páginas web dinámicas y atractivas para el control y monitoreo de entradas/salidas será divertido para los ingenieros. El ET-7065 ofrece a los usuarios un acceso fácil y seguro desde cualquier lugar y a cualquier hora.<BR> 

Además, el ET-7065 soporta también el protocolo Modbus/TCP, lo cual hace una perfecta integración entre este dispositivo y software SCADA. <BR>

El ET-7065 provee 6 Relevadores Photo-MOS de salida (tipo A) y 6 entradas digitales de contacto húmedo (tipo sink, source). Cada Relevador soporta un contacto de 1A@60Vac o 1A@60Vdc, y cada canal de entrada digital soporta una entrada de contador (32 bits and 500Hz max.).
</p><BR>

