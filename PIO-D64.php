<center><strong>Tarjeta PCI, 32 canales de entrada digital y 32 canales de salida digital, un contador de de 16 bit y otro de 32 bit ambos a 4MHz.</strong></center><br>


<p>La tarjeta PIO-D64U es el producto de nueva generación que ICP DAS proporciona para cumplir con los requisitos de cumplimiento de RoHS. La nueva tarjeta PIO-D64U está diseñada como un reemplazo directo para el PIO-D64, y los usuarios pueden reemplazar el PIO-D64 por el PIO-D64U directamente sin modificación de software / controlador.<br>

La tarjeta PCI universal PIO-D64U admite bus PCI de 3,3 V / 5 V, mientras que la PIO-D64 admite bus PCI de 5 V. Estas tarjetas proporcionan una entrada digital de 32 canales y una salida digital de 32 canales que constan de dos puertos de entrada de 16 bits y dos puertos de salida de 16 bits. El PIO-D64U y el PIO-D64 también ofrecen contador / temporizador de 6 canales con fuentes de cuatro tiempos, 2 MHz, 1 MHz, 500 kHz y 250 kHz. El usuario puede usar la fuente de reloj de la plataforma de soldadura. 3 del temporizador / contador de 6 canales son para fines generales tales como la medición de frecuencia, el conteo de eventos y la generación de impulsos; los otros 3 canales son para la función de interrupción.<br>

El PIO-D64U también agrega un interruptor de identificación de tarjeta y resistencias de extracción / extracción para DI a bordo. Los usuarios pueden configurar la identificación de la tarjeta y reconocer la placa mediante la identificación a través del software cuando usan dos o más tarjetas PIO-D64U en una computadora. Los resistencias pull-high / pull-low permiten especificar el estado DI cuando los canales DI están desconectados; el estado de DI puede permanecer en estado alto o bajo que no sea flotante.<br>

El PIO-D64 / D64U es compatible con varios sistemas operativos, como Linux, DOS, Windows 98 / NT / 2000 y Windows 32 bits de Windows XP / 2003 / Vista / 7. También proporciona el control DLL y Active X, y varios programas de muestra de lenguaje en Turbo C ++, Borland C ++, Microsoft C ++, Visual C ++, Borland Delphi, Borland C ++ Builder, Visual Basic, C # .NET, Visual Basic.NET y LabVIEW para ayudar usuarios para desarrollar rápida y fácilmente sus aplicaciones.
</p><BR><br>

<strong>Caracteristicas</strong>

<ul>
<li>Admite el bus PCI de +5 V para PIO-D64</li>
<li>Admite el bus PCI + 3.3 / + 5 V para PIO-D64U</li>
<li>Doble cara SMT, tarjeta corta</li>
<li>Proporciona cuatro conectores de cable plano de 20 pines a la placa base DB-16P, DB-16R</li>
<li>Entrada digital de 32 canales y líneas de salida digital de 32 canales</li>
<li>Función de ID de tarjeta para PIO-D64U</li>
<li>Resistencias pull-up o pull-down en líneas de E / S para PIO-D64U</li>
<li>Un contador de 16 bits y un contador de 32 bits con base de tiempo de 4 MHz</li>
<li>3 contadores programables independientes de 16 bits</li>
<li>Manejo de interrupción programable</li>
<li>Cinco encabezados de 20 pines</li>
<li>Interruptor de interrupción por: Disparador par / temporizador</li>
<li>El tiempo de respuesta DIO es de aproximadamente 0,77 µs (1,3 MHz máx.)</li>
</ul><br>

