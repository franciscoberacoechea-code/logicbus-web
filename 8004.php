<p align="justify">La interfaz de E/S digital PCI 8004 proporciona 16 entradas ópticamente aisladas y 16 salidas de relé Reed. Las entradas protegen la PC y otros equipos sensibles contra picos y corriente de bucle a tierra que se pueden generar en entornos industriales, mientras que las salidas proporcionan cierres de interruptor de contacto seco de alta calidad, larga vida, baja corriente (10 vatios máximo). Los relés de láminas son adecuados para aplicaciones de baja corriente. Los relés están normalmente abiertos y cerrados cuando están energizados.
<br><br>
Las entradas en el 8004 están clasificadas para 3-13V. Para entradas de 10-30 V, solicite el 8004H.
<br><br>
Los controladores y las utilidades del software SeaIO Classic facilitan la instalación y operación con los sistemas operativos Microsoft Windows.
<br><br>
Comience a desarrollar su E/S digital con el Manual de E/S digital que le proporcionará información útil que utilizará una y otra vez. Consulte el Capítulo 1 para obtener una descripción general de los principios lógicos.</p>

<strong>Características:</strong>
<ul>
<li>Cumple con las directivas RoHS y WEEE</li>
<li>16 salidas de relé Reed (SPST)</li>
<li>16 entradas ópticamente aisladas</li>
<li>Relés de láminas DIP de 10VA altamente confiables</li>
<li>La resistencia de inmersión enchufable permite un rango de entrada configurable por el usuario de hasta +24 V</li>
<li>Alimentación (+ 5V y + 12V) y conexión a tierra en el conector</li>
<li>Compatible con bus universal (3.3V y 5V)</li>
<li>Incluye cable de 72 ? con conector DB78 Macho a DB37 Macho y DB37 Hembra (Artículo #CA165)</li>
<li>El software SeaIO Classic es compatible con los sistemas operativos Microsoft Windows</li>
<li>Soporte de software para Linux disponible</li>
</ul>

