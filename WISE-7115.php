<center><strong>Módulo de 7 canales de entrada para RTD de 3 hilos, servidor web integrado para lógica de control IF-THEN-ELSE, alimentación y comunicación a través de Ethernet y Modbus TCP.</strong></center><br>
 <br>

<p> 
WISE-7115 es un dispositivo Web Inside Smart Engine (WISE) desarrollado por ICP DAS. Apto para su uso como unidades de control para control y monitoreo lógico remoto, WISE-7115 proporciona una interfaz web intuitiva y fácil de usar que permite a los usuarios implementar la lógica de control IF-THEN-ELSE en controladores con programación limitada o sin programación por parte del usuario. Con sus características potentes y fáciles de usar, minimizará la curva de aprendizaje, acortará el tiempo de comercialización y reducirá drásticamente el esfuerzo y el gasto en el desarrollo del sistema.<BR><BR>

El dispositivo WISE-7115 se adhiere a la especificación IEEE 802.3af (clasificación, clase 1) de alimentación sobre Ethernet (PoE). Con la capacidad de recibir energía de redes habilitadas con PoE a través de pares de Ethernet (cable Ethernet Categoría 5), ​​brinda mayor flexibilidad, mayor eficiencia y diseño de sistemas simplificado que ahorra espacio, reduce el uso de cables y elimina la necesidad de enchufes eléctricos adicionales. Para entornos que no sean PoE, el dispositivo WISE-7115 aún se puede alimentar a través de otras fuentes de alimentación, como adaptadores de CA y baterías.<BR><BR>

El módulo WISE-7115 admite el protocolo Modbus / TCP para una integración perfecta con el software SCADA. Cuenta con una entrada RTD de 7 canales de 16 bits y 3 cables. Cada canal (apoyado por la eliminación de la resistencia del conductor RTD de 3 hilos) se puede configurar individualmente para varios rangos de temperatura.</p><BR>

<strong>Caracteristicas:</strong>
<ul>
<li>Servidor web incorporado para la configuración de reglas IF-THEN-ELSE</li>
<li>Motor de reglas IF-THEN-ELSE incorporado para operación lógica</li>
<li>No más programación. ¡Simplemente haz clic y termina!</li>
<li>Soporte IO, contador, temporizador, operaciones de correo electrónico</li>
<li>Protocolo Modbus / TCP para la integración sin fisuras del software SCADA</li>
<li>Energía sobre Ethernet (PoE) compatible con IEEE 802.3af</li>
<li>10/100 Base-TX Ethernet</li>
<li>Tipo AI: 7 RTD (Pt100, Pt1000, Ni120, Cu100, Cu1000)</li>
<li>Configuración individual del canal</li>
<li>Entrada RTD de 3 hilos con eliminación de resistencia del cable</li>
<li>Aislamiento bidireccional / Protección ESD</li>
</ul>


