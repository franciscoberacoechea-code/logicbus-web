                <p class="light-black">En el caso de aplicaciones industriales o de construcción que requieren capacidades de trabajo bajas o medias, las celdas de carga de tensión se utilizan para medir cargas de tracción o de “tracción”, lo que las hace ideales para aplicaciones de grúas, control de peso de polipastos y aparejos. Estos sistemas de control de carga de grúas también se conocen como indicación de control de carga (LMI), enlaces de tensión o grilletes de carga.</p>
                <p class="light-black">Las celdas de carga se instalan comúnmente en un bloque de carga y en un gancho de elevación para garantizar que la grúa no se sobrecargue. El operador puede monitorear en línea mientras se aplica la carga al polipasto hasta que la carga esté completamente suspendida. En cualquier momento a medida que aumenta la carga, el operador puede invertir la operación de elevación en caso de sobrecarga. Se puede usar un indicador de carga instalado en la cabina del operador para detener la operación de elevación, activar una luz intermitente o activar una alarma audible.</p>
                <p class="light-black">La serie de celdas de carga FUTEK LCF es adecuada para una capacidad de hasta 100 000 lb y puede soportar una sobrecarga segura de hasta el 150 % con protección IP hasta IP65, lo que la hace adecuada para aplicaciones industriales pesadas.</p>
                <p class="light-black">Todas las piezas de la grúa hidráulica deben funcionar juntas para lograr la máxima seguridad. Además de medir la carga, los ingenieros también pueden medir la presión del pistón de elevación hidráulico y de los pistones de los estabilizadores. La presión del pistón de elevación permite controlar la sobrecarga y el peso. Indica el momento de fuerza aplicado sobre la pluma y la amplitud del gancho a medida que se eleva la carga.</p>
                <p class="light-black">Para garantizar la estabilidad del camión, se utilizan estabilizadores que actúan como contrapesos que evitan que la grúa se incline demasiado hacia un lado o hacia el otro. Como se muestra en la ilustración, estos estabilizadores utilizan transmisores de presión para garantizar que la presión adecuada se distribuya de manera uniforme a cada lado.</p>
