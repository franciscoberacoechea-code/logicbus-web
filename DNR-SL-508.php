      <td colspan="2"><div align="justify">The DNA/DNR-SL-508 are 8-port serial communications interfaces for Cube/RACKtangle&reg; I/O chassis respectively. The boards offer fully isolated software-configurable RS-232 or RS-485 interfaces. The board is an ideal interface to serial based data acquisition and control interfaces as well as general purpose serial I/O.<br>
          <br>
          The DNA/DNR-SL-508 support standard serial transfer rates up to 1 Mbaud in RS-485 mode or up to 256 kbaud in RS-232 mode. It also supports communications at 12, 12.5 and 50 kbaud with better than 0.1% data rate accuracy. Based upon an industry standard 16550 UART on each port, the board supports both half- and full-duplex modes for RS-422/485 operation.<br>
          <br>
          The DNA/DNR-SL-508 are compatible with RS-422 point to point or network applications when used in RS-485 mode and provide 200&#8486; software-selectable TX and/or RX termination for RS-485 communications. Additionally, the DNA-SL-508 provides 1k&#8486; software-selectable fail-safe RX termination for RS-485 mode.<br>
          <br>
          In RS-232 mode, the layer provides TX and RX as well as the standard RTS and CTS hardware hand shaking signals required by many external serial devices. The DNA/DNR-SL-508 is supported by the UEIDAQ Framework providing a simple and complete software interface to all popular programming languages, operating systems and data acquisition and control applications (e.g. LabVIEW, DASYLab, MATLAB).<br>
          <br>
      The DNR-SL-508 includes the UEI-RSS Remote Serial Server application, Windows&nbsp;and Linux&nbsp;versions. This server allows a Windows or Linux host PC to configure the DNR-SL-508 ports as standard serial ports within the host OS (e.g. as COM1: to COM255: ports in Window or standard POSIX functions in Linux). The UEI-RSS supports up to 255 unique serial ports per Ethernet port on the host.</div></td>
