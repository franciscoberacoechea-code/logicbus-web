<li>Watchdog Dual Integrado</li>
<li>Aislamiento de dos vías / protección ESD</li>
<li>Tipo de Salida Digital: 8 Relevadores de potencia (Tipo A)</li>
<li>Ethernet 10/100 Base-TX</li>
<li>Conexión par de E/S</li>
</ul>
