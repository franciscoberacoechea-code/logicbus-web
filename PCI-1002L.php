<center><strong>Tarjeta PCI Bus de 32 canales de entrada analógicos, 12 bits de resolución, 16 canales de entrada digitales y 16 canales de salida digitales, frecuencia de muestreo de 110kS/s, Ganancia baja (sin FIFO).</strong></center><br>


<p>La serie PCI-1002 es una familia de placas A / D para PC con un bus PCI. Cuenta con adquisición de datos de 110 KHz en DOS y Windows. El PCI-1202H / 1202L proporciona 32 entradas diferenciales de terminación única o 16, 16 canales de entrada digital y de salida digital. El -H significa el modelo de alta ganancia y el -L significa el modelo de baja ganancia. La serie PCI-1202 proporciona tres modos de disparo externos flexibles: disparo previo, gatillo posterior y gatillo externo. 
</p><BR><br>

<strong>Caracteristicas</strong>

<ul>
<li>Bus PCI</li>
<li>Convertidor A / D de 110 bits de 12 bits</li>
<li>PCI-1002H / -1002L, 32 entradas diferenciales single-ended / 16</li>
<li>Las tasas de muestreo de un solo canal o múltiple</li>
<li>Los canales son 110 K muestras / s</li>
<li>Tres disparadores externos diferentes: disparador posterior, disparador previo, medio</li>
<li>16 canales de entrada digital / 16 canales de salida digital</li>
<li>1002L: baja ganancia programable: 1, 2, 4, 8.</li>
<li>1002H: alta ganancia programable: 1, 10, 100, 1000.</li>
<li>Disparador interno / externo.</li>
<li>Tablero de tamaño medio</li>
</ul>
