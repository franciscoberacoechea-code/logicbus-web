        <p>El DN-DO-16DR-B es una tarjeta de terminación con salida de relé (Forma C, SPDT). El DN-DO-16DR-B se utiliza
          para el canal de salida digital 0 ~ 15. La tarjeta ofrece 2 salidas para cada canal para extender la lógica de
          control debido al relé de la Forma C, puede ser una salida lógica positiva (N.O.) o negativa (N.C.) o ambas.
          Además, cada canal está integrado en dos varistores en N.O. y N.C. canal para proteger contra transitorios de
          alta tensión y sobretensiones al bucle de control.<br><br>
          NOTA: El DN-DO-16DR-B no puede funcionar de manera independiente. Se debe conectar a <a
            href="DN-DO-16DR-A">DN-DO-16DR-A</a>, cuando se usa el canal 15 ~ 31.</p>
