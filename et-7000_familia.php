        <h1>Familia Compacta Distribuida (ET-7000)</h1>

        <div align="center">
          <a href="javascript:openWin('imagenes/02/intro_et7k_12.jpg',0,0)"><img src="imagenes/02/intro_et7k_12.jpg"
              alt="ET-7000: Familia Compacta Distribuida" width="70%"></a>
        </div>
        <br><br>

        <p>La serie ET-7000 es una familia de m&oacute;dulos de control y adquisici&oacute;n de datos Internet/Ethernet
          que soportan el protocolo Modbus/TCP y es tambi&eacute;n un módulo Ethernet de E/S remotas con un servidor web
          integrado utilizado para la configuraci&oacute;n, monitoreo de datos de E/S y control utilizando un navegador
          web.</p>

        <div align="center">
          <img src="imagenes/02/Esquema_datalogger.jpg" alt="serie ET-7000">
        </div>

        <div>
          <p>
            <strong>Características:</strong>
          <ul>
            <li><strong>Power over Ethernet (PoE):</strong>
              <p>El m&oacute;dulo PET-7000 de la serie puede ser alimentado por un switch PoE IEEE 802.3af compatible.
                Tanto los datos y la alimentaci&oacute;n se pueden transmitir mediante un cable Ethernet, eliminando la
                necesidad de cableado adicional y fuente de alimentaci&oacute;n.</p>
            </li>
            <li><strong>Integraci&oacute;n de servidor Web:</strong>
              <p>Cada m&oacute;dulo ET-7000/PET-7000 ha incorporado un servidor web que permite a los usuarios
                configurar, monitorear y controlar el m&oacute;dulo desde una ubicaci&oacute;n remota mediante un
                navegador web normal.</p>
            </li>
            <li><strong>Web HMI</strong>
              <p>La funci&oacute;n Web HMI permite a los usuarios crear p&aacute;ginas web din&aacute;micas y atractivas
                para monitorear y controlar las E/S. Los usuarios pueden cargar im&aacute;genes de dise&ntilde;o de E/S
                (bmp, jpg, gif formato) y definir una descripci&oacute;n de cada E/S. No son necesarias habilidades HTML
                o Java para crear las p&aacute;ginas web.</p>
            </li>
            <li><strong>Seguridad de Comunicaci&oacute;n:</strong>
              <p>Cuenta y contrase&ntilde;a son necesarias al iniciar sesi&oacute;n en el servidor web ET-7000. El
                filtrado de direcciones IP tambi&eacute;n est&aacute; incluido, &eacute;ste puede utilizarse para
                permitir o denegar conexiones con direcciones IP espec&iacute;ficas.</p>
            </li>
            <li>Protocolos Modbus/TCP y Modbus/UDP
              <p>Los protocolos Modbus/TCP y Modbus/UDP cuentan con la funci&oacute;n de esclavo en el puerto Ethernet,
                puede utilizarse para proporcionar datos a distancia el software SCADA.</p>
            </li>
            <li><strong>Construido a partir de las E / S :</strong>
              <p>Yo Varios componentes de la periferia se mezclan con m&uacute;ltiples canales en un solo m&oacute;dulo,
                que proporciona el que m&aacute;s rentable / S de uso y mejora el rendimiento de las operaciones de I /
                O.</p>
            </li>
            <li><strong>Doble del perro guardi&aacute;n:</strong>
              <p>El perro guardi&aacute;n es doble consiste en un m&oacute;dulo y un perro guardi&aacute;n del perro
                guardi&aacute;n de Comunicaci&oacute;n. La acci&oacute;n de la AO, NO se asocia tambi&eacute;n a la del
                perro guardi&aacute;n doble.</p>
            </li>
            <li><strong>M&oacute;dulo Watchdog:</strong>
              <p>Es un circuito integrado de hardware para supervisar el funcionamiento del m&oacute;dulo y se
                restablecer&aacute; la CPU en caso de fallo se produce en el hardware o el software. Entonces, el
                encendido del valor de la AO, NO se cargar&aacute;.</p>
            </li>
            <li><strong>Comunicaci&oacute;n de Vigilancia:</strong>
              <p>Es una funci&oacute;n de software para supervisar la comunicaci&oacute;n entre el host y el
                m&oacute;dulo ET-7000/PET-7000. El tiempo de espera de la comunicaci&oacute;n es el perro
                guardi&aacute;n programable, cuando el ET-7000/PET-7000 no recibir comandos desde el host por un tiempo,
                el organismo de control las fuerzas de la AO, NO a la pre-programados fuerte valor para evitar
                da&ntilde;os impredecibles de la relacionada dispositivos.</p>
            </li>
            <li><strong>Encendido de valor y valor seguro:</strong>
              <p>Adem&aacute;s de establecer por la AO conjunto, NO comandos, la AO, NO se puede establecer en virtud de
                otras dos condiciones.</p>
            </li>
            <li><strong>Encendido del valor:</strong>
              <p>El valor de encendido se carga en la AO, hacer bajo 3 condiciones: encendido, reinicio en el
                M&oacute;dulo de Vigilancia, reajustado por orden de reposici&oacute;n.<br>
                Valor seguro: Cuando el perro guardi&aacute;n de comunicaci&oacute;n est&aacute; habilitada y un tiempo
                de espera de comunicaci&oacute;n del perro guardi&aacute;n se produce, el "valor seguro" se carga en la
                AO, DO.</p>
            </li>
            <li><strong> I / O de conexi&oacute;n Par:</strong>
              <p>Esta funci&oacute;n se utiliza para crear un IA / DI de AO / DO par a trav&eacute;s de la Ethernet. Una
                vez completada la configuraci&oacute;n, el m&oacute;dulo ET-7000/PET-7000 puede sondear el estado de la
                distancia AI / DI dispositivos y utilice el protocolo Modbus / TCP para escribir continuamente a un
                local de AO / DO canales en el fondo.</p>
            </li>
            <li><strong>Confiable bajo ambiente &aacute;spero altamente:</strong>
              <ul>
                <p>
                  <li>Temperatura de funcionamiento: -25 ~ +75 &deg; C</li>
                  <li>Temperatura de almacenamiento: -30 ~ +80 &deg; C</li>
                  <li>Humedad 10 ~ 90% RH (sin condensaci&oacute;n)</li>
                </p>
              </ul>
            </li>
          </ul>
          </p>
        </div>
