<p>Permite una conexión robusta a Internet para máquinas expendedoras, tickets o seguimiento de activos. Su diseño modular es compatible con una amplia gama de protocolos que abordan el rápido desarrollo de Internet de las cosas (IoT).<br>
El enrutador de grado industrial proporciona tecnologías clave para acceder a cualquier tipo de aplicaciones en Internet, pero también a sitios de Intranet y estaciones remotas que se pueden conectar a través de su potente suite de protocolos VPN, incluyendo OpenVPN e IPsec.<br>
El módem integrado es compatible con redes MIMO LTE y garantiza la conectividad WWAN con hasta 100 Mbps. El WiFi IEEE 802.11abgn, Bluetooth 4.2, incluido Bluetooth Low Energy (BLE) o USB, abre otras posibilidades para integrar sensores y actuadores fácilmente en la red.<br>
Un concepto de protección de hardware brinda flexibilidad adicional para convertir el NB800 en un dispositivo a medida (OEM) específico de la aplicación o para seguir los cambios tecnológicos. Por ahora, los escudos con doble CAN o E / S digitales y las interfaces seriales están disponibles.<br>
La resistente carcasa de aluminio adecuada para montaje en pared en combinación con el rango de temperatura soportado de -40 ° C a 70 ° C representa su robustez. NB800 resiste tensiones mecánicas y térmicas.<br><br>
El software del enrutador se basa en componentes bien probados que incluyen un sistema operativo Linux integrado y una amplia gama de protocolos de enrutamiento y comunicación como VLAN, Mobile IP, OSPF, BPG y RSTP. Es posible ejecutar aplicaciones de cliente en un contenedor LXC. Un SDK ofrece a los programadores una gran herramienta para implementar todo tipo de aplicaciones con scripts simples. El preprocesamiento de datos se puede hacer directamente en el enrutador, ahorrando así un IPC adicional.
Otras características incluyen un Administrador de enlaces inteligente para conexiones celulares optimizadas, Calidad de servicio (QoS) para un intercambio de datos eficiente, Correo electrónico y SMS para alarmas y notificaciones, un servidor web y autenticación RADIUS y SSID ocultos para WLAN.
