<center><strong>PROFINET a Modbus RTU / ASCII Gateway.</strong></center><br>

<p>El GW-7662 especialmente diseñado para el dispositivo PROFINET IO. Permite que el controlador PROFINET acceda a los dispositivos Modbus. Estos dispositivos Modbus pueden ser un PLC, un sensor, módulos de la serie ICPDAS M-7000, etc. También ofrecemos un software de utilidad para que los usuarios configuren GW-7662. Al usar este módulo, los usuarios pueden poner sus dispositivos Modbus en la red PROFINET fácilmente.</p>

<strong>Características:</strong>
<ul>
<li>Protocolo: dispositivo PROFINET E/S.</li>
<li>Clase de conformidad PROFINET B y clase de RT 1.</li>
<li>Tiempo cíclico: 1 ms (min).</li>
<li>Archivo genérico GSDML proporcionado (Versión 2.25).</li>
<li>La longitud máxima de los datos de entrada / salida es 512/512 Bytes.</li>
<li>Soporta Modbus Master y modo esclavo.</li>
<li>Soporta Modbus RTU y formato ASCII.</li>
<li>Soporta varios tipos de velocidad en baudios para COM1 de 1.2 a 460.8 kbps.</li>
<li>Proporcionar indicadores LED.</li>
<li>4 kV Protección de contacto ESD para cualquier terminal.</li>
<li>Amplio rango de entrada de potencia (+10 a +30 VDC) y temperatura de funcionamiento (-25 a 75 ° C).</li>
</ul>

<strong>Aplicaciones:</strong>
<ul>
<li>Automatización industrial.</li>
<li>Automatización industrial.</li>
<li>Automatización de procesos.</li>
</ul> 
   


