<center><strong>Tarjeta PCI Bus de 32 canales de entrada analógicos, 12 bits de resolución, 2 canales convertidores Digital/Analógico a 110kHz, frecuencia de muestreo a 110kS/s, Ganancia baja (1k word FIFO).</strong></center><br>


<p>La serie PCI-1202 es una familia de tarjetas de adquisición de datos de alto rendimiento para el bus PCI. Presenta una adquisición de datos continua, sin interrupciones, de 110KHz para baja ganancia (40KHz para ganancia alta) bajo DOS y Windows. La familia PCI-1202 tiene la misma arquitectura de hardware que PCI-1802. El PCI-1202 proporciona entradas análogas diferenciales de un canal o de 16 canales de 32 canales. Al igual que la familia PCI-1802, la serie PCI-1202 presenta una función de "Escaneo mágico", función M, función X y función de captura continua.
</p><BR><br>

<strong>Caracteristicas</strong>

<ul>
<li>Bus PCI (v2.1), 33 MHz 5 V 32 bits.</li>
<li>Convertidor A / D de 110 bits de 12 bits</li>
<li>32 entradas diferenciales single-ended / 16</li>
<li>Memoria intermedia 1K palabra FIFO</li>
<li>Frecuencias de muestreo de canal único o canales múltiples:</li>
<ul>
  <li>110K muestras / s para modelo de baja ganancia</li>
  <li>40K muestras / s para el modelo de alta ganancia.</li>
</ul>
<li>Tres factores desencadenantes externos diferentes:</li>
<ul>
  <li>post-disparo</li>
  <li>pre-disparador</li>
  <li>gatillo medio</li>
</ul>
<li>16 canales de entrada digital / 16 canales de salida digital</li>
<li>PCI-1202L proporciona baja ganancia programable:</li>
<ul>
  <li>0.5, 1, 2, 4, 8.</li>
</ul>
<li>PCI-1202H proporciona alta ganancia programable:</li>
<ul>
  <li>0.5, 1, 5, 10, 50, 100, 500, 1000.</li>
</ul>
<li>Disparador interno / externo.</li>
<li>Dos DAC programables independientes de 12 bits.</li>
<ul>
  <li>Rendimiento de 2 MHz por canal (maxi)</li>
</ul>
<li>Velocidad de transferencia de datos de 2,7 M palabras / alta velocidad.</li>
</ul>
