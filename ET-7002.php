<p>El ET-7002 es un módulo multifuncional con entradas analógicas de 3 canales, entradas digitales de 6 canales y salidas de relé de 3 canales. Proporciona varias entradas analógicas programables (+/- 150 mV, +/- 500 mV, +/- 1 V, +/- 5 V, +/- 10 V, +/- 20 mA, 0 ~ 20 mA y 4 ~ 20 mA). Cada entrada analógica puede configurar un rango adecuado con una protección de alto voltaje de 240 Vrms. Cada entrada analógica se puede programar para aceptar corriente o voltaje como entrada / salida dependiendo de la posición del puente correspondiente. El ET-7002 es totalmente compatible con RoHS y tiene calificación para protección ESD de 4 kV así como para aislamiento intramódulo de 2500 VDC.</p>        

<strong>Caracteristicas:</strong>
<ul>
<li>Servidor web incorporado.</li>
<li>Web HMI.</li>
<li>Soporte para protocolos Modbus TCP y Modbus UDP.</li>
<li>Seguridad de comunicación.</li>
<li>Conmutador Ethernet de 2 puertos para topología Daisy-Chain.</li>
<li>Dual Watchdog.</li>
<li>Amplio rango de temperatura de funcionamiento: -25 ~ + 75 ° C.</li>
<li>Conexión de par de E / S.</li>
<li>E / S incorporada.</li>
<li>AI: 3 canales con protección de sobretensión de 240 Vrms.</li>
<li>DI / contador: 6 canales.</li>
<li>Relé de potencia: 3 canales.</li>
</ul>

