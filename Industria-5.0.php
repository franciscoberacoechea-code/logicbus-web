      <h2 class="subtitle text-center blue">Robots colaborativos y la Industria 5.0</h2>

      <p>Una de las ideas en la colaboración entre hombre-máquina en manufactura es una visión a corto plazo. Se dio a conocer los resultados global de la consulta accenture, se revela que el 85% de los líderes de las empresas, prevén que sus líneas de producción podrán contar con los robots colaborativos dentro de sus planta para el año 2020, es por eso que la industria 5.0 es necesaria debido a la alta demanda de personalización de muchos consumidores en los productos que compran.</p>
      <p>Haciendo una comparación con los robots de la industria 4.0, los robots colaborativos de la industria 5.0, posee una gran ventaja al adquirir conocimiento valioso, que son mezclados con los del artesano, productor o fabricante.</p>
      <p>La experiencia y el toque de personalización fungen como un activo crucial de alto valor que resulta ser el diferenciador del enfoque de producción de volumen que es distinguido a la robótica de la industria 4.0.</p>

