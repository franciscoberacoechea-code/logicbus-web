M-7017Z tiene canales configurables por software: de 10 canales diferenciales a 20 canales de final único. Se aceptan tanto voltaje como corriente: ± 150mV, ± 500mV, ± 1V, ± 5V, ± 10V, ± 20mA, 0 ~ 20mA y 4 ~ 20mA. No se necesita una resistencia externa para medir la corriente; todo lo que tiene que hacer es abrir primero la carcasa y finalizar la configuración con un puente. ¡Medir la corriente es tan simple como crees! El M-7017Z también supera 240Vrms en protección de voltaje para entradas diferenciales y 150Vrms en protección de sobrevoltaje para entradas aisladas, aislamiento intramódulo de 3000VDC, protección ESD de contacto de +/- 4KV, protección EFT de +/- 4KV para potencia y +/- 1KV Protección EFT para RS-485. La frecuencia de muestreo de M-7017Z es cambiante. Hay modo rápido y modo normal para su consideración. El modo rápido es 60Hz con resolución de 12 bits. El modo normal es 10Hz con resolución de 16 bits.<BR><BR>

