<h3>Decodificacion de bus CAN</h3><BR><BR>

<p align="justify">Los osciloscopios PicoScope serie 6000 son recomendados para la decodificación serial mientras su memoria les permita recolectar secuencias de datos grandes e ininterrumpidas. El PicoScope 6403 puede recolectar miles de cuadros por segundo en su memoria de 1 millón de muestras y puede decodificar hasta 4 buses simultáneamente usando sus cuatro canales.
Los PicoScope muestran los datos decodificados en el formato de tu preferencia: en vista, en ventana o en los dos al mismo tiempo. El formato "en vista" muestra los datos decodificados debajo de la forma de onda en un eje común de tiempo, con los errores de cuadros rojo. Puedes hacer zoom en estos cuadros para ver el ruido o distorsión de la forma de onda.
El formato "en ventana" muestra una lista de los cuadros decodificados, incluyendo los datos y todas las banderas e identificadores. Puedes configurar las condiciones de filtrado para mostrar sólo los cuadros en los que estás interesado, buscar cuadros con propiedades específicas o definir un patrón de inicio para que el programa espere antes de listar los datos.</p><br><br>

