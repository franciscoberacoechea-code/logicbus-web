<li>Soporta entrada de corriente, voltaje y termopar</li>
<li>Ethernet 10/100 Base-TX</li>
<li>Conexión par de E/S</li>
<li>Configuración de canales independientes</li>
<li>6 Canales para salida digital para salida de alarma</li>
</ul>

