<center><strong>Módulo Ethernet de adquisición de datos con 10 entradas diferenciales (mV, mA, TC) y 6 salidas digitales aisladas, soporta Modbus TCP. Incluye la tarjeta DN-1822 y cable de 1.8 m.</strong></center><br>

<div align="right">
<a href="https://tienda.logicbus.com.mx/ET-7018ZS2_p_1560.html" title="Ir a Tienda" target="_blank"><img src="images/shopping_cart.png" border=0></a>
</div> <br>

<p>El ET-7018Z es un módulo de E / S Ethernet basado en la web que cuenta con un servidor web incorporado, que permite la configuración, el monitoreo de E / S y el control de E / S mediante el uso de un navegador web común. Con la función HMI web, no se necesitan habilidades de programación o HTML. Los usuarios pueden crear páginas web dinámicas y atractivas para la supervisión de E / S y el control de E / S. ¡El ET-7018Z ofrece un acceso fácil y seguro para los usuarios en cualquier momento y en cualquier lugar! ET-7018Z también es compatible con el protocolo Modbus / TCP que hace una integración perfecta con el software SCADA.<br><br>

El ET-7018Z es una entrada analógica diferencial de 16 bits y 10 canales y un módulo de salidas digitales de 6 canales que proporciona un rango de entrada programable en todos los canales analógicos (± 15 mV, ± 50 mV, ± 100 mV, ± 500 mV, ± 1 V, ± 2,5 V, ± 20 mA, 0 ~ 20 mA, 4 ~ 20 mA y termopares) y salida digital se puede establecer la salida de alarma. Cada canal analógico puede configurar un rango individual y tiene una protección de sobrevoltaje de 240 VCA.</p><BR>


<strong>Caracteristicas:</strong>
<ul>
<li>PoE y opciones regulares de Ethernet</li>
<li>Servidor web incorporado</li>
<li>HMI web</li>
<li>Modbus / TCP, protocolo Modbus / UDP</li>
<li>Seguridad de comunicación</li>
<li>Dual Watchdog</li>
<li>Temperatura de funcionamiento: -25 ~ +75 ° C</li>
<li>Conexión de par de E / S</li>
<li>E / S incorporada</li>
<li>Entrada de termopar: 10 canales</li>
<li>DO: 6 canales</li>
</ul>
