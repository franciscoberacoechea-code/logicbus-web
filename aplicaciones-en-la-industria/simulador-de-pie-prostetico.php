                    <li class="mb-3"><b>Sistema de Control Cerrado</b>: El <b>circuito cerrado</b> que se crea entre el <b>sensor de marcha</b>, el <b>actuador servomotor</b> y la <b>PC</b> garantiza que el sistema se ajuste dinámicamente a las necesidades del usuario, lo que ayuda a mejorar la rehabilitación.</li>
                    <li class="mb-3"><b>Adapatación a la Marcha del Paciente</b>: El sistema permite a los pacientes probar y ajustar las prótesis en tiempo real, simulando con precisión la marcha humana.</li>
                    <li class="mb-3"><b>Monitoreo y Ajuste de Resultados</b>: Gracias a SENSIT™, se pueden visualizar y ajustar los resultados, asegurando que la prótesis se adapta de forma óptima a las necesidades del paciente.</li>
                </ul>
                <p class="light-black">La <b>celda de carga LCM200</b> de <b>FUTEK</b> juega un papel clave en la mejora de la <b>rehabilitación</b> de pacientes con amputaciones trans-tibiales, proporcionando un <b>análisis preciso</b> de la marcha y un <b>ajuste dinámico</b> de las prótesis robóticas para optimizar la rehabilitación y la <b>adaptación</b> al nuevo dispositivo.</p>
