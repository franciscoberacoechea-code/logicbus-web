                <p class="text-center light-black font-weight-bold">¿Cómo funciona?</p>
                <ol class="light-black">
                    <li class="mb-3">Fuerza de los pedales de freno : la validación del sistema de freno por cable se lleva a cabo normalmente durante varias etapas del proceso de fabricación. Comienza en la etapa de desarrollo inicial, seguida de pruebas de resistencia, de laboratorio y de pista, y continúa durante el proceso de producción para una mayor garantía de calidad. Al utilizar los sensores de fuerza de pedal LAU220 de FUTEK (también conocidos como celdas de carga de freno), los fabricantes de automóviles pueden verificar la seguridad y la confiabilidad del sistema de freno por cable. Los sensores de fuerza de pedal están diseñados para medir la carga aplicada a los pedales de freno, acelerador y embrague durante los eventos de aceleración, desaceleración y cambio de transmisión.</li>
                    <li class="mb-3">Pinza de freno : En los sistemas de freno por cable, los controladores centrales requieren información precisa sobre la fuerza de sujeción entre la pastilla de freno y el disco en función del desplazamiento de la pastilla, que generalmente se denota como la curva característica de la pinza. Debido al envejecimiento, la temperatura y otras variaciones ambientales, las curvas características de la pinza varían con el tiempo. Por lo tanto, la calibración de la pinza es vital para una acción de frenado de alto rendimiento y la seguridad del vehículo. Además, durante la validación del diseño, los ingenieros utilizan un sistema de medición de fuerza para validar y calibrar los sistemas de circuito cerrado de freno por cable. El lavador de carga QLA307 de FUTEK tiene un perfil bajo y puede soportar cargas masivas, y se usa comúnmente como celda de carga de pinza para pruebas de pastillas de freno.</li>
