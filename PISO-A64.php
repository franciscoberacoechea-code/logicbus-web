<center><strong>Tarjeta de entrada digital aislada de 64 canales (fuente actual). Incluye cable CA-4037B y dos conectores CA-4002 D-Sub.</strong></center><br>


<p>El PISO-P64 tiene 64 canales de entradas digitales ópticamente aisladas, dispuestas en cuatro bancos. Cada canal de entrada utiliza una entrada de fotoacoplador que permite la fuente de alimentación interna aislada o la potencia externa seleccionada por un puente. Los canales de entrada aislados 0-15 están diseñados en el grupo A, los canales 16-31 están diseñados en el grupo B, los canales 32-47 están diseñados en el grupo C y los canales 48-63 están diseñados en el grupo D. La fuente de alimentación del puerto de entrada puede utilice la alimentación externa o la potencia desde el lado de la PC con un convertidor DC / DC. La placa interactúa con las señales lógicas de campo, lo que elimina los problemas de bucle de tierra y aísla la computadora host de tensiones dañinas. El PISO-P64 tiene un conector D-Sub de 37 pines y un conector macho de 40 pines. Los usuarios pueden conectar la señal digital a través del segundo conector D-Sub.
</p><BR><br>

