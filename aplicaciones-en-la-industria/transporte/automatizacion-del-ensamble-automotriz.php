                        de ensamblaje. Estos sensores pueden ir conectados a un PLC con entradas digitales como los
                        modelos <a class="blue link-orange font-weight-bold"
                            href="https://tienda.logicbus.com.mx/automatizacion-y-control-de-procesos-plc-fatek-plc-expandible-serie-fbs"
