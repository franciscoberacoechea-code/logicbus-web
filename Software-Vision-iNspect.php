<p align="justify">iNspect es un software de aplicación de visión diseñado específicamente para simplificar el diseño y la implementación de la inspección automatizada en la fábrica. iNspect ofrece a los usuarios nuevos y experimentados una herramienta práctica que ofrece una funcionalidad inquebrantable que se puede aplicar fácilmente a una amplia gama de tareas de fabricación. 
<br><br>
La configuración simple y directa de iNspect permite a los usuarios configurar e implementar rápidamente una aplicación. Cada una de las herramientas de inspección ha sido cuidadosamente diseñada para extraer la información relevante de la imagen del objeto. ¡No se requiere programación ni capacitación extensiva!</p>

