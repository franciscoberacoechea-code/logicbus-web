<strong>Descripción General</strong><br>
<p align="justify">La PCI-QUAD04 es una tarjeta de entrada de encoder de cuadratura de cuatro canales para computadoras con bus PCI. Basado en el chip de interfaz LS7266, la tarjeta es poderosa y fácil de usar.
Todas las conexiones están hechas por medio de un conector D macho de 37 pines. El corazón de esta tarjeta son dos LS7266, IC de contador de cuadratura de 24 bits de 2 ejes. Cada IC contiene:</p><br>

<ul>
<li>2 contadores de 24 bits.</li>
<li>Registros de preset y latch de salida de 24 bits.</li>
<li>Filtro digital integrado.</li>
<li>Preescaladores de contador de 8 bits.</li>
<li>Modos de contador programable incluyendo modos de no-cuadratura</li>
</ul><br>

<p align="justify">La tarjeta PCI-QUAD04 es plug and play y no requiere configurar ningun dip switch . Los jumpers en la tarjeta son usadas para seleccionar entre modos de entrada diferenciales o referenciados a tierra.</p><br><br>

