                    <li class="mb-3">ISO 7975: Automóviles de pasajeros: frenado en una curva: método de prueba de bucle abierto.
                </ul>
                <p class="light-black">FUTEK respalda a los fabricantes de sistemas Brake by Wire al ofrecer sensores que están optimizados para pruebas de pedales y pinzas de freno.</p>
                <p class="text-center light-black font-weight-bold">¿Cómo funciona?</p>
                <ol class="light-black">
                    <li class="mb-3">Las pruebas del sistema de frenos se realizan normalmente durante varias etapas del proceso de fabricación. Comienzan en la etapa de desarrollo inicial, siguen con las pruebas de resistencia, de laboratorio y de pista, y continúan durante el proceso de producción para garantizar una mayor calidad.</li>
                    <li class="mb-3">En esta aplicación particular, los operadores pueden utilizar la celda de carga de pedal LAU220 de FUTEK, que está equipada con una placa de montaje para facilitar la instalación.</li>
                    <li class="mb-3">Esta celda de carga de fuerza del pedal, que se instala en la parte superior del pedal de freno del automóvil, mide y registra con precisión las fuerzas aplicadas durante las pruebas programadas. Estas pruebas se llevan a cabo para validar la integridad del sistema de frenos.</li>
                    <li class="mb-3">La superficie superior del sensor es esférica, centralizando la fuerza de impacto.</li>
                    <li class="mb-3">Los operadores pueden monitorear los datos a través de la pantalla digital portátil inteligente IHH500 o la pantalla de montaje en panel IPM650 de FUTEK; o pueden transmitirse a una computadora a través de las soluciones USB de FUTEK.</li>
                    <li class="mb-3">Los datos se pueden monitorear a través del software de medición y prueba SENSIT™ de FUTEK. SENSIT™ puede monitorear hasta 16 canales de lecturas de medición, así como gráficos en vivo y registros de datos.</li>
                    <li class="mb-3">Este sistema también se puede utilizar para probar el pedal del acelerador, del embrague y del freno de estacionamiento.</li>
