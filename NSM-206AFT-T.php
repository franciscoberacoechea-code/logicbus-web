<center><strong>Multimodo, conector ST, 4 puertos 10/100 Mbps con 2 puertos de fibra Interruptor, caja de metal, admite un rango de voltaje de entrada de 12 - 48VDC, tiene un conector FT, opera hasta 75C.</strong></center><br>

<p>El NS-206AF / NSM-206AF es un Ethernet no administrado de 4 puertos con 2 conmutadores de puerto de fi bra. Usando la fibra óptica, puede evitar que el ruido interfiera con su sistema y admite transmisiones de alta velocidad (100 Mbps) y de alta distancia (hasta 60 km). El NS-206AF / NSM-206AF proporciona un amplio rango de potencia de 12 a 48 VDC para adaptarse a todos los estándares de potencia comunes que se encuentran en la automatización industrial, sin convertidores de potencia externos. La amplia entrada de potencia reduce los costos de instalación y mantenimiento.</p><BR>

<strong>Caracteristicas</strong>

<ul>
<li>Proporciona un puerto de fibra de 6 x 100-FX más 4 puertos Ethernet.</li>
<li>Cada puerto admite una negociación automática de velocidad de 10/100 Mbps.</li>
<li>Control de flujo de contrapresión Full Duplex IEEE 802.3xy semidúplex.</li>
<li>Carril DIN.</li>
<li>Crossover automático MDI / MDI-X para plug-and-play.</li>
<li>Arquitectura de almacenamiento y reenvío.</li>
<li>Entradas redundantes de potencia +12 ~ 48 VDC.</li>
<li>Admite temperaturas de funcionamiento de -30 ~ + 75 ° C.</li>
</ul>
