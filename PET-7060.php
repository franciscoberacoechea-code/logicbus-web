<li>10/100 Base-TX Ethernet</li>
<li>Conexión de par de E / S</li>
<li>Tipo de DO: 6 relé de potencia (Forma A)</li>
<li>Tipo DI: 6 contacto húmedo (sumidero / fuente)</li>
<li>Entrada digital PoE</li>
<li>Salida digital PoE</li>
<li>Desarrollado a través de Ethernet</li>
</ul>
