<p>El módulo de aislamiento K112 ha sido diseñado para conectar sensores de estado encendido / apagado a salidas NPN o PNP. Cuenta con una fuente estabilizada y aislada, que lo vuelve adecuado para sensores de 2 o 3 hilos. El módulo puede implementarse en la entrada de unidades de control de procesos, o directamente a una unidad de carga pesada, como una alarma luminosa o una bobina, debido a que sus salidas están protegidas contra una sobrecarga.
</p><br>


<strong>Características</strong>
<ul>
<li>Alimentación de 19.2 a 30 Vdc</li>
<li>Entrada a pulsos digitales compatible con los sensores más comunes: Contacto mecánico, IEC1131, NAMUR, 2 o 3 hilos NPN/PNP con 12V o 22V, Reed, fototransistor y dispositivos AICHI</li>
<li>Temperatura en operación de -10 a +65°C</li>
<li>Dimensiones: 93.1 x 102.5 x 6.2mm</li>
</ul>


