                <ol class="light-black">
                    <li class="mb-3"><b>Materiales Especializados</b>:
                        <ul>
                            <li>En ambientes de campos magnéticos fuertes, el equipo debe estar hecho de <b>materiales no magnéticos y con protección contra el magnetismo</b>, como el <b>Cobre Berilio</b>.</li>
                            <li>Estos materiales cumplen dos funciones cruciales:
                                <ul>
                                    <li><b>Prevención de alteraciones en las mediciones</b> del sensor debido al campo magnético.</li>
                                    <li><b>Eliminación del riesgo de atracción magnética</b> hacia la fuente del campo, evitando daños al equipo y al sensor.</li>
                                </ul>
                            </li>
                        </ul>
                    </li>
                    <li class="mb-3"><b>Protección y Exactitud de las Mediciones</b>:
                        <ul>
                            <li>La protección magnética evita que cualquier campo generado por el sensor afecte las mediciones de otros sensores o instrumentos cercanos.</li>
                        </ul>
                    </li>
                    <li class="mb-3"><b>Aplicación en Entornos Magnéticos</b>:
                        <ul>
                            <li>En esta aplicación, se instala una <b>Celda de Carga en Miniatura de Tipo S LSB200</b> dentro de una <b>máquina de resonancia magnética (MRI)</b> para realizar mediciones de fuerza.</li>
                            <li>El cableado y la señal del LSB200 se conducen fuera del MRI, hacia instrumentos colocados a una distancia segura, evitando cualquier daño al MRI o al sensor.</li>
                        </ul>
                    </li>
                    <li class="mb-3"><b>Opciones de Amplificación y Visualización</b>:
                        <ul>
                            <li>La señal del LSB200 se amplifica mediante un <b>Amplificador Analógico de la serie IAA</b> y puede enviarse a:
                                <ul>
                                    <li>Un <b>DAQ (Adquisición de Datos)</b>.</li>
                                    <li>Una pantalla digital de montaje en panel <b>IPM650</b> o la pantalla de mano <b>IHH500</b>.</li>
                                    <li>Un <b>controlador digital IDC305</b> para convertirla a una señal SPI.</li>
                                    <li>Una PC mediante el <b>Módulo de Salida USB220</b> y el software <b>SENSIT™</b> para registrar y analizar la medición.</li>
                                </ul>
                            </li>
                        </ul>
                    </li>
