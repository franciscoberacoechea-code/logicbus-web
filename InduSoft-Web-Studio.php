<p align="justify">La potencia constante, la refrigeración, la calefacción, la seguridad y la protección contra incendios son funciones críticas de la automatización de edificios. Sin embargo, los centros de datos plantean problemas únicos para la integración de los sistemas de gestión de edificios. Los controles ambientales para los sistemas de datos no solo deben ayudar a la productividad de los empleados, sino que deben emplearse consideraciones especiales para proteger el valioso equipo de TI que se encuentra dentro de un centro de datos.
<br><br>
La automatización de edificios para centros de datos debe, ante todo, ofrecer una fuente de energía continua y eficiente, con medidas de seguridad para proteger equipos y datos en caso de una interrupción del servicio, y medios para cambiar sin problemas de una fuente de energía a otra. Otra faceta clave de la gestión del centro de datos es garantizar que el enfriamiento sea suficiente para mantener el equipo a las temperaturas ideales, incluso en caso de interrupciones. Los sistemas de prevención de incendios también deben diseñarse de tal manera que las medidas de extinción de incendios no supongan una amenaza para los sistemas eléctricos sensibles.
<br><br>
La seguridad es otra característica clave. Tanto la seguridad física como la de TI son necesarias para proteger los datos críticos. La capacidad de monitorear las funciones integradas de automatización de edificios y verificar que todas funcionan correctamente es vital para los centros de datos que se utilizan en las operaciones del gobierno, ya que pueden estar sujetos a auditorías. 
<br><br>
Intermast LLC en Ekaterimburgo, Rusia, descubrió la necesidad de monitorear la automatización de edificios para los centros de datos cuando encargaron a USSC, Ltd, en cooperación con FirstMile desarrollar un sistema de enfriamiento y suministro de energía eléctrica para los equipos de los centros de datos en la planta.

</p><br><br>

<h3>EL RETO</h3>

<p align="justify">Antes de la instalación del sistema de suministro de energía eléctrica y de refrigeración, la planta no tenía forma de monitorear los sistemas del centro de datos. Los cortes de energía no se pudieron rastrear, y las advertencias no se pudieron enviar en caso de mal funcionamiento del equipo. Podría tomar horas o días notar problemas importantes en la infraestructura del centro de datos. 
<br><br>
Al igual que con cualquier proyecto de automatización de edificios de gran tamaño, también existía el problema de cómo varios sistemas, como la prevención de incendios, la refrigeración, la fuente de alimentación y el HVAC, podían monitorearse desde una sola interfaz. Construir la comunicación de automatización de un sistema a otro puede ser difícil de administrar sin una plataforma de software SCADA capaz de unirlos en un sistema que pueda ser monitoreado efectivamente.
<br<<br>
Cuando comenzaron a desarrollar los sistemas de automatización de edificios, USSC y First Mile también evaluaron el software que podría usarse para monitorear la información del centro de datos. InduSoft Web Studio fue elegido para esta tarea, gracias a la disponibilidad de opciones de conectividad y la relación costo-funcionalidad que lo hizo más atractivo que el software SCADA de la competencia. Con InduSoft Web Studio, sería posible vincular los sistemas de control dispares en el edificio y recibir información en una interfaz fácil de leer. Debido a que First Mile ya estaba familiarizado con InduSoft Web Studio, la instalación se podía realizar de manera rápida y rentable.</p><br><br>

