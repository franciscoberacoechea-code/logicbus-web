<center><strong>8 entradas digitales aisladas y 8 tarjetas de salida de relés. Incluye conector D-Sub CA-4002.</strong></center><br>


<p> Las tarjetas PISO-P8SSR8AC proporcionan 8 canales DI ópticamente aislados y 8 canales de salida de relé de estado sólido. Los canales DI proporcionan una protección de aislamiento de 3750 Vrms, lo que permite que las señales de entrada floten por completo para evitar bucles de tierra y aíslan la computadora host de tensiones dañinas.<br>

Los relés se utilizan donde es necesario controlar un circuito utilizando una señal de baja potencia (con aislamiento eléctrico completo entre el control y los circuitos controlados), o donde varios circuitos deben ser controlados por una señal. Los relés de estado sólido (SSR) controlan los circuitos de potencia utilizando un dispositivo semiconductor en lugar de partes móviles para realizar la conmutación. Las ventajas de SSR incluyen confiabilidad a largo plazo, sin rebote de contacto, sin chispas, operación silenciosa, ruido eléctrico reducido al cambiar y conmutación más rápida que los relés electromecánicos.<br> 

El PISO-P8SSR8AC se puede usar en varias aplicaciones, como controlar el estado ON / OFF de dispositivos externos, controlar relés externos o pequeños interruptores de potencia, activar alarmas, cerrar contactos, detectar voltajes o conmutadores externos, etc. Las tarjetas pueden instalarse en una ranura PCI de 5 V y soporte verdadero "Plug & Play", con un solo conector DB-37 provisto para facilitar el cableado. <br><br>

El PISO-P8SSR8AC admite varias versiones del sistema operativo, como Linux, DOS, Windows 98 / NT / 2000 y 32/64-bit Windows 7 / Vista / XP. El control DLL y Active X junto con varios programas de muestra de lenguaje basados ??en Turbo C ++, Borland C ++, Microsoft C ++, Visual C ++, Borland Delphi, Borland C ++ Builder, Visual Basic, C # .NET, Visual Basic.NET y LabVIEW se proporcionan para ayudar a los usuarios a desarrollar rápida y fácilmente sus propias aplicaciones.
</p><BR><br>

