      <td colspan="2"><div align="justify">
        The DNA/DNR-SOE-648 is a 48 channel, high performance Sequence of Events recorder input interface. The DNA-SOE-648 and DNR-SOE-648 are compatible with popular &ldquo;Cube&rdquo; and RACKtangle&reg; I/O chassis respectively, The DNx-SOE-648 system includes the RACKtangle/Cube I/O board as well as screw terminal panel and cable. Systems requiring more than 48 channels are easily accommodated by simply adding more DNx-SOE-648s and if necessary, additional Cubes or RACKtangles. SOE systems requiring 5000 or even more channels are easily designed and deployed using DNx-SOE-648 based systems.<br>
        <br>
        System sample rate and time stamp resolution is user programmable from 250 &micro;S up to 16.4 seconds in 250 &micro;S increments. Duration of the recorded data is limited only by the hard drive of the host PC in PowerDNA mode, or by the size of SD card or USB drive when used in a chassis.<br>
        <br>
        The DNx-SOE-648 accepts inputs from 0 to 140 VDC. The switch levels are software selectable anywhere in the range with 100 mV resolution. The system offers programmable hysteresis over the full input range. The board provides user programmable debounce durations between 5 and 500 ms. Each board provides 350 Vrms isolation between the I/O and the cube and other installed I/O layers. All inputs are overvoltage protected from -25 to +200 VDC, and against ESD.<br>
        <br>
        Unlike many SOE systems that provide limited deployment flexibility, the DNx-SOE-648 offers the ability to do everything a standard SOE recorder does, plus much more. In addition to logging and timestamping events, a system can be configure to log many other parameters including temperature, pressure, strain, vibration and more. It may also acquire data from serial I/O devices, or provide data directly via the internet . Finally, an SOE-648 system can be configured to provide control capabilities and in particular is an ideal primary or backup initiator of emergency shut down procedures.<br>
        <br>
        The DNx-SOE-648 includes software drivers supporting all popular operating systems including: Windows, Linux, QNX, VXWorks, RTX, and most other popular Real-Time Operating Systems. Windows users may take advantage or the powerful Framework which provides a simple and complete software interface to all popular Windows programming language and data acquisition and control applications (e.g. LabVIEW, DASYLab, MATLAB).        
