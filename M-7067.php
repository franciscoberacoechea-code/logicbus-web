          <p>La serie 7061 proporciona 12 canales de salida de relé de potencia y la serie 7067 proporciona 7 canales de salida de relé de señal. Hay opciones para configurar los valores de encendido y seguro. También se proporcionan protección contra ESD de 4 kV y aislamiento intra-módulo de 3750 VDC para mejorar las capacidades de protección contra el ruido en el entorno industrial. Las versiones "D" de la serie 7061 proporcionan 12 indicadores LED y las versiones "D" de la serie 7067 proporcionan 7 indicadores LED que pueden usarse para monitorear el estado de los canales de salida de relé. Las versiones "M" de cada serie son compatibles con los protocolos Modbus RTU y DCON, que se pueden configurar a través del software. La serie 7061 es la solución ideal para aplicaciones de alta potencia y la serie 7067 es la solución ideal para la conmutación de señales pequeñas.</p><BR>

