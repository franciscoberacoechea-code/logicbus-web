<p>El I-7531 es un repetidor CAN utilizado para establecer un acoplamiento físico de dos o más segmentos de un sistema de bus CAN. Los usuarios pueden implementar topologías de árbol o estrella, así como las largas líneas de caída con el I-7531. Los usuarios también pueden aumentar la cantidad máxima de nodos de bus utilizando el I-7531. El I-7531 es un repetidor CAN ópticamente aislado que proporciona 2500 Vrms de aislamiento óptico. Esta función lo ayuda a separar y proteger los segmentos críticos del sistema del resto de la red CAN. Y su protección galvánica aísla entre dos segmentos CAN y la fuente de alimentación.</p>

