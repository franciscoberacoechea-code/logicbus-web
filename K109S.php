<p>K109S es un dispositivo que acepta señales de mA / V capaces de convertirlo en señales estándar de mA / V. El dispositivo puede alimentar también todos los sensores de 2 hilos y todos los parámetros son confiables a través de interruptores DIP. La conexión de la fuente de alimentación está disponible en los terminales o un conector especial (K-BUS) permite una distribución de la fuente de alimentación a los módulos a través del conector de bus. Un aislamiento galvánico de 3 vías entre la fuente de alimentación // entrada // circuitos de salida garantiza la integridad de sus datos.
</p><br>

<strong>Caracteristicas:</strong>
<ul>
<li>Alimentación: 19~30 Vdc</li>
<li>Entrada: Corriente 0/4~20 mA o voltaje 0/1~5 Vdc, 0/2~10Vdc</li>
<li>Salida: Corriente 0/4~20 mA, 20~4/0 mA o voltaje 0/1~5 Vdc, 0/2~10 Vdc</li>
<li>Aislamiento galvánico de 3 vías</li>
<li>Dimensiones (102.5 x 93.1 x 6.2 mm)</li>
<li>Resolución a 14 bits</li>
<li>Precisión: 0.1%</li>
<li>Configurable mediante DIP switch</li>
<li>Montaje en riel DIN</li>
</ul>

