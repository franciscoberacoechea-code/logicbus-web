<p>El uso del medio de fibra óptica para aplicaciones Ethernet se ha vuelto más popular debido a las excelentes características físicas de la fibra óptica, especialmente para redes de larga distancia. Sin embargo, el cable de fibra óptica es muy costoso, por lo que si podemos aplicar una solución que utiliza solo 1 cable en lugar de 2, el costo de la infraestructura se puede reducir a la mitad.
<br><br>
La serie NS-200WDM de convertidores de fibra monocatenaria admite la tecnología de multiplexación por división de longitud de onda (WDM) que permite que dos canales de comunicación de datos independientes transmitan y reciban más de una línea de fibra óptica estándar, de modo único. Esto no solo duplica el ancho de banda existente, sino que también reduce de manera efectiva el costo de crear una nueva infraestructura de fibra óptica.</p>

<strong>Caracter&iacute;sticas:</strong>
<ul>
<li>Crossover automático MDI / MDI-X para plug-and-play.</li>
<li>Cada puerto admite una negociación automática de velocidad de 10/100 Mbps.</li>
<li>Arquitectura de almacenamiento y reenvío.</li>
<li>Control de flujo de contrapresión Full Duplex IEEE 802.3xy semidúplex.</li>
<li>Ancho de banda de memoria de 1,4 Gbps de alto rendimiento.</li>
<li>Motor de búsqueda integrado con direcciones MAC dedicadas de 1 K unicast.</li>
<li>Admite +10 ~ + 30Vdc voltaje de protección de polaridad inversa.</li>
<li>Admite temperaturas de funcionamiento de 0 ° C ~ + 70 ° C.</li>
<li>Montaje en raíl DIN para uso industrial.</li>
</ul>


