<p align="justify">Diseñado con el chip A/D de aproximación sucesiva Maxim MAX197, el SeaI/O-470M-OEM es una interfaz RS-485 Modbus RTU que proporciona ocho entradas diferenciales o 16 de un solo extremo de 12 bits y dos  canales de salida D/A de 12 bits. Las entradas A/D son seleccionables por software para rangos de 0-5V, 0-10V, +/-5V y +/-10V y cada canal se puede configurar mediante hardware para medir un bucle de corriente de 4-20mA. Los dos canales D/A de 12 bits se pueden seleccionar mediante puentes para rangos de salida de 0-5V y 0-10V.
<br><br>
Además, el módulo SeaI/O-470M-OEM proporciona ocho entradas aisladas ópticamente clasificadas para 5-30 V CC y cuentan con aislamiento externo de 300 V, mientras que ocho salidas de colector abierto pueden absorber hasta 580 mA, ideal para conmutar dispositivos de 24 V que se encuentran comúnmente en entornos industriales. Perfecto para una variedad de aplicaciones de adquisición/control de datos y de prueba y medición, el SeaI/O-470M-OEM incluye terminales de tornillo extraíbles, que simplifican las conexiones de cableado de campo. El SeaI/O-470M-OEM se alimenta de su fuente de 9-30V DC, o seleccione entre una variedad de opciones de fuente de alimentación Sealevel.
<br><br>
Amplíe su red de E/S con los productos de la serie SeaI/O N. Las placas OEM SeaI/O están disponibles con relés Reed y Forma C, entradas ópticamente aisladas, interfaces TTL, funcionalidad A/D y D/A. Se pueden agregar hasta 246 módulos de expansión adicionales utilizando conectores de paso convenientes.
<br><br>
Comun&iacute;quese con los m&oacute;dulos de E/S digitales Ethernet eI / O utilizando el protocolo Modbus TCP est&aacute;ndar de la industria o use las bibliotecas de software SeaMAX API de su programa de aplicaci&oacute;n. Los controladores y las utilidades del <strong><a href="software-seamax" target="_blank">software SeaMAX </a></strong> facilitan la instalaci&oacute;n y operaci&oacute;n usando los sistemas operativos Windows 10 y 8.  
