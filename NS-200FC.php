<center><strong>* Para uso en modo múltiple * 10 / 100BaseT Ethernet a fibra óptica 100BaseFX Converter. El Ethernet admite las funciones Auto-Negociación 10 / 100M y MDI / MDIX automático. Tiene conector SC, admite temperaturas de funcionamiento de 0 ~ + 70 ° C</strong></center><br>
 <br>

<p> 
El NS-200FC funciona en modo half o full duplex. En modo dúplex completo, el rango es de 2 km con cables de fibra de 62.5 / 125μm; en modo semidúplex, el rango es de 412 m con cables de fibra de 62.5 / 125μm. Contiene la función de "arranque suave" con protección de sobrecarga, protección de alto y bajo voltaje. El ancho del NS-200FC es de solo 32.30 mm, por lo que puede usarse donde el espacio es importante.
</p><BR>

<strong>Caracteristicas:</strong>
<ul>
<LI>Crossover automático MDI / MDI-X para plug-and-play.</LI>
<LI>Cada puerto admite una negociación automática de velocidad de 10/100 Mbps.</LI>
<LI>Arquitectura de almacenamiento y reenvío.</LI>
<LI>Control de flujo de contrapresión Full Duplex IEEE 802.3xy semidúplex.</LI>
<LI>Admite +10 ~ +30 VCC de voltaje.</LI>
<LI>Admite temperaturas de funcionamiento de 0 ° C ~ +70 ° C.</LI>
<LI>Montaje en riel DIN para uso industrial.</LI>
</ul>
