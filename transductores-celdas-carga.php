<h1>Transductores de celdas de carga</h1><br>

<p>Una celda de carga es un transductor que es utilizado para convertir una fuerza en una señal eléctrica. Esta conversión es indirecta y se realiza en dos etapas. Mediante un dispositivo mecánico, la fuerza que se desea medir deforma una galga extensiometrica. La galga extensiometrica convierte el (desplazamiento) o deformación en señales eléctricas.</p>

