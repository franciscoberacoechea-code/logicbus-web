<p>Power-over-Ethernet (PoE) permite que la energía y los datos se transporten a través de un solo cable Ethernet, por lo que un dispositivo puede operar únicamente a partir de la energía que recibe a través del cable de datos. Esta innovación permite una mayor flexibilidad en el diseño de la oficina, una mayor eficiencia en el diseño de sistemas y un tiempo de respuesta más rápido en la configuración e implementación.<BR>

El PET-7026-48 tiene una verdadera potencia IEEE 802.3af (clasificación, Clase 1) sobre Ethernet (PoE) usando ambos pares de Ethernet (cable de Ethernet de Categoría 5). El PET-7026-48 puede recibir energía de fuentes de alimentación auxiliares, como adaptadores de CA y batería, además de la red habilitada para PoE. Esta es una característica deseable cuando los requisitos de potencia total del sistema exceden la capacidad de carga del PSE. Además, con la opción de alimentación auxiliar, el PET-7026-48 se puede utilizar en un sistema Ethernet estándar (no PoE).<BR>

El PET-7026-48, un módulo de E / S Ethernet basado en web, cuenta con un servidor web incorporado, que permite la configuración, el monitoreo de E / S y el control de E / S simplemente usando un navegador web común. Además, con la función HMI web, no se necesitan más habilidades de programación o HTML; la creación de páginas web dinámicas y atractivas para el monitoreo de E / S y control de E / S sería divertido para los ingenieros para siempre. ¡El PET-7026-48 ofrece un acceso fácil y seguro para los usuarios desde cualquier lugar y en cualquier momento! Además, PET-7026-48 también es compatible con el protocolo Modbus / TCP que hace una integración perfecta con el software SCADA.<BR>

El PET-7026-48 es un módulo multifuncional, hay entradas analógicas de 6 canales, salida analógica de 2 canales, entradas digitales de 2 canales y módulo de salidas digitales de 2 canales. Proporciona un rango de entrada programable en todas las entradas analógicas (+/- 500mV, +/- 1V, +/- 5V, +/- 10V, +/- 20mA, 0 ~ 20mA y 4 ~ 20mA), las salidas analaog son de 12 bits con +/- 5V, +/- 10V, 0 ~ 20mA y 4 ~ 20mA y salida digital se puede establecer la salida de alarma. Cada entrada analógica puede configurar un rango individual y tiene una protección de 240 Vrms de alto voltaje. Puente seleccionable para entradas / salidas de tensión o corriente.<BR></p>        

