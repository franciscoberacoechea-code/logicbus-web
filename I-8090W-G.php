<p align="justify">I-8090W es una tarjeta de contador de codificador de 3 ejes. La tarjeta codificadora I-8090W tiene filtro digital interno, contador de 16 bits y alta velocidad de conteo de 1Mpps. La aplicación de la I-8090W es la medición de posición / distancia, la medición de la velocidad, la retroalimentación para el control del motor, la entrada de la rueda de mano, etc. Un sistema que incluye, I-8091W, I-8090W se puede implementar como un sistema de control de movimiento independiente para máquinas automáticas.</p>

<strong>Características:</strong>
<ul>
<li>Contador de codificador de 3 ejes y 16 bits.</li>
<li>Contador de codificador de 32 bits por software.</li>
<li>Velocidad máxima de conteo: 1M de pulso / seg.</li>
<li>Entrada diferencial: A +, A-, B +, B-, C +, C-.</li>
<li>Modo de recuento de cuadrantes, modo de conteo CW / CCW, modo de conteo de pulso / Dir.</li>
<li>Voltaje aislado: 2500 Vrms.</li>
</ul>

