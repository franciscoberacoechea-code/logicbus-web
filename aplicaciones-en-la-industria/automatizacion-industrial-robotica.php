                <ol class="light-black">
                    <li class="mb-3"><b>Montaje y Configuración del Sensor de Torque</b>:
                        <ul>
                            <li>En la aplicación ilustrada, se utiliza un sensor de torque rotativo en el ensamblaje de una máquina de prueba automatizada para medir la resistencia y durabilidad de los palos de hockey profesionales durante un “slap shot” (disparo de hockey).</li>
                            <li>Este sensor se integra en el brazo robótico de la máquina, el cual puede rotar hasta 180 o 360 grados, simulando el impacto de un disparo real.</li>
                        </ul>
                    </li>
                    <li class="mb-3"><b>Medición del Torque y Punto de Rotura</b>:
                        <ul>
                            <li>El sensor de torque rotativo registra la fuerza de rotación exacta (punto de rotura) ejercida por el palo de hockey al golpear el disco. Esto permite a los ingenieros de prueba evaluar la resistencia del palo en condiciones de uso intensivo.</li>
                            <li>Los datos de torque se visualizan en tiempo real a través de dispositivos como el <b>IHH500 Intelligent Digital Hand Held Display</b> o el <b>IPM650 Panel Mount Display</b> de FUTEK, o se transmiten directamente a una PC mediante el <b>USB520</b>.</li>
                        </ul>
                    </li>
                    <li class="mb-3"><b>Solución de Transmisión de Datos</b>:
                        <ul>
                            <li>El <b>USB520</b> es ideal para aplicaciones que requieren la traducción de lecturas de torque rotativo en datos de ángulo y velocidad. Su diseño compacto y robusto lo hace perfecto para integrarse en aplicaciones industriales como esta.</li>
                        </ul>
                    </li>
                    <li class="mb-3"><b>Análisis y Reporte de Resultados</b>:
                        <ul>
                            <li>Si los ingenieros de prueba desean recolectar, graficar e interpretar estos datos, pueden emplear el software SENSIT™ de FUTEK. Con <b>SENSIT™</b>, es posible registrar y analizar los datos de manera detallada para evaluar la calidad y durabilidad del equipo deportivo.</li>
                        </ul>
                    </li>
                </ol>
                <p class="text-center light-black font-weight-bold">Ventajas del Sistema de Prueba</p>
                <ul class="light-black">
