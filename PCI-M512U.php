	<td colspan="2" align="left"><strong>Descripci&oacute;n General </strong><br>
  <br>
	  El PCI-M512/PCI-M512U provee una memoria SRAM de 512 kB con bater&iacute;a de respaldo, entrada digital de 12 bits y salida digital de 16 bits. Adicionalmente soporta los bus PCI 5 V y 3.3 V, mientras que el PCI-M512 soporta s&oacute;lo el bus 5 V. El PCI-M512U (Versi&oacute;n PCI Universal) es totalmente compatible con la PCI-512 (versi&oacute;n PCI). <br>
  <br>     
	  Los usuarios pueden usar el DB-16P para conectar los puertos CN2 para prop&oacute;sito de aislamiento, o usar el DB-16R para conectar los puertos de salida CN1 para el control de relevador. <br>
  <br>
  <br>
  El PCI-M512/PCI-M512U est&aacute; equipado con dos bater&iacute;as de litio para mantener el contenido en caso que la PC se quede sin energ&iacute;a. Las dos bater&iacute;as pueden continuar suministrando energ&iacute;a a la SRAM de 512 kB para retener los datos importantes por 10 a&ntilde;os; y el dise&ntilde;o de estas bater&iacute;as es seguro para mantener los datos cuando se reemplacen por unas nuevas. <br>
  <br>     
  El PCI-M512/PCI-M512U tambi&eacute;n provee 4 indicadores LED para mostrar el estado de las bater&iacute;as. Es f&aacute;cil saber si el estado de las 2 bater&iacute;as es normal, si tienen voltaje bajo o si est&aacute;n fallando con estos 4 indicadores LED. <br>
          <br>
        El PCI-M512/PCI-M512U es una soluci&oacute;n ideal para la confiabilidad de un sistema.</td>
