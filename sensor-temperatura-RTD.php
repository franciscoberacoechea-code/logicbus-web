            <h3 class="subtitle blue text-center">Medición de temperatura y control PID</h3>

            <p>El <a href="PLC-Serie-FBs" title="Productos PLC">PLC FBs</a> proporciona módulos de temperatura de
                termopar (J, K, R, S, E, T, B, N) así como un módulo de temperatura RTD (para Pt-100 y Pt-1000). Los <a
                    href="termopares" title="">termopares</a> son adecuados para la medición de grandes rangos de
                temperatura, como un proceso de caldera. Los RTD son buenos para la medición de baja temperatura, gamas
                más pequeñas de temperatura y una resolución más alta tal como aplicaciones de refrigeración y de aire
                acondicionado. Debido a las características del control de temperatura, multiplexeo en el escaneo de
                entradas de temperatura y el <a href="lb-tb-pid" title="Control PID">control PID</a> de múltiples
                lazos hacen que un solo PLC FBs sea capaz de realizar hasta 32 lazos de control de temperatura PID. Con
                la instrucción conveniente de la medición de temperatura y control de temperatura PID en el desarrollo
                del programa en escalera reduce significativamente la dificultad, el costo, el tiempo de desarrollo y
                pruebas de monitoreo de programas de control.</p>


