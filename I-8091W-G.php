<p align="justify">La tarjeta de control de motor paso a paso I-8091W es una tarjeta de generación de impulsos de 2 ejes controlada por microcomputadora. Incluye un FIFO de 2K bytes para recibir el comando de movimiento del host. Una microcomputadora para la generación y protección de perfiles, chip DDA de 2 ejes para ejecutar la función DDA cuando se usa el comando de interpolación, aislamiento óptico de 2500 Vrms insertado para aplicaciones industriales.</p>

<strong>Características:</strong>
<ul>
<li>Control de motor paso a paso independiente de 2 ejes / control de servomotor simultáneo (tipo de entrada de pulso).</li>
<li>Velocidad máxima del pulso: 1Mpps.</li>
<li>Número máximo de pasos: 232 -1 pasos.</li>
<li>CPU integrada.</li>
<li>Interfaz de tipo de comando.</li>
<li>Interpolación circular de 2 ejes lineal de 2 ejes.</li>
<li>Aceleración / desaceleración trapezoidal automática.</li>
<li>Modos de pulso de salida: CW / CCW o pulso / dirección.</li>
<li>La polaridad de salida puede ser programable.</li>
<li>3 entradas digitales ópticas aisladas por eje para interruptores de límite.</li>
<li>Condición inicial del interruptor de límite programable como apertura normal (NO) o cierre normal (NC).</li>
</ul>

