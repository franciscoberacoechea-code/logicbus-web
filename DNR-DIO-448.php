      <td colspan="2"><div align="justify">The DNR-DIO-448 is a 48-channel, high performance digital input boards designed for use in a wide variety of digital monitoring applications and is fully compatible with popular "Cube" data acquisition and control chassis as well as all other cube-based products.<br>
          <br>
          The "Guardian advantage" on the DNR-DIO-448 is an innovative A/D input approach allowing the board to offer incredible input flexibility. A diagnostic input mode monitors the actual analog voltage at each input, allowing quick and accurate detection of short and open circuits as well marginal or failing drive circuitry. The analog input capability is also a powerful installation, diagnostic and data acquisition tool.<br>
          <br>
          The board offers programmable hysteresis over the full input range. Hysteresis is independently programmable on each 24-bit port. The DNR-DIO-448 also supports user programmable debouncing intervals which may also be set on each channel independently with durations between 5 and 500 ms.&nbsp;<br>
          <br>
          The DNR-DIO-448 reads all 48 bits at sustained rates in excess of 1 kS/second. Each channel is configured with a 33 kOhm pull up/down resistor. This makes the board an ideal solution for monitoring contact closures as well as standard voltage inputs. The pull-up/pull-down resistors are configured by connecting the "PLEVEL" pins on the I/O connector to Vcc or ground. Each board provides 350 Vrms isolation between the I/O and the cube and other installed I/O layers. All inputs are overvoltage protected to &plusmn;40 VDC, and against ESD.<br>
          <br>
      The DNR-DIO-448 is fully supported by the UEIDAQ Framework which provides a simple and complete software interface to all popular programming languages, operating systems and data acquisition and control applications (e.g. LabVIEW, DASYLab, MATLAB).</div></td>
