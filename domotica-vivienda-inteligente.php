      <h2 class="subtitle blue text-center my-5">Ejemplo de Domótica</h2>
      <p>Para entender mejor acerca de la Domótica, les estaremos mencionando varios ejemplos de lugares domóticas en México:</p>
      <p class="med">Automatización en casas</p>
      <p>En la ciudad de México, la organización Nuovo, realizó un proyecto de una casa 100% automatizada, como resultado quedó totalmente increíble. Este ha sido un gran proyecto ya que introduce grandes decoraciones, control de vivienda, iluminación, comodidades dentro del agua, e incluyendo hasta un cine totalmente profesional, Esta casa está totalmente personalizada.</p>
      <p>A través de los tiempos el museo de Santiago Carbonell del estado de Querétaro, ha mostrado todas las obras de arte, y el objetivo para un proyecto de domótica, por eso se creó un ambiente con la iluminación, seguridad y sonido idóneo. Para este proyecto se instalaron para cada característica los mejores sistemas de audio, seguridad e iluminación controlados y automatizados, por el motivo de ahorro de energía, ya que por el cual todo esto se diseñó para que una sola persona fuese el encargado de todo el sistema domótica.</p>
      <p class="med">Domótica hacia el futuro</p>
      <p>La domótica, o tecnología aplicada al hogar, ha integrado a través del tiempo tecnologías de comunicación, informática y automatización, la cual han desempeñado una combinación perfecta que pueden conseguir viviendas inteligentes.</p>
      <p>La domótica tiene muy claro su objetivo: conseguir el mayor bienestar, seguridad y confort, en el caso de las vivienda como dentro de la industrial, las nuevas tecnologías han logrado que por medio de la domótica se use como herramienta hoy en día, elementos importantes como la iluminación, la seguridad la climatización o la comunicación, entre tantos elementos, ha sido un factor fundamental dentro de la sociedad como la industria.</p>
      <p>Hoy en día la domótica se ha convertido en un factor importante hacia el futuro, para poder disfrutar de un planeta mucho más verde, más sostenible, respetando el medio ambiente, respetando el entorno de rodear cada construcción. En estos años se ha notado un cambio, un creciente interés por parte de la población en general por los sistemas domóticas y la inteligencia ambiental.</p>
      <p>La domótica es muy importante hoy en día, ya que el consumo energético se ha disparado en los últimos tiempos y es necesario que se tomen medidas inmediatas.</p>
      <h2 class="subtitle blue text-center my-5">¿Por qué es importante la domótica?</h2>
      <p>Las tecnologías han evolucionado mucho, y han traído avances como es en el caso de la domótica, con la cual con el poder de automatizar los hogares y edificios, ha permitido que en un solo clic podamos programas la casa o edificio para que sea independiente y haga actividades como por ejemplo, cerrar persianas, apagar luces, programar la lavadora, entre otras actividades. Cada día más, este factor se ha convertido en una de las tecnologías más usadas y cada vez hay más profesionales en el sector.</p>
