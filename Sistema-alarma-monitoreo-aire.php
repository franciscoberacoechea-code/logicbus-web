<p align="justify">Con una industria altamente desarrollada y el gran uso de energía fósil, la calidad de vida humana ha sido cambiada. El escape de los parque industriales han sido verificados conteniendo muchos contaminantes como partículas en suspensión, tales como (PM10), monóxido de carbono ( CO), dióxido de carbono(CO2), dióxido de azufre(S02), dióxido de nitrógeno (NO2), ozono (03), etc. La organización Mundial de la salud (OMS) ha demostrado que los contaminantes del aire pueden ser daño al cuerpo humano, como enfermedades del corazón, disminución de la fertilidad humana, o incluso las enfermedades crónicas que causan cáncer.<br>
En los últimos años, las sustancias nocivas de la atmósfera aumentaron año tras año. Las personas que viven cerca de los parques industriales tienen miedo, a causa de los eventos de envenenamiento causados por contaminantes del aire tóxicos, por lo que ha surgido manifestaciones, a lo cual el gobierno ha ordenado que alguna fábrica suspenda las operaciones, La administración de Protección ambiental (EPA) recientemente también adopta medidas preferenciales, tratamientos e incentivos para guiar a los fabricantes que instalan activamente  los equipos de detección o realizan mejoras en el proceso para cumplir con las emisiones estándar mínimas . Al mismo tiempo, para disminuir la contaminación y proteger la salud de las personas y su calidad de vida.</p><br>

<div align="center"><h2>CONTAMINACIÓN DEL AIRE</h2></div><br>
<p align="justify">La contaminación del aire no solo amenaza la salud de los seres humanos sino también aumenta la carga social sobre los recursos médicos y perturba el balance ecológico. Los humanos deberían comenzar a reconsiderar ¿Qué tipo de civilización avanzada necesitamos? ¿Volveremos a la esencia de la vida humana durante el proceso de búsqueda de la evolución industrial? Solo el desarrollo en un ambiente saludable garantiza la evolución sustentable. Cada día, la conservación de la energía y reducción de carbono, energía renovable son importantes en la protección del medio ambiente.<br>
Debido a estas situaciones, Logicbus es una empresa ambientalmente responsable contando con los equipos de la marca ICP DAS, una variedad de tecnología verde. Las cuales son soluciones de tecnológicas que se aplican a cada industria para cumplir con el objetivo de operación sostenible.<br>
Por ejemplo, para prevenir eficazmente la contaminación por gases de escape, presentamos un “sistema de monitoreo y alarma de contaminación del aire”, para que el operador pueda tener efectiva e inmediatamente lecturas cuando el contaminante esté arriba del valor límite, and asegurarse de la calidad  del ambiente laboral y salud de las personas.</p>

