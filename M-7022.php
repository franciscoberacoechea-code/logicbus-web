<center><strong>Salida de corriente de 2 canales, salida de tensión y módulo de adquisición de datos de salida analógica. Se puede comunicar a través de Modbus RTU y RS-485. Admite temperaturas de funcionamiento entre -25 ° C y 75 ° C (-13 ° F ~ + 167 ° F).</strong></center><br>
 <br>

<p> 
El I-7022 es un módulo de salida analógica de 2 canales y 12 bits que está diseñado para salidas de voltaje y corriente utilizando el protocolo DCON. El I-7022 cuenta con un aislamiento intramódulo de 3000 VDC, y la fuente de alimentación para la salida de corriente se puede seleccionar como interna o externa a través de un puente. También se proporcionan opciones para permitir que se establezcan los valores de encendido y seguro. El M-7022 y el M-7022A son compatibles tanto con Modbus RTU como con los protocolos DCON que pueden configurarse mediante software, y todas las especificaciones de hardware son las mismas que las de la I-7022.</p><BR>

<strong>Caracteristicas:</strong>
<ul>
<LI>Salida analógica de 2 canales</LI>
<LI>Software seleccionable de corriente o salida de voltaje</LI>
<LI>Valor de encendido configurado</LI>
<LI>Ajuste de valor seguro</LI>
<LI>Detección de cable abierto para salida de corriente</LI>
<LI>Voltaje de lectura o corriente</LI>
<LI>Aislamiento de canal a canal de 2 kV</LI>
<LI>Aislamiento intramódulo de 3000 VDC</LI>
<LI>Pendiente de salida programable</LI>
<LI>Dual Watchdog</LI>
<LI>Amplio rango de temperatura de funcionamiento: -25 a + 75 ° C</LI>
</ul>
