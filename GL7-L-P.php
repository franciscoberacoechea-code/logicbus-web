<p align="justify">El módulo lógico / de pulso ingresa señales de reloj digital de relés o tacómetros y medidores de flujo con salidas de pulso. Puede medir la sincronización de las señales de relé de control o los caudales de los sensores de salida de impulsos.<br><br>
En modo lógico: la velocidad de muestreo máxima es de 1MS / s (1µs) a 1S / hr. (1hr).<br><br>
Al monitorear tanto el control de relé de las entradas analógicas de las señales de control como las entradas de voltaje de los sensores que monitorean las mediciones físicas, puede encontrar la relación entre los interruptores de relé de control y cómo afectan la medición o los procesos en las líneas de fabricación o proceso.<br><br>
En modo de impulso: la velocidad de muestreo máxima es de 10kS / s (100µs) a 1S / hr (1hr). Puede contar la cantidad de pulsos para medir señales de las salidas del codificador, la velocidad de rotación utilizando sensores de efectos de sala o tacómetros, y los caudales. Al combinar los módulos junto con otros conjuntos de módulos, puede monitorear el número de pulsos junto con la forma de onda analógica utilizada por otros módulos.</p><br><br>

