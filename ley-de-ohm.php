        <p class="text-justify paragraph mt-5" itemprop="abstract">La ley de Ohm es un elemento fundamental para la explicación de ciertos fenómenos relacionados con la electricidad. Este hecho fue descubierto en el año de 1827 por <b>George Simon Ohm</b>, observó la relación entre el voltaje aplicado <b>V</b>, la Intensidad <b>I</b> y la resistencia <b>R</b>, donde se expresa con la famosa Ley de Ohm, que es la ecuacion fundamental de toda la ciencia de la electricidad, esta ley ha revestido extraordinaria importancia en los cálculos eléctricos. En su formulación más sencilla, esta ley afirma que la intensidad de la corriente (I) que circula por un conductor eléctrico es directamente proporcional a la diferencia de potencial (V) y, paralelamente, inversamente proporcional a la resistencia (R). </p>
