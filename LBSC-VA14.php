                  <li>Opción con dos salidas configurables para señales diferentes disponibles en un equipo con diseño
                    de 22.5mm de ancho</li>
                  <li>Amplio rango de alimentación de 85-265 Vac, 100-300 Vdc ó 20-56 Vdc</li>
                  <li>Aprobado por CE</li>
