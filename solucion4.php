<h2>Visión de conjunto.</h2>
<p>Un cliente de Sealevel se especializa en la fabricación petroquímica. Descubrieron que los empleados, cuando trabajan con maquinaria, a menudo utilizan sus instintos en lugar de depender de datos confiables. Inintencionadamente, crearon un riesgo de falla en la fabricación del proceso, lo que contribuyó al daño de la máquina. El equipo dejaba de funcionar durante períodos prolongados, lo que a veces repercutia en resultados catastróficos debido al sobrecalentamiento.</p>

<p>Nuestro cliente se acercó a SEALEVEL en busca de una solución que elimine la interferencia humana y mejore los procedimientos de mantenimiento preventivo. Solicitaron un sistema con informes continuos y precisos que podrían ayudar a programar adecuadamente el servicio de la maquinaria.</p>
<center><img src="imagenes/Soluciones/Solucion4/img1.jpg" width="40%"></center>
<h2>Requisitos clave de la aplicación.</h2>
<ul>
<li>Monitorear el voltaje para determinar el estado y la duración operativa de una máquina.</li>
<li>Interfaz con sensores para controlar la temperatura.</li>
<li>Registre los datos para analizar .</li>
<li>Alerta a través de un mensaje de texto cuando la temperatura de los umbrales se excede.</li>
</ul>
<h2>La solución Sealevel.</h2>
<p>El equipo de ingeniería de Sealevel personalizó un dispositivo de borde SeaConnect 370 IoT para interactuar con sensores de detección de voltaje que monitorean el rendimiento de cada máquina. El SeaConnect 370 estándar cuenta con un onboard 1-Wire Bus, que satisface fácilmente las necesidades de detección de temperatura. Al vincular los dispositivos SeaConnect 370 con una versión con etiqueta privada del software Sealevel SeaCloud, el cliente creó alertas configurables y mantuvo los datos históricos disponibles para su análisis.</p>

<p>Con una gran experiencia en soluciones de comunicaciones críticas, Sealevel está especialmente calificado para comprender la importancia de resultados confiables y precisos. Con algunas modificaciones en un producto estándar, los ingenieros de SEALEVEL entregaron un sistema completo que incrementó la eficiencia, mejoró los procesos de mantenimiento preventivo y, lo más importante, evitó las devastadoras fallas de rendimiento.</p>
