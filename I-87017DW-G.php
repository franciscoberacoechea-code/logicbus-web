<p align="justify">I-87017DW es una interfaz en serie y módulo de entrada analógica de 8 canales Diferencial / 16-Canales Sencillos. El rango de entrada analógica es seleccionable por software y admite +/- 10V, +/- 5V, +/- 1V, +/- 500mV, +/- 150mV y +/- 20mA. El modo diferencial y de final único se selecciona mediante jumpers.</p>

Caracterísiticas:
<ul>
<li>Entrada analógica de 8 canales Diferencial / 16 canales Single-ended.</li>
<li>Conector D-Sub 37.</li>
<li>Protección contra ESD de 4 kV.</li>
<li>Dual Watchdog.</li>
<li>Aislamiento intramódulo de 3000 VDC, campo a lógica.</li>
<li>Un amplio rango de temperatura de funcionamiento: -25 ° C ~ 75 ° C.</li>
<li>Conformidad con la RoHS.</li>
</ul>

