<center><strong>Conmutador Ethernet 10/100 Mbps Industrial no gestionable de 8 puertos. Admite temperaturas de funcionamiento de -40 ° C ~ + 75 ° C.</strong></center><br>


<p>El NS-208A tiene 8 puertos Ethernet que admiten 10/100 Base-TX, con una función de autonegociación de 10 / 100M y función MDI / MDI-X automática. <br>

Todos los puertos Ethernet tienen memorias intermedias de memoria que admiten el mecanismo de almacenar y reenviar, lo que garantiza que los datos se puedan transmitir correctamente. El NS-208A es compatible con estándares de red avanzados para optimizar el rendimiento de la red, reducir los costos de mantenimiento y garantizar la seguridad de la red. <br>

El mecanismo de control de flujo también se negocia. Hay LED de velocidad de enlace / datos para cada puerto para ayudar a solucionar problemas. Los conectores de puerto están blindados RJ-45.</p><BR>

<strong>Caracteristicas</strong>

<ul>
<li>Crossover automático MDI / MDI-X para plug-and-play.</li>
<li>Arquitectura de almacenamiento y reenvío.</li>
<li>Control de flujo de contrapresión Full Duplex IEEE 802.3xy semidúplex.</li>
<li>Carril DIN.</li>
<li>Cada puerto admite una negociación automática de velocidad de 10/100 Mbps.</li>
<li>Admite entrada de alimentación de +12 ~ +48 VDC.</li>
<li>Admite temperaturas de funcionamiento de -40 ° C ~ +75 ° C.li></li>
</ul>
