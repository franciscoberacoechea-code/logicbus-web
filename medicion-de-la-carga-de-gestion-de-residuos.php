<div class="part1">

<article>
  <p><b>Resumen de la aplicaci&oacute;n:</b>
Los contenedores grandes de gestión de residuos están destinados a recoger basura hasta que alcancen una capacidad específica. Una vez que se alcanza esa capacidad, es necesario eliminar el contenido. El uso de celdas de carga ayuda a monitorear el aumento de capacidad del contenedor.
 </p>

<img src="https://www.logicbus.com.mx/imagenes/soluciones-en-la-industria/agricultura/medicion-de-carga-de-gestion-de-residuos.jpg" alt="Aplicacion medicion de carga de gestion de residuos" width="40%">
<div>
  <p><b>C&oacute;mo funciona:</b><br></p>
  <ol>
    <li>Los contenedores de residuos de tamaño industrial pueden contener 50 toneladas. La eliminación del contenido solo se produce una vez que el propio contenedor ha alcanzado su capacidad máxima.</li>
    <li>La instalación de celdas de carga en la base del contenedor monitorea los aumentos en la capacidad del contenedor proporcionando una medición de la carga de desechos.</li>
    <li>En este escenario de aplicación específico, se deben montar cuatro placas de carga de 25 toneladas en la base de cada pata del contenedor mediante dos opciones de montaje.</li>
    <li>La primera opción de montaje es montar el botón de carga encima de una placa de carga en una superficie limpia y nivelada sobre la que se asentará el contenedor. La segunda opción de montaje es montar el botón de carga encima de una placa de carga debajo de cada pie del contenedor.</li>
    <li>A través de cualquier metodología de carga, los datos recopilados por cada celda de carga se pueden transmitir a través de una caja de conexiones sumadora a una pantalla digital o directamente a una PC. </li>
  </ol>
