                    <li class="mb-3">El segundo método es conectar cada celda de carga tipo panqueque de la serie LCF a la caja de conexiones sumadora de 2 a 4 canales IAC200 de FUTEK, que recopilará la carga colectiva de cada celda de carga y luego transmitirá esa salida a una pantalla (IHH500 o IPM650).</li>
                    <li class="mb-3">Estos métodos también pueden automatizarse para hacer sonar una alarma o enviar una notificación cuando el peso del silo alcanza una masa específica (celdas de carga del silo).</li>
