							<strong>Descripción</strong><br>

							<p align="justify">El FBs-CM25E es un módulo de interfaz de Ethernet de la serie FBs-PLC. Éste módulo provee la capacidad a los PLC-FBs para que puedan acceder a otros controladores o dispositivos a través de la red Ethernet activamente (cliente) o pasivamente (servidor). Todos los modelos de ésta serie (MA, MC, MN) pueden ser monitoreados y diagnosticados remotamente mediante Internet usando éste módulo. Mientras está trabajando, éste módulo utiliza el Puerto 4 del CPU para comunicarse con Internet. También provee un puerto (Puerto 3) genérico de RS-232 para aplicaciones periféricas. Mientras se instala el módulo puede ser montado en un riel DIN o se puede ajustar seguramente con tornillos. Sin duda el FBs-CM25E es de gran utilidad para toda forma de comunicación.</p>

							<STRONG>Características:</STRONG>
							<ul>
								<li>Soporta el acceso a múltiples clientes</li>
								<li>Soporta el modo cliente o servidor</li>
								<li>Soporta el protocolo del fabricante o Modbus-TCP</li>
								<li>Control de acceso basado en IP</li>
								<li>Velocidad de transmisión de alta velocidad de 230.4 Kbps para interfaz serial</li>
								<li>Configuración por línea o por red</li>
							</ul>
