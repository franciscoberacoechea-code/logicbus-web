<center><strong>Conmutador de Ethernet 10/100/1000 Base-T industrial no administrado de 8 puertos con entrada de alimentación +12 ~ 48 VDC. Admite temperaturas de funcionamiento de -30 ° C ~ + 70 ° C.</strong></center><br>


<p>El NS-208AG tiene 8 puertos de conmutación Ethernet que admiten 10/100/1000 Base-T, con una función de autonegociación de 10/100 / 1000M y función MDI / MDIX automática. Puede conectar 8 estaciones de trabajo y automáticamente cambia la velocidad de transmisión (10 Mbps o 100 Mbps o 1000 Mbps) para las conexiones correspondientes. El mecanismo de control de flujo también se negocia. Hay LED de velocidad de enlace / datos para cada puerto para ayudar a solucionar problemas. Los conectores de puerto están blindados RJ-45.</p><BR>

<strong>Caracteristicas</strong>

<ul>
<LI>Crossover automático MDI / MDI-X para plug-and-play.</LI>
<LI>Cada puerto admite la negociación automática de velocidad de 10/100 y 1000 Mbps.</LI>
<LI>Arquitectura de almacenamiento y reenvío.</LI>
<LI>Control de flujo de contrapresión Full Duplex IEEE 802.3xy semidúplex.</LI>
<LI>Ancho de banda de memoria de alto rendimiento de 16 Gbps.</LI>
<LI>Entradas de alimentación +12 VDC ~ +48 VDC.</LI>
<LI>Admite temperaturas de funcionamiento de -30 ° C ~ + 70 ° C.</LI>
<LI>Montaje en raíl DIN para uso industrial.</LI>
</ul>
