<center><strong>Módulo de 32 canales de salida digitales aislados de colector abierto, de tipo Sink.</strong></center><br>

<p style="text-align: justify;">El módulo I-87041W / I-87041PW ofrece 32 canales de salida digital, cada uno de ellos con aislamiento fotocupla y admite salida de tipo sink con un colector abierto. La I-87041W / I-87041PW incluye 32 indicadores LED que se pueden usar para monitorear el estado de los canales de salida digital, y hay opciones disponibles para configurar los valores de encendido y seguro. Se proporciona protección de 4 kV ESD y aislamiento intramódulo de 3750 Vrms como estándar. El I-87041W / I-87041PW se puede emparejar con una placa secundaria, como el DN-37-381-A para facilitar el cableado, o el DN-8K32R para la salida de relevo.</p><br>


<strong>Caracteristicas:</strong>
<ul>
<li>Salida de colector abierto de 32 canales</li>
<li>Salida digital tipo sink</li>
<li>Protección contra cortocircuitos, protección contra sobretensiones y protección contra sobrecarga para I-87041PW</li>
<li>Pizarras opcionales</li>
<li>Protección contra ESD de 4 kV</li>
<li>Aislamiento intramódulo de 3750 Vrms</li>
<li>Valor de encendido configurable</li>
<li>Valor seguro configurable</li>
<li>RoHS</li>
<li>Amplia gama de temperaturas de funcionamiento: -25 ~ + 75 ° C</li>
</ul>



