                <p class="light-black font-weight-bold">¿Qué son los sistemas de freno por cable?</p>

                <p class="light-black">Los sistemas de freno por cable (BbW) son una tecnología emergente que se utiliza actualmente en los coches de carreras de Fórmula 1 y en algunos vehículos de lujo. El sistema, que es más rápido y preciso que los frenos tradicionales, controla los frenos de un coche electrónicamente.</p>

                <p class="light-black font-weight-bold">¿Cómo funcionan los sistemas BbW?</p>
                <p class="light-black">No existe un vínculo mecánico físico entre las pinzas y el pedal de freno. En cambio, el pedal funciona como un simulador. Cuando un conductor lo pisa, la fuerza se mide mediante sensores que comunican inmediatamente la información de frenado a la unidad de control de frenos (BCU). La BCU procesa esta información y envía un comando a los actuadores electrohidráulicos, que convierten la señal de comando en presión hidráulica de la pinza/fuerza de sujeción, que a su vez reduce la velocidad o detiene el vehículo.</p>

                <p class="light-black font-weight-bold">¿Cómo se utilizan los sensores de fuerza en la validación del diseño de freno por cable?</p>
                <p class="light-black">Si bien los sistemas BbW aún no se han introducido con éxito en la producción en serie, se espera que se conviertan en algo habitual en un futuro próximo. A medida que los fabricantes de automóviles diseñan sus propios sistemas de freno por cable, tienen que abordar cuestiones de costo, confiabilidad y seguridad. Esto hace que las pruebas rigurosas de durabilidad y fatiga sean aún más cruciales. FUTEK respalda a los fabricantes de sistemas BbW al ofrecer sensores optimizados para las pruebas de pedales y pinzas de freno. Esta nota de aplicación ilustra cómo se pueden aplicar las celdas de carga y los sensores de fuerza para la validación y calibración del diseño.</p>

                <p class="light-black">Cumplimiento de normas de la industria automotriz</p>
