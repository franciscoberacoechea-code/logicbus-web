<center><strong>Switch ethernet con 8 puertos capa-2 con 2 puertos de fibra optica y 6 puertos ethernet base-T, conector FT, multi-modo.</strong></center><br>


<p>El MSM-508FT es un conmutador administrado Industrial Ethernet Layer 2 de 8 puertos con fibra de 2 puertos (conector ST; modo múltiple) que asegura la transmisión de datos mediante el uso de transmisión de fibra óptica para proporcionar inmunidad contra interferencia EMI / RFI. Se usa Ethernet para transmitir una señal de hasta 2 km (6,600 pies) y es la solución perfecta para aplicaciones donde la transmisión debe protegerse contra la exposición eléctrica, sobrevoltajes, rayos o corrosión química.<br><br>

Los puertos de fibra de MSM-508FT funcionan en modo dúplex medio o completo. En modo dúplex completo, el rango es de 2 km con cables de fibra de 62.5 / 125µm; en modo semidúplex, el rango es de 412 m con cables de fibra de 62.5 / 125µm. El puerto Ethernet de MSM-508FT admite la función de autonegociación 10 / 100M y la función MDI / MDIX automática.<br><br>

Se puede gestionar a través del puerto RS-232 a través de una consola serie o un puerto Ethernet mediante telnet o navegador web. Además, el conmutador admite muchas funciones gestionadas potentes, como la VLAN basada en etiquetas 802.1Q, la VLAN basada en puertos, la QoS 802.1p (calidad de servicio), la interconexión de puertos, el árbol de expansión, las pruebas de cables y la duplicación de puertos. La técnica integrada Cyber-Ring ICP DAS permite que varios interruptores se coloquen en un anillo redundante. El conmutador detecta y se recupera de una falla de enlace de fibra o cobre dentro de aproximadamente 50 ms, para la mayoría de las aplicaciones un proceso sin interrupciones. Compatible con Modbus / TCP, Modbus / RTU y OPC, la aplicación SCADA puede monitorear el estado de Ethernet y el puerto de fibra con protocolo Modbus o OPC.<br><br>

MSM-508FT proporciona dos entradas de alimentación que se pueden conectar simultáneamente a fuentes de alimentación de CC en vivo. Si una de las entradas de alimentación falla, la otra fuente en vivo actúa como una copia de seguridad para admitir automáticamente las necesidades de energía del MSM-508FT. Y, la facilidad de salida de retransmisión puede entregar una señal de advertencia mientras falla la alimentación dual o el enlace de red.</p><BR>

