<p align="justify">El puerto de E / S digital de 20 mA consta de 12 líneas individuales compatibles con TTL (Ch, # 1 ... # 8), cada una de las cuales se puede configurar como: bit de entrada digital, bit de salida digital, salida de control, salida de reloj 43 . Cuando se configura como una entrada, se puede usar un canal para detectar una alta digital (2.1 a 30 voltios) o baja digital (-10V a .65Volts). Cuando se configura como una salida, un canal puede configurarse como alto (por ejemplo,> 2 V) o bajo (por ejemplo, < 0,8 V). Estos pines de E / S están protegidos contra cortocircuitos contra altas tensiones de hasta 32.0V y hasta -16.0V.
<br><br>
El puerto de E / S digital sumidero de 200 mA consta de 16 líneas individuales compatibles con TTL (Ch # 9 ... # 24), cada una de las cuales se puede configurar como: bit de entrada o salida 44 . Cuando se configura como una entrada, se puede usar un canal para detectar una alta digital (2.1 a 30 voltios) o baja digital (-10V a .65Volts). Cuando se configura como una salida, un canal puede configurarse como alto (por ejemplo,> 2 V) o bajo (por ejemplo, < 0,8 V). Estos pines de E / S están protegidos contra cortocircuitos contra altas tensiones de hasta 32.0V y hasta -16.0V.</p>

<strong>Caracteristicas:</strong>
<ul>
<li>La tarjeta i460 se conecta a una jaula de tarjetas instruNet i4xx de 4 a 16 ranuras , que a su vez se conecta a una computadora con Windows</li>
<li>12x E / S digital universal (receptor de 20 mA, -10V..30V)</li>
<li>16x I / O digital (200mA disipador, -10V..30V)</li>
</ul><br><br>

