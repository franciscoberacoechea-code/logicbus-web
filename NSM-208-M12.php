<center><strong>EN50155 Switch Ethernet no administrado M12 de 8 puertos diseñado para aplicaciones industriales en entornos hostiles. Incluye M12D-4P-IP68 x 8, A-CAP-M12M x 8, M12A-5P-IP68 y A-CAP-M12F x 1. Admite temperaturas de funcionamiento de -40 ~ + 75 ° C (-40F ~ 167F).</strong></center><br>


<p>El NSM-208-M12 está diseñado para aplicaciones industriales en entornos hostiles. Los conectores M12 aseguran la estanqueidad, proporcionan conexiones robustas y garantizan un funcionamiento confiable; incluso para aplicaciones que están sometidas a altas vibraciones y golpes.<br>

El conmutador Ethernet es compatible con IEEE 802.3 / 802.3u / 802 / 3x con 10 / 100M, full / half-duplex, MDI / MDI-X autodetección, y proporciona una solución económica para su red Ethernet industrial. <br>

El NSM-208-M12 proporciona una amplia gama de potencia de 12 a 53 V CC para adaptarse a los estándares de potencia comunes que se encuentran en la automatización industrial, sin convertidores de potencia externos. La amplia entrada de potencia reduce los costos de instalación y mantenimiento.</p><BR>

<strong>Caracteristicas</strong>

<ul>
<li>Cada puerto admite una negociación automática de velocidad de 10/100 Mbps.</li>
<li>Conector tipo M12 de 8 puertos 10/100 Mbps con protección IP40.</li>
<li>EN50155 / 50121-3-2 / 50121-4, y NEMA TS2 cumple.</li>
<li>Crossover automático MDI / MDI-X para plug-and-play.</li>
<li>Arquitectura de almacenamiento y reenvío.</li>
<li>Control de flujo de contrapresión Full Duplex IEEE 802.3xy semidúplex.</li>
<li>Admite temperaturas de funcionamiento de -40 ° C ~ +75 ° C.</li>
</ul>
