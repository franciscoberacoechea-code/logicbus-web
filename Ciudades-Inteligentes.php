<h2>D.  Casas Inteligentes</h2>
Dentro de la evolución inteligente también abarca a las casas, y en este sector lo que se busca integrar en la mayoría de los casos es:
<li>Aumentar la seguridad.</li>
<li>Incrementar el confort.</li>
<li>Mejorar las comunicaciones.</li>
<li>Facilitar el control integral de la casa</li>
<li>Gestionar la energía, controlando su gasto y ahorrando dinero.</li>
<li>Ofrecer nuevos servicios.</li>
<p align="justify">Antes de continuar avanzando con estos conceptos, explicaremos la diferencia de la “Domotica” y “TIC”:
La palabra Domótica, viene del latín “domus” que significa casa o domicilio, y del griego “automática”, de donde deriva nuestra palabra “automatización”. Lo cierto es que este término genera confusión en la sociedad actual y se están barajando diferentes conceptos para definir, lo que en realidad llamamos la introducción de las Tecnologías de la Información y Comunicación<br>
(TIC) en el hogar. Las tecnologías de las que hablamos a grandes rasgos se orientan a dos propósitos fundamentales: uno es la automatización de todas las acciones posibles que se puedan llevar a cabo en el hogar, y, el otro, es el de intercomunicar esas acciones entre sí y con el exterior.<br>
Ambos términos están muy ligados entre sí, ya que podemos hablar también de IoT, que es darle internet a las cosas, y con esto intercomunicarlos para dar como resultado un comportamiento autónomo y automatizado. Por lo anterior, solo hablaremos de proyectos más relevantes o iniciativas que tenemos para desarrollar.</p>

