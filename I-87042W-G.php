<center><strong>Módulo de 16 entradas digitales aisladas y 16 salidas digitales aisladas, cada una con aislamiento de Fotocupla, soporta salida tipo Sink con protección de cortocircuito.</strong></center><br>

<p style="text-align: justify;">I-87042W ofrece 16 canales para entrada digital y 16 canales para salida digital.Cada una de las características es el aislamiento de fotocupla.I-87042W admite salida tipo sumidero con protección contra cortocircuitos. Hay opciones para el valor de encendido y el valor seguro para su consideración. Acerca de la Entrada, puede elegir de tipo sink o source mediante conexión por cable. Todos los canales pueden usarse como contador de 16 bits. I-87042W también tiene 32 indicadores LED para el estado del canal. La protección 4KV ESD y el aislamiento intramódulo de 3750VDC son estándar.</p><br>


<strong>Caracteristicas:</strong>
<ul>
<li>Entrada digital para tipo sink o source.</li>
<li>Salidas digitales para tipo sink.</li>
<li>Configuración del valor de encendido.</li>
<li>Configuración de valor seguro</li>
<li>Aislamiento fotocupla.</li>
<li>4KV ESD Protection.</li>
<li>Aislamiento intramódulo de 3750 VDC.</li>
<li>RoHS</li>
<li>Amplia gama de temperaturas de funcionamiento: -25 ~ + 75 ° C</li>
</ul>



