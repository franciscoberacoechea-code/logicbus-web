<p>El GW-7238D es una puerta de enlace que proporciona conversión entre J1939 y el protocolo Modbus TCP / RTU. Para la red J1939, el GW-7238D es compatible con PDU1, PDU2, tipo específico de transmisión y destino de mensajes J1939. Para la red Modbus TCP / RTU, el GW-7238D es un servidor Modbus TCP / esclavo RTU para responder a la solicitud del cliente Modbus TCP / RTU maestro. El software de utilidad se proporciona para que los usuarios configuren J1939 y Modbus TCP / RTU en el GW-7238D. Los campos de aplicación pueden ser aplicaciones de trenes de potencia Diesel, redes en vehículos para camiones y autobuses, etc.

</p>

<strong>Caracteristicas:</strong>
<ul>
<li>Proporciona LED de indicación PWR / J1939 / MODBUS</li>
<li>Una función de puente para seleccionar 120 Ohms resistente</li>
<li>Watchdog inside</li>
<li>Transmisión y recepción de todo tipo de mensajes J1939, incluidos PDU1, PDU2, difusión y destino específico</li>
<li>J1939 Protocolo de transporte para la transmisión y recepción de mensajes de gran tamaño (9 - 1785 bytes)</li>
<li>Admite BAM de mensaje de gestión de conexión</li>
<li>Gestión de direcciones de red</li>
<li>Admite interfaces RS-232, RS-485 y Ethernet</li>
<li>Velocidades de baudios configurables de 2400, 4800, 9600, 19200, 38400, 57600, 115200 bps</li>
<li>Admite el protocolo Modbus TCP server / RTU esclavo</li>
<li>Configurable para Modbus Network ID (1 ~ 250)</li>
<li>Permite 5 accesos simultáneos de clientes Modbus / TCP</li>
<li>Admite el código de función 03/04/06/16 de las funciones Modbus para leer y escribir mensajes J1939</li>
</ul>

