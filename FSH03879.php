<strong><center>LLB130, 25 lb, botón de carga subminiatura, Material - 17-4 PH S.S., Cumple con RoHS, 34 Awg 4 Cable trenzado conductor, 5 pies de largo</center></strong><br>

<p>El botón de carga en miniatura LLB130 de FUTEK  está diseñado para aplicaciones de compresión en línea o de prensa. La LLB130 está hecha de un robusto acero inoxidable 17-4 PH con un diámetro exterior subminiatura de 0.38 pulgadas [9.5 mm].
<br><br>
Aunque tradicionalmente los botones de carga en miniatura no son conocidos por su alta precisión, los ingenieros de FUTEK han disipado este concepto al mejorar continuamente la precisión de este producto. Estas celdas de carga alcanzan una gran precisión y rigidez con una no linealidad de ± 0.5% y una desviación de 0.0005 en [0.013 mm] nominal. También encontrará opciones disponibles para salidas externas coincidentes.
<br><br>
El botón de carga en miniatura LLB130 estándar se puede modificar o personalizar para satisfacer sus requisitos y la mayoría de las capacidades están en nuestro inventario, lo que las hace disponibles para una entrega rápida. Similar a toda nuestra línea de productos de Celdas de Carga, este modelo se fabrica en los Estados Unidos y utiliza tecnología de galga extensiométrica de lámina metálica.
</p><br>

<strong>Características:</strong>
<ul>
<li>Compensación de temperatura totalmente interna (sin circuito de acondicionamiento externo)</li>
<li>Subminiatura / peso ligero</li>
<li>Baja deflexión / respuesta rápida</li>
<li>Construcción de acero inoxidable 17-4 PH.</li>
<li>Para uso en compresión</li>
<li>Utiliza tecnología de galga extensible de lámina metálica.</li>
<li>Se adhiere a la directiva RoHS 2011/65 / EU</li>
<li>Accesorios e instrumentos relacionados disponibles</li>
</ul>

