<p>El GW-7434D puede ser un dispositivo maestro DeviceNet en el bus CAN sobre una red DeviceNet.  Es un "set de conexión maestra predefinida", y soporta funciones de servidor para comunicación con dispositivos esclavos.  Además, también se incluye el software para usuarios para que puedan configurar los parámetros del dispositivo GW-7434D.</p><BR>

<strong>Caracteristicas:</strong>
<ul>
<li>MAC ID maestro programable DeviceNet</li>
<li>Velocidad de transferencia programable 125K, 250K, 500K</li>
<li>Soporta hasta 63 dispositivos DeviceNet máximo</li>
<li>El número de fragmento máximo es hasta 64</li>
<li>Soporta modo de operación de E/S: poll, bit-strobe y cambio de estado/cíclico</li>
<li>Soporta la adición y eliminación de dispositivos en la red</li>
<li>Soporta el arranque automático para comunicarse con dispositivos esclavos</li>
<li>Convierte un único Modbus/TCP a multi Modbus/RTU</li>
<li>Acceso permitido de multicliente al mismo tiempo</li>
</ul>

<strong>Aplicaciones:</strong>
<ul>
<li>Sistemas de control</li>
<li>Automatización de edificios</li>
<li>Automatización de fábricas</li>
<li>Adquisición de datos distribuidos</li>
</ul>


