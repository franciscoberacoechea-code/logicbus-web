<p>El Siglent SHS1102 es un osciloscopio digital de doble canal con una gran pantalla a color de 5,7 pulgadas y es lo suficientemente portátil para transportarse entre diferentes escenarios de prueba.
<br>
Es adecuado para su uso en una amplia gama de diferentes aplicaciones incluyendo pruebas de electrónica de potencia (fuentes de alimentación conmutadas, inversores, convertidores e iluminación), energía eólica, energía fotovoltaica y otras pruebas de equipos de energía nuevos, pruebas electrónicas automotrices, pruebas de vehículos eléctricos, industriales pruebas de sistema de energía, pruebas de campo, aplicaciones educativas y más.
<br><br>
Para ayudar a mejorar las pruebas y la seguridad, la serie SHS1000 viene con la tecnología incorporada IsolatedChannel, una técnica patentada única utilizada por Siglent para proporcionar aislamiento de la tierra y el aislamiento entre los canales.
<br>
Este probador en particular presenta un ancho de banda de 100MHz, velocidad de muestreo en tiempo real de 1GSa / s, velocidad de muestreo equivalente de 50GSa / sy profundidad de memoria de 2Mpts.
<br>
También se integra en el SHS1102 un multímetro totalmente funcional que es capaz de medir el voltaje de CC / CA, corriente de CC / CA, resistencia, capacitancia, diodo y continuidad.
</p><BR>

