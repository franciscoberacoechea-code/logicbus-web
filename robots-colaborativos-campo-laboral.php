      <h2 class="subtitle blue text-center mt-5 mb-3">Inteligencia Artificial (IA)</h2>

      <p>El término AI fue acuñado por John McCarthy, un informático estadounidense, en 1956 durante la Conferencia de Dartmouth, donde nació la disciplina. Hoy en día, es un término general que abarca todo, desde la automatización de procesos robóticos hasta la robótica actual. Ha ganado prominencia recientemente debido, en parte, a los grandes volúmenes de datos, o al aumento de velocidad, tamaño y variedad de datos que las empresas están recopilando. AI puede realizar tareas tales como identificar patrones en los datos, tareas altamente repetitivas de manera más eficiente que los seres humanos, lo que permite a las empresas <a class="blue link-orange" href="https://www.logicbus.com.mx/dasylab"> obtener más información sobre sus datos</a></p>

      <h2 class="subtitle blue text-center mt-5 mb-3">Robots colaborativos</h2>

      <p>La aplicación más común de la IA esta presente en los robots colaborativos o CoRobots, que son robots que trabajan a la par con las personas dentro de una planta industrial, abarcando tareas complejas y difíciles para el humano, ofreciendo una mayor seguridad y disminuyendo los esfuerzos puestos en las actividades, esto se debe a la capacidad sensorial añadida a estos nuevos equipos. Para muchos casos la idea, la idea de desplazamiento se ha convertido en un proceso de integración y balance, pretendiendo asegurar la calidad y alcanzar las metas de producción.</p>
      <p>La nueva generación de robots colaborativos no solo favorecerá el diseño de entornos laborales automatizados más seguros, sino que ayudara a que las empresas sean más competitivas en términos de productividad, cumplimiento de órdenes, flexibilidad, calidad y otros factores clave como la trazabilidad. El robot colaborativo más común utilizado en las grandes industrias son los famosos brazos robóticos, ayudando a llevar a cabo tareas repetitivas a una velocidad predeterminada de acuerdo a la tarea para su aplicación. Además de facilitar el transportar o sostener objetos pesados, un ejemplo claro del uso de CoRobots, es en la industria automotriz o la manufactura.</p>

