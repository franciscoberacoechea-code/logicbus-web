  <p><b>C&oacute;mo funciona:</b><br></p>
  <ol>
    <li style="color: black;">Los controles cíclicos de helicóptero (joysticks), son responsables para los movimientos lateral y longitudinal de la aeronave.</li>
    <li style="color: black;">Para asegurarnos de que ese mecanismo funciona apropiadamente, los ingenieros de calidad pueden instalar el sensor multiaxial <strong><a href="https://tienda.logicbus.com.mx/MAU300_c_1948.html">MAU300</a></strong> dentro de cada una de las direcciones del joystick.</li>
