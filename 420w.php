<p align="justify">Controle y monitoree 16 entradas aisladas ópticamente y 8 salidas de relé de forma C (SPDT) a través de una red inalámbrica con el SeaI/O-420W. Las entradas pueden oscilar entre 5 y 30V DC, mientras que los relés de forma C proporcionan cierres de interruptor de hasta 60V DC a 2A. Las entradas y salidas se agrupan en segmentos de cuatro bits que comparten un común para facilitar el cableado a través de bloques de terminales extraíbles de 3.5mm. El SeaI/O-420W se alimenta de su fuente de 9-30V DC, o seleccione entre una variedad de opciones de fuente de alimentación Sealevel.
<br><br>
Comuníquese con el SeaI/O-420W a través de redes Wi-Fi (802.11b y 802.11g) usando las bibliotecas de software Sealevel SeaMAX API o use cualquier dispositivo compatible con Modbus TCP. Los controladores y las utilidades del <strong><a href="software-seamax" target="_blank">software SeaMAX </a></strong> de Sealevel facilitan la instalación y el funcionamiento con los sistemas operativos Microsoft Windows 10 y 8. Las funciones de seguridad incluyen WEP y los últimos estándares de encriptación WPA-TKIP y WPA2-AES.
<br><br>
Amplíe su red de E /S con los productos de la serie SeaI/O N. Los módulos SeaI/O están disponibles con relés Reed y Forma C , entradas ópticamente aisladas, interfaces TTL , funcionalidad A/D y D/A. Se pueden agregar hasta 246 módulos de expansión adicionales utilizando conectores de paso convenientes.
