<center><strong>Convertidor/Puerta de enlace (Gateway) HART a Modbus TCP. Opera como HART maestro para acceder dispositivos HART esclavos desde dispositivos Modbus TCP maestros. Montaje en Riel DIN o pared. Temp. en operación -25 a 75°C. Requiere alimentación 10~30Vdc.</strong></center><br>

<p>El HRT-711 Modbus TCP a HART Gateway está especialmente diseñado para el dispositivo maestro del protocolo HART. Permite que el dispositivo maestro Modbus/TCP acceda a los dispositivos esclavos HART. Estos dispositivos HART pueden ser un transmisor, un actuador, un dispositivo de salida de corriente, etc. Además, también ofrecemos el software de utilidad para que los usuarios configuren el HRT-711. Al usar este módulo, los usuarios pueden integrar sus dispositivos HART en la red Modbus fácilmente.</p>
<ul>
<li>Soporte HART Marco corto/largo</li>
<li>Admite el modo de ráfaga HART</li>
<li>Permitir dos Maestros HART</li>
<li>Soporta formato Modbus/TCP</li>
<li>Soporte Modbus Slave/HART Master Mode</li>
<li>Soporte de actualización de firmware a través del puerto Com</li>
<li>Soporte de reemplazo en línea de dispositivos HART</li>
<li>El soporte adquiere la dirección de trama larga automáticamente</li>
<li>Proporcionar indicadores LED</li>
<li>Perro guardián incorporado</li>
<li>Protección ESD 4KV</li>
</ul>
<p>El protocolo HART (transductor remoto direccionable de autopista) utiliza el estándar de codificación por desplazamiento de frecuencia (FSK) Bell 202 para superponer señales de comunicación digital en la corriente de bucle de 4-20 mA que se muestra en la figura siguiente. HART se comunica a 1200 bps sin interrumpir e interferir con la señal de 4-20 mA y permite que una aplicación host (maestra) envíe/reciba información digital desde un dispositivo de campo inteligente. La señal de 4-20 mA comunica el valor medido primario, el estándar de la industria más rápido y confiable. La señal digital se puede usar para obtener información adicional del dispositivo, incluido el estado del dispositivo, diagnósticos, valores medidos o calculados adicionales, etc. Por lo tanto, la comunicación HART que incluye información analógica y digital proporciona una solución de comunicación de campo completa muy robusta y de bajo costo que es fácil de usar y configurar. HART es un protocolo maestro/esclavo que proporciona hasta dos maestros (primario y secundario) y el maestro secundario, como la computadora de mano, puede usarse para monitorear/controlar la información del bus HART. HART se puede usar en varios modos, como punto a punto o multipunto para comunicar información a/desde instrumentos de campo inteligentes y sistemas de control o monitoreo central. La siguiente es la descripción de dos modos principales de operación HART.</p>

Características:
<ul>
<li>Relativamente fácil de entender y usar, el protocolo HART proporciona acceso a la gran cantidad de información adicional (variables, diagnósticos, calibración, etc.)</li>
<li>HART es una solución sin riesgo para una comunicación de campo mejorada</li>
<li>Compatibilidad con cableado estándar de 4-20 mA</li>
<li>Transmisión simultánea de datos digitales.</li>
<li>Reducción de riesgos a través de un protocolo altamente preciso y robusto.</li>
<li>Aumenta la disponibilidad de la planta</li>
<li>Reduce los costos de mantenimiento</li>
<li>Mejorar el cumplimiento regulatorio</li>
</ul>

Utilería:
