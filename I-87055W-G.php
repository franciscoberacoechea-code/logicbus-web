<center><strong>Módulo de 8 canales de entrada digitales no aislados y 8 canales de salida no aislados, con contadores de 16 bits.</strong></center><br>

<p style="text-align: justify;">El módulo I-87055W ofrece 8 canales de entrada digital no aislados y 8 canales de salida digital no aislados. Todos los canales de Entrada Digital también pueden usarse como contadores de 16 bits. El I-87055W admite salida digital tipo sink y entrada digital con conexiones de contacto seco. El I-87055W incluye 16 indicadores LED que se pueden usar para monitorear el estado de los canales de Entrada Digital y Salida Digital, y hay opciones disponibles para configurar los valores de encendido y seguro. La protección ESD de 4 kV se proporciona para los canales de Entrada Digital y Salida Digital como estándar.</p><br>


<strong>Caracteristicas:</strong>
<ul>
<li>Entrada digital no aislada de 8 canales y salida digital no aislada de 8 canales</li>
<li>Canales de salida digital tipo sink</li>
<li>Canales de entrada digital de contacto seco</li>
<li>Todos los canales de entrada digital se pueden usar como contadores de 16 bits</li>
<li>Todos los canales son no aislados</li>
<li>Protección contra ESD de 4 kV</li>
<li>Valor de encendido configurable</li>
<li>Valor seguro configurable</li>
<li>RoHS</li>
<li>Amplio rango de temperatura de funcionamiento: -25 a + 75 ° C</li>
</ul>



