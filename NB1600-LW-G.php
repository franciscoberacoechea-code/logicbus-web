<p>El Punto de acceso inalámbrico a Internet (WIAP) proporciona acceso inalámbrico a Internet para otros dispositivos. Con la función Multi-SSID se pueden operar varias redes WiFi separadas al mismo tiempo. 
En la configuración multi-WAN, el dispositivo funciona como un enrutador de menor costo con retroceso automático en caso de una falla. En este caso, la interfaz WiFi está configurada como un cliente y un puerto Ethernet está conectado a una red local.
<br>
El receptor GPS integrado le permite ubicar la posición del dispositivo con una alta precisión o usar la señal GPS como base de tiempo. La integración en servicios de mapas como Google Maps le permite rastrear el dispositivo si está montado en un equipo en movimiento.
<br>
En su rol de servidor de dispositivos, el NB1600 convierte tanto la interfaz serial como la interfaz USB a IP, permitiendo el acceso remoto a estas interfaces. Cualquier PC con conexión IP al enrutador puede usar el dispositivo remoto USB o RS-232 como si estuviera directamente conectado. Esta configuración permite utilizar el controlador original. 
Las E / S digitales se pueden configurar mediante dispositivos locales o remotos. Según las modificaciones del estado del puerto de entrada, las aplicaciones pueden ser informadas y, por ejemplo, se envía un SMS a un grupo de números.
<br>
El SDK permite a los usuarios programar el NB1600 con un simple script e implementar todo tipo de aplicaciones. El preprocesamiento se puede hacer directamente en el enrutador, ahorrando así un IPC adicional.
<br>
Otras características y servicios son: servidor DHCP, proxy DNS, agente DNS dinámico, agente SNMP, servidor Telnet, servidor SSH, servidor web, correo electrónico y SMS. El enrutador es operado por el administrador web o por la línea de comandos. 
Las actualizaciones de firmware y configuración se pueden realizar fácilmente desde el control remoto de una manera segura. La interfaz SNMP permite la integración del enrutador en un sistema de administración de red para supervisión.
</p><br>

