<h2>Caracteristicas</h2><br>

<p align="justify">La serie VP-2117 de ViewPAC es el ISaGRAF PAC con pantalla gráfica y teclado. Está equipado con una CPU 80186 (16 bits y 80 MHz) con un sistema operativo MiniOS7, 3 ranuras de E / S, una pantalla LCD STN, un teclado de goma y varias conexiones, incluidas Ethernet y RS-232/485.</p>

<strong>El ViewPAC - VP-2117 es compatible con ISaGRAF</strong>
<ul>
<li>IEC 61131-3 Lenguajes de programación PLC estándar abiertos (LD, FBD, SFC, ST, IL, FC) + Diagrama de flujo (FC)</li>
<li>Escaneo automático de E / S</li>
<li>Depuración / control / monitoreo en línea, simulación fuera de línea</li>
<li>HMI gráfico simple</li>
</ul>

<p align="justify">Su sistema operativo, MiniOS7, puede arrancar en muy poco tiempo (0.4 ~ 0.8 segundos). Tiene una función de diagnóstico de hardware integrada y admite la gama completa de funciones necesarias para acceder a todos los módulos de E / S de la serie I-8K e I-87K de alto perfil, como DI, DO, DI / DO, AI, AO, Contador / Frecuencia, módulos de control de movimiento, etc. Los usuarios también pueden elegir módulos de E / S remotas RS-485 (serie I-7000) o unidades de expansión (RU-87Pn o I-87Kn) conectadas con I / 87K serie de alto perfil I / O módulos.<br />
En comparación con las soluciones HMI + PLC tradicionales, ViewPAC reduce el costo general del sistema, el espacio y le ofrece todas las mejores características de los HMI y PLC.</p>

<strong>Caracterisiticas del software</strong>
<ul>
<li>Sistema operativo integrado MiniOS7 (similar a DOS)</li>
<li>ISaGRAF Ver.3 SoftLogic Inside</li>
<li>Compatible con el estándar IEC 61131-3</li>
<li>Admite funciones de gráficos y teclado</li>
<li>Acepta max. Tamaño del código ISaGRAF de 64 KB</li>
</ul>
<strong>Caracteristicas del Hardware</strong>
<ul>
<li>80186 CPU (16 bits y 80 MHz)</li>
<li>768 KB SRAM y 512 KB Flash</li>
<li>Panel frontal compatible con IP65</li>
<li>Teclado de caucho</li>
<li>STN LCD con fuentes inglesas y chinas</li>
<li>3 ranuras de expansión de E / S (admiten módulos de E / S de alto perfil)</li>
<li>64 MB de memoria NAND para almacenamiento de datos</li>
<li>Puerto Ethernet 10 / 100M</li>
<li>3 puertos serie (RS-232, RS-485)</li>
</ul>

<strong> Aplicaciones:</strong>
<p align="justify">Monitoreo ambiental, automatización de fábrica, sistema de gestión de edificios, control de máquinas industriales, etc.</p>
