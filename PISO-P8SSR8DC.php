<center><strong>8 entradas digitales aisladas y 8 tarjetas de salida de relés. Incluye el conector CA-4002 D-Sub.</strong></center><br>


<p>El PISO-P8R8 es una placa de interfaz de entrada / salida aislada de 8 canales para las computadoras con bus PCI. El PISO-P8R8 proporciona 8 salidas de relé electromecánicas y 8 entradas ópticamente aisladas, mientras que PISO-P8SSR8AC y PISO-P8SSR8DC se pueden usar en varios aplicaciones que incluyen cierre de contacto, detección de voltaje externo, detección de interruptor externo y conmutación de carga y diseñado para un conector D-Sub de 37 pines. Se puede instalar en una ranura PCI de 5 V y puede admitir verdadero "Plug & Play".
</p><BR><br>

<strong>Caracteristicas</strong>

<ul>
<li>8 canales de salida SSR</li>
<li>8 canales de entrada digital óptica aislada</li>
<li>Entrada de señal CC con filtro o filtro W / O</li>
<li>Entrada de señal de CA con filtro</li>
</ul><br>

