<strong>Aplicaciones</strong><br>
<p align="justify">El switch i-Snail-S provee un método de monitoreo efectivo y exacto para el estado encendido/apagado de cargas eléctricas, incluyendo ventiladores, bombas, motores, calentadores y virtualmente cualquier dispositivo alimentado con corriente alterna.<br>
La salida digital (on/off) provee un cierre de contacto seco, normalmente abierto que puede hacer interfaz a PLCs, paneles DDC o relevadores de contol.</p><br>

<strong>Características:</strong>
<ul>
<li>Encendido bajo (menos de 0.150 A)</li>
<li>Histéresis y circuitería anti-transitoria elimina vibración y falsa conmutación</li>
<li>Cableado Fácil</li>
<li>Cubierta dura</li>
<li>Bajo Costo</li>
</ul><br><br>

<strong>Descripcion</strong><br>
<p align="justify">El i-Snail-S sirve como un sensor de carga Go/No-Goultra sensitivo. El relevador de contacto seco (normalmente abierto) cierra cuando una mínima cantidad (150mA) de corriente AC está fluyendo a través de su línea monitoreada. El dispositivo es ideal para monitorear el estado de ventiladores, motores, bombas, calentadores o cualquier dispositivo que sea alimentado por AC, incluyendo cargas pequeñas y grandes.
La salida es un relevador de estado sólido bidireccional con un cambio pequeño en la resistencia de menos de 4 ohms. La salida puede hacer interfaz con PLCs, paneles DDC u otros relevadores.
La histéresis avanzada y la detección de circuitería transitora previene la vibración y la falsa conmutación debido a picos de la línea.
El i-Snail-S contiene una cubierta dura con un bloque de terminales de barrera integrados o cables de 6" para un cableado fácil. El i-Snail-S tiene detección de circuitería avanzada que habilita un switch de características "ideales". La salida se enciende con una curva de conmutación tipo "brick wall".<br><br>
