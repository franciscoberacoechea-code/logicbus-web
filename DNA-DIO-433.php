      <td colspan="2"><div align="justify">The DNA-DIO-433 is a 32 channel, digital output boards compatible with &ldquo;Cube&rdquo; series chassis. Each channel is configured as a current source and switches voltages between 3.3 and 36 VDC. Each channel is rated for continuous operation at 600 mA with an output voltage drop of less than 550 mV. The DNA-DIO-433 is an ideal digital output interface in a wide variety of data acquisition and control applications.<br>
          <br>
          As part of Guardian series, the DNA-DIO-433 not only controls the digital outputs, it also allows monitoring of each channel&rsquo;s output voltage and current. This allows the application to detect and flag short and open circuits as well as other &ldquo;suspicious&rdquo; behavior.<br>
          <br>
          The Guardian advantage also includes programmable overcurrent protection. The user may select the current and duration of overload (as short as 10 mS) required before the channel is shut down. Each board provides 350 Vrms isolation and update rates to 1 kHz.<br>
          <br>
          Each channel offers a pulse-width-modulated (PWM) &ldquo;soft-start/stop&rdquo; capability. This allows power to be applied/removed gradually, greatly increasing the reliability of devices like incandescent bulbs where thermal shock reduces life expectancy.<br>
          <br>
      The DNA-DIO-433 is fully supported by the UEIDAQ Framework which provides a simple and complete software interface to all popular programming languages, operating systems and data acquisition and control applications (e.g. LabVIEW, DASYLab, MATLAB).</div></td>
