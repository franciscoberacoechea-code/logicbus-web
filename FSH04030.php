<p>El modelo LCB400 es una celda de carga de extremo de barra (tensión/compresión) diseñada para aplicaciones que involucran actuadores en línea o gatos hidráulicos con roscas macho/hembra. El modelo estándar de Celda de carga de extremo de barra LCB400 (Tensión/Compresión) tiene roscas macho/hembra, usa un aluminio ligero 2024 para capacidades inferiores y un robusto acero inoxidable 17-4 para capacidades superiores. Este modelo es adecuado para los requisitos de capacidad de rango medio a alto (1,000 lb - 10,000 lb). Para cualquier aplicación que requiera un rango de capacidad más alto, consulte la LCB450.
<br><br>
Esta célula de carga de extremo de barra (tensión/compresión) tiene una alta precisión y una gran rigidez. Tiene una no linealidad de ± 0.5% y una deflexión de 0.001” nominal. La Celda de Carga de Extremo de Varilla LCB400 (Tensión/Compresión) se puede modificar o personalizar para cumplir con sus requisitos y utiliza tecnología de galga extensiométrica de lámina metálica.</p>

<strong>Características:</strong><br>
<ul>
<li>Peso: 8 oz - 20 oz.</li>
<li>Baja deflexión.</li>
<li>Receptáculo Bendix.</li>
<li>Conector de acoplamiento opcional.</li>
<li>Aluminio 2024 o construcción de acero inoxidable 17-4.</li>
<li>Tanto en tensión como en compresión.</li>
<li>Aplicaciones de rango medio a alto rango de capacidad.</li>
<li>Utiliza tecnología de medidor de deformación de lámina metálica.</li>
</ul>

