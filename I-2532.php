<center><strong>Convertidor CAN a fibra optica/ 2 puertos CAN/ 1 conector para fibra optica de tipo ST multi-modo/ protocolo CAN 2.0A/2.0B/ alimentacion de +10 a +30 Vdc</strong></center><br>

<p>El medio de transmisión de fibra óptica es un buen material para proteger la transmisión de datos de interferencias EMI/RFI.  Ha sido utilizado en medios ambientes muy amplios y hostiles.  El bus CAN es famoso en aplicaciones industriales y en orden para resolver el problema entre el uso de diferentes medios de transmisión, I-2532 esta especialmente diseñado para convertir el bus CAN eléctrico a fibra óptica.<BR><BR>
La longitud de la fibra entre dos I-2532 puede ser de hasta 1.4 Km (4593 ft).  I-2532 es la solución económica para aplicaciones donde se requiere proteger la transmisión de datos de exposiciones eléctricas, sobretensiones,  luz o corrosiones químicas.</p>

<strong>Características:</strong>
<ul>
<li>Compatible con especificaciones CAN 2.0A y 2.0B</li>
<li>Totalmente compatible con estándares ISO 11898-2</li>
<li>Soporta velocidad de transmisión de hasta 500 Kbps</li>
<li>Fibra puerto: ST (multi modo)</li>
<li>Longitud de la onda: 850 nm</li>
<li>Detección de autotransmisión</li>
<li>Hasta 100 nodos sobre el puerto CAN</li>
<li>Terrminal a tornillos removible</li>
<li>Fácil montaje en riel DIN</li>
</ul>

