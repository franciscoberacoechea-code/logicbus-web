          <h2>Digitalizador de alta velocidad PicoScope 6407</h2>

          <p>El PicoScope 6407 es un dispositivo USB compacto que convierte su PC o computadora portátil en un digitalizador de 4 canales de alta velocidad. El PicoScope 6407 se diferencia del resto de los osciloscopios de PC de la serie PicoScope 6000 en que tiene entradas de 50 Ω de ancho de banda alto con rangos de entrada fijos de ± 100 mV y conectores SMA. Las señales de entrada más grandes se pueden acomodar con el uso de atenuadores externos (ver accesorios).</p>

          <h2>Características</h2>
          <ul>
            <li>4 canales (fijos ± 100 mV)</li>
            <li>Ancho de banda de 1 GHz</li>
            <li>Tamaño de búfer de 1 GS</li>
            <li>Muestreo en tiempo real de 5 GS/s</li>
            <li>Memoria segmentada / disparador rápido de bloque</li>
            <li>Generador de funciones incorporado / AWG</li>
            <li>Controladores y SDK incluidos (Windows, Linux, Mac)</li>
            <li>Software de aplicación PicoScope incluido</li>
          </ul>


          <h2>El mejor ancho de banda, tasa de muestreo y profundidad de memoria de su clase</h2>

          <p>Con un ancho de banda de 1 GHz complementado con una frecuencia de muestreo en tiempo real de 5 GS / s, el PicoScope 6407 puede mostrar pulsos de disparo único con una resolución de tiempo de 200 ps.</p>

          <p>El búfer de 1 gigasample en el PicoScope 6407 puede contener dos capturas de 100 ms a la velocidad de muestreo máxima de 5 GS / s. El PicoScope 6407 se adapta a una amplia gama de aplicaciones de alta velocidad que incluyen:</p>

          <ul>
            <li>Radar / Lidar / Sonar</li>
            <li>Prueba de semiconductor</li>
            <li>Prueba de línea de producción</li>
            <li>Inteligencia de señales (SIGINT)</li>
            <li>Investigación física</li>
            <li>Imágenes médicas</li>
            <li>Prueba no destructiva</li>
          </ul>


          <h2>Adquisición y digitalización de datos a alta velocidad.</h2>

          <p>El kit de desarrollo de software (SDK) le permite escribir su propio software e incluye controladores para Microsoft Windows, macOS y Linux (incluida una versión beta para Raspberry Pi).</p>

          <p>El código de ejemplo muestra cómo interactuar con paquetes de software de terceros como Microsoft Excel, National Instruments LabVIEW y MathWorks MATLAB.</p>

          <p>Los controladores admiten la transmisión de datos USB, un modo que captura datos continuos sin interrupciones a través de USB directamente a la memoria RAM o al disco duro de la PC a velocidades de más de 10 MS / sy el tamaño de captura está limitado solo por el almacenamiento de PC disponible. Las tasas de muestreo en el modo de transmisión están sujetas a las especificaciones de la PC y la carga de aplicaciones.</p>

          <h2>Activación digital avanzada</h2>

          <p>La mayoría de los osciloscopios digitales todavía utilizan una arquitectura de disparo analógica basada en comparadores. Esto causa errores de tiempo y amplitud que no siempre se pueden calibrar y, a menudo, limita la sensibilidad del disparador a anchos de banda altos.</p>

          <p>En 1991, Pico fue pionero en el uso de la activación completamente digital utilizando los datos digitalizados reales. Esta técnica reduce los errores de activación y permite que nuestros osciloscopios se activen en las señales más pequeñas, incluso en el ancho de banda completo. Los niveles de disparo y la histéresis se pueden configurar con alta precisión y resolución.</p>

          <p>El retardo de rearme reducido provisto por el disparo digital, junto con la memoria segmentada, permite la captura de una nueva forma de onda cada microsegundo hasta que el búfer está lleno.</p>

          <p>La serie PicoScope 6000 ofrece un conjunto de disparadores avanzados líderes en la industria que incluyen ancho de pulso, pulso runt, ventana, lógica y abandono.</p>


          <h2>Generador de función y forma de onda arbitraria</h2>

          <p>El PicoScope 6407 tiene un generador de funciones integrado de 20 MHz (seno, cuadrado, triángulo, nivel de CC, ruido blanco, PRBS y otros). Además de los controles básicos para establecer el nivel, el desplazamiento y la frecuencia, los controles más avanzados le permiten barrer en un rango de frecuencias. Combinado con la opción de retención de pico de espectro, esto constituye una herramienta poderosa para probar las respuestas de amplificador y filtro.</p>

          <p>Las herramientas de activación permiten que se produzcan uno o más ciclos de una forma de onda cuando se cumplen varias condiciones, como la activación del alcance o el fallo de una prueba de límite de máscara.</p>

          <p>El PicoScope 6407 también incluye un generador de forma de onda arbitraria (AWG) de 12 bits a 200 MS / s. Las formas de onda AWG pueden crearse o editarse utilizando el editor AWG incorporado, importarse desde las trazas del osciloscopio o cargarse desde una hoja de cálculo.</p>





