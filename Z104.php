<strong><center>Convertidor análogo de voltaje o corriente a frecuencia con aislamiento galvánico.</center></strong>

<div align="right">
<a href="https://tienda.logicbus.com.mx/Z104_p_4202.html" title="Ir a Tienda" target="_blank"><img src="images/shopping_cart.png" alt="Comprar"></a>
</div> <br>

<p>Z104 permite una conversión de la señal de entrada de corriente o voltaje en una serie de pulsos con una duración constante. Un uso típico es cuando, con un medidor de flujo con una salida analógica (ejemplo 4-20mA), el flujo debe ser totalizado. La salida es programable en un rango de 1 pulso cada 2 horas a 10 KHz. Un aislamiento galvánico de 3 vías entre la fuente de alimentación // entrada // circuitos de salida garantiza la integridad de sus datos.</p><br>

<strong>Caracteristicas</strong>
<ul>
<li>Alimentación: 19 a 40 Vdc ó 19 a 28 Vac (opcional de 9 a 30 Vdc)</li>
<li>Entrada: corriente 0 a 20, 4 a 20 mA</li>
<li>Salida: colector abierto NPN a 30 Vdc 300mA, relevador reed 30 Vdc/sc 100mA</li>
<li>Precisión 0.2%</li>
<li>Aislamiento galvánico a 3 vías</li>
<li>Terminales a tornillo removibles</li>
<li>Montaje en riel DIN </li>
</ul>

