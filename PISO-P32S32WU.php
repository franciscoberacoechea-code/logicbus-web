<center><strong>Tarjeta de salida universal PCI, 32-CH con aislamiento óptico y 32-CH con colector abierto óptico (8 canales para 500 mA y 24 canales para salida de corriente de 100 mA, NPN, RoHS).</strong></center><br>


<p>PISO-P32S32WU tiene 32 canales de DI aislado ópticamente y 32 canales de placa de salida de colector abierto aislada ópticamente (8 canales para 500 mA y 24 canales para salida de corriente de 100 mA, NPN), dispuestos en cuatro bancos aislados. Cada canal de entrada utiliza un fotoacoplador para aislar la tarjeta y la computadora de la señal externa. Cada salida digital ofrece un transistor NPN y un diodo de supresión integral para carga inductiva. PISO-P32S32WU requiere alimentación externa para controlar los puertos D / I y D / O y admite funciones de ID de tarjeta (jumper) para la identificación de varias tarjetas y es compatible con las ranuras PCI de 5 V y 3,3 V.<br>

Esta placa de interfaz se instala fácilmente en cualquier PC. La placa interactúa con las señales lógicas de campo, lo que elimina los problemas de bucle de tierra y aísla la computadora host de tensiones dañinas. PISO-P32S32WU tiene un conector D-Sub de 37 pines y un conector macho de 40 pines. El cable plano de 40 pines a DB-37 se usa para arreglarlo con la caja. El usuario puede conectar la señal digital a través del segundo conector D-Sub. Cada conector D-Sub contiene 16 canales de entrada y 16 canales de salida.<br> 

El PISO-P32S32WU es compatible con varios sistemas operativos, como Linux, DOS, Windows 98, Windows 2000, Windows NT, Windows XP de 32 bits, Vista de 32 bits y Windows 7 de 32 bits. También proporciona el control DLL y Active X, y varios programas de muestra de lenguaje en Turbo C ++, Borland C ++, Microsoft C ++, Visual C ++, Borland Delphi, Borland C ++ Builder, Visual Basic, C # .NET, Visual Basic.NET y LabVIEW para ayudar usuarios para desarrollar rápida y fácilmente sus aplicaciones.<br>
</p><BR><br>

<strong>Caracteristicas</strong>

<ul>
<li>Entrada digital óptica aislada 32-CH.</li>
<li>Salida digital aislada en 32 canales.</li>
<li>Voltaje de aislamiento: 3750 Vrms (usando energía externa).</li>
<li>Identificación de la tarjeta: configuración del puente para la identificación de varias tarjetas</li>
<li>(Versión 1.5 o superior).</li>
<li>Colector abierto: 500 mA (8 canales), 100 mA (24 canales), sumidero de corriente, NPN.</li>
</ul>
