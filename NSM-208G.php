<center><strong>Conmutador Gigabit Ethernet 10/100/1000 BaseT no administrado de 8 puertos en carcasa de metal. Admite temperaturas de funcionamiento entre -30 ° C y 70 ° C.</strong></center><br>


<p>El NSM-208G tiene 8 puertos de conmutación Ethernet que admiten 10/100/1000 Base-T, con una función de autonegociación de 10/100 / 1000M y función MDI / MDI-X automática. Puede conectar 8 estaciones de trabajo y cambia automáticamente la velocidad de transmisión (10 Mbps o 100 Mbps o 1000 Mbps) para las conexiones correspondientes. <br>

El mecanismo de control de flujo también se negocia. Hay LED de velocidad de enlace / datos para cada puerto para ayudar a solucionar problemas. Los conectores de puerto están blindados RJ-45. <br>

NS-208AG / NSM-208AG es exactamente lo mismo que NSM-208G excepto por la entrada de alimentación.</p><BR>

<strong>Caracteristicas</strong>

<ul>
<li>Crossover automático MDI / MDI-X para plug-and-play.</li>
<li>Arquitectura de almacenamiento y reenvío.</li>
<li>Control de flujo de contrapresión Full Duplex IEEE 802.3xy semidúplex.</li>
<li>Admite entrada de alimentación de +12 V CC ~ +48 V CC para NS-208AG y NSM-208AG.</li>
<li>Cada puerto admite la negociación automática de velocidad 10/100 y 1000 Mbps.</li>
<li>Ancho de banda de memoria de alto rendimiento de 16 Gbps.</li>
<li>Admite marcos Jumbo 9K para Speed ​​1000M.</li>
<li>Admite temperaturas de funcionamiento de -40 ° C ~ +75 ° C.</li>
<li>Montaje en carril DIN./li></li>
</ul>
