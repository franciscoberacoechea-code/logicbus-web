          <p>Los Picoscope 4424 y 4224 ofrecen una alta resolución (12 bits) y una alta precisión de CC (1%), lo que los convierte en una excelente opción para el análisis de ruido, vibración, electrónica de precisión y mecánica.</p>

          <p>La interfaz IEPE opcional (ver más abajo) permite la conexión directa y la alimentación de los acelerómetros y micrófonos estándar de la industria.</p>

          <h2>La alta resolución ofrece 16 veces más detalles.</h2>

          <p>Los PicoScope 4224 y 4424 son osciloscopios de 12 bits que ofrecen una resolución vertical 16 veces mayor que los osciloscopios tradicionales de 8 bits (4096 niveles verticales frente a 256). El ejemplo muestra cómo con un osciloscopio de 12 bits (traza azul) puede ampliar para revelar detalles de la señal que no son visibles en un osciloscopio de 8 bits (traza negra).</p>

          <p>Además de la alta resolución vertical, la memoria intermedia de muestra de 32 millones asegura una resolución horizontal alta también. Puede recopilar capturas largas y detalladas sin que la tasa de muestreo disminuya.</p>

          <p>Una vez que haya visto formas de onda de alta resolución en un monitor de PC de alta resolución, nunca más querrá usar un osciloscopio de mesa tradicional con su pequeña pantalla de nuevo.</p>

          <p>Además de los trazados mejorados del osciloscopio, la alta resolución ofrece grandes beneficios cuando se realiza un análisis de espectro que ofrece un rango dinámico adicional de 20 dB en el espectro sobre osciloscopios de 8 bits. Las señales que antes estaban ocultas en el piso de ruido ahora son claramente visibles y el espectro se convierte en una herramienta poderosa para rastrear las causas del ruido.</p>

          <h2>Interfaz IEPE</h2>

          <p>El PicoScope 4224 está disponible con una interfaz interna opcional IEPE (circuito piezoeléctrico) que permite la conexión directa y la alimentación de los acelerómetros y micrófonos estándar de la industria.</p>

          <p>Cuando está deshabilitado, los canales se pueden usar como entradas normales del osciloscopio. Cuando IEPE está habilitado (cada canal tiene control independiente a través del software), la entrada está acoplada a CA y se emite una señal de 24 V, 4 mA para alimentar sensores externos.</p>

          <p>La alta resolución y el rango dinámico del 4224 lo hacen ideal para usar con acelerómetros y micrófonos. Tener la interfaz IEPE incorporada lo convierte en una solución compacta y portátil.</p>

          <h2>Pantalla avanzada</h2>

          <p>El software PicoScope dedica casi toda el área de visualización a la forma de onda. Esto asegura que la cantidad máxima de datos se vea a la vez. El área de visualización es mucho más grande y de mayor resolución que con un alcance de mesa tradicional.</p>


          <p>Con una gran área de visualización disponible, también puede crear una visualización de pantalla dividida personalizable y ver múltiples canales o diferentes vistas de la misma señal al mismo tiempo. Como muestra el ejemplo, el software incluso puede mostrar múltiples trazados de osciloscopio y analizador de espectro a la vez. Además, cada forma de onda que se muestra funciona con ajustes individuales de zoom, panorámica y filtro para una máxima flexibilidad.</p>

          <p>El software PicoScope se puede controlar mediante métodos abreviados de mouse, pantalla táctil o teclado.</p>

          <h2>Analizador de espectro FFT</h2>

          <p>La vista de espectro representa la amplitud frente a la frecuencia y es ideal para encontrar ruido, interferencia o distorsión en las señales. El analizador de espectro en PicoScope es del tipo de Transformada Rápida de Fourier (FFT) que, a diferencia de un analizador de espectro de barrido tradicional, puede mostrar el espectro de una forma de onda única y no repetitiva.</p>

          <p>Una amplia gama de configuraciones le permite controlar el número de bandas de espectro (bandejas FFT), tipos de ventanas, escala (incluido log / log) y modos de visualización (instantánea, promedio o retención de pico).</p>

          <p>Puede visualizar múltiples vistas de espectro junto con vistas de osciloscopio de los mismos datos. Un conjunto completo de mediciones automáticas en el dominio de la frecuencia se puede agregar a la pantalla, incluyendo THD, THD + N, SNR, SINAD y IMD. Se puede aplicar una prueba de límite de máscara a un espectro para pruebas automatizadas.</p>

          <h2>Integridad de la señal</h2>

          <p>La mayoría de los osciloscopios se reducen a un precio. Los PicoScopes están construidos según una especificación.</p>

          <p>El cuidadoso diseño del frente y el blindaje reducen el ruido, la interferencia y la distorsión armónica. Años de experiencia en el diseño de osciloscopios se pueden ver en la mejora de la planitud del ancho de banda y la baja distorsión.</p>

          <p>Estamos orgullosos del rendimiento dinámico de nuestros productos y, a diferencia de la mayoría de los fabricantes de osciloscopios, publicamos nuestras especificaciones en detalle. El resultado es simple: cuando prueba un circuito, puede confiar en la forma de onda que ve en la pantalla.</p>

