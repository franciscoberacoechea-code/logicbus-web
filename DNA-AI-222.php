          <br>
          An A/D per channel configuration allows simultaneous sampling at rates up to 100 S/s each (1200 S/s aggregate). The A/D per channel configuration virtually eliminates input cross talk and channel settling time issues.&nbsp;<br>
          <br>
          The DNx-AI-222 is an ideal, high accuracy RTD measurement device, offering total errors of less than 0.2 &deg;C on all standard 100 Ohm RTDs. This accuracy combined with the 350 VDC/Vrms channel-to-channel and channel-to-chassis isolation makes the board a perfect solution for industrial temperature measurement, even when using non-isolated RTDs in high voltage environments.&nbsp;<br>
          <br>
          The software included will perform all required RTD linearization and compensation and returns data in &deg;C, &deg;K, &deg;F or &deg;R when desired. The software also allows the temperature conversion to be disabled and the inputs can measure resistance in Ohms up to 40 kOhms.<br>
          <br>
          Software included with the DNx-AI-222 provides a comprehensive yet easy to use API that supports all popular Windows programming languages as well as supporting programmers using Linux and most real-time operating systems including QNX, RTX, InTime, VXworks and more. The UEIDAQ Framework supplies complete support for those creating applications in data acquisition software packages such as LabVIEW, MATLAB/Simulink, DASYLab or any application which supports ActiveX or OPC servers.
