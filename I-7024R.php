          <p>I-7024R es un módulo de interfaz RS-485 y ofrece salidas analógicas de 4 canales y entradas digitales de 5 canales. Proporciona salidas análogas programables de 14 bits con 0 ~ 5 V, +/- 5 V, 0 ~ 10 V, +/- 10 V, 0 ~ 20 mA y 4 ~ 20 mA. Y cada terminal admite protección ESD de 4 kV. E I-7024R mejora la calidad de salida en entornos radiantes.</p><br>

          <strong>Características:</strong>
          <ul>
            <li>Salida analógica de 4 canales y entrada digital de 5 canales</li>
            <li>Software seleccionable de corriente o salida de voltaje</li>
            <li>Valor de encendido configurado</li>
            <li>Ajuste de valor seguro</li>
            <li>Aislamiento intramódulo de 3000 VDC</li>
            <li>Pendiente de salida programable</li>
            <li>Dual Watchdog</li>
            <li>Amplio rango de temperatura de funcionamiento: -25 a + 75 ° C</li>
          </ul><br>



