<p>PEX-CAN200i puede representar una solución económica de una placa CAN activa con bus PCI Express. Tiene 2 puertos de comunicación de bus CAN independientes con conector de terminal de tornillo de 5 pines o conector D-sub de 9 pines, y tiene la capacidad de cubrir una amplia gama de aplicaciones CAN. Además, PEX-CAN200i utiliza el nuevo controlador CAN Phillips SJA1000T y el transceptor 82C250, que proporcionan arbitraje de bus, detección de errores con corrección automática y función de retransmisión.</p><BR>

<strong>Aplicaciones:</strong>
<ul>
<li>Aplicación de comunicación CAN bus.</li>
<li>Aplicación de protocolo DeviceNet, CANopen, CAN J1939, SDS (red amplia de sistema).</li>
<li>Sistema de control</li>
<li>Automatización de edificios</li>
<li>Automatización industrial</li>
<li>Adquisición de datos distribuidos.</li>
</ul><br>

<strong>Caracteristicas:</strong>
<ul>
<li>Interfaz PCI Express</li>
<li>Compatible con CAN 2.0 partes A y B</li>
<li>Totalmente compatible con el estándar ISO 11898-2</li>
<li>Soporte CAN bardo de 10K a 1M bps</li>
<li>Aislamiento de pareja de fotos de 2500 Vrms en el bus CAN</li>
<li>33 MHz, 32 bit, X1 PCI Express bus</li>
<li>Puente incorporado para seleccionar resistencia terminal de 120 ohmios</li>
<li>Aislamiento galvánico 3KV</li>
<li>2 canales CAN independientes</li>
<li>Mapeo de memoria directa al controlador CAN</li>
<li>Proporcionar demos de VB, VC ++, Delphi, BC ++</li>
<li>Controlador LabView / DASYLab</li>
<li>Soporte de controladores Windows 98 / ME / NT / 2K / XP</li>
</ul>
