<center><strong>Entrada digital aislada de 4 canales (contador) y módulo de salida de relé de 4 canales con entrada de voltaje, DCON y protocolo Modbus RTU, admite temperaturas de funcionamiento de -25 ~ + 75 ° C.</strong></center><br>

<p>El M-7060P ofrece entradas digitales de 4 canales, salidas de relé de potencia de Forma A de 2 canales y salidas de relé de potencia de Forma C de 2 canales al mismo tiempo. Además, puede elegir el tipo de sumidero o el tipo de fuente de entrada digital a través de conexiones de cable. Todos los canales de entrada se pueden usar como contadores de 16 bits. M-7060P también tiene 8 indicadores LED para salidas de relés de potencia y monitoreo de estado de entradas digitales. Y ambos son compatibles con los protocolos Modbus RTU y DCON que se pueden configurar a través del software. Existen opciones para configurar valores de encendido y salida digital segura. También se proporcionan 4 kV de protección ESD y 3750 VDC de aislamiento intramódulo para enriquecer la capacidad de protección contra el ruido para entornos industriales. La diferencia de especificación M-7060P, M-7060P Admite la forma A del relé de potencia (16 A a 250 VCA / 10 A a 30 VCC) y la Forma C (10 A NO / 6 A NC a 250 VCA.</p><BR>

<strong>Caracteristicas</strong>

<ul>
<li>entradas digitales y 4 salidas de relés</li>
