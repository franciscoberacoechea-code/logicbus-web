            </div>
            <p>Los <strong>osciloscopios</strong>, en general se dividen en <strong>Analógicos</strong> y <strong>Digitales</strong>, ambos muestran las mismas gráficas, sin embargo existen algunas diferencias entre estos instrumentos y algunos poseen limitaciones. Los <strong>analógicos</strong> trabajan directamente con la señal aplicada, esta una vez amplificada desvía un haz de electrones en sentido vertical proporcionalmente a su valor. Mientras que los <strong>Digitales</strong> utilizan un conversor <strong>analógico-digital</strong>, para que pueda almacenar digitalmente la señal de entrada, reconstruyendo posteriormente esta información en la pantalla.</p>
            <ol>
                <li class="med">Osciloscopios Analógicos</li>
                <p>De vez en cuando podemos encontrar ejemplares de <strong>osciloscopios analógicos</strong> en las mesas de trabajo de técnicos, quienes a la fuerza de costumbre no se atreven a pisar el umbral del signo digital, pero poco a poco estos modelos a su tiempo se desplazan por sus sucesores los digitales. Prácticamente cada <strong>osciloscopio analógico</strong> debe tener uno o varios canales verticales, canal horizontal, base de tiempo, sistema de disparo y por supuesto, módulo de tubo de rayos catódicos.</p>
                <p>Estos componentes nos lleva a su función, la tensión a medir es aplicada a las placas de desviación de un tubo de rayo catódico, utilizando un amplificador de alta impedancia de entrada, mientras tanto que a la placas de desviación horizontal se aplica una tensión en diente de sierra, esto quiere decir, que de forma repetida, crece suavemente y luego se cae de forma brusca. Esta tensión es producida mediante un circuito oscilador apropiado y su frecuencia puede ajustarse dentro de un amplio rango de valores, lo que permite adaptarse a la frecuencia de la señal a medir. A esto se le denomina base de tiempos.</p>
                <center><img src="https://www.logicbus.com.mx/imagenes/articulo/Funcion-osciloscopio-analogico.jpeg" class="img-fluid" alt="Función del osciloscopio analógico" title="Función del osciloscopio analógico" width="500px">
                </center>
                <li class="med"><a class="link-orange" href="osciloscopios_digitales_escritorio">Osciloscopios Digitales</a></li>
                <p>Hoy en día, los <strong>osciloscopios digitales</strong>, han reemplazado a los <strong>analógicos</strong>, debido a que los <strong>digitales</strong> cuentan con las mismas características que las analógicas, pero al mismo tiempo posee diferencias que los hace mejores para un buen trabajo determinado.</p>
                <p>El <strong>osciloscopio digital</strong> es un instrumento que permite la visualización y medición de una señal eléctrica, con la diferencia de utilizar la digitalización de la señal de entrada. Esta digitalización consiste en asignar un código binario a muestras que se toman de la señal de entrada análoga. Para hacer esto se necesita un circuito que obtenga las muestras y un conversor análoga-digital. (ADC), y para el almacenamiento, es necesario una memoria. Después de haber almacenado los datos, se pueden hacer distintos tipos de cálculos realizados por el mismo osciloscopio.</p>
