<STRONG>Características:</STRONG>
<ul>
<li>Memoria SRAM de 512 kB para PCI-M512/PCI-M512U</li>
<li>Dos baterías de Litio, BT1 & BT2, para respaldo de datos de la SRAM</li>
<li>Dos indicadores de batería baja y batería defectuosa, para la batería BT1</li>
<li>Otros dos indicadores de batería baja y batería defectuosa, para la batería BT2</li>
<li>Salida Digital o de relevador de 16 bits para propósito general compatible con TTL (con la placa hija (daughter board) DB-16R o DB-24PR)</li>
<li>Entrada Digital o Aislada de 12 bits para propósito general compatible con TTL (con placa hija DB-16P)</li>
<li>[Sólo para PCI-M512] </li>
<li>Tarjeta PCI, soporta el bus PCI 5 V</li>
<li>[Sólo para PCI-M512U] </li>
<li>Tarjeta PCI Universal, soporta los bus PCI 5 V y 3.3 V</li>
</ul><br>

<strong>Descripción:</strong><br>
<p align="justify">El PCI-M512/PCI-M512U provee una memoria SRAM de 512 kB con batería de respaldo, entrada digital de 12 bits y salida digital de 16 bits. Adicionalmente soporta los bus PCI 5 V y 3.3 V, mientras que el PCI-M512 soporta sólo el bus 5 V. El PCI-M512U (Versión PCI Universal) es totalmente compatible con la PCI-512 (versión PCI). 
<br><br>
Los usuarios pueden usar el DB-16P para conectar los puertos CN2 para propósito de aislamiento, o usar el DB-16R para conectar los puertos de salida CN1 para el control de relevador. 
<br><br>
El PCI-M512/PCI-M512U está equipado con dos baterías de litio para mantener el contenido en caso que la PC se quede sin energía. Las dos baterías pueden continuar suministrando energía a la SRAM de 512 kB para retener los datos importantes por 10 años; y el diseño de estas baterías es seguro para mantener los datos cuando se reemplacen por unas nuevas. 
<br><br>
El PCI-M512/PCI-M512U también provee 4 indicadores LED para mostrar el estado de las baterías. Es fácil saber si el estado de las 2 baterías es normal, si tienen voltaje bajo o si están fallando con estos 4 indicadores LED. 
<br><br>
El PCI-M512/PCI-M512U es una solución ideal para la confiabilidad de un sistema.</p>




