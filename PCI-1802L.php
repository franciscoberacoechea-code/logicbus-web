<LI>Memoria intermedia 1K palabra FIFO</LI>
<LI>PCI-1802H, PCI-1802L: 32 entradas diferenciales single-ended / 16</LI>
<LI>Memoria intermedia de 8K palabra FIFO</LI>
<LI>Las tasas de muestreo de canales únicos o múltiples: 330K muestras / s para modelo de baja ganancia y 44K muestras / s para el modelo de alta ganancia.</LI>
<LI>Tres factores desencadenantes externos diferentes: post-disparo, pre-disparador y gatillo medio</LI>
<LI>16 canales de entrada digital / 16 canales de salida digital</LI>
<LI>1800L, 1802L: baja ganancia programable: 0.5, 1, 2, 4, 8.</LI>
<LI>1800H, 1802H: alta ganancia programable: 0.5, 1, 5, 10, 50, 100, 500, 1000.</LI>
<LI>Disparador interno / externo.</LI>
<LI>Dos DAC programables independientes de 12 bits.</LI>
<LI>Rendimiento de 2 MHz por canal (maxi)</LI>
<LI>Velocidad de transferencia de datos de 2,7 M palabras / alta velocidad.</LI>
<LI>PCI-1800H, PCI-1800L: expande el canal usando DB-889D</LI>
<LI>PCI-1802H, PCI-1802L: expande el canal usando DB-889D y DB-1825</LI>
<LI>Tablero de tamaño medio</LI>
</ul>
