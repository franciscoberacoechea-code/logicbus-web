<h2>Caracteristicas</h2><br>

<p align="justify">La serie ICP DAS ViewPAC, VP-211x y VH-211x tiene una CPU de 16 bits, pantalla gráfica con resolución de 128 x 64, teclado de goma de silicona, puertos de comunicación Ethernet, RS-232, RS-485 y 3 ranuras de expansión de E / S. También equipa un sistema operativo tipo DOS llamado MiniOS7. Los usuarios pueden desarrollar programas, usar compiladores C para crear archivos ejecutables de 16 bits (* .exe) y luego descargarlo al controlador. Turbo C 2.0 o Turbo C ++ 1.0.1 se pueden usar para compilar programas de aplicación y generar archivos de ejecución. Los archivos de ejecución se pueden descargar a VP-211X y VH-211x a través de puerto RS-232 o Ethernet. Recomendamos Turbo C ++ 1.01. Hay muchos programas de demostración disponibles para referencia. Para la programación TCP / IP, proporcionamos una plantilla de servidor TCP / IP llamada XServer. Es una herramienta muy poderosa, fácil de usar y flexible que puede ahorrar un 90% de tiempo de desarrollo.<br />
ViewPAC combina iPAC, una pantalla gráfica y un teclado en una unidad. Equipa una CPU 80186 (16 bits y 80MHz) con un sistema operativo MiniOS7, varias interfaces de comunicación (Ethernet, RS-232/485), 3 ranuras para expandir módulos de E / S, LCD STN y un teclado de goma. Su sistema operativo, MiniOS7, puede arrancar en muy poco tiempo (0.4 ~ 0.8 segundos). Tiene una función de diagnóstico de hardware integrada y admite la gama completa de funciones necesarias para acceder a todos los módulos de E / S de la serie I-8K e I-87K de alto perfil, como DI, DO, DIO, AI, AO, Counter / Frecuencia y módulos de control de movimiento. En comparación con las soluciones HMI + PLC tradicionales, ViewPAC reduce el costo general del sistema, el espacio y le ofrece todas las mejores características de los HMI y PLC.</p>

