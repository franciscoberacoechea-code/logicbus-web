<p>El convertidor I-7550 est&aacute; especialmente dise&ntilde;ado para el dispositivo esclavo del protocolo PROFIBUS DP. Ofrece 3 tipos de v&iacute;as de comunicaci&oacute;n: RS-232, RS-422 y RS-485. Con el dise&ntilde;o COM 1 h&iacute;brido, los usuarios pueden escoger un tipo de puerto COM para usar. Usando &eacute;ste m&oacute;dulo, los usuarios pueden poner sus dispositivos RS-232/422/485 en la red PROFIBUS de una manera muy f&aacute;cil.</p><BR>

<strong>Aplicaciones:</strong>
<ul>
   <li>Automatizaci&oacute;n Industrial </li>
   <li>Automatizaci&oacute;n de F&aacute;bricas</li>
   <li>Automatizaci&oacute;n de Proceso
</ul>

<br>

<strong>Características:</strong>
<ul>
<li>Soporte para el protocolo PROFIBUS DP-V0 Esclavo </li>
<li> Detecta la velocidad de transmisi&oacute;n autom&aacute;ticamente </li>
<li> Direcciona 0~126 por medio de switches rotatorios</li>
<li> 128 Bytes de largo de entrada de datos</li>
<li>128 Bytes de largo de salida de datos</li>
<li> Protecci&oacute;n de Aislamiento de Voltaje de 3000VDC </li>
<li> COM 1 H&iacute;brido: RS-232/422/485 con &quot;Self-Turner&quot;</li>
<li>Soporta formato de datos COM1: 7/8 bits de datos, Paridad par/ipar/ninguna, 1  bit de parada</li>
<li>  Soporta velocidades de transmisi&oacute;n de: 9.6, 19.2, 45.45, 93.75, 187.5, 500, 1500, 3000, 6000, 1
</ul>

