<p align="justify">El I-87018PW es un módulo de entrada de termopar de 8 canales. El rango de entrada analógica es seleccionable por software y admite +/- 15 mV, +/- 100 mV, +/- 500 mV, +/- 1 V, +/- 2.5 V, 0 ~ +20 mA, +4 ~ +20 mA o +/- 20 mA, y termopares de tipo J, K, T, E, R, S, B, N, C, L, M y LDIN43710. Ofrece la compensación automática de la unión fría para cada canal, y admite la detección de termopar abierto.</p>

<strong>Características:</strong>
<ul>
<li>Entrada de termopar de 8 canales.</li>
<li>Configuración de canal individual.</li>
<li>Detección abierta de termopar.</li>
<li>Consistencia de salida de temperatura.</li>
<li>Salida de temperatura estable en el campo.</li>
<li>240 Vrms Protección contra sobretensión.</li>
<li>Protección contra ESD de 4 kV.</li>
<li>Dual Watchdog.</li>
<li>Aislamiento intramódulo de 3000 VDC, campo a lógica.</li>
<li>RoHS.</li>
<li>Amplio rango de temperatura de funcionamiento: -25 ~ + 75 ° C.</li>
</ul>

