<center><strong>Entrada digital aislada de 16 canales, salida de relé PhotoMos de 16 canales. Incluye cable CA-4037W y dos conectores CA-4002 D-Sub.</strong></center><br>


<p>El PCI-P16POR16 es una tarjeta PCI compatible con el bus PCI de 5 V. Tanto los canales DI aislados como los canales de retransmisión PhotoMos usan una ruta de transmisión óptica corta para transferir una señal electrónica entre los elementos de un circuito y mantenerlos aislados eléctricamente. El PCI-P16POR16 proporciona 5000 Vrms. Los relés PhotoMos se utilizan cuando es necesario controlar un circuito con una señal de baja potencia (con aislamiento eléctrico completo entre el control y los circuitos controlados), o donde varios circuitos deben controlarse con una señal.<br>

El PCI-P16POR16 puede usarse en diversas aplicaciones, como controlar el estado ON / OFF de dispositivos externos, controlar relés externos o pequeños interruptores de potencia, activar alarmas, cerrar contactos, detectar voltajes o conmutadores externos, etc.<br>

Estas tarjetas admiten varias versiones del sistema operativo, como Linux, DOS, Windows 98 / NT / 2000 y Windows 7 / Vista / XP de 32/64 bits. El control DLL y Active X junto con varios programas de muestra de lenguaje basados ??en Turbo C ++, Borland C ++, Microsoft C ++, Visual C ++, Borland Delphi, Borland C ++ Builder, Visual Basic, C # .NET, Visual Basic.NET y LabVIEW se proporcionan para ayudar a los usuarios a desarrollar rápida y fácilmente sus propias aplicaciones.
</p><BR><br>

<strong>Caracteristicas</strong>

<ul>
<li>Filtro de entrada de señal de CC seleccionable.</li>
<li>Entrada de señal de CA con filtro.</li>
<li>Indicador de encendido LED.</li>
<li>Relé PhotoMOS de larga duración y alta fiabilidad.</li>
<li>Baja corriente de fuga cuando el relé PhotoMOS está apagado.</li>
<li>Sin rebote de contacto, sin chispas.</li>
<li>Sin ruido acústico.</li>
<li>Operación DIO de alta velocidad.</li>
<li>Admite Plug & Play para obtener recursos de E / S.</li>
<li>Ya no es necesario configurar manualmente la dirección de E / S y la IRQ.</li>
<li>Admite el bus PCI + 3.3 / + 5 V.</li>
<li>16 canales de salida de relé PhotoMOS.</li>
<li>16 canales de entrada digital ópticamente aislados.</li>
<li>Protección de aislamiento de foto de 5000 Vrms.</li>
<li>Admite la identificación de la tarjeta (interruptor SMD).</li>
<li>Admite el estado de DO Readback (Nivel de registro).</li>
</ul>
