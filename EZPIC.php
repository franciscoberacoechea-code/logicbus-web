<p>Sensor multimodo fotoeléctrico digital de alto rendimiento que se puede configurar con solo presionar un botón. No hay trabajo de conjetura por parte del operador. A partir de ese momento, el sensor mantendrá automáticamente una configuración perfecta, gracias al dinámico Sistema automático de seguimiento de contraste (ACT). La rutina EZ-PRO ™ AUTOSET también se puede implementar desde un interruptor remoto momentáneo (es decir, un botón o una pantalla táctil). El EZ-PRO ™ está equipado con un indicador de contraste, así como un indicador de diagnóstico de alerta de acción que permite al operador verificar visualmente el rendimiento. Cuando la función de bloqueo está habilitada (ver funciones avanzadas), el sensor EZ-PRO ™ es a prueba de manipulaciones. Ahora, el sensor le proporcionará el rendimiento automático y sin problemas que espera de un SMARTEYE®. Puede montarse lateralmente o en riel Din. Epoxi encapsulado, es ultra resistente y a prueba de vibraciones.</p><br>

