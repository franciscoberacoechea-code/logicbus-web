                    <p align="justify">El modelo GL240 es un producto de registrador de datos de tercera generación con
                        un precio
                        / rendimiento excepcional. Es un dispositivo de 10 canales analógicos aumentado por cuatro
                        entradas y
                        salidas discretas. Sus entradas discretas se pueden configurar como un grupo para que sean
                        entradas lógicas
                        o entradas de pulsos. Cuando se configura para el pulso, cada uno de los cuatro canales se puede
                        configurar
                        para medir la frecuencia o para contar. Las cuatro salidas discretas son alarmas que pueden ser
                        activadas
                        por una variedad de condiciones de canales de entrada analógica y pulsos / discretos fácilmente
                        definidos.
                        Los 10 canales de entrada analógica GL240 pueden configurarse para medir un voltaje conectado
                        directo en el
                        rango de 20 mV a 100 V a escala completa en 12 rangos, o para un termopar de cualquier tipo para
                        medir la
                        temperatura. Cada uno de los canales de entrada analógica del GL240 está aislado eléctricamente
                        de otros
                        canales y de la toma de tierra eléctrica, lo que permite realizar mediciones en tierra usando
                        shunts, así
                        como termopares con conexión a tierra.<br><br>
                        La característica más potente del GL240 es su flexibilidad de activación. La grabación de datos
                        se puede
                        iniciar o detener de forma independiente en función del nivel de señal analógica y de pulsos /
                        discreta
                        (simple o con ventana), alarma, fecha y hora y día de la semana. Los disparadores también se
                        pueden
                        configurar para que funcionen solo una vez, o para que se repitan automáticamente. La capacidad
                        del GL240
                        para adaptarse a prácticamente cualquier condición de disparo deseada permite que el instrumento
                        funcione
                        sin supervisión durante largos períodos de tiempo con total autonomía.<br><br>
                        Finalmente, el alcance de medición de un GL240 con capacidad inalámbrica se amplía aún más
                        mediante el uso
                        del accesorio GL100. El GL100 permite de forma inalámbrica mediciones de temperatura / humedad,
                        aceleración,
                        CO2, iluminancia, corriente alterna y más.</p>

