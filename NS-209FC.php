<center><strong>Switch Industrial con 8 puertos Ethernet 10/100 Base-Tx y un puerto de Fibra Óptica multi-modo con conector SC, alimentación de 12-48 Vdc.</strong></center><br>


<p>El NS-209FC (conector SC; modo múltiple) es un convertidor no gestionable de Industrial Ethernet de 8 puertos (10 / 100Base-TX) a fibra óptica (100Base-FX) que asegura la transmisión de datos mediante el uso de transmisión de fibra óptica para proporcionar inmunidad de EMI / Interferencia RFI. Se usa Ethernet para transmitir una señal de hasta 2 km (6,600 pies), y es la solución perfecta para aplicaciones donde la transmisión debe protegerse contra la exposición eléctrica, sobrevoltajes, rayos o corrosión química.<br>
El NS-209FC funciona en modo half o full duplex. En modo dúplex completo, el rango es de 2 km con cables de fibra de 62.5 / 125µm; en modo semidúplex, el rango es de 412 m con cables de fibra de 62.5 / 125µm.<br>
El Ethernet admite la función de autonegociación 10 / 100M y la función automática MDI / MDIX.</p><BR>

<strong>Caracteristicas</strong>

<ul>
<li>Crossover automático MDI / MDI-X para plug-and-play</li>
<li>Cada puerto admite una negociación automática de velocidad de 10/100 Mbps</li>
<li>Arquitectura de almacenamiento y reenvío</li>
<li>Control de flujo de contrapresión Full Duplex IEEE 802.3xy semidúplex</li>
<li>Ancho de banda de memoria de alto rendimiento de 3.2 Gbps</li>
<li>Motor de búsqueda integrado con direcciones MAC dedicadas de 1 K unicast.</li>
<li>Admite un voltaje de + 10 ~ + 30Vdc</li>
<li>Admite temperaturas de funcionamiento de -10 ~ + 70 ° C</li>
<li>Montaje en riel DIN para uso industrial</li>
</ul>
