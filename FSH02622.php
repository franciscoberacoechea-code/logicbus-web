<p>El botón de carga roscada en miniatura LLB215 de FUTEK   (salida de cable inferior) está diseñado para aplicaciones de compresión en línea o de prensa. El LLB215 está hecho de un robusto acero inoxidable 17-4 PH, con un diámetro exterior subminiatura de 0.38 in [9.5 mm].
<br><br>
Aunque los botones de carga roscados en miniatura tradicionalmente no son conocidos por su alta precisión, los ingenieros de FUTEK han disipado este concepto al mejorar continuamente la precisión de este producto. Estas celdas de carga logran una gran precisión y rigidez con una no linealidad de ± 0.5% y una desviación de 0.0007 en nominal. También encontrará opciones disponibles para salidas externas coincidentes.
<br><br>
El botón de carga roscado en miniatura LLB215 estándar (salida de cable inferior) se puede modificar o personalizar para satisfacer sus requisitos y la mayoría de las capacidades están en nuestro inventario, lo que las hace disponibles para una entrega rápida. Similar a toda nuestra línea de productos de Celdas de Carga, este modelo se fabrica en los Estados Unidos y utiliza tecnología de galga extensiométrica de lámina metálica.
</p><br>

