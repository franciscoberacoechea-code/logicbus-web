      <td colspan="2"><div align="justify">The DNA/DNR-SL-504 are 4-port serial communications interfaces for Cube/RACKtangle I/O chassis respectively. Each port may be independently configurable as RS-232, RS-485, RS-422/423 as well as set for synchronous or asynchronous communications. Each port is fully isolated from the other three ports as well as from the Cube or RACKtangle chassis. The board is an ideal interface to a wide variety of serial based data acquisition and control interfaces as well as general purpose serial I/O.<br>
          <br>
          The DNx-SL-504 supports most popular synchronous serial protocols, including HDLC and SDLC. The RS-485/422 implementation provides transmit and receive, data and clock interface while the RS-232 configuration also supports standard CTS and RTS signals. The maximum transfer rate in RS-485/422 and RS-232 modes are 4 Mbaud and 600 kbaud respectively.<br>
          <br>
          The DNx-SL-504 support standard asynchronous serial transfer rates up to 1 Mbaud in RS-485 mode or up to 256 kbaud in RS-232 mode. It also supports communications at 12, 12.5 and 50 kbaud with better than 0.1% data rate accuracy. The DNx-SL-504 is based on the Zilog Z16C32 serial controller chip and supports most popular synchronous serial protocols including HDLC and SDLC.<br>
          <br>
          The DNA/DNR-SL-504 are compatible with RS-422 point to point or network applications when used in RS-485 mode and provide 200&Omega; software-selectable TX and/or RX termination for RS-485 communications. Additionally, the DNA-SL-504 provides 1k&Omega; software-selectable fail-safe RX termination for RS-485 mode.<br>
          <br>
          The DNA/DNR-SL-504 is supported by the UEIDAQ Framework providing a simple and complete software interface to all popular programming languages, operating systems and data acquisition and control applications (e.g. LabVIEW, DASYLab, MATLAB).
