<strong>Características principales</strong>
<ul>
 <li>Pequeño, de instalación sencilla</li>
 <li>No requiere alimentación externa, se alimenta del puerto USB y cuenta con tecnología plug and play</li>
 <li>Adopta la configuración de interfaz RS-485 ó RS-422 automáticamente</li>
 <li>Compatible con modo half dúplex (para RS-485) y full dúplex (sólo para RS-422)</li>
 <li>La transmisión de datos alcanza hasta 1.8 km a una velocidad de 115200 bps</li>
 <li>Control automático de envío de datos, detección automática de transmisión de datos y de sentido de dirección</li>
 <li>Detección automática de velocidad de transmisión sin retraso</li>
 <li>Certificaciones FCC, CE y aprovación RoHS</li>
