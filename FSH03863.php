<p>El amplificador analógico IAA100 con salida de voltaje es la nueva solución de amplificador de uso general de FUTEK para la amplificación en línea de cualquier sensor de tipo extensómetro de puente completo con salida de rango mV / V. El nuevo modelo combina precisión y facilidad de integración con un error total del 0.005%. El IAA100 presenta una carcasa de aluminio con un clip DIN integrado diseñado para aplicaciones en entornos industriales.
</p><br>

<strong>Caracteristicas:</strong>
<ul>
<li>Salida Bipolar, Entrada Diferencial</li>
<li>± 5 o ± 10 salidas VDC</li>
<li>Excitación del puente: 5 o 10 VDC (interruptor DIP)</li>
<li>Gamas: 0.5, 1.0, 1.5, 2.0, 2.5, 3.0, 4.0, 10.0 mV / V (Interruptor DIP)</li>
<li>256 Combinaciones de Shunt seleccionables: 30kO, 43.7kO, 60.4kO, 87.6kO, 100kO, 150kO, 300kO, 432kO (Interruptor DIP)</li>
<li>Botón de activación Shunt Cal accesible externamente</li>
<li>Shunt remoto controlado digitalmente</li>
<li>Potenciómetros internos y compensados</li>
<li>Interruptor DIP de polaridad de inversión del sensor</li>
<li>Interruptor DIP Zero Shift</li>
<li>Certificación de Clase 1 para dispositivos aeroespaciales y de grado médico</li>
</ul>

