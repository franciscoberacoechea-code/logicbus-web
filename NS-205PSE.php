<center><strong>Conmutador Power-over-Ethernet (PoE) 10/100 Base-T (x) Industrial Unmanaged de 5 puertos. Entradas de alimentación + 46VDC ~ + 55VDC. Admite temperaturas de funcionamiento de -30 ° C ~ + 75 ° C (-22F ~ 167F). Tiene un montaje en carril DIN.</strong></center><br>

<p>El NS-205PSE es un conmutador Ethernet industrial PoE (Power-over-Ethernet) no gestionable de 5 puertos, tiene 4 puertos PoE que se clasifican como equipos de fuente de alimentación (PSE). El NS-205PSE hace que la fuente de alimentación centralizada se haga realidad y proporciona hasta 15.4 vatios de potencia por puerto. El NS-205PSE se puede usar para alimentar los dispositivos con alimentación (PD) compatibles con IEEE802.3af por cable Ethernet y elimina la necesidad de cableado de alimentación adicional.</p><BR>

<strong>Caracteristicas</strong>

<ul>
<li>Crossover automático MDI / MDI-X para plug-and-play</li>
<li>Cada puerto admite la negociación automática de velocidad a 10 / 100Mbps</li>
<li>Arquitectura de almacenamiento y reenvío</li>
<li>Control de flujo de contrapresión Full Duplex IEEE 802.3xy semidúplex</li>
<li>Ancho de banda de memoria de alto rendimiento de 3.2 Gbps.</li>
<li>Entradas de alimentación +46 ~ + 55V DC</li>
<li>Admite temperaturas de funcionamiento de -30 ° C ~ + 75 ° C</li>
<li>Montaje en riel DIN</li>
<li>Puertos PoE compatibles con IEEE 802.3af</li>
<li>Cuatro puertos PoE con operación del equipo de abastecimiento de energía (PSE)</li>
<li>Detección automática de PD (dispositivos con alimentación) y administración automática de energía</li>
<li>Detección de sobretemperatura, sobrecorriente y sobre / bajo voltaje</li>
</ul>
