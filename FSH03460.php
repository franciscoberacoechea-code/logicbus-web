<p>La pantalla digital portátil de mano IHH500Es la solución de FUTEK que se puede integrar fácilmente para trabajar con células de carga, sensores de par y sensores de presión. El IHH500 tiene un rango de entrada de hasta +/- 500 mV/V. Además de la entrada de mV/V, el dispositivo acepta sensores de salida amplificada en el rango de ± 12 VDC o hasta 30 mA. También tiene dos relés individuales y dos salidas analógicas de voltaje y corriente analógica. Este dispositivo proporciona 24 VDC/5VDC adicionales como fuente de alimentación para sensores con amplificador incorporado. La pantalla de mano de FUTEK también es compatible con TEDS, lo que facilita el cambio entre diferentes sensores. Un ADC de alta velocidad/bajo ruido/alta resolución (24 bits) está integrado en el dispositivo para que sea adecuado para mediciones de alta precisión. El IHH500 utiliza una batería recargable con una larga vida útil. Esta pantalla digital en particular también tiene la capacidad de mostrar valores en una computadora a través de un enlace USB.</p>

<strong>CARACTERÍSTICAS:</strong>
<ul>
<li>Medición de velocidad/potencia.</li>
<li>Medida de resistencia de puente.</li>
<li>Opciones del teclado (Rastrear/Mantener, Restablecer Pico/Valle, Unidad, Tara/Bruto, Derivación, Batería, Pantalla, Menú).</li>
<li>First Peak/First Valley Feature.</li>
<li>Menú de navegación fácil de usar.</li>
<li>Calibración de derivación.</li>
<li>Conversión de unidades universales.</li>
<li>Admite el estándar IEEE1451.4 (plantillas TEDS 30 y 33).</li>
<li>Salida USB.</li>
<li>Salida ASCII Stream.</li>
<li>Configuración de salida de voltaje y corriente seleccionable.</li>
</ul>

