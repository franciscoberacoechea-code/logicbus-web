        <p>La serie DN-8468 es una daughter-board diseñada para los controladores de movimiento de 4 ejes, como I-8094,
          I-8094F, I-8094A, I-8094H y PISO-PS400. Y son para diferentes controladores de motor, como uso general, el
          amplificador de motor Mitsubishi y Panasonic. No es solo una placa de terminales atornillada para una fácil
          conexión de señales; también proporciona circuitos de aislamiento a bordo para proteger los controladores. Las
          señales de interfaz se dividen en cuatro grupos. Cada grupo corresponde a un solo eje y contiene las líneas de
          comando de salida de impulsos necesarias, líneas de realimentación del codificador, entradas de propósito
          especial (Inicio, cerca del hogar, interruptores de límite) y una salida de servo habilitación. Los conectores
          de terminal se utilizan para facilitar el cableado.<br><br>
          Los usuarios pueden intercambiar conectores para intercambiar cada definición axial sin tener que volver a
          cablear laboriosamente. Esta placa también contiene un módulo de potencia integrado que proporciona diferentes
          voltajes para otros circuitos incorporados. Y este módulo de potencia acepta una gran potencia de entrada (20
          ~ 26 VDC).</p>

        <strong>Características:</strong>
        <ul>
          <li>Foto-acoplamiento de alta velocidad aislado.</li>
          <li>Tipos de comando de pulso Step Motors o Servo Motors.</li>
          <li>Suministro de LED de alimentación y otros LEDs de estado (Inicio, Interruptores de límite, ...).</li>
          <li>Proporcionar un terminal FRnet para la expansión de E/S en serie de alta velocidad cuando el controlador
            admite FRnet.</li>
        </ul>
