<center><strong>Convertidor de protocolos CAN open / DCON Gateway</strong></center><br>

<p>El I-7231D está especialmente diseñado para el dispositivo esclavo del protocolo CANopen. Sigue el CANopen Spec DS-301 V4.02 y DSP-401 V2.1, y proporciona muchas características para los usuarios, tales como DOP dinámico, objeto EMCY, valor de salida de error, SYNC cíclico y acíclico... etc. El I-7231D admite hasta 15 módulos DCON para la expansión de E / S y se adapta a una gran cantidad de ICP DAS DI / AI / DO / AO módulos. El usuario puede elegir módulos DI / DO / AI / AO de la serie I-7K / I-87K para adaptarse a la práctica personalizada aplicaciones. Además, también proporcionamos la utilidad I-7231D para permitir a los usuarios crear el archivo EDS dinámicamente.</p>


<ul>
<strong>Especificaciones:</strong>

<li>NMT: Esclavo</li>
<li>Control de errores: Node Guarding / Heartbeat Producer</li>
<li>Nº de SDO: 1 servidor, 0 cliente</li>
<li>Nº de DOP: valor predeterminado 4 TxPDO y RxPDO</li>
<li>Modalidades PDO: Evento desencadenado, solicitado a distancia, SYNC cíclico y acíclico</li>
<li>Mensaje de emergencia: disponible</li>
<li>Versión CANopen: DS-301 v4.02</li>
<li>Perfil del dispositivo: DSP-401 v2.1</li>
<li>Produzca el archivo EDS de forma dinámica</li>
<li>Ejecutar, ERR e indicador de rebasamiento</li>
<li>Soporta módulos de la serie Max 15 I-7K / I-87K</li>
<li>Configuración de CAN Baud Rate por utilidad: 10K, 20K, 50K,</li>
<li>125K, 250K, 500K, 800K, 1M bps</li>
<li>LED de 7 segmentos para mostrar ID de nodo, velocidad en baudios CAN y velocidad de baudios RS-485</li>
</ul>

