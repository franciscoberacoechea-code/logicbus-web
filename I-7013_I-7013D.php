          <center><strong>Módulo de adquisición de datos de entrada RTD con 1 canal analógico (tipo de entrada RTD), transmisible a través de RS-485, y software EZ Data Logger GRATUITO. Admite temperaturas de funcionamiento entre -25 ° C ~ + 75 ° C (-13 ° F ~ + 167 ° F).</strong></center><br>

          <p>I-7013 es un módulo de entrada RTD de un solo canal. I-7013 es una solución rentable para una amplia gama de valiosas señales y sistemas de control industrial. La utilidad DCON puede ayudar a los usuarios a configurar y probar los módulos I-7013. Se proporcionan muchas funciones de biblioteca y programas de demostración para permitir a los usuarios desarrollar programas fácilmente en sistemas operativos Windows, Linux y DOS. Los usuarios pueden montar los módulos en un riel DIN, panel o pared. Los módulos tienen un bloque de terminal de tornillo para conectarse a las señales. I-7013 viene con el software EZ Data Logger GRATIS.</p><BR>

          <strong>Características:</strong>
          <ul>
            <li>Entrada analógica aislada 3000VDC</li>
            <li>ADC sigma-delta de 24 bits para proporcionar una precisión excelente</li>
            <li>Conexión directa de termopar con CJC incorporado</li>
            <li>Calibración de software</li>
            <li>Dual Watchdog</li>
          </ul>


