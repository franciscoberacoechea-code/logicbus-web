                <p class="text-center light-black font-weight-bold">¿Qué son los sistemas Steer-by-Wire?</p>

                <p class="light-black">Tradicionalmente, los vehículos automotores de carretera y todoterreno utilizan un sistema hidromecánico para la dirección. El sistema mecánico suele estar formado por un mecanismo de dirección de piñón y cremallera que está físicamente conectado al volante.</p>
                <p class="light-black">En los años 80 y 90, la dirección asistida se hizo popular y ayudó a reducir la cantidad de fuerza necesaria para girar el volante. Esto se logró a través de un actuador hidráulico que asiste en el giro del mecanismo de dirección de piñón y cremallera. Incluso con la dirección asistida eléctrica, el mayor desafío son las limitaciones de los componentes mecánicos.</p>
                <p class="light-black">La tecnología Steer-by-Wire (SbW) o Drive-by-Wire (DbW) en la industria automotriz es el uso de electrónica, actuadores y algoritmos para reemplazar las conexiones hidráulicas y mecánicas entre el volante manual y la carretera. Esta tecnología reemplaza los sistemas de control mecánico tradicionales con sistemas de control electrónico y este concepto es muy similar a los sistemas fly-by-wire ampliamente utilizados en la industria de la aviación.</p>

                <p class="text-center light-black font-weight-bold">¿Cómo se utilizan los sensores de par de dirección en los sistemas Steer-by-Wire?</p>
                <p class="light-black">Los sensores de par de reacción y de múltiples ejes se utilizan con frecuencia en el entorno de prueba de dirección por cable para validar el diseño del sistema de control. Los sensores de par y los transductores de múltiples ejes se instalan en el volante (módulo de entrada) y en la transmisión de piñón y cremallera (módulo de actuación) durante la fase de verificación y validación para auditar y calibrar el sistema de control de dirección por cable (parámetros del bucle de control, dinámica de los actuadores). Los sistemas de dirección por cable deben validarse durante la fase de diseño del producto y requieren una auditoría extrema antes de implementarse en el producto comercial final.</p>
                <p class="light-black">Los ingenieros de diseño de automóviles pueden aprovechar el sensor de torque multieje de alta precisión de FUTEK para auditar y validar nuevos diseños de sistemas de dirección por cable, así como para calibrar los sistemas de control de retroalimentación.</p>

                <p class="text-center light-black font-weight-bold">¿Cómo funciona?</p>
                <ol class="light-black">
                    <li class="mb-3">Volante/columna de dirección: durante la fase de validación del producto, el sensor de par y empuje de perfil bajo QMA148 proporciona a los ingenieros de control y garantía de calidad las herramientas adecuadas para medir el par de rotación aplicado a los controles de dirección. Este sensor de par multieje también se puede utilizar para controlar la tracción y el empuje de las manos del conductor en el volante a medida que acelera y desacelera y/o la medición de la fuerza de impacto frontal de los maniquíes de prueba de choque. El sensor de par y empuje de perfil bajo QMA148 de FUTEK se instala entre el volante y la columna de dirección.</li>
                    <li class="mb-3">Módulo de accionamiento/engranaje de dirección: durante la validación del diseño del producto, los ingenieros de control deben medir el par de accionamiento que se aplica a la transmisión de piñón y cremallera (módulo de accionamiento). Esto garantiza la calibración adecuada del circuito de control de par. Los sensores de par de reacción personalizados de FUTEK se pueden instalar con el actuador de ángulo de dirección para medir el par de accionamiento real ejercido y calibrar correctamente el módulo de accionamiento mediante retroalimentación de par adicional.</li>
                </ol>
