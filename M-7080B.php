<center><strong>Entrada de frecuencia / contador de 2 canales con batería de respaldo. Se comunica sobre Modbus RTU y el protocolo DCON. Viene con el software gratuito EZ Data Logger para registro de datos y monitoreo remoto. Admite temperaturas de funcionamiento entre -25 ° C ~ 75 ° C (-13 ° F ~ + 167 ° F). Tiene un soporte de riel din.</strong></center><br>
 <br>

<p> 
El M -7080B está inteligentemente diseñado para proporcionar acondicionamiento de señales, monitoreo del sistema y ajustes de valores seguros. Es un módulo de entrada de contador / frecuencia con respaldo de batería que admite Modbus RTU. En caso de falla de energía, mantendrá las lecturas debido a la batería de respaldo. Es una solución rentable para una amplia gama de valiosas señales y sistemas de control industrial.<BR><BR>

La utilidad DCON puede ayudar a los usuarios a configurar y probar el módulo de entrada de frecuencia / contador de alta velocidad M-7080. Se proporcionan muchas funciones de biblioteca y programas de demostración para permitir a los usuarios desarrollar programas fácilmente en sistemas operativos Windows, Linux y DOS. La interfaz de comunicación es el protocolo Modbus a través de RS-485 y también Modbus RTU para comunicarse fácilmente con el software SCADA / HMI más popular y PLC. Los usuarios pueden montar los módulos en un riel DIN, panel o pared. Los módulos tienen un bloque de terminal de tornillo para conectarse a las señales.
</p><BR>

<strong>Caracteristicas:</strong>
<ul>
<LI>Entrada digital de 2 canales / frecuencia, contacto húmedo, tipo de fregadero</LI>
<LI>Equipado con respaldo de batería, puede funcionar en caso de pérdida de potencia.</LI>
<LI>Admite protocolos Modbus RTU y DCON</LI>
<LI>± 4 kV Protección de contacto ESD para cada terminal</LI>
<LI>Admite un rango de entrada de alimentación de 24 ~ 30 VDC</LI>
<LI>Consumo de energía: 2.0 W</LI>
<LI>Montaje en pared o riel DIN</LI>
<LI>Admite temperaturas de funcionamiento de -25 ~ + 75 ° C (-13F ~ 167F).</LI>
</ul>
