   </tr>
   <tr>
     <td height="17" colspan="2"><ul>
       <li> Tres modos diferentes de operaci&oacute;n; mensajes SMS, GPRS, Datos de llamada CSD (todos ellos al mismo tiempo)</li>
       <li> Puerto USB para monitoreo y actualizaci&oacute;n de firmware</li>
       <li> Bater&iacute;a de Li-ion 1700 mAh, 24 horas de operaci&oacute;n</li>
       <li> Interruptor Mec&aacute;nico para desconectar y conectar la bater&iacute;a interna</li>
       <li> El mas bajo nivel de la funci&oacute;n watchdog</li>
       <li> Puede ser usado directamente con los PLCs FBS-xxMC (Puerto 3) o mediante el adaptador de comunicaci&oacute;n  CA0 para PLCs FBS-xxMA (Puerto 2)</li>
       <li> La funci&oacute;n SMS es completamente bajo el control del programa del PLC</li>
       <li> No se necesita el soporte del programa del PLC para la operaci&oacute;n de CSD y GPRS, excepto para la configuraci&oacute;n de muchos registros del PLC</li>
       <li> Leds indicadores para monitoreo del equipo</li>
       <li> Un FBS-CMGSM puede utilizarse para hacer una RED de PLCs. Las entradas y salidas 
       pueden estar situadas en diferentes lugares</li>
       <li> Un FBS-CMGSM soporta un n&uacute;mero ilimitado de I/O digitales y an&aacute;logas (red del PLC) </li>
