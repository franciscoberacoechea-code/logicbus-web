          <center><strong>Módulo de adquisición de datos de entrada analógica de 10 canales, admite entrada de corriente, entrada de voltaje y entrada de termopar. Se puede comunicar a través de Modbus RTU y RS-485 con protección de alto voltaje y cable.</strong></center><br>
          <br>

          <p> 
            El M-7018Z es un módulo de adquisición de datos de entrada de termopares de tensión y corriente de 10 canales. Se puede comunicar a través de Modbus RTU y RS-485 con protección de alto voltaje. Admite temperaturas de funcionamiento entre -25 a 75 ° C (-13F ~ 167F). El M-7018Z viene con un DB-1820 Daugther Board que admite Modbus RTU. Se pueden controlar de forma remota utilizando un conjunto de comandos denominado protocolo DCON. Con el protocolo Modbus RTU, puede comunicarse fácilmente con el software SCADA y PLC más populares.</p><BR>

          <strong>Características:</strong>
          <ul>
            <LI>Entrada analógica de 10 canales</LI>
            <LI>Consistencia de salida de temperatura</LI>
            <LI>Salida de temperatura estable en el campo</LI>
            <LI>Entrada de corriente, voltaje y termopar</LI>
            <LI>Protección contra sobretensiones de hasta 240 Vrms</LI>
            <LI>Configuración individual del canal</LI>
            <LI>Detección abierta de termopar</LI>
            <LI>Protección contra ESD de 4 kV</LI>
            <LI>Aislamiento intramódulo de 3000 VDC</LI>
            <LI>Dual Watchdog</LI>
            <LI>Amplio rango de temperatura de funcionamiento: -25 a + 75 ° C</LI>
          </ul>
