<center><strong>Tarjeta PCI, cuenta con 144 entradas/salidas digitales, provee un conector de DB-37, proporciona 4 fuentes de interrupción, voltaje de alimentación PCI 5V @ 1100mA.</strong></center><br>


<p>El PIO-144 proporciona 144 líneas de E / S digitales TTL. El DIO-144 emula el modo 8255 0 y tiene una corriente de salida aumentada de 15 mA (fuente) y 64 mA (sumidero), lo que le permite controlar los LED y el relé. El DIO-144 consta de dieciocho puertos bidireccionales de 8 bits y 2 líneas de entrada para habilitar e interrumpir la interrupción. Los puertos de 8 bits se denominan puerto A (PA), puerto B (PB) y puerto C (PC). El puerto C se puede dividir en dos puertos de cuatro bits. Todos los puertos se configuran como entradas al encender o restablecer. El DIO-144 usa 4 direcciones de E / S. La dirección base se puede seleccionar de 200 a 3FF hex. La señal de interrupción se puede conectar a cualquiera de los niveles de interrupción, de 2 a 7.
</p><BR><br>

<strong>Caracteristicas</strong>

<ul>
<li>Admite el bus PCI de + 5V para PIO-D144</li>
<li>Admite el bus PCI + 3.3 / + 5 V para PIO-D144U / D144LU</li>
<li>Admite PCI Express x 1 para PEX-D144LS</li>
<li>144 canales de E / S digital</li>
<li>18 puertos de E / S bidireccionales de 8 bits</li>
<li>Puentes pull-high / pull-low para canales DI para PIO-D144LU / PEX-D144LS</li>
<li>Función de identificación de tarjeta para PIO-D144U / D144LU y PEX-D144LS</li>
<li>PIO-D144 / D144U / D144LU: cinco conectores de cable plano de 50 clavijas y un conector de 37 clavijas</li>
<li>PEX-D144LS: Un conector SCSI II de 100 pines y un conector de cable plano de 5 pines.</li>
<li>PIO-D144 / D144U / D144LU: el tiempo de respuesta DIO es de aproximadamente 1 µs (1MHz)</li>
<li>PEX-D144LS: el tiempo de respuesta DIO es de aproximadamente 500 kHz</li>
</ul>
