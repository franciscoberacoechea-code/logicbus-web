<center><strong>Controlador inteligente de datos PAC Logger con capacidades SMS, MiniOS7, comunicable a través de Ethernet, RS-485, RS-232, Modbus TCP, Modbus RTU. Admite temperaturas de funcionamiento de -25 ~ + 75 ° C</strong></center><br>
