          <p>El tM-AD5 es un módulo de entrada analógica que incluye 5 canales de entrada analógicos diferenciales y proporciona un rango de entrada programable en todas las entradas analógicas (+/- 500 mV, +/- 1 V, +/- 2.5 V, +/- 5 V, +/- 10 V). Proporciona una protección de sobretensión de 120 VDC. La velocidad de muestreo del tM-AD5 es ajustable y está disponible en modo rápido o normal y también proporciona protección de 4 KV ESD así como aislamiento intra-módulo de 2500 Vrms.</p><br>

          <strong>Caracter&iacute;sticas </strong>
          <ul>
            <li>Entradas diferenciales de 5 canales.</li>
            <li>Entradas de tensión.</li>
            <li>Protección de sobretensión de 120 VCC.</li>
            <li>Resolución: 14/12 bits.</li>
            <li>Frecuencia de muestreo ajustable.</li>
            <li>4 kV ESD y EFT Protection.</li>
            <li>Protección contra sobretensiones de 3 kV.</li>
            <li>Dual Watchdog.</li>
            <li>Aislamiento intramódulo de 2500 V CC.</li>
            <li>Amplio rango de temperatura de funcionamiento: -25 ~ +75°C.</li>
          </ul>

