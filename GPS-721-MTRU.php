<center><strong>Módulo de receptor GPS remoto con 1 DO y 1 salidas PPS..</strong></center><br>

<p>El GPS-721-MRTU, una nueva solución de GPS para el módulo Receptor GPS remoto, que ofrece alta sensibilidad, bajo consumo de energía y factor de forma ultra pequeño con protocolos DCON, Modbus RTU y GPS. Este potente elemento le proporciona una sensibilidad superior y un rendimiento sobresaliente incluso en el entorno más hostil. El GPS-721 proporciona un canal adicional de 1 canal y un canal de control de acceso (PPS) para los usuarios. Las señales PPS se pueden utilizar para medir el tiempo y el tiempo. Uno puede combinar la funcionalidad PPS con otra como fuente de sincronización de tiempo.
<br><br>
Por lo tanto, el GPS-721 puede ser un potente módulo remoto GPS así como un módulo GPS de propósito general con interfaz RS232. También se puede aplicar en navegación automotriz, posicionamiento personal y navegación, navegación marina, corrección de tiempo satelital, etc.</p>

Caracteristicas:
<ul>
<li>Soporta GPS de 32 canales y NMEA v0183 v3.01 (Baudrate 9600 bps).</li>
<li>RS-485 soporta el protocolo DCON y Modbus RTU.</li>
<li>RS-232 soporta el formato NMEA v3.01 v0183, DCON o protocolo Modbus RTU.</li>
<li>Incorporado de 1 canal DO, 1 canal PPS (1 pulso por segundo), 1 puerto RS-485, 1 puerto RS-232.</li>
<li>PPS: salida de impulsos de 100 ms / s para la medición precisa del tiempo y el tiempo.</li>
<li>10 ~ 30 VDC - (Protección de polaridad inversa de potencia).</li>
<li>Con varios indicadores LED del sistema.</li>
<li>Diseño de riel DIN.</li>
</ul>
Aplicaciones:
<ul>
<li>Navegación automotriz.</li>
<li>Posicionamiento personal y navegación.</li>
<li>Navegación marina.</li>
<li>Corrección del tiempo del satélite.</li>
<li>Cronometraje preciso y medición del tiempo.</li>
</ul>
