<article>
  <p><b>Resumen de la aplicaci&oacute;n:</b>
La cirugía mínimamente invasiva (MIS) y la cirugía de acceso de puerto único (SPAS) han reducido drásticamente el riesgo y el tiempo de recuperación para los pacientes que se someten a extracción de tumores, reparación de arterias y válvulas cardíacas y fertilización in vitro. Ya sea que se realice con un sistema quirúrgico robótico o con las manos entrenadas de un cirujano, se requiere instrumentación de precisión para trabajar con los delicados tejidos del paciente mientras se proporciona un agarre preciso y seguro sin ejercer una fuerza excesiva. Las fuerzas aplicadas con instrumentación robótica deben calibrarse de modo que los mecanismos de retroalimentación visual y háptica informen sobre las fuerzas aplicadas correctas durante la cirugía. La instrumentación manual requiere la verificación de las fuerzas aplicadas para que las sensaciones táctiles que siente el cirujano sean predecibles y consistentes.
 
</p>

<img src="imagenes/soluciones-en-la-industria/farmaceutica-y-laboratorio/Calibracion-De-Herramientas-Laparoscopicas.jpg" alt=" Celda de carga  prueba de jeringas" width="70%">


<div>
  <p><b>C&oacute;mo funciona:</b><br></p>
  <ol>
    
<li style="color: black;">Las celdasas de carga permiten a los profesionales médicos verificar que las herramientas de sujeción apliquen la cantidad adecuada de fuerza antes de que se utilicen en cirugía.

</li>
<li style="color: black;">En esta aplicación, el botón de carga en miniatura de FUTEK (<strong><a href="https://www.logicbus.com.mx/LLB130" target="_blank">LLB130</a></strong>) se monta en la punta de agarre de un instrumento de mano laparoscópico. La celda de carga registra las mediciones de fuerza, que se pueden utilizar para calibrar la herramienta.

</li>
<li style="color: black;">La retroalimentación de carga se puede mostrar en las pantallas digitales <strong><a href="https://tienda.logicbus.com.mx/FSH03571_p_6818.html" target="_blank">IHH500</a></strong> o <strong><a href="https://tienda.logicbus.com.mx/Paneles_c_1663.html" target="_blank">IPM650</a></strong> de FUTEK, o transmitirse a través de <strong><a href="https://tienda.logicbus.com.mx/FSH03634_p_6807.html" target="_blank">USB</a></strong> a una PC. Luego, estos datos se pueden examinar para determinar si la herramienta es adecuada para el funcionamiento o si es necesario ajustarla.

</li>
<li style="color: black;">El emparejamiento del software de prueba y medición SENSIT ™ con cualquiera de los instrumentos de FUTEK le brinda al usuario la capacidad de registrar datos de las mediciones y almacenarlas para llevar un registro o historial de calibración.
</li>

