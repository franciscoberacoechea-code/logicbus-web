 El USB-2404-10 es un dispositivo USB de alta velocidad con cuatro entradas de 24-bits simultánea analógica con una frecuencia de muestreo de 50 kS / s por canal, y una entrada de ± 10 V Rango de voltaje. El USB-2404-10 es totalmente compatible con USB 1.1 y USB 2.0. Un filtro anti-alias elimina el ruido que pueden estar presentes en las señales antes de la conversión. 250 Vrms canal a canal y el aislamiento de canal a tierra protege el módulo y equipo contra picos de suelo, y asegura un flujo de datos confiable. A bordo de LED indica el estado del dispositivo. conexiones de campo realizados en cuatro de 2 polos, terminales de tornillo desmontable. El USB 2.0 de alta velocidad del conductor transferencias de datos a velocidades de hasta 480 Mbps. Energía para el USB-2404-10 viene de  5 voltios USB de su ordenador. No necesita alimentación externa.<br>
