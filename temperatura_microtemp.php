            <br><br>
            La tecnología en miniatura de MadgeTech abre nuevas opciones para documentar y garantizar entornos adecuados para productos farmacéuticos, investigación biomédica, procesamiento de alimentos y transporte. Nuestro software fácil de usar pero versátil no solo le permite ver los datos en unidades de temperatura comunes, como ºC y ºF, sino también en Kelvin y Rankine. 
