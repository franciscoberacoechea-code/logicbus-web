<h2><center>Diagramas de aplicaciones<br>Línea de ensamble/Automatización</center></h2>

<div align="center"><img src="imagenes/36/application_108_LLB500.jpg" alt="Aplicaciones" width="50%" class="image_productos"></div><br>

<p align="justify">A continuación se presenta una línea común de ensamble. Es una línea de montaje de cinta transportadora donde una pieza de metal está viajando a través de varias operaciones. El primer paso es la estación de punzado / estampado en el que se está monitoreando la carga especificada. Cuando la herramienta golpea, la carga sale de su intervalo aceptado y se lo comunica al usuario para cambiar de la herramienta.
<br><br>
A continuación, en la estación siguiente, la herramienta se controla mediante la medición de un par / fuerza. En ambos casos la información puede ser proporcionada en formato digital y enviada a un SPC (control estadístico de procesos) para su posterior análisis.</p><br>
