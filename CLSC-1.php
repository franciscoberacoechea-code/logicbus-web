<p>El primer sensor ultrasónico de etiqueta transparente con pantalla gráfica OLED para controlar el rendimiento del sensor. En el sensor están diseñadas todas las características de facilidad de uso que han hecho que los sensores de TRI-TRONICS sean tan conocidos en la industria.
<br><br>
La tecnología ultrasónica junto con el procesamiento de señal digital facilita la detección de etiquetas claras y opacas sobre un material de respaldo transparente u opaco. La presentación de la pantalla gráfica OLED en lugar de las simples luces indicadoras ofrece al usuario una vista sin precedentes del rendimiento, las opciones, los modos del programa y las sencillas instrucciones útiles del sensor nunca antes ofrecidas en un sensor de etiqueta transparente. Una placa de separación extraíble de acero inoxidable y una carcasa de aluminio anodizado hacen que este sensor sea resistente. La configuración es rápida presionando un botón para la etiqueta y una vez para el espacio de etiqueta.
</p><br>

<b>Características:</b>
<ul>
<li>Pantalla alfanumerica OLED.</li>
<li>Indicador de contraste grafico de 10 barras.</li>
<li>Pantalla numerica estática y dinamica.</li>
<li>AUTOSET de un boton (Establece espacio).</li>
<li>Tweak-able (Ascenso/Descenso momentáneo ajustables).</li>
<li>Temporizadores y retardos disponibles.</li>
<li>Versión de cable y conector (M12 y M8).</li>
<li>Placa de protección desmontable.</li>
<li>Alta velocidad (200µs) (1800 pies/548 m por minuto).</li>
<li>Alojamiento duradero y robusto.</li>
<li>Compatible con configuraciones de montaje existentes.</li>
</ul>
