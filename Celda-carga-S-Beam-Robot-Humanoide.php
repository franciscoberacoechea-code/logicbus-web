<div align="center"><h2>CELDA DE CARGA S-BEAM</h2></div><br>
<p>Las celdas de carga tipo S, también conocidas como celdas de carga tipo Z, son una opción popular para muchas aplicaciones, ya que funcionan en tensión o compresión, por lo que son ideales para instalaciones donde la carga puede cambiar de tensión a compresión y viceversa. Las celdas de carga de vigas S se usan comúnmente cuando la instalación cuelga de la celda de carga e incluye medidas de seguridad integradas. Nuestras celdas de carga de vigas en Z están disponibles desde 20 kg y son adecuadas para aplicaciones delicadas hasta grandes capacidades de 20000 kg / 20t. Para un mejor rendimiento, instale también los extremos de las barras o los botones de carga Todas las celdas de carga pueden suministrarse individualmente o combinadas con nuestra instrumentación de vanguardia para un sistema de pesaje completo.<br>
La celda de carga tipo viga, tiende a ser utilizada frecuentemente por la variedad de opciones disponibles. Entre las aplicaciones encontramos máquinas de llenado, plataformas industriales empotradas, pesaje de tanques y silos, además de pesaje a bordo en vehículos, equipamiento médico y procesos controlados por pesaje, en las que la instalación de una celda de carga tipo viga es requerida.</p></br></br>

<div align="center"><h2>CELDA DE CARGA DEL ROBOT HUMANOIDE</h2></div><br>

<p align="justify">Una de las marcas que se asoció con The Robot Studio es FUTEK, ya que esta organización es un especialista en hardware robótico biométrico, para construir un robot humanoide de funcionamiento completo. En este proyecto hay más de 60 celdas de carga en miniatura S-Beam LSB200 Jr. De FUTEK en funcionamiento que monitorean los movimientos del robot. A continuación se mencionará su función de este proyecto.</p>
