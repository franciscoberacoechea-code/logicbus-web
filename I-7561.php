<h1>I-7561</h1>

<div align="center">
<img src="imagenes/02/I-7561.jpg" width="189" alt="I-7561" border="0" align="top"><br><br>
<strong>Convertidor de USB a RS-232/422/485</strong>
</div>

<div align="right"> 
 <a href="https://tienda.logicbus.com.mx/I-7561_p_1495.html" title="Ir a Tienda" target="_blank"><img src="images/shopping_cart.png" alt="Ir a Tienda"></a>
