<center><strong>Módulo de 8 canales de entrada digitales aislados de 10-80VAC con contadores de 16 bits.</strong></center><br>

<p style="text-align: justify;">El I-87059W es un módulo de entrada digital de AC de 8 canales con aislamiento de alto voltaje. El nivel de voltaje ON para el rango del módulo puede estar entre 10 y 80 VCA, y todos los canales DI también se pueden usar como contadores de 16 bits.</p><br>


<strong>Caracteristicas:</strong>
<ul>
<li>8 canales de entrada digitales AC</li>
<li>Filtro de paso bajo</li>
<li>Aislamiento de fotoacoplamiento</li>
<li>Toda la entrada de canales digitales se puede usar como contador</li>
<li>Pantalla LED de E / S</li>
<li>± 4 kV Protección ESD</li>
<li>Aislamiento intramódulo 5000 Vrms</li>
<li>Aislamiento de canal a canal de 2 kV</li>
<li>Proteccion al sobrevoltaje</li>
<li>Amplio rango de temperatura de funcionamiento: -25 a + 75 ° C</li>
</ul>



