<center><strong>Tarjeta de 32 Canales de entradas Analógicas, dos canales D/A y E/S Digitales, 330KS/s de 12 bit a baja ganancia (palabra FIFO de 8K)</strong></center><br>


<p>La serie PCI-1800 es una familia de placas de adquisición de datos de alto rendimiento para PC con un bus PCI. Presenta una adquisición continua de datos sin brechas, de 330 KHz para baja ganancia (44 KHz para ganancia alta) en DOS y Windows. La familia PCI-1800 tiene la misma arquitectura y tiene dos canales de salida D / A de 12 bits, 16 canales de entrada digital y 16 canales de salida digital. El PCI-1800H, PCI-1800L proporciona 16 entradas diferenciales de terminación única u 8. El PCI-1802H y el PCI-1802L proporcionan 32 entradas diferenciales de terminación única o 16. El -H significa el modelo de alta ganancia y el -L significa el modelo de baja ganancia. La función de escaneo de PCI-1800 es increíble. Lo llamamos Magic Scan. La función de escaneo de canal variable se encuentra en algunas placas de adquisición de datos famosas. Comparado con el escaneo de canales variables, Magic Scan mejora muchas funciones y satisface la demanda de usuarios de alto nivel. El mecanismo de Escaneo Mágico no solo escanea los diferentes canales de entrada a tasas muy diferentes, sino también a diferentes ganancias. Incluso en exploraciones multicanal, las tasas de muestreo pueden mantenerse a 330KS / s.  
</p><BR><br>

<strong>Caracteristicas</strong>

<ul>
<LI>Bus PCI (v2.1), 33 MHz 5 V 32 bits.</LI>
