<center><strong>Ethernet industrial 10/100 BaseT no administrada de 4 puertos con conmutador de fibra óptica dual 100 BaseFX con conector SC.</strong></center><br>

<p>El NSM-206FC (conector SC, modo múltiple) es un Industrial 10/100 Base-T (X) de 4 puertos no gestionado con conmutador dual de base 100 FX que asegura la transmisión de datos mediante el uso de transmisión de fibra óptica para proporcionar inmunidad frente a EMI / Interferencia RFI. Utiliza Ethernet para transmitir una señal de hasta 2Km (6,600 pies), y es la solución perfecta para aplicaciones donde la transmisión debe protegerse de la exposición eléctrica, sobrevoltajes, rayos o corrosión química. El NSM-206FC funciona en modo half o full duplex. En modo dúplex completo, el rango es de 2Km con cables de fibra de 62.5 / 125μm; en modo semidúplex su alcance es de 412 m con cables de fibra de 62.5 / 125μm. El NSM-206FC puede extender su LAN en una configuración de conexión en cadena. Consulte el Manual del usuario "target =" _ blank "> Manual del usuario. NSM-206FC proporciona dos entradas de alimentación que se pueden conectar simultáneamente a fuentes de alimentación de CC en vivo. Si una de las entradas de alimentación falla, la otra fuente en vivo actúa como una copia de seguridad para admitir automáticamente las necesidades de energía del NSM-206FC.</p><BR>

<strong>Caracteristicas</strong>

<ul>
<LI>Proporciona un puerto de fibra 2 x 100-FX más 4 puertos Ethernet.</LI>
<LI>Cada puerto admite una negociación automática de velocidad de 10/100 Mbps.</LI>
<LI>Control de flujo de contrapresión Full Duplex IEEE 802.3xy semidúplex.</LI>
<LI>Crossover automático MDI / MDI-X para plug-and-play.</LI>
<LI>Arquitectura de almacenamiento y reenvío.</LI>
<LI>Admite temperaturas de funcionamiento de 0 ~ +70 ° C.</LI>
</ul>
