          The heart of every PowerDNA system is the Cube. The DNA-PPC8 Cube is 4" x 4.1" x 5.8" and is packed with power and flexibility. Each I/O Cube consists of two primary subsections. The top level of the cube provides the Cube Controller, Network Interface and power supply. The lower levels of the cube provide I/O slots. With over 30 different I/O boards available, PowerDNA is sure to offer a configuration perfectly matched to your application. <br>
          <br>
          The PowerDNA Cube is supported by all popular Windows, Vista, Linux and Real-time operating systems. Our UEIDAQ Framework provides a simple and universal API and supports all common programming languages. The Cube is also fully supported by an extensive array of application packages including LabVIEW, MATLAB, DASYLab and more.<br>
