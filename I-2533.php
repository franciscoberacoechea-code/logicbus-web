<center><strong>Convertidor CAN a fibra optica</strong></center><br>

<p>I-2533 es un puente local CAN usado para establecer una conexión entre dos sistemas bus CAN vía fibra óptica como medio de transmisión.  Para resolver el problema entre la transmisión CAN y fibra, I-2533 esta especialmente diseñado para convertir la señal CAN eléctrica a fibra óptica.
<BR><BR>
El modelo I-2533 tiene tres características importantes.  Primero, el límite de distancia de transmisión de los sistemas CAN no se reducirá debido a la velocidad de transmisión CAN, significa que la distancia total de la red puede ser extendida.  Segundo, el error de bus en una red CAN no afectará el funcionamiento de otra red CAN.  Finalmente, dos redes CAN pueden comunicarse una a otra usando diferentes velocidades de transmisión por alta flexibilidad.</p>


