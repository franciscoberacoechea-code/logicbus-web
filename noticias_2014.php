<strong>l)	Comunicaci&oacute;n maestro – esclavo.</strong><br>
Explicaci&oacute;n y ejemplo de comunicaci&oacute;n entre 2 PLC’s.<br>
<strong>m)	Comunicaci&oacute;n Software SCADA.</strong><br>
