                rendimiento del sensor, las opciones, los modos de programa y las instrucciones simples y útiles
                nunca antes ofrecidas en un sensor de etiqueta clara. Una placa de separación extraíble de acero
                inoxidable y una carcasa de aluminio anodizado hacen que este sensor sea resistente. La
                configuración es rápida con solo presionar un botón para la etiqueta y una presión para el espacio
                entre etiquetas.</p>


