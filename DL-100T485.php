<p>El DL-100T485 / DL-100T485P / DL-100T485-W / DL-100T485P-W / DL-100TM485 / DL-100TM485P / DL-100TM485-W / DL-100TM485P-W es un módulo de registrador de datos de temperatura y humedad. Contiene una interfaz de comunicación RS-485 y una pantalla LCD para mostrar una variedad de datos de temperatura, humedad e identificación del módulo. La memoria de almacenamiento de datos puede almacenar hasta 4088 registros de temperatura y humedad.
La utilidad Data Logger se incluye para permitir la instalación, configuración, recuperación y visualización de datos en un formato de gráfico potente que se puede exportar a Excel.
</p><br>


<strong>Caracateristicas</strong>
<ul>
<li>Rangos de medición: -20 ~ + 60 ° C y 0 ~ 100% RH</li>
<li>Exactitud:</li>
<ul>
<li>+/- 0.4 ° C; +/- 3.0% RN para versiones no PA</li>
<li>+/- 0.3 ° C; +/- 1.8% HR para la versión P</li>
</ul>
<li>LCD Display Shows Temperature, Humidity and Module ID</li>
<li>Entrada de alimentación de 10 ~ 30 VCC</li>
<li>IP66 a prueba de agua</li>
<li>El registrador de datos puede almacenar hasta 4088 registros de temperatura y humedad</li>
<li>Interfaz de comunicación RS-485</li>
<li>Protocolo DCON o Modbus RTU</li>
<li>Software de Windows incluido</li>
</ul>

<strong>Apliucaciones:</strong>
<ul>
<li>Transporte de alimentos o productos farmacéuticos.</li>
<li>Industria de alimentos y bebidas (HACCP)</li>
<li>Estaciones de sangre, farmacias.</li>
<li>Construcción y gestión energética.</li>
<li>Almacenes</li>
<li>Museos, archivos, galerías.</li>
</ul>




