<center><strong>Módulo de 4 / 8 canales de entrada de Contador/Frecuencia/Codificador de 32 bits.</strong></center><br>

<p style="text-align: justify;">El I-87084W-G es un módulo de entrada de contador / frecuencia / codificador de alta velocidad de 32 bits que ofrece una variedad de opciones de modo, que incluyen "contador ascendente", "entrada de frecuencia", "contador ascendente / descendente", "directo / Contador de pulsos" y "Contador de fases A / B". Las combinaciones de modos se pueden configurar individualmente para los 8 canales, donde algunos canales se pueden configurar en el modo "Contador progresivo" y otros canales se pueden configurar simultáneamente en "Frecuencia", "Contador ascendente / descendente" o modo "Entrada de codificador. "El filtro digital incorporado es válido tanto para aislados como no aislados y puede filtrar ruido donde el ancho de pulso alto / bajo es menor que el ancho mínimo alto / bajo del filtro digital. El I-87084W-G proporciona una función de respaldo de batería virtual en el modo contador, y el modo aislado o no aislado es seleccionable por puente.</p><br>


<strong>Caracteristicas:</strong>
<ul>
<li>8 canales de contador / frecuencia o 4 canales de entrada de codificador</li>
<li>Filtro digital programable</li>
<li>Entrada aislada o no aislada</li>
<li>Contador de 32 bits</li>
<li>Configuración individual del canal</li>
<li>Copia de seguridad de la batería virtual para preservar los valores del contador</li>
<li>Frecuencia máxima de hasta 1 MHz</li>
<li>+/- 4 kV Protección ESD</li>
<li>Valores preestablecidos para entrada de contador</li>
<li>RoHS</li>
<li>Amplio rango de temperatura de funcionamiento: -25 ~ + 75 ° C</li>
</ul>


