      <p align="justify"> 
        El FBs-RTD6 es un módulo para medición de temperatura de la serie de PLC FBs. Proporciona 6 canales de entrada para lectura de RTD con resolución de 0.1 ºC y 1 ºC . El tiempo de escaneo tiene una resolución de 2 s para 0.1 ºC y 1 s para 1 ºC . Este módulo permite la conexión a 3 hilos para RTD con compensación automática de la resistencia introducida por los cables. Todas las funciones incluidas en el módulo son configurables mediante software, por lo que no hay hardware, switches o conexiones adicionales que el usuario deba ajustar.
