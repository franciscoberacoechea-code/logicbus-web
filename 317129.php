<p>Los prácticos terminales de abrazadera de resorte de la serie PIK proporcionan un rango de sección transversal de 1,5 ~ 10 mm². No es necesario un destornillador para instalar el cable en el bloque de terminales. Son adecuados para su uso con o sin virolas. Para que la conexión sea suficiente para insertar el cable en el terminal, la serie PIK proporciona un montaje más práctico. Solo los conectores inferiores pueden interconectarse con otras abrazaderas.Los accesorios de los terminales, como las placas finales y las conexiones cruzadas, agilizan el proceso de montaje como en los terminales de prueba. Se pueden proporcionar soluciones de marcado especiales para cada sección transversal mediante el etiquetado del plóter.</p><br>
	

