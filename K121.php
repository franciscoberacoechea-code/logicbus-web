<p align="justify">
El K121 es un convertidor/aislador universal. Es adaptable para conversiones para RTD, TC, Ohm, V y mA. En caso de las entradas de mA/V pueden configurarse con los siguientes límites: ± 24 mA y ± 30 V. Gracias al K121 se obtienen muchos beneficios: Es sólo una unidad para infinitas aplicaciones, menos cableado (la alimentación y la salida utilizan el mismo circuito). El K121 es utilizado para leer diferentes tipos de sensor mediante una tarjeta de PLC de entradas analógicas con una fuente integrada.</p><br>

<STRONG>Características:</STRONG>
<ul>
<li>Alimentación: 7~30 Vcd (desde el circuito de entrada).</li>
<li>Entrada análoga universal:</li>
<ul>
<li>Termopar: J, K, R, S, T, B, E, N.</li>
<li>RTD: PT100-500-1000, Ni100 de 2, 3 o 4 hilos.</li>
<li>Voltaje: -150~ +150 mV, -30~ +30 Vdc).</li>
<li>Corriente: -24~ +24 mA.</li>
<li>Potenciómetro: 500 Ohm~10KOhm.</li>
<li>Resistencia: hasta 1760 Ohms</li>
</ul>
<li>Salida: Corriente de 4 a 20 mA.</li>
<li>Aislamiento galvánico de 1.5 kVac</li>
</ul>
