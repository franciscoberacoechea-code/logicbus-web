<p>El ET-7060, es un módulo que permite controlar entradas y salidas digitales mediante Ethernet, este módulo incluye un servidor web integrado, el cual permite configurar el dispositivo, monitorear y controlar las entradas y salidas desde un simple navegador web. El control y supervisión remotos son tan sencillos como navegar en Internet. <BR>

Con la función web HMI, no es necesario programar ni tener habilidades en HTML; la creación de páginas web dinámicas y atractivas para el control y monitoreo de entradas/salidas será divertido para los ingenieros. El ET-7060 ofrece a los usuarios un acceso fácil y seguro desde cualquier lugar y a cualquier hora. <BR>

Además, el ET-7060 soporta también el protocolo Modbus/TCP, lo cual hace una perfecta integración entre este dispositivo y software SCADA. <BR>

El ET-7060 provee 6 Relevadores de potencia de salida (tipo A) y 6 entradas digitales de contacto húmedo (tipo sink, source). Cada Relevador de potencia soporta un contacto de 5A@250Vac o 5A@30Vdc, y cada canal de entrada digital soporta una entrada de contador (32 bits and 500Hz max.).<BR>
