<center><strong>Gateway Servidor BACnet/IP a Modbus TCP Cliente, 1 puerto RS-232 y 1 puerto Ethernet 10/100 Base-TX. Protocolo Modbus TCP Client, montaje en riel DIN, alimentación +10 ~ +30 VDC</strong></center><br>

<div align="right">
<a href="https://tienda.logicbus.com.mx/GW-5493_p_1535.html" title="Ir a Tienda" target="_blank"><img src="images/shopping_cart.png" border=0 alt="Comprar"></a>
</div> <br>

<p>El GW-5493 es un Gateway entre Modbus TCP y BACnet/IP totalmente configurable. The GW-5493 includes BACnet/IP Server and Modbus TCP Client which is used to make Modbus TCP devices accessible on a BACnet network. El GW-5493 es un BACnet/IP como servidor y Modbus TCP como cliente que hacen posible que los dispositivos Modbus TCP sean accesibles en una Red BACnet. </p>
<p>El protocolo BACnet ha sido diseñado específicamente para satisfacer las necesidades de comunicación de la construcción de sistemas de automatización y control para aplicaciones tales como calefacción, ventilación, aire acondicionado de control, etc. </p>
<p>El GW-5493 contiene un gran número de objetos BACnet (AI, AO, AV, BI, BO, BV, MSI, MSO, MSV) ofreciendo flexibilidad en la asignación de registros Modbus RTU a cualquier combinación de objetos BACnet. BIBBs múltiples (DS-RP-B, DS-RPM-B, DS-WP-B, DS-WPM, DS-COV-B, etc.) son compatibles. Todos los datos de transferencia son configurables mediante un navegador Web estándar. </p><BR>


 <center><img src="imagenes/02/BMGW-AP.jpg" align="center" border="0" class="image_productos" alt="BACnet, Building Automation Control Network Modbus RTU"></center><br><br>

<strong>Aplicaciones:</strong>
<ul>
   <li> Automatización de edificios</li>
   <li> Control de aire acondicionado, calefacción y ventilación</li>
  <li> Control de iluminación</li>
  <li> Control de accesos</li>
  <li> Sistemas de detección de incendios</li>
</ul>

<br>

<strong>Características Generales:</strong>
<ul>
<li> Forma rápida y rentable para la integración de redes</li>
<li> Indicación por LED de estado de comunicación y alimentación</li>
<li> Leer / Escribir a cualquier registro Modbus a través de BACnet</li>
<li> No requiere programación</li>
<li> Mapeo de registro Modbus configurado</li>
</ul>

<BR>

<strong>Bacnet</strong>
<ul>
<li>Totalmente compatible con servidor BACnet / IP</li>
<li>Soporta un máximo de 200 objetos de cualquiera de los tipos: entrada analógica, salida analógica, variable análoga, entrada binaria, salida binaria, variable binaria, entrada Multi-estado, salida Multi-estado</li>
<li>BIBB (BACnet Interoperability Building Blocks) soportados: DS-RP-B, DS-RPM-B, DS-WP-B, DS-WPM-B, DS-COV-B, DM-DDB-B, DM-DOB-B , DM-DCC-B, DM-TS-B, DM-UTC-B, DM-RD-B</li>
</ul>

<br>

<strong>Modbus TCP</strong>
<UL>
<LI>Modbus TCP cliente totalmente configurable por el usuario</LI>
<LI>Soporta Coils, Input Register, Holding Register</LI>
<LI>Soporta los siguientes códigos de función 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x10, 0x0F</LI>
</UL>

<br>

<STRONG>Software</STRONG>
<ul>
<li>Configuración a través de un navegador web estándar</li>
<li>Dispone de una interfaz para la configuración de la Red Modbus</li>
<li>Dispone de una interfaz para la configuración BACnet</li>
</ul>


