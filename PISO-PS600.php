<p>El controlador PISO-PS600 combina un procesador de señal digital 1600 MIPS de nueva generación con un elemento lógico FPGA (Arreglo de compuerta programable de campo) 9526, circuitería de búfer de E / S y software de caracterización de control de movimiento para controlar la posición del comando de pulso de 6 ejes servo / motores paso a paso. El PISO-PS600 no solo realiza control de movimiento mediante operaciones de bucle completo (o bucle semicerrado) y manejo de errores, sino que también adopta la ganancia de avance para reducir el perfil de velocidad tras los errores para lograr el control de posición.<br><br> 

El PISO-PS600 se puede usar en cualquier IPC con un bus PCI, y es adecuado para aplicaciones de control de movimiento de propósito general. Esta tarjeta también contiene un puerto FRnet que permite expandir fácilmente la E / S digital rápida del IPC. Esta interfaz FRnet de dos hilos permite un máximo de 128 canales DI y 128 canales DO, que se escanean automáticamente en un período de 0,72 ms. Además de su amplio rango de velocidad, este controlador de movimiento inteligente también tiene una variedad de funciones de control de movimiento incorporadas, como interpolación lineal de 2 a 6 ejes, interpolación circular de 2 a 3 ejes, aceleración de curva T / S / desaceleración, y localización automática, etc.</p><br>

<strong>Características:</strong>
<ul>
<li>Tarjeta de control de movimiento basada en DSP con interfaz PCI.</li>
<li>Control de movimiento independiente de 6 ejes.</li>
<li>Admite modos de control de cerrado completo y semicerrado.</li>
<li>Frecuencia de salida de pulso máxima: 4 Mpps.</li>
<li>Frecuencia de entrada máxima del codificador: 12 MHz.</li>
<li>Modo de inicio de 4 pasos con búsqueda automática.</li>
<li>Función de interpolación circular de 2 a 6 ejes lineal / de 2 a 3 ejes.</li>
<li>Aceleración y desaceleración de curva T / S programables.</li>
<li>Cambiar la velocidad y la posición sobre la marcha.</li>
<li>Pestillo de posición de alta velocidad y disparador de comparación.</li>
<li>Funciones de jogging y generador de impulsos manuales completamente funcionales.</li>
<li>E / S remota expansible: 128 DI y 128 DO mediante una interfaz FRnet de dos hilos.</li>
</ul><br>

