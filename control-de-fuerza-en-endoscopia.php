  <p align="justify"><b>Resumen de la aplicaci&oacute;n:</b>
    Las endoscopias permiten a los doctores revisar el interior de un paciente para buscar anomalías durante un diagnóstico, laparoscopía o procedimientos de exploración.El movimiento de estos dispositivos se maneja a través de un cable y deben tener muy poca retroalimentación háptica.<br> Esto requiere de un entrenamiento extensivo para que el operador aprenda a juzgar la fuerza aplicada de manera solamente visual. Al hacer estos controles más intuitivos se puede mejorar la fidelidad de la fuerza requerida por el operador para operar estos dispositivos. Este proceso involucra una celda de carga en línea autoclavable que da la retroalimentación de la fuerza que llevan los cables que realizan la fuerza.
  </p>

