<center><strong>Modbus Esclavo a Ethernet / Puerta de enlace IP.</strong></center><br>

<p>El GW-7473 (Modbus TCP / RTU Slave a EtherNet / IP Scanner Gateway) es útil para el intercambio de datos entre Modbus Master y el adaptador EtherNet / IP. Lee los datos de registro del adaptador EtherNet / IP y publica estos datos en los datos del registro de entrada del cliente Modbus TCP, así como de Modbus RTU Master. Los datos de salida transmitidos por Modbus TCP / RTU Master se actualizan a los datos de registro del adaptador EtherNet / IP. Para ahorrar espacio de instalación, el GW-7473 también se ofrece en un asombroso factor de forma diminuto que hace que sea fácil de instalar en cualquier lugar, incluso conectado directamente a un dispositivo serie o incrustado en una máquina. El GW-7473 cuenta con una poderosa MCU de 32 bits para manejar el tráfico de red eficiente y proporciona la potencia sobre Ethernet (PoE) compatible con IEEE 802.3af (clasificación, Clase 1) con un cable Ethernet de categoría 5 estándar. A través del interruptor NS-205PSE, Poe, el GW-7473 se puede alimentar a través del cable Ethernet. Cuando no hay un conmutador PoE en el sitio, el GW-7473 proporciona otra forma de alimentarse de adaptadores de CC. Estas dos interfaces de poder son redundantes. Si uno falla, otro se encargará de suministrar la potencia adecuada al GW-7473.</p>

<strong>Características:</strong><br><br>
<strong>Características generales:</strong>
<ul>
<li>Potente MCU de 32 bits maneja el tráfico de red eficiente.</li>
<li>10/100 Base-TX Ethernet, RJ-45 x1.</li>
<li>Entradas de alimentación redundantes: PoE (IEEE 802.3af, Clase 1) y toma de CC.</li>
<li>Soporta protocolos ARP, TCP, UDP, ICMP, DHCP, BOOTP y TFTP.</li>
<li>Fácil actualización de firmware a través de Ethernet.</li>
<li>Conector de bloque de terminales extraíble.</li>
<li>Diminuto factor de forma y bajo consumo de energía.</li>
<li>RoHS compatible con libre de halógenos.</li>
</ul>
<strong>Características de EtherNet / IP:</strong>
<ul>
<li>Objetos compatibles según el estándar CIP.</li>
<ul>
<li>Objeto de montaje.</li>
<li>Objeto de Connection Manager.</li>
<li>Objeto de enlace Ethernet.</li>
<li>Objeto del enrutador de mensajes.</li>
<li>Objeto de interfaz TCP / IP.</li>
</ul>
<li>Protocolo Ethernet: Escáner EtherNet / IP.</li>
<ul>
<li>Clase 1 (conectado) Servidor de E / S y cliente.</li>
<li>Soporte máximo 5 conexiones de adaptador EtherNet / IP.</li>
<li>Tamaño de datos del comando EtherNet / IP I / O: 200 bytes.</li>
</ul>
</ul>
<strong>Características de Modbus:</strong>
<ul>
<li>Protocolo Modbus: Servidor Modbus TCP / RTU Protocolos esclavos.</li>
<li>Soporte máximo 5 clientes Modbus TCP.</li>
<li>Códigos de función de Modbus RTU admitidos:</li>
<ul>
<li>01 hex: estado de salida de lectura.</li>
<li>02 hex: estado de entrada de lectura.</li>
<li>03 hex: leer múltiples registros de datos.</li>
<li>04 hex: leer los registros de entrada.</li>
<li>0F hex: escribe varios bits.</li>
<li>10 hex: escribir registro de datos múltiples.</li>
</ul>
</ul>
<strong>Aplicaciones:</strong>
<ul>
<li>Sistema de control.</li>
<li>Automatización de edificios.</li>
<li>Automatización industrial.</li>
<li>Adquisición de datos distribuidos.</li>
</ul> 
