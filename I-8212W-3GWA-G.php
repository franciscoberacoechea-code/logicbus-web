<p align="justify">El I-8212W-3GWA es un módulo industrial Tri-banda 3G que funciona en frecuencias de WCDMA 2100/1900/850 MHz y GSM 850/900/1800/1900 MHz. Estos módulos utilizan la red 2G / 3G para la transferencia de datos conveniente y económica desde instrumentos remotos, medidores, computadoras o sistemas de control en datos en vivo o paquetes de datos. Estos módulos tienen la pila TCP / IP integrada para que incluso los controladores simples con puertos de comunicaciones seriales puedan conectarse al módem sin la necesidad de una implementación especial del controlador. Con las características de los suyos, los sistemas pueden ser aplicaciones de conexión SMS y GPRS o 3G con nuestras series PAC como iPAC-8000, WinPAC-8000 , LinPAC-8000 o XP-8000.</p>

<strong>Características:</strong>
<ul>
<li>Admite Tri-banda UMTS 2100/1900/850 MHz y banda cuádruple GSM 850/900/1800/1900 MHz.</li>
<li>Protección contra ESD de 4 KV.</li>
<li>Diseñado para aplicaciones WCDMA, GPRS y SMS.</li>
<li>Admite servidor TCP, cliente TCP, pila de conexión de cliente UDP de 3G o GPRS.</li>
<li>Soporta comandos estándar AT.</li>
<li>Alta confiabilidad en entornos hostiles.</li>
<li>Soporte XP-8000, WinPAC-8000, LinPAC-8000, ViewPAC, iPAC-8000.</li>
</ul>

