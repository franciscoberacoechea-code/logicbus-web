        <p><b>WLS-IFC:</b></p>

        <p>El WLS-IFC es un módulo de interfaz de USB a inalámbrico que es compatible con los sistemas operativos populares de Microsoft® Windows. El WLS-IFC es totalmente compatible con los puertos USB 1.1 y USB 2.0. </p>

        <p>El dispositivo WLS-IFC funciona como la interfaz entre una computadora y uno o más dispositivos remotos de la serie WLS. Los dispositivos remotos pueden ubicarse hasta 150 pies (50 metros) en interiores, o hasta media milla (750 m) al aire libre desde el WLS-IFC. </p>

        <p>Usted configura los parámetros de red necesarios para la comunicación con dispositivos remotos. Todos los parámetros son seleccionables por software. Solo los dispositivos con la misma configuración de parámetros pueden comunicarse entre sí. Una vez que configure el WLS-IFC para comunicarse con dispositivos remotos, puede conectarlo a diferentes computadoras sin tener que configurar los parámetros de red. </p>


        <p>El WLS-IFC tiene LEDs que indican el estado de Comunicación a través del enlace inalámbrico. Un gráfico de barras LED muestra el margen de desvanecimiento de las señales recibidas por el WLS-IFC. </p>
