<center><strong>Convertidor esclavo/ maestro PROFIBUS / HART, 1 puerto PROFIBUS con protocolo DP-V0 & DP-V1, 4 canales HART, 1 puerto RS-232, alimentación de +10 ~ +30 VDC, montaje en riel DIN.</strong></center><br>

<p>La pasarela GW-7557 está especialmente diseñada para el dispositivo esclavo del protocolo PROFIBUS DP. Permite al maestro PROFIBUS acceder a los dispositivos esclavos HART. Estos dispositivos esclavos HART pueden ser un transmisor, un actuador, un dispositivo de salida de corriente, etc. Además, también ofrecemos el software de utilidad para que los usuarios configuren el GW-7557. Al usar este módulo, los usuarios pueden poner sus dispositivos esclavos HART en la red PROFIBUS muy fácilmente.</p><BR>

<strong>Características:</strong>
<ul>
<LI>Protocolo y jerarquía: esclavo DP-V0</LI>
<LI>Detecta la velocidad de transmisión (9.6 ~ 12000 kbps) automáticamente</LI>
<LI>Velocidad máxima de transmisión de hasta 12 Mbps para PROFIBUS y 115.2 kbps para puerto COM</LI>
<LI>Longitud máxima de datos de E / S: 240/240 Bytes</LI>
<LI>Soporte de 4 canales HART</LI>
<LI>Soporte HART corto / largo marco</LI>
<LI>Soporte modo HART Burst</LI>
<LI>Permite dos HART Masters</LI>
<LI>Trabajando en modo HART punto a punto o multi-drop</LI>
<LI>Conectando hasta 15 módulos HART</LI>
<LI>Protección de aislamiento de red: iCoupler de alta velocidad</LI>
<LI>Protección de aislamiento de 3000 VDC en el lado PROFIBUS</LI>
<LI>Protección contra ESD de 4 kV</LI>
</ul>
