<center><strong>Módulo de conmutador Fast Ethernet de 10 puertos a 10/100 Mbps (RoHS).</strong></center><br>

<p>El I-8135W es un módulo de conmutador Ethernet de cinco puertos flexible y de alto rendimiento. Se puede instalar en PAC (XPAC, WinPAC, LinPAC, iPAC, ViewPAC, ...) y recibe energía directamente del plano posterior. Ya no es necesario un adaptador de alimentación adicional para un conmutador Ethernet.
<br><br>
En sus soluciones PAC, si desea expandir la conexión Ethernet, I-8135W es bueno para reemplazar los conmutadores Ethernet comunes para ahorrar espacio de instalación y adaptador de alimentación.
</p>

Caracteristicas:
<ul>
<li>Switch Ethernet RJ-45 de 5 puertos.</li>
<li>Cada puerto admite una negociación automática de velocidad de 10/100 Mbps.</li>
<li>Control de flujo de contrapresión Full Duplex IEEE 802.3xy semidúplex.</li>
<li>Crossover automático MDI / MDI-X para plug-and-play.</li>
<li>Ancho de banda de memoria de alto rendimiento de 3.2 Gbps.</li>
<li>Memoria de búfer de 512 Kbits.</li>
</ul>
