<div align="center"><h2>VI. CÓMO FUNCIONA</h2></div><br>
<p align="justify">El botón de carga en miniatura de la serie LLB de FUTEK que Logicbus ofrece para ti. Se instala entre dos placas. También se encuentra entre estas placas un tubo de proceso.<br>
A medida que el fluido fluye a través del tubo de proceso, su diámetro se expande. El diseño único de esta placa (puntos de pivote), permite que se produzca esta expansión.<br>
A medida que el tubo se expande, la placa superior comienza a aplicar medidas de fuerza en el botón de carga.
Esta fuerza aplicada luego se transmite a una de varias opciones de instrumentos: una pantalla digital, un amplificador o un módulo USB.
Tanto las pantallas digitales como el módulo USB pueden utilizar el software de prueba y medición SENSIT ™ de FUTEK para graficar y recopilar los datos
</p>

