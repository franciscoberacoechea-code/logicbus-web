<p>In the Voltage Calibrator mode, the Multifunction Calibrator generates  DC/AC voltages up to 1000 V and in the Current Calibrator mode it generates DC/AC currents up to 20 A . Using a 50-turn transformer, the AC current range can be extended to 500 A. The best accuracy of the calibrator on DC voltage ranges is 0.0035%, on AC voltage ranges 0.03%, on DC current ranges 0.013% and on AC current ranges 0.055%. The frequency range is from 20 Hz to 50 kHz. The calibrator can generate periodic non-harmonic signals with a defined crest factor. Such signals can be used to test the sensitivity of multimeters to distorted signals. The Multifunction Calibrator simulates both resistance and capacitance. The resistance  range extends to 50 MOhm and the capacitance range is from 1 nF to 50 �F.  The precision of both quantities is sufficient for the calibration of commonly used hand-held multimeters. The basic accuracy of the resistance ranges and capacitance ranges is 0.03%, and  0.5% respectively. The resistance calibration may be used with both DC and AC signals up to 1 kHz.
