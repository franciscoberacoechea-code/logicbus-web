  	¿Cómo se utilizan los sensores de fuerza y ​​par en los maniquíes de pruebas de choque? Un maniquí de prueba de choque, comúnmente conocido como maniquí de prueba antropomórfico (ATD), es un dispositivo de prueba automotriz de alta precisión que se utiliza para medir el potencial de lesiones humanas en choques de vehículos simulados. Simula las dimensiones, las proporciones de peso y las articulaciones de las articulaciones y las extremidades de un cuerpo humano durante una colisión de tráfico.
