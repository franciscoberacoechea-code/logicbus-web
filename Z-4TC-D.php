<p align="justify">El Z-4TC-D permite adquirir datos hasta de 4 termopares (J, K, E, N, S, R, B, T) a través de un PLC con una única entrada / salida digital. La interfaz de PLC se basa en tres señales de tipo PNP adaptados para la conexión a la mayoría de los PLCs disponibles en el mercado. La interfaz se compone de una señal de reloj generada por el PLC (salida de transistor una señal de señal de datos y la señal de STROBE generada por el módulo</p>

<strong>Características:</strong>
<ul>
<li>Entrada para 4 termopares: J, K, R, S, T, B, E, N</li>
<li>Detección de termopar abierto</li>
<li>Tiempo de muestreo por canal de 240ms o 480ms para todos los canales</li>
<li>Aislamiento de 1500Vac</li>
<li>Fácil conexión de alimentación y comunicación serial para montaje en riel DIN</li>
<li>Salida: Señal Digital de strobo (fin de secuencia), dato, reloj</li>
<li>La medición de entrada puede ser configurada para temperatura o mV (± 160 mV)</li>
<li>Filtros programables para estabilizar las mediciones de entrada</li>
<li>Compensación de punta fría</li>
</ul><br><br>


