      <td colspan="2"><div align="justify">The DNR-AI-254 is a four channel LVDT/RVDT input and output simulation board for powerful data acquisition and control RACKtangle&reg; I/O racks. The boards are ideally suited for a wide variety of rotational and linear motion measurements in many industries. The boards also offer a unique LVDT/RVDT simulated output capability designed to provide stimulus in avionics test and simulator applications. Each of the four channels on the board may be configured as either an input channel with excitation or as an output/simulator.<br>
          <br>
          The 4 input channels are compatible with 4-, 5- and 6-wire LVDT/RVDT configurations. The board&rsquo;s high precision circuitry combined with each channel&rsquo;s independent 16-bit A/D converters allow an overall measurement accuracy of better than 0.1%. The inputs may be read at rates up to 500 readings per second, depending upon the reference frequency.<br>
          <br>
          Each channel provides an independent excitation output user programmable from 2 to 7 Vrms at frequencies from 50 to 5,000 Hz. The excitation output is capable of driving currents up to 50 mA, suitable for driving primary impedances as low as 90 ohms at excitations up to 6 Vrms.&nbsp;<br>
          <br>
          The DNR-AI-254 also provides up to 4 channels of simulated LVDT/RVDT output that are ideal for driving simulator inputs or for use in testing LVDT/RVDT measurement products. The outputs each accept an independent excitation signal and offer 2, 3 or 4 wire outputs with 16-bit resolution and an overall accuracy of better than 0.1%. Each channel is capable of driving up to 50 mA at 7 Vrms without external buffering.&nbsp;<br>
          <br>
          The DNR-AI-254 offers 350 Vrms of isolation between channels as well as between the I/O connections and the Cube. Like all UEI &ldquo;Cube&rdquo; and RACKtangle compatible I/O boards, the DNA/DNR-AI-254 offers operation in harsh environments and Cube systems have been tested to 5g vibration, 50g shock, -40 to +85 &deg;C temperatures and altitudes up to 70,000 feet.<br>
          <br>
      Software for the DNR-AI-254 is provided as part of the UEI Framework. The framework provides a comprehensive yet easy to use API that supports all popular Windows programming languages as well as supporting programmers using Linux and most real-time operating systems including QNX, RTX, RT Linux and more. Finally, the framework supplies complete support for those creating applications in LabVIEW, MATLAB/Simulink, DASYLab or any application supporting ActiveX or OPC servers.</div></td>
