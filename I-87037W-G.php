<p style="text-align: justify;">El I-87037W proporciona 16 canales para salida digital, cada uno de los cuales cuenta con aislamiento de fotocupla. El I-87037W admite salida de tipo source con protección contra cortocircuitos y cada canal puede controlar 700mA de carga. Existen opciones para configurar valores de encendido y salida digital segura. También se proporcionan 4 kV de protección ESD y 3750 VDC de aislamiento intramódulo para enriquecer la capacidad de protección contra el ruido para entornos industriales.</p><br>


