        <p>La serie ICP DAS WinPAC-8x46 (WP-8146/8446/8846) es la nueva generación basada en WinCE PAC (controlador de automatización programable). Cuenta con el poderoso InduSoft Web Studio e ISaGRAF. InduSoft es una poderosa colección integrada de herramientas de desarrollo de e-automation que incluye todos los componentes necesarios para desarrollar Human Machine Interface (HMI) y Supervisory Control and Data Acquisition (SCADA). ISaGRAF es un software de tipo PLC y es compatible con los cinco idiomas IEC61131-3 (LD, ST, FBD, SFC y FC). WinPAC-8x46 equipa una CPU PXA270 (520MHz) con un sistema operativo Windows CE.NET 5.0, variante de conectividad (puertos Ethernet dobles 10/100 Base-TX, 2 o 4 puertos RS-232/485, 1 VGA, 1 puerto USB) y ranuras de 1/4/8 para alto rendimiento de módulos de E / S de tipo paralelo (serie I-8K de alto perfil) y módulos de E / S de tipo serie (módulos de E / S de alto perfil Hot-Swap I-87K) ) Se incluyen SRAM de 128 MB, SRAM de respaldo de batería dual de 512 KB, FLASH de 96 MB y microSD de 16 GB. Para soporte redundante: se proporcionan temporizadores Watchdog duales, entradas de alimentación redundantes, SRAM de respaldo de batería dual y puertos Ethernet duales. ¡La serie WinPAC-8x47 definitivamente actualizará su sistema!
