<p>El I-7241D es un producto de bus CAN. El dispositivo ofrece la puerta de enlace de comunicaciones entre DeviceNet y el protocolo DCON. El protocolo DCON es el protocolo de comunicación de los módulos IO I-7K e I-87K de ICP DAS. El I-7241D puede ser un dispositivo esclavo DeviceNet en el bus CAN para la red DeviceNet. Es un dispositivo esclavo del Grupo 2 solamente y admite "Conjunto de conexión maestro / esclavo predefinido". También proporcionamos el software de utilidad para que los usuarios configuren los parámetros del dispositivo y construyan el archivo EDS para el dispositivo esclavo DeviceNet. Los usuarios pueden aplicar fácilmente módulos de E / S I-7K e I-87K en aplicaciones DeviceNet con el I-7241D.</p><BR>

<strong>Características:</strong>
<ul>
<LI>NMT: Esclavo</LI>
<LI>Admite un conjunto de conexión maestro / esclavo predefinido</LI>
<LI>Asignación dinámica de objetos de ensamblaje</LI>
<LI>Admite un conjunto de conexión sin conexión, mensaje de latido del dispositivo y mensaje de apagado del dispositivo</LI>
<LI>Proporciona un objeto de montaje</LI>
<LI>Dynamicly Product EDS File</LI>
<LI>Modos de funcionamiento de E / S: sondeo, Bit-Strobe, cambio de estado / cíclico</LI>
<LI>Soporte máximo de 15 I-7K / I-87K IO módulos</LI>
<LI>Proporciona una utilidad amigable para la configuración</LI>
<LI>Velocidad en baudios: 125Kb, 250Kb, 500Kb</LI>
<LI>Cambio en línea velocidad en baudios e ID MAC de CAN</LI>
<LI>LED de 7 segmentos para mostrar el modo de operación, la ID MAC, la velocidad en baudios y el código de error</LI>
</ul>
