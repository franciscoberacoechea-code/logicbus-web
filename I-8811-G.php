<center><strong>Controlador integrado con pantalla / desarrollo de siete dígitos de cinco dígitos</strong></center><br>


<p>El I-8411 / I-8811 es un controlador integrado de serie con 4/8 ranuras de E / S. Ambos están equipados con MiniOS7. El MiniOS7 puede arrancar en muy poco tiempo (0.4 ~ 0.8 segundos). Tiene una función de diagnóstico de hardware incorporada, y admite todas las funciones para acceder a todos los módulos de E / S de las series 8K y 87K, como DI, DO, DIO , AI, AO, contador / frecuencia, módulos de movimiento, etc. El plano posterior I-8411 / I-8811 está equipado con cuatro puertos COM serie, incluyen puertos RS-232 y RS-485 y se pueden usar en aplicaciones remotas de adquisición y control de datos, incluida la supervisión del entorno, la administración de energía y la automatización de fábrica. Al utilizar la SRAM de respaldo de batería S-256 (256 KBytes) o S-512 (512 KBytes), proporcionan la función de almacenamiento del registrador de datos.
</p><BR><br>


<strong>Caracteristicas:</strong>
<ul>
<li>Proporciona un número de serie de hardware o un ASICKey para proteger los sistemas designados.</li>
<li>El circuito de vigilancia incorporada reiniciará el módulo de la CPU si ocurre una falla en el hardware o software, lo que permite que el sistema del controlador sea más confiable y estable en ambientes hostiles y ruidosos.</li>
<li>Dual Bus diseñado para admitir módulos de E / S de la serie I-8K e I-87K, como DI / DO, AI / AO, módulos de contador / frecuencia. La ranura de expansión mpact I / O permite la instalación rápida de varios módulos de E / S de 8K y 87K.</li>
</ul>

