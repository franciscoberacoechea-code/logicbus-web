<li>Indicador de alerta de acción</li>
<li>Tres camillas de pulso; 10ms, 25ms y 50ms</li>
<li>Indicador de contraste de 5 LED</li>
<li>Cable o desconexión rápida.</li>
<li>Bloques ópticos intercambiables</li>
<li>Botón de bloqueo</li>
<li>Light On / Dark On selección automática</li>
<li>Salida NPN y PNP</li>
</ul>
	

