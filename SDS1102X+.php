Los nuevos osciloscopios de Super Fósforo SDS1000X / SDS1000X + de SIGLENT están disponibles en dos anchos de banda, 100 MHz y 200 MHz, tienen una frecuencia de muestreo de 1 GSa / sy una longitud de registro estándar de 14 Mpts. Las funciones más utilizadas se pueden acceder con su diseño de un solo botón de uso fácil.
