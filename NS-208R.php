<center><strong>Conmutador Ethernet no administrado de 8 puertos, 10/100 Mbps industriales, montaje en riel DIN (versión robusta). Admite temperaturas de funcionamiento de -40 ° C ~ + 75 ° C (-40 ° F ~ 167 ° F).</strong></center><br>


<p>El conmutador Ethernet NS-208R está diseñado para aplicaciones industriales, como aplicaciones de material rodante, vehículos y ferrocarriles. Los recubrimientos conformales encapsulan las placas de circuitos y sus componentes electrónicos para evitar la entrada de humedad, hongos, polvo y otros contaminantes ambientales. Después de realizar el recubrimiento en los interruptores, proporciona protección ambiental y mecánica para prolongar significativamente la vida útil de los componentes y los circuitos para cumplir con los desafíos en entornos industriales severos. <br>

El NS-208R proporciona un amplio rango de potencia de +12 V CC ~ +48 V CC para adaptarse a todos los estándares de potencia comunes que se encuentran en la automatización industrial, sin convertidores de potencia externos. La amplia entrada de potencia reduce los costos de instalación y mantenimiento..</p><BR>

<strong>Caracteristicas</strong>

<ul>
<li>Conformal recubierto para los duros estándares ferroviarios.</li>
<li>Crossover automático MDI / MDI-X para plug-and-play.</li>
<li>Arquitectura de almacenamiento y reenvío.</li>
<li>Control de flujo de contrapresión Full Duplex IEEE 802.3xy semidúplex.</li>
<li>Cada puerto admite una negociación automática de velocidad de 10/100 Mbps.</li>
<li>Admite entrada de alimentación de +12 ~ +48 VDC.</li>
<li>Admite funcionamiento</li>
</ul>
