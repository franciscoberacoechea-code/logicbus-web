          <p>Osciloscopios para PC y osciloscopios de señal mixta</p>


          <h2>Potencia, portabilidad y rendimiento.</h2>


          <p>Los osciloscopios para PC con alimentación USB de la serie PicoScope 3000 son pequeños, livianos y portátiles, y se pueden deslizar fácilmente en una bolsa para computadora portátil mientras ofrecen una gama de especificaciones de alto rendimiento.</p>

          <p>Estos osciloscopios ofrecen 2 o 4 canales analógicos y una función incorporada / generador de forma de onda arbitraria. Los modelos MSO agregan 16 canales digitales. Especificaciones de rendimiento clave:</p>


          <ul>
            <li>Ancho de banda analógico de 200 MHz</li>
            <li>Muestreo en tiempo real de 1 GS/s</li>
            <li>Buffer de memoria de 512 MS</li>
            <li>100,000 formas de onda por segundo</li>
            <li>Analizador lógico de 16 canales (modelos MSO)</li>
            <li>Generador de forma de onda arbitraria</li>
            <li>Conectado y alimentado por USB 3.0</li>
            <li>Decodificación en serie y pruebas de máscara como estándar</li>
            <li>Software para Windows, Linux y Mac.</li>
            <li>Respaldados por el software avanzado PicoScope 6, estos dispositivos ofrecen un paquete ideal y económico para muchas aplicaciones, que incluyen diseño de sistemas integrados, investigación, pruebas, educación, servicio y reparación.</li>
          </ul>


          <h2>Alto ancho de banda y tasa de muestreo</h2>


          <p>A pesar de su tamaño compacto y bajo costo, no se compromete el rendimiento con anchos de banda de hasta 200 MHz. Este ancho de banda se compara con una tasa de muestreo en tiempo real de hasta 1 GS / s, lo que permite una visualización detallada de las altas frecuencias. Para señales repetitivas, la tasa de muestreo efectiva máxima se puede aumentar a 10 GS / s usando el modo de muestreo de tiempo equivalente (ETS).</p>

          <p>Otros osciloscopios tienen tasas de muestreo máximas altas, pero sin memoria profunda no pueden mantener estas tasas en bases de tiempo largas. La serie PicoScope 3000 ofrece profundidades de memoria de hasta 512 millones de muestras, más que cualquier otro osciloscopio en este rango de precios, lo que permite que el PicoScope 3406D MSO muestree a 1 GS / s hasta 50 ms / div (500 ms de captura total hora).</p>

          <p>La gestión de todos estos datos requiere algunas herramientas poderosas. Hay un conjunto de botones de zoom, además de una ventana de vista general que le permite ampliar y reposicionar la pantalla simplemente arrastrando con el mouse o la pantalla táctil. Factores de zoom de varios millones son posibles. Otras herramientas, como el búfer de forma de onda, la prueba de límite de máscara, la decodificación en serie y la aceleración de hardware, funcionan con la memoria profunda, lo que convierte a la serie PicoScope 3000 en uno de los osciloscopios más potentes del mercado.</p>




          <h2>Analizador lógico / capacidad de señal mixta</h2>


          <p>Los osciloscopios de señal mixta de la serie PicoScope 3000D incluyen 16 entradas digitales para que pueda ver señales digitales y analógicas simultáneamente.</p>

          <p>Las entradas digitales se pueden mostrar individualmente o en grupos con nombre, con valores binarios, decimales o hexadecimales que se muestran en una pantalla de estilo bus. Se puede definir un umbral lógico separado de –5 V a +5 V para cada puerto de entrada de 8 bits. El disparador digital se puede activar mediante cualquier patrón de bits combinado con una transición opcional en cualquier entrada. Los disparadores lógicos avanzados se pueden configurar en los canales de entrada analógicos o digitales, o en ambos para habilitar el disparo complejo de señales mixtas.</p>

          <p>Las entradas digitales aportan potencia adicional a las opciones de decodificación en serie. Puede decodificar datos en serie en todos los canales analógicos y digitales simultáneamente, brindándole hasta 18 canales de datos. Por ejemplo, puede decodificar varias señales SPI, I²C, CAN bus, LIN bus y FlexRay al mismo tiempo.</p>


          <h2>Decodificación de bus serie y análisis de protocolo.</h2>

          <p>PicoScope puede decodificar 1 cable, ARINC 429, CAN, DCC, DMX512, Ethernet, FlexRay, I²C, I²S, LIN, PS / 2, SENT, SPI, UART (RS-232 / RS-422 / RS-485), y Los datos del protocolo USB 1.1 como estándar, con más protocolos en desarrollo y disponibles en el futuro con actualizaciones de software gratuitas.</p>

          <p>El formato de gráfico muestra los datos decodificados (en hexadecimal, binario, decimal o ASCII) en un formato de temporización del bus de datos, debajo de la forma de onda en un eje de tiempo común, con cuadros de error marcados en rojo. Estos marcos pueden ampliarse para investigar problemas de integridad de señal o ruido.</p>

          <p>El formato de la tabla muestra una lista de los marcos decodificados, incluidos los datos y todos los indicadores e identificadores. Puede configurar las condiciones de filtrado para mostrar solo los marcos que le interesan o buscar marcos con las propiedades especificadas. La opción de estadísticas revela más detalles sobre la capa física, como los tiempos de cuadro y los niveles de voltaje. PicoScope también puede importar una hoja de cálculo para decodificar los datos en cadenas de texto definidas por el usuario.</p>


          <h2>Generador de función y forma de onda arbitraria</h2>


          <p>Todas las unidades PicoScope 3000D tienen un generador de funciones incorporado (seno, cuadrado, triángulo, nivel de CC, ruido blanco, PRBS, etc.) en el panel frontal. Los modelos PicoScope 3000D MSO tienen el conector en el panel posterior.</p>

          <p>Además de los controles básicos para establecer el nivel, el desplazamiento y la frecuencia, los controles más avanzados le permiten barrer en un rango de frecuencias. Combinado con la opción de retención de pico de espectro, esto constituye una herramienta poderosa para probar las respuestas de amplificador y filtro.</p>

          <p>Las herramientas de activación permiten que se produzcan uno o más ciclos de una forma de onda cuando se cumplen varias condiciones, como la activación del alcance o el fallo de una prueba de límite de máscara.</p>

          <p>También se incluye un generador de forma de onda arbitraria (AWG) de 14 bits a 80 MS / s. Las formas de onda AWG pueden crearse o editarse utilizando el editor AWG incorporado, importarse desde las trazas del osciloscopio o cargarse desde una hoja de cálculo.</p>


          <h2>Analizador de espectro FFT</h2>


          <p>La vista de espectro representa la amplitud en función de la frecuencia y es ideal para detectar ruido, interferencia o distorsión en las señales. El analizador de espectro en PicoScope es del tipo de Transformada Rápida de Fourier (FFT) que, a diferencia de un analizador de espectro de barrido tradicional, puede mostrar el espectro de una forma de onda única y no repetitiva.</p>

          <p>Una amplia gama de configuraciones le permite controlar el número de bandas de espectro (bandejas FFT), tipos de ventanas, escala (incluido log / log) y modos de visualización (instantánea, promedio o retención de pico).</p>

          <p>Puede visualizar múltiples vistas de espectro junto con vistas de osciloscopio de los mismos datos. Un conjunto completo de mediciones automáticas en el dominio de la frecuencia se puede agregar a la pantalla, incluyendo THD, THD + N, SNR, SINAD y IMD. Se puede aplicar una prueba de límite de máscara a un espectro e incluso puede utilizar el modo AWG y el espectro juntos para realizar un análisis de red escalar barrida.</p>

          <h2>Integridad de la señal</h2>

          <p>La mayoría de los osciloscopios se reducen a un precio. Los PicoScopes están construidos según una especificación.</p>

          <p>El cuidadoso diseño del frente y el blindaje reducen el ruido, la interferencia y la distorsión armónica. Años de experiencia en el diseño de osciloscopios se pueden ver en la mejora de la plenitud del ancho de banda y la baja distorsión.</p>

          <p>Estamos orgullosos del rendimiento dinámico de nuestros productos y, a diferencia de la mayoría de los fabricantes de osciloscopios, publicamos nuestras especificaciones en detalle. El resultado es simple: cuando prueba un circuito, puede confiar en la forma de onda que ve en la pantalla.</p>


          <h2>Conectividad USB</h2>

          <p>La conexión USB no solo permite la adquisición y transferencia de datos a alta velocidad, sino que también hace que imprimir, copiar, guardar y enviar sus datos desde el campo sea rápido y fácil. La alimentación por USB elimina la necesidad de transportar una fuente de alimentación externa voluminosa, lo que hace que el kit sea aún más portátil para el ingeniero en movimiento.</p>

          <p>Los osciloscopios de la serie PicoScope 3000 cuentan con una conexión SuperSpeed USB 3.0, lo que hace que el proceso ya optimizado de transferencia de datos y las tasas de actualización de formas de onda sea aún más rápido. Los beneficios adicionales de una conexión USB 3.0 incluyen un ahorro más rápido de formas de onda y una transmisión continua sin interrupciones más rápida de hasta 125 MS / s cuando se usa el SDK, mientras que el alcance aún es compatible con sistemas USB más antiguos.</p>



