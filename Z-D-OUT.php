<center><strong>M&oacute;dulo de adquisici&oacute;n de datos con 5 entradas digitales.</strong></center>

<div align="right">
<a href="https://tienda.logicbus.com.mx/Z-D-OUT_p_4161.html" title="Ir a Tienda" target="_blank"><img src="images/shopping_cart.png" border=0 target="_blank" alt="Comprar"></a>
