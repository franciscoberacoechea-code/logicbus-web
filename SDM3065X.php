<br><br>
El SIGLENT SDM3065X tiene un poderoso motor de prueba, tamaño de flash Nand de 1Gb, archivos de configuración de almacenamiento masivo y archivos de datos, datos históricos y almacenamiento de disco U externo. Las interfaces SDM3065X incluyen dispositivo USB, host USB, LAN (Accesorios opcionales: GPIB y tarjeta de escáner. Puede admitir el control remoto a través de comandos y es compatible con los comandos de los multímetros de flujo principal.) El SDM3065X es compatible con control de medición de sensor fácil, conveniente y flexible software: EasyDMM. Por lo tanto, puede convertir fácilmente su entorno de prueba existente.
<br>
El escáner SIGLENT es un multiplexor que proporciona capacidades de medición multipunto a la serie SDM3000 de multímetros digitales. El escáner cuenta con 12 canales de corriente multipropósito + 4 y admite las siguientes funciones de medición: DCV, ACV, DCI, ACI, 2WR, 4WR, CAP, FREQ, DIODE, CONT y TEMP (RTD y termopar). Proporciona un cómodo y solución versátil para aplicaciones de prueba que requieren múltiples puntos de medición o señales, y es una herramienta ideal para el quemado y prueba de producción de I + D.
</p><BR>

