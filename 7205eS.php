   <div align="justify"> La 7205eS PCI Express con interfaz serial proporciona 2 puertos seriales configurables para  RS-232, RS-422 o RS-485. Cada puerto serial  utiliza un UART 16C950 con Tx/Rx FIFOs de 128 bytes los cuales habilitan tasas de datos a 921.6K bps para comunicaciones confiables de alta velocidad en aplicaciones de datos intensivos. &Eacute;ste UART de gran desempe&ntilde;o incluye soporte de encuadre de 9 bits y es totalmente compatible con aplicaciones de 16550. Adem&aacute;s el oscilador 14.7456 y el prescalador de reloj flexible soporta el rango m&aacute;s amplio de velocidades de transmisi&oacute;n est&aacute;ndares y no est&aacute;ndares. <br>
   <br>
   En el modo  RS-485, el transmisor es automaticamente habilitado en hardware, eliminando la necesidad de un software de control. &Eacute;sto permite que la  7205eS sea usado con aplicaciones de comunicaciones seriales est&aacute;ndar y quita el riesgo de corrupci&oacute;n de datos o retenci&oacute;n de bits. En el modo RS-232 todas las se&ntilde;ales de control son implementadas para una m&aacute;xima compatibilidad con un amplio rango de perif&eacute;ricos seriales. El driver y las utiler&iacute;as del software hacen que la instalaci&oacute;n y operaci&oacute;n sean f&aacute;ciles usando los istemas operativos  Windows 98, ME, 2000, NT, XP, Vista y Linux. <br>
   <br>
   La 7205eS es una tarjeta PCI Express X1 compatible con cualquier slot PCI Express. Si tienes un slot de PCI Express de Bajo Perfil, ordena el 7205e. La tarjeta viene con un cable de 36" que termina en dos conectores DB9M. <br>
