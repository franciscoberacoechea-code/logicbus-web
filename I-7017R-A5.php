<p>I-7017R-A5 es un módulo de entrada analógica de alto voltaje de 8 canales. Pertenece a la familia I-7000 de módulos de adquisición y control de datos de red. I-7017R-A5 como todos nuestros módulos I-7000 se puede controlar de forma remota utilizando un conjunto de comandos de protocolo DCON. La comunicación entre el módulo y el host se realiza en formato ASCII a través de un estándar de bus serie bidireccional RS-485. Las tasas de baudios son programables por software y se pueden seleccionar velocidades de transmisión de hasta 115.2K baudios.</p>

