      <p class="container text-justify paragraph">Esto permite que el sensor de temperatura se adapte rápidamente y registre con precisión las variaciones de temperatura en entornos cambiantes. Las aplicaciones incluyen la creación de perfiles de hornos, la esterilización por vapor, la verificación y el mapeo de autoclaves, el procesamiento de mariscos, la congelación rápida y más.</p>

      <p class="container text-justify paragraph">El registrador de datos HITEMP140-FR está diseñado con acero inoxidable de grado alimenticio. El dispositivo se puede colocar en entornos de hasta 140 °C (284 °F) y la sonda es capaz de medir de -200 a 260 °C (-328 a 500 °F). El HITEMP140-FR también está disponible con una carcasa de protección térmica opcional para ampliar el rango operativo del registrador de datos de -200 a 250 °C (-328 a 482 °F). El kit de protección térmica HITEMP140-FR-TSK viene con una carcasa superior ventilada o al ras para adaptarse a una multitud de aplicaciones.</p>

      <p class="container text-justify paragraph">La función de configuración de disparadores del HITEMP140-FR permite a los usuarios configurar umbrales de temperatura alta y baja que, cuando se alcanzan o superan, iniciarán o detendrán automáticamente el registro de datos en la memoria. Este registrador de datos es capaz de almacenar hasta 32,700 lecturas con fecha y hora y cuenta con una memoria de estado sólido no volátil que retiene los datos incluso si la batería se descarga.</p>

      <p class="container text-justify paragraph">El HITEMP140-FR es compatible con el software Madgetech 4. Los datos se pueden ver en formatos gráficos o tabulares y hay vistas de resumen y estadísticas disponibles para un análisis más detallado. El software incluye funciones de exportación a Excel®, anotación de datos, calibración digital y más.</p>

