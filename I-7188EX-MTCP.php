      <td>
        <div align="justify">Si el firmware de default no cubre totalmente tus requerimientos, puedes usarel SDK para modificar ese firmwate para agregar funciones extra. El Modbus SDK tiene las siguientes caracter&iacute;sticas:<br>
	         
	         <ul>
               <li> <strong>Soporta protocolo de comandos extras definidos por el usuario (TCP/IP)</strong><br> 
               El protocolo Modbus/TCP soporta 2 formatos de datos b&aacute;sicos (bit y 2 bytes int). &Eacute;sto significa que si los clientes (llamados tambi&eacute;n maestros) no soportan Modbus/TCP o si necesitas algun otro formato de datos (por ejemplo, valores flotantes o de cadena), el i-7188E no se puede comunicar con ellos. Al usar &eacute;sta caracter&iacute;stica puedes desarrollar tu protocolo de comandos especiales para transferir cualquier formato de datos.</li>
               <li>	<strong>M&eacute;todo de programaci&oacute;n basado en registros (f&aacute;cil de usar)</strong><br> 
               La librer&iacute;a Modbus soporta 4 tablas de registros internos (iMemory_AI, iMemory_AO, iMemory_DI, iMemory_DO), se pueden usar &eacute;stos para almacenar datos espec&iacute;ficos. Cuando los clientes Modbus/TCP hacen una solicitud al i-7188E, el kernel del Modbus responder&aacute; desde esas 4 tablas. </li>
               <li><strong>Provee registros definidos por el usuario</strong><br> 
               Las cuatro tablas de registros internos est&aacute;n abiertos para todos los usuarios. Necesitas asignar estas tablas por t&iacute; mismo. </li>
               <li><strong>Se puede conectar a dispositivos esclavos Modbus/TCP <br>
               </strong>Usando la funci&oacute; ModbusTCP_Master2Slave(declarada en la librer&iacute;a MBTCP_7E.h), el 7188EX-MTCP puede conectar hasta 8 dispositivos Modbus/TCP.</li>
               <li><strong>Se puede conectar a dispositivos esclavos  Modbus/RTU</strong><br>
               Usando la funci&oacute;n ModbusMaster2Slave (declarada en la librer&iacute;a MBTCP_7E.h), los dispositivos Modbus/RTU pueden ser integrados f&aacute;cilmente a registros internos del i-7188Es. Los Maestros s&oacute;lo piden n al i-7188E obtener la informaci&oacute;n de los dispositivos Modbus/RTU.</li>
               <li><strong>Se puede conectar a dispositivos seriales que no sean Modbus/RTU </strong><br>
               Algunos dispositivos seriales no soportan el protocolo Modbus/RTU. Proveemos funciones para quejar que el  i-7188E -MTCP accese a dispositivos seriales. Se puede poner la informaci&oacute;n de los registros interno en ellos. As&iacute;, los dispositivos seriales que no cuenten con Modbus pueden tambi&eacute;n soportar Modbus/TCP.</li>
               <li><strong>Compatible con Xserver SDK </strong><br> 
               El Modbus SDK est&aacute; basado en el  Xserver SDK. Para aprender m&aacute;s de las habilidades de programaci&oacute;n, puedes basarte en los demos del Xserver.</li>
