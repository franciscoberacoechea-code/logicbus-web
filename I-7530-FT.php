<p>I-7530-FT es un convertidor tolerante a fallas de baja velocidad RS-232 / CAN y puede convertir mensajes con precisión entre medios de comunicación CAN y RS-232. Puede resistir más ruido en entornos hostiles e incluso acceder a mensajes CAN con una sola línea de bus CAN. Para utilizar la red CAN con dispositivos RS-232 programables tradicionales, ofrecemos una manera fácil de lograr este objetivo mediante varias llamadas a funciones del usuario. Se puede utilizar en la aplicación de monitoreo de bus CAN, automatización de edificios, adquisición remota de datos, control y monitoreo ambiental, equipos e investigaciones de laboratorio, automatización de fábricas, etc.</p>

<strong>Caracter&iacute;sticas:</strong>
		<ul>
<li>Microprocesador adentro con 20MHz</li>
<li>Firmware del convertidor incorporado CAN / RS-232</li>
<li>Totalmente compatible con la norma ISO 11898-3</li>
<li>Velocidad máxima de transmisión de hasta 125 kbps para CAN y 115.2 kbps para RS-232</li>
<li>Admite tanto CAN 2.0A como CAN 2.0B</li>
<li>Buffers integrados RS-232 / CAN FIFO</li>
<li>Indicador de alimentación, flujo de datos e error para CAN y RS-232</li>
<li>Diseño de watchdog de hardware</li>
		</ul>

