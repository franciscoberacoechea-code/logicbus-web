<p>La serie WinPAC-8x49 (WP-8149/8449/8849) es la nueva generación basada en WinCE InduSoft PAC (controlador de automatización programable) de ICP DAS. Equipa una CPU PXA270 (520MHz) con sistema operativo Windows CE.NET 5.0, conectividad variante (10/100 puertos Ethernet Base-TX dual, 2 o 4 puertos RS-232/485, 1 VGA, 1 puerto USB) y 1 / Ranuras de 4/8 para módulos de E / S de alto rendimiento de tipo paralelo (serie I-8K de alto perfil) y módulos de E / S de tipo serie (módulos de E / S de alto perfil I-87K de intercambio en caliente). Los recuerdos vienen con SRAM de 128 MB, SRAM con respaldo de batería dual de 512 KB, FLASH de 96 MB y microSD de 16 GB. Compatibilidad redundante: temporizadores Watchdog duales, entradas de alimentación redundantes, SRAM de respaldo de batería dual, puertos Ethernet duales. ¡La serie WinPAC-8x47 actualizará tu sistema!
</p><BR><br>


