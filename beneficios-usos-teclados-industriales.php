      <h2 class="subtitle blue text-center mt-5 mb-3">Introducción</h2>
      <p>Cuando nosotros utilizamos un ordenador, el componente de entrada, es el teclado para tener una Iteración con él, ordenando que realizar, pero si en dado caso llegara a faltarnos, no podríamos comunicarlos o acceder al monitor y realizar todas las interacciones que estamos acostumbrados a realizar. En lugares en donde se esté laborando con sustancias y líquidos o donde se expone el teclado a caídas o golpes, por esta razón se crearon teclados industriales que tienen características que soportan este tipo de situaciones. A lo largo de este artículo se abordaran con más amplitud este tema innovador.</p>

      <h2 class="subtitle blue text-center mt-5 mb-3">Teclado Industrial. Concepto</h2>
      <p>Como se mencionó anteriormente el teclado es uno de los elementos más importantes dentro de la automatización, el operador introduce las órdenes de trabajo que la máquina debe realizar o el usuario puede editar el programa general que controla la máquina. Sin embargo, en el mercado existe una gran variedad de fabricantes de teclados industriales, y cada uno tiene una forma diferente de comunicar sus teclados a las máquinas, en algunos casos se tienen que instalar controladores especiales al ordenador para que pueda admitirlo o reconocerlo al conectarlo y muchas veces estos teclados no son compatibles entre sí, es decir, en caso de que un teclado ya instalado falle, no se podrá remplazar por otro de diferente fabricante, ya que no suelen tener la misma configuración del protocolo de comunicación.</p>
      <p>De acuerdo con los avances tecnológicos, la industria de procesos requiere sistemas con mayor cantidad de elementos o mecanismos que puedan controlarse de una forma más fácil, confiable y eficaz; por esta razón, se pensó en dispositivos más autónomos como es el uso de micro controladores y la PC para el control.</p>
      <ul>
        <li>Fuera de los muchos beneficios que un teclado industrial puede manifestarse, algunos de ellos son los siguientes.</li>
