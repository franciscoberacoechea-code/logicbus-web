<p>La tarjeta PCI-P16C16U es el producto de nueva generación que ICP DAS proporciona para cumplir con los requisitos de cumplimiento de RoHS y está diseñado como completamente compatible con PCI-P16C16U. Los usuarios pueden reemplazar el PCI-P16C16 por el PCI-P16C16U directamente sin modificación de software/controlador. 
<br><br>
La tarjeta PCI universal PCI-P16C16U admite bus PCI de 3,3 V/5 V. Estas tarjetas contienen 16 canales de entrada digital ópticamente aislados y 16 canales de salida digital de colector abierto (fregadero, NPN). Los canales DI proporcionan una protección de aislamiento de 5000 Vrms que permite flotar por completo las señales de entrada para evitar bucles de tierra y aislar la computadora host de daños en los voltajes. Los canales de salida del colector abierto (DO) se usan típicamente para notificaciones de alarma y advertencia, control de salida de señal, control de circuitos externos que requieren un nivel de voltaje más alto y aplicaciones de transmisión de señal, etc. 
<br><br>
El PCI-P16C16U también agrega un interruptor de identificación de tarjeta a bordo. Los usuarios pueden configurar la identificación de la tarjeta y luego reconocer la placa mediante la identificación a través del software cuando usan dos o más tarjetas en una computadora. 
<br><br>
El PCI-P16C16U es compatible con varias versiones del sistema operativo, como Linux, DOS, Windows 8/7/2008/2003/XP de 32/64 bits. El control DLL y Active X junto con varios programas de muestra de lenguaje basados ??en Turbo C ++, Borland C ++, Microsoft C ++, Visual C ++, Borland Delphi, Borland C ++ Builder, Visual Basic, C # .NET, Visual Basic.NET y LabVIEW se proporcionan para ayudar a los usuarios a desarrollar rápida y fácilmente sus propias aplicaciones.</p>

Características:
<ul>
<li>Soporta el bus PCI +3.3 V/+ 5 V.</li>
<li>16 canales de salida digital de colector abierto (Fregadero, NPN).</li>
<li>16 canales de entrada digital ópticamente aislados.</li>
<li>Filtro de entrada de señal de CC seleccionable.</li>
<li>Entrada de señal de CA con filtro.</li>
<li>Indicador LED de estado de la alimentación externa.</li>
<li>Función de ID de tarjeta.</li>
<li>Admite Plug & Play para obtener recursos de E/S.</li>
<li>No más configuraciones manuales de dirección de E/S e IRQ.</li>
</ul>

