                </div><br>
                <p align="justify">Actualmente, hay dos jugadores principales con productos de alimentación inalámbricos
                    listos
                    para el mercado. Uno de ellos es Energous. Se centra en las redes de electrónica de consumo, como
                    las salas de
                    estar inteligentes. El otro es Ossia. Esta aplicación se adapta mejor a las redes de electrónica
                    comercial,
                    como cafeterías y aeropuertos.<br>
                    Ambas compañías han surgido en el último año. Cada uno de ellos se basa en un canal de RF diferente.
                    Energous
                    usa la frecuencia de 900MHz en sus transmisores WattUp. Ossia utiliza el espectro de 2.4GHz para su
                    estándar
                    "Cota".
                    ¿Cómo funciona el poder inalámbrico?</p>
                <div align="center">
                    <center>
                        <div class="seccion" id="">
                            <div class="col-center">
                                <h2>¿Cómo funciona el poder inalámbrico?</h2>
                            </div>
                        </div>
                    </center>
                </div><br>
                <p align="justify">Energous tiene diferentes requisitos para la transmisión, dependiendo de la
                    distancia.
                    Funciona hasta 15 pies de distancia. Para los objetos de "campo medio" a "campo lejano", Energous
                    usa la
                    formación de haces. Este proceso envía haces de energía directamente a un receptor desde el
                    transmisor WattUp.
                    Es un sistema gestionado por software. Comprueba los dispositivos Bluetooth a cargar, su distancia y
                    su
                    autorización de red. En otras palabras, el transmisor no desperdiciará su energía tratando de cargar
                    cada
                    dispositivo electrónico en la habitación.
                    En contraste, los receptores de Ossia envían primero una señal de baliza de baja potencia. Luego, el
                    transmisor de potencia Cota envía su energía a lo largo de esa vía de señal. A partir de ahí, el
                    proceso es el
                    mismo: el receptor convierte la RF a la alimentación de CC. Varios dispositivos pueden emitir
                    señales a la vez
                    y tener haces de RF dirigidos a ellos específicamente y simultáneamente. Los productos Cota tienen
                    chips
                    receptores, baterías u otros dispositivos de almacenamiento de energía instalados para enviar estas
                    señales,
                    convertir la energía en energía y almacenarla.<br>
                    En ambos casos, el dispositivo de carga puede moverse por la habitación. Su trayectoria de recepción
                    se
                    ajustará con ello. Sin embargo, en ambos casos, los dispositivos aplicables deben ser relativamente
                    de baja
                    potencia y los tiempos de carga son lentos. La carga, aunque lenta, es continua.</p>

