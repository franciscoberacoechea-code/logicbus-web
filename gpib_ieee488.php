<h1><strong>GPIB/IEEE-488</strong></h1>
<br>

<p align="justify"><strong>GPIB/IEEE-488</strong> consiste de una o más tarjetas de interfaz y uno o más instrumentos. Las tarjetas de interfaz son controladores GPIB que gobiernan el flujo de información en el bus. Esto se logra mandando comandos a los instrumentos para que hablen, escuchen o respondan a pedidos de servicio de los dispositivos. Puede haber mas de un controlador GPIB en un bus, pero solo uno puede tener el control a la vez. Un controlador GPIB pude pasar el control del bus de sí mismo a otro controlador en el bus, pero solo un controlador puede tener el control de bus. Este tipo de controladores es conocido como Controlador-A-Cargo (Controller-In-Charge, CIC o System Controller) y es responsable del manejo total de bus.</p>
