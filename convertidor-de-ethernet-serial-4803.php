        <center><strong>Convertidor/Servidor serial Ethernet a 8 puertos seriales, cada puerto configurable como RS232/RS422/RS485 con conectores DB9. Incluye cables Ethernet: 1 directo y 1 cruzado y 1 fuente de 127Vac a 5Vdc. Carcasa metalica. Compatible con Windows y Linux</strong></center><br>

        <p align="justify">El servidor Ethernet a serie 4803 es la forma más fácil de conectar dispositivos serie RS-232, RS-422 o RS-485 a su red Ethernet. Los productos SeaLINK® utilizan el protocolo TCP/IP RFC 2217 estándar de la industria para maximizar la compatibilidad con la más amplia gama de aplicaciones y dispositivos.
        <br><br>
        Los controladores y las utilidades del software SeaLINK facilitan la instalación y operación con los sistemas operativos Microsoft Windows. Después de la instalación del software, los puertos seriales del 4803 aparecen como puertos COM virtuales para la máquina host. Las llamadas operativas en serie estándar se redirigen de forma transparente al 4803, lo que garantiza la compatibilidad con los dispositivos en serie heredados y permite la compatibilidad con el software existente. El túnel en serie también es compatible, permitiendo que dos dispositivos seriales nativos se comuniquen a través de una red. Alternativamente, se admite el modo de socket de datos sin procesar, lo que elimina la necesidad de un controlador. Cada puerto se puede configurar individualmente como RS-232, RS-422 o RS-485.</p>

        Características:
        <ul>
