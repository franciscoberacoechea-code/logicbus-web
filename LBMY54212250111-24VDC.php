          de accionamiento, la que circula por la bobina del electroimán, y los circuitos controlados por relevadores,
          lo que hace que se puedan manejar altos voltajes o elevadas potencias con pequeñas tensiones de control.
          <br>
          También ofrecen la posibilidad de control de un dispositivo a distancia mediante el uso de pequeñas señales de
          control, viajando por la línea de control solo la corriente necesaria para activar la bobina.
          <br>
          Solo se necesitan ~40mA para activar la bobina del relevador, lo que permite que dispositivos con salida de
          baja potencia (tarjetas DAQ, PLC, módulo de control, etc.), pueda controlar cargas de hasta 5A.
