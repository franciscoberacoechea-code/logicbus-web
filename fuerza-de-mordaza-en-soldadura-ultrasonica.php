    <li style="color: black;">Adicionalmente, el <strong><a href="https://tienda.logicbus.com.mx/FSH03912_p_14231.html" target="_blank">IDA100</a></strong> permite registro y monitoreo de la salida de la celda de carga mediante el software SENSIT.</li>
