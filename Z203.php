<p>El modelo Z203 es un módulo para medici&oacute;n de potencia monof&aacute;sica con rango de entrada de 500 Vac y hasta 5 A (50~60 Hz). Este equipo permite obtener mediciones de variables el&eacute;ctricas como Vrms, Irms, Watt, Var, Frecuencia y factor de potencia.<br><br>
Las mediciones pueden ser obtenidas mediante comunicaci&oacute;n serial en los registros <a href="https://www.logicbus.com.mx/convertidores_info#Modbus">Modbus</a> correspondientes.<br><br>
Este dispositivo posee una salida an&aacute;loga configurable para corriente o voltaje para retransmisi&oacute;n de una de las variables (Vrms, Irms, Watt, Var, Frecuencia o factor de potencia) seleccionadas por el usuario v&iacute;a DIP switch. La salida an&aacute;loga es proporcional a la variable seleccionada y escalable mediante software.</p>
<strong>Caracter&iacute;sticas:</strong>
        <ul>
            <li>Comunicaci&oacute;n serial <a href="https://www.logicbus.com.mx/convertidores_info#RS-485">RS-485</a> con protocolo ModBus RTU, m&aacute;ximo 32 nodos.</li>
            <li>Par&aacute;metros configurables a trav&eacute;s de DIP switch o software.</li>
            <li>Salida an&aacute;loga de retransmisi&oacute;n aislada.</li>
            <li>Posibilidad de conexi&oacute;n con transformadores de corriente.</li>
            <li>Conexiones mediante terminales a tornillo y montaje en riel DIN.</li>
            <li>Protecci&oacute;n contra ESD de hasta 4 KV.</li>
            <li>LEDs indicadores de alimentaci&oacute;n, estado y comunicaci&oacute;n.</li>
            <li>Aislamiento entre la alimentaci&oacute;n, entradas y salida.</li>
          </ul>

