            <div class="col-12 col-md-7 text-justify">
                <p class="light-black">La <b>soldadura ultrasónica</b> une dos piezas de material (por ejemplo, plástico) mediante vibraciones de alta frecuencia. Este proceso produce soldaduras limpias y uniformes, creando uniones estancas a fluidos. Debido a su limpieza, la soldadura ultrasónica es ideal para equipos médicos, juguetes, semiconductores y electrónica de consumo. Uno de los aspectos clave para obtener una soldadura limpia es aplicar la fuerza de sujeción correcta. Demasiada poca fuerza resulta en una soldadura incompleta, mientras que demasiada fuerza puede deformar las piezas. Integrar una <b>celda de carga</b> en línea con el sistema de soldadura ultrasónica permite proporcionar la cantidad adecuada de fuerza de contacto a cada pieza.</p>
                <p class="text-center light-black font-weight-bold">¿Cómo funciona?</p>
                <ol class="light-black">
                    <li class="mb-3"><b>Instalación de la Celda de Carga:</b>
                        <ul>
                            <li>Una celda de carga de la serie <b>LCB/LCF</b> se monta entre el <b>convertidor</b> y el <b>actuador</b> que mueve el ensamblaje o pila de soldadura ultrasónica.</li>
                        </ul>
                    </li>
                    <li class="mb-3"><b>Amortiguación de Vibraciones:</b>
                        <ul>
                            <li>Se coloca un <b>amortiguador</b> entre el convertidor y la celda de carga <b>LCB/LCF</b> para minimizar los efectos de las altas vibraciones de velocidad sobre el sensor. Este amortiguador ayuda a mantener la precisión de las mediciones a pesar de las vibraciones generadas durante el proceso de soldadura.</li>
                        </ul>
                    </li>
                    <li class="mb-3"><b>Medición de la Fuerza de Sujeción:</b>
                        <ul>
                            <li>A medida que el ensamblaje aprieta las piezas a soldar, la celda de carga <b>LCB/LCF</b> mide las fuerzas de sujeción durante el <b>tiempo de soldadura</b> y de <b>mantención</b>.</li>
                        </ul>
                    </li>
                    <li class="mb-3"><b>Amplificación y Transmisión de Señales:</b>
                        <ul>
                            <li>Las señales de la celda de carga son amplificadas y transmitidas mediante los amplificadores <b>IAA Series</b> o <b>IDA100</b> a la <b>PLC</b> del soldador. Esto permite un <b>control de fuerza de sujeción en bucle cerrado</b>, garantizando que la cantidad correcta de fuerza se aplique durante todo el proceso.</li>
                        </ul>
                    </li>
                    <li class="mb-3"><b>Registro y Monitoreo de Datos:</b>
                        <ul>
                            <li>El <b>IDA100</b> permite la recopilación de datos y el monitoreo de la salida de la celda de carga mediante una PC con el software <b>SENSIT™</b>. Este software permite registrar, analizar y visualizar los datos en tiempo real.</li>
                        </ul>
                    </li>
                    <li class="mb-3"><b>Rastreo de Producción e IoT:</b>
                        <ul>
                            <li>Los datos generados a través de <b>SENSIT™</b> pueden ser utilizados para operaciones de <b>Internet de las Cosas (IoT) y trazabilidad de la producción</b>, facilitando la integración en procesos de calidad y seguimiento de producción.</li>
                        </ul>
                    </li>
                </ol>
                <p class="text-center light-black font-weight-bold">Beneficios del Sistema</p>
                <ul class="light-black">
                    <li class="mb-3"><b>Control de Fuerza de Sujeción</b>: La celda de carga permite asegurar que se aplique la cantidad justa de fuerza, evitando defectos de soldadura o daño a las piezas.</li>
                    <li class="mb-3"><b>Amortiguación de Vibraciones</b>: El uso de un amortiguador entre la celda de carga y el convertidor garantiza que las vibraciones no afecten las mediciones de la celda de carga, manteniendo la precisión.</li>
                    <li class="mb-3"><b>Monitoreo en Tiempo Real</b>: La capacidad de monitorear y registrar los datos en tiempo real ayuda a los operadores a ajustar los parámetros del proceso de manera óptima.</li>
                    <li class="mb-3"><b>Trazabilidad y Control de Calidad</b>: Los datos recolectados pueden ser utilizados para asegurar que las soldaduras cumplen con los estándares de calidad y para rastrear el proceso a lo largo de la producción.</li>
                </ul>
                <p class="light-black">Este enfoque de medir y controlar la <b>fuerza de sujeción</b> mediante una celda de carga permite optimizar el proceso de soldadura ultrasónica, mejorando la calidad del producto final.</p>
