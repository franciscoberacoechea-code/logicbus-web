          <P align="justify">El T201DC es un transductor de corriente aislado, sin contacto. La función y la apariencia del dispositivo es muy similar a los estándares activos CT, pero la diferencia es que puede medir la componente continua de la corriente que pasa por él. Para su resistencia eléctrica, facilidad de uso y dimensiones compactas, el T201DC es bueno para cualquier tipo de medición de corriente hasta 40Adc.</P>

          <STRONG>Características:</STRONG>
          <ul>
            <li>No tiene derivaciones, no se pierde potencia del circuito de corriente primario</li>
            <li>Alta precisión: clase |0.2|</li>
            <li>Alimentado por el lazo de 4 a 20 mA, desde 6 hasta 100 V, polaridad inversa, está protegido contra transitorios a 120V y picos a 1.5J</li>
            <li>Seleccionable entre 8 rangos, bipolares y unipolares, por medio de dip switch</li>
            <li>Sistema de detección de fallos por medio de un uC integrado</li>
            <li>Protección de sobrecalentamiento</li>
            <li>Rápida respuesta para sobrecorriente (~40ms)</li>
            <li>Útil para baterías, cargadores de baterías, paneles solares, unidades de potencia y cargas dc genéricas</li>
            <li>Tamaño Compacto: Menos de 40 x 40 x 20 mm</li>
            <li>Incluye el accesorio A-DIN-T201 para montaje en Riel DIN T201.</li>
          </ul>
