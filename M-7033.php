          <p> 
            El I-7033 es un módulo de entrada RTD de 3 canales que se utiliza para medir temperaturas a través de un sensor RTD y admite sensores de tipo Pt100, Ni120 y Pt1000. El módulo permite conexiones de RTD de 2/3/4 hilos y características de detección de cable abierto. Además, el I-7033 también incluye un aislamiento intramódulo de 3000 VDC y admite la eliminación de la resistencia del cable para conexiones de 3/4 hilos.</p><BR>

          <strong>Características:</strong>
          <ul>
            <LI>Entrada RTD de 3 canales.</LI>
            <LI>Eliminación de resistencia de plomo para conexiones de 3/4 hilos.</LI>
            <LI>Detección de cables abiertos.</LI>
            <LI>Protección contra ESD de 4 kV.</LI>
            <LI>Aislamiento intramódulo de 3000 VDC.</LI>
            <LI>Dual Watchdog.</LI>
            <LI>Amplio rango de temperatura de funcionamiento: -25 a + 75 ° C.</LI>
          </ul>
