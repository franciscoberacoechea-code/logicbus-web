<center><strong>Tarjeta PCI con 1 puerto CAN en modo maestro con firmware DeviceNet, protocolo CAN USB2.0A/USB2.0B, conector DB9 hembra.</strong></center><br>

<div align="right">
<a href="https://tienda.logicbus.com.mx/PISO-DNM100-D_p_1549.html" title="Ir a Tienda" target="_blank"><img src="images/shopping_cart.png" border=0></a>
