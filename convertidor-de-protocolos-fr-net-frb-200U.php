        <p class="subtitulo"><b>Tarjeta de comunicación FRnet de bus PCI aislada con 1 puerto FRnet.</b></p>

        <p>Los sistemas de control de entrada y salida basados en la PC se utilizan extensamente en usos de sistema de medición y control. Pero a veces es muy difícil resolver las demandas de las misiones de control de sincronización críticas. Como resultado de las características especiales del FRnet, tales como sincronización real de entrada y salida y tiempo fijo de exploración, las tarjetas FRB pueden ser agregadas a los sistemas basados en la PC para dar funciones de control adicionales como PLC, sin necesidad de mezclar reguladores basados en la PC con PLCs. </p>

        <p>La FRB-100/200/200U es una tarjeta de comunicación aislada de FRnet. La FRB-100 tiene un solo puerto de FRnet, mientras que la FRB-200/200U tiene dos puertos de FRnet. Cada puerto de FRnet puede controlar un máximo de 16 nodos de comunicación, enumerados a partir de 0 a 15. Cada solo nodo del módulo remoto de entrada y salida puede controlar un máximo de 16 canales de entrada y salida digitales. Es decir cada puerto de FRnet puede controlar un máximo de 128 canales de entradas digitales y 128 canales de salidas digitales. Las tarjetas tradicionales de alto canal de entrada y salida ocupan varias ranuras de la PC, tales como PIO-D144 o DIO-144, y los cables abultados pueden ser difíciles de dirigir. Varias tarjetas de FRB pueden ser combinadas para trabajar juntas para controlar miles de canales de entradas y salidas.</p>


