          <p>La serie I-7000 es una familia de módulos en red de control y adquisición de datos, proporcionando análogo a digital, digital a análogo, entrada/salida digital, temporizador/contador y otras funciones.  Los módulos pueden ser controlados remotamente usando comandos, los cuales son llamados protocolo DCON.  La comunicación entre los módulos y el host es en formato ASCII vía RS485 bidireccional.  La velocidad de transmisión es programable hasta 115.2 Kbps.
            <br><br>
            El módulo I-7016D proporciona acondicionamiento y protección rentable para un amplio rango de sistemas y control de señales industriales.  La utilidad DCON ayuda al usuario a configurar y probar el módulo I-7016D.  También se incluye muchas funciones de librería y programas demo para permitir al usuario desarrollar programas fácilmente bajo Windows, Linux y DOS.  Los usuarios pueden montar los módulos sobre riel DIN, panel o pared. También tiene un bloque de terminal a tornillos para conectar las señales.
            <br><br>
            El módulo I-7016D incluye software para adquisición de datos desde una computadora. Con Display.</p>
