<h3>LOS RESULTADOS</h3>

<p align="justify">Los resultados de la instalación fueron inmediatos. Al recibir y poder responder a los problemas dentro del centro de datos, la empresa Intermast ha podido maximizar el tiempo de actividad de la maquinaria en aproximadamente un 20%. Con las nuevas capacidades de seguimiento y análisis de datos de la aplicación InduSoft Web Studio, será posible mejorar aún más la eficiencia operativa en todo el centro de datos. Intermast podrá reducir los costos de energía, disminuir el tiempo de inactividad de la máquina y evitar costosas fallas de la máquina.</p>

