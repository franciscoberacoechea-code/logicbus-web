          <strong>Modulo de expansión para PLC serie FBs con salida para controlar 16 display LED de 7 segmentos u 8 display LED de 16 segmentos (o 128 LEDs independientes)</strong>
        </div><br>

        <p align="justify">El FBs-7SG2 es uno de los módulos de control de display LED de la serie PLC FBs. Éste módulo puede soportar hasta 16 dígitos del display LED de 7 segmentos (incluyendo el punto decimal) u 8 dígitos del display LED alfanumérico de 16 segmentos o 128 display LED independientes. El voltaje de conducción de éste módulo se puede seleccionar entre 2.4V y 11.7V con la finalidad de cumplir los requerimientos de diferentes tamaños de display LED. El modelo del display puede ser controlado directamente modificado el contenido del registro de salida. Para las aplicaciones involucradas con displays alfanuméricos de 16 segmentos se puede usar la instrucción de la función TDSP para asistencia.</p>
