<b>Ejemplos de aplicacion</b></p></center>
<li>Intercambiables a altas temperaturas</li>
<li>El RU-87P8 no necesita apagar su energía para reemplazar o enchufar los módulos de E / S I-87K. Todo el sistema puede seguir funcionando sin interrupción.</li>
<li>Configuración automática</li>
<li>Las configuraciones de los módulos de E / S I-87K se pueden preconfigurar y almacenar en la memoria no volátil del RU-87P8. Cuando el RU-87P8 está encendido o hay un módulo de E / S I-87K enchufado, el RU-87P8 verifica y restaura automáticamente estas configuraciones para cada módulo de E / S I-87K.</li>
<li>El sistema es fácilmente duplicable</li>
<li>Con la utilidad DCON, puede realizar fácilmente una copia de seguridad de las configuraciones del módulo I-87K y escribir en otra RU-87P8. Este diseño puede duplicar fácil y rápidamente muchas unidades de E / S de la serie RU-87P.</li>
</ul>

