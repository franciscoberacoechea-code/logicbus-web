<p>El codificador RH-P, también conocido como indicador de posición de pulso (PPI) o Tach, se usa generalmente para medir el movimiento lineal en un sistema de transportador. El número de pulsos por revolución se determina al configurar los interruptores de configuración. Normalmente está equipado con un par de ruedas medidoras de circunferencia de 12 ", modelo MW-1-B, o ruedas de circunferencia de 30 cm, modelo MW-30-B, que le permiten viajar directamente sobre la cinta transportadora, rastreando el transportador independientemente del transportador diámetro de los rodillos. El RH-P también incluye la característica Anti-Jitter que elimina los pulsos extraños generados si el transportador se detiene en un borde de impulso.</p><br>

<strong>Características</strong>
<ul>
<li>Pulsos programables/Revolución.</li>
<li>ESD/Cortocircuito/Voltaje reverso protegido.</li>
<li>Circuito "Anti-Jitter" exclusivo para aplicaciones de transportadores.</li>
<li>Vea el modelo R22 para un codificador con ruedas más pequeño.</li>
</ul>

<strong>Incluye los siguientes accesorios con cada artículo:</strong>
<ul>
<li>2x MW-30-B rueda de medición de circunferencia de 30 cm, diámetro interior de 3/8 ".</li>
<li>1x MB-UB1 Under-belt montaje de montaje de contrapeso.</li>
<li>1x C3-3-20 CF Montaje de cable de 3 pines, 3 conductores y 20 pies.</li>
</ul>
