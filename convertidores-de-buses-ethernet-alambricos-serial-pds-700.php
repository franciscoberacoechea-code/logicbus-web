        <p class="subtitulo"><b>Servidor de Dispositivos Programable (PDS) - Multipuertos de Serial a Ethernet</b></p>

        <p>Conecta todos tus dispositivos seriales a Ethernet. PLCs, lectores de código de barras, Lectores RFID, medidores, controladores de movimiento, y muchos otros dispositivos seriales que han sido ampliamente usados durante años. Para hacer el mayor uso de los datos registrados y para lograr un control remoto conveniente, &eacute;ste equipo integra esos dispositivos seriales con redes modernas. Toda la serie PDS tiene la habilidad programable que convierte tus ideas en realidad.</p>

        <p><b>Características</b></p>

        <p><b>Habilidad de Programación</b><br>
        El PDS ofrece el XServer (Libreria incluída) que permite a los usuarios desarrollar firmware propio de valor agregado de una manera fácil</p>
        <div align="center"><a href="imagenes/02/PDS_01.gif"><img src="imagenes/02/PDS_01.gif" alt="Programmable Device Servers (PDS)" width="70%" ></a></div>


        <p class="mt-5"><b>Virtual COM (Driver + Utilería)</b> <br>
        Hay dos maneras de accesar a los dispositivos seriales a trav&eacute;s del PDS del lado de la PC. Una es por TCP/IP y otra es por medio de VirtualCOM. Con VirtualCOM hacemos una perfecta integración de los puertos COM del PDS con la PC.</p>

        <p>Con el driver  VxComm, puedes convertir fácilmente los puertos com del PDS en puertos de la PC, lo que te ahorrará tiempo para reprogramar el software original de la PC y te dejará tener un fácil acceso a trav&eacute;s de internet a tu PDS.</p>

        <p>Con la utilería  VxComm, puedes escanear el PDS, configurarlo y hacer un mapeo masivo extendido de COM en segundos. Y una función de pruebas integrada es ofrecida por esta utilería.</p>

        <div align="center"><img src="imagenes/02/PDS_02.gif" alt="Programmable Device Servers (PDS)" width="70%"></div>

        <p class="mt-5"><b>Varias Selecciones</b> <br>
        La serie completa PDS-700 incluye de 2 puertos COM a 8 puertos COM, y algunos de los modelos están equipados con hasta 6 Entradas Digitales y 7 Salidas Digitales al mismo tiempo. Hay más de 10 modelos para seleccionar.</p>
        <div align="center"><img src="imagenes/02/PDS_00.jpg" alt="Programmable Device Servers (PDS)" width="30%"></div>

        <p><b>Virtual I/O</b> <br>
        "Virtual I/O" es la tecnología de extensión del "Virtual COM". El Virtual I/O hace exactamente lo que hace Virtual COM, la única diferencia es que el Virtual I/O convierte las Entradas y Salidas digitales del PDS en puertos COM de la PC. Y así puedes accesar a las E/S digitales del PDS por el protocolo DCON. Además, la utilería DCON soporta configurar las E/S digitales por el Viertual COM para que asi puedas hacer pruebas de funciones básicas o aplicaciones de una manera conveniente.</p>
        <div align="center"><img src="imagenes/02/PDS_03.jpg" alt="Programmable Device Servers (PDS)" width="70%"></div>



