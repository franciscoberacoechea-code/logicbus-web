        <p>WinPAC-8000 es el PAC de segunda generación de ICP DAS. Equipa CPU PXA270 (520MHz) con sistema operativo Windows CE .NET 5.0, conectividades variantes (VGA, USB, Ethernet, RS-232/485) y ranuras 1/4/8 para módulos de E / S paralelos de alto rendimiento (alto perfil I-8K series) y módulos de E / S de tipo serie (módulos I / O de alto perfil I-87K).<br>
          Su sistema operativo, Windows CE 5.0, tiene muchas ventajas, incluyendo capacidad dura en tiempo real, tamaño de núcleo pequeño, velocidad de arranque rápida, manejo de interrupciones a un nivel más profundo, control determinista alcanzable y bajo costo. El uso de Windows CE 5.0 en WinPAC-8000 le da la capacidad de ejecutar software de control basado en PC como Visual Basic.NET, Visual C #, Embedded Visual C ++, software SCADA, Soft PLC ... etc.
        </p><BR><br>


        <strong>Caracteristicas:</strong>
        <ul>
          <li>Puerto VGA incorporado</li>
          <li>Capacidad de intercambio en caliente del módulo de E / S (estará disponible)</li>
          <li>(Para los módulos de perfil alto I-87K solamente)</li>
          <li>Capacidad de expansión de E / S enriquecida (RS-232/485, Ethernet, FRnet, CAN)</li>
          <li>Disco flash incorporado (31 MB para WP-8x4x, 63 MB para WP-8x3x)</li>
          <li>Temporizador de doble vigilancia</li>
          <li>SRAM con respaldo de batería doble (512 KB)</li>
          <li>Puertos Ethernet dobles</li>
          <li>Entrada de energía redundante</li>
          <li>El diseño de la carcasa con ventilación permite la operación entre -25 ? ~ + 75 ?</li>
        </ul>

