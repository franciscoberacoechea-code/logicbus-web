<p align="justify">ViewPAC-25W9 es la nueva generación basada en WinCE InduSoft PAC de ICP DAS. ViewPAC combina WinPAC, pantalla gráfica y teclado en una unidad. Equipa una CPU PXA270 (520MHz) que ejecuta el sistema operativo Windows CE.NET 5.0, conectividades variantes (USB, Ethernet, RS-232/485), 3 ranuras para expandir módulos de E / S, LCD TFT de 5.7 "y un teclado de goma.<br /><br />
Su sistema operativo, Windows CE.NET 5.0, tiene muchas ventajas, incluye capacidad dura en tiempo real, tamaño de núcleo pequeño, velocidad de arranque rápida, manejo de interrupciones a un nivel más profundo, control determinista alcanzable y bajo costo. InduSoft Web Studio Runtime también está preinstalado. InduSoft Web Studio es una poderosa colección integrada de herramientas de automatización que incluye todos los componentes necesarios para desarrollar las modernas interfaces de máquina humana (HMI), control de supervisión y adquisición de datos (SCADA), y aplicaciones integradas de instrumentación y control.<br />
En comparación con las soluciones IPC + PLC tradicionales, ViewPAC reduce el costo general del sistema, el espacio y le ofrece todas las mejores características de IPC y PLC.</p>
