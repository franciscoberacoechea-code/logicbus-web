                    <li class="mb-3">El TRS605 fue colocado directamente entre el cigüeñal del motor y el freno regenerativo, permitiendo capturar simultáneamente mediciones de torque y desplazamiento con un solo sensor.</li>
                    Para la gestión de datos, el USB520 fue la solución ideal para traducir las lecturas del encoder rotativo, tales como ángulo y velocidad. Su diseño compacto y robusto lo hace perfecto para este tipo de aplicación.</li>
