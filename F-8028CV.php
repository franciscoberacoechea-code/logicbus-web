<center><strong>Módulo redundante de salida analógica de 8 canales (cubierta gris) (RoHS).</strong></center><br>

<p>El F-8028CV es un módulo de salida analógica de 16 bits y 8 canales que presenta un rango de salida programable en todos los canales. Proporciona un convector digital a analógico controlado por el módulo del sistema para convertir los datos digitales en señales de salida. Los usuarios pueden especificar el valor de inicio y seguridad a través del software de configuración. Además, este módulo tiene una precisión de ± 0.05% para una aplicación altamente precisa. Además, el F-8028CV proporciona aislamiento óptico de 3000VDC entre canales y bus de fondo. Si cualquier alto voltaje o corriente daña estos canales, este módulo no afectará a otros componentes en el sistema iDCS-8000.</p>

Caracteristicas:
<ul>
<li>8 canales de salida de corriente / voltaje.</li>
<li>Exceso de rango.</li>
<li>Protección contra cortocircuitos.</li>
<li>Detección de cable abierto.</li>
<li>Conformidad con la RoHS.</li>
<li>Aislamiento de 3000 VDC desde la salida al plano posterior.</li>
<li>Aislamiento de 3000 VDC desde la salida a la tierra del cuadro.</li>
<li>Redundancia.</li>
<li>Tiempo de conmutación redundante rápido ( < 1 ms).</li>
</ul>
Aplicaciónes:
<ul>
<li>Automatización de edificios.</li>
<li>Automatización industrial.</li>
<li>Automatización de máquinas.</li>
<li>Mantenimiento remoto.</li>
<li>Diagnóstico remoto.</li>
<li>Equipo de pruebas.</li>
</ul>
