<center><strong>Conmutador Ethernet no gestionable de 5 puertos 10/100 Mbps PoE (PSE) con carcasa metálica; Entrada de 24 VDC. Tiene temperaturas de funcionamiento de -40 ° C ~ + 75deg; F (-40 ° F ~ + 167 ° F).</strong></center><br>

<p>El NS-205PSE-24V / NSM-205PSE-24V es un conmutador Ethernet industrial PoE (Alimentación por Ethernet) no gestionable de 5 puertos; admite 4 puertos PoE que se clasifican como equipos de fuente de alimentación (PSE). El NS-205PSE-24V / NSM-205PSE-24V hace que la fuente de alimentación centralizada se haga realidad y proporciona hasta 15.4 vatios de potencia por puerto PSE.<BR>

El NS-205PSE-24V / NSM-205PSE-24 está diseñado con un impulso de 24 VCC a 48 V CC para aplicaciones PoE donde la fuente de alimentación de 48 VCC no está disponible.</p><BR>

<strong>Caracteristicas</strong>

<ul>
<li>Crossover automático MDI / MDI-X para plug-and-play</li>
<li>Cada puerto admite una negociación automática de velocidad de 10/100 Mbps</li>
<li>Arquitectura de almacenamiento y reenvío</li>
<li>Control de flujo de contrapresión Full Duplex IEEE 802.3xy semidúplex</li>
<li>Ancho de banda de memoria de alto rendimiento de 3.2 Gbps</li>
<li>Entrada de energía, +18 VDC ~ +32 VDC</li>
<li>Admite temperaturas de funcionamiento de -40 ° C ~ +75 ° C</li>
<li>Carril DIN</li>
<li>Puertos PoE compatibles con IEEE 802.3af</li>
<li>Cuatro puertos PoE con operación del equipo de abastecimiento de energía (PSE)</li>
<li>Detección automática de PD (dispositivos con alimentación) y administración automática de energía</li>
<li>Detección de sobretemperatura, sobrecorriente y sobre / bajo voltaje</li>
</ul>
