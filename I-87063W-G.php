<p style="text-align: justify;">El módulo I-87063W proporciona 4 canales de entrada digital aislados y 4 canales de salida rele forma C. Todos los canales de entrada digital se pueden usar como contadores de 16 bits. Además, se puede seleccionar entrada digital tipo sink o source a través de las conexiones de cables. El I-87063W incluye 8 indicadores LED que se pueden usar para monitorear el estado de la Entrada Digital y la Salida de Relé, y hay opciones disponibles para configurar el encendido y los valores seguros. También se proporcionan protección ESD de 4 kV y aislamiento intramódulo de 3750 VDC para mejorar las capacidades de protección contra el ruido del módulo en entornos industriales hostiles.</p><br>


<strong>Caracteristicas:</strong>
<ul>
<li>Entrada digital de 4 canales y salida de relé de 4 canales</li>
<li>Salida de relé de potencia forma C</li>
<li>Canales de entrada digitales tipo Sink y Source</li>
<li>Los canales de entrada digital se pueden usar como contadores de 16 bits</li>
<li>Valor de encendido configurable</li>
<li>Valor seguro configurable</li>
<li>Protección contra ESD de 4 kV</li>
<li>Aislamiento intramódulo de 3750 VDC</li>
<li>RoHS</li>
<li>Amplio rango de temperatura de funcionamiento: -25 a + 75 ° C</li>
</ul>



