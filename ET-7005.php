<p>El ET-7005, es un módulo Ethernet que posee un servidor web integrado que permite configurar el módulo, controlar y monitorear las E/S desde cualquier navegador web.<br>

Con la función web HMI, no es necesario programar ni tener habilidades en HTML; la creación de páginas web dinámicas y atractivas para el control y monitoreo de entradas/salidas será divertido para los ingenieros. El ET-7005 ofrece a los usuarios un acceso fácil y seguro desde cualquier lugar y a cualquier hora.<br>

Además, el ET-7005 soporta también el protocolo Modbus/TCP, lo cual hace una perfecta integración entre este dispositivo y software SCADA.<br>

El ET-7005 es un módulo de 16 bits con 8 entradas análogas diferenciales y 4 salidas digitales, se pueden programar los rangos de entrada en todos sus canales análogos y la salida digital puede ponerse como salida de alarma. Cada canal análogo permite configurarle un rango individual.</p><BR>

