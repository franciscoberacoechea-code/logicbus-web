          <center><strong>Módulo de entrada digital aislado de 8 canales, comunicable por medio del protocolo ModBus y RS-485.</strong></center><br>

          <p>El tM-P8 ofrece 8 canales para entrada digital, cada uno de los cuales cuenta con aislamiento de fotocouple. Además, la entrada puede ser de tipo sink o source utilizando conexiones de cable y todos los canales se pueden utilizar como contadores de 16 bits. También se proporciona una protección ESD de 4 kV y un aislamiento intramódulo de 3750 VDC.<p>

            <strong>Caracter&iacute;sticas </strong>
          <ul>
            <li>Entradas digitales tipo fregadero y fuente.</li>
            <li>Aislamiento de fotocouple.</li>
            <li>Todos los canales se pueden utilizar como contadores de 16 bits.</li>
            <li>Watchdog dual.</li>
            <li>Económico.</li>
            <li>Amplio rango de temperatura de funcionamiento: -25 ~ + 75°C.</li>
          </ul>

          <strong>Aplicaciones:</strong>
