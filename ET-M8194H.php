<p>El ET-M8194H es un producto nuevo de ICP DAS que se puede utilizar para implementar la funcionalidad de control remoto a través de Ethernet e incluye un módulo I-8094H (un módulo de control de servomotor paso a paso / pulsado de 4 ejes con una CPU integrada) y una interfaz de comunicación Ethernet. El ET-M8194H inteligentepuede proporcionar a los usuarios la capacidad de desarrollar una amplia gama de aplicaciones de control de movimiento remoto, y puede integrarse en cualquier sistema donde la plataforma de host esté construida en el protocolo Modbus TCP (por ejemplo: PC, PAC o PLC). Además, la implementación de una solución de control de movimiento multi-estación y multieje se puede lograr fácilmente mediante la conexión en cascada de varios dispositivos ET-M8194H utilizando cables Ethernet, ya sea con o sin conmutadores Ethernet. ICP DAS también proporciona la utilidad EzMove y una biblioteca de API que se puede utilizar para configurar el ET-M8194H y desarrollar rápidamente aplicaciones de control personalizadas.</p>        

<strong>Caracteristicas:</strong>
<ul>
<li>Control remoto a través de Modbus TCP / Ethernet</li>
<li>Se puede controlar usando SCADA, PAC o PLC, etc.</li>
<li>Se puede integrar en aplicaciones multieje de múltiples ejes</li>
<li>Capacidad de control de movimiento de 4 ejes</li>
<li>Función de interpolación lineal de 2/3 ejes</li>
<li>Función de interpolación circular de 2 ejes</li>
<li>Función programable de inicio automático</li>
<li>Viene con la utilidad EzMove para configuración y macroprogramación</li>
<li>Probar funciones de movimiento a través de EzMove sin compilación</li>
<li>Biblioteca API para el desarrollo rápido de aplicaciones</li>
<li>Fácil cableado para aplicaciones de estaciones múltiples</li>
<li>Función IP_lock para control remoto de seguridad</li>
</ul>




