          <h1 align="center"><strong>PCI</strong></h1>
          <br>

          <p align="justify">Bus estándar de computadoras para conectar dispositivos periféricos directamente a la placa base. Estos dispositivos pueden ser circuitos integrados ajustados en esta (los llamados dispositivos planares en la especificación PCI) o tarjetas de expansión que se ajustan en conectores. Es común en computadoras personales, donde ha desplazado al ISA como bus estándar, pero también se emplea en otro tipo de computadoras.
            <br><br>
          En diferencia de los buses ISA, el bus PCI permite configuración dinámica de un dispositivo periférico. En el tiempo de arranque del sistema, las tarjetas PCI y el BIOS interactúan y negocian los recursos solicitados por la tarjeta PCI. Esto permite asignación de las IRQ y direcciones del puerto por medio de un proceso dinámico diferente del bus ISA, donde las IRQ tienen que ser configuradas manualmente usando jumpers externos.</p>

