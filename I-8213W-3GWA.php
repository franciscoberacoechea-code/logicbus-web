<center><strong>Módulo 3G Industrial de tres bandas con función de GPS (RoHS).</strong></center><br>

<p>El I-8213-3GWA es un módulo industrial Tri-banda 3G con función de GPS que funciona en frecuencias de WCDMA 2100/1900/850 MHz y GSM 850/900/1800/1900 MHz. Estos módulos utilizan la red 2G / 3G para la transferencia de datos conveniente y económica desde instrumentos remotos, medidores, computadoras o sistemas de control en datos en vivo o paquetes de datos. Estos módulos tienen la pila TCP / IP integrada para que incluso los controladores simples con puertos de comunicaciones seriales puedan conectarse al módem sin la necesidad de una implementación especial del controlador. Con las características de los suyos, los sistemas pueden ser aplicaciones de conexión SMS y GPRS o 3G con nuestras series PAC como iPAC-8000, WinPAC-8000, LinPAC-8000 o XP-8000.</p>

Caracteristicas:
<ul>
<li>Admite Tri-banda WCDMA 2100/1900/850 MHz y banda cuádruple GSM 850/900/1800/1900 MHz.</li>
<li>Protección contra ESD de 4 KV.</li>
<li>Diseñado para aplicaciones WCDMA, GPRS y SMS.</li>
<li>Admite servidor TCP, cliente TCP, pila de conexión de cliente UDP de 3G o GPRS.</li>
<li>Soporta comandos estándar AT.</li>
<li>Indicadores LED para indicadores de encendido, GSM y GPS (solo I-8213W-3GWA).</li>
<li>Alta confiabilidad en entornos hostiles.</li>
<li>Soporte de 32 canales GPS y NMEA v0183 v3.01 (solo I-8213W-3GWA).</li>
<li>PPS: salida de impulsos de 100 ms / seg para la medición precisa del tiempo y el tiempo (solo I-8213W-3GWA).</li>
<li>Soporte XP-8000, WinPAC-8000, LinPAC-8000, ViewPAC, iPAC-8000.</li>
</ul>
