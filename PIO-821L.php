<center><strong>Tarjeta PCI, 45 kS/s Baja Ganancia,proporciona 16 canales de entrada análoga u 8 diferenciales, rangos de entrada programables por software, rangos de salida de +/-5V, +/-2.5V, +/-1.25V y +/-0.625, resolución de 12 bit, 1 canal de voltaje de salida 0-5V o 0-10V seleccionable por jumper, 16 canales digitales de entrada y 16 canales digitales de salida, 3 temporizadores/contadores, ganancia programable 1, 2, 4 y 8.</strong></center><br>


<p>La PCI-821L / H es una placa multifuncional de alto rendimiento para computadoras compatibles con PC / AT. El PCI-821L proporciona baja ganancia (1, 2, 4, 8) y el PCI-821H admite alta ganancia (1, 10, 100, 1000). El PCI-821L / H contiene un ADC de 12 bits con hasta 16 canales de entrada análoga unipolares u 8 diferenciales. También tiene salidas de voltaje DAC de 12 bits y 16 canales de entrada digital y salida digital compatibles con TTL, respectivamente. La velocidad máxima de muestreo del convertidor A / D es de aproximadamente 45K.sample / sec.
</p><BR><br>

<strong>Caracteristicas</strong>

<ul>
<li>La máxima tasa de muestreo del convertidor A/D está alrededor de 45 kS/s</li>
<li>Los rangos de entrada son seleccionables por software</li>
<li>Bus PCI compatible con PS/AT</li>
<li>Modo de Disparo del A/D: software trigger, pacer trigger, external trigger</li>
<li>16 canales en Modo Común / 8 canales diferenciales de entrada analógicos</li>
<li>Alta ganancia programable de: 1, 10, 100, 1000 (PCI-821H)</li>
<li>Baja ganancia programable de: 1,2,4,8 (PCI-821L)</li>
<li>Rango de entrada: ±5V,±0.5V, ±0.05V,±0.005V(PCI-821H)</li>
<li>Rango de entrada:±5V,±2.5V,±1.25V,±0.625V (PCI-821L)</li>
<li>1 Canal para la salida de voltaje del D/A de 12 bits</li>
<li>16 entradas digitales/16 salidas digitales (TTL compatible)</li>
</ul>
