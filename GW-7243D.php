<center><strong>Modulo de Puerta de Enlace (Gateway) entre una red DeviceNet Esclavo y una red Modbus TCP. Con un puerto Rs232/ un puerto Rs485/ señales CAN H y CAN L/ puerto Ethernet 10/100. Alimentacion de 10~30VDC</strong></center><br>

