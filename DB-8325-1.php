<p>La DB-8325 es una placa de terminales de tornillo universal rentable para tarjetas A / D aisladas de la Serie ISO-813 y Serie PISO-813. La placa se puede usar para implementar filtros de paso bajo, derivación de corriente y funciones de atenuación de voltaje, e incluye almohadillas en blanco para la detección de rotura, así como un conector de 37 pines (CN3).
La siguiente es una descripción general de las características proporcionadas por la placa de terminales DB-8325:
<ul>
  <li>Tablero de terminales de tornillo de bajo costo.</li>
  <li>Almohadillas en blanco para la detección de rotura.</li>
  <li>Filtro de paso bajo, derivación de corriente y atenuación de voltaje.</li>
</ul>

La placa de bornes DB-8325 proporciona la capacidad de realizar las funciones de filtro de condensador, divisor de voltaje y entrada de corriente, cada una de las cuales se describe con más detalle a continuación. Lo siguiente proporciona una ilustración del método de cableado.<br>
La placa de terminales DB-8325 proporciona la capacidad de realizar funciones de filtro de condensador, divisor de voltaje y entrada de corriente.
<br>
El filtrado de entrada se puede implementar en la placa de terminales DB-8325 instalando una resistencia y un condensador en el canal de entrada deseado.
<br>
La placa de terminales DB-8325 proporciona dos resistencias en el canal de entrada que se pueden usar para dividir la señal de voltaje de entrada si el nivel de señal es mayor que el rango de entrada para la tarjeta A / D.
<br>
Para medir la señal de entrada actual, se debe instalar una resistencia de 250 &Omega; en RD2.</p>
