      <td colspan="2"><div align="justify">The DNA-AI-224 and DNR-AI-224 are high speed, four channel strain gage input boards for data acquisition and control Cubes and RACKtangle&reg; I/O racks respectively. The boards provide an ideal combination of high speed, accuracy and connection flexibility and are suitable for use in a wide variety of applications.<br>
          <br>
          The analog inputs offer 18-bit resolution at sample rates up to 100 kilosamples per second. Each channel has an A/D converter and all four channels are sampled simultaneously. The combination of the 18-bit resolution with the board&rsquo;s automatic offset zeroing and automatic gain calibration ensure the measurements are extremely accurate. Each channel also includes an anti-aliasing filter that automatically is configured to match the sample rate (*Please see the note on the following page for details)<br>
          <br>
          The DNx-AI-224 accepts inputs from full, half or quarter bridge gages and load cells. Bridge completion resistors are built in for use with 120, 350 and 1000 ohm gages. Of course full bridge gages of any resistance value may also be measured. Each channel offers an independent excitation output, programmable from 0 to &plusmn;10 Vdc, in 65535 steps. The excitation outputs can drive up to 50 mA each, allowing 1k bridges to be driven at &plusmn;10 Vdc, 350 ohm bridges at &plusmn;8.75 V and 120 ohm bridges at up to &plusmn; 3 Vdc.<br>
          <br>
          The board provides on-board compression and tension shunt calibration with shunt-calibration values selectable between 10 k and 170 k ohm, in 256 steps. Connections for external, user supplied shunt resistors are also provided. An automatic input nulling/balancing capability has also been built in allowing most bridges to be quickly and easily balanced before testing actually begins.<br>
          <br>
          The DNx-AI-224 offers 350 Vrms of isolation between the I/O connections and the Cube or RACKtangle. Like all UEI &ldquo;Cube&rdquo; and RACKtangle I/O boards, the DNA offers operation in harsh environments. Cube systems have been tested to 5g vibration, 50g shock, -40 to +85 &deg;C and altitudes up to 70,000 feet.<br>
          <br>
      Software for the DNA/DNR-AI-224 is provided as part of the UEI Framework. The framework provides a comprehensive yet easy to use API that supports all popular Windows programming languages as well as supporting programmers using Linux and most real-time operating systems including QNX, RTX, RT Linux and more. Finally, the framework supplies complete support for those creating applications in LabVIEW, MATLAB/Simulink, DASYLab or any application supporting ActiveX or OPC servers.</div></td>
