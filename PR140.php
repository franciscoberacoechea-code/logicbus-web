                <p align="justify">El PR140 es un registrador de datos de presión diseñado para su uso en la validación
                  y mapeo de autoclaves. Este robusto dispositivo puede soportar temperaturas de hasta 140 ° C y es
                  completamente sumergible (IP68).
                  <br><br>
                  El PR140 está construido con un manómetro de precisión de acero inoxidable. El dispositivo tiene una
                  precisión de ± 0.03 Bar (± 0.435 PSI), que se puede lograr en un amplio rango de temperatura, desde 20
                  ° C hasta +140 ° C (68 ° F a 284 ° F). El PR140 se puede programar para tomar lecturas con una
                  frecuencia de tan solo una vez por segundo (1 Hz) y tiene memoria no volátil que puede almacenar hasta
                  32,700 mediciones.
                  <br><br>
                  El puerto de presión NPT de 1/8 pulgadas que aparece en el dispositivo permite la compatibilidad con
                  una variedad de accesorios y adaptadores. Esto es ideal para propósitos de calibración, así como para
                  conectar el registrador de datos para medir sistemas de presión de proceso.
                  <br><br>
                  El PR140 es fácil de usar. Simplemente colóquelo en la estación de acoplamiento IFC400 o IFC406 (se
                  vende por separado), conéctese a una computadora y el dispositivo puede iniciarse, detenerse o
                  descargarse con el software MadgeTech. Los datos gráficos, tabulares y de resumen se proporcionan para
                  el análisis y se pueden ver en PSIA, mmHg, bar, Torr y kPa. Los datos también se pueden exportar
                  automáticamente a Excel® para realizar más cálculos.
                </p>

