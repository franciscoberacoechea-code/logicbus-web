<center><strong>Módulo de 16 canales de salida para relevador tipo Form A.</strong></center><br>

<p style="text-align: justify;">El I-87061PW es un módulo de salida de relé de potencia de 16 canales donde cada canal de salida de relé es independiente. El I-87061W es un módulo de salida de relé de potencia de 16 canales con los canales de salida divididos en cuatro grupos, donde cada grupo proporciona cuatro canales que comparten un solo punto COM. Los módulos I-87061W e I-87061PW incluyen 16 indicadores LED que se pueden usar para monitorear el estado de la salida del relé, y también están disponibles las opciones para configurar los valores de encendido de relé de encendido y de seguridad. La protección ESD de 4 kV y el aislamiento intramódulo de 3750 VDC se proporcionan de forma estándar para mejorar las capacidades de protección contra el ruido en entornos industriales hostiles.</p><br>


<strong>Caracteristicas:</strong>
<ul>
<li>Salida de relé de potencia de 16 canales dividida en cuatro grupos, donde cada grupo proporciona cuatro canales que comparten un solo punto COM.</li>
<li>± 4 kV Protección ESD</li>
<li>Aislamiento intramódulo de 3750 VDC</li>
<li>Valor de encendido configurable</li>
<li>Valor seguro configurable</li>
<li>Dual Watchdog</li>
<li>Amplio rango de temperatura de funcionamiento: -25 a + 75 ° C</li>
</ul>



