                <p class="paragraph text-justify">Los <strong>termómetros de resistencia </strong> o <strong>termómetros
                        a resistencia </strong> son transductores de temperatura, los cuales se basan en la dependencia
                    de la resistencia eléctrica de un material con la temperatura, es decir, son capaces de transformar
                    una variación de temperatura en una variación de resistencia eléctrica. </p>
                <p class="paragraph text-justify">Los <strong>RTD </strong> son sensores de temperatura resistivos. En
                    ellos se aprovecha el efecto que tiene la temperatura en la conducción de los electrones para que,
                    ante un aumento de temperatura, haya un aumento de la resistencia eléctrica que presentan.</p>
            </div>
        </div>
        <div class="container my-5 text-justify paragraph">
            <p>Este efecto suele aproximarse a un sistema de primer o segundo orden para facilitar los cálculos. Los
                sensores RTD suelen ir asociados a montajes eléctricos tipo Puente de Wheatstone, que responden a la
                variación de la resistencia eléctrica por efecto de la temperatura para originar una señal analógica de
                4-20 mA que es la que se utiliza en el sistema de control correspondiente como señal de medida.</p>
            <p>Un tipo de RTD son las <strong>Pt100 </strong> o <strong>Pt1000</strong>. Estos sensores deben su nombre
                al hecho de estar fabricados de platino (Pt) y presentar una resistencia de 100ohms o 1000ohms
                respectivamente a 0°C. Son dispositivos muy lineales en un gran rango de temperaturas.</p>

            <p>El platino tiene la particularidad de tener una relación resistencia-temperatura sumamente lineal, por lo
                cual es el material más utilizado y generalmente se le denominan a estos termómetros IPRT (
                <em>Industrial Platinum Resistance Thermometer </em>) o RTD ( <em>Resistance Temperature Detector
                </em>). El platino tiene las ventajas de:
            </p>
            <ul>
                <li>Ser químicamente inerte</li>
                <li>Tiene un elevado punto de fusión (2041,4 K)</li>
                <li>Como ya hemos dicho, tiene una alta linealidad</li>
                <li>Puede ser obtenido con un alto grado de pureza. </li>
            </ul>

