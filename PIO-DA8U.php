<center><strong>PCI universal, incluye 8 canales de salida analoga de 14 bit, rango de +/-10V y 0-20mA, así como también incluye 16 canales digitales de entrada y 16 canales digitales de salida, cuenta con 3 temporizadores/contadores de 16 bit.</strong></center><br>


<p>Las tarjetas de salida analógicas PISO-DA8U y PIO-DA8U admiten una interfaz PCI universal (3,3 V / 5 V PCI). Estas tarjetas están equipadas con 8 canales de salida analógica de 14 bits. Cada uno de los canales D / A presenta un pestillo doble. Las tarjetas de la serie PISO-DAxU y PIO-DAxU (versiones universales PCI) son totalmente compatibles con las tarjetas PIO-DAx (versiones PCI) y los usuarios pueden reemplazar el PIO-DAx por PISO-DAxU o PIO-DAxU directamente sin software / controlador modificación.<br>

La serie PISO-DA agrega diseño de aislamiento de alto voltaje que ofrece una capacidad duradera para mantener las computadoras de los usuarios a salvo de sobretensiones inesperadas. ¡Son los componentes de aislamiento de alta calidad incorporados los que hacen que la serie PISO-DA tenga un aislamiento de 2500 VDC con bus! Para las series PIO-DA y PISO-DA, su rango de salida de voltaje es de -10 V a +10 V, y su rango de salida de corriente es de 0 a 20 mA. Además, la serie PISO-DA y la serie PIO-DA también presentan las siguientes ventajas gracias a la innovación de ICP DAS:<br>

<ul>
<li>Calibración precisa y fácil de usar.
ICP DAS proporciona la calibración del software en lugar de la calibración manual, de modo que ya no se requieren jumpers y trim-pots. La información de calibración se puede guardar en EEPROM para uso a largo plazo.</li>
<li>Configuración de canal individual.
En otras palabras, ¡cada canal se puede configurar individualmente como salida de tensión o salida de corriente!</li>
<li>Tarjeta de identificacion.
ICP DAS proporciona la función de identificación de tarjeta para la serie PISO-DA y PIO-DA8U (versión 1.1 o superior). Los usuarios pueden configurar la identificación de la tarjeta para cada tarjeta y luego reconocerlas una a una cuando se usan más de dos tarjetas en una computadora.
La serie PISO-DA y la serie PIO-DA admiten una amplia gama de sistemas operativos, como Linux, DOS, Windows 98 / NT / 2000 y Windows XP / Vista / 7 de 32 bits. Además, ICP DAS proporciona todos los archivos DLL y Active X para los usuarios, y ejemplos de programas que abarcan desde Turbo C ++, Borland C ++, Microsoft C ++, Visual C ++, Borland Delphi, Borland C ++ Builder, Visual Basic, C # .NET, Visual Basic.NET y ¡LabView también se proporciona para un aprendizaje intuitivo y rápido!</li>
</ul>

</p><BR><br>

<strong>Caracteristicas</strong>

<ul>
<li>Admite bus PCI de +5 V para PIO-DA8</li>
<li>16/8/4 canales, salida analógica de 14 bits</li>
<li>Rango de salida de voltaje: ± 10 V</li>
<li>Rango de salida actual: 0 ~ 20 mA (fregadero)</li>
<li>Fuente de interrupción del temporizador de dos pacer</li>
<li>Doble-buffer D / A pestillo</li>
<li>Calibración de software</li>
<li>16 canales DI, 16 canales DO</li>
<li>Un conector D-Sub, dos conectores de cable plano de 20 pines</li>
<li>Se conecta directamente a DB-16P, DB-16R, DB-24C, DB-24PR y DB-24POR</li>
<li>Compatible con bus PCI +5 V y +3.3 V</li>
<li>Protección de aislamiento de potencia y tipo bus de 2500 VDC</li>
<li>El puerto de entrada digital se puede configurar para jalar alto o jalar bajo</li>
<li>Función de ID de tarjeta, (Versión 1.1 o superior)</li>
