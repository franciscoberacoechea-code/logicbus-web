                        convierta en
                        un completo sistema de adquisición y control de datos que puede ser usado en experimentos de
                        automatización,
                        pruebas de productos, monitoreo y control de equipo de producción o puede integrarse en
                        productos como el
                        sistema de seguridad de un aeropuerto. </p><br><br>

