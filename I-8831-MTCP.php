              <div align="justify">
                <ul Style="text-align:left">
                  <li><strong>Soporta Convertidor Modbus/RTU a Modbus/TCP.</strong></li>
                  <br>
                  El Puerto COM de los I-8000E -MTCP pueden ser configurados en modo gateway y conectar al dispositivo
                  Modbus/RTU. La PC host puede conectar el dispositivo Modbus/RTU por el protocolo Modbus/TCP con
                  ethernet.
                </ul>
              </div>
            </td>
          </tr>
          <tr align="right">
            <td colspan="2">
              <div align="justify">
                <ul Style="text-align:left">
                  <li><strong>Soporta técnica VxComm para cada puerto COM de controladores. </strong></li>
                  <br>
                  Cuando el dispositivo serial no soporta Ethernet, los usuarios pueden usar el Puerto COM virtual para
                  accesar el dispositivo por Ethernet. Sólo configura el puerto COM del I-8000E -MTCP como el
                  modo VxComm, e instalar el driver VxComm en la PC, después mapear un puerto COM virtual al Puerto COM
                  I-8000E -MTCP's COM Port. Después de todo, los programa del usuario puede comunicar con el
                  puerto serial COM del dispositivo remoto por el proceso del estándar RS-232.
                </ul>
              </div>

