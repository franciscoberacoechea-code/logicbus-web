<p>Z202 acepta un voltaje alternativo (10..490 Vac) y proporciona una salida analógica aislada (mA o V). También dispone de interruptores DIP para establecer el rango específico, entrada y salida. Se puede solicitar con fuente de alimentación alta o baja. Z202 también se puede usar como un micrómetro (500 µAfs). Un aislamiento galvánico de 3 vías entre la fuente de alimentación // entrada // circuitos de salida garantiza la integridad de sus datos.
</p><br>

<strong>Caracteristicas:</strong>
<ul>
<li>Entrada: 1 canal para voltaje de 10~490 Vac</li>
<li>Salida: 1 canal de corriente 0~20 mA, 4~20 mA ó voltaje 0~10 Vdc, 2~10 Vdc</li>
<li>Aislamiento galvánico de 3 vías</li>
<li>Alta precisión: 0.3%</li>
<li>Conexiones mediante terminales a tornillo y montaje en riel DIN</li>
<li>Alimentación:</li>
<ul>
<li>Z202: 9~40 Vdc ó 19~28 Vac</li>
<li>Z202-H: 85~265 Vac/Vdc.</li>
</ul>
</ul>

