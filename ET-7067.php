 El ET-7067, es un m&oacute;dulo que permite controlar entradas y salidas digitales mediante Ethernet, este m&oacute;dulo incluye un servidor web integrado, el cual permite configurar el dispositivo, monitorear y controlar las entradas y salidas desde un simple navegador web. El control y supervisi&oacute;n remotos son tan sencillos como navegar en Internet. <br>
 <br>
Con la funci&oacute;n web HMI, no es necesario programar ni tener habilidades en HTML; la creaci&oacute;n de p&aacute;ginas web din&aacute;micas y atractivas para el control y monitoreo de entradas/salidas ser&aacute; divertido para los ingenieros. El ET-7067 ofrece a los usuarios un acceso f&aacute;cil y seguro desde cualquier lugar y a cualquier hora. <br>
<br>
Adem&aacute;s, el ET-7067 soporta tambi&eacute;n el protocolo Modbus/TCP, lo cual hace una perfecta integraci&oacute;n entre este dispositivo y software SCADA. <br>
<br>
El ET-7067 


 


 provee 8 Relevadores de potencia de salida (tipo A) y 6 entradas digitales de contacto h&uacute;medo (tipo sink, source). Cada Relevador  soporta un contacto de 5A@250Vac o 5A@30Vdc.<br>
