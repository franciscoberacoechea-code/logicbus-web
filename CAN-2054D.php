<center><strong>Módulo esclavo DeviceNet de entrada digital aislada de 8 canales y salida digital aislada de 8 canales.</strong></center><br>

<p>El CAN-2054D sigue la especificación DeviceNet Volumen I / II, Versión 2.0. El usuario puede acceder al estado de E / S digital y configurar la configuración a través del archivo DeviceNet EDS.
<br><br>
Este módulo tiene una entrada de sink/source aislada de 8 canales y una salida de sumidero aislada de 8 canales. Se puede aplicar a diversas aplicaciones, como PNP, NPN, TTL, contacto de relevo, etc. Gracias a los maestros DeviceNet de ICP DAS, puede construir rápidamente una red DeviceNet para satisfacer sus necesidades.</p>

