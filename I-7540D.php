<p>La serie I-7540D son convertidores de CAN a Ethernet y, por lo general, se utilizan como servidor de dispositivo <a href="convertidores_info#CAN">CAN</a> /<a href="convertidores_info#RS-232">RS-232</a> /<a href="convertidores_info#RS-485">485</a> Ethernet. Admiten funciones de acceso a socket y tecnología de puerto COM virtual que ayuda a los usuarios a obtener los datos CAN, RS-232, RS-485 a través del puerto COM virtual.
<br><br>
La serie I-7540D también proporciona un modo transparente, que permite que las redes CAN se acoplen a través de Internet / Ethernet, por lo que es posible la supervisión y el control remotos. Por las características del pequeño sistema operativo, la independencia del protocolo, la carcasa pequeña y la flexibilidad, es capaz de adaptarse ampliamente a varias aplicaciones RS-232, RS-485 y CAN, que pueden basarse en el protocolo privado RS-232, protocolo CAN privado, Modbus protocolo, protocolo CANopen, protocolo DeviceNet o protocolo J1939.</p>

