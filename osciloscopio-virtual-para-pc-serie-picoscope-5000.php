          <p>Los diseños electrónicos de hoy emplean una amplia gama de tipos de señales: analógica, digital, serial (tanto de alta como de baja velocidad), paralelas, audio, video, distribución de energía, etc. Todos deben ser depurados, medidos y validados para garantizar que el dispositivo bajo prueba esté funcionando correctamente y dentro de las especificaciones.</p>

          <p>Para manejar esta variedad de tipos de señales, el hardware PicoScope 5000D FlexRes emplea múltiples ADC de alta resolución en los canales de entrada en diferentes combinaciones paralelas y de tiempo intercalado para optimizar la tasa de muestreo a 1 GS / sa 8 bits, la resolución a 16 bits a 62.5 MS / s, u otras combinaciones intermedias: selecciona la resolución de hardware más adecuada para los requisitos de cada medición.</p>

          <p>Hay disponibles modelos de 2 y 4 canales, todos con una conexión SuperSpeed ​​USB 3.0, que proporciona un ahorro de formas de onda a la velocidad de la luz y al mismo tiempo mantiene la compatibilidad con los estándares USB más antiguos. El kit de desarrollo de software PicoSDK® admite la transmisión continua a la computadora host a velocidades de hasta 125 MS / s. El producto es pequeño y ligero, y funciona silenciosamente gracias a su diseño sin ventilador de bajo consumo.</p>

          <p>Respaldado por el software gratuito y actualizado PicoScope 6, el PicoScope 5000D Series ofrece un paquete ideal y económico para muchas aplicaciones, incluyendo diseño, investigación, pruebas, educación, servicio y reparación.</p>



          <h2>¿Qué es FlexRes?</h2>

          <p>Los osciloscopios de resolución flexible Pico FlexRes le permiten reconfigurar el hardware del alcance para aumentar la tasa de muestreo o la resolución. Esto significa que puede reconfigurar el hardware para que sea un osciloscopio de 8 bits rápido (1 GS / s) para observar señales digitales, o un osciloscopio de 16 bits de alta resolución para trabajos de audio y otras aplicaciones analógicas. Ya sea que esté capturando y decodificando señales digitales rápidas o buscando distorsión en señales analógicas sensibles, los osciloscopios FlexRes son la respuesta.</p>

          <h2>Memoria de captura profunda</h2>

          <p>Los osciloscopios de la serie PicoScope 5000D tienen memorias de captura de forma de onda que van de 128 a 512 millones de muestras, muchas veces más que los tradicionales visores de sobremesa. La memoria profunda permite la captura de formas de onda de larga duración a la máxima velocidad de muestreo. De hecho, la serie PicoScope 5000D puede capturar formas de onda de más de 500 ms de largo con una resolución de 1 ns. Por el contrario, la misma forma de onda de 500 ms capturada por un osciloscopio con una memoria de 10 megasample tendría una resolución de solo 50 ns.</p>

          <p>La memoria profunda también puede ser útil de otras maneras: PicoScope le permite dividir la memoria de captura en una serie de segmentos, hasta un máximo de 10 000. Puede configurar una condición de disparo para almacenar una captura separada en cada segmento, con tan poco Como 1 µs de tiempo muerto entre capturas. Una vez que haya adquirido los datos, puede recorrer la memoria de un segmento a la vez hasta que encuentre el evento que está buscando. Se incluyen herramientas poderosas para permitirle administrar y examinar todos estos datos. Además de funciones como la prueba de límite de máscara y el modo de persistencia de color, el software PicoScope 6 le permite hacer zoom en su forma de onda por un factor de varios millones. La ventana de Vista general del zoom le permite controlar fácilmente el tamaño y la ubicación del área de zoom.</p>

          <p>Otras herramientas, como DeepMeasureTM, la decodificación en serie y la aceleración de hardware funcionan con la memoria profunda, lo que convierte a la serie PicoScope 5000D en uno de los osciloscopios más potentes del mercado.</p>

          <h2>Modelos de señal mixta</h2>

          <p>Los modelos PicoScope 5000D MSO agregan 16 canales digitales a los 2 o 4 canales analógicos, lo que le permite correlacionar con precisión el tiempo de los canales analógicos y digitales. Los canales digitales se pueden agrupar y mostrar como un bus, con cada valor de bus mostrado en hexadecimal, binario o decimal o como un nivel (para pruebas DAC). Puede configurar disparadores avanzados a través de los canales analógicos y digitales. Los canales digitales también se pueden usar como fuentes para los decodificadores en serie, dando hasta 20 canales de datos, por ejemplo, decodificando múltiples señales SPI, I²C, bus CAN, bus LIN y FlexRay al mismo tiempo.</p>

          <h2>Activación digital avanzada</h2>

          <p>La serie PicoScope 5000D ofrece un conjunto de disparadores avanzados líderes en la industria que incluyen el ancho del pulso, el pulso runt, la ventana y el abandono.</p>

          <p>El disparador digital disponible en los modelos MSO le permite activar el alcance cuando alguna o todas las 16 entradas digitales coinciden con un patrón definido por el usuario. Puede especificar una condición para cada canal individualmente, o configurar un patrón para todos los canales a la vez utilizando un valor hexadecimal o binario. También puede usar el disparador lógico para combinar el disparador digital con un disparador de borde o ventana en cualquiera de las entradas analógicas, por ejemplo, para disparar valores de datos en un bus paralelo sincronizado.</p>

          <h2>Generador de función y forma de onda arbitraria</h2>

          <p>Todas las unidades PicoScope 5000D tienen un generador de forma de onda arbitraria (AWG) de 200 bits / s de 14 bits integrado. Puede crear y adaptar formas de onda arbitrarias utilizando el editor incorporado, importarlas desde las trazas existentes del osciloscopio o cargar una forma de onda desde una hoja de cálculo.</p>

          <p>El AWG también puede actuar como un generador de funciones con un rango de señales de salida estándar, incluyendo seno, cuadrado, triángulo, nivel de CC, ruido blanco y PRBS. Además de los controles básicos para configurar el nivel, el desplazamiento y la frecuencia, los controles más avanzados le permiten barrer en un rango de frecuencias.</p>

          <p>Combinado con la opción de retención de pico de espectro, esto constituye una herramienta poderosa para probar las respuestas de amplificador y filtro. Las herramientas de activación le permiten generar uno o más ciclos de una forma de onda cuando se cumplen varias condiciones, como la activación del alcance o el fallo de una prueba de límite de máscara.</p>


