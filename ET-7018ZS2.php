<h1>ET-7018Z/S2</h1>

<center>
<img src="https://tienda.logicbus.com.mx/assets/images/02/ET-7018Z_S2.jpg" alt="Módulo Ethernet de adquisición de datos: ET-7018Z/S2" title="Módulo Ethernet de adquisición de datos: ET-7018Z/S2" width="200" class="image_productos">
