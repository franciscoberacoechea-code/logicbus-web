<p align="justify"><b>El modelo LCB450 es una celda de carga de alta capacidad</b> (extremo de barra) para actuadores en línea o gatos hidráulicos con roscas macho / hembra. El modelo estándar de celda de carga de alta capacidad LCB450 (extremo de barra) tiene roscas macho / hembra y receptáculo Bendix. Utiliza acero inoxidable 17-4 y pesa aproximadamente 20 oz. Este modelo es muy adecuado para los requisitos de capacidad de rango medio a alto (5,000 lb - 20,000 lb). Para cualquier aplicación que requiera un rango de capacidad más bajo, consulte LCB200 y LCB400. Esta celda de carga de alta capacidad (extremo de barra) tiene una alta precisión y alta rigidez. Tiene una no linealidad de ± 0.5% y una deflexión de 0.001” nominal.</p>

