<p>DeviceNet es un sistema de red industrial abierto de bajo costo. Proporciona el servicio de comunicación necesario para varios tipos de aplicaciones, como sensores, conmutadores, escáner de código de barras, unidades de CA / CC, etc. DeviceNet admite el modelo de conexión Maestro / Esclavo. El módulo PISO-DNM100 actúa sobre el dispositivo maestro DeviceNet y se comunica con los dispositivos esclavos remotos. Existe un firmware de protocolo DeviceNet completo en el PISO-DNM100. Los usuarios pueden acceder fácilmente al dispositivo esclavo a través de PISO-DNM100 utilizando las funciones de la biblioteca DLL y no necesitan tratar con el complejo protocolo DeviceNet. Los usos pueden usarse tan fácilmente como las funciones de "Lectura / Escritura" para acceder a datos esclavos de E / S.</p><BR>


<strong>Caracteristicas:</strong>
<ul>
<LI>Versión DeviceNet: Volumen I y II, Versión 2.0</LI>
<LI>ID MAC programable maestro y velocidad en baudios</LI>
<LI>Velocidad en baudios: 125 kbps, 250 kbps, 500 kbps</LI>
<LI>Soporte Grupo 2 y conexión UCMM</LI>
<LI>Modos de funcionamiento de E / S: Encuesta, Bit-Strobe, Cambio de estado / Cíclico</LI>
<LI>Longitud de E / S: 512 bytes de entrada máx. Y 512 bytes de salida por esclavo</LI>
<LI>Nodo esclavo: 63 nodos máx.</LI>
<LI>Admite la función del dispositivo esclavo de búsqueda automática.</LI>
<LI>Admite la adición y eliminación en línea de dispositivos</LI>
<LI>Soporte autodetectar el Grupo 2 y el dispositivo UCMM</LI>
<LI>Reconexión automática cuando la conexión está rota</LI>
<LI>LED: estado, ERR</LI>
</ul>
