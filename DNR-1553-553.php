      <td colspan="2"><div align="justify">The DNR-1553-553 is a high performance, two channel MIL-STD-1553 interface for new RACKtangle&reg; I/O Chassis. Each channel operates fully independently and provides a complete dual, redundant 1553 interface. Each channel may be set as 1553a or 1553b, and the "b" interface fully implements specification notices 1 and 2. Each channel is transformer coupled, though direct coupling is available as an option.<br>
          <br>
          Most 1553 functions are implemented by the on-board FPGA. This greatly reduces the burden placed on the RACKtangle CPU and ensures the DNR-1553-553 does not interfere with the functionality of other I/O boards installed.<br>
          <br>
          Each channel may be independently configured as Bus Controller (BC), Remote Terminal (RT) or Bus Monitor (MT). As a Bus Controller, the board supports all standard BC-RT, RT-BC and RT-RT transfers and Mode Code, One-shot, and Broadcast messaging. The Remote Terminal support allows the board to be set at a single RT address, or to emulate up to 31 different RTs on the bus. The RT implementation supports single, double, and circular message buffering. Bus Monitoring (MT) mode provides the ability to monitor all activity, or select activity based upon RT address or Mode Code. In addition to monitoring data, MT mode monitors time tags, errors status and RT response time. Finally, each DNR-1553-553 channel may be set to simultaneously act as an RT and an MT.<br>
          <br>
          Like the Chassis in which it is installed, the DNR-1553-553 is well suited for the harsh environments sometimes encountered in flight testing applications. The board is specified for operation from -40 &deg; to +85 &deg;C, from 0 to 60,000 feet. The system is also fully tested for operation at 5&nbsp;<em>g</em>&nbsp;vibration and up to 50&nbsp;<em>g</em>&nbsp;shock.<br>
          <br>
      The DNR-1553-553 includes our 1553 API, which has been designed to offer simple, easy-to-use controls and yet maintain the ability to access all 1553 functionality. The software driver is compatible with all popular operating systems including Vista, Windows, Linux as well as many real-time OS's including RTX, QNX, RT Linux and more. Software support is also included for all popular programming languages and applications packages including LabVIEW.</div></td>
