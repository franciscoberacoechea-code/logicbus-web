<p>Los sensores de marca de registro SMARTEYE ® COLORMARK ™ ll combinan una capacidad de percepción de color única con una respuesta de velocidad muy alta. Se han incorporado muchas características importantes en el diseño para satisfacer la creciente demanda de control de registro de precisión en la maquinaria de envasado de mayor velocidad de hoy en día. Proporciona rangos de operación ampliados, supresión de fondo mejorada y la eliminación de problemas de saturación.
</p>
<br>
<p>La tarea específica de un detector de marca de registro fotoeléctrico es responder a las marcas de registro impresas en el material de embalaje a medida que pasan a través del haz de luz del sensor. La salida del sensor debe cambiar cuando la marca llega precisamente a su posición para que se produzca la función de control. La resolución de la ubicación exacta de cada marca de registro que pasa es una nota clave para garantizar que la iniciación de la respuesta electromecánica activada por el sensor esté sincronizada con la llegada de la marca.</p>

<b>Características:</b>
<ul>
<li>Vivienda impermeable</li>
<li>Ajuste de la perilla del embrague (Offset / EDR ® )</li>
<li>Indicador de contraste de 10 LED</li>
<li>EDR ® "Rango dinámico mejorado": elimina los efectos de deslumbramiento en los puntos calientes. Funciona con los materiales más brillantes, incluidas las láminas.</li>
<li>El Pulsador opcional garantiza un mínimo de 10 milisegundos de salida: tiempo suficiente para la verificación visual del LED y para que el control responda.</li>
<li>Elección de la fuente de luz: verde, rojo, azul o blanco.</li>
</ul>
