<p>Con las aplicaciones industriales y OEM que requieren cada vez más dispositivos USB, tener disponibles más puertos USB se convierte en una necesidad. Logicbus ofrece la HUB4PH-KT, un HUB de 4 puertos USB 2.0 con alimentación interna. El hub es compatible con USB 2.0, proporcionando una velocidad máxima 480Mbps, y es compatible con dispositivos USB 1.1 y 1.0. El HUB4PH-KT incluye un cable de alimentación de 5 V para obtener la energía de la fuente de la PC desde un conector de disco duro estándar. Pida el cable USB interno adecuado para su tarjeta madre en la sección de accesorios requeridos.
<br><br>
Los cargadores USB ha ganado popularidad, el mínimo 500mA que se encuentran en otros hubs USB 2.0 se ha convertido en algo insuficiente para dispositivos que requieren una corriente mayor. Los puertos de la HUB4PH-KT se configuran como CDP (Charging Downstream Ports o Puertos para carga) capaces de suministrar hasta 1.5 A de corriente a cada dispositivo Conectado. Todos los puertos USB CDP tienen especificación de carga BC1.2, perfecto para cargar baterías o alimentación de periféricos USB de alta corriente.
<br><br>
El HUB4PH-KT integra puertos USB con bloqueo SeaLATCH, que son totalmente compatibles con los cables USB estándar. Cuando se utiliza con un cable USB SeaLATCH tipo A, el tornillo de metal proporciona una conexión segura con el dispositivo y evita la desconexión accidental del cable. Puede solicitar cables opcionales USB con conectores SeaLATCH, o utilizar cables USB estánda.</p>
<strong>Caracter&iacute;sticas:</strong>
<ul>
  <li>HUB USB 2.0 con alimentación externa, proporciona cuatro puertos USB CDP.</li>
  <li>Cuatro puertos de carga (CDP) proporcionan hasta 1.5A a cada dispositivo conectado.</li>
  <li>Todo el CDP son las especificaciones de carga de la batería BC1.2 compatible.</li>
  <li>Puertos USB con bloqueo SeaLATCH ofrecen conexión segura con cables USB SeaLATCH mediante tornillos metálicos.</li>
  <li>LED de estado indica conexión interna con el host.</li>
  <li>Compatibilidad HUB USB (Universal Serial Bus) 2.0.</li>
  <li>Compatible con dispositivos USB 1.1 y USB 1.0.</li>
  <li>Soporta alta velocidad 480Mbps, 12Mbps de velocidad completa y 15 Mbps a baja velocidad.</li>
  <li>Compatible con Windows, Linux y otros sistemas operativos con soporte USB.</li>
  <li>Incluye cable de alimentación interna de 5V.</li>
  <li>Utiliza conector Molex de 5 pines verticales 2mm con bloqueo para la conexión USB.</li>
</ul>
 
