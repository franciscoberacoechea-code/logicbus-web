                <p class="text-center light-black font-weight-bold">¿Qué es un comprobador de torsión de tapas de botellas?</p>
                En las aplicaciones de tapado de botellas, los ingenieros de control de calidad quieren asegurarse de que se aplique una fuerza y un par de torsión constantes en las tapas de las botellas, lo que es clave para reducir las tasas de rechazo de productos.</p>

                <p class="light-black">El par de torsión de tapado no solo es importante para garantizar que la botella se envíe correctamente sellada para evitar fugas durante el transporte, sino que el comprobador de torsión de tapas de botellas para la medición repetible del par de torsión de apertura y cierre de las tapas de las botellas es fundamental en las tapas de seguridad a prueba de niños. Además, en los sistemas que requieren envases desinfectados o esterilizados, la verificación de la medición exitosa del par de torsión de la tapa es fundamental para la validación del sello y el control de calidad.</p>

                <p class="text-center light-black font-weight-bold">¿Por qué utilizar un sensor FUTEK en su aplicación de medidor de torsión de tapas?</p>
                <p class="light-black">Para lograr esto, se utiliza un sensor de par y empuje biaxial en la prensa de tapado como medidor de torsión de tapas para garantizar la precisión, la consistencia y la integridad del sello. El comprobador de torsión de tapas digital FUTEK es ideal para pruebas básicas de torsión de botellas en sentido horario y antihorario.</p>


                <p class="light-black">El sensor de par de reacción de torsión y empuje MBA500 de FUTEK mide el par de aplicación y extracción de la tapa de la botella hasta 500 lb-in (56,5 Nm) con una precisión de ±0,25 %. La celda de carga biaxial de torsión y empuje está diseñada para medir momentos de torsión de reacción, así como cargas de tensión y compresión. Este sensor de torsión/empuje, con compensación de temperatura y construido completamente de aluminio, puede lograr una impresionante no linealidad del 0,2 % y, sin embargo, proporcionar un exceso de capacidad del 150 % (50 a 150 lb) al 125 % (200 lb).</p>

                <p class="light-black">Se logra un excelente rendimiento y una alta precisión a través de dos salidas independientes para las fuerzas de torsión y empuje aplicadas. Los sensores de fuerza/torque se utilizan en toda la industria para pruebas de productos, ensamblaje robótico, rectificado y pulido. El sensor biaxial de torsión y empuje MBA500 ofrece una excelente solución para medir cargas en tensión y compresión, así como torsión en sentido horario y antihorario. El MBA500 es compacto, pesa solo 6,5 oz y ofrece un diseño compacto.</p>

                <p class="text-center light-black font-weight-bold">¿Cómo funciona?</p>
                <ol class="light-black">
                    <li class="mb-3">Los operadores han instalado un sensor biaxial en su línea de producción para monitorear el actuador/motor que alimenta la prensa de tapado.</li>
                    <li class="mb-3">Instalado directamente debajo del actuador de la prensa tapadora, este sensor biaxial mide el torque y el empuje ejercidos a medida que cada tapa se sella en su respectivo contenedor.</li>
                    <li class="mb-3">Estas mediciones de torque y empuje se pueden amplificar a través del amplificador de la serie IAA de FUTEK a un PLC, mostrarse en una pantalla digital (IPM650 o IHH500) o transmitirse directamente a una PC usando las soluciones USB de FUTEK.</li>
                    <li class="mb-3">Si el instrumento está emparejado con el software de prueba y medición SENSIT™ de FUTEK, los operadores pueden registrar, graficar y capturar todos los datos en la PC.</li>
