    <h1><br>Current Flow</h1>
    <P>
    	Electrons is the outer orbits of an atom a attracted to the nucleus by less force than electrons whose orbits are near the nucleus. These outer electrons may be easily forced from their orbits, while electrons in the inner orbits are called<b> &#34Bound Electrons&#34</b> since they cannot be forced out of their orbits.
    </P>
    <p>
      Atoms and molecules in a material are in continuous random motion, the amount of this motion determined by the material, temperature and pressure. This random motion causes electrons in the outer rings to be forced from their orbits, becoming<b> &#34Free Electrons&#34</b>.
    </p>
    <p>
      &#34Free Electrons&#34 are attracted to other atoms which have lost electrons, resulting in a continuous passage of electrons from atoms to atom within the material. 
    </p>
    <p>The random movement of the &#34Free Electrons&#34 from atom to atom is normally equal in all directions so that electrons are not lost or gained by any particular part of the material. When most of the electron movement takes place in the same direction, so that one part of the material loses electrons while another part gains electrons, the net electron movement or flow is called <b>&#34Current Flow&#34</b>.</p>
   
