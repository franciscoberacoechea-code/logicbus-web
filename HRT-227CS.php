<center><strong>Convertidor de fibra HART a modo único.</strong></center><br>

<p>El HRT-227CS es un convertidor de HART a fibra emparejado utilizado para extender la distancia de comunicación HART a través del medio de transmisión de fibra óptica monomodo. Para resolver el problema entre HART y el medio de transmisión de fibra, HRT-227CS está especialmente diseñado para convertir la señal HART en cables de fibra óptica. Incorpora una resistencia de bucle HART de 250 Ω ajustable mediante un interruptor DIP. Por lo tanto, los usuarios pueden hacer que la recolección de datos y el procesamiento de la red HART sean más fáciles y rápidos al aplicar HRT-227CS. Además, también ofrecemos la herramienta gratuita HC_Tool para la configuración del módulo fácilmente.</p>

<strong>Características:</strong>
<ul>
<li>Soporte HART corto/largo marco.</li>
<li>Soporte HART Burst modo.</li>
<li>Soporte de modo punto a punto o multi-drop HART.</li>
<li>Admite la conexión de hasta 15 dispositivos esclavos HART.</li>
<li>Permitir dos maestros HART.</li>
<li>Proporcionar la herramienta HC_Tool para la configuración del módulo.</li>
<li>Soporte de actualización de firmware a través de ComPort.</li>
<li>Detección de líneas discontinuas de fibra.</li>
<li>Tipo de fibra: SC; Modo singular; 100 Base-FX.</li>
<li>Fibra máx. distancia de transmisión de hasta 30 km.</li>
<li>Protección 4KV ESD.</li>
<li>Perro guardián incorporado.</li>
<li>Resistencia de bucle de 250Ω seleccionable.</li>
<li>El puerto HART con la misma identificación de grupo puede comunicarse entre sí.</li>
</ul>
