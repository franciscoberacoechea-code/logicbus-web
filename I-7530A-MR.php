<p>El I-7530A-MR está diseñado para liberar la potencia del bus CAN mediante el método de comunicación RS-232/485/422. Convierte con precisión mensajes entre redes CAN y RS 232/485/422. Este módulo le permite comunicarse fácilmente con dispositivos CAN desde cualquier PC o dispositivo con interfaz RS-232/485/422. El dispositivo programable RS 232/485/422 (por ejemplo: PC, PLC o PAC) o el dispositivo maestro Modbus RTU pueden usar el puerto serie para conectarse a la red CAN a través de la I-7530A-MR.</p>

<strong>Caracter&iacute;sticas:</strong>
		<ul>
<li>RoHS Design</li>
<li>Totalmente compatible con el estándar ISO 11898-2</li>
<li>Velocidad de transmisión del bus CAN programable de 10 kbps a 1 Mbps o velocidad en baudios definida por el usuario</li>
<li>Apoya la configuración del filtro de aceptación del bus CAN</li>
<li>Soporte de actualización de firmware a través de RS-232</li>
<li>Proporciona herramienta de utilidad para la configuración del módulo y la prueba de comunicación del bus CAN</li>
<li>Puente incorporado para seleccionar resistencia de terminación de 120O</li>
<li>CAN buffer: 128 marcos de datos; Buffer UART: 256 bytes</li>
<li>Indicador de alimentación, flujo de datos y error para estado CAN y UART</li>
<li>Diseño de reloj de hardware</li>
<li>Convertir el mensaje CAN en una cadena de comando ASCII específico (modo Normal)</li>
<li>Convertir cadena de comando ASCII específico en mensaje CAN (modo Normal)</li>
<li>Proporciona la comunicación transparente entre los dispositivos RS-232/485/422 a través del bus CAN (modo de conexión de pares)</li>
<li>Código de función de soporte 0x03 / 0x04 / 0x10 del comando Modbus RTU para leer y escribir mensajes CAN (modo Modbus RTU)</li>
		</ul>

