<p align="justify">La interfaz serie 7202 PCI proporciona dos puertos serie RS-232 capaces de velocidades de datos de 460.8K bps. Cada puerto RS-232 implementa todas las señales de control de módem para una máxima compatibilidad con una amplia gama de periféricos. El 7202 utiliza 16C850 UART que proporcionan FIFO de Tx / Rx de 128 bytes.<br><br>
El software SeaCOM de Sealevel hace que la instalación y operación sean fáciles de usar con los sistemas operativos Microsoft Windows y Linux.</p>

<strong>Características:</strong>
<ul>
<li>16C850 UART con búfer con FIFO de 128 bytes</li>
<li>Tasas de datos a 460.8K bps</li>
<li>Todas las señales de control de módem implementadas.</li>
<li>Dos conectores DB-9M</li>
</ul><br>


