<center><strong>8 puertos 10/100/100 Base-T, 2 (100 / 1G) SFP L2 Plus Interruptor administrado IEEE802.3ab.</strong></center><br>

<p>FSM-510G-2F es un conmutador de gestión de L2 que cumpla con todos Gigabit 802.3ab / u / x / z IEEE, Ethernet Gigabit Ethernet y especificaciones. Proporciona puertos Ethernet de 8 gigabits (10/100/1000 Mbps TP) 2 puertos SFP.
<br><br>
El conmutador se puede gestionar a través del puerto en serie RS-232 a través de una conexión directa o a través del puerto Ethernet utilizando Telnet o la unidad de administración basada en la Web, asociada con el agente SNMP. Con el agente SNMP, el administrador de la red puede iniciar sesión en el switch para monitorear, configurar y controlar cada actividad portuaria de forma amigable. La administración general de la red se mejora y la eficiencia de la red también se mejora para acomodar aplicaciones de gran ancho de banda. Además, el conmutador presenta funciones integrales y útiles como QoS (calidad de servicio), Spanning Tree, VLAN, trunking de puertos, control de ancho de banda, seguridad de puertos, SNMP / RMON</p>

Caracteristicas:
<ul>
<li>IEEE 802.3ab 1000BASE-T Gigabit Ethernet.</li>
<li>Las características L2 + proporcionan una mejor capacidad de administración, seguridad, QoS y rendimiento.</li>
<li>Red redundante Protección de conmutación por error del anillo (< 20 ms).</li>
<li>Compatibilidad con multidifusión IGMP v1 / v2 / v3, proxy y snooping.</li>
<li>Control de tormenta de multidifusión / transmisión / inundación.</li>
</ul>
