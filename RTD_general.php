      <td height="31" colspan="2" valign="top"><div align="justify">Los <strong>term&oacute;metros de resistencia </strong> o <strong>term&oacute;metros a resistencia </strong> son transductores  de temperatura, los cuales se basan en la dependencia de la resistencia el&eacute;ctrica  de un material con la temperatura, es decir, son capaces de transformar una variaci&oacute;n de temperatura en una variaci&oacute;n de resistencia el&eacute;ctrica. </div></td>
    </tr>
    <tr>
