<h2>Comparación de características</h2>
				
<p>Cuatro instrumentos virtuales: Graficador, Osciloscopio, Generador de Funciones y Generador de Pulsos.
<br><br>
TracerDAQ se incluye con todas las tarjetas de Measurement Computing (MCC).<br>
El TracerDAQ Pro ofrece adicionalmente recursos y controles activos. Ambas versiones son compatibles con los sistemas operativos Windows 10/8/7/Vista®/XP SP2, en sus versiones de 32-bit y 64-bit.
<br><br>
TracerDAQ y TracerDAQ Pro son aplicaciones de software “listas para usarse” para almacenar datos,  mostrarlos gráficamente y generar señales de salida, minutos después de la instalación de las tarjetas y sin necesidad de escribir código. Cada una de las versiones consta de cuatro aplicaciones de instrumentos virtuales: Graficador, Osciloscopio, Generador de Funciones y Generador de Pulsos, que permiten al usuario personalizar la apariencia, guardar configuraciones para uso futuro y cambiar dichas configuraciones, con el uso de puntos de referencia interactivos.
<br><br>
TracerDAQ Pro es un paquete de las misma aplicaciones con más características, lo que lo hace más poderoso, ofreciendo más canales activos, mas muestras por canal y una selección de opciones y mejoras diseñadas para realizar una gran cantidad de aplicaciones de prueba y medición.</p>

