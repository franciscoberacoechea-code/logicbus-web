<strong>Caracteristicas:</strong>
<ul>
<li>Controlador de movimiento básico de 4 ejes</li>
<li>Comunicación USB 2.0 y RS-485</li>
<li>Frecuencia de salida de hasta 400000 pulsos</li>
<li>Aceleración trapezoidal</li>
<li>Salidas de colector abierto de Pulse/Dir/Enable por eje</li>
<li>Entradas opto aisladas de +Limit, -Limit, y Home por eje</li>
<li>4 entradas digitales opto aisladas</li>
<li>4 salidas digitales opto aisladas</li>
<li>Lenguaje similar a BASIC para programación en modo autónomo</li>
