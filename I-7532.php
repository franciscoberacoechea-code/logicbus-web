<p>I-7532 es un puente CAN utilizado para establecer una conexión entre dos sistemas de bus CAN en una red CAN y hay más funciones equipadas que I-7531 (repetidor CAN). Tres poderosas características son provistas por I-7532. En primer lugar, la limitación de la distancia de transmisión del sistema de bus CAN en cada lado de la I-7532 es independiente, lo que significa que la distancia total de la red CAN se puede ampliar. Segundo, cuando ocurrieron algunos errores (por ejemplo, un error de bit) en un lado de la I-7532 del sistema de bus CAN; el otro lado todavía puede funcionar correctamente. El último, la velocidad de transmisión y la configuración del filtro de estos dos canales CAN en la I-7532 pueden ser diferentes para una gran flexibilidad y eficiencia.</p>

