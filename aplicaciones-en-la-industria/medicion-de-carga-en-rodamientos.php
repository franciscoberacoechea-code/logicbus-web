                <p class="light-black">El propósito principal de los rodamientos con elementos rodantes es restringir un sistema rotatorio y, al mismo tiempo, reducir el impacto de la fricción en la rotación. Son partes cruciales de las máquinas rotatorias, como motores y turbinas, y las fallas de los rodamientos son una fuente importante de costosas interrupciones. Las fallas de los rodamientos pueden ser desastrosas y generar importantes tiempos de inactividad y costos de mantenimiento, especialmente para aplicaciones donde el acceso a reparaciones es limitado. La medición de la carga de los rodamientos es fundamental para prevenir fallas porque proporciona datos sobre las cargas de reacción a las fuerzas externas que experimenta un sistema de rodamientos.</p>
                <p class="light-black">La medición de las fuerzas de reacción de los cojinetes provocadas por cargas externas en una máquina proporciona una indicación precisa de cuánta carga axial y/o radial soporta el cojinete. Las fuerzas externas ejercidas sobre los cojinetes se pueden medir utilizando celdas de carga y sensores de par y empuje, y ayudan a los ingenieros a diseñar y especificar mejor los cojinetes o incluso a realizar cambios de diseño en el equipo para evitar la sobrecarga de los cojinetes y fallas prematuras. </p>
                <p class="light-black">Otro beneficio de la medición de carga es la capacidad de realizar un monitoreo en tiempo real. El registro continuo de la carga axial y radial de los cojinetes permite a los ingenieros detectar y activar alarmas por sobrecarga, así como activar circuitos de interbloqueo para garantizar la seguridad de la máquina y de toda la operación.</p>
                <p class="light-black">Esta aplicación ilustra cómo medir y monitorear cargas axiales y radiales aplicadas a un rodamiento de elementos rodantes utilizando celdas de carga de galgas extensométricas y sensores de carga de empuje.</p>

                <p class="text-center light-black font-weight-bold">¿Cómo funciona?</p>
                <ol class="light-black">
                    <li class="mb-3">Las celdas de carga de botón LLB450 de FUTEK se instalan entre los accesorios de carga y los gatos hidráulicos para medir cargas axiales y radiales en línea.</li>
                    <li class="mb-3">A medida que el rodamiento gira, se aplican cargas externas radial y axialmente al rodamiento del elemento rodante.</li>
                    <li class="mb-3">Las celdas de carga capturan fuerzas axiales y radiales en tiempo real y las transmiten a los amplificadores para el acondicionamiento de la señal.</li>
                    <li class="mb-3">Luego, el acondicionador de señal digital USB se comunica con una PC o un software de escritorio para la visualización, el registro y el análisis de datos en tiempo real.</li>
                    <li class="mb-3">También se puede utilizar un DAQ externo para recopilar y almacenar datos operativos de los rodamientos.</li>
