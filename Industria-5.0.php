      <h2 class="subtitle blue text-center">INDUSTRIA 5.0</h2>

      <p>La industria 5.0 se basa en las capacidades de los robots y las habilidades humanas, ya que unidos convergen para obtener lo mejor. Es un estado de desarrollo donde los fabricantes hacen una combinación de habilidades únicas de un trabajador cualificado con la capacidad de un robot para hacer frente a las tareas como levantamiento de objetos pesados o el manejo de sustancias peligrosas, al mismo tiempo proporciona una buena calidad constante durante el día.</p>
      <p>La industria 5.0 implica un cambio de la fabricación moderna, así como una amplia gama de otros procesos, comerciales y no comerciales, ya que con esto permite que el hombre y maquina trabajen codo a codo, en colaboración mediante el uso de <a class="blue link-orange" href="https://www.logicbus.com.mx/robots-colaborativos">robots colaborativos</a> conocidos como Cobots.</p>
      <p>Es un hecho que la revolución digital ha transformado a la industria en su completa totalidad. Al agregar maquinas e inteligencia artificial en los procesos productivos, se habilita el entorno de trabajo cada vez más adaptable, listo para el cambio y receptivo, esto quiere decir, que una fuerza industrial que está conectada en la que los hombres y maquina reinventan los procesos de producción.</p>

      <center><img src="https://www.logicbus.com.mx/imagenes/articulo/industria2.jpg" class="image_productos" width="40%" alt="Figura 2. Industria 5.0: un cambio en los procesos de producción" title="Figura 2. Industria 5.0: un cambio en los procesos de producción"></center>
