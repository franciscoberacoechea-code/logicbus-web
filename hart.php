</div>
<p>Este protocolo permite comunicar con un instrumento de campo sobre un lazo de corriente 4-20 mA, tanto los datos de configuración y parámetros como las medidas de proceso como temperatura, caudal, presión o cualquier otra. La información de control del instrumento se modula digitalmente sobre el lazo de corriente y por tanto no hay interferencias entre ellas. Su velocidad es de 1200 bps, de forma que el equipo maestro puede actualizar la información varias veces por segundo.
<br><br>
Los modernos controladores empleados en los sistemas de control distribuido (DCS), son transparentes a estos instrumentos de forma que se pueden configurar y programar remotamente desde el nivel de operación de los sistemas de control.</p>

