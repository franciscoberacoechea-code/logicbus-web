            <div class="col-12 col-md-7 text-justify">
                <p class="light-black">Medir el torque generado por motores o frenos se puede lograr acoplando directamente un sensor de torque rotatorio en línea con el eje del motor o montando el motor directamente sobre un sensor de torque de reacción. Sin embargo, en algunos casos, ninguna de estas soluciones funciona, como sucede con un <b>dinamómetro de torque</b>. En este tipo de aplicaciones, se utiliza una celda de carga y se aplica la ecuación <b>Torque = Fuerza x Distancia</b> para convertir la fuerza medida en torque (celda de carga de torque).</p>

                <p class="text-center light-black font-weight-bold">¿Cómo funciona?</p>
                <ol class="light-black">
                    <li class="mb-3"><b>Aplicación de Torque en un Freno:</b>
                        <ul>
                            <li>En este caso, un <b>freno</b> tiene un brazo de momento (momento de palanca) fijado a una distancia específica desde el centro del eje de rotación.</li>
                        </ul>
                    </li>
                    <li class="mb-3"><b>Medición de Fuerza con la Celda de Carga LCF400:</b>
                        <ul>
                            <li>En el extremo del brazo de momento, se coloca una <b>celda de carga LCF400</b> para medir la fuerza generada a través del brazo a medida que el freno genera torque al resistir el movimiento. Actúa como un transductor de torque utilizando la ecuación <b>Torque = Fuerza x Distancia</b>.</li>
                            <li>La <b>LCF400</b> es ideal para esta aplicación, ya que es altamente resistente a cargas externas y puede resistir cambios repentinos en la salida del motor.</li>
                        </ul>
                    </li>
                    <li class="mb-3"><b>Amplificación y Transmisión de Señales:</b>
                        <ul>
                            <li>La señal generada por la LCF400 es amplificada mediante un <b>amplificador analógico de la serie IAA</b>, luego se envía a un <b>DAQ (Data Acquisition System)</b>, se muestra en una <b>pantalla de montaje en panel IPM650</b> o se registra usando el <b>módulo USB220</b> con salida USB en una PC que ejecuta el software <b>SENSIT</b>.</li>
                        </ul>
                    </li>
                    <li class="mb-3"><b>Conversión de Fuerza a Torque:</b>
                        <ul>
                            <li>Cualquier fuerza medida por la LCF400 se multiplica por la distancia al centro del motor para derivar el torque utilizando la ecuación <b>Torque = Fuerza x Distancia</b>.</li>
                            <li>La conversión de <b>fuerza a torque</b> se puede realizar automáticamente, en tiempo real, utilizando la función matemática incluida en <b>SENSIT</b>.</li>
                        </ul>
                    </li>
                    <li class="mb-3"><b>Monitoreo en Tiempo Real:</b>
                        <ul>
                            <li>Adicionalmente, el <b>IDA100</b> (Amplificador Configurable Digitalmente) puede ser utilizado para monitorear el torque a través del software <b>SENSIT</b>, mientras genera una salida analógica para cerrar el ciclo con un controlador de motor.</li>
                        </ul>
                    </li>
                </ol>
                <p class="text-center light-black font-weight-bold">Ventajas del Sistema</p>
                <ul class="light-black">
                    <li class="mb-3"><b>Precisión en la Medición de Torque</b>: La medición precisa de la fuerza combinada con la ecuación de torque permite obtener resultados altamente confiables para pruebas y análisis.</li>
                    <li class="mb-3"><b>Resistencia a Cargas Externas</b>: La <b>LCF400</b> es resistente a cargas externas y cambios repentinos de carga, lo que la hace ideal para aplicaciones de alta dinámica.</li>
                    <li class="mb-3"><b>Monitoreo en Tiempo Real y Registro de Datos</b>: Los ingenieros pueden ver los resultados de las pruebas en tiempo real y realizar un registro y análisis detallado de los datos para garantizar que el sistema esté funcionando correctamente.</li>
                </ul>
                <p class="light-black">Este enfoque de usar una celda de carga para medir torque proporciona una solución flexible y precisa, especialmente cuando no es posible usar un sensor rotatorio directo.</p>
