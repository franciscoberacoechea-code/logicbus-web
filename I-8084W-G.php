<center><strong>Módulo de contador/frecuencia/codificador de 4/8 canales</strong></center><br>

<p align="justify">I-8084W-G es una E / S de contador / frecuencia / codificador de alta velocidad de 32 bits (hardware) con "Contador ascendente", "Frecuencia", "Contador ascendente / descendente", "Contador de impulsos / dir" y "A / B Modo de contador de fase. I-8084W-G puede tener una combinación de modo variedad para los 8 canales. Eso significa que puede usar algunos canales como "Contador ascendente" y otros como "Frecuencia" o "Fase A / B".</p>

<strong>Caracteristicas:</strong>
<ul>
<li>Soporte de contador de 8 (ancho de pulso mínimo = 2 µs).</li>
<li>Soporte 8 Frecuencia (Ancho mínimo de pulso = 2 µs).</li>
<li>Soporte 4 Contador de subida / bajada (ancho de pulso mínimo = 2 µs).</li>
<li>Soporte 4 Dir / Contador de pulsos (Ancho mínimo de pulso = 2 µs).</li>
<li>Soporte 4 Contador de Fase A / B (Ancho de Pulso Mínimo = 2 µs).</li>
<li>Soporte 1 ~ 32767 (us) filtro digital.</li>
<li>Admite señales de entrada aisladas y no aisladas.</li>
<li>Equipar con indicadores LED de señal de alimentación y entrada.</li>
</ul>



