            <strong>Descripción del producto</strong><br>

            
            <p>Detecta de forma fiable la posición de las marcas de registro en varias bandas de material que corren a muy alta velocidad para aplicaciones en las industrias de impresión, empaquetado y conversión. La frecuencia de conmutación del sensor es de 50Khz con una repetibilidad de 5μs. Esto proporciona una estabilidad sin precedentes de la posición de la marca. Es ideal en procesos donde la sincronización es crítica. <br><br>

            El sensor utiliza un punto de luz blanca de 2,2 mm para detectar una marca, un borde del producto o una característica del producto cuando se aproxima al sensor en cualquier dirección. Nuestras línea de versiones verticales y horizontales usan un emisor tricolor para realzar el funcionamiento. La repetibilidad de 5μs proporciona alta precisión a alta velocidad. La única pregunta es ... "¿Qué tan rápido puede correr la máquina?" 
            Al utilizar nuestros soportes de conversión, el sensor es un reemplazo para los sensores de marcas de registro existentes. El soporte de conversión proporciona al usuario un patrón de perno de orificio-a-orificio del sensor retirado y cuando se instala alinea el punto focal en la misma posición exacta que el sensor eliminado y con esto se elimina la necesidad de cualquier modificación. </p><br>

