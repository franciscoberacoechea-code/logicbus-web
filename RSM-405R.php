<p>El RSM-405-R es un interruptor de grado industrial en tiempo real de 5 puertos que fue diseñado específicamente para cumplir con los estándares ferroviarios. Tiene conectividad Ethernet 10/100 Base-T (X) con velocidad de negociación automática, modo dúplex F / H y conexión automática MDI / MDI-X. Tiene un montaje de carril din. El sólido diseño de grado industrial asegura un funcionamiento confiable en áreas de aplicación comunes como: aplicaciones ferroviarias, fábricas de semiconductores, entornos de control de inventario, líneas de ensamblaje, fabricación y mucho más. Es compatible con un rango de temperatura operativa de -30 ° C ~ 75 ° C. Cumple con los estándares de emisión, inmunidad y vibración de EMC. Esto les permite ser funcionales en ambientes muy duros.</p><BR><br>




