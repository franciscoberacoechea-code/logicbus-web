<p>El I-7561 es un m&oacute;dulo para transmitir datos seriales sobre USB. Permite que conectes tu dispositivo serial al sistema usando una interfaz USB. Al conectar el I-7561 a una computadora, obtienes un puerto <a href="https://www.logicbus.com.mx/convertidores_info">RS-232/422/485</a>.<br>
As&iacute; como el I-7520, el I-7561 contiene un chip auto ajuste, el cual detecta autom&aacute;ticamente la velocidad de transferencia y formato de datos de la red RS-485. El m&oacute;dulo I-7561, obtiene la energ&iacute;a del puerto USB y no necesita un adaptador de energ&iacute;a. Adem&aacute;s se caracteriza por una tasa de transmisi&oacute;n de alta velocidad de 115.2 KB/s, y soporta varios Sistemas Operativos. Puertos independientes RS-232/422/485.</p>
	   
    <ul><strong>Características:</strong>
		  <li>Velocidad M&aacute;xima de especificaciones USB 1.1</li>
		  <li>Entrada: Protocolo USB</li>
		  <li>Salida: Protocolo RS-232/422/485</li>
		  <li>Velocidad de Transferencia: Auto ajuste interno</li>
		  <li>Provee Protecci&oacute;n de Aislamiento de 3000 Vdc</li>
		  <li>256 M&oacute;dulos M&aacute;ximo en una Red RS-485 sin repetidor</li>
		  <li>2048 M&oacute;dulos M&aacute;ximo en una Red RS-485 con repetidor</li>
		  <li>Petici&oacute;n del Repetidor: 4000 pies o sobre 256 m&oacute;dulos</li>
		  <li>Instalaci&oacute;n Plug-and-Play</li>
		  <li>El I-7561, recibe la energ&iacute;a del puerto USB, no necesita suministro de energ&iacute;a externa</li>
		  <li>Soporta drivers de Windows 98/ME/2000/XP y Linux. Los drivers para otros sistemas operativos, est&aacute;n actualmente en desarrollo</li>
		</ul>

