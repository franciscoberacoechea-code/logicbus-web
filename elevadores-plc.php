<p align="justify">Hoy en día existen dos tipos de elevadores que son los más utilizados: <b>Los Hidráulicos y los electromecánicos.</b></p>

<h2><center>ASCENSORES HIDRÁULICOS</center></h2><BR>

<p align="justify">los ascensores hidráulicos una de sus funciones es que son impulsados por una energia procedente de una central hidráulica (Bomba + Motor), ya que estos inyecta un fluido hidráulico  a un cilindro que es actuado de forma directa o indirectamente sobre la cabina.<br>
de esta forma para elevar la cabina, la central bombea el fruido hacia el cilindro, el cual al acomularse la presión necesaria empuja la cabina del ascensor. Sin enbargo, al momento de descender solamente se requiere el accionamiento de una vávula, la cual es permitido el retorno del fluido hacia la central haciendo bajar de forma controlada al elevador.</p><br>
<center><img src="https://www.logicbus.com.mx/imagenes/articulo/ascensor2.png" class="image_productos" width ="25%" alt="Figura 2. Estructura de un Ascensor Hidráulico" title="Figura 2. Estructura de un Ascensor Hidráulico"></center><p><center><p><center><b>Figura 2. Estructura de un Ascensor Hidráulico</b></center></p><br>

<p align="justify">los elevadores hidráulicos tiene sus ventajas, la cual, una de ella es que tiene un mejor aprovechamiento del espacio, un coste económico menor, amplio de rango de capacidad de carga y que no requieren de elementos de contrapeso.</p><br>

<h2><center>ASCENSORES ELECTROMECÁNICOS</center></h2><BR>

<p align="justify">los ascensores electromecánicos cuentan con dos tipos, los que requieren de un cuarto de máquinas situado en la parte superior o inferior del hueco del ascensor y los que no requieren de cuarto de máquinas al integrarse la maquinaria en el propio hueco del ascensor.<br>
Básicamente los dos tipos tienen un funcionamiento con un sistema en suspensión compuesto por un lado por la cabina y por otro por un contrapeso unidos principalmente mediante cables, cintas o correas dentadas.<br>
La energía necesaria para hacer que el ascensor se eleve o descienda viene proporcionada por un motor eléctrico, el cual puede equipar un reductor o en los más actuales, un motor gearless de imanes permanentes.</p>
<center><img src="https://www.logicbus.com.mx/imagenes/articulo/ascensor3.png" class="image_productos" width ="25%" alt="Figura 3. Estructura de un Ascensor electromecánicos" title="Figura 3. Estructura de un Ascensor electromecánicos"></center><p><center><p><center><b>Figura 3. Estructura de un Ascensor electromecánicos</b></center></p><br>

<p align="justify">una de ventajas de este elevador es que puede alcanzar grandes alturas y disponen un amplio rango de velocidades, en cuanto a los ascensores sin cuarto de máquina se dispone una gran versatibilidad al no tener que habilitar un espacio fuera del hueco del elevador , también cuenta con un mayor ahorro energético de ascensores con motores sin reductor de última generación.</p>

<h2><center>PLC EN LA FUNCIONALIDAD DE LOS ELEVADORES</center></h2>
<p align="justify">un PLC (<b>Programmable Logic Controller</b>), es uno de los dispositivos electrónicos que se programa para realizar acciones de control automático. el PLC es un cerebro que activa componentes de maquinaria que pudieran ser peligrosas para el ser humano.<br>
<a href="https://tienda.logicbus.com.mx/">Logicbus</a> cuenta con <a href="https://tienda.logicbus.com.mx/PLC_c_2794.html">FBs-PLC</a> de la marca FATEK, este PLC puede tener hasta 16 puntos de entradas de interrupción externas. La interrupción puede activarse mediante el cambio del estado de entrada, que puede ser borde positivo / borde negativo o ambos bordes. Cuando se utiliza la función de interrupción de entrada, se pueden detectar operaciones de alta velocidad en la entrada que normalmente se perdería en una exploración de E / S normal.<br><br>
