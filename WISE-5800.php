<center><strong>Módulo de comunicación con E/S Configurables por el usuario a través del protocolo Modbus TCP</strong></center><br>
 <br>

<p> 
WISE es una serie de productos que funcionan para el control de unidades lógicas remotas y monitoreo de diversas aplicaciones industriales. WISE ofrece una interfaz web fácil de usar e intuitiva que permite a los usuarios implementar la lógica de control IF-THEN-ELSE de los controladores a sólo unos pocos clics de distancia, no se requiere programación.<br><br>

WISE-5800 soporta un bus de expansión de E/S para implementar varias funciones E/S como D/I, D/O y D/A de acuerdo con el XW-Board. Además WISE-5800 soporta la serie de módulos de E/S remotas I-7000. Basada en la variedad de E/S de los módulos I-7000, WISE-5800 puede proporcionar más flexibilidad para el usuario en el campo de aplicación.<br><br>

WISE-5800 soporta protocolo Modbus/TCP para hacer una perfecta integración con el software SCADA. Además, WISE-5800 proporciona un registrador de datos que funciona con una tarjeta microSD, puede grabar E/S del canal de desencadenador de evento o periodo de tiempo regular. Los archivos de datos pueden ser enviados por correo electrónico o FTP. Todas las configuraciones se pueden completar a través del navegador.</p><BR>


<strong>Caracteristicas:</strong>
<ul>
<li>Servidor Web Integrado para el establecimiento de reglas IF-THEN-ELSE.</li>
<li>Integrado en la regla de combinación lógica IF-THEN-ELSE.</li>
<li>Soporta E/S, Contador, Temporizador, Calendario, Correo electrónico, Operaciones de recipe.</li>
<li>No se requiere programar. Basta con hacer clic y listo!</li>
<li>Los archivos de datos y registrador de datos cuentan con funciones de envio soportadas.</li>
<li>Protocolo Modbus TCP para la integración de software SCADA.</li>
<li>Ethernet 10/100 Base-TX .</li>
<li>Soporta XW-Board.</li>
<li>Soporta Módulos remotos I-7000 (Hasta 16).</li>
<li>Sincronización de tiempo SNTP compatibles.</li>
</ul>
