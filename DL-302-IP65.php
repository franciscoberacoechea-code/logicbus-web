<p>El dispositivo DL-302-IP65 Data Logger registra información de CO, CO2, temperatura, humedad y punto de rocío, incluidas las marcas de fecha y hora, y almacena hasta 450,000 registros descargables. El DL-302-IP65 permite al usuario acceder a datos en tiempo real mediante el uso del software gratuito de Windows, la aplicación iOS o la aplicación Android, siempre que estén conectados a la misma red local que el registrador de datos. Se proporciona soporte para protocolos industriales populares como DCON, Modbus RTU y Modbus TCP, así como el protocolo de conectividad emergente máquina a máquina (M2M) / IoT (Internet de las cosas) - MQTT. El registrador de datos DL-300 se puede conectar a través de interfaces de comunicación ampliamente utilizadas, como RS-485, Ethernet y PoE, lo que significa que el dispositivo se puede integrar fácilmente en los sistemas HMI o SCADA existentes, y es fácil de mantener en un sistema de control distribuido.
</p><br>


