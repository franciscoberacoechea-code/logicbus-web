<p>CAN (Controller Area Network) es un protocolo de control de bus en serie especialmente adecuado para construir redes de dispositivos industriales inteligentes y construir sistemas inteligentes de control automático. Se aplica popularmente en la automatización industrial, automatización de edificios, vehículos, marina y redes de control integrado. Para expandir los productos de funciones CAN, el módulo I-87120 se desarrolla para este propósito. Es un tipo de módulo y debe conectarse a una unidad host, como la MCU I-8000 y la serie iP-8000 (Unidad de control principal), ViewPAC-2000, WinPAC-8000, LinPAC-8000 y XPAC-8000- CE6. I-87120 proporciona una forma de conectar estas unidades anfitrionas ICPDAS con la red CAN. Debido a las características de I-8000, iP-8000, ViewPAC-2000, WinPAC-8000, LinPAC-8000 y XPAC-8000-CE6, estas unidades de host se pueden organizar para que sean un convertidor CAN, un dispositivo esclavo CAN y un dispositivo maestro CAN en una red CAN. La figura del lado derecho muestra la arquitectura de la aplicación para los módulos I-87120.
</p><BR><br>


<strong>Caracteristicas:</strong>
