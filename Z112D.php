<p>Z112 es un amplificador para sensores de ENCENDIDO / APAGADO y proporciona una salida de relé. Está disponible como canal único (Z112A) o canal doble independiente (Z112D). El canal único dispone también del sistema de división de impulsos (de 1 a 256). También la longitud de la salida de impulsos es configurable desde 100 ms hasta 500 ms. Un aislamiento galvánico de 3 vías entre la fuente de alimentación // entrada // circuitos de salida garantiza la integridad de sus datos.
</p><br>


<strong>Características</strong>
<ul>
<li>Alimentación de 19.2 a 30 Vdc</li>
<li>Entrada a pulsos digitales compatible con los sensores más comunes: Contacto mecánico, IEC1131, NAMUR, 2 o 3 hilos NPN/PNP con 12V o 22V, Reed, fototransistor y dispositivos AICHI</li>
<li>Temperatura en operación de -10 a +65°C</li>
<li>Dimensiones: 93.1 x 102.5 x 6.2mm</li>
</ul>


