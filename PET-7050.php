<p>La serie ET-7000 proporciona capacidades de red completas y una variedad de funciones de E / S, junto con módulos de control y monitorización de E / S Ethernet basados ​​en web, lo que significa que los módulos pueden controlarse de forma remota utilizando el protocolo Modbus TCP / UDP a través de Ethernet red. Esto garantiza que la serie ET-7000 / ET-7200 proporcione integración con HMI, SCADA, PLC y otros sistemas de software de control industrial.
<br><br>
El PET-7050 es compatible con las especificaciones IEEE 802.3af Power-Over-Ethernet (Clase 1). Al conectarse a dispositivos de red compatibles con el estándar PoE IEEE 802.3af, se puede suministrar energía a través de un cable Ethernet de cobre.
<br><br>
PET-7050 proporciona 6 canales de salida digital de tipo fregadero y 12 canales de entrada digital de contacto húmedo, cada uno de los cuales puede usarse como un contador de 32 bits.</p>        

