<center><strong>Controlador serie integrado de entrada / salida con 8 ranuras basadas en ISaGRAFm, pantalla de 7 segmentos de 5 segmentos, puerto RS 232, puerto RS 485, SRAM de 512Kb, flash de 512 KB, NVRAM, reloj en tiempo real, MiniOS7.</strong></center><br>

<p align="justify">La serie RU-87P8 es una unidad de expansión de E / S remota remota que solía expandir los módulos de E / S de la serie I-87K a través de la red RS-485 para aplicaciones de monitoreo y control industrial. Hay más de 30 módulos de E / S compatibles con la unidad; incluyendo entrada / salida analógica, entrada / salida digital, módulos de E / S de contador / frecuencia.<br />
RU-87P8 está diseñado para ser utilizado en entornos hostiles y ruidosos, por lo que el hardware se fabrica con amplios rangos de entrada de alimentación (10 ~ 30 V CC), potencia aislada y temperatura de funcionamiento (-25 ° C ~ + 75 ° C). Simplifica la instalación y el mantenimiento de los módulos de E / S con configuración automática y de intercambio en caliente, detección de fallas y errores, doble watchdog, encendido programable y valores seguros.<br />
Se proporcionan varios kits de desarrollo de software (SDK) y demostraciones, como DLL, ActiveX, controlador Labview, controlador Indusoft, controlador Linux, servidor OPC, etc. Los módulos de E / S de la serie I-87K enchufados a la RU-87Pn pueden ser fácilmente integrado en el sistema de software variante.
