<p>El tM-SG4 es un módulo opcional que es usado para mejorar la comunicación en una red RS485.  Proporciona switch para seleccionar resistores pull-high y pull-low sobre RS485.  También tiene resistencia de terminación seleccionable con switch de 15 pasos donde el usuario puede seleccionar una resistencia de terminación adecuada para ser conectada fácilmente a la red RS485.</p>

<strong>Características:</strong>
<ul>
<li>Resistencias seleccionables por switch pull-high y pull-low</li>
<li>Resistencia de terminación seleccionable por switch</li>
<li>Indicadores LED</li>
<li>Montaje en riel DIN</li>
<li>Módulo totalmente rentable</li>
<li>Temperatura de operación: -25°C ~ +75°C</li>
</ul>
	
