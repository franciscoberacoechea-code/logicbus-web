            <strong>Descripción del producto</strong><br>

            
            <p>Utiliza un rayo láser para mantener un punto de luz visible enfocado en el objeto o la característica a detectar. Es fácil de alinear, fácil de configurar y diseñado para la repetibilidad del rendimiento de sensor a sensor. La pantalla gráfica OLED intuitiva proporciona toda la información necesaria y confirmación visual de la estabilidad de detección, dando al usuario confianza en el rendimiento a largo plazo del sensor. El haz láser consistentemente pequeño se utiliza para detectar cosas tales como una lengüeta en una batería, una tapa de botella desalineada o faltante o una tapa de lata cruzada. Es útil no sólo en aplicaciones de propósito general, como un detector de productos para sistemas de visión, y aplicaciones de inspección sencillas, sino también para aplicaciones de alta precisión para detección de piezas pequeñas, inspección de identificación de identificación crítica y detección de paquetes microelectrónicos. 
            <br><br>
            La pantalla OLED Alfanumérica proporciona toda la información que necesita un operador de línea para maximizar el tiempo. Hay un indicador de contraste de 10 segmentos para visualizar la intensidad dinámica de la señal y el rendimiento del sensor; Un número de punto de referencia y número de intensidad de señal para la visualización estática de los atributos de contraste a largo plazo; Símbolos para indicar el modo de detección, el modo de salida, el estado del temporizador y el estado del botón de bloqueo. Esta pantalla también proporciona ayuda visual cuando se configura el sensor para un requerimiento especifico de una aplicación. Con esta pantalla OLED única, el usuario también puede ver el Sensor Scope para confirmar la robustez a largo plazo del contraste de la aplicación. Esta característica asegura que la línea de producción no tendrá que ser constantemente monitoreada para un rendimiento de producción constante. </p><br>

