          <br>
          All 32 channels may be configured to update simultaneously, or they may be updated one at a time as data is written. A 1024 sample FIFO on each channel allows each D/A to be updated at 10 kHz without data loss. Double buffering the outputs combined with the use of low glitch D/As make the DNR-AO-332 an ideal solution for generating low frequency wave forms or providing highly accurate switched stimulus. The board also offers a digital input bit which may be used as a trigger or as a general purpose input. A digital output bit is also provided.&nbsp;<br>
          <br>
      Software for the DNR-AO-332 is provided as part of the UEIDAQ Framework. The framework provides a comprehensive yet easy to use API that supports all popular Windows programming languages as well as supporting programmers using Linux and most realtime operating systems including QNX (call for pricing), RTX, RT Linux and more. Finally, the framework supplies complete support for those creating applications in data acquisition software packages such as LabVIEW, MATLAB/Simulink, DASYLab or any application which supports ActiveX or OPC servers.</div></td>
