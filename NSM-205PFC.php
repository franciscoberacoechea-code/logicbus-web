<center><strong>Conector SC multimodo, 4 puertos 10/100 Mbps PoE (PSE) con 1 conmutador de puerto de fibra; Estuche de metal.</strong></center><br>

<p>El NS-205PFx / NSM-205PFx es un PoE (PSE) no administrado de 4 puertos con 1 conmutador de puerto de fibra; admite 4 puertos PoE que se clasifican como equipos de fuente de alimentación (PSE). El NS-205PFx / NSM-205PFx hace que la fuente de alimentación centralizada se haga realidad y proporciona hasta 15.4 vatios de potencia por puerto PSE. Al usar fibra óptica, puede evitar que el ruido interfiera con su sistema y admite transmisiones de alta velocidad (100 Mbps) y alta (hasta 60 km).</p><BR>

<strong>Caracteristicas</strong>

<ul>
<li>Proporciona un puerto de fibra 1 x 100-FX más 4 puertos PoE</li>
<li>Crossover automático MDI / MDI-X para plug-and-play</li>
<li>Cada puerto admite la negociación automática de velocidad a 10 / 100Mbps</li>
<li>Arquitectura de almacenamiento y reenvío</li>
<li>Control de flujo de contrapresión Full Duplex IEEE 802.3xy semidúplex</li>
<li>4 puertos PoE con operación de equipos de abastecimiento de energía (PSE)</li>
<li>Detección automática de PD (dispositivos con alimentación) y administración automática de energía</li>
<li>Detección de sobretemperatura, sobrecorriente y sobre / bajo voltaje</li>
<li>Entrada de energía, +46 ~ +55 VDC</li>
<li>Admite temperaturas de funcionamiento de -30 ~ + 75 ° C</li>
<li>Carril DIN</li>
</ul>
