<p align="justify">El módulo de Adquisición de Datos de Termopar TC-08 está diseñado para medir un rango amplio de temperaturas usando cualquier termopar que tenga un conector termopar tamaño miniatura.<br>
La tarjeta viene equipada con compensación de punta fría (CJC), el TC-08 tiene un rango de temperatura efectivo de -270 a +1820 °C (Los rangos de temperatura actual depende del termopar que está siendo usado).<br><br>

<strong>Todos los beneficios de ser USB:</strong><br>

El TC-08 se conecta a un puerto USB de una computadora basada en Windows y activa la PC servidor para automáticamente detectar el TC-08 (evitando la necesidad para cualquier procedimieno de configuración compleja). La conexión USB también permite al TC-08 alimentarse directamente por el bus USB (eliminando la necesidad de un suministro de energía y haciendo al TC-08 ideal para mediciones de temperatura, ambos en el laboratorio y en el campo)<br> 
La conectividad del TC-08 permite hasta 20 módulos de adquisición de datos USB TC-08 para ser usados simultáneamente en una computadora (Haciendo al TC-08 ideal para usarse como un gran sistema de adquisición de temperaturas multicanal con un costo por canal significativamente más bajo que otros sistemas de este tamaño)<br> 
Con el módulo de adquisición de datos termopar TC-08 tus mediciones pueden ser hechas de forma rápida y exacta.<br>
El poco tiempo de conversión del TC-08 permite realizar hasta 10 mediciones de temperatura cada segundo. Mientras la alta resolución asegura que el TC-08 puede detectar el momento en que cambia la temperatura.<br><br>

<strong>Todo lo que tu necesitas en una unidad fácil de usar</strong><br>
La adquisición de datos de Temperatura es muy fácil (simplemente conecta el TC-08 a un puerto USB de tu computadora, conecta los termopares y ya estás listo para medir temperaturas).</p><br><br>

