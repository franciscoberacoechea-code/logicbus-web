  <h1 class="my-5"><b class="margen">Soporte de empuje del motor cohete</b></h1>
<center><h2><b>Aplicación de Celdas de carga</b></h2></center><br>

<div class="part1">

<article>
  <p><b>Resumen de la aplicaci&oacute;n:</b>
La caracterización de motores de cohetes sólidos, líquidos e híbridos a menudo se realiza con modelos informáticos y pruebas en tierra. Para los combustibles experimentales, aerospike y otras boquillas de compensación de altitud experimentales, es necesario realizar pruebas en tierra para caracterizar sus curvas de empuje y I sp  en condiciones de prueba estática. Para lograr esto, se acopla una celda de carga de la serie LCF entre el motor cohete y el soporte de empuje. Además del empuje, al incorporar cuatro celdas de carga de 3 ejes en los soportes de la base del banco de pruebas, el flujo másico del motor se puede medir directamente y, en ciertas circunstancias, también se puede medir el empuje de escape vectorizado. Soporte de empuje de cohete inspirado en Diseño del laboratorio de propulsión suizo SPL.
</p>
<div align="center">
<img src="https://www.logicbus.com.mx/imagenes/soluciones-en-la-industria/aeroespacial/soporte-de-empuje-del-motor-cohete.jpg" alt="soporte-de-empuje-del-motor-cohete" width="70%">
</div>
<div>
  <p><b>C&oacute;mo funciona:</b><br></p>
  <ol>
    
<li style="color: black;">En esta aplicación, el motor cohete se enrosca en la celda de carga universal de la serie LCF.</li>
<li style="color: black;">El soporte del motor evita cualquier carga lateral en la celda, lo que garantiza que la celda de carga solo reciba cargas axiales.</li>
<li style="color: black;">El conjunto de la celda de carga está montado en un banco de pruebas fijo que asegura el motor.</li>
<li style="color: black;">En línea con los soportes de la base, se instalan células de carga multieje <strong><a href="https://tienda.logicbus.com.mx/FSH04139_p_18525.html" target="_blank">MTA400</a></strong> / MTA600</li>
<li style="color: black;">Mientras el motor está funcionando, el empuje se mide con las celdas de carga de la serie LCF.</li>
<li style="color: black;">El flujo másico y el arrastre (también conocido como "patada") se capturan con las celdas de carga <strong><a href="https://tienda.logicbus.com.mx/FSH04139_p_18525.html" target="_blank">MTA400</a></strong> / MTA600.</li>
<li style="color: black;">Los datos de empuje se pueden transmitir en vivo y registrar para su monitoreo y revisión y comparación posteriores con modelos simulados con <strong><a href="https://tienda.logicbus.com.mx/FSH03927_p_14415.html" target="_blank">USB220</a></strong> y SENSIT</li>
<li style="color: black;">Los datos de flujo másico de las 4 celdas de carga de varios ejes se capturan, transmiten y registran con <strong><a href="https://tienda.logicbus.com.mx/FSH03927_p_14415.html" target="_blank">USB220</a></strong> y SENSIT.</li>
<li style="color: black;">Cada eje del <strong><a href="https://tienda.logicbus.com.mx/FSH04139_p_18525.html" target="_blank">MTA400</a></strong> / MTA600 se captura con un <strong><a href="https://tienda.logicbus.com.mx/FSH03927_p_14415.html" target="_blank">USB220</a></strong> separado.</li>
<li style="color: black;">La salida de la celda de carga también se puede amplificar a través de la serie IAA para su captura mediante DAQ preexistentes.</li>

  </ol>
    
