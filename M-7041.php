          <center><strong>Módulo de adquisición de datos de entrada digital (contador) de 14 canales, transmisible a través de Modbus RTU y RS-485, admite temperaturas de funcionamiento de -25 ~ 75 ° C</strong></center><br>
          <br>

          <p> 
            El I-7041 proporciona 14 canales para entrada digital, cada uno de los cuales cuenta con aislamiento de fotoacoplamiento. Además, la entrada digital del receptor o del tipo fuente se puede seleccionar a través de conexiones por cable, y todos los canales se pueden usar como contadores de 16 bits. El I-7041DD incluye 14 indicadores LED que se pueden usar para monitorear el estado del canal DI. La protección ESD de 4 kV y el aislamiento intramódulo de 3750 VDC son estándar. Las especificaciones de hardware para el M-7041 y el M-7041P son las mismas que para el I-7041, y son compatibles con los protocolos Modbus RTU y DCON, que se pueden configurar a través del software. ICPDAS recomienda seleccionar la versión "P" del módulo de entrada digital para uso industrial.
          </p><BR>

          <strong>Características:</strong>
          <ul>
            <li>Fuente de entrada digital tipo fuente o fuente.</li>
            <li>Aislamiento de fotoacoplamiento.</li>
            <li>Todos los canales se pueden usar como contadores de 16 bits.</li>
            <li>± 4 kV Protección ESD.</li>
            <li>Voltaje de aislamiento de 3750 VDC.</li>
            <li>Dual Watchdog.</li>
            <li>Amplio rango de temperatura de funcionamiento: -25 ~ + 75 ° C.</li>
          </ul>
