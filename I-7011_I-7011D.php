<center><strong> M&oacute;dulo de Entrada de termopar</strong></center><br>

<p>El módulo I-7011 proporciona protección y acondicionamiento rentables para una amplia gama de valiosas señales y sistemas de control industrial. La utilidad DCON puede ayudar a los usuarios a configurar y probar los módulos I-7011. Se proporcionan muchas funciones de biblioteca y programas de demostración para permitir a los usuarios desarrollar programas fácilmente en sistemas operativos Windows, Linux y DOS. Los usuarios pueden montar los módulos en un riel DIN, panel o pared. Los módulos tienen un bloque de terminal de tornillo para conectarse a las señales. I-7011 viene con el software EZ Data Logger GRATIS.</p><BR>


