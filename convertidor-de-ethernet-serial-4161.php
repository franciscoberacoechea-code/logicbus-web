<p align="justify">Comuníquese fácilmente con hasta 16 dispositivos en serie a través de una red Ethernet con el servidor en serie 4161 Ethernet. Cada puerto RS-232 implementa todas las señales de control de módem comunes para una máxima compatibilidad con una amplia gama de periféricos. Los productos SeaLINK® utilizan el protocolo TCP/IP RFC 2217 estándar de la industria para maximizar la compatibilidad con la más amplia gama de aplicaciones y dispositivos.
<br><br>
Los controladores y las utilidades del software SeaLINK de Sealevel facilitan la instalación y operación con los sistemas operativos Microsoft Windows. Después de la instalación del software, los puertos seriales del 4161 aparecen como puertos COM virtuales para la máquina host. Las llamadas operativas en serie estándar se redirigen de forma transparente al 4161, lo que garantiza la compatibilidad con los dispositivos en serie heredados y permite la compatibilidad con el software existente. El túnel en serie también es compatible, permitiendo que dos dispositivos seriales nativos se comuniquen a través de una red. Alternativamente, se admite el modo de socket de datos sin procesar, lo que elimina la necesidad de un controlador.
<br><br>
Alojados en recintos metálicos resistentes para montaje en rack de 1U, los dispositivos 4161 son adecuados para una variedad de aplicaciones y entornos. Los LED indicadores de alimentación se incluyen en la parte frontal y posterior del gabinete, y cada uno de los 16 conectores serie RJ45 proporciona indicadores LED Tx y Rx para ayudar en la resolución de problemas. El rango de temperatura de funcionamiento estándar es de 0C a + 70C, y hay disponibles modelos de temperatura extendida (-40C a + 85C).
<br><br>
Para simplificar la instalación y la configuración, se incluye una copia impresa de la Guía de inicio rápido de SeaLINK con todos los pedidos del servidor serie Ethernet.</p>

<strong>Caracteristicas:</strong>
<ul>
	<li>Ethernet 10/100BaseT (detección automática)</li>
	<li>Aparece como puertos COM virtuales para la máquina host</li>
	<li>Velocidades de datos a 230.4K bps</li>
	<li>Admite velocidades de transmisión personalizadas y protocolo de 9 bits</li>
	<li>Intercambiables en caliente</li>
	<li>El circuito de vigilancia/reinicio incorporado recupera automáticamente el convertidor de estados de error inesperados</li>
	<li>Los puertos serie utilizan conectores RJ45</li>
	<li>Adaptador de CA de 120 V con conector de bloqueo incluido (salida de 12 V CC a 1 A, artículo n. ° TR125)</li>
	<li>Para facilitar la instalación, incluye cable de conexión CAT5 de 7 '(azul, artículo # CA246) y cable cruzado (amarillo, artículo # CA251)</li>
	<li>Incluye bucle invertido RJ45 para probar RS-232</li>
	<li>El software Sealevel SeaLINK es compatible con los sistemas operativos Microsoft Windows y Linux</li>
</ul>

