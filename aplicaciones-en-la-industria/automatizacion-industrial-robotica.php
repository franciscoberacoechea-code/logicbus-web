                    <li class="mb-3"><b>Versatilidad y Conectividad</b>: La integración con el USB520 y la flexibilidad de visualización en diferentes dispositivos facilita el monitoreo en tiempo real y la captura de datos para análisis posteriores.</li>
                    <li class="mb-3"><b>Cumplimiento de Normas de Seguridad</b>: Al medir y verificar la resistencia de los palos de hockey, se asegura que el producto cumpla con los estándares de seguridad y durabilidad esperados por los consumidores y reguladores.</li>
                </ul>
