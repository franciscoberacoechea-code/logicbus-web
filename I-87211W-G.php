<p align="justify">El I-87211W, una nueva solución de GPS para el módulo Receptor GPS de la familia I-87K en ICP DAS, con alta sensibilidad, bajo consumo de energía y factor de forma ultra pequeño con protocolos DCON y GPS. Este potente elemento le proporciona una sensibilidad superior y un rendimiento excepcional incluso en el entorno más hostil. El I-87211W proporciona DO adicional de 2 canales y PPS de 1 canal para los usuarios. Las señales PPS se pueden usar para la medición precisa del tiempo y el tiempo. Uno puede combinar la funcionalidad PPS con otra como fuente de sincronización de tiempo.
<br><br>
Por lo tanto, el I-87211W puede ser un potente módulo de GPS, así como un módulo de GPS de propósito general con interfaz RS232 en PAC y unidades de expansión de E/S remotas. También se puede aplicar en navegación automotriz, posicionamiento personal y navegación, navegación marina, corrección de tiempo satelital, etc.</p>

<strong>Características:</strong>
<ul>
<li>Admite PAC y unidades de expansión de E/S remotas de ICP DAS</li>
<li>Admite 66 canales de GPS y NMEM v0183 v3.01</li>
<li>RS-232 admite el formato NEMA v0183 v3.01 o el protocolo DCON</li>
<li>DS de 2 canales incorporados, PPS de 1 canal (1 pulso por segundo), 1 puerto RS-232</li>
<li>PPS: salida de impulsos de 100 ms/s para la medición precisa del tiempo y el tiempo</li>
<li>Con varios indicadores LED del sistema</li>
<li>Montaje en riel DIN</li>
</ul>

