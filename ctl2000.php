          <p align="justify">CTL2000 es robusto, único en su clase para monitoreo de temperatura durante los ciclos de pasteurización de carcasa. Equipado con puertos para 8 termopares, el CTL2000 monitorea y registra la temperatura de varias secciones del armazón durante la pasteurización, ofreciendo un perfil de temperatura continua y precisa para verificar y validar que los microorganismos nocivos están agotados con eficacia.<br><br>
            La carcasa durable es a prueba de gotas y diseñada para sobrevivir los elementos de la carnicería. La cima de la carcasa está hecha de acero inoxidable grado alimentos con una calidad industrial que bordea los puertos de termopar para proteger contra la infiltración de residuos y ciclos de lavados. Los materiales de calidad y opciones de formato se eligieron mediante normas y directrices sanitarias, y hechas con materiales certificados para el contacto directo con alimentos tal y como se describe en la norma NSF-51.<br><br>
            El CTL2000 es fácil de manejar y cuelga de manera segura desde el armazón por un gancho de acero inoxidable. Este dispositivo es capaz de soportar temperaturas desde -20°C a 100°C, permitiéndolo monitorear el proceso de pasteurización entero.<br>
            Cada canal puede almacenar hasta 129,024 lecturas lo cual ayuda en el registro de múltiples ciclos. La capacidad de frecuencia de lectura puede ser tan rápido como 1 vez por segundo o de manera menos frecuente como una lectura cada 24 horas. Opera con baterías reemplazables y tiene un botón para inicio directamente en el dispositivo. El usuario puede programar un inicio retardado desde el software.<br>
            El software ofrece una gran cantidad de opciones para desplegar datos y reportes para facilitar el análisis de los resultados de cada ciclo y tiene la verificación para la regulación USDA.</p><br><br>

