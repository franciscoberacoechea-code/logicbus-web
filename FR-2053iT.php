<li>Mecanismo de sincronización simple.</li>
<li>No hay sobrecarga de software en el procesamiento del protocolo.</li>
<li>Apoyo a la radiodifusión (transmisión de datos 1: n).</li>
<li>Duplicar fácilmente la salida.</li>
<li>Tiempo de escaneo de E/S fijo y sincronización de E/S.</li>
