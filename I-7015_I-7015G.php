          <center><strong>Módulo de adquisición de datos de entrada RTD (detector de temperatura de resistencia) de 3 hilos con 6 canales de entrada analógica, transmisibles a través de RS-485, y software EZ Data Logger GRATUITO. Admite temperaturas de funcionamiento entre -25 ° C ~ + 75 ° C (-13 ° F `+ 167 ° F).</strong></center><br>

          <p>La serie I-7000 es una familia de módulos de adquisición y control de datos de red, que proporciona funciones de entrada / salida digital, analógica a digital, digital a analógica, temporizador / contador y otras. Los módulos se pueden controlar de forma remota utilizando un conjunto de comandos, que llamamos el protocolo DCON. La comunicación entre el módulo y el host se realiza en formato ASCII a través de un estándar de bus serie bidireccional RS-485. Las tasas de baudios son programables por software y se pueden seleccionar velocidades de transmisión de hasta 115.2 Kbps.<br><br>

            I-7015 está inteligentemente diseñado para proporcionar monitoreo del sistema de acondicionamiento de señal y configuraciones de valores seguros. I-7015 es una solución rentable para una amplia gama de valiosas señales y sistemas de control industrial. La utilidad DCON puede ayudar a los usuarios a configurar y probar los módulos de entrada I-7015 RTD. Se proporcionan muchas funciones de biblioteca y programas de demostración para permitir a los usuarios desarrollar programas fácilmente en sistemas operativos Windows, Linux y DOS. Los usuarios pueden montar los módulos en un riel DIN, panel o pared. Los módulos tienen un bloque de terminal de tornillo para conectarse a las señales. I-7015 viene con el software EZ Data Logger GRATUITO.</p><BR>

          <strong>Características:</strong>
          <ul>
            <li>Entrada RTD de 6 canales</li>
            <li>Entrada RTD de 3 hilos con eliminación de resistencia del cable</li>
            <li>Alta resolución: 16 bits</li>
            <li>Configuración del canal individual</li>
            <li>Detección de cables abiertos</li>
            <li>Protección contra ESD de 4 kV</li>
            <li>Protección EFT de 4 kV</li>
            <li>Aislamiento intramódulo de 3000 VDC</li>
            <li>Dual Watchdog</li>
            <li>Amplio rango de temperatura de funcionamiento: -25 a + 75 ° C</li>
          </ul>


