<p>Se utiliza para pilotar 5 relay SPST de salida de todos los sistemas de control que son capaces de comunicarse con el protocolo de transmisión <a href="https://www.logicbus.com.mx/convertidores_info#Modbus">MODBUS</a> RTU a través de la interfaz serie <a href="https://www.logicbus.com.mx/convertidores_info#RS-485">RS485</a>.<br>
El instrumento consta de 5 relay de salida SPST NO con salida negativa en común y 5 A 250Vac capacidad de carga resistiva, 2 A carga inductiva. Para cada salida es posible establecer si el estado de los relés si en resto, en caso afirmativo, debe ser NO de otra manera NC, así como el estado a que los relés deben tomarse al arrancar o, en el caso de falta de comunicación, incluido un retraso que puede variar entre 50 y 2500 ms.<br>
El cableado de la fuente de alimentación y bus de serie se ve facilitada por el uso de un bus de soporte que se puede alojar dentro de la guía DIN.<br>
El sistema también permite el intercambio en caliente, es decir, la inserción y la extracción del módulo del bus sin la interrupción de la comunicación ni la fuente de alimentación a la parte restante del sistema.<br>
Señalización frontal con LEDs para: presencia de alimentación, anomalía, estado de las 5 entradas, recepción/transmisión de datos. </p>
 <strong>Caracter&iacute;sticas:</strong>
     <ul>
        <li>5 entradas digitales.</li>
        <li>Entradas con contacto de 16 bits, Frecuencia M&aacute;xima de entradas 100 Hz.</li>
        <li>Protocolo modbus RTU serial RS485 </li>
        <li>Alimentaci&oacute;n y conexi&oacute;n serial por medio del Bus Z-PC-DINAL2-17.5 </li>
        <li>Tiempo de comunicaci&oacute;n por debajo de los 10 ms (a 38400 baudios) </li>
        <li>Distancia de conexi&oacute;n hasta 1200 m </li>
     </ul>
