          Su sistema operativo, Windows CE 5.0, tiene muchas ventajas, incluida la capacidad dura en tiempo real, tamaño de núcleo pequeño, velocidad de arranque rápida, manejo de interrupciones a un nivel más profundo, control determinista alcanzable y bajo costo. El uso de Windows CE 5.0 en el WinPAC-8000 le da la capacidad de ejecutar software de control basado en PC, como Visual Basic.NET, Visual C #, Embedded Visual C ++, software SCADA, Soft PLC, etc.
