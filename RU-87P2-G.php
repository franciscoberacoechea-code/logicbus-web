<center><strong>Unidad de expansión de E / S remota remota basada en RS-485 con 2 ranuras</strong></center><br>

<p align="justify">RU-87Pn series is a remote intelligent I/O expansion unit to expand I-87K series I/O modules over the RS-485 for industrial monitoring and controlling applications.<br />
RU-87Pn is designed to be used in harsh and noisy environment, so the hardware is manufactured with wide power input range (10 ~ 30 VDC), isolated power input and can operate under wide temperature (-25°C ~ +75°C). To simplify installation and maintenance of I/O modules, it provides many useful features, such as: hot swap allowed, auto configuration, LED indicators for fault detection, dual watchdog to keep alive, programmable power on and safe values for safety.<br />
There are more than 30 I/O modules supported with the unit, including analog input/output, digital input/output, counter, frequency I/O modules. We provide various software development kits (SDK) and demos, such as DLL, ActiveX, Labview driver, InduSoft driver, Linux driver, OPC server, etc. The I-87K series I/O modules plugged in the RU-87Pn can be easily integrated into variant software system.
</p><BR><br>


