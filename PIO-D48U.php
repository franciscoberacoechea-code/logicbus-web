<center><strong>Tarjeta universal PCI, 48 canales de entada/salida digitales, 2 temporizadores/contadores de 16 bit a 4 MHz, voltaje de alimentación PCI de 3.3V/5V.</strong></center><br>


<p>El PIO-D48U es el producto de nueva generación que ICP DAS proporciona para cumplir con los requisitos de cumplimiento de RoHS y está diseñado como completamente compatible con el PIO-D48. Los usuarios pueden reemplazar el PIO-D48 por el PIO-D48U directamente sin modificación de software / controlador.<br>

El PIO-D48U admite bus PCI de 3,3 V / 5 V, mientras que el PEX-D48 es compatible con el bus PCI Express. Estas tarjetas proporcionan 48 líneas de E / S digitales TTL, y estas líneas se agrupan en seis puertos bidireccionales de 8 bits. Cada tres puertos de 8 bits están agrupados como puerto A (PA), puerto B (PB) y puerto C (PC) en un conector, y el puerto C se puede dividir en 2 partes de mordisco (4 bits). Todos los puertos se configuran como entradas al encender o restablecer.<br>

El PIO-D48U también agrega un interruptor de ID de tarjeta y resistencias de extracción / extracción para DI a bordo. Los usuarios pueden establecer la ID de la tarjeta en una placa y reconocer la placa mediante la ID a través del software cuando usan dos o más tarjetas PIO-D48U en una computadora. Los resistencias pull-high / pull-low permiten especificar el estado DI cuando los canales DI están desconectados; el estado de DI permanecerá en estado alto o bajo que no sea flotante.<br>

El PIO-D48 / D48U es compatible con varios sistemas operativos, como Linux, DOS, Windows 98, Windows 2000, Windows NT, Windows XP de 32 bits, Vista de 32 bits y Windows 7 de 32 bits. También proporciona el control DLL y Active X y varios programas de muestra de lenguaje en Turbo C ++, Borland C ++, Microsoft C ++, Visual C ++, Borland Delphi, Borland C ++ Builder, Visual Basic, C # .NET, Visual Basic.NET y LabVIEW para ayudar a los usuarios a desarrollar sus aplicaciones rápida y fácilmente.<br>
</p><BR><br>

