        <p>En temas de medición de potencia, los transformadores de corriente, también conocidos como donas, nos permiten medir y monitorear sistemas de alta tensión, cuyos valores de corriente son tales que no pueden ser medidos directamente por un sistema o dispositivo digital. <BR>
          Para eso Logicbus maneja una amplia gama de modelos con diferentes tipos de salidas tales como: 5A, 4~20mA, 0~10V. Estos los puede encontrar de diferentes tipos de instalaciones (Solid Core y Split Core).<BR>
          Solid Core: En las de tipo Solid Core ( o Núcleo Cerrado) el cable se debe pasar entre el dispositivo, por lo que se desconecta la línea a medir.<BR>
          Split Core: Las donas de tipo Split Core (o Núcleo Abierto) , el equipo se puede abrir como pinza para introducir la línea sin necesidad de desconectarla.<BR>
          Contamos con equipos con diferentes rangos de medición, que van desde 5A hasta 4000 A:
