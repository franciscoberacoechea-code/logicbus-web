      <p>Las personas que tengan estos trabajos serán clave para mantener las operaciones automatizadas de IoT
        funcionando sin problemas y sin riesgos. Serán esenciales para resolver los problemas más complejos que
        enfrentan las cadenas de suministro de fabricación y las líneas de producción que las máquinas no pueden
        resolver.</p>

      <h3 class="subtitle blue text-center">IV. TRABAJOS DE MANTENIMIENTO Y CIBERSEGURIDAD IIOT</h3>

      <p>También habrá una enorme necesidad de que los empleados con conocimientos generales de redes y circuitos
        de IoT realicen tareas de mantenimiento y preserven la seguridad. Estos individuos serán mecánicos
        expertos, ingenieros eléctricos, mecánicos e informáticos o informáticos. Su educación será muy similar
        a la mecánica automotriz, con el aprendizaje y la experiencia de laboratorio. </p>

      <p>
        <center><img src="https://www.logicbus.com.mx/imagenes/articulo/iiot-3.jpg" class="image_productos" width="50%"
            alt="iiot" title="CYBERSERGURIDAD IIOT "><br><b>Fig. 3 CYBERSEGURIDAD IIOT </b>
        </center>
      </p>

      <p>Sus responsabilidades incluirán la configuración de programas digital twin, el mantenimiento de los datos
        y evitar que las redes sean hackeadas o uso indebido, y el mantenimiento de la integridad física de los
        dispositivos. Cuando un activo inteligente informa de errores a su operador, un "mecánico de electrónica
        inteligente" estará en el lugar para diagnosticar y reparar el problema de inmediato. Sin la inmediatez
        del mantenimiento, se anularán todos los beneficios de la automatización (análisis de datos en tiempo
        real, programación de respuestas y consistencia). </p>

      <h3 class="subtitle blue text-center">V. CONCLUSIÓN</h3>
      <p>IIoT ya comenzó a transformar las ciudades y las redes domésticas. A medida que se abre camino en las
        industrias de manufactura y otras industrias, los empleadores deben estar preparados para la inundación
        de contratación que será necesaria para cumplir con estos nuevos roles. Los destinos de las empresas
        manufactureras deberán invertir en educación STEAM, habilidades técnicas y preparación para IIoT para
        contar con una fuerza de trabajo que pueda aprovechar la transformación lucrativa y emocionante. </p>
