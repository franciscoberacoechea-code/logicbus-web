                <p class="light-black">Los contenedores de gestión de residuos de gran tamaño están diseñados para recoger basura hasta que alcanzan una capacidad específica. Una vez que se alcanza esa capacidad, es necesario proceder con la disposición de los contenidos. Utilizar celdas de carga permite monitorear el aumento de la capacidad del contenedor mediante la medición de la carga de residuos.</p>

                <p class="text-center light-black font-weight-bold">¿Cómo funciona?</p>
                <ol class="light-black">
                    <li class="mb-3">Los contenedores industriales para la gestión de residuos tienen la capacidad de albergar hasta 50 toneladas de desechos. La disposición de los residuos solo ocurre cuando el contenedor ha alcanzado su capacidad máxima.</li>

                    <li class="mb-3">Para monitorear el aumento en la carga de residuos, se instalan celdas de carga en la base del contenedor. Estas celdas permiten medir de manera precisa el peso acumulado a medida que el contenedor se llena, proporcionando una visión clara de la capacidad restante.</li>

                    <li class="mb-3">En este escenario de aplicación específico, se deben montar cuatro placas de carga de 25 toneladas en la base de cada pata del contenedor. Hay dos opciones de montaje disponibles para la instalación:</li>
                    <ul>
                        <li class="mb-3">Montar un botón de carga sobre una placa de carga en una superficie limpia y nivelada, sobre la cual descansará el contenedor.</li>
                        <li class="mb-3">Montar el botón de carga bajo cada pie del contenedor, sobre una placa de carga.</li>
                    </ul>
                    <li class="mb-3">Independientemente de la metodología de montaje seleccionada, los datos recogidos por cada celda de carga se pueden transmitir a través de una caja de suma a una pantalla digital o directamente a una PC. Esto permite a los operadores visualizar en tiempo real el peso de los residuos y planificar la disposición cuando el contenedor se acerca a su capacidad máxima.</li>
                </ol>
                <p class="text-center light-black font-weight-bold">Beneficios de Monitorear la Capacidad en Contenedores de Residuos</p>
                <ul>
                    <li class="mb-3">Optimización del proceso de vaciado: Las celdas de carga aseguran que el contenedor sólo se vacíe cuando haya alcanzado su capacidad total, optimizando así los recursos de transporte y disposición.</li>
                    <li class="mb-3">Monitoreo en tiempo real: La capacidad de transmitir datos en tiempo real permite a los operadores mantener un control preciso sobre la capacidad restante y evitar sobrecargas.</li>
                    <li class="mb-3">Flexibilidad en el montaje: Las opciones de instalación de las placas de carga brindan versatilidad para adaptarse a diferentes entornos y tipos de contenedores.</li>
                    <li class="mb-3">Automatización del monitoreo: Con la transmisión de datos a pantallas digitales o directamente a un ordenador, se minimiza la intervención manual, mejorando la eficiencia operativa.</li>
                </ul>
