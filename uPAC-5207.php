<center><strong>Controlador programable de poco tamaño basado en ISaGRAF, 1 puerto ethernet, 2 puertos paralelos, MiniOS7.</strong></center><br>

<p align="justify">La serie μPAC-5x07 (P) es un controlador de automatización programable de tamaño de la palma de la mano. Tiene una CPU 80186, SRAM, Flash, puerto Ethernet, puerto RS-232 y RS-485. Con un sistema operativo tipo DOS (MiniOS7) y un firmware desarrollado que se ejecuta dentro, puede actuar como una PC pequeña.<br />
Para la expansión de hardware, también es compatible con un bus de expansión de E / S. El bus de expansión de E / S se puede utilizar para implementar varias funciones de E / S, como DI, DO, A / D, D / A, temporizador / contador, UART y otras funciones de E / S. Casi todas las clases de funciones de E / S pueden ser implementadas por este bus. El autobús puede soportar una placa. Hay más de 10 placas disponibles para la serie μPAC-5x07 (P), puede elegir una de ellas para expandir las características de hardware.<br />
μPAC-5x07 (P) es el modelo de μPAC-5x07 con PoE (Power-over-Ethernet). PoE permite que la energía y los datos se transporten a través de un solo cable Ethernet, por lo que un dispositivo puede operar únicamente a partir de la energía que recibe a través del cable de datos. Esta innovación permite una mayor flexibilidad en el diseño de la oficina, una mayor eficiencia en el diseño de sistemas y un tiempo de respuesta más rápido en el diseño de sistemas, y un tiempo de respuesta más rápido en la configuración e implementación.
