<h3>Caracteristicas</h3>

<p>FR-2053 proporciona una entrada digital de 16 canales aislados de foto-acoplador en el FRnet. La transmisión de datos de E/S es controlada por el chip de control de FRnet (desarrollado por ICPDAS). Fue diseñado para proporcionar comunicación de red de alta velocidad determinista. Se han incorporado circuitos anti-ruido en el chip de control de FRnet para garantizar la fiabilidad de la comunicación.<br>

FRnet es un bus de campo industrial innovador que ofrece control E/S determinístico de alta velocidad, capacidades de sincronización de E/S real, comunicación sin protocolo y programación sencilla. La línea ICP DAS FRnet ofrece una tecnología de vanguardia para aplicaciones de adquisición de datos de alta velocidad. El FR-2053 es un módulo de E/S distribuida de salida digital aislada con 16 puertos.</p>

<lo>
<li>Alta fiabilidad de transmisión</li>
<li>Mecanismo de sincronización simple</li>
<li>Montaje en riel DIN</li>
<li>No hay sobrecarga de software en el protocolo</li>
<li>Procesamiento Isochronous DI/DO</li>
<li>Apoyo a la radiodifusión (transmisión de datos 1:n)</li>
</lo>

