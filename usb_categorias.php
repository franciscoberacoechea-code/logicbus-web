<h1><strong>USB</strong></h1>
<br>

<p align="justify"><strong>USB</strong> responde a las siglas Universal Serial Bus y hace referencia a un protocolo de conexión que permite enlazar diversos periféricos a un dispositivo electrónico (frecuentemente, un ordenador) para el intercambio de datos, el desarrollo de operaciones y, en algunos casos, la carga de la batería del dispositivo o dispositivos conectados. Es, por tanto, básicamente, un puerto que funciona de toma de conexión entre diferentes aparatos.</p>

