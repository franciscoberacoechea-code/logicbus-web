<p align="justify">El 7804 es un adaptador PCI compatible con Universal Bus (3.3V o 5V) , de interfaz múltiple y ocho puertos . Al ofrecer ocho canales RS-232, RS-422 o RS-485 seleccionables en el campo, el 7804 ofrece la máxima flexibilidad para expandir las comunicaciones serie.<br>
El 7804 admite velocidades de datos de PC estándar y cuenta con una velocidad máxima de 921.6K bps. La placa está diseñada con el UART XR16C864, que proporciona un FIFO de 128 bytes, ocho veces más grande que las placas diseñadas con partes compatibles con 16C550. Los búferes más grandes permiten un funcionamiento sin errores incluso en aplicaciones de alta velocidad. En el modo RS-485, la placa proporciona el control automático de la habilitación del controlador RS-485 para un arbitraje maestro de red sin problemas. Además, la terminación de la red RS-485, crítica para la robusta comunicación de múltiples caídas, puede agregarse selectivamente al circuito a través de los interruptores DIP.</p>

<strong>Características:</strong>
<ul>
<li>Cumple con las directivas RoHS y WEEE</li>
<li>Cada puerto configurable individualmente para RS-232, RS-422 o RS-485</li>
<li>16C864 UART con búfer con FIFO de 128 bytes</li>
<li>Tasas de datos a 921.6K bps</li>
<li>Compatible con bus universal (señalización 3.3V y 5V)</li>
<li>Requiere 3.3V de potencia en bus PCI</li>
<li>RS-485 automático habilitar / deshabilitar</li>
<li>El cable de 36 ″ incluido termina en ocho conectores DB9M (artículo # CA145)</li>
</ul><br>


