<center><strong>PCI universal, cuanta con 32 canales de entradas análogas simples o 16 canales de entrada análoga diferencial, a una velocidad máxima de muestreo 250 kS/s con una resolución de 12 bit, control de ganancia programable, 2 canales análogos de salida de voltaje a 16 bit en un rango de +/-10V, +/-5, 0-10V y 0-5V, 32 canales de entrda/salida digital programables.</strong></center><br>


<p>La PCI-822LU es una tarjeta multifunción de alto rendimiento que proporciona E / S analógicas de alta velocidad y funciones de E / S digitales. La tarjeta PCI-822LU tiene una interfaz PCI universal que admite bus PCI de 3,3 V y 5 V. Esta tarjeta presenta un convertidor A / D continuo de 250 k Samples / Sec de 12 bits, FIFO de hardware de muestras de 8 K, convertidor D / A de 2 bits, E / S digital programable de 32 canales y lectura de DO. El PCI-822LU proporciona entradas análogas diferenciales de un solo extremo o 16 ch de 32 canales que se pueden seleccionar por puente. El PCI-822LU está equipado con una PGA de alta velocidad con controles de ganancia programables (1,2,4,8).<br>

El PCI-822LU tiene el interruptor de ID de tarjeta y resistencias de extracción / extracción para DI a bordo. Los usuarios pueden configurar la ID de la tarjeta en una placa y reconocer la placa mediante la ID a través del software cuando usan dos o más tarjetas PCI-822LU en una computadora. Los resistencias pull-high / pull-low permiten especificar el estado DI; cuando los canales DI están desconectados, el estado DI permanecerá en un estado alto o bajo que no sea flotante.<br>

El PCI-822LU proporciona dos métodos de activación programables: disparador de software y disparador de marcapasos. La función de escaneo de canales A / D de PCI-822LU es tan sorprendente que la llamamos MagicScan. El controlador MagicScan elimina la mayoría de los trabajos de obtención de valor A / D, como seleccionar canal, establecer ganancia, establecer el tiempo, activar el ADC y obtener datos. Con las características incorporadas de MagicScan y de interrupción, está descargando efectivamente su CPU del trabajo. Incluso en el modo de exploración de canales, puede tener un código de ganancia diferente para cada canal, y la tasa de muestreo puede llegar a 250 kS / s en total. El PCI-822LU es adecuado para aplicaciones de gama alta.<br>
</p><BR><br>

<strong>Caracteristicas</strong>

<ul>
<li>Compatible con bus PCI +5 V y +3.3 V</li>
<li>Función de ID de tarjeta [A / D]</li>
<li>Un convertidor A / D con un máximo de 250 k Samples / Sec.</li>
<li>Convertidor A / D de resolución de 12 bits</li>
<li>8 K muestras de hardware FIFO</li>
<li>32 entradas análogas diferenciales single-ended / 16</li>
<li>Controlador MagicScan incorporado</li>
<li>Función de interrupción</li>
<li>Dos disparos A / D diferentes: disparador de software, disparador de marcapasos.</li>
<li>Control de ganancia programable, control de compensación programable [D / A]</li>
<li>Salida de voltaje de 2 canales de 16 bits.</li>
<li>Rango de salida de tensión: +/- 10 V, +/- 5V, 0 ~ 10 V, 0 ~ 5 V [DIO]</li>
<li>32-ch programable DI / DO</li>
<li>Tire de la función high / pull low en DI</li>
<li>Estado de DO leído de nuevo</li>
<li>Velocidad de transferencia de datos de alta velocidad.</li>
</ul>
