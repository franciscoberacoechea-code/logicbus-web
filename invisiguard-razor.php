Protección máxima para las puertas instalada en minutos. El sistema InvisiGuard Razor puede ser instalado tanto en cabinas de elevador modernas como viejas y viene completo con todos los soportes de montaje y hardware. Nuestro exclusivo diseño de soporte de cola de milano facilita la configuración del borde para el montaje en puertas de separación lateral y central. Los soportes personalizados pueden adaptarse a las necesidades del OEM. La fuente de alimentación universal hace que la conexión a cualquier controlador de puerta y la potencia de la cabina sea rápida.
