<p align="justify"><b>El perfil de temperatura del horno</b> puede ayudar a garantizar que se produzca un producto de calidad de forma constante. La creación de perfiles permite a los usuarios optimizar su proceso, comprobar el control del proceso y realizar correcciones a un proceso cuando sea necesario. El QuadThermoVault es un registrador de temperatura del horno térmicamente aislado, alimentado por batería y de cuatro canales capaz de soportar temperaturas extremas. Puede soportar temperaturas del horno de hasta 662 ºF por hasta 25 minutos cuando está sellado correctamente. Su carcasa de acero inoxidable y sus propiedades térmicas se prestan para ser el dispositivo ideal de registro de temperatura para aplicaciones como hornos de curado con recubrimiento en polvo, hornos de curado con recubrimiento húmedo, hornos de lote y hornos de cinta transportadora. Las sondas externas de termopar proporcionan mediciones de temperatura precisas, con tiempos de respuesta rápidos.<br>

Nuestro software fácil de usar descarga fácilmente los datos a una computadora, donde las lecturas pueden mostrarse en grados Celsius, grados Fahrenheit, Kelvin o Rankine. El software permite al usuario ver todos los puntos de datos o un rango de puntos de datos y un resumen de los datos que se están viendo para cálculos tales como la Temperatura Cinética Media (MKT). Si se necesita realizar un análisis adicional de los datos, los datos se pueden exportar fácilmente a Excel® simplemente haciendo clic en un botón.</p>

