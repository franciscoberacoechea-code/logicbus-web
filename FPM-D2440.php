<center><strong>Módulo de potencia, entrada 24VDC, 35W @ 5V, 120W @ 24V, con función redundante.</strong></center><br>

<p>El FPM-D2440 es un módulo de potencia para el sistema iDCS-8000. Es una entrada de 24 VDC con salida de potencia aislada de 5V. La potencia aislada de 5V proporciona un máximo de 40W al sistema iDCS-8000. Este módulo de potencia también ofrece alimentación de 24 V no aislada con límite de fusible de 5 A. Además, este módulo también ofrece LED para indicar el estado de la energía localmente. Además, el módulo ofrece aislamiento de 1000 VDC entre canales y bus de fondo. Si cualquier alto voltaje o corriente daña los canales, el sistema (placas base, otros módulos y la unidad de control) no se verán afectados debido al beneficio del aislamiento.</p>

Caracteristicas:
<ul>
<li>Entrada de 24 VCC, salida de 5V / 40W y 24V / 120W.</li>
<li>Intercambiables en caliente.</li>
<li>Conformidad con la RoHS.</li>
<li>Aislamiento de 1000 VDC.</li>
<li>Redundancia.</li>
</ul>
Aplicaciones:
<ul>
<li>Automatización de edificios.</li>
<li>Automatización industrial.</li>
<li>Automatización de máquinas.</li>
<li>Mantenimiento remoto.</li>
<li>Diagnóstico remoto.</li>
<li>Equipo de pruebas.</li>
</ul>
