<p>ET-7026 es un módulo de E / S Ethernet basado en la web que cuenta con un servidor web incorporado que permite la configuración, el monitoreo de E / S y el control de E / S a través de un navegador web común. Con la función HMI web, no se necesitan habilidades de programación o HTML; la creación de páginas web dinámicas y atractivas para la supervisión de E / S y el control de E / S es fácil. ¡ET-7026 ofrece un acceso fácil y seguro para los usuarios desde cualquier lugar y en cualquier momento! ET-7026 también es compatible con el protocolo Modbus / TCP que hace una integración perfecta con el software SCADA.</p><BR>

