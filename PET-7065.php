<p> 
El Power-over-Ethernet (PoE) permite que los datos y la energía se transfieran por un sólo cable de Ethernet para que un dispositivo pueda operar desde la energía que recibe mediante el cable de datos. Ésta innovación permite una mayor flexibilidad en el diseño de oficinas, una eficiencia mas alta en el diseño de sistemas y más rapidez en la implementación.<br><br>

El PET-7065 ofrece compatibilidad con IEEE 802.3af (clasificación, Clase 1) Power over Ethernet (PoE) usando los dos pares de Ethernet (Cable Ethernet Categoría 5). El PET-7065 puede recibir energía de una fuente auxiliar como adaptadores AC y baterías, además de la red PoE. Ésta es una característica deseable cuando la energía total del sistema requerida excede la capacidad de carga de PSE. <br><br>

El PET-7065, es un módulo Ethernet que posee un servidor web integrado que permite configurar el módulo, controlar y monitorear las E/S desde cualquier navegador web. Con la función web HMI, no es necesario programar ni tener habilidades en HTML; la creación de páginas web dinámicas y atractivas para el control y monitoreo de entradas/salidas será divertido para los ingenieros. El PET-7065 ofrece a los usuarios un acceso fácil y seguro desde cualquier lugar y a cualquier hora.<br><br>

Además, el PET-7065 soporta también el protocolo Modbus/TCP, lo cual hace una perfecta integración entre este dispositivo y software SCADA.<br>

El PET-7065 provee 6 Relevadores Photo MOS de salida (tipo A) y 6 entradas digitales de contacto húmedo (tipo sink, source). Cada Relevador soporta un contacto de 1A@60Vac o 1A@60Vdc, y cada canal de entrada digital soporta una entrada de contador (32 bits and 500Hz max.).</p><BR>


