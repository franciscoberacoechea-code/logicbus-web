<p align="justify">El LBNP16302T-2D(RS-232) es un servidor Ethernet a serial de grado industrial de alto desempeño. Puede satisfacer los requerimientos de consumo, temperatura, volumen y habilidad de manejo. Ofrece 2 puertos RS232 (conector RS-232: RJ45) y un puerto Ethernet 10/100Base-Tx.
 <br><br>
Además, proporciona herramientas de configuración basadas en plataforma de Windows. Puede guiar al usuario a configurar el dispositivo paso a paso, todas las configuraciones vienen desde la WEB o Telnet. Soporta puerta de enlace cruzada y router cruzado, el usuario puede configurar la dirección IP, modo servidor y cliente, tamaño de paquete de datos, etc.</p>

<strong>Características:</strong>
<ul>
<li>Soporta Ethernet 10/100M</li>
<li>Soporta 2 puertos RS-232</li>
<li>Soporta configuración WEB o Telnet</li>
<li>Soporta protocolos TCP, UDP, ARP, ICMP, DHCP y DNS</li>
<li>Soporta modo de trabajo servidor TCP, cliente TCP, auto TCP, UDP y controlador Real COM</li>
<li>Soporta multidifusión UDP y modo subnet UDP</li>
<li>Soporta comunicación de puerta de enlace cruzada y router cruzado</li>
<li>Soporta acceso al puerto serial COM virtual y recuperación automática por interrupción de red</li>
<li>Proporciona herramientas de configuración en plataforma Windows para instalación y uso fácil</li>
<li>Diseño de grado industrial, grado de protección IP30</li>
<li>Sin ventilador, diseño de bajo consumo</li>
<li>Temperatura de funcionamiento: -40~85°C</li>
</ul><br><br>


