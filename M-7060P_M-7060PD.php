<li>nfiguración configurable de Power-on Value</li>
<li>nfiguraciones configurables de valores seguros</li>
<li>al Watchdog</li>
<li>Amplia gama de temperaturas de funcionamiento: -25 ~ +75 ° C</li>
</ul>
