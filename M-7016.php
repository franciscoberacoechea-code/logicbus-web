          <p>La serie M-7016 son los últimos módulos de entrada de medidor de tensión de ICP DAS. Alrededor de nuestro entorno, hay numerosos ejemplos de fuerza de conversión en una salida eléctrica medible. En la mayoría de los casos, necesitamos una celda de carga de tipo extensómetro. ¿Cómo vamos a hacer para aprovechar al máximo la producción eléctrica?<br><br>

            ¡La serie M-7016 es definitivamente su elección número 1! La serie M-7016 no solo procesa los datos de las celdas de carga o medidores de tensión, sino que también realiza un mapeo lineal al mismo tiempo para obtener resultados intuitivos; ¡por una tabla corresponsal definida por el usuario, la serie M-7016 convierte los datos en peso directamente!<br><br> 

            En los nuevos modelos, la serie M-7016 es compatible con los protocolos Modbus RTU y DCON.</p><BR>

