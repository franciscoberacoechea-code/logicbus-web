<p><b>Resumen de la aplicaci&oacute;n:</b>
    La soldadura ultrasónica une dos piezas de material (por ejemplo: plástico) usando vibraciones de alta frecuencia. Esto resulta en un proceso de soldadura más limpio. Es ideal para equipo médico, juguetes, semiconductores y electrónica. Uno de los aspectos clave para este tipo de soldadura es una fuerza de mordaza exacta. Al incorporar una celda de carga lineal podemos asegurar un contacto más exacto en cada parte.
