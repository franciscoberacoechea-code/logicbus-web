        <p>El tM-TH8 es un módulo de entrada de termistor aislado de 8 canales que puede usarse para medir temperaturas
          a través de un termistor. Se admiten muchos tipos de termistor y se pueden añadir tipos definidos por el
          usuario especificando los coeficientes Steinhart, si es necesario. El aislamiento intramódulo de 2500 VCC y la
          protección de sobretensión de 120 VDC para el termistor del tM-TH8 garantizan que el módulo funcione con mayor
          fiabilidad.</p>

        <strong>Características </strong>
        <ul Style="text-align:left">
          <li>Entrada de termistor de 8 canales.</li>
          <li>Protección de sobretensión de 120 VCC.</li>
          <li>Resolución: 16 bits.</li>
          <li>Tipos de termistor definidos por el usuario.</li>
          <li>2 kV ESD y 4 kV EFT Protecton.</li>
          <li>Watchdog dual.</li>
          <li>Aislamiento intramódulo de 2500 V CC.</li>
          <li>Amplio rango de temperatura de funcionamiento: -25 ~ + 75 ° C></li>
        </ul>

        <strong>Aplicaciones:</strong>
