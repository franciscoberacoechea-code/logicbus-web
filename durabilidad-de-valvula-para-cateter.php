  <p align="justify"><b>Resumen de la aplicaci&oacute;n:</b>
    Cuando una de las válvulas de tu corazón falla, necesitarás un reemplazo que pueda soportar el rigor del cuerpo humano. Las válvulas para catéter son requeridas con durabilidad y confiabilidad suficiente, para mantenerse en el paciente de forma indefinida.
    En este caso la durabilidad se refiere a resistir la presión de la sangre. Para asegurar esto se coloca un actuador lineal y una jeringa con pistón que empuja el fluido a un pequeño vaso que permitirá sostener la presión constante.
</p>

