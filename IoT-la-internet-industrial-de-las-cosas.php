      <p>Las nuevas funciones y/o roles del educador también surgirán a medida que se necesite el desarrollo de la
        fuerza de trabajo para cumplir con los requisitos exigidos. Se estima que habrá una brecha de
        habilidades hasta que los aprendices y las escuelas técnicas puedan proporcionar la preparación adecuada
        para los estudiantes. Hasta entonces, los fabricantes se dirigen a grupos demográficos específicos, como
        los veteranos, para cerrar la brecha de inmediato a través de la capacitación interna.</p>

      <h3 class="subtitle blue text-center">II. IIOT EMPLEOS DE DESARROLLO.</h3><br>
      <p>De los nuevos roles, estos ya atraen currículos. Los desarrolladores de IIoT provienen de escuelas de
        codificación, carreras de ingeniería y ciencias de la computación, aficionados y desarrolladores
        autodidactas. Estas son personas que pueden diseñar placas con éxito para comunicaciones y operaciones
        de IoT, así como software de código para aplicaciones IIoT.</p>
      <p>Los desarrolladores de IIoT pueden ser de corporaciones tecnológicas o pueden ser diseñadores internos
        que fabrican productos patentados para necesidades específicas de fabricación. Independientemente de
        quién los emplee, son esenciales para las operaciones de IIoT del futuro.</p>

      <h3 class="subtitle blue text-center">III. EMPLEOS DE OPERACIONES IIOT</h3>

      <p>Los roles y las posiciones en las operaciones unirán mano de obra con conocimientos de informática,
        habilidades técnicas, comunicaciones y habilidades de análisis. Estas personas podrían obtener
        experiencia a través de escuelas técnicas de corta duración y aprendizajes, ya sea con un conocimiento
        general de los sistemas de IIoT o conocimiento específico de las máquinas. Los posibles puestos de
        trabajo también cambiarán:
      </p>
      <ol>
        <li>Operador Inteligente de Maquinas - programa y supervisa la máquina inteligente</li>
        <li>Asistente de análisis y captura de datos: realiza una encuesta de captura de datos de dispositivos
          IoT y compila informes de análisis realizados de forma automática.</li>
        <li>Especialista en redes: una función de TI, esta persona supervisará las redes entre los activos para
          garantizar que los datos se compartan de forma segura y precisa. </li>
        <li>Miembro del equipo Smart Line: miembro humano del equipo de fabricación que trabaja con máquinas
          para finalizar un producto. </li>
        <li>Supervisor Inteligente de Almacén: un administrador principal que es responsable de la instalación
          de la máquina inteligente, tiene un profundo conocimiento de la tecnología detrás de las máquinas y
          mantiene el sistema inteligente funcionando.</li>
      </ol>

