<center><strong>Módulo de entrada analógica de 10/20 canales con protección de alto voltaje.</strong></center><br>

<p>El I-87017ZW es un módulo de entrada analógica que incluye 10 canales de entrada analógica o 20 canales de entrada analógica de terminación única. Proporciona un rango de entrada programable en todas las entradas analógicas. (+/- 150 mV, +/- 500 mV, +/- 1 V, +/- 5 V, + / - 10 V, +/- 20 mA o 0 ~ 20 mA) Cada entrada analógica puede configurarse para rango individual que proporciona una protección de sobretensión de 240 Vrms y una protección de sobreintensidad de 50 mA a 110 V CC / V CA. Las entradas de tensión y corriente son seleccionables por puente. La frecuencia de muestreo del I-87017ZW es ajustable y está disponible en modo rápido o normal. El módulo también presenta detección de cable abierto por canal para entradas de 4 ~ 20 mA que proporciona protección ESD de 4 KV así como aislamiento intramódulo de 3000 VDC.</p>

Caracteristicas:
<ul>
<li>Entradas unidireccionales de 10 canales o de un solo canal de 20 canales.</li>
<li>Puente seleccionable de voltaje o entrada de corriente.</li>
<li>Protección de sobretensión 240 Vrms.</li>
<li>Alta resolución: 16 bits.</li>
<li>Admite el modo rápido y el modo normal.</li>
<li>Protección contra ESD de 4 kV.</li>
<li>Aislamiento intramódulo de 3000 VDC.</li>
<li>Dual Watchdog.</li>
<li>Conformidad con la RoHS.</li>
<li>Amplio rango de temperatura de funcionamiento: -25 ° C ~ +75 ° C.</li>
<li>Protección contra la sobretensión.</li>
<li>Configuración individual del canal.</li>
</ul>
