<p align="justify">Existen hoy en día muchos sensores de temperatura infrarrojos que tienen una función llamada Procesamiento Peak and Valley Hold. ¿Qué hace esta función y cuándo debería usarla?
<br><br>
En algunas aplicaciones, el sensor de temperatura infrarrojo no tiene continuamente una buena vista del objetivo. Por ejemplo, puede haber espacios entre los elementos que se miden en un transportador en movimiento, o un agitador giratorio en una cuba de líquido podría ingresar periódicamente al área de medición.
</p><br>

