<p align="justify">El módulo I-87005W se usa para medir la temperatura usando un termistor. El módulo admite una amplia gama de termistores y presenta una configuración de canal individual, lo que significa que ocho de los canales de entrada se pueden configurar individualmente para diferentes tipos de termistor. Además, el I-87005W también proporciona 8 canales de salida digital que pueden usarse para salida de alarma y admite tipos de termistor definidos por el usuario, que pueden agregarse especificando los coeficientes de Steinhart, si es necesario. La inclusión del aislamiento intramódulo de 3000 VDC y la protección contra sobretensiones para los termistores en la I-87005W garantiza que el módulo funcione con una mayor fiabilidad.</p>

Caracterísiticas:
<ul>
<li>Entrada de termistor.</li>
<li>Configuración de canal individual.</li>
<li>Detección de cables abiertos.</li>
<li>Salida digital de 8 canales para salida de alarma.</li>
<li>Aislamiento intramódulo de 3000 VDC.</li>
<li>Protección de sobretensión para la entrada del termistor.</li>
<li>Tipos de termistor definidos por el usuario.</li>
<li>RoHS.</li>
<li>Amplio rango de temperatura de funcionamiento: -25 ~ + 75 ° C.</li>
</ul>
