<strong><center>Acondicionador/aislador digital universal, una entrada de pulso (Contacto IEC 1131.1, Namur, PNP/NPN, reed, photocell) y 2 salidas simultaneas (NPN, PNP) de 30Vdc. Frecuencia max: 400Hz. Montaje en riel DIN. Alimentación de 19~30Vdc o accesorio K-BUS</center></strong>

<div align="right">
<a href="https://tienda.logicbus.com.mx/K112_p_3945.html" title="Ir a Tienda" target="_blank"><img src="images/shopping_cart.png" alt="Comprar"></a>
