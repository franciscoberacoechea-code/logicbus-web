<ul>
<li>Entrada: Termopar (J, K, R, S, T, B, E, N)</li>
<li>Salida: Corriente de 0/4~20 mA, 20~4/0mA. Voltaje de 0~5 Vdc, 1~5 Vdc, 0~10 Vdc, 10~0 Vdc</li>
<li>1 salida de relevador de estado sólido (24Vdc @ 60mA) para alarma o control de termostato</li>
<li>Aislamiento Galvánico de 3 vías (alimentación, entrada y salidas)</li>
<li>Montaje en Riel DIN</li>
