          <p>Los USB-87Pn son una serie de unidades de expansi&oacute;n inteligentes de entradas y salidas para Rack, caracterizado por su interfaz de comunicaci&oacute;n USB, hot swap y sobre todo que esta unidad puede expandir sus funciones conect&aacute;ndole cualquiera de los m&oacute;dulos de la serie I-87K (perfil alto). Utilizado para el monitoreo industrial y aplicaciones de control. Hay mas de 30 m&oacute;dulos de entradas y salidas soportados por esta unidad, incluyendo entradas y salidas an&aacute;logas, entradas y salidas digitales y m&oacute;dulos de entradas y salidas de contador / frecuencia.          </p>
          <p>Las unidades o módulos de expansión  permiten añadir entradas o salidas de señales análogas o digitales al PLC, de  esta manera haciendo más amplia la funcionabilidad de los dispositivos y el  sistema.</p>
<p>
  <!--td {border: 1px solid #ccc;}br {mso-data-placement:same-cell;}-->Los rack, también conocidos  como gabinetes o chasis, es la parte medular de un sistema PLC, ya que permiten  la conexión física o ensamble a todos los componentes de Entrada/Salida, de  igual manera, funciona como vinculo de comunicación o bus de comunicación entre  dichas partes.</p>
          <p>            El USB-87Pn esta dise&ntilde;ado para ser usado dentro de ambientes rudos y ruidosos, por tal motivo su hardware esta fabricado para un amplio rango de alimentaci&oacute;n (10 - 30VDC) y temperaturas de operaci&oacute;n de -25 a 75&deg;C. El hot swap, la auto configuraci&oacute;n, la detecci&oacute;n de errores, su watchdog dual, encendido programable y valores seguros simplifican la instalaci&oacute;n y mantenimiento de los m&oacute;dulos E/S.          <br>
            Varios sets de herramientas de desarrollo y demos est&aacute;n incluidos como DLL, ActiveX, drivers para Labview, Indusoft, y Linux, servidor OPC, etc. La serie de m&oacute;dulos de E/S de la serie I-87K conectados en el USB-87Pn pueden f&aacute;cilmente ser integrados dentro de varios sistemas con diferentes software.        </p>
