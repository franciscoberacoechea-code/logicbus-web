                        dataloggers con tecnología IoT de Seneca que recopilan datos en tiempo real para la gestión y
                        análisis estas herramientas permiten predecir fallos potenciales y planificar el mantenimiento
                        asegurando un funcionamiento continuo y eficiente.</li>
