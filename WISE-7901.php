        <br>

        <p> 
          WISE-7901 sigue la especificación IEEE 802.3af (clasificación, Clase 1) de alimentación a través de Ethernet (PoE). Permite recibir energía de la red habilitada para PoE mediante pares Ethernet (cable Ethernet de categoría 5). Esta característica proporciona una mayor flexibilidad y una mayor eficiencia, por lo tanto, simplifica el diseño de los sistemas, ahorra espacio, reduce los cables y elimina la necesidad de enchufes eléctricos dedicados. Mientras tanto, en el caso de un entorno no PoE, WISE-7901 aún podrá recibir energía de fuentes de alimentación auxiliares como adaptadores de CA o batería, etc.<br><br>

          Este módulo WISE-7901 es compatible con el protocolo Modbus / TCP para una integración perfecta con el software SCADA disponible. Es compatible con un bus de expansión de E / S para implementar diversas funciones de E / S, como D / I, D / O, A / D, D / A de acuerdo con el uso de X-Board.
        </p><br>

        <strong>Caracteristicas:</strong>
        <ul>
          <li>Servidor web incorporado para la configuración de reglas IF-THEN-ELSE</li>
          <li>Motor de reglas IF-THEN-ELSE incorporado para operación lógica</li>
