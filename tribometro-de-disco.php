  <p><b>Resumen de la aplicaci&oacute;n:</b>
    Las almohadillas de freno y los revestimientos resistentes a rayaduras requieren de un estudio y entendimiento de los coeficientes de fricción para calcular su vida útil.
    Esto requiere de un tribómetro que pueda identificar las características y propiedades del material que se someterá a fricción. Con un sensor de carga multiaxial puede lograrse el cálculo de fricción y vida útil del material.
</p>

