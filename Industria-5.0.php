      <h2 class="subtitle blue text-center">Robots colaborativos: el futuro industrial</h2>
      <p>Debido a que los Cobots son fáciles de programar y seguros, en la mayoría de los casos es posible prescindir de las jaulas de seguridad, ya que son algo costosas para la instalación y por igual consume mucho espacio. Las aplicaciones robóticas ya no están limitadas a los entornos de las fábricas cerradas y los accesos restringidos, si no que ahora pueden trabajar codo a codo con un operario humano. Esto se ha convertido en una herramienta personalizada que los miembros de cualquier plantilla de trabajo pueden ser usados para aplicar sus habilidades creativas de una manera más efectiva y así proporcionar un mayor valor humano.</p>
      <p>Esta opción, deja a los empleados humanos libre para aplicar sus habilidades intangibles y explotar sus conocimientos y creatividad a proyectos más complejo, y para aumentar la productividad de la parte del proceso de fabricación que está bajo su supervisión. La industria 5.0 y los Cobots como eje central industrial, es combinar la creatividad y la capacidad de resolver problemas o retos de las personas con la velocidad, productividad y consistencia de los robots, y explorar cómo uno debe aprovechar al máximo lo que cada uno aporta a los procesos de producción.</p>
