        <strong>Descripción: </strong>
        <p align="justify">B-ALARM es un dispositivo GSM diseñado para la gestión remota de alarmas en hogares,
          edificios, plantas, máquinas de producción a través de comandos simples enviados con mensajes SMS. Con
          cualquier teléfono inteligente es posible controlar el encendido y apagado de la caldera, activar un contacto,
          etc. El dispositivo está equipado con un módulo GSM en su interior que se comporta como cualquier otro
          terminal telefónico en una red celular. La unidad permite operar con comandos a costo cero a través del
          timbre, así como con comandos rápidos con código numérico y temporizado. También tiene 1 entrada digital y 1
          relé de salida SPDT con una capacidad de 3 A / 250 Vac. B-ALARM puede contar con un libro de comandos para 5
          usuarios (1 de los cuales es un administrador) y una guía telefónica SIM que se extiende hasta 250 usuarios
          (comandos que suenan). La configuración en línea está garantizada por el software plug & play EASY SETUP y
          parcialmente de forma remota a través de SMS.</p>

        <strong>Características:</strong>
        <ul>
          <li>Cumple con las directivas RoHS y WEEE</li>
          <li>Compatible con PCI Express X1</li>
          <li>16 entradas ópticamente aisladas</li>
          <li>La resistencia de inmersión enchufada permite un rango de entrada configurable por el usuario de hasta 24
            V</li>
          <li>16 salidas de relé Reed (SPST)</li>
          <li>Relés de láminas DIP de 10VA de alta fiabilidad</li>
          <li>Alimentación (+ 5V y + 12V) y conexión a tierra en el conector de la placa DB78</li>
          <li>Incluye cable de 72 ″ con conector macho DB78 a DB37 macho y DB37 hembra conectores (Artículo # CA165)
          </li>
          <li>El software SeaIO Classic es compatible con los sistemas operativos Microsoft Windows</li>
          <li>Soporte de software para Linux disponible</li>
        </ul>

