<p>Módulo para la conversión de una señal analógica de corriente o tensión en una frecuencia (pulsos) directamente proporcional a la señal aplicada. Ampliamente utilizado como un "integrador" para totalizar, con un contador de impulsos, señales de caudal generadas por medidores con señal de salida analógica.<br><br>

<b>ENTRADA:</b> programable mediante interruptores DIP para 0 - 20 mA y corriente de 4 - 20 mA (con conexión activa y pasiva) o para 0 - 5 V CC, 1 - 5 V CC, 0 - 10 V CC y voltaje de 2 - 10 V CC.
<b>CONSTANTE DE INTEGRACIÓN</b> programable para el final de escala de 1 pulso cada 27 minutos a 20 pulsos por segundo.
<b>CALIBRACIÓN EXTREMADAMENTE SIMPLE</b> que solo requiere el uso de un comprobador digital ordinario.<br><br>

Dos LED de señalización en el panel frontal indican el encendido y el pulso de salida. La caja Noryl autoextinguible es del ancho de 3 módulos DIN y está diseñada para encajar en un raíl de montaje de 35 mm (DIN 46277).</p>


