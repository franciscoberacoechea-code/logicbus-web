<center><strong>E / S digital de nivel TTL de 32 canales, entrada digital de 16 canales aislada ópticamente y 16 tarjeta de salida digital de colector abierto (fuente actual). Incluye el conector CA-4002 D-Sub.</strong></center><br>


<p>El PISO-730 proporciona E / S digitales aisladas de 32 canales (16 DI y 16 DO) y E / S de nivel TTL digital de 32 canales (16 DI y 16 DO). Cada salida digital ofrece un transistor PNP y diodo de supresión integral para carga inductiva. La placa interactúa con las señales lógicas de campo, lo que elimina los problemas de bucle de tierra y aísla la PC host de tensiones dañinas. Sus canales de E / S aislados proporcionan hasta 3750Vdc de protección. 

El PISO-730 tiene un conector tipo D de 37 pines y dos conectores de cable plano de 20 pines. El cable plano se puede conectar al adaptador ADP-20 / PCI. El adaptador se puede fijar en el chasis. Se puede instalar en una ranura PCI de 5 V y puede admitir verdaderamente "Plug and Play".
</p><BR><br>

<strong>Caracteristicas</strong>

<ul>
<li>Bus PCI</li>
<li>16 canales aislados de DI / DO</li>
<li>32 canales DIO de nivel TTL (16 x DI y 16 x DO)</li>
<li>Convertidor DC / DC incorporado</li>
<li>Un conector de tipo D DB-37 para entrada y salida de aislamiento</li>
<li>Dos conectores separados de 20 pines para canales de entrada y salida no aislados.</li>
<li>Voltaje de aislamiento 3750Vdc</li>
<li>n Interrumpir: 2 canales</li>
<li>Tablero de 5V PCI</li>
</ul><br>

