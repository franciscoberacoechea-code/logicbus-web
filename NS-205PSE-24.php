<center><strong>Conmutador Ethernet Power Over Ethernet PoE (PSE) de 5 puertos a 10/100 Mbps con entrada de 24 VCC. Admite temperaturas de funcionamiento de -40 ~ + 75 ° C (-40F ~ 167F).</strong></center><br>

<p>El NS-205PSE-24 es un conmutador Ethernet industrial PoE (Power-over-Ethernet) no gestionable de 5 puertos. Admite 4 puertos PoE que se clasifican como equipos de fuente de alimentación (PSE). El NS-205PSE-24V permite una fuente de alimentación centralizada y proporciona hasta 15,4 vatios de potencia por puerto PSE. El NS-205PSE-24 está diseñado con un impulso de 24 VCC a 48 VCC para aplicaciones PoE donde la fuente de alimentación de 48 VCC no está disponible.</p><BR>

<strong>Caracteristicas</strong>

<ul>
<li>Crossover automático MDI / MDI-X para plug-and-play</li>
<li>Cada puerto admite una negociación automática de velocidad de 10/100 Mbps</li>
<li>Arquitectura de almacenamiento y reenvío</li>
<li>¿Doble contrapresión dúplex IEEE 802.3xy semidúplex? o control</li>
<li>4 puertos PoE con operación de equipos de abastecimiento de energía (PSE)</li>
<li>Detección automática de PD (dispositivos con alimentación) y administración automática de energía</li>
<li>Detección de sobretemperatura, sobrecorriente y sobre / bajo voltaje</li>
<li>Admite temperaturas de funcionamiento de -40 ° C ~ +75 ° C</li>
<li>Entradas de alimentación +18 V CC ~ +32 V CC (NS-205PSE-24V / NSM-205PSE-24V)</li>
<li>Ancho de banda de memoria de alto rendimiento de 3.2 Gbps</li>
<li>Puertos PoE compatibles con IEEE 802.3af</li>
<li>Embalajes delgados en su montaje en riel DIN</li>
</ul>
