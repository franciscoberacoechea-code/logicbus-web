Los osciloscopios USB port&aacute;tiles incluyen el software PicoScope que provee analizador de espectro y funciones de medici&oacute;n. El software PicoScope hace uso total de la capacidad del procesador de tu PC permiti&eacute;ndote ver se&ntilde;ales en tiempo real, acercamiento de tus se&ntilde;ales, guardar e imprmir formas de ondas capturadas.
