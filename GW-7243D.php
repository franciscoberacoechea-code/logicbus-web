<p>El GW-7243D es uno de los productos de DeviceNet en ICP DAS y se destaca como un esclavo DeviceNet para el dispositivo de puerta de enlace maestra Modbus TCP / RTU / ASCII. Permite que un maestro ubicado en una red DeviceNet entre en un diálogo con dispositivos esclavos en la red Modbus TCP / RTU / ASCII. En la red DeviceNet, funciona como un dispositivo "Grupo 2 solo servidor". En la red Modbus, GW-7243D representa un dispositivo maestro y envía un mensaje de solicitud para acceder al dispositivo esclavo Modbus TCP / RTU / ASCII mediante la definición del objeto DeviceNet. Para simplificar el mecanismo de conversión de protocolo, también proporcionamos la herramienta de utilidad GW-7243D para configurar el dispositivo y crear el archivo EDS para el dispositivo esclavo DeviceNet.</p><BR>

<strong>Caracteristicas:</strong>
<ul>
<li>Grupo 2 Solo servidor Suscriptor de DeviceNet</li>
<li>Soporte explícito y conexión de sondeo</li>
<li>El usuario puede seleccionar el protocolo Modbus RTU / ASCII para cada puerto COM</li>
<li>Compatibilidad máxima con 10 comandos Modbus RTU / ASCII para cada puerto COM</li>
<li>Soporte máximo 4 dispositivos Modbus TCP</li>
<li>Soporte máximo 5 comandos Modbus TCP para cada dispositivo Modbus TCP</li>
<li>Soporta códigos de función Modbus: 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x0F y 0x10</li>
<li>Soporte máximo 2048 canales DI, 2048 canales DO, 1024 canales AI y 1024 canales AO para cada dispositivo Modbus TCP</li>
</ul>
