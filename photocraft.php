            <h2 class="text-center"><b>Encoders Programable tipo rueda</b></h2>
            <p>Los encoders de rueda viajan directamente sobre el material en movimiento, utilizan una banda de rodadura que tiene un alto coeficiente de fricción y tienen un par de arranque muy bajo que prácticamente no causa deslizamiento de las ruedas en la correa. Además, las ruedas están rectificadas con precisión con tolerancias exactas, en comparación con un rodillo que tiene una tolerancia mucho mayor y su circunferencia rara vez se traduce en un número integral de impulsos de codificador por unidad de movimiento lineal.</p>
            <br>
            <p>Nuestros codificadores de rueda simple y doble ofrecen ventajas adicionales:</p>
            <ul>
                <li>Brazo de montaje integrado para una fácil instalación</li>
                <li>Accesorios para el montaje por encima o por debajo de un transportador o una banda móvil.</li>
                <li>Construcción robusta para servicio continuo en aplicaciones industriales</li>
                <li>La función "Anti-Jitter" eliminó los problemas de medición y seguimiento, y los errores de orden resultantes a menudo se encuentran cuando un transportador o una banda se detiene o se reinicia</li>
                <li>Protección de circuito que elimina las fallas causadas por los niveles significativos de electricidad estática a menudo asociados con los transportadores</li>
                <li>Versiones "programables" que permiten la selección de varias características en el momento de la instalación, como los pulsos por revolución y el tipo de circuito de salida, lo que da como resultado una flexibilidad máxima con un inventario mínimo</li>
            </ul>
