<p>Z-4AI-D permite adquirir hasta N.4 entradas analógicas (ma o V) a través de un PLC con solo entrada / salida digital. La interfaz del PLC se basa en tres señales de tipo PNP adecuadas para la conexión a la mayoría de los PLC disponibles en el mercado. La interfaz se compone de una señal de RELOJ generada por el PLC (salida de transistor), una señal de DATOS y una señal de APROBACIÓN generada por el módulo.
</p><br>

<strong>Caracteristicas:</strong>
<ul>
<li>Interfaz para PLC en el estándar digital de E/S (sólo DC )</li>
<li>Entrada de voltaje +/- 10 Vdc y de corriente + / - 20 mA dc</li>
<li>Alimentación de 19 a 40 Vdc ó 19 a 28 Vac (50-60 Hz)</li>
<li>Tiempo de muestreo ajustable a 400 ms a 14 bits + signo , 200 ms a 13 bits + signo</li>
<li>Protección de las entradas de hasta 60V</li>
<li>Aislamiento de entrada a 1500 Vac</li>
<li>Distancia de conexión hasta 100 m ( con cable blindado)</li>
</ul>

