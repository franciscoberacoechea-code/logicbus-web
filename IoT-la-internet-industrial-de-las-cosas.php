            <h3 class="subtitle blue text-center">I. INTRODUCCIÓN</h3>

            <p>Hay reacciones mixtas sobre aplicaciones de tecnología avanzada en escenarios laborales.
              "Robots robando trabajos" es el coco de los trabajadores de fabricación de equipo de
              automatización. Desde la década de 80´s, se ha estudiado cómo la tecnología cambiante
              afectará a los trabajadores jóvenes, preocupándose de que ellos y sus trabajos sean
              obsoletos.</p>

