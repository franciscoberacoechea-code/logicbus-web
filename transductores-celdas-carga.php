<p>Una celda de carga por lo general se compone de cuatro galga extensiometricas conectadas en una configuración tipo puente de Wheatstone. La señal que se obtiene es de mili volts y tiene que ser amplificada a voltaje, corriente 0~20m Amp o 4~20m Amp e incluso a una señal análoga con un amplificador de instrumentación mediante puertos RS232 o RS485. La salida del transductor  se toma para realizar cálculos necesarios para obtener la fuerza aplicada al transductor.</p>

