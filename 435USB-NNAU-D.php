<p><strong>USB a PLC 5E Gateway.</strong><br>
Acaba de encontrar la forma más fácil de mover datos entre un dispositivo USB y PLC 5Es. Transfiera datos sin esfuerzo desde cualquier USB HID o dispositivo de impresora, como lectores de códigos de barras, básculas de pesaje, escáneres RFID o impresoras, a la tabla de datos de su PLC. 
<br><br>
El 435USB es un gateway USB a PLC que, en el modo Direct Tag, escribe datos de dispositivos USB directamente en la tabla de datos de su PLC 5E. Es simple en función y fácil de usar por diseño. 
<br><br>
<strong>Actualiza las redes y conserva el legado de su hardware.</strong><br>
Aunque Ethernet es el estándar, todavía hay una gran cantidad de dispositivos ASCII y ahora esos dispositivos no tienen un puerto serie. TIENEN UN PUERTO USB. Estas básculas de bajo costo, lectores de códigos de barras, dispositivos RFID y una multitud de otras unidades generan datos ASCII que necesita en su proceso. Usted sabe cómo configurarlos, cómo hacer que funcionen y que sean confiables. Con el 435USB puedes integrar sin esfuerzo estos dispositivos con tus PLC 5Es. 
<br><br>
<strong>¿Qué hace que nuestros Gateways sean los mejores?</strong><br>
No hay instrucciones de mensaje o árbol de IO para tratar. En el modo de etiqueta directa, simplemente define una etiqueta de PLC para enviar y una para recibir y listo.</p>
	
