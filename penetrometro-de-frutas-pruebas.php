  <p><b>C&oacute;mo funciona:</b><br>
1.Una celda de carga OEM LSM250 o LSM300 est&aacute; montada dentro de una unidad de mano con una punta penetrante adjunta.<br>
2.Luego, un operador presiona el ensamblaje en la pulpa de la fruta o verdura.<br>
