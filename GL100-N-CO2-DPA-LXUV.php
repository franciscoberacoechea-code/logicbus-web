<p align="justify">El Graphtec GL100-N-CO2-DPA-LXUV es un conjunto que se incluye con el registrador de datos compacto GL100-N, el sensor de dióxido de carbono GS-CO2, el adaptador del sensor de corriente de CA GS-DAP-AC y el GL-LXUV. Iluminancia y sensor UV. Su cuerpo permite a los usuarios cambiar sensores y terminales para medir varias señales. La dimensión del cuerpo principal es un ligero de 2,6 pulgadas de ancho x 3,93 pulgadas de alto x 1,06 pulgadas de espesor (66 mm x 100 mm x 27 mm).<br><br>
Funciona con dos baterías AA (no incluidas) o alimentación de bus USB (incluye cable USB MicroB-A incluido). Con una memoria integrada de 4,9 MB y una memoria externa a través de la ranura para tarjeta Micro SD, el cuerpo del GL100 también incluye un puerto USB (conexión Micro B).<br><br>
La pantalla del GL100NCO2DPALXUV es un monocromo retroiluminado con una resolución de puntos de 128x64 que muestra los valores medidos y la configuración. Los datos grabados no se muestran en la unidad principal; Los datos capturados solo se pueden mostrar en la PC usando el software de aplicación incluido.<br><br>
El sensor de densidad GS-CO2 compacto del conjunto GL100-N-CO2-DPA-LXUV está diseñado para las industrias que requieren una solución de control y monitoreo del clima, como las áreas de invernadero, hidropónica, agricultura y botánica donde los operadores necesitan monitoreo del clima y el clima en tiempo real. Los museos y galerías de bellas artes también se sirven para entornos de ambiente controlado donde sobresale el GS-CO2.<br><br>
El sensor de iluminancia y UV GS-LXUV para el GL100-N-CO2-DPA-LXUV es para industrias que requieren una medición de luz precisa con intensidad de rayos UV y monitoreo de luminancia acumulada. Esta es la aplicación de hardware perfecta para invernaderos, hidropónicos, agricultura y salas botánicas que brindan a los técnicos de mantenimiento el monitoreo del clima y el clima en tiempo real. Los museos y galerías de bellas artes también se sirven para entornos controlados.<br><br>
El GS-DAP-AC es un adaptador de sensor de corriente CA que puede conectarse con hasta 2 sensores simultáneamente, y se puede conectar al GS-TH (no incluido con el GL100-N-CO2-DPA-LXUV), el GS- CO2, y el GS-LVUX.</p><br><br>

