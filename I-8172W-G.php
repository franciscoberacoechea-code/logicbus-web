<center><strong>Módulo FRnet de 2 puertos.</strong></center><br>

<p>Los módulos de la serie ICPDAS XP-8000, XP-8000-CE6, XP-8000-CE6-PRO, WinCon-8000, WP-8000, LinCon-8000, LP-8000, I-8000 e iP-8000 son todos controladores de automatización programables (PAC) que usan un módulo de comunicación FRnet I-8172W para implementar una red FRnet. El I-8172W es un controlador de comunicación FRnet aislado. El I-8172W tiene dos puertos FRnet, cada puerto FRnet puede controlar un máximo de 16 nodos de comunicación, numerados del 0 al 15. Cada nodo del módulo de E / S remotas puede controlar un máximo de 16 canales DI / DO. En otras palabras, cada puerto FRnet puede controlar un máximo de 128 canales DI y 128 canales DO.</p>

Caracteristicas:
<ul>
<li>Cableado reducido, cableado a dos hilos.</li>
<li>Tecnología de comunicación token-stream innovadora.</li>
<li>Capacidades de sincronización de E / S en tiempo real.</li>
<li>Tiempo de ciclo cíclico fijo para control determinista.</li>
<li>Capacidades de control de E / S distribuidas de alta velocidad.</li>
<li>Programación de E / S de asignación de memoria.</li>
<li>Fácilmente programable.</li>
<li>Sin sobrecarga de software para el procesamiento del protocolo.</li>
</ul>
Aplicaciones:
<ul>
<li>Automatización industrial.</li>
<li>Control remoto de E / S.</li>
<li>Automatización de edificios.</li>
<li>Gestión de estacionamiento.</li>
</ul>
