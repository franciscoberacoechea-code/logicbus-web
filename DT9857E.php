<tr><td colspan="3"><div align="justify">
  <h2><strong>DT9857E</strong> para Vibración y Sonido</h2>
  <p>Es un módulo para adquisición de señales dinámicas de alta precisión  para ruido, vibración y medidas acústicas. Disponible en 8 o 16 sensores de  entrada de 24 bit IEPE (ICP) que son sincronizados con una entrada de tacómetro,  2 contadores de medición, y un contador/temporizador de propósito general para  proveer flujos de datos que son comparados en tiempo, para uso en el campo o  laboratorio. 2 salidas D/A de estímulo, cada uno de 32 bit de resolución, y un  puerto de salida digital de 8 bit está disponible para el control y la generación  de ondas dinámicas. Es un módulo construido de material resistente, compacto,  se conecta vía USB lo que lo hace ideal para muchas aplicaciones de medición.<br>
    Características</p>
  <ul>
    <li>Entradas análogas IEPE simultaneas, salidas análogas  de estímulo para ondas, tacómetro síncrono con entrada para flujo de datos, pre  y post triggering avanzado, 16 DIO (8 in/8 out), contadores/temporizadores síncronos,  y Bus de sincronización de hasta 256 canales A/D y 32 canales D/A</li>
    <li>Todas las entradas y salidas pueden ser  sincronizadas para corroborar los datos medidos</li>
    <li>Soporta la habilidad de regresar el valor del  puerto de entrada digital, tacómetro, contador de medición, y contadores de propósito  general en la entrada análoga de flujo de datos, todos sincronizados con datos  de entradas análogas.</li>
    <li>8 o 16 entradas simultaneas IEPE, 4mA a 24V,  todas las entradas usan convertidores a 24 bit Delta-Sigma A/D para mediciones  de alta resolución a 105.6kHz, AC o DC.</li>
    <li>2 canales de salida convertidores de 32 bits D/A  para estimulo o generación de ondas a 216kHz</li>
    <li>Inicio de Trigger (Software, externo, Bus de Sincronización,  limites) para obtener muestras post trigger, trigger de referencia para obtener  muestras de pre/post trigger.</li>
    <li>Trigger de limite análogo en cualquier canal de  entrada análoga para programar el valor de limite desde -10V a +10V</li>
    <li>Conector SyncBus para adquirir por sincronización  y estimulo de onda en hasta 16 módulos  DT9857E</li>
    <li>Alimentación de corriente externa 4.7V a 28V</li>
  </ul>
