                    <li class="mb-3">En esta aplicación, el botón de carga nano QLA424 con un dispositivo personalizado se monta en la punta de agarre de un instrumento manual laparoscópico. La celda de carga registra las mediciones de fuerza, que se pueden utilizar para calibrar la herramienta.</li>
