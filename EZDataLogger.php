<p align="justify">EZ Data Logger es un software de adquisición y registro de datos para los módulos I-7000, M-7000, I-8000, módulos ET, módulos tM, G-4500, GT-540, entre otros. Puede ser aplicado a sistemas remotos de E/S. Con su interfaz amigable los usuarios pueden hacer un programa de adquisición de datos fácil y rápidamente sin conocimientos avanzados de programación.</p>

<center>
  <img src="imagenes/02/diagramas/scope[1].gif" alt="EZ Data Logger" title="EZ Data Logger" width="35%" class="image_productos">
</center>

<STRONG>Características:</STRONG>
<ul>
  <li>Compatible con los protocolos DCON, Modbus RTU, Modbus ASCII, Modbus TCP.</li>
  <li>Soporta mútiples puertos COM Ports y conexiones TCP/IP.</li>
  <li>Compatible con puerto COM virtual (máximo 32 Canales para la versión gratuita).</li>
  <li>Soporta Lógica de control por ejemplo VB Script, C, C++, etc.</li>
  <li>Configuración sencilla de los módulos: cada módulo y punto de E/S puede ser configurado individualmente.</li>
  <li>Creación de grupos de trabajo que le permitirán al usuario una mejor organización y control de su proyecto.</li>
  <li>Función "Tendencias de datos en tiempo real" (con zoom in y zoom out: cada línea de tendencia puede guardar mas de 86400 registros).</li>
  <li>Función "Layout": El usuario puede colocar imágenes prediseñadas o drag-drop para crear un sistema SCADA y monitorear las variables de su proyecto.</li>
</ul><br><br>

<center>
  <img src="imagenes/02/ez-imagen.jpg" alt="EZ Data Logger" title="EZ Data Logger" width="35%" class="image_productos">
</center>

<ul>
  <li>Creación y manipulación de bases de datos que pueden ser exportadas a formato de Excel, CVS, Access, etc.</li>
  <li>Creación de reportes para enviar mediante correo electrónico, SMS (se requiere módem GSM) o mostrar en pantalla.</li>
  <li>Alarma audible configurable con niveles Alto/Bajo la cual mantiene su estado hasta que el valor a medir sea menor al límite de <li>alarma establecido. Estas alarmas también pueden ser enviadas mediante correo electrónico, SMS (se requiere módem GSM) o mostrar en pantalla.</li>
  <li>Linealización de valores, lo que le permite al usuario configurar la ganancia y el offset para escalar valores de las distintas variables de su proyecto.</li>
  <li>No requiere conocimiento avanzado en programación.</li>
</ul>

<strong>Módulos compatibles:</strong><br>
<ul>
  <li>Módulos DCON (Serie I-7000, I-87K, I-8000)</li>
  <ul>
<li>Módulos I-7000</li>
<li>Módulos I-8000</li>
  </ul>
  <li>Modbus/TCP</li>
  <ul>
<li>I-8000E-MTCP</li>
<li>I-8000E-MTCP</li>
<li>Módulos ET</li>
<li>Controladores ISaGRAF ( I-8417/8817/8437/8837, I-7188EG, I-7188XG, Wincon-8x37 )</li>
<li>7188E-MTCP</li>
  </ul>
  <li>Modbus/RTU</li>
  <ul>
    <li>Serie M-7000</li>
  </ul>
  <li>Dispositivos con protocolos Modbus RTU, Modbus ASCII, Modbus TCP</li>
</ul>

<strong>Limitaciones:</strong><br>
<ul>
  <li>Hasta 32 canales para cada grupo de trabajo.</li>
  <li>Se requiere un dispositivo Modbus (TCP o RTU) para activar los drivers modbus del software.</li>
  <li>Compatible con Windows 7/Vista/XP/2000/NT/98.</li>
</ul>

<p>Q & A</p>
<ul>
  <li>Q1.¿Cómo muestro los valores analógicos en otra unidad, por ejemplo en kg?</li>
</ul>

<p align="justify">Configurando la ganancia y el offset se puede escalar los valores a cualquier unidad que se requiera. Para obtener la ganancia y offset exactos, tienes que obtener dos valores primero, y después utilizar el método de seguimiento para obtener el siguiente método y obtener el resultado final. Configura la ganancia y el offset en Configuración de Grupo.</p><br><br>

<center><img src="imagenes/02/diagramas/grafico.gif" alt="EZDataLogger" title="EZDataLogger" width="70%" class="image_productos"></center><br><br>
<ul>
  <li>Q2.¿Cómo activo el driver Modbus?</li>
</ul><br>

<p align="justify">Cuando instalas drivers Modbus, tienes que conectar al menos un dispositivo Modbus a los drivers Modbus activos. Después los drivers modbus pueden accesar a otros dispositivos modbus como un PLC... El siguiente dispositivo puede ser conctado para activar todo el driver Modbus. Los módulos seriales M7000, i-7188EX-MTCP, ET-6000, controladores ISaGRAF ( i-8417/8817/8437/8837, i-7188EG, i-7188XG, Wincon-8x37 )</p>

