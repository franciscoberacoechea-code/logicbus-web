<p>El enrutador WLAN NB1600 es un punto de acceso de grado industrial con funciones adicionales. La tarjeta WLAN integrada se puede configurar como punto de acceso o como cliente. En el modo de punto de acceso, el enrutador puede establecer hasta 4 redes WLAN diferentes.<br>
Como destaque especial, NB1600 ofrece dos puertos Ethernet que son altamente configurables. Usados ??como puertos LAN, pueden formar un conmutador de 2 puertos o tener dos redes IP separadas y enrutadas. Utilizado como puertos WAN, el NB1600 actúa como un firewall industrial con funcionalidad de cliente VPN.<br>
La interfaz serie RS-232 puede configurarse por software como consola del sistema o servidor de dispositivos serie. Los equipos heredados que no tienen ningún puerto Ethernet se pueden conectar de esta manera.<br>
El NB1600 tiene dos entradas binarias aisladas y dos salidas de relé para la conexión directa de sensores y actuadores.<br>
El puerto USB permite la configuración y la actualización del firmware desde la tarjeta de memoria. Solicite asistencia técnica para su dispositivo USB específico.
NB1600 es compatible con las principales tecnologías de VPN, como IPsec y OpenVPN. Tanto el modo servidor como el cliente son posibles. El manejo simple de una infraestructura de clave pública facilita la conexión de dos NB1600 a través de un túnel VPN.<br>
Otros servicios incluyen servidor DHCP, servidor proxy DNS, agente DDNS, agente SNMP, servidor telnet, servidor SSH, servidor web, cliente de correo electrónico y cliente de SMS. El dispositivo se administra a través de una GUI web fácil de usar o la interfaz de línea de comandos. La actualización de software a través del aire es fácil y segura.
</p><br>

