<center><strong>Modbus RTU / ASCII para HART Gateway.</strong></center><br>

<p>El HRT-710, Gateway está especialmente diseñado para el dispositivo maestro del protocolo HART. Permite que el maestro Modbus acceda a los dispositivos HART. Estos dispositivos HART pueden ser un transmisor, un actuador, etc. Además, también proporcionamos la utilidad de software, HG_Tool, para la configuración del módulo y el diagnóstico del dispositivo HART. Al usar estos módulos, los usuarios pueden integrar sus dispositivos HART en la red Modbus de manera fácil y rápida.
<br><br>
HRT-710, un maestro HART para la pasarela esclava Modbus, se aplica para integrar la información de estos medidores de flujo HART en el sistema HMI del cliente. Mediante el HRT-710, todos los medidores de flujo HART se considerarán como dispositivos esclavos Modbus y el sistema HMI puede usar la comunicación Modbus RTU incorporada para acceder fácilmente a estos medidores de flujo HART.
<br><br>
Se necesita integrar más de 250 información de dispositivo HART al centro de vigilancia. En el lado de la PC, utiliza 3 piezas de tarjetas PCI (VXC-148U, para 24 canales de expansión RS-485). I-2542A e I-2542B (RS-485 a Fibra) se utilizan en todos los canales RS-485 para extender la distancia de comunicación RS-485. Hay aproximadamente 20 piezas de módulos HRT-710 utilizados en cada canal RS-485 con la identificación de la estación diferente. A través de la estructura, el sistema SCADA o HMI puede integrar toda la información del dispositivo HART a través del protocolo Modbus de manera fácil y rápida.</p>

<strong>Características:</strong>
<ul>
<li>Soporta armazón HART corto/ largo.</li>
<li>Soporta HART Burst modo.</li>
<li>Permitir dos HART Masters.</li>
<li>Trabajando en modo HART punto a punto o multi-drop.</li>
<li>Conectando hasta 15 módulos HART.</li>
<li>Soporta Modbus RTU y formato ASCII.</li>
<li>Admite el modo Modbus Slave.</li>
<li>Admite actualización de firmware a través de Com Port. (FW_v1.2 y HW_v1.2).</li>
<li>Soporte de reemplazo en línea de dispositivos HART. (FW_v1.5).</li>
<li>Admite adquirir Long Frame Address automatically (FW_v1.5).</li>
<li>Puerto COM aislado: RS-232/422/485.</li>
<li>Proporcionar indicadores LED.</li>
<li>Watchdog incorporado.</li>
<li>Se puede montar en carril DIN.</li>
</ul>
