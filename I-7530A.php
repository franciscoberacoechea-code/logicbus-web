<div align="center">
<img src="https://tienda.logicbus.com.mx/assets/images/02/I-7530A.jpg" width="20%" alt="Convertidor Inteligente CAN a RS232-RS422-RS485: I-7530A" title="Convertidor Inteligente CAN a RS232-RS422-RS485: I-7530A" class="image_productos"><br><br>
<strong>Convertidor RS232/RS485/RS422 a CAN, 1 puerto CAN, 1 puerto RS232/485/422, protocolo CAN 2.0A/2.0B, conector CAN: D-Sub 9 pines, Alimentación +10V DC ~ +30V DC.</strong>
