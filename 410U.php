<p align="justify">Controle y monitoree 16 entradas ópticamente aisladas y 16 salidas de relé Reed a través de cualquier conexión USB con el SeaI/O-410U-OEM. Las entradas pueden oscilar entre 5 y 30V DC, mientras que los relés Reed brindan cierres de interruptores de larga duración adecuados para dispositivos de baja corriente. Las entradas y salidas se agrupan en segmentos de cuatro bits que comparten un común para facilitar el cableado a través de bloques de terminales extraíbles de 3.5mm. El SeaI/O-410U-OEM recibe alimentación de su fuente de 9-30V DC, o seleccione entre una variedad de opciones de fuente de alimentación Sealevel.
<br><br>
Comuníquese con SeaI/O-410U-OEM utilizando el protocolo Modbus RTU estándar de la industria o use las bibliotecas de software Sealevel SeaMAX API de su programa de aplicación. Los controladores y las utilidades del <strong><a href="software-seamax" target="_blank">software SeaMAX </a></strong> de Sealevel facilitan la instalación y el funcionamiento con los sistemas operativos Microsoft Windows 10 y 8.
<br><br>
Amplíe su red de E /S con los productos de la serie SeaI/O N. Las placas OEM SeaI/O están disponibles con relés Reed y Forma C, entradas ópticamente aisladas, interfaces TTL, funcionalidad A/D y D/A. Se pueden agregar hasta 246 módulos de expansión adicionales utilizando conectores de paso convenientes.
</p>

