<center><strong>Conmutador Ethernet de 10 puertos a 10/100 Mbps PoE (PSE).</strong></center><br>


<p>El NS-208PSE / NS-208PSE-4 es un conmutador Ethernet Industrial PoE (Energía sobre Ethernet) no gestionable de 8 puertos, admite puertos 8/4 PoE que se clasifican como equipos de fuente de alimentación (PSE). El NS-208PSE / NS-208PSE-4 hace que la fuente de alimentación centralizada se haga realidad y proporciona hasta 15.4 W de potencia por puerto. El NS-208PSE / NS-208PSE-4 se puede utilizar para alimentar los dispositivos con alimentación (PD) compatibles con IEEE802.3af por cable Ethernet y elimina la necesidad de cableado de alimentación adicional. <br>

El NS-208PSE / NSM-208PSE es exactamente el mismo que el NS-208PSE-4 / NSM-208PSE-4, excepto para los puertos PoE.</p><BR>

<strong>Caracteristicas</strong>

<ul>
<li>Cada puerto admite una negociación automática de velocidad de 10/100 Mbps.</li>
<li>Control de flujo de contrapresión Full Duplex IEEE 802.3xy semidúplex.</li>
<li>Detección automática de PD (dispositivos con alimentación) y administración automática de energía.</li>
<li>Detección de sobretemperatura, sobrecorriente y sobre / bajo voltaje.</li>
<li>Admite temperaturas de funcionamiento de -40 ° C ~ +75 ° C.</li>
<li>Crossover automático MDI / MDI-X para plug-and-play.</li>
<li>Arquitectura de almacenamiento y reenvío.</li>
<li>8 puertos PoE para NS-208PSE / NSM-208PSE; 4 puertos PoE para NS-208PSE-4 / NSM-208PSE-4.</li>
<li>Admite +46 ~ +55 VDC de entrada de potencia.</li>
<li>Montaje en carril DIN.</li>
