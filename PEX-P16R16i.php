<center><strong>Tajeta PCI Express, cuenta con 16 canales de entrada digitales aisladas y 16 canales de salida a relevador, aislamiento en voltaje de 3750 Vrms, bus de datos de 8 bit, provee de un conector DB37 hembra.</strong></center><br>


<p>La PEX-P16R16i es una tarjeta PCI Express que contiene 16 entradas digitales de acoplador de fotos que proporcionan una protección de aislamiento de 3750 Vrms, lo que permite que las señales de entrada floten por completo para evitar bucles de tierra. Equipado con 16 canales de salida de relé para permitir el control del estado ON / OFF de dispositivos externos, controlar relés externos, pequeños interruptores de potencia o activar alarmas. El PEX-P16R16i es totalmente compatible con el PISO-P16R16 , y los usuarios pueden reemplazar fácilmente el PISO-P16R16 con el PEX-P16R16i sin necesidad de modificar el software / controlador cuando utilizan computadoras PCI Express.<br><br>

<Strong>Nota:</Strong> El nombre del producto para la tarjeta PISO-P16R16E (PCI Express) se ha modificado para el PEX-P16R16i (todas las características siguen siendo las mismas). El prefijo "PEX" indica que la tarjeta se basa en la "interfaz PCI Express".<br>

Varias versiones de SO son compatibles con estas tarjetas, como Linux, DOS, Windows 98 / NT / 2000 y 32/64-bit Windows 7 / Vista / XP. El control DLL y Active X junto con varios programas de muestra de lenguaje basados ??en Turbo C ++, Borland C ++, Microsoft C ++, Visual C ++, Borland Delphi, Borland C ++ Builder, Visual Basic, C # .NET, Visual Basic.NET y LabVIEW se proporcionan para ayudar a los usuarios a desarrollar rápida y fácilmente sus propias aplicaciones.</p><br>

<strong>Caracteristicas</strong>

<ul>
<li>PCI-Express (3.3 V / 12 V) para el PEX-P16R16i</li>
<li>Admite CardID (dip-switch) [PEX-P16R16i]</li>
<li>Salida de relé de 16 canales</li>
<li>Entrada digital de 16 canales aislada ópticamente (3750 Vrms)</li>
<li>Filtro de entrada de señal de CC seleccionable</li>
<li>Entrada de señal de CA con filtro Software</li>
<li>Programa de ejemplo DOS Lib y TC / BC / MSC (con códigos fuente)</li>
<li>DLL y OCX SDK para Windows 98 / NT / 2000</li>
<li>DLL y OCX SDK para Windows XP / 2003 / Vista / 7 de 32 bits y 64 bits.</li>
<li>Se incluyen programas de ejemplo VB / VC / Delphi / BCB / VB.NET / C # .NET con códigos fuente</li>
<li>Kit de herramientas de LabVIEW para Windows</li>
<li>Driver para Linux</li>
</ul>
