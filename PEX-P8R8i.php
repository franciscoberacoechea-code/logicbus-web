<center><strong>Tarjeta PCI Express con 8 entradas digitales aisladas y 8 salidas de relé. Incluye un conector CA-4002 D-Sub y un Kit de desarrollo de software con programas de demostración.</strong></center><br>

<p>La PEX-P8R8i es una tarjeta PCI Express que contiene 8 entradas digitales de acoplador de fotos que proporcionan una protección de aislamiento de 3750 Vrms, lo que permite que las señales de entrada floten por completo para evitar bucles de tierra. Equipado con 8 canales de salida de relé para permitir el control del estado ON / OFF de dispositivos externos, controlar relés externos, pequeños interruptores de alimentación o activar alarmas. El PEX-P8R8i es totalmente compatible con el PISO-P8R8, y los usuarios pueden reemplazar fácilmente el PISO-P8R8 con el PEX-P8R8i sin necesidad de modificar el software / controlador cuando usan computadoras PCI Express. 
<br><br>
<strong>Nota:</strong> El nombre del producto para la tarjeta PISO-P8R8E (PCI Express) se ha modificado para el PEX-P8R8i (todas las características siguen siendo las mismas). El prefijo "PEX" indica que la tarjeta se basa en la "interfaz PCI Express". 
<br><br>
Varias versiones de SO son compatibles con estas tarjetas, que incluyen Linux, DOS, Windows 98 / NT / 2000 y 32/64-bit Windows 7 / Vista / XP. El control DLL y Active X junto con varios programas de muestra de lenguaje basados en Turbo C ++, Borland C ++, Microsoft C ++, Visual C ++, Borland Delphi, Borland C ++ Builder, Visual Basic, C # .NET, Visual Basic.NET y LabVIEW se proporcionan para ayudar a los usuarios a desarrollar rápida y fácilmente sus propias aplicaciones.</p>
	
Características:
<ul>
<li>Admite CardID (dip-switch).</li>
<li>Salida de relé de 8 canales.</li>
<li>Entrada digital de 8 canales aislada ópticamente (3750 Vrms).</li>
<li>Filtro de entrada de señal de CC seleccionable.</li>
<li>Entrada de señal de CA con filtro.</li>
</ul>
