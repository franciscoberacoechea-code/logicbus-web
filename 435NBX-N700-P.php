<p><strong>Convierte sus datos ASCII</strong><br>
La manera más ágil para convertir datos en formato ASCII a un PLC Allen Bradley Micrologix, ControlLogix, CompactLogix PLC-5 y SLC5/05 a través de Ethernet/IP. A través de una configuración simple basada en el navegador usted define la cadena de caracteres ASCII y luego observa como se entrega directamente a través de una etiqueta definida por el usuario o la ubicación del registro en la tabla de datos de su PLC. 
<br><br>
<strong>Necesita enviar datos ASCII desde el PLC?</strong><br>
Simplemente Complete y coloque la segunda etiqueta o ubicación de registro con el mensaje que desea enviar. Cuando la puerta de enlace ve una longitud mayor a cero procesará los datos y los enviará al dispositivo serie. 
<br><br>
Solo una etiqueta de entrada direccionado a una etiqueta de salida. No requiere instrucciones extra para entradas y salidas.
