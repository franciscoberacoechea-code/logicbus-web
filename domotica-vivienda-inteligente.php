      <p>Dentro de los avances tecnológicos, en el transcurso del tiempo que se vienen realizando en las áreas de telecomunicación, informática y electrónica, ha favorecido el desarrollo de productos y sistemas para el manejo y la inspección de los equipamientos de viviendas y edificios, aceptando a su vez una comunicación mayor bidireccional entre los tipos de usuarios y sus viviendas o edificios.</p>
      <p>Gracias a las nuevas tecnologías como los nuevos Smartphone y tabletas de última generación, cada día somos capacitados para llevar el control de sus funciones y la visualización de nuestras viviendas en cualquier momento, desde programación de los sistemas climáticos hasta la seguridad. Por estas razones es cada vez mayor el control del usuario en los equipamientos domésticos, y como resultado produce mayor confort y por lo consiguiente el ahorro de energía.</p>
      <p>Actualmente, el aumento de vida de la persona, ha provocado un fenómeno natural sin procedentes. Hemos estado hundidos dentro de la sociedad de la información y el conocimiento, como por ejemplo, la llegada del internet, dicha tecnología ha ofrecido una gran cantidad de servicios y aplicaciones, tanto en el entorno industrial como sociedad.</p>
      <h2 class="subtitle blue text-center my-5">Domótica</h2>
      <p>La domótica es aplicada en las ciencias y en los elementos de desarrollo electrónicos e informáticos, ya que por ella proporcionan algún nivel de automatización dentro de alguna casa, pudiendo ser por ejemplo un simple temporizador para poder encender y pagar una luz o cualquier aparato a una hora programada, hasta los sistemas más complejos son capaces de interactuar con cualquier elemento eléctrico de la casa.</p>
      <p>La vivienda domótica es aquella que integra una serie de automatizaciones en materia de electricidad, informática, robótica y telecomunicaciones, la domótica tienen un objetivo, y es asegurar al usuario o cliente un aumento de confort, de la seguridad, el ahorro energético, que tenga una facilidad de comunicación, entre otros. De esta manera, la domótica busca la integración de todos los aparatos del hogar, con el fin de que todo funcione en perfectas maneras, con la mayor utilización y el mínimo control por parte del usuario.</p>
