<center><strong>Convertidor Modbus TCP a CANopen maestro/ 1 puerto Ethernet 10/100M/ 1 puerto CAN/ display de 7 segmentos/ alimentacion de +10 a +30 Vdc</strong></center><br>

<p>El GW-7433D es una solución que proporciona una transformación de comunicación entre protocolo CANopen y protocolo Modbus/TCP.  Soluciona un problema crítico: conecta una red CANopen existente con un dispositivo maestro basado en ethernet siempre y cuando el dispositivo maestro soporte protocolo Modbus/TCP.  Habilita redes CANopen para ser acopladas junto con el Internet/Ethernet, donde sea que el monitoreo y control es logrado.<BR><BR>
Para redes CANopen, el GW-7433D es un dispositivo maestro CANopen.  Soporta funciones PDO y SDO para comunciarse con dispositivos esclavos.  Desde la vista de redes Modbus/TCP, GW-7433D juega el rol de servidor Modbus/TCP para recibir comandos desde clientes Modbus/TCP o replicar la información a clientes Modbus/TCP.  </p>


