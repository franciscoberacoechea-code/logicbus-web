<strong>Módulo Ethernet de adquisición de datos con 10 entradas análogas diferenciales o 20 entradas en modo común para voltaje y corriente con protección de alto voltaje, 4 salidas digitales, alimentación y comunicación a través de Ethernet y Modbus TCP/UDP.</strong>
