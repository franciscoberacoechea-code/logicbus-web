<p align="justify">El LBMODEL16485P es uno de los mejores convertidores seriales que existen, este tiene aislamiento y protección de voltaje en las entradas. El aislamiento de la alimentación es generado internamente. El servidor no consume energia del lado del puerto RS-232. Tiene LEDs para indicar el tráfico de datos. Solo el lado del RS-232 requiere alimentación. El LBMODEL16485P consume energia del lado del puerto RS-232 para la conexión de las líneas de la computadora en que esta instalado. Solo una línea de conexión debe estar en estado alto para encender el convertidor. Si las líneas de conexión en estado alto no están disponibles, el convertidor recomendado es el LBMODEL16485P. El lado de los puertos RS-485/422 es alimentado por una fuente externa incluida de 5Vdc.</p><br><br>

<strong>Características:</strong>
<ol>
<li>Aislamiento de 2500V, Protección de voltaje de entrada de 1500W</li>
<li>Transmite a una distancia de hasta 1800 metros a una velocidad de 115.2kbps</li>
<li>Con la tecnología “auto-adaptación” Adopta la interfaz automáticamente</li>
<li>No requiere configuración para utilizar el Puerto RS-485 o RS-422</li>
<li>El control de envío de datos es automático, detecta y distingue automáticamente la dirección de la transferencia de datos</li>
<li>Detecta automáticamente la frecuencia de la señal serial, transmite automáticamente sin retrasos</li>
</ol>
