                    <li class="mb-3">Este sensor multiaxial, en conjunto con el USB220, permite una configuración portátil en la que tanto aficionados como ingenieros de pruebas pueden usar una laptop para analizar en tiempo real los datos de la prueba, ya sea en un entorno controlado en interiores o al aire libre.</li>
                </ol>

                <p class="text-center light-black font-weight-bold">Ventajas de Usar el Sensor MBA500 en Pruebas de Drones</p>
                <ul>
                    <li class="mb-3">Medición precisa y simultánea: El MBA500 permite medir tanto el empuje como el torque generado por cada hélice y motor, ayudando a detectar cualquier desbalance.</li>
                    <li class="mb-3">Bajo nivel de interferencia: El diseño del sensor permite reducir al mínimo el crosstalk, ofreciendo datos más claros y precisos sobre el rendimiento del motor.</li>
                    <li class="mb-3">Portabilidad y versatilidad: Con el USB220, los usuarios pueden realizar pruebas en distintos entornos, obteniendo datos en tiempo real directamente en una laptop.</li>
                    <li class="mb-3">Optimización del rendimiento: Los datos recolectados permiten ajustar los motores y hélices para maximizar la estabilidad del cuadricóptero, asegurando un vuelo controlado y eficiente.</li>
