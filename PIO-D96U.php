<center><strong>Tarjeta universal PCI, 96 canales de Entrada/Salida digitales, Entradas/salidas programables por software, 1 Temporizador interno programable de 32-bit, 4 canales para interrupciones.</strong></center><br>


<p>La tarjeta PIO-D96U es el producto de nueva generación que proporciona ICP DAS para cumplir con los requisitos de cumplimiento de RoHS. La nueva tarjeta PIO-D96U está diseñada como un reemplazo directo para el PIO-D96, y los usuarios pueden reemplazar el PIO-D96 por el PIO-D96U directamente sin modificación de software / controlador.<br>

La tarjeta PCI universal PIO-D96U admite bus PCI de 3,3 V / 5 V, mientras que la PIO-D96 admite bus PCI de 5 V. Estas tarjetas proporcionan 96 líneas de E / S digitales TTL que constan de doce puertos bidireccionales de 8 bits. Cada tres puertos en un conector se agrupan y nombran como puerto A (PA), puerto B (PB) y puerto C (PC), respectivamente. Todos los puertos se configuran como entradas al encender o restablecer.<br>

El PIO-D96U también agrega un interruptor de ID de tarjeta a bordo. Los usuarios pueden establecer la identificación de la tarjeta y luego reconocer la placa mediante la identificación a través del software cuando usan dos o más tarjetas PIO-D96U en una computadora.<br>

El PIO-D96 / D96U admite varios sistemas operativos, como Linux, DOS, Windows 98 / NT / 2000 y Windows XP / 2003 / Vista / 7 de 32 bits. También proporciona el control DLL y Active X, y varios programas de muestra de lenguaje en Turbo C ++, Borland C ++, Microsoft C ++, Visual C ++, Borland Delphi, Borland C ++ Builder, Visual Basic, C # .NET, Visual Basic.NET y LabVIEW para ayudar usuarios para desarrollar rápida y fácilmente sus aplicaciones.
</p><BR><br>

<strong>Caracteristicas</strong>

<ul>
<li>Soporta el bus PCI de + 5V para PIO-D96</li>
<li>Admite el bus PCI + 3.3 / + 5 V para PIO-D96U</li>
<li>96 canales de E / S digital</li>
<li>Puertos de E / S programables bidireccionales bajo control de software</li>
<li>Todas las líneas de E / S almacenadas en el tablero</li>
<li>Se conecta directamente a DB-24PR, DB-24PD, DB-24RD, DB-24PRD, DB-16P8R, DB-24POR, DB-24SSR, DB-24C o cualquier tarjeta compatible con OPTO-22.</li>
<li>Un temporizador interno programable de 32 bits</li>
<li>Un conector DB37, tres cabeceras de caja de 50 clavijas</li>
<li>Fuente de interrupción: 4 canales</li>
<li>Función de identificación de tarjeta para PIO-D96U</li>
<li>Salida de búfer para mayor capacidad de conducción</li>
<li>El tiempo de respuesta DIO es de aproximadamente 0,77 µs (1,3 MHz máx.)</li>
</ul><br>

