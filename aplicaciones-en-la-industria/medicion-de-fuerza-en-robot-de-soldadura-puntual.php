            <div class="col-12 col-md-7 text-center">
                <p class="light-black text-justify">Los soldadores robóticos por puntos son esenciales en la industria manufacturera, ya que automatizan el proceso de soldadura en ensamblajes complejos o de difícil acceso, acelerando la producción y mejorando la consistencia en la calidad de las soldaduras. Para garantizar la resistencia y la calidad de cada soldadura, el robot debe aplicar una fuerza de sujeción uniforme en las piezas que va a soldar. Para lograr esta precisión, se utiliza un Sensor de Carga de Terminal de Varilla LCB400 en línea con el actuador de las pinzas de soldadura, midiendo la fuerza de sujeción aplicada durante cada proceso de soldadura.</p>

                <p class="text-center light-black font-weight-bold">¿Cómo funciona?</p>
                <p class="light-black text-justify">En esta configuración, el Sensor de Carga LCB400 se instala en línea con el actuador que controla las pinzas de soldadura.</p>
                <ol class="light-black text-justify">
                    <li class="mb-3"><b>Medición de la Fuerza de Sujeción:</b> Cuando el actuador cierra las pinzas sobre una pieza, el LCB400 mide la fuerza que se aplica en esa pieza. Esta fuerza de sujeción es crucial para asegurar una soldadura fuerte y completa, y que no se dañe el material.</li>
                    <li class="mb-3"><b>Transmisión de Datos:</b> La medición de fuerza del LCB400 se envía a los amplificadores analógicos de galgas extensiométricas de la serie IAA o al IDA100. Estos amplificadores analizan la señal de salida del sensor, ofreciendo una señal analógica precisa y amplificada para el control del PLC que gestiona el proceso de soldadura.</li>
                    <li class="mb-3"><b>Control en Tiempo Real:</b> El PLC, al recibir la señal de fuerza amplificada, ajusta el sistema de sujeción de las pinzas en tiempo real para asegurar que la fuerza aplicada cumpla con los estándares de calidad requeridos en la soldadura.</li>
                    <li class="mb-3"><b>Registro de Datos para Control de Calidad:</b> El uso del software SENSIT™ de FUTEK junto con el IDA100 permite registrar las mediciones del sensor, proporcionando un historial de datos que puede ser analizado para cumplir con los parámetros de control de calidad establecidos. Esto permite a los operadores identificar y corregir problemas de fuerza de sujeción, manteniendo la consistencia en los lotes de producción.</li>
                </ol>
                <p class="text-center light-black font-weight-bold">Beneficios del Sistema de Monitoreo de Fuerza en Soldadura Robótica</p>
                <p class="light-black text-justify">Implementar sensores de carga en los sistemas de soldadura robótica ofrece numerosas ventajas en términos de eficiencia y control de calidad:</p>
                <ul class="light-black text-justify">
                    <li class="mb-3"><b>Precisión y Consistencia:</b> Al garantizar una fuerza de sujeción uniforme en cada punto de soldadura, se mejora la calidad del ensamblaje y se evita la variabilidad en las soldaduras.</li>
                    <li class="mb-3"><b>Optimización del Control en el Proceso de Soldadura:</b> La integración del sensor de carga y el PLC permite ajustes automáticos, garantizando que la fuerza se mantenga dentro de los parámetros requeridos sin necesidad de intervención manual.</li>
                    <li class="mb-3"><b>Control de Calidad Rigurosamente Documentado:</b> El registro de datos mediante el software SENSIT™ permite un control detallado y análisis histórico del proceso, facilitando auditorías y asegurando que cada soldadura cumpla con las normas de calidad.</li>
                    <li class="mb-3"><b>Reducción de Costos y Aumento de la Productividad:</b> Al minimizar los errores y la variabilidad, se reduce el desperdicio de material y se optimizan los tiempos de producción, logrando un proceso eficiente y rentable.</li>
                </ul>
