  <h1 class="my-5"><b class="margen">Verificaci&oacute;n de torque en Herramienta/Calibraci&oacute;n de sensor</b></h1>
<center><h2><b>Aplicación de Sensor de torque</b></h2></center><br>

<div class="part1">

<article>
  <p><b>Resumen de la aplicaci&oacute;n:</b>
    En las líneas de ensamble, las llaves de torque permiten que los  fijadores (tornillos, tuercas y pernos) sean ajustados exactamente al torque especificado, haciendo que el producto funcione por muchos años sin daños en los sujetadores ni problemas para retirarlos. En aplicaciones comerciales tales como reparaciones, detalles técnicos y otros asuntos, permite evitar colocar torque de más sobre el sujetador y así no dañar las roscas.
  </p>
  <p>
    Sin embargo, el torque solamente es útil cuando es preciso. Normalmente luego de 5000 ciclos, se requiere de una recalibración para asegurarse de que aún es confiable. Mucha gente solamente confía en la calibración que viene de fábrica e ignora el hecho de que las llaves de torque deben calibrarse anualmente por su uso a lo largo del tiempo.
    Las calibraciones para llave de torque son ajustes o correcciones que se realizan a un transductor de torque para asegurarnos de que opere en el rango más preciso posible.
  </p>

  <img src="imagenes/36/diagramas/automatizacion/verificacion-de-torque-calibracion-de-sensor.jpg" alt="Verificación de torque en Herramienta/Calibración de sensor" width="60%">

  <div>
    <p><b>C&oacute;mo funciona:</b><br></p>
    <ol>
      <li style="color: black;">La serie <strong><a href="https://tienda.logicbus.com.mx/Sensor-de-Torque-de-Reacci%C3%B3n_c_1652.html" target="_blank">TDF</a></strong> de Futek es una herramienta eficiente para la calibración de torque o para auditar llaves de torque.</li>
      <li style="color: black;">En esta aplicación, el sensor de torque a reacción de la familia <strong><a href="https://tienda.logicbus.com.mx/Sensor-de-Torque-de-Reacci%C3%B3n_c_1652.html" target="_blank">TDF</a></strong> se fija en un plato de montaje y adaptado a una llave de torque utilizando adaptadores hembra/macho.</li>
      <li style="color: black;">A medida que el operador moviliza la llave hacia arriba y abajo,el sensor de torque Futek se encargará de registrar la medida.</li>
      <li style="color: black;">Estas mediciones se enviarán directamente al instrumento seleccionado. Dependiendo de la selección, el operador podrá observar los datos o se irán directo a una computadora.</li>
      <li style="color: black;">Si los datos muestran alguna anomalía, la llave de torque puede necesitar una calibración para mostrar la respuesta esperada.</li>
      <li style="color: black;">Cada sensor está propenso a errores de medición. Estas incertidumbres es la diferencia algebraica entre el valor que se indica a la salida del sensor contra el valor que debería mostrarse. Los errores tienen muchos factores que los originan:</li>
      <br>
      <ul>
        <li>Compensación cero</li>
        <li>Linealidad</li>
        <li>Histéresis</li>
        <li>Repetibilidad</li>
        <li>Intervalo de cambio de temperatura y cero</li>
      </ul>
    </ol>
  </div><br>

