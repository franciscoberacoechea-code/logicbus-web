<p align="justify" style="font-style: italic;">Se puede configurar un sensor con el procesamiento Peak and Valley Hold para medir la temperatura de la superficie de un objeto en un transportador en movimiento</p>

<center><img src="https://www.logicbus.com.mx/imagenes/articulo/peak2.jpg" class="image_productos" width ="35%" alt="Figura 2.  configuración de un sensor para poder medir la temperatura" title="Figura 2.  configuración de un sensor para poder medir la temperatura"></center><p><center><p><center><b>Figura 2.  configuración de un sensor para poder medir la temperatura</b></center></p><br>

<p align="justify" style="font-style: italic;">El procesamiento Peak and Valley Hold también se puede configurar para permitir que el sensor mida la temperatura de la superficie de un líquido en una cuba con un agitador</p><br>

<p align="justify">En estos casos, sin el procesamiento de la señal, podría ser imposible que un sistema de alarma o control monitoree la lectura de la temperatura medida, y la lectura podría ser de poca utilidad para el operador.<br><br>

Una de las marcas que cuentan con los sensores con la función Peak and Valley Hold es CALEX, estos sensores ofrecen una solución para controlar la temperatura de dichos objetivos. Las aplicaciones exitosas incluyen la fabricación de chocolate y toffee, y el curado de pintura automotriz.</p>

<div align="center"><h2>¿Cómo funciona el Procesamiento Peak and Valley Hold?</h2></div><br>
<p align="justify">Con Peak and Valley Hold habilitado, la temperatura del objetivo se mantiene mientras se interrumpe la medición. El sensor ignora las breves lecturas de temperatura alta o baja durante un período de tiempo determinado (el Período de retención).
<br><br>
De esta manera, los intervalos entre las lecturas de temperatura de los artículos en un transportador pueden ignorarse, y el sensor puede emitir continuamente la temperatura de la superficie de un líquido en una cuba como si el brazo de agitación giratorio no interrumpiera la medición.</p>
<center><img src="https://www.logicbus.com.mx/imagenes/articulo/peak3.jpg" class="image_productos" width ="70%" alt="Figura 3.  Procesamiento Peak and Valley Hold para objetos frios o calientes en un transportador" title="Figura 3.  Procesamiento Peak and Valley Hold para objetos frios o calientes en un transportador"></center><p><center><p><center><b>Figura 3.  Procesamiento Peak and Valley Hold para objetos frios o calientes en un transportador</b></center></p><br>

<p align="justify">En el modo de retención máxima, el sensor mantiene constante la temperatura máxima durante el período de retención. Después de este tiempo, el sensor emitirá la temperatura más alta que midió durante el Período de retención. Si el sensor detecta una temperatura más alta durante este Período de retención, mantiene esta temperatura más alta constante durante el Período de retención.
<br><br>
En el modo de retención de valle, el proceso funciona de la misma manera que la retención de picos, excepto que el sensor emite la temperatura mínima detectada de manera constante para el período de retención. Si se detecta una temperatura más baja durante este período de retención, la temperatura más baja se mantendrá durante el período de retención.
<br><br>
El período de retención debe configurarse para que coincida o exceda el período de tiempo entre los objetos en la cinta transportadora o la duración por la cual la obstrucción (por ejemplo, el agitador) pasa dentro del campo de visión del sensor.</p>

