<p align="justify">El modelo LCB400 es una celda de carga de extremo de barra (tensión / compresión) diseñada para aplicaciones que involucran actuadores en línea o gatos hidráulicos con roscas macho / hembra. El modelo estándar de celda de carga de extremo de barra LCB400 (tensión / compresión) tiene roscas macho / hembra, utiliza un ligero aluminio 2024 para capacidades más bajas y un acero inoxidable 17-4 robusto para las capacidades más altas. Este modelo es muy adecuado para los requisitos de capacidad de rango medio a alto (1,000 lb - 10,000 lb). Para cualquier aplicación que requiera un mayor rango de capacidad, consulte el LCB450.</p> 

