<center><strong> Convertidor USB a RS-232 (Windows 8 / 8.1). </strong></center><br>

<p>La I-7560U proporciona un puerto COM serial de Windows a través de su conexión USB y es compatible con dispositivos <a href="convertidores_info#RS-232">RS-232</a> nuevos y heredados. El USB Plug-and-Play permite una fácil expansión del puerto serie y no requiere ajustes de IRQ, DMA o puerto de E/S manualmente.<br><br>

El I-7560U presenta un conjunto completo de datos de módem RS-232 y señales de control (TxD, RxD, RTS, CTS, DSR, DTR, DCD, RI y GND) en su conector macho DB-9 compatible con PC. También presenta una velocidad de transmisión de 115200 bps de alta velocidad.<br><br>

La I-7560U se alimenta desde el bus USB y no se necesita una fuente de alimentación adicional.</p>

