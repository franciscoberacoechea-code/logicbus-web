<center><strong>Módulo de entrada analógica de 8 canales.</strong></center><br>

<p>El I-8017DW-G es un módulo de entrada analógica de alto rendimiento. Se pueden conectar hasta 16 entradas diferenciales de un solo canal u 8 canales a un módulo. Cuenta con una resolución de 14 bits, frecuencias de muestreo 100Ks/s. Proporciona protección de aislamiento de 2500 Vrms.</p>

Caracteristicas:
<ul>
<li>Convertidor AD de 14 bits a 100 KHz.</li>
<li>Disparador interno o externo.</li>
</ul>
Aplicaciones:
<ul>
<li>Sistema de adquisición de datos de alta velocidad.</li>
<li>Monitor de proceso y control.</li>
<li>Análisis de vibraciones.</li>
<li>Generador de patrones digitales del puerto de E/S digital.</li>
</ul>
