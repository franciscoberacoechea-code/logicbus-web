<p align="justify">Convertidor/aislador con entrada para termopar (J, K, E, N, S, R, B, T), 1 salida análoga y 1 salida a relevador de alarma. Configurable mediante DIP switch. Este dispositivo cuenta con aislamiento galvánico de 3 vías, lo que garantiza la protección de datos. Conector tipo pinza para una fácil instalación. Montaje en riel DIN. Alimentación de 19~30 Vdc.</p>

