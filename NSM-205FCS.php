<center><strong>Unmanaged 4-Port Industrial 10/100 Base-T con 100 Base-FX Fiber Switch, monomodo; Conector SC</strong></center><br>

<p>El NSM-205FCS (conector SC, modo único) es un Ethernet Industrial de 4 puertos no administrado (10 / 100Base-TX) con conmutador de fibra (100Base-FX) que asegura la transmisión de datos mediante el uso de transmisión de fibra óptica para proporcionar inmunidad frente a EMI / Interferencia RFI. Se usa Ethernet para transmitir una señal de hasta 15 km, y es la solución perfecta para aplicaciones donde la transmisión debe protegerse contra la exposición eléctrica, sobrevoltajes, rayos o corrosión química.<br>

El NSM-205FCS funciona en modo dúplex completo. En modo dúplex completo, el alcance es de 15 km con cables de fibra de 8.3 / 125, 8.7 / 125, 9/125 o 10/125 £ gm.<br>

El Ethernet admite la función de autonegociación 10 / 100M y la función automática MDI / MDIX.<br>

NSM-205FCS proporciona dos entradas de alimentación que se pueden conectar simultáneamente a fuentes de alimentación de CC en vivo. Si una de las entradas de alimentación falla, la otra fuente en vivo actúa como una copia de seguridad para respaldar automáticamente las necesidades de energía del NSM-205FCS.</p><BR>

<strong>Caracteristicas</strong>

<ul>
<li>Crossover automático MDI / MDI-X para plug-and-play</li>
<li>Cada puerto admite una negociación automática de velocidad de 10/100 Mbps</li>
<li>Arquitectura de almacenamiento y reenvío</li>
<li>Control de flujo de contrapresión Full Duplex IEEE 802.3xy semidúplex</li>
<li>Ancho de banda de memoria de alto rendimiento de 3.2Gbps</li>
<li>Frame buffer memory: 512 Kbit</li>
<li>Motor de búsqueda integrado con direcciones MAC dedicadas de 1 K unicast.</li>
<li>Entradas de alimentación redundantes +10 ~ + 30V DC</li>
<li>Alarma de falla de energía por salida de relé</li>
<li>Admite temperaturas de funcionamiento de 0 ~ + 70 ¢ XC</li>
<li>Montaje en raíl DIN y orificio de tornillo para el kit de montaje en pared.</li>
</ul>
