            <p><b>C&oacute;mo funciona:</b><br></p>
              <ol>
                <li style="color: black;">Una celda de la serie <strong><a href="https://tienda.logicbus.com.mx/LCM100-_c_2595.html">LCM</a></strong> o LSB se colocan en línea con el actuador de jeringa y pistón para medir la fuerza que el actuador lineal está ejerciendo.</li>
                <li style="color: black;">A medida que el actuador lineal empuja, el flujo abrirá la válvula para catéter.</li>
                <li style="color: black;">Una válvula de retención, mantiene el fluido moviéndose a través de la válvula para catéter y vaso de presión se utiliza para permitir al sistema alcanzar presión explosiva.</li>
                <li style="color: black;">El actuador lineal se retrae para regresar al pistón a su posición inicial, forzando al catéter a cerrarse y rellenarse a través de la válvula de retención.</li>
