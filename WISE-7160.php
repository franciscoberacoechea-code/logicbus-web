<center><strong>Módulo de 6 canales de salida de relevador, 6 canales aislados de entrada digital, servidor web integrado para lógica de control IF-THEN-ELSE, alimentación y comunicación a través de Ethernet y Modbus TCP.</strong></center><br>
 <br>

<p> 
WISE (Web Inside, Smart Engine) es un controlador fácil de usar para su uso en monitoreo remoto y control, automatización de edificios, automatización industrial, mantenimiento remoto y aplicaciones de prueba. WISE ofrece una interfaz web fácil de usar que permite a los usuarios implementar lógica de control como IF-THEN-ELSE con solo unos pocos clics; no se necesita programación. Al conectarse con otras E / S de adquisición de datos, el controlador inteligente WISE puede enviar automáticamente alarmas de correo electrónico a los usuarios en función de las condiciones configurables. Por ejemplo, en una aplicación de monitoreo de tanques, el controlador puede configurarse para enviar alarmas de correo electrónico al personal relacionado si el nivel del tanque supera el nivel preestablecido. La interfaz de usuario simple puede ayudar a los usuarios a mejorar su productividad y reducir sus costos operativos.<br><br>

WISE-7160 sigue la especificación Power-over-Ethernet (PoE) de IEEE 802.3af (clasificación, Clase 1). Puede ser alimentado por el puerto Ethernet PoE, que agrega más flexibilidad y mayor eficiencia para los usuarios. De esta manera, puede simplemente el diseño del sistema, ahorrar espacio, reducir cables y costos. En el caso de un entorno no PoE, el controlador WISE-7151 también puede ser alimentado por fuentes de alimentación auxiliares como adaptadores de CA o batería, etc.<br><br>

El controlador WISE-7160 se comunica a través del protocolo Modbus TCP para integrarse fácilmente con el software SCADA disponible. Cuenta con entradas digitales de contacto húmedo aisladas de 16 canales. Cada canal de entrada digital admite entrada de contador.</p><BR>

<strong>Caracteristicas:</strong>
<ul>
<li>Puede enviar alarmas de correo electrónico y SMS a los usuarios según las condiciones configurables</li>
<li>Servidor web incorporado para una fácil configuración</li>
<li>Motor de reglas IF-THEN-ELSE incorporado para control lógico</li>
<li>No se requieren habilidades de programación. La configuración se puede hacer en un navegador web regular con unos pocos clics.</li>
<li>Admite operaciones de E / S, contador, temporizador y correo electrónico</li>
<li>Se comunica a través de Modbus TCP y puede integrarse con Modbus I / O y el software SCADA.</li>
<li>Cumpla con el estándar IEEE 802.3af Power over Ethernet (PoE)</li>
<li>Equipado con puerto Ethernet 10/100 Base-TX</li>
<li>Aislamiento bidireccional / Protección ESD</li>
<li>Entrada digital de 6 canales, salida de relé de potencia de 6 canales</li>
</ul>
