<p align="justify">La interfaz serie 7204 PCI proporciona dos puertos serie, cada uno configurable individualmente para RS-422 o RS-485. La placa es capaz de velocidades de datos de 460.8K bps y maneja automáticamente la activación/desactivación del transmisor RS-485. El 7204 utiliza 16C850 UART que proporcionan FIFO de Tx/Rx de 128 bytes. Las opciones de pedido permiten la elección de UART con soporte para velocidades de transmisión personalizadas y protocolos de 9 bits.</p>

<strong>Características:</strong>
<ul>
<li>Cumple con las directivas RoHS y WEEE</li>
<li>Cada puerto configurable individualmente para RS-422 o RS-485</li>
<li>16C850 UART con búfer con FIFO de 128 bytes</li>
<li>Tasas de datos a 460.8K bps</li>
<li>RS-485 automático habilitar/deshabilitar</li>
<li>Dos conectores DB-9M</li>
</ul><br>


