<center><strong>Medidor de panel inteligente, modelo IPM650 Pro, mV/V, VDC, medición de corriente, salida analógica, relevadores de alarma, TEDS y salida USB.</strong></center><br>

<div align="right">
<a href="https://tienda.logicbus.com.mx/FSH03633_p_6809.html" title="Ir a Tienda" target="_blank"><img src="images/shopping_cart.png" alt="Comprar"></a>
