<p align="justify">El Graphtec GL100-N-4VT es un conjunto que viene con el registrador de datos compacto GL100-N y el terminal de voltaje y temperatura de 4 canales GS-4VT. Su cuerpo permite a los usuarios cambiar sensores y terminales para medir varias señales. La dimensión del cuerpo principal es un ligero de 2,6 pulgadas de ancho x 3,93 pulgadas de alto x 1,06 pulgadas de espesor (66 mm x 100 mm x 27 mm).<br><br>
Funciona con dos baterías AA (no incluidas) o alimentación de bus USB (incluye cable USB MicroB-A incluido). Con una memoria integrada de 4,9 MB y una memoria externa a través de la ranura para tarjeta Micro SD, el cuerpo del GL100 también incluye un puerto USB (conexión Micro B).<br><br>
La pantalla del GL100N4VT es un monocromo retroiluminado con resolución de 128 × 64 puntos que muestra los valores medidos y la configuración. Los datos grabados no se muestran en la unidad principal; Los datos capturados solo se pueden mostrar en la PC usando el software de aplicación incluido.</p><br><br>

