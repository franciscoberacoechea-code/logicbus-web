                  puede ser integrado al registro I-8000E
                  -MTCP fácilmente. El I-8000E-MTCP requiere los datos E/S del dispositivo Modbus/RTU,
                  después los pone en sus registros. La PC host puede tener todos los datos de E/S leyendo los
                  registros del I-8000E -MTCP.
                </ul>

