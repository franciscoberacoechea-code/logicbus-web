<ul>
<li>Entradas digitales de 16 canales.</li>
<li>Entradas digitales de alta tensión de 150 VDC.</li>
<li>Aislamiento de fotoacoplamiento.</li>
<li>Medición de larga distancia.</li>
<li>Todos los canales se pueden usar como contadores de 16 bits.</li>
<li>Protección contra ESD de 4 kV.</li>
<li>Aislamiento intramódulo de 3750 VDC.</li>
<li>Dual Watchdog.</li>
<li>Amplio rango de temperatura de funcionamiento: -25 ~ + 75 ° C.</li>
